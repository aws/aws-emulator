/// What this update resolved against the stored secret: the secret it is addressed
/// to, the KMS key the call leaves it on, and whether the token names a version
/// already holding exactly this value.
struct Target {
    arn: String,
    kms_key_id: Option<String>,
    replay: bool,
}

/// Every refusal this update is subject to, decided against the secret the store
/// holds, with the key a new version would be stored under.
///
/// One decision for both times it is made — before the value is sealed and again
/// when it is stored, since the store's guard is released in between — so an update
/// that raced another one is refused by the state it actually lands in.
fn admit(
    secret: Option<&crate::state::Secret>,
    version_id: &str,
    value: Option<&crate::state::envelope::SecretValue>,
    requested_kms_key_id: Option<&str>,
    requesting_owner: Option<&crate::state::service_owned::OwningService>,
) -> Result<Target, UpdateSecretError> {
    let Some(secret) = secret else {
        return Err(UpdateSecretErrorModeled::ResourceNotFoundException(
            ResourceNotFoundException {
                message: Some(crate::state::SECRET_NOT_FOUND_MESSAGE.to_string()),
            },
        )
        .into());
    };
    // A secret inside its recovery window still exists, so it is refused by
    // its state: "The secret is scheduled for deletion."
    // (`InvalidRequestException`, this service's Smithy model.)
    if secret.scheduled_for_deletion() {
        return Err(UpdateSecretErrorModeled::InvalidRequestException(
            InvalidRequestException {
                message: Some(crate::state::MARKED_FOR_DELETION_MESSAGE.to_string()),
            },
        )
        .into());
    }
    // "The secret is managed by another service, and you must use that service to
    // update it" (`InvalidRequestException`, this service's Smithy model): the
    // details and the value of a secret another service manages are that service's,
    // so a caller's update of one is refused before anything is sealed or stored.
    if let Some(owner) = crate::state::service_owned::refusing_owner(
        secret.owning_service.as_deref(),
        requesting_owner,
    ) {
        return Err(UpdateSecretErrorModeled::InvalidRequestException(
            InvalidRequestException {
                message: Some(
                    crate::state::service_owned::managed_by_another_service_message(owner),
                ),
            },
        )
        .into());
    }
    // A replica tracks its primary, so it is not written in its own Region: the
    // primary is where a value or a detail of the secret is changed, and the
    // change reaches the replica from there.
    if secret.is_replica() {
        return Err(UpdateSecretErrorModeled::InvalidParameterException(
            InvalidParameterException {
                message: Some(crate::state::NOT_PERMITTED_ON_REPLICA_MESSAGE.to_string()),
            },
        )
        .into());
    }

    let replay = value.is_some_and(|value| {
        secret
            .version(version_id)
            .is_some_and(|existing| existing.holds_same_value(value))
    });
    if value.is_some() && !replay {
        if secret.version(version_id).is_some() {
            return Err(UpdateSecretErrorModeled::ResourceExistsException(
                ResourceExistsException {
                    message: Some(crate::state::token_in_use_message(version_id, &secret.arn)),
                },
            )
            .into());
        }
        // Bound the secret before it grows, the same way `PutSecretValue`
        // does: an update that leaves no deprecated version to evict would
        // grow the store without end, so it is refused with the modelled
        // quota error. See `state::VERSIONS_PER_SECRET`.
        let claimed = vec![crate::state::STAGE_CURRENT.to_string()];
        if !secret.has_room_for_version(&claimed) {
            return Err(UpdateSecretErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(crate::state::version_quota_message()),
                },
            )
            .into());
        }
    }
    // "If you set this to an empty string, Secrets Manager uses the Amazon Web
    // Services managed key aws/secretsmanager." (`UpdateSecretRequest$KmsKeyId`,
    // this service's Smithy model.) A new version is stored under the key this call
    // leaves the secret on, so the key it names is the one the value is encrypted
    // under.
    let kms_key_id = match requested_kms_key_id {
        Some("") => Some(crate::state::DEFAULT_KMS_KEY_ALIAS.to_string()),
        Some(named) => Some(named.to_string()),
        None => secret.kms_key_id.clone(),
    };
    Ok(Target {
        arn: secret.arn.clone(),
        kms_key_id,
        replay,
    })
}

/// `InvalidRequestException` — "A parameter value is not valid for the current
/// state of the resource." — for a call that stores a value, and so creates a
/// version, without naming that version's id (see
/// [`crate::state::MISSING_CLIENT_REQUEST_TOKEN_MESSAGE`]).
fn missing_client_request_token() -> UpdateSecretError {
    UpdateSecretErrorModeled::InvalidRequestException(InvalidRequestException {
        message: Some(crate::state::MISSING_CLIENT_REQUEST_TOKEN_MESSAGE.to_string()),
    })
    .into()
}

/// Whether this call leaves the secret on a KMS key other than the one its stored
/// versions are held under, and so has to move them to it.
///
/// A secret names its key in any of the forms `KmsKeyId` accepts, and every
/// spelling of the Amazon Web Services managed key names the one key no caller can
/// act on, so what is compared is the customer managed key each value NAMES rather
/// than the two strings (see [`crate::state::envelope::customer_managed_key`]).
fn moves_to_another_key(held_under: Option<&str>, resolved: Option<&str>) -> bool {
    crate::state::envelope::customer_managed_key(held_under)
        != crate::state::envelope::customer_managed_key(resolved)
}

/// Re-encrypt `staged` — the versions carrying the staging labels the service
/// moves — under the key this call leaves the secret on, answering each version
/// with the value it is now held as.
///
/// A version is opened under the key that holds it and sealed again under the new
/// one: the plaintext is unchanged, so nothing a caller reads moves. A version
/// the new key will not encrypt is left out and stays under the key already
/// holding it — "If you don't have kms:Encrypt permission to the new key, Secrets
/// Manager does not re-encrypt existing secret versions with the new key"
/// (`UpdateSecretRequest$KmsKeyId`, this service's Smithy model) — while a version
/// that cannot be OPENED at all refuses this update with `DecryptionFailure`,
/// since a value this service cannot read is one it cannot move to another key.
async fn reseal_staged<Eng: Send + Sync + 'static>(
    engine: &Eng,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    target: &Target,
    staged: Vec<(String, crate::state::envelope::StoredValue)>,
) -> Result<Vec<(String, crate::state::envelope::StoredValue)>, UpdateSecretError> {
    let mut resealed = Vec::with_capacity(staged.len());
    for (staged_id, stored) in staged {
        let context = crate::state::envelope::ValueContext::new(&target.arn, &staged_id);
        let opened = crate::state::envelope::open(engine, ctx, region, &context, &stored)
            .await
            .map_err(decryption_failure)?;
        match crate::state::envelope::seal(
            engine,
            ctx,
            region,
            target.kms_key_id.as_deref(),
            &context,
            &opened,
        )
        .await
        {
            Ok(sealed) => resealed.push((staged_id, sealed)),
            Err(refusal) => {
                ::tracing::debug!(
                    version_id = %staged_id,
                    refusal = ?refusal,
                    "the new key did not encrypt this version, which stays under the key \
                     holding it"
                );
            }
        }
    }
    Ok(resealed)
}

/// How a read this update had to make, to move a version to another key, and that the
/// version's key refused is answered.
///
/// A caller whose authority does not reach `kms:Decrypt` on that key is NOT AUTHORIZED,
/// which is a refusal of the ACCESS this update needed rather than a failure to decrypt: the
/// common `AccessDeniedException` carrying this service's own sentence for it
/// ([`crate::state::envelope::KMS_ACCESS_DENIED_MESSAGE`]). Every other refusal is
/// `DecryptionFailure` — "Secrets Manager can't decrypt the protected secret text using the
/// provided KMS key." — relaying the KMS refusal it met (see
/// [`crate::state::envelope::KmsRefusal`]).
fn decryption_failure(refusal: crate::state::envelope::KmsRefusal) -> UpdateSecretError {
    if let Some(denied) = refusal.denied_message() {
        return crate::scaffolded::AccessDeniedException::new(denied).into();
    }
    UpdateSecretErrorModeled::DecryptionFailure(DecryptionFailure {
        message: Some(refusal.decryption_failure_message()),
    })
    .into()
}

/// How a write the secret's KMS key refused is answered, which is the mirror of
/// [`decryption_failure`] for the operation the key could not perform, with the class
/// following from WHY the key could not be used
/// ([`crate::state::envelope::KmsRefusal::kind`]): the common `AccessDeniedException`,
/// carrying the same sentence, for a caller whose authority does not reach
/// `kms:GenerateDataKey` on the key; the modelled `InvalidParameterException` for a
/// `KmsKeyId` that resolves to NO key, which is a fault of the value the request
/// carried rather than of a key; and `EncryptionFailure` for a key that exists and
/// would not encrypt under it, or a failure KMS said nothing about.
fn encryption_failure(refusal: crate::state::envelope::KmsRefusal) -> UpdateSecretError {
    if let Some(denied) = refusal.denied_message() {
        return crate::scaffolded::AccessDeniedException::new(denied).into();
    }
    if refusal.kind() == crate::state::envelope::RefusalKind::NoSuchKey {
        return UpdateSecretErrorModeled::InvalidParameterException(InvalidParameterException {
            message: Some(refusal.invalid_key_message()),
        })
        .into();
    }
    UpdateSecretErrorModeled::EncryptionFailure(EncryptionFailure {
        message: Some(refusal.encryption_failure_message()),
    })
    .into()
}

/// The modelled server error for a request that cannot reach this service's
/// store. `service_state` answers `None` only when the engine is not the shared
/// in-memory one, which is a server-side fault, never a bad request.
fn state_unavailable() -> UpdateSecretError {
    UpdateSecretErrorModeled::InternalServiceError(InternalServiceError {
        message: Some("the Secrets Manager emulator's state store is unavailable".to_string()),
    })
    .into()
}
