/// How a pass established that the stretch of text it placed is protected health
/// information, and therefore how much confidence the detection carries.
///
/// These are EVIDENCE classes rather than decoration: which class placed an entity says
/// what the pass actually verified about the characters it reports, so two spans found
/// the same way carry the same confidence.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Evidence {
    /// The span's own characters are the whole of the evidence: a written form that
    /// only this identifier class takes, so nothing but the form can be wrong.
    Form,
    /// The span's own form is ambiguous — a bare number, a capitalized word — and it is
    /// admitted only because the words around it name what it is.
    Context,
    /// A written form one of the lexicons below names, where a longer match is a more
    /// specific mention of the same thing.
    Lexicon,
}

impl Evidence {
    /// The confidence a span of this evidence class carries, in (0, 1].
    ///
    /// The class weight says how the span was established; the confidence this reports is
    /// that weight carried by the span's OWN written form, so two spans established the
    /// same way but written out to different extents are reported with different
    /// confidences rather than one constant for the whole class. A lexicon match is
    /// weighted by how many tokens its written form spans before that.
    ///
    /// `labelled` says that the record ALSO writes a field label of this span's own
    /// identifier class in front of it. That is a second, independent piece of evidence
    /// for the same detection — the characters take the class's written form AND the
    /// record says which class the value is — so the detection is reported with more
    /// confidence than the same form standing on its own.
    fn score(self, matched: &str, labelled: bool) -> f32 {
        let base = match self {
            Self::Form => WEIGHT_PATTERN,
            Self::Context => WEIGHT_CUE,
            Self::Lexicon => term_confidence(matched.split_whitespace().count()),
        };
        let confidence = span_confidence(base, matched);
        // A span a cue PLACED already carries that cue as its evidence, so the label is
        // not counted twice.
        if labelled && self != Self::Context {
            raised(confidence)
        } else {
            confidence
        }
    }
}

