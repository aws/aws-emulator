/// The readings one token's evidence allows, as `(modelled tag, weight)` in the
/// order the cues were collected — strongest cue first, so a tie resolves to the
/// most frequent reading.
///
/// This is what the tagger computes and what the response reports: the tag is the
/// reading holding the most weight and the confidence is that reading's share.
#[derive(Debug, Default, Clone)]
struct Readings {
    readings: Vec<(&'static str, f64)>,
    /// Whether the only reading the token's own evidence left is the open-class
    /// default: no word class claims the word, no inflection and no suffix speaks for
    /// it, so it is read as a common noun. The contextual rules read this, because
    /// such a word is the one a context can say the most about.
    open_class_default: bool,
}

impl Readings {
    /// Add `weight` to the evidence for `tag`, as a new reading or on top of one the
    /// token already had: cues that agree add up.
    fn support(&mut self, tag: &'static str, weight: f64) {
        match self
            .readings
            .iter_mut()
            .find(|(candidate, _)| *candidate == tag)
        {
            Some(reading) => reading.1 += weight,
            None => self.readings.push((tag, weight)),
        }
    }

    /// Leave the reading of `tag` what [`CONTEXT_CONTRADICTED`] keeps: the context
    /// speaks against it, which does not make it impossible.
    fn contradict(&mut self, tag: &str) {
        if let Some(reading) = self
            .readings
            .iter_mut()
            .find(|(candidate, _)| *candidate == tag)
        {
            reading.1 *= CONTEXT_CONTRADICTED;
        }
    }

    /// Whether the token's OWN evidence left a reading of `tag` at all.
    fn has(&self, tag: &str) -> bool {
        self.readings
            .iter()
            .any(|(candidate, _)| *candidate == tag)
    }

    /// The reading holding the most weight, and its share of the whole.
    ///
    /// The share is strictly positive, and strictly below 1 for any token carrying
    /// the [`CUE_UNLISTED_READING`] residual, so no word is ever reported as
    /// certain.
    fn reported(&self) -> (&'static str, f32) {
        let mut best: Option<(&'static str, f64)> = None;
        let mut total = 0.0;
        for (tag, weight) in &self.readings {
            total += *weight;
            if best.is_none_or(|(_, best_weight)| *weight > best_weight) {
                best = Some((*tag, *weight));
            }
        }
        match best {
            // Nothing the tagger can read: an empty token cannot occur, since every
            // token carries at least one character, but the class is reported rather
            // than asserted away.
            None => ("O", 1.0),
            Some((tag, weight)) => (tag, (weight / total.max(f64::MIN_POSITIVE)) as f32),
        }
    }
}

/// The part-of-speech tagger: the lexicon indexed by word, plus the verb stems the
/// inflectional rules derive forms from.
#[derive(Debug)]
struct Tagger {
    /// Word -> every modelled tag a word class of [`LEXICON`] claims it for, in that
    /// list's precedence order, which is the order of how frequent the readings are.
    lexicon: HashMap<&'static str, Vec<&'static str>>,
    /// The verb stems of [`VERBS`], for recognising regular inflections.
    verb_stems: HashSet<&'static str>,
}

/// The shared tagger. Built once: indexing the lexicon is far more expensive than
/// tagging one document, and it is immutable afterwards.
fn tagger() -> &'static Tagger {
    static TAGGER: OnceLock<Tagger> = OnceLock::new();
    TAGGER.get_or_init(Tagger::build)
}

impl Tagger {
    /// Index [`LEXICON`] in precedence order, keeping EVERY class that claims a word
    /// so an ambiguous one carries each of its readings.
    fn build() -> Self {
        let mut lexicon: HashMap<&'static str, Vec<&'static str>> = HashMap::new();
        for (tag, words) in LEXICON {
            for word in *words {
                let readings = lexicon.entry(*word).or_default();
                if !readings.contains(tag) {
                    readings.push(tag);
                }
            }
        }
        Self {
            lexicon,
            verb_stems: VERBS.iter().copied().collect(),
        }
    }

    /// Every reading `token` carries on its own, before the context it stands in.
    ///
    /// `sentence_initial` says whether the token opens a sentence, where
    /// capitalisation carries no proper-noun evidence.
    fn readings(&self, token: &str, sentence_initial: bool) -> Readings {
        let mut readings = Readings::default();
        let mut letters = false;
        let mut digits = false;
        let mut symbols = false;
        let mut marker = false;
        for character in token.chars() {
            letters |= character.is_alphabetic();
            digits |= character.is_numeric();
            symbols |= SYMBOLS.contains(&character);
            marker |= NON_LINGUISTIC_MARKERS.contains(&character);
        }

        // The classes a token's Unicode general categories decide on their own: there
        // is no other reading of them, and no unlisted one either.
        if !letters && !digits {
            // Punctuation, or a symbol when any character is a Unicode Symbol.
            readings.support(if symbols { "SYM" } else { "PUNCT" }, CUE_CATEGORY);
            return readings;
        }
        // A word carrying an address, URL, path or identifier marker is non-linguistic.
        if letters && marker {
            readings.support("O", CUE_CATEGORY);
            return readings;
        }
        if digits && (!letters || token.starts_with(|c: char| c.is_numeric())) {
            // All digits (and the separators inside a figure): a numeral. Digits
            // followed by letters: an ordinal or a measurement, still a numeral.
            readings.support("NUM", CUE_CATEGORY);
            return readings;
        }

        // A word: the lexicon's readings first, most frequent first, then the
        // morphological ones, and the open-class default only when nothing else
        // speaks for the word at all.
        let lower = token.to_lowercase();
        if let Some(claimed) = self.lexicon.get(lower.as_str()) {
            for (rank, tag) in claimed.iter().enumerate() {
                let weight = if rank == 0 {
                    CUE_LEXICON_PRIMARY
                } else {
                    CUE_LEXICON_FURTHER
                };
                readings.support(tag, weight);
            }
        }
        // A clitic UAX#29 kept attached: the stem before it carries the readings.
        if let Some(stem) = strip_clitic(&lower) {
            if let Some(claimed) = self.lexicon.get(stem) {
                for tag in claimed {
                    readings.support(tag, CUE_CLITIC_STEM);
                }
            }
        }
        // A regular inflection of a lexicon verb (`barks`, `stopped`, `making`).
        if self.is_inflected_verb(&lower) {
            readings.support("VERB", CUE_INFLECTION);
        }
        // Capitalisation away from the start of a sentence, and all-capital acronyms,
        // are evidence of a proper noun.
        if is_acronym(token) || (!sentence_initial && starts_uppercase(token)) {
            readings.support("PROPN", CUE_CAPITALISATION);
        }
        // Derivational morphology: the first suffix that matches, longest first.
        let length = lower.chars().count();
        for (suffix, tag) in SUFFIX_RULES {
            // Longer than the suffix it is matched on, counted in characters like
            // every other length in this handler.
            if length > suffix.chars().count() + 1 && lower.ends_with(suffix) {
                readings.support(tag, CUE_MORPHOLOGY);
                break;
            }
        }
        if readings.readings.is_empty() {
            readings.support("NOUN", CUE_OPEN_CLASS);
            readings.open_class_default = true;
        }
        // The residual every open vocabulary leaves: a reading this lexicon does not
        // carry, reported as the modelled `O` tag if it ever won, which it cannot,
        // since the cues above always weigh more.
        readings.support("O", CUE_UNLISTED_READING);
        readings
    }

    /// Whether `word` is a regular `-s`, `-ed` or `-ing` inflection of a verb the
    /// lexicon holds.
    fn is_inflected_verb(&self, word: &str) -> bool {
        inflection_stems(word)
            .iter()
            .any(|stem| self.verb_stems.contains(stem.as_str()))
    }
}

/// The stems a regular English inflection of `word` could have been formed from:
/// `-s`/`-es`/`-ies`, `-ed`/`-d` and `-ing`, each also undoing a doubled final
/// consonant and a dropped silent `e`.
fn inflection_stems(word: &str) -> Vec<String> {
    let mut stems = Vec::new();
    fn push_variants(stems: &mut Vec<String>, stem: &str) {
        // Counted in characters, like every other length in this handler.
        if stem.chars().count() < 2 {
            return;
        }
        stems.push(stem.to_string());
        stems.push(format!("{stem}e"));
        let mut characters = stem.chars().rev();
        if let (Some(last), Some(previous)) = (characters.next(), characters.next()) {
            if last == previous && last.is_alphabetic() {
                stems.push(stem[..stem.len() - last.len_utf8()].to_string());
            }
        }
    }

    if let Some(stem) = word.strip_suffix("ies") {
        stems.push(format!("{stem}y"));
    }
    for suffix in ["ing", "es", "ed", "s", "d"] {
        if let Some(stem) = word.strip_suffix(suffix) {
            push_variants(&mut stems, stem);
        }
    }
    stems
}

/// `word` without a trailing English clitic, when it carries one.
fn strip_clitic(word: &str) -> Option<&str> {
    CLITICS.iter().find_map(|clitic| {
        word.strip_suffix(clitic)
            .filter(|stem| stem.chars().count() >= 2)
    })
}

/// Whether the token starts with an upper-case letter.
fn starts_uppercase(token: &str) -> bool {
    token.chars().next().is_some_and(char::is_uppercase)
}

/// Whether the token is an all-capital acronym of at least two letters.
fn is_acronym(token: &str) -> bool {
    token.chars().filter(|c| c.is_alphabetic()).count() >= 2
        && token.chars().all(|c| !c.is_alphabetic() || c.is_uppercase())
}

/// Whether `character` belongs to a word: a letter, a digit, or the connector
/// UAX#29 keeps inside one (`ExtendNumLet`, so `user_id` stays one token).
fn is_word_character(character: char) -> bool {
    character.is_alphanumeric() || character == '_'
}

/// The index just past the word starting at `start` in `characters`.
///
/// A word is a run of word characters, which a joiner continues when a character of
/// the same kind stands on either side of it: an apostrophe between letters
/// (`MidLetter`) or a separator between digits (`MidNum`). Every other character is
/// a token of its own, so punctuation is split off one mark at a time.
fn word_end(characters: &[(usize, char)], start: usize) -> usize {
    let mut index = start + 1;
    while index < characters.len() {
        let character = characters[index].1;
        if is_word_character(character) {
            index += 1;
            continue;
        }
        let previous = characters[index - 1].1;
        let joins = match characters.get(index + 1).map(|(_, next)| *next) {
            Some(next) if MID_LETTER.contains(&character) => {
                previous.is_alphabetic() && next.is_alphabetic()
            }
            Some(next) if MID_NUM.contains(&character) => {
                previous.is_numeric() && next.is_numeric()
            }
            _ => false,
        };
        if !joins {
            break;
        }
        index += 2;
    }
    index
}

/// Segment `text` into the syntax tokens `DetectSyntax` reports.
///
/// Boundaries are word boundaries, so a figure (`3.14`) and a contraction (`don't`)
/// each stay whole while punctuation is split off; whitespace carries no token.
/// `TokenId` is the token's 1-based position in the document and the offsets are a
/// half-open range of zero-based character positions, so slicing the document by them
/// returns the token's own `Text`.
///
/// Shared with `crate::ops::batch_detect_syntax`: batching changes how many documents
/// one request carries, never how a document is segmented or tagged, so the two
/// operations cannot drift apart.
pub(crate) fn syntax_tokens(text: &str) -> Vec<SyntaxToken> {
    analyse(text)
        .into_iter()
        .enumerate()
        .map(|(position, analysed)| {
            let (tag, score) = analysed.readings.reported();
            SyntaxToken {
                token_id: Some(position as i32 + 1),
                text: Some(analysed.text.to_string()),
                begin_offset: Some(analysed.begin as i32),
                end_offset: Some(analysed.end as i32),
                part_of_speech: Some(PartOfSpeechTag {
                    tag: Some(tag.to_string()),
                    score: Some(score),
                }),
            }
        })
        .collect()
}

/// The tag this service's part-of-speech tagger reads at each token of `text`, keyed
/// by the token's BYTE offset.
///
/// The ONE place a caller asks what English makes of a word HERE — whether a capital
/// marks a name (`Amazon Comprehend is a service`) or is the orthography of a
/// sentence's first word (`Contact John Smith at …`), and whether a word is the noun
/// a phrase is headed by. The tagger answers from the word's own evidence and the
/// position it stands in, and the entity and targeted-sentiment recognisers read that
/// answer rather than deciding it a second way.
pub(crate) fn tags_by_offset(text: &str) -> HashMap<usize, &'static str> {
    analyse(text)
        .into_iter()
        .map(|token| (token.byte_begin, token.tag()))
        .collect()
}

/// One analysed token of a document: the span it occupies and the readings its own
/// evidence and the context it stands in leave it with.
///
/// `pub(crate)` beside [`analyse`], because `BatchDetectKeyPhrases` chunks the noun
/// phrases of its documents out of exactly this analysis: a key phrase and a syntax
/// token of one document must never come from two analyses that can disagree.
#[derive(Debug)]
pub(crate) struct AnalysedToken<'a> {
    /// The token's own text, a slice of the document.
    pub(crate) text: &'a str,
    /// Zero-based CHARACTER offset of the token's first character, which is the scale
    /// every offset this service reports is on.
    pub(crate) begin: usize,
    /// Zero-based character offset one past the token's last character.
    pub(crate) end: usize,
    /// Byte offset of the token's first character, for slicing a span of the document
    /// that covers more than one token out of it.
    pub(crate) byte_begin: usize,
    /// Byte offset one past the token's last byte.
    pub(crate) byte_end: usize,
    /// The token's lowercased form, for the contextual rules.
    lowercase: String,
    readings: Readings,
}

impl AnalysedToken<'_> {
    /// The tag this token is reported with.
    pub(crate) fn tag(&self) -> &'static str {
        self.readings.reported().0
    }

    /// The confidence this token's tag is reported with.
    pub(crate) fn score(&self) -> f32 {
        self.readings.reported().1
    }
}

/// Segment `text` into tokens, read each one's own evidence, and resolve the readings
/// the context they stand in speaks for or against.
///
/// Three contextual rules, each over the readings rather than over a decided tag, so
/// the confidence a token comes back with says how much the context left to the
/// reading it overturned:
///
/// 1. A noun phrase's head and its modifiers. A verb reading of the word straight
///    after an article is spoken against by that position and the noun reading is
///    supported (`the train`, `the running water`); a GERUND or PARTICIPLE standing
///    between a modifier and a head noun is part of that noun phrase, naming a thing
///    (`language processing service`) or describing one (`the delayed flight`), while
///    a finite verb form in the same position is the clause's predicate (`the service
///    finds insights`) and keeps its reading.
/// 2. A predicative complement. A participle, or a word no word class claims at all,
///    standing in the predicate of a form of `be` — straight after it or past the
///    adverbs between them — with no object and no `by` behind it, is the predicate's
///    adjective rather than a second verb or a noun (`the flight was delayed`, `the
///    screen is broken`, `the staff were rude`, `the weather is rather pleasant`) — a
///    passive, which `by` or an object marks, keeps its verb reading.
/// 3. An auxiliary. An auxiliary or modal is AUX when it ACCOMPANIES a main verb, as
///    the modelled tag's own documentation says; standing with no verb behind it, it
///    IS the clause's main verb and its verb reading is the supported one (`the train
///    was late`, `I have a car`).
///
/// Rule 1 and rule 2 run before rule 3, because whether an auxiliary accompanies a
/// main verb depends on what the word behind it was resolved to.
pub(crate) fn analyse(text: &str) -> Vec<AnalysedToken<'_>> {
    let tagger = tagger();
    let characters: Vec<(usize, char)> = text.char_indices().collect();
    let mut tokens: Vec<AnalysedToken<'_>> = Vec::new();
    let mut index = 0usize;
    let mut sentence_initial = true;

    while index < characters.len() {
        let (byte, character) = characters[index];
        if character.is_whitespace() {
            // No token is reported for whitespace, but a line break still ends a
            // sentence for the capitalisation heuristic.
            sentence_initial |= character == '\n';
            index += 1;
            continue;
        }

        // `index` counts CHARACTERS, so it is the offset the response reports; the
        // byte index beside it is only used to slice the token out of the document.
        let begin = index;
        let end = if is_word_character(character) {
            word_end(&characters, index)
        } else {
            index + 1
        };
        let end_byte = characters.get(end).map_or(text.len(), |(byte, _)| *byte);
        let piece = &text[byte..end_byte];
        index = end;

        let readings = tagger.readings(piece, sentence_initial);
        sentence_initial = piece.chars().all(|c| SENTENCE_FINAL.contains(&c));

        tokens.push(AnalysedToken {
            text: piece,
            begin,
            end,
            byte_begin: byte,
            byte_end: end_byte,
            lowercase: piece.to_lowercase(),
            readings,
        });
    }

    resolve_proper_names(&mut tokens);
    resolve_relative_pronouns(&mut tokens);
    resolve_noun_phrases(&mut tokens);
    resolve_auxiliaries(&mut tokens);
    tokens
}

/// Rule 0 of [`analyse`]: a capitalised word that stands in a NAME is read as a
/// proper noun.
///
/// Capitalisation on its own is weak evidence, and it is no evidence at all where
/// orthography demands a capital — at the start of a sentence — so a word the lexicon
/// claims for another class (`Main` in `Main Street`) or claims for nothing at all
/// (`Amazon` opening a sentence) is otherwise read as that class or as a common noun.
/// Two kinds of evidence are read here, both about the RUN of capitalised words the
/// token stands in rather than about the capital alone:
///
/// 1. The NEIGHBOUR: a word standing next to one that already reads as a proper noun
///    is a further word of that same multiword name — the Universal Dependencies
///    reading of every word of a name, not only of its head (`Main Street`).
/// 2. The POSITION, for a word opening a sentence, where the capital says nothing: a
///    word English has no class for, inside a capitalised run of more than one word
///    standing as its clause's SUBJECT, is part of the name that run writes (`Amazon
///    Comprehend is a service`, `Initech Inc announced its release`).
///
/// What the two guards keep out: a lone capital the orthography put there (`Dogs
/// bark.`, `Insights matter.` — one word, so no run and no neighbour), and a word
/// standing in its clause as something other than its subject (`Contact John Smith at
/// …` — no predicate follows the run, so the opening word is not part of the name).
///
/// Two passes, left to right then right to left, so a name is read whichever end of it
/// the anchor sits at (`Main Street`, `Amazon Comprehend`), and the whole run of a
/// longer name is reached one word at a time.
fn resolve_proper_names(tokens: &mut [AnalysedToken<'_>]) {
    let capitalised: Vec<bool> = tokens
        .iter()
        .map(|token| starts_uppercase(token.text))
        .collect();
    // A word whose capital is the only orthographic evidence it has: it opens a
    // sentence, so the capital is the orthography's rather than the name's.
    let opens_a_sentence: Vec<bool> = tokens
        .iter()
        .enumerate()
        .map(|(position, token)| capitalised[position] && !token.readings.has("PROPN"))
        .collect();
    let anchors = |tokens: &[AnalysedToken<'_>], position: usize| {
        capitalised[position] && tokens[position].tag() == "PROPN"
    };
    let forward: Vec<usize> = (0..tokens.len()).collect();
    for pass in [forward.clone(), forward.into_iter().rev().collect()] {
        for position in pass {
            if !capitalised[position] || tokens[position].tag() == "PROPN" {
                continue;
            }
            if opens_a_sentence[position] {
                // The capital says nothing here, so what reads the word as a name is
                // the run it opens standing in subject position.
                if tokens[position].readings.open_class_default
                    && names_the_subject(tokens, &capitalised, position)
                {
                    tokens[position].readings.support("PROPN", CUE_CONTEXT);
                }
                continue;
            }
            let beside_a_name = position
                .checked_sub(1)
                .is_some_and(|before| anchors(tokens, before))
                || (position + 1 < tokens.len() && anchors(tokens, position + 1));
            if beside_a_name {
                tokens[position].readings.support("PROPN", CUE_CONTEXT);
            }
        }
    }
}

/// Whether the run of capitalised words starting at `position` writes a NAME standing
/// as its clause's subject: more than one capitalised word, followed by the clause's
/// predicate.
///
/// An abbreviating period inside or at the end of the run is part of how the name is
/// spelled rather than a boundary — `Lars E. Nyqvist signed the lease`, `Initech Inc.
/// shipped a release` — since the tokenizer reports that period as a token of its own.
fn names_the_subject(
    tokens: &[AnalysedToken<'_>],
    capitalised: &[bool],
    position: usize,
) -> bool {
    let mut after = position;
    let mut words = 0usize;
    while after < tokens.len() {
        if capitalised[after] {
            words += 1;
            after += 1;
            continue;
        }
        let abbreviating =
            tokens[after].text == "." && after > position && capitalised[after - 1];
        if !abbreviating {
            break;
        }
        after += 1;
    }
    words > 1
        && tokens
            .get(after)
            .is_some_and(|candidate| PREDICATE_TAGS.contains(&candidate.tag()))
}

/// Rule 0b of [`analyse`]: a relativizer standing for the noun its clause modifies is
/// a relative PRONOUN rather than a determiner.
///
/// The position is what tells the two readings apart: a determiner determines the noun
/// phrase behind it (`that service`), while a relative pronoun stands between the noun
/// its clause modifies and that clause's own predicate (`the service that uses machine
/// learning`, `the insights that are reported`). So the rule asks for exactly that
/// position — a noun-phrase head in front, a predicate behind — which also leaves the
/// complementiser alone, since that one follows a VERB (`said that it works`) rather
/// than a noun.
fn resolve_relative_pronouns(tokens: &mut [AnalysedToken<'_>]) {
    for position in 0..tokens.len() {
        if !RELATIVIZERS.contains(&tokens[position].lowercase.as_str()) {
            continue;
        }
        let modifies_a_noun = position.checked_sub(1).is_some_and(|before| {
            NOUN_PHRASE_HEAD_TAGS.contains(&tokens[before].tag()) || tokens[before].tag() == "PRON"
        });
        // The clause's predicate, past the adverbs standing in front of it.
        let mut behind = position + 1;
        while behind < tokens.len() && AUXILIARY_SKIPPABLE_TAGS.contains(&tokens[behind].tag()) {
            behind += 1;
        }
        let heads_a_clause = tokens
            .get(behind)
            .is_some_and(|candidate| PREDICATE_TAGS.contains(&candidate.tag()));
        if modifies_a_noun && heads_a_clause {
            tokens[position].readings.support("PRON", CUE_CONTEXT);
            tokens[position].readings.contradict("DET");
        }
    }
}

/// Rules 1 and 2 of [`analyse`], left to right: a resolved token is the context the
/// next one is read in.
fn resolve_noun_phrases(tokens: &mut [AnalysedToken<'_>]) {
    for position in 0..tokens.len() {
        let tag = tokens[position].tag();
        // Rule 1 is about a verb reading; rule 2 also covers a word no word class
        // claims at all, which in the predicate of a copula is its adjective.
        let open_class = tokens[position].readings.open_class_default;
        if tag != "VERB" && !open_class {
            continue;
        }
        let previous = position
            .checked_sub(1)
            .map(|before| (tokens[before].tag(), tokens[before].lowercase.clone()));
        let next = tokens
            .get(position + 1)
            .map(|after| (after.tag(), after.lowercase.clone()));
        let (previous_tag, previous_word) = match previous {
            // A verb opening a document stands after nothing.
            None => continue,
            Some(previous) => previous,
        };
        // The word carrying the predicate, past the adverbs standing between it and
        // this one (`is rather pleasant`, `was very delayed`).
        let mut before = position;
        while before > 0 && AUXILIARY_SKIPPABLE_TAGS.contains(&tokens[before - 1].tag()) {
            before -= 1;
        }
        let predicate_of = before
            .checked_sub(1)
            .map(|copula| tokens[copula].lowercase.clone())
            .is_some_and(|word| COPULA_FORMS.contains(&word.as_str()));
        let predicative = predicate_of
            && (open_class
                || PARTICIPLE_ENDINGS
                    .iter()
                    .any(|ending| tokens[position].lowercase.ends_with(ending)))
            && next.as_ref().is_none_or(|(tag, word)| {
                // An object or a `by` phrase behind it makes it a passive verb or a
                // predicate noun rather than the predicate's adjective.
                word != "by"
                    && !NOUN_PHRASE_HEAD_TAGS.contains(tag)
                    && *tag != "DET"
                    && *tag != "PRON"
            });
        if predicative {
            tokens[position].readings.contradict("VERB");
            tokens[position].readings.contradict("NOUN");
            tokens[position].readings.support("ADJ", CUE_CONTEXT);
            continue;
        }
        if tag != "VERB" {
            continue;
        }
        // A gerund or a participle standing in a noun phrase is part of it rather
        // than its clause's verb. A PARTICIPLE between a modifier and a head noun
        // describes the head (`the delayed flight`). A GERUND needs no head behind it:
        // standing after a common-noun or adjective modifier it names a thing — as the
        // head of a nominal compound (`machine learning`, `data processing`) or as a
        // further word inside one (`language processing service`) — which is the
        // Universal Dependencies reading of a verbal noun. A FINITE verb form in the
        // same position is the clause's predicate (`the service finds insights`), so it
        // keeps its reading, and a gerund after an auxiliary is a progressive (`is
        // processing data`), whose auxiliary is not a nominal modifier.
        let compound_modifier = NOMINAL_COMPOUND_MODIFIER_TAGS.contains(&previous_tag);
        let nominal_modifier = NOUN_PHRASE_MODIFIER_TAGS.contains(&previous_tag)
            && next.is_some_and(|(tag, _)| NOUN_PHRASE_HEAD_TAGS.contains(&tag));
        let gerund = tokens[position].lowercase.ends_with(GERUND_ENDING);
        let participle = PARTICIPLE_ENDINGS
            .iter()
            .any(|ending| tokens[position].lowercase.ends_with(ending));
        if previous_tag == "DET" || ARTICLES.contains(&previous_word.as_str()) {
            // A determiner opens a noun phrase, so the word it opens heads one. The
            // relative reading of a relativizer is already resolved
            // ([`resolve_relative_pronouns`]), so a clause's predicate is not demoted
            // by the pronoun standing in front of it.
            tokens[position].readings.contradict("VERB");
            tokens[position].readings.support("NOUN", CUE_CONTEXT);
        } else if gerund && (compound_modifier || nominal_modifier) {
            tokens[position].readings.contradict("VERB");
            tokens[position].readings.support("NOUN", CUE_CONTEXT);
        } else if nominal_modifier && participle {
            tokens[position].readings.contradict("VERB");
            tokens[position].readings.support("ADJ", CUE_CONTEXT);
        }
    }
}

/// Rule 3 of [`analyse`]: an auxiliary accompanies a main verb, or it is one.
fn resolve_auxiliaries(tokens: &mut [AnalysedToken<'_>]) {
    for position in 0..tokens.len() {
        if !AUXILIARIES.contains(&tokens[position].lowercase.as_str()) {
            continue;
        }
        // The word that would be the main verb, past the adverbs and the negator an
        // auxiliary can carry before it.
        let mut behind = position + 1;
        while behind < tokens.len() && AUXILIARY_SKIPPABLE_TAGS.contains(&tokens[behind].tag()) {
            behind += 1;
        }
        let accompanies = tokens
            .get(behind)
            .is_some_and(|candidate| candidate.tag() == "VERB");
        let readings = &mut tokens[position].readings;
        if accompanies {
            readings.support("AUX", CUE_CONTEXT);
            readings.contradict("VERB");
        } else {
            readings.support("VERB", CUE_CONTEXT);
            readings.contradict("AUX");
        }
    }
}

