//! @op ContainsPiiEntities
//!
//! Analyses the submitted document for personally identifiable information and
//! answers the LABELS — the PII entity types — it carries.
//!
//! ## How the document is analysed
//!
//! The recognizer in this module places PII entities in a document by matching the
//! published FORM of each entity type and, where the defining standard gives the
//! value a check digit, verifying it. Every label this operation returns therefore
//! comes from something the recognizer found in the text, at a known offset: a
//! document with no recognisable PII answers an empty `Labels` list rather than a
//! verdict nothing computed.
//!
//! [`detect_pii_spans`] is that recognizer, and it is the ONE place the entity rules
//! live. It returns the spans (type, confidence, begin/end offset) so the
//! `DetectPiiEntities` operation projects the same spans into `PiiEntity` values and
//! agrees with this operation by construction. `ContainsPiiEntities` projects them
//! into the distinct set of types.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `ContainsPiiEntities::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! This operation holds NO state: its answer is a function of `Text` and
//! `LanguageCode` alone, so repeating a call returns the same labels and nothing a
//! later caller reads is changed by one. The recognizer is synchronous, CPU-bound
//! work with no await of its own, so [`recognize_pii`] runs it OFF the async worker
//! under a wall-clock budget: the request has a real await point, so it stays
//! cancellable and timeout-able, and a burst of concurrent documents cannot starve
//! the operations sharing the runtime.
//!
//! @generated by the emulator core scaffold op-stub generator.
//! Shared types live in `super::types`; the error channel in `crate::scaffolded`.
//!
//! ---
//!
//! # Modeled contract for `ContainsPiiEntities`
//!
//! What AWS documents for this operation, from this service's Smithy model. HTML is
//! stripped and long entries are clipped at ` …`. For the FULL text of any one item,
