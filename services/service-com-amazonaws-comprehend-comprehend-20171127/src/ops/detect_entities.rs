/// A word, a number or an abbreviation: a maximal run of letters and digits, with
/// the internal period, ampersand, apostrophe or hyphen a name can carry.
fn token_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(r"[\p{L}\p{N}]+(?:[.&'\u{2019}\-][\p{L}\p{N}]+)*").expect("a valid token pattern")
    })
}

/// Whether the characters between two tokens end a sentence.
///
/// A period does only when the token in front of it is not an abbreviation or an
/// initial, so `Dr. Jane` stays one sentence while `met. Jane` does not.
fn ends_sentence(previous: &Token, gap: &str) -> bool {
    if gap.contains('\n') || gap.contains('!') || gap.contains('?') {
        return true;
    }
    gap.contains('.') && !is_abbreviation(previous)
}

fn is_abbreviation(token: &Token) -> bool {
    token.lower.chars().count() == 1 || abbreviations().contains(token.lower.as_str())
}

/// Split the document into tokens, marking which ones are capitalized and which open
/// a sentence.
fn tokenize(text: &str) -> Vec<Token> {
    let mut tokens: Vec<Token> = Vec::new();
    for found in token_regex().find_iter(text) {
        let sentence_initial = match tokens.last() {
            None => true,
            Some(previous) => ends_sentence(previous, &text[previous.end..found.start()]),
        };
        let raw = found.as_str();
        tokens.push(Token {
            start: found.start(),
            end: found.end(),
            lower: normalise(raw),
            capitalized: raw.chars().next().is_some_and(char::is_uppercase),
            sentence_initial,
        });
    }
    tokens
}

/// Whether a candidate span may run across the characters between two of its tokens:
/// whitespace, an ampersand (`Johnson & Johnson`) and the period of an abbreviation
/// or an initial keep one name together; anything else ends it, as does a line break.
fn continues_span(previous: &Token, gap: &str) -> bool {
    if gap.contains('\n') {
        return false;
    }
    if !gap
        .chars()
        .all(|c| c.is_whitespace() || c == '&' || c == '.')
    {
        return false;
    }
    !gap.contains('.') || is_abbreviation(previous)
}

/// A date expression's whole mention, out of the span its rule matched.
///
/// RULE: the span reported for an entity covers the complete mention, so a date
/// expression written with the deictic modifier that says WHICH day it names
/// (`next Friday`) or with the part of the day that narrows it (`Friday morning`)
/// is reported whole, with `BeginOffset` at the modifier's first character — the
/// offsets a client highlights or redacts the mention with have to cover all of it,
/// and `Text` is the characters they delimit.
///
/// Both sides are extended over whitespace WITHIN a line only, since a line break
/// ends a mention, and over words that are never entities of their own, so no
/// extension can swallow a neighbouring entity.
fn complete_date_mention(text: &str, start: usize, end: usize) -> (usize, usize) {
    static PREFIX: OnceLock<Regex> = OnceLock::new();
    static SUFFIX: OnceLock<Regex> = OnceLock::new();
    // A run of modifiers, since English stacks them (`this coming Monday`), and all
    // of the run belongs to the one expression.
    let prefix = PREFIX.get_or_init(|| {
        Regex::new(&format!(r"(?i)\b(?:(?:{DATE_DEICTIC_PATTERN})[ \t]+)+$"))
            .expect("a valid date modifier pattern")
    });
    let suffix = SUFFIX.get_or_init(|| {
        Regex::new(&format!(r"(?i)^[ \t]+(?:{DAY_PART_PATTERN})\b"))
            .expect("a valid day part pattern")
    });

    // Each side is searched over a WINDOW of the document rather than over all of it
    // in front of (or behind) every date, so a document carrying thousands of dates
    // costs a constant per date instead of a scan of the whole text.
    let start = match prefix.find(&text[window_start(text, start)..start]) {
        Some(modifier) => {
            let candidate = window_start(text, start) + modifier.start();
            // The window may cut a longer word down to a modifier (`unnext`), which
            // the slice's own start reads as a word boundary; the document's
            // character in front of it is what decides.
            if text[..candidate]
                .chars()
                .next_back()
                .is_some_and(char::is_alphanumeric)
            {
                start
            } else {
                candidate
            }
        }
        None => start,
    };
    let end = match suffix.find(&text[end..window_end(text, end)]) {
        Some(day_part) => {
            let candidate = end + day_part.end();
            // Likewise behind: a day part the window cut short (`mornings`) is not
            // one, whatever the slice's end looks like to the pattern.
            if text[candidate..]
                .chars()
                .next()
                .is_some_and(char::is_alphanumeric)
            {
                end
            } else {
                candidate
            }
        }
        None => end,
    };
    (start, end)
}

/// Where the lookbehind of [`complete_date_mention`] starts: at most
/// [`MENTION_COMPLETION_WINDOW_BYTES`] before `start`, on a character boundary.
///
/// A modifier run is a handful of short words, so the window is a constant and no
/// mention is completed out of text far away from it.
fn window_start(text: &str, start: usize) -> usize {
    let mut floor = start.saturating_sub(MENTION_COMPLETION_WINDOW_BYTES);
    while floor < start && !text.is_char_boundary(floor) {
        floor += 1;
    }
    floor
}

/// Where the lookahead of [`complete_date_mention`] ends: the counterpart of
/// [`window_start`].
fn window_end(text: &str, end: usize) -> usize {
    let mut ceiling = end
        .saturating_add(MENTION_COMPLETION_WINDOW_BYTES)
        .min(text.len());
    while ceiling > end && !text.is_char_boundary(ceiling) {
        ceiling -= 1;
    }
    ceiling
}

/// Every entity a lexical pattern rule finds.
fn pattern_entities(text: &str) -> Vec<Recognised> {
    let mut found = Vec::new();
    for rule in pattern_rules() {
        for captures in rule.re.captures_iter(text) {
            let Some(matched) = captures.get(rule.capture) else {
                continue;
            };
            let mut start = matched.start();
            let mut end = matched.end();
            if rule.trim_trailing_punctuation {
                while end > start
                    && text[start..end]
                        .chars()
                        .next_back()
                        .is_some_and(|c| matches!(c, '.' | ',' | ';' | ':' | '!' | '?' | ')'))
                {
                    end -= text[start..end]
                        .chars()
                        .next_back()
                        .map_or(0, char::len_utf8);
                }
            }
            // A span may also have leading whitespace when the pattern allowed one
            // before a scale word; never report it as part of the entity.
            while start < end && text[start..end].starts_with(char::is_whitespace) {
                start += text[start..end]
                    .chars()
                    .next()
                    .map_or(0, char::len_utf8);
            }
            if start >= end {
                continue;
            }
            if rule.min_digits > 0
                && text[start..end].chars().filter(char::is_ascii_digit).count() < rule.min_digits
            {
                continue;
            }
            // The rule's own guards are about the form it MATCHED, so they are
            // applied before the span is completed out to the whole mention.
            let matched_tokens: Vec<&str> = token_regex()
                .find_iter(&text[start..end])
                .map(|token| token.as_str())
                .collect();
            if matched_tokens.len() < rule.min_tokens {
                continue;
            }
            if rule.require_capitalized
                && !matched_tokens
                    .iter()
                    .any(|token| token.chars().next().is_some_and(char::is_uppercase))
            {
                continue;
            }
            // A date expression's modifier and day part belong to the mention, so
            // the span is completed out to it before it is reported or weighed.
            let (start, end) = if rule.entity_type == TYPE_DATE {
                complete_date_mention(text, start, end)
            } else {
                (start, end)
            };
            let form_chars = text[start..end]
                .chars()
                .filter(|character| !character.is_whitespace())
                .count()
                .max(1);
            found.push(Recognised {
                start,
                end,
                entity_type: rule.entity_type,
                // A closed form's evidence is the span's own characters: how much it
                // constrains them (the rule's specificity level) and how many of the
                // mention's characters it accounts for. The completion above is
                // rule-driven too — a deictic modifier and a day part are closed
                // lists — so every character of the reported mention is named.
                evidence: Evidence {
                    support: EVIDENCE_PER_SPECIFICITY_LEVEL * f64::from(rule.priority)
                        + EVIDENCE_PER_FORM_CHAR * form_chars as f64,
                    competing: 0.0,
                },
                priority: rule.priority,
            });
        }
    }
    found
}

/// Every entity a capitalized phrase in running text yields.
fn phrase_entities(text: &str) -> Vec<Recognised> {
    let tokens = tokenize(text);
    // Where this service's part-of-speech tagger reads a proper noun. A capital is
    // evidence of a name everywhere EXCEPT at the start of a sentence, where
    // orthography puts one whatever the word is, so a sentence's first word is read
    // as part of the name after it only where something says it is one: the tagger
    // reads it as a proper noun (`Amazon Comprehend is a service`), or a lexicon here
    // names it. With neither, the capital says nothing and the word is left out of the
    // candidate — `Contact John Smith` names John Smith. A function word is left to
    // the rule below, which is what reads the article of a name that carries one.
    let proper_nouns = crate::ops::detect_syntax::tags_by_offset(text);
    let mut found = Vec::new();
    let mut index = 0;
    while index < tokens.len() {
        if !tokens[index].capitalized {
            index += 1;
            continue;
        }
        if tokens[index].sentence_initial
            && !function_words().contains(tokens[index].lower.as_str())
            && tokens.get(index + 1).is_some_and(|next| next.capitalized)
            && proper_nouns.get(&tokens[index].start) != Some(&"PROPN")
            && !named_by_a_lexicon(&tokens[index].lower)
        {
            index += 1;
            continue;
        }
        if function_words().contains(tokens[index].lower.as_str()) {
            // An article or a preposition opens a name only when a capitalized
            // token follows it (`The New York Times`), and `classify_phrase` trims
            // it back off unless a lexicon names the phrase as written.
            let opens_a_name = tokens
                .get(index + 1)
                .is_some_and(|next| next.capitalized)
                && continues_span(&tokens[index], &text[tokens[index].end..tokens[index + 1].start]);
            if !opens_a_name {
                index += 1;
                continue;
            }
        }
        let mut end = index + 1;
        while end < tokens.len() && end - index < MAX_SPAN_TOKENS {
            if !continues_span(&tokens[end - 1], &text[tokens[end - 1].end..tokens[end].start]) {
                break;
            }
            if tokens[end].capitalized {
                end += 1;
                continue;
            }
            // A run of lowercase particles stays in the name only when a capitalized
            // token follows it (`The Old Man and the Sea`, `Bank of America`).
            let mut after_particles = end;
            while after_particles < tokens.len()
                && name_connectors().contains(tokens[after_particles].lower.as_str())
                && continues_span(
                    &tokens[after_particles - 1],
                    &text[tokens[after_particles - 1].end..tokens[after_particles].start],
                )
            {
                after_particles += 1;
            }
            let name_resumes = after_particles > end
                && after_particles < tokens.len()
                && tokens[after_particles].capitalized
                && after_particles + 1 - index <= MAX_SPAN_TOKENS
                && continues_span(
                    &tokens[after_particles - 1],
                    &text[tokens[after_particles - 1].end..tokens[after_particles].start],
                );
            if name_resumes {
                end = after_particles + 1;
                continue;
            }
            break;
        }
        for part in divide_phrase(&tokens, index..end) {
            if let Some(entity) = classify_phrase(text, &tokens, part) {
                found.push(entity);
            }
        }
        index = end;
    }
    found
}

/// Whether one of this recogniser's own lexicons names `word`: a well-known
/// organization, a place, or an English given name. Such a word carries its own
/// evidence of being a name wherever it stands, including at the start of a sentence.
fn named_by_a_lexicon(word: &str) -> bool {
    let canonical = canonical(word);
    organizations().contains(canonical.as_str())
        || places().contains(canonical.as_str())
        || given_names().contains(word)
}

/// How many characters of the phrase the tokens in `cues` hold, or `None` when the
/// phrase carries no cue.
///
/// Cues that agree add up, so a span carrying two designators is read with the
/// characters of both; `token_chars` is the character length of each token of the
/// phrase, in the same order as `normalised`.
fn cue_chars(
    normalised: &[String],
    token_chars: &[usize],
    cues: &HashSet<&'static str>,
) -> Option<usize> {
    let chars: usize = normalised
        .iter()
        .zip(token_chars)
        .filter(|(token, _)| cues.contains(token.as_str()))
        .map(|(_, chars)| *chars)
        .sum();
    (chars > 0).then_some(chars)
}

/// The longest contiguous run of a phrase's tokens that a lexicon names, as the run's
/// position in the phrase, with the type that lexicon gives it. Organizations are
/// consulted before places at equal length, so a company named after a city reads as
/// the company.
fn lexicon_match(normalised: &[String]) -> Option<(Range<usize>, &'static str)> {
    for length in (1..=normalised.len()).rev() {
        for start in 0..=normalised.len() - length {
            let phrase = canonical(&normalised[start..start + length].join(" "));
            if organizations().contains(phrase.as_str()) {
                return Some((start..start + length, TYPE_ORGANIZATION));
            }
            if places().contains(phrase.as_str()) {
                return Some((start..start + length, TYPE_LOCATION));
            }
        }
    }
    None
}

/// The phrase's tokens as a lexicon holds a name: see [`canonical`].
fn canonical_phrase(tokens: &[Token], phrase: Range<usize>) -> String {
    canonical(
        &tokens[phrase]
            .iter()
            .map(|token| token.lower.as_str())
            .collect::<Vec<&str>>()
            .join(" "),
    )
}

/// Divide a candidate span back into the names it joined.
///
/// A span a lexicon names as a whole is one name (`Bank of America`). Otherwise it is
/// divided at every run of phrase connectors, except where the word in front of the
/// run is an institution, place or event head noun and so takes the connector's
/// complement (`University of Washington`): `Jane Doe and Michael Brown` is two
/// names, `Department of Justice` is one.
///
/// It is divided once more where a lexicon names its LEADING words as a company and
/// further capitalised words follow: a company's name followed by a name of its own is
/// the company and then the thing it names (`Amazon Comprehend` is Amazon's service,
/// not a company called "Amazon Comprehend"), which is what keeps the two from being
/// reported as one entity covering both. A tail carrying a legal-form or institution
/// designator is NOT divided off, since that tail is part of the company's own name
/// (`Microsoft Corporation`).
fn divide_phrase(tokens: &[Token], phrase: Range<usize>) -> Vec<Range<usize>> {
    let whole = canonical_phrase(tokens, phrase.clone());
    if organizations().contains(whole.as_str()) || places().contains(whole.as_str()) {
        return vec![phrase];
    }
    if let Some(company) = leading_company(tokens, phrase.clone()) {
        let mut parts = Vec::with_capacity(2);
        parts.push(phrase.start..company);
        parts.extend(divide_phrase(tokens, company..phrase.end));
        return parts;
    }
    let mut parts = Vec::new();
    let mut start = phrase.start;
    let mut index = phrase.start;
    while index < phrase.end {
        if !phrase_connectors().contains(tokens[index].lower.as_str()) {
            index += 1;
            continue;
        }
        let run_start = index;
        while index < phrase.end && phrase_connectors().contains(tokens[index].lower.as_str()) {
            index += 1;
        }
        if run_start > start && is_head_noun(&tokens[run_start - 1].lower) {
            continue;
        }
        if run_start > start {
            parts.push(start..run_start);
        }
        start = index;
    }
    if start < phrase.end {
        parts.push(start..phrase.end);
    }
    parts
}

/// Where the company name a lexicon reads at the START of `phrase` ends, when the
/// phrase carries one and further words follow it.
///
/// `None` when no leading run of the phrase names a company, when that run is the
/// whole phrase, or when the words after it carry a legal-form or institution
/// designator — then the tail is part of the company's own name rather than a name of
/// its own. The LONGEST leading run a lexicon names is the one answered, so a company
/// whose name is several words long is not cut in half.
fn leading_company(tokens: &[Token], phrase: Range<usize>) -> Option<usize> {
    let tail_designates = |from: usize| {
        tokens[from..phrase.end].iter().any(|token| {
            organization_designators().contains(token.lower.as_str())
                || geographic_designators().contains(token.lower.as_str())
                || event_designators().contains(token.lower.as_str())
        })
    };
    (phrase.start + 1..phrase.end)
        .rev()
        .filter(|end| organizations().contains(canonical_phrase(tokens, phrase.start..*end).as_str()))
        .find(|end| !tail_designates(*end))
}

/// Whether a lexicon names the capitalised words immediately in front of `phrase` as
/// a company, inside the same sentence.
///
/// What `divide_phrase` divided off: the leading company name of one candidate span.
/// Only whitespace may stand between the two, so a company named in an earlier clause
/// says nothing about this span.
///
/// The look-back is bounded by [`MAX_SPAN_TOKENS`], the longest candidate span this
/// recogniser reads, so the check costs a constant per phrase rather than a scan of
/// everything in front of it — a document of thousands of capitalized tokens cannot
/// make the pass quadratic.
fn company_in_front(text: &str, tokens: &[Token], phrase: Range<usize>) -> bool {
    let Some(before) = phrase.start.checked_sub(1) else {
        return false;
    };
    if !text[tokens[before].end..tokens[phrase.start].start]
        .chars()
        .all(char::is_whitespace)
    {
        return false;
    }
    // Ascending, so the LONGEST run ending at `before` is the one read: a company
    // whose name is several words long is read whole.
    (before.saturating_sub(MAX_SPAN_TOKENS - 1)..=before).any(|start| {
        tokens[start..=before].iter().all(|token| token.capitalized)
            && organizations().contains(canonical_phrase(tokens, start..before + 1).as_str())
    })
}

/// The character length of each of the phrase's tokens, in phrase order: what every
/// rule's evidence is weighed over, since a rule constrains CHARACTERS and the
/// whitespace and punctuation between two tokens is not something it names.
fn token_chars(text: &str, tokens: &[Token], phrase: Range<usize>) -> Vec<usize> {
    tokens[phrase]
        .iter()
        .map(|token| text[token.start..token.end].chars().count())
        .collect()
}

/// How many characters of the phrase carry the capital that marks a name in running
/// English text.
///
/// At least one, because a candidate phrase is anchored on a capitalized token: the
/// orthographic evidence of a candidate span is never nil.
fn capitalized_chars(text: &str, tokens: &[Token], phrase: Range<usize>) -> usize {
    tokens[phrase]
        .iter()
        .filter(|token| token.capitalized)
        .map(|token| text[token.start..token.end].chars().count())
        .sum::<usize>()
        .max(1)
}

/// Whether the span is written the way English writes a personal name: two or more
/// tokens, the first and the last capitalized, every token either capitalized
/// (a given name, a middle initial, a surname) or one of the particles a name
/// carries ([`NAME_PARTICLES`], as in `Vincent van Gogh`), and no determiner in front
/// of it ([`DETERMINERS`]).
///
/// This is SHAPE evidence — it says the characters are written like a name, not
/// whose name they are — so it never types a span on its own: the caller pairs it
/// with the syntactic position below.
fn person_name_shape(text: &str, tokens: &[Token], phrase: Range<usize>) -> bool {
    let span = &tokens[phrase.clone()];
    let Some((first, last)) = span.first().zip(span.last()) else {
        return false;
    };
    if span.len() < 2 || !first.capitalized || !last.capitalized {
        return false;
    }
    let introduced_by_determiner = phrase
        .start
        .checked_sub(1)
        .and_then(|previous| tokens.get(previous))
        .is_some_and(|previous| {
            determiners().contains(previous.lower.as_str())
                && text[previous.end..first.start]
                    .chars()
                    .all(char::is_whitespace)
        });
    !introduced_by_determiner
        && span.iter().filter(|token| token.capitalized).count() >= 2
        && span
            .iter()
            .all(|token| token.capitalized || name_particles().contains(token.lower.as_str()))
}

/// Whether the span stands where English puts a person: in the subject position of a
/// verb whose subject is human, or in the participant position such a verb marks with
/// a preposition ([`PERSON_PREDICATES`], [`PERSON_ROLE_MARKERS`]).
///
/// Only a token the span is adjacent to inside one sentence counts — the characters
/// between the two must be whitespace — so a verb across a clause or sentence
/// boundary is no evidence about this span.
fn person_bearing_position(text: &str, tokens: &[Token], phrase: Range<usize>) -> bool {
    let adjacent = |left: usize, right: usize| {
        text[tokens[left].end..tokens[right].start]
            .chars()
            .all(char::is_whitespace)
    };
    // The verb after the span: `Jeff Bezos said`.
    if phrase.end < tokens.len()
        && adjacent(phrase.end - 1, phrase.end)
        && person_predicates().contains(tokens[phrase.end].lower.as_str())
    {
        return true;
    }
    let Some(before) = phrase.start.checked_sub(1) else {
        return false;
    };
    if !adjacent(before, phrase.start) {
        return false;
    }
    // The verb in front of the span: `hired Jane Doe`.
    if person_predicates().contains(tokens[before].lower.as_str()) {
        return true;
    }
    // The role the verb's preposition marks: `founded by Jeff Bezos`.
    person_role_markers().contains(tokens[before].lower.as_str())
        && before
            .checked_sub(1)
            .is_some_and(|verb| {
                adjacent(verb, before)
                    && person_predicates().contains(tokens[verb].lower.as_str())
            })
}

/// Type one capitalized phrase from the evidence around and inside it, in order of
/// the evidence's precision. A phrase no rule places is reported as `OTHER` — unless
/// it is a lone word opening a sentence, where the capital is orthography rather than
/// evidence of a name, and then nothing is reported.
fn classify_phrase(text: &str, tokens: &[Token], phrase: Range<usize>) -> Option<Recognised> {
    // The phrase as the document writes it, before an honorific or an article in
    // front of the name is trimmed off.
    let written_start = tokens[phrase.start].start;
    let written_end = tokens[phrase.end - 1].end;
    let written_chars: usize = token_chars(text, tokens, phrase.clone()).iter().sum();
    // A lexicon entry naming the phrase AS WRITTEN is the whole evidence, so the
    // name keeps the article it is written with (`The New York Times`).
    let whole = canonical_phrase(tokens, phrase.clone());
    for (lexicon, entity_type) in [
        (organizations(), TYPE_ORGANIZATION),
        (places(), TYPE_LOCATION),
    ] {
        if lexicon.contains(whole.as_str()) {
            return Some(Recognised {
                start: written_start,
                end: written_end,
                entity_type,
                // The lexicon spells out every character of the span, so nothing in
                // it is unaccounted for; the orthography of the name corroborates it.
                evidence: Evidence {
                    support: EVIDENCE_PER_LEXICON_CHAR * written_chars as f64
                        + EVIDENCE_PER_CAPITALIZED_CHAR
                            * capitalized_chars(text, tokens, phrase.clone()) as f64,
                    competing: 0.0,
                },
                priority: 1,
            });
        }
    }
    let mut phrase = phrase;
    let mut title_cue = false;
    // Whether the name is written with an article in front of it, which a personal
    // name in English never is (`The Zorblax Initiative` names a body, not a person).
    let mut article = false;
    // An honorific or an article in front of the name is not part of it.
    while phrase.len() > 1 {
        let leading = tokens[phrase.start].lower.as_str();
        if person_titles().contains(leading) {
            title_cue = true;
            phrase.start += 1;
            continue;
        }
        if function_words().contains(leading) {
            article = true;
            phrase.start += 1;
            continue;
        }
        break;
    }
    if !title_cue {
        title_cue = phrase
            .start
            .checked_sub(1)
            .and_then(|previous| tokens.get(previous))
            .is_some_and(|previous| {
                person_titles().contains(previous.lower.as_str())
                    && text[previous.end..tokens[phrase.start].start]
                        .chars()
                        .all(|c| c.is_whitespace() || c == '.')
            });
    }

    let start = tokens[phrase.start].start;
    let end = tokens[phrase.end - 1].end;
    let normalised: Vec<String> = tokens[phrase.clone()]
        .iter()
        .map(|token| token.lower.clone())
        .collect();
    // What every rule below weighs its evidence over: the characters of each token
    // of the span, the characters of the span as a whole, and the characters the
    // document capitalized.
    let chars_of = token_chars(text, tokens, phrase.clone());
    let span_chars: usize = chars_of.iter().sum();
    let head_chars = chars_of.first().copied().unwrap_or_default();
    let capitalized = capitalized_chars(text, tokens, phrase.clone());
    // One typed reading of the span, weighed from the evidence that typed it: the
    // rule's own strength over the characters it names, corroborated by the span's
    // orthography, against the reading in which the characters that evidence does NOT
    // name are no part of the entity.
    let typed = |entity_type: &'static str, strength_per_char: f64, named_chars: usize| {
        Some(Recognised {
            start,
            end,
            entity_type,
            evidence: Evidence {
                support: strength_per_char * named_chars as f64
                    + EVIDENCE_PER_CAPITALIZED_CHAR * capitalized as f64,
                competing: READING_UNNAMED_CHAR * span_chars.saturating_sub(named_chars) as f64,
            },
            priority: 1,
        })
    };

    if let Some(cues) = cue_chars(&normalised, &chars_of, organization_designators()) {
        return typed(TYPE_ORGANIZATION, EVIDENCE_PER_CUE_CHAR, cues);
    }
    // An honorific announces that the name behind it is a personal one, which places
    // the name's head; what the rest of the span adds, the cue does not name.
    if title_cue {
        return typed(TYPE_PERSON, EVIDENCE_PER_CUE_CHAR, head_chars);
    }
    if let Some(cues) = cue_chars(&normalised, &chars_of, geographic_designators()) {
        return typed(TYPE_LOCATION, EVIDENCE_PER_CUE_CHAR, cues);
    }
    if let Some(cues) = cue_chars(&normalised, &chars_of, event_designators()) {
        return typed(TYPE_EVENT, EVIDENCE_PER_CUE_CHAR, cues);
    }
    let lexicon_hit = lexicon_match(&normalised);
    // A lexicon entry naming the WHOLE phrase outranks the given-name rule, so a
    // place that is also a given name reads as the place.
    if let Some((run, entity_type)) = lexicon_hit.clone() {
        if run.len() == normalised.len() {
            return typed(entity_type, EVIDENCE_PER_LEXICON_CHAR, span_chars);
        }
    }
    if given_names().contains(normalised[0].as_str()) {
        return typed(TYPE_PERSON, EVIDENCE_PER_CUE_CHAR, head_chars);
    }
    // A span written like a personal name, standing where English puts a person, is
    // a PERSON however the name is spelled: the evidence is the SHAPE of the name
    // together with its syntactic position, so a name no lexicon carries is typed
    // from the document's own structure rather than left to the catch-all.
    if !article
        && person_name_shape(text, tokens, phrase.clone())
        && person_bearing_position(text, tokens, phrase.clone())
    {
        return typed(TYPE_PERSON, EVIDENCE_PER_NAME_SHAPE_CHAR, span_chars);
    }
    if let Some((run, entity_type)) = lexicon_hit {
        let named: usize = chars_of.get(run).map_or(0, |run| run.iter().sum());
        return typed(entity_type, EVIDENCE_PER_LEXICON_CHAR, named);
    }
    // A name standing straight after a company's name, inside the same sentence, names
    // something of that company's: a product or service it offers, which is the
    // modelled `COMMERCIAL_ITEM`. The cue is the company name in front of the span —
    // the same shape of evidence as the honorific that announces a person — so it
    // weighs over the head of the span it announces, and it is read only where a
    // lexicon names the words in front as a company, never from the capital alone.
    if company_in_front(text, tokens, phrase.clone()) {
        return typed(TYPE_COMMERCIAL_ITEM, EVIDENCE_PER_CUE_CHAR, head_chars);
    }
    if normalised.len() >= 2 || !tokens[phrase.start].sentence_initial {
        // The span is a name — that is what its orthography says — but no rule
        // places it in a category, so the modelled `OTHER` is the reading reported
        // and the typed readings nothing could confirm stay open.
        return Some(Recognised {
            start,
            end,
            entity_type: TYPE_OTHER,
            evidence: Evidence {
                support: EVIDENCE_PER_CAPITALIZED_CHAR * capitalized as f64,
                competing: READING_UNTYPED_NAME,
            },
            priority: 1,
        });
    }
    None
}

/// Keep one entity per stretch of characters: the earliest candidate first, the
/// longest reading of the same start, and at equal length the rule class with the
/// higher precision. Overlapping candidates behind the one kept are dropped, so the
/// returned list is ordered by position and never double-reports a character.
///
/// A dropped candidate covering EXACTLY the kept span's characters with another type
/// is a reading of that mention the evidence left open, so its weight stays in the
/// kept entity's confidence: a mention two rules read two ways is reported with less
/// certainty than one only a single rule can read. A candidate of the same type, or
/// one covering part of the span, is a reading the kept one already accounts for and
/// weighs nothing further.
fn resolve_overlaps(mut found: Vec<Recognised>) -> Vec<Recognised> {
    found.sort_by(|left, right| {
        left.start
            .cmp(&right.start)
            .then((right.end - right.start).cmp(&(left.end - left.start)))
            .then(right.priority.cmp(&left.priority))
            .then(
                right
                    .evidence
                    .support
                    .total_cmp(&left.evidence.support),
            )
    });
    let mut kept: Vec<Recognised> = Vec::new();
    for candidate in found {
        match kept.last_mut() {
            Some(last) if candidate.start < last.end => {
                if last.entity_type != candidate.entity_type
                    && candidate.start == last.start
                    && candidate.end == last.end
                {
                    last.evidence.competing += candidate.evidence.support;
                }
            }
            _ => kept.push(candidate),
        }
    }
    kept
}

/// Weigh in what the REST of the document says about each mention: a name the
/// document writes again, read the same way, corroborates that reading.
///
/// The evidence is a property of the document rather than of one occurrence — every
/// writing of the mention carries it — so a caller reads the same confidence whichever
/// occurrence it looks at, and a mention written once is left exactly as its own span
/// weighed.
fn corroborate_repeated_mentions(text: &str, found: &mut [Recognised]) {
    // One pass to count each reading, so the weighing stays linear in the number of
    // detections however many mentions a document carries.
    let mut writings: HashMap<(&str, &str), usize> = HashMap::new();
    for entity in found.iter() {
        *writings
            .entry((&text[entity.start..entity.end], entity.entity_type))
            .or_default() += 1;
    }
    for entity in found.iter_mut() {
        let repeats = writings
            .get(&(&text[entity.start..entity.end], entity.entity_type))
            .copied()
            .unwrap_or(1)
            .saturating_sub(1);
        entity.evidence.support += EVIDENCE_PER_CORROBORATING_MENTION * repeats as f64;
    }
}

/// Every entity the recogniser finds in `text`, as the modelled `Entity` list:
/// ordered by position, each carrying the characters it covers, the modelled type,
/// the zero-based CHARACTER offsets of that stretch and the confidence its own
/// evidence leaves that reading ([`Evidence::confidence`]) — a per-detection value,
/// not a constant of the rule class that typed it.
///
/// The offsets are consistent with the text by construction: `BeginOffset` is the
/// character index the entity starts at and `EndOffset` the index one past its last
/// character, so the entity's `Text` is exactly the substring they delimit, and the
/// span covers the WHOLE mention the document writes.
pub fn detect_entities(text: &str) -> Vec<Entity> {
    let char_starts: Vec<usize> = text.char_indices().map(|(index, _)| index).collect();
    let char_offset = |byte: usize| char_starts.partition_point(|&start| start < byte) as i32;
    let mut found = pattern_entities(text);
    found.extend(phrase_entities(text));
    let mut recognised = resolve_overlaps(found);
    corroborate_repeated_mentions(text, &mut recognised);
    recognised
        .into_iter()
        .map(|entity| Entity {
            score: Some(entity.evidence.confidence()),
            r#type: Some(entity.entity_type.to_string()),
            text: Some(text[entity.start..entity.end].to_string()),
            begin_offset: Some(char_offset(entity.start)),
            end_offset: Some(char_offset(entity.end)),
            // Plain-text input has no blocks, so nothing to reference: the modelled
            // member documents it as "empty for plain-text input".
            block_references: None,
        })
        .collect()
}

/// Every entity the recogniser places in `text`, as its BYTE span paired with the
/// modelled `EntityType` it is typed as, in document order.
///
/// The same recognition [`detect_entities`] reports, before the character-offset
/// translation the modelled members carry — the scale a caller that works in byte
/// offsets needs. Read by `DetectTargetedSentiment`, whose targets are the things the
/// document NAMES: one recogniser answers what a document names, so the two
/// operations cannot disagree about it.
pub(crate) fn entity_spans(text: &str) -> Vec<(Range<usize>, &'static str)> {
    let mut found = pattern_entities(text);
    found.extend(phrase_entities(text));
    resolve_overlaps(found)
        .into_iter()
        .map(|entity| (entity.start..entity.end, entity.entity_type))
        .collect()
}

/// Every PERSON mention the entity recogniser places in `text`, as BYTE offsets into
/// it.
///
/// The ONE person-name recogniser of this service, read by the PII family: a personal
/// name carries no closed form, so what places one is the name's shape and the
/// syntactic position it stands in ([`person_name_shape`],
/// [`person_bearing_position`]) together with the honorifics and the person-lexicon
/// entries beside it — exactly the evidence `DetectEntities` types a `PERSON` on. A
/// document's names cannot depend on which operation asks for them, so
/// `ContainsPiiEntities` and `DetectPiiEntities` place their `NAME` entities from this
/// list rather than from a second, narrower recogniser of their own.
///
/// Byte offsets, because that is the scale the PII recognizer resolves overlaps on
/// before translating the surviving spans to the character offsets the modelled
/// members carry.
pub(crate) fn person_name_spans(text: &str) -> Vec<Range<usize>> {
    entity_spans(text)
        .into_iter()
        .filter(|(_, entity_type)| *entity_type == TYPE_PERSON)
        .map(|(span, _)| span)
        .collect()
}

/// [`detect_entities`] run OFF the async worker: the recogniser is synchronous,
/// CPU-bound work with no await of its own, so it goes to the blocking pool and the
/// worker serving this request is released while it runs. The
/// `spawn_blocking(..).await` is a real await point, so a request waiting on a
/// recognition can be cancelled or timed out, and a burst of concurrent documents
/// cannot starve the operations sharing the runtime.
///
/// `Err` carries the sentence the caller puts in its OWN modelled server error: the
/// pass either did not answer inside [`RECOGNITION_TIME_BUDGET`] — the budget bounds
/// the caller's wait, not the blocking task, which runs to its natural end — or did
/// not run at all, and in both cases nothing was analysed, so no entity may be
/// fabricated for it.
///
/// `pub(crate)` because every other caller recognises a document through this SAME
/// seam — the batch sibling runs it once per document — so one document's entities
/// cannot depend on which operation submitted it.
pub(crate) async fn recognize_entities(text: String) -> Result<Vec<Entity>, String> {
    match ::tokio::time::timeout(
        RECOGNITION_TIME_BUDGET,
        ::tokio::task::spawn_blocking(move || detect_entities(&text)),
    )
    .await
    {
        Ok(Ok(entities)) => Ok(entities),
        Ok(Err(error)) => Err(format!("the entity recognition did not complete: {error}")),
        Err(_) => Err(format!(
            "the entity recognition did not complete within {} seconds",
            RECOGNITION_TIME_BUDGET.as_secs()
        )),
    }
}

