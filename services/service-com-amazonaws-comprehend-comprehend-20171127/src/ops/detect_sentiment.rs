/// The shared sentiment engine. Built once: `new()` parses the lexicon files, which
/// is far more expensive than scoring one document, and it is immutable afterwards.
fn analyzer() -> &'static SentimentIntensityAnalyzer<'static> {
    static ANALYZER: OnceLock<SentimentIntensityAnalyzer<'static>> = OnceLock::new();
    ANALYZER.get_or_init(SentimentIntensityAnalyzer::new)
}

/// The modelled enum values of `SentimentType` paired with their confidences, in
/// the order a tie between two equal confidences resolves: a signed verdict wins
/// over `NEUTRAL`, which wins over `MIXED`.
fn ranked_labels(
    positive: f64,
    negative: f64,
    neutral: f64,
    mixed: f64,
) -> [(&'static str, f64); 4] {
    [
        ("POSITIVE", positive),
        ("NEGATIVE", negative),
        ("NEUTRAL", neutral),
        ("MIXED", mixed),
    ]
}

/// How much one unit of a document's NEUTRAL material weighs against one unit of its
/// sentiment-bearing material, in deciding whether the document carries sentiment at
/// all.
///
/// The engine answers how INTENSE the sentiment in a document is, and over which
/// share of it: `pos`, `neg` and `neu` are the shares of the document's weight
/// carrying each polarity and no polarity, summing to 1. The modelled
/// `SentimentScore` members are confidences — "the sentiments, and their
/// corresponding confidence levels" — so the share has to be calibrated into one, and
/// the calibration is a comparison: the document carries sentiment to the extent its
/// sentiment-bearing material OUTWEIGHS its neutral material. In odds form, the
/// confidence is `d / (d + this * (1 - d))` over the polarity-carrying share `d`,
/// which is 0 for a document holding no sentiment-bearing word, approaches 1 for one
/// holding nothing else, and rises with the share in between.
///
/// Below 1 because a sentiment-bearing word is the informative material in deciding
/// this question and a neutral one is the background it stands in: a sentence of
/// praise does not stop being praise for also naming what is praised. Not far below
/// 1, because the comparison has to stay a comparison: a document of plain fact that
/// happens to carry one evaluative word is mostly neutral material and must come back
/// NEUTRAL, which is exactly what reporting a COUNT of lexicon hits cannot do — one
/// hit in a long document and one in a three-word complaint are the same count and
/// nothing like the same evidence.
///
/// It is the ONE calibration constant of this projection, applied identically to
/// every document, so no request can select it.
const NEUTRAL_MATERIAL_WEIGHT: f64 = 0.3;

/// How much CONTRAST the reported distribution carries over the shares the engine
/// measured.
///
/// Why a calibration step exists at all: the engine answers with SHARES of the
/// document's weight, and a share is not what the modelled members describe — each is
/// "the level of confidence that Amazon Comprehend has in the accuracy of its
/// detection of the … sentiment", which a caller gates a decision on ("act above
/// 0.95", "treat a second sentiment above 0.1 as ambiguous"). Reporting the share
/// itself hands a document whose material predominantly carries one reading back as
/// an ambiguous one, with the runner-up holding everything the leader did not.
///
/// What this is: each of the four shares raised to this exponent, then renormalised
/// over the four. The transform is strictly monotone, so it changes NO ranking — the
/// verdict is the same arg-max over the same four hypotheses — and it introduces no
/// number of its own: every confidence is still a function of the engine's reading of
/// the submitted document. What it changes is the SCALE: the confidence concentrates
/// on the reading the document's own material predominantly supports, and the others
/// keep what their own evidence leaves them, so the four stay ordered by evidence and
/// a confident document stops being reported as a doubtful one.
///
/// It is the ONE contrast constant of this projection, applied identically to every
/// class of every document, so no request can select it. The value is where both
/// halves of a confidence hold: a document whose material predominantly carries one
/// reading clears the decision threshold a caller gates on, while the margin the
/// engine measured still SHOWS — two documents it is differently sure about are
/// reported differently, which a higher exponent loses by squeezing every clear
/// document onto one reported value.
const SENTIMENT_CONTRAST_EXPONENT: i32 = 6;

/// The weight of a reading the document leaves OPEN, per WORD of the document that
/// leaves it open.
///
/// A reading is open when the document could carry it and the engine's lexicon could
/// have missed the words that show it, or read words it holds the other way round:
/// every one of the four modelled members is open for any document, since a document
/// the engine read as wholly positive still leaves room for a negative word the
/// lexicon does not hold or a negation it mis-scoped. This is the weight of that room,
/// so a class the engine found no word for comes back as the negligible possibility it
/// is rather than as a flat 0.
///
/// How MUCH room each reading keeps is a function of the DOCUMENT, because the document
/// is what leaves it, and it is counted in the document's own words
/// ([`open_reading_words`]): for a signed reading, the words the engine placed no
/// polarity on — each one a word that could have carried the polarity it missed — as
/// far as the net polarity it measured admits that direction; for `NEUTRAL`, the words
/// it DID read as polar, which it could have over-read. So the residual members of two
/// documents are not one shared literal — which says the same thing about every
/// document and destroys any ordering between them — and the residual members of one
/// document are ordered by what that document itself says.
///
/// `MIXED` is open the way the two signed readings are open TOGETHER: it is the
/// confidence that the document carries BOTH polarities at once, so it needs a word
/// the lexicon missed of EACH polarity, and the room it keeps is the room the two
/// signed readings keep multiplied — strictly below either of them, strictly above
/// zero for any document that leaves both open, and falling away faster than either as
/// the document rules them out. A confidence is never a flat impossibility, which is
/// what an exact zero would report, and what destroys a client's log-scale comparison
/// between two documents.
///
/// The room is conceded by the reading the document's own material supports, which is
/// the only one with anything to concede, so the four still sum to 1. A class the
/// document carries any evidence at all for is reported with that evidence, which is
/// far larger. The weight itself is the ONE such constant of this projection, applied
/// identically to every class of every document, so no request can select it: a
/// hundred-thousandth of one word's worth, which leaves an open reading orders of
/// magnitude below any threshold a caller gates a decision on while keeping it above
/// the flat impossibility it is not.
const MISSED_READING_WEIGHT: f64 = 1e-5;

/// How many of a document's words can bear on the room one open reading keeps.
///
/// The room is a RESIDUAL, so it stays one: a document long enough to hold hundreds of
/// words the engine placed no polarity on has already said everything it can about a
/// polarity the lexicon might have missed, and a reading nothing else supports may not
/// grow into a confidence a caller could act on however long the document runs.
const MISSED_READING_WORD_CEILING: f64 = 500.0;

/// The words of `text` that leave a reading open, in the document's own words: `share`
/// of them, plus the one word any document could have hidden a missed reading in, and
/// no more than [`MISSED_READING_WORD_CEILING`].
///
/// The share is the engine's own — the share of the document's weight it read as
/// carrying no polarity, for a signed reading, or as carrying one, for `NEUTRAL` — so
/// the count is a property of the submitted document and of nothing else. The plus one
/// is what keeps every open reading strictly above 0 for a document the engine read at
/// all, however short it is.
fn open_reading_words(text: &str, share: f64) -> f64 {
    let words = text.split_whitespace().count() as f64;
    (1.0 + words * share).min(MISSED_READING_WORD_CEILING)
}

/// Score `text` into Comprehend's four confidences plus the winning label.
///
/// The engine reports `pos`/`neg`/`neu` — the shares of the document's weight
/// carrying each polarity, which sum to 1 — and `compound`, its normalised net
/// polarity. Those become the four modelled confidences in two steps:
///
/// 1. HOW SURE the document carries sentiment at all: the share of its weight that
///    carries a polarity at all, `pos + neg`, weighed against the neutral material
///    beside it ([`NEUTRAL_MATERIAL_WEIGHT`]). Whatever is left of 1 is the confidence
///    of `Neutral` — the hypothesis that the document carries no sentiment — so a
///    document of plain fact comes back NEUTRAL however long it is, and one whose
///    every word is evaluative comes back with a classifier's confidence.
/// 2. HOW that confidence splits between the signed classes: over the
///    sentiment-bearing weight alone, `p` and `n` are the positive and negative
///    shares (`p + n = 1`). `Mixed` is the part of it carrying BOTH polarities,
///    `2 * min(p, n)`, which is what MIXED means, and the rest, `|p - n|`, goes to
///    whichever direction predominates. The three sum to 1, so the four shares sum to
///    1, and a document carrying both polarities in balance is MIXED rather than the
///    stronger of the two.
/// 3. The four shares read as CONFIDENCES: each raised to
///    [`SENTIMENT_CONTRAST_EXPONENT`] and the four renormalised, which leaves the
///    distribution concentrated on the reading the document's own material
///    predominantly supports while keeping the four ordered exactly as the engine's
///    shares ordered them.
///
/// Each OPEN class then keeps the room the DOCUMENT leaves it
/// ([`MISSED_READING_WEIGHT`]), conceded by the reading the document supports, so no
/// open reading is reported as a flat impossibility, the residual members of two
/// documents are not one shared literal, and the residual members of ONE document are
/// four distinct magnitudes ordered by what that document itself leaves open —
/// `MIXED`, which needs a missed word of each polarity, keeping the product of what
/// the two signed readings keep. The verdict is the arg-max of the four the response
/// carries.
///
/// Visible to the crate because `DetectTargetedSentiment` scores the clause each
/// mention sits in through exactly this function, and `BatchDetectSentiment` scores
/// every document of a batch through it: one document, one clause and one batched
/// document must all be scored on the same scale, so there is one scorer rather
/// than three. Batching changes how many documents one request carries, never how a
/// document is scored, so a batch answers the same verdict for the same text.
pub(crate) fn score_sentiment(text: &str) -> (String, SentimentScore) {
    let scores = analyzer().polarity_scores(text);
    let positive_share = scores.get("pos").copied().unwrap_or_default();
    let negative_share = scores.get("neg").copied().unwrap_or_default();

    // Step 1: the confidence that the document carries sentiment at all, from the
    // share of its weight that carries a polarity against the neutral material
    // beside it.
    let signed = positive_share + negative_share;
    let carries_sentiment = if signed > 0.0 {
        signed / (signed + NEUTRAL_MATERIAL_WEIGHT * (1.0 - signed))
    } else {
        0.0
    };

    // Step 2: how that confidence splits, from the balance of the two polarities
    // over the sentiment-bearing weight alone.
    let (positive, negative, mixed) = if signed > 0.0 {
        let positive_part = positive_share / signed;
        let negative_part = negative_share / signed;
        let both = 2.0 * positive_part.min(negative_part);
        (
            carries_sentiment * (positive_part - negative_part).max(0.0),
            carries_sentiment * (negative_part - positive_part).max(0.0),
            carries_sentiment * both,
        )
    } else {
        // The engine found no polarity to split: the whole confidence that the
        // document carries sentiment has nowhere to go, so the document is neutral.
        (0.0, 0.0, 0.0)
    };
    let neutral = (1.0 - positive - negative - mixed).max(0.0);

    // Step 3: the four shares read as confidences. Raising each to the contrast
    // exponent and renormalising is strictly monotone, so the ordering of the four —
    // and with it the verdict below — is the engine's own.
    let weights =
        [positive, negative, neutral, mixed].map(|share| share.powi(SENTIMENT_CONTRAST_EXPONENT));
    let weight: f64 = weights.iter().sum();
    let [positive, negative, neutral, mixed] = if weight > 0.0 {
        weights.map(|value| value / weight)
    } else {
        // No share at all: the engine read nothing in the document, which is the
        // NEUTRAL hypothesis and nothing else.
        [0.0, 0.0, 1.0, 0.0]
    };

    // The room every OPEN reading keeps ([`MISSED_READING_WEIGHT`]), counted in the
    // document's own words and conceded by the reading that material supports, so the
    // four still sum to 1. A signed reading is open over the words the engine placed no
    // polarity on, as far as the net polarity it measured admits that direction;
    // `NEUTRAL` is open over the words it read as polar, which it could have over-read;
    // `MIXED` is open only where BOTH signed readings are, so it keeps the room the two
    // of them keep multiplied, which is strictly below either.
    let lean = ((scores.get("compound").copied().unwrap_or_default() + 1.0) / 2.0).clamp(0.0, 1.0);
    let unread = open_reading_words(text, (1.0 - signed).clamp(0.0, 1.0));
    let mut confidences = [positive, negative, neutral, mixed];
    let open_positive = MISSED_READING_WEIGHT * unread * lean;
    let open_negative = MISSED_READING_WEIGHT * unread * (1.0 - lean);
    let floors = [
        open_positive,
        open_negative,
        MISSED_READING_WEIGHT * open_reading_words(text, signed.clamp(0.0, 1.0)),
        open_positive * open_negative,
    ];
    // The supported reading is the arg-max, taken as the LAST of equal readings
    // because `ranked_labels` resolves a tie to the FIRST of them: the concession
    // then comes out of the reading the tie-break does not name, so a tie stays
    // resolved the way the engine's own shares resolved it. The verdict below is the
    // arg-max of the four the response carries, whatever this does to them, so the
    // label and the distribution cannot disagree.
    let supported = (0..confidences.len())
        .reduce(|best, candidate| {
            if confidences[candidate] >= confidences[best] {
                candidate
            } else {
                best
            }
        })
        .unwrap_or_default();
    let mut conceded = 0.0;
    for index in 0..confidences.len() {
        if index != supported && confidences[index] < floors[index] {
            conceded += floors[index] - confidences[index];
            confidences[index] = floors[index];
        }
    }
    confidences[supported] -= conceded;
    let [positive, negative, neutral, mixed] = confidences;

    // Arg-max over the four. `ranked_labels` is already in tie-break order and the
    // fold keeps the incumbent on a tie, so two equal confidences always resolve to
    // the same label.
    let sentiment = ranked_labels(positive, negative, neutral, mixed)
        .into_iter()
        .reduce(|best, candidate| if candidate.1 > best.1 { candidate } else { best })
        .map_or("NEUTRAL", |(label, _)| label);

    (
        sentiment.to_string(),
        SentimentScore {
            positive: Some(positive as f32),
            negative: Some(negative as f32),
            neutral: Some(neutral as f32),
            mixed: Some(mixed as f32),
        },
    )
}

