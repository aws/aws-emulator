/// The `LanguageCode` values the in-process sentiment engine has a lexicon for.
///
/// VADER's lexicon and its boosters, negations and idioms are English. Every other
/// value Comprehend's `LanguageCode` enum names is answered with the modelled
/// `UnsupportedLanguageException` rather than with a neutral verdict that no
/// analysis produced. Shared with `crate::ops::batch_detect_sentiment`, whose
/// `LanguageCode` covers every document in the batch.
pub(crate) const ANALYSABLE_LANGUAGES: &[&str] = &["en"];

/// The shared sentiment engine. Built once: `new()` parses the lexicon files, which
/// is far more expensive than scoring one document, and it is immutable afterwards.
fn analyzer() -> &'static SentimentIntensityAnalyzer<'static> {
    static ANALYZER: OnceLock<SentimentIntensityAnalyzer<'static>> = OnceLock::new();
    ANALYZER.get_or_init(SentimentIntensityAnalyzer::new)
}

/// The modelled enum values of `SentimentType` paired with their confidences, in
/// the order a tie between two equal confidences resolves: a signed verdict wins
/// over `NEUTRAL`, which wins over `MIXED`.
fn ranked_labels(
    positive: f64,
    negative: f64,
    neutral: f64,
    mixed: f64,
) -> [(&'static str, f64); 4] {
    [
        ("POSITIVE", positive),
        ("NEGATIVE", negative),
        ("NEUTRAL", neutral),
        ("MIXED", mixed),
    ]
}

/// How much one unit of a document's NEUTRAL material weighs against one unit of its
/// sentiment-bearing material, in deciding whether the document carries sentiment at
/// all.
///
/// The engine answers how INTENSE the sentiment in a document is, and over which
/// share of it: `pos`, `neg` and `neu` are the shares of the document's weight
/// carrying each polarity and no polarity, summing to 1. The modelled
/// `SentimentScore` members are confidences — "the sentiments, and their
/// corresponding confidence levels" — so the share has to be calibrated into one, and
/// the calibration is a comparison: the document carries sentiment to the extent its
/// sentiment-bearing material OUTWEIGHS its neutral material. In odds form, the
/// confidence is `d / (d + this * (1 - d))` over the polarity-carrying share `d`,
/// which is 0 for a document holding no sentiment-bearing word, approaches 1 for one
/// holding nothing else, and rises with the share in between.
///
/// Below 1 because a sentiment-bearing word is the informative material in deciding
/// this question and a neutral one is the background it stands in: a sentence of
/// praise does not stop being praise for also naming what is praised. Not far below
/// 1, because the comparison has to stay a comparison: a document of plain fact that
/// happens to carry one evaluative word is mostly neutral material and must come back
/// NEUTRAL, which is exactly what reporting a COUNT of lexicon hits cannot do — one
/// hit in a long document and one in a three-word complaint are the same count and
/// nothing like the same evidence.
///
/// It is the ONE calibration constant of this projection, applied identically to
/// every document, so no request can select it.
const NEUTRAL_MATERIAL_WEIGHT: f64 = 0.3;

/// The confidence each of the four modelled classes keeps whatever the document says.
///
/// `SentimentScore` is a distribution over four hypotheses, and no hypothesis about a
/// natural-language document is impossible: a document the engine reads as wholly
/// positive still leaves a little room for a negative reading the lexicon missed.
/// This is that room — the prior mass each class carries before the document's own
/// evidence is added, which is what keeps every member strictly positive instead of
/// reporting a flat 0 for a class the engine found no word for.
const SENTIMENT_CLASS_PRIOR: f64 = 1e-3;

/// Score `text` into Comprehend's four confidences plus the winning label.
///
/// The engine reports `pos`/`neg`/`neu` — the shares of the document's weight
/// carrying each polarity, which sum to 1 — and `compound`, its normalised net
/// polarity. Those become the four modelled confidences in two steps:
///
/// 1. HOW SURE the document carries sentiment at all: the share of its weight that
///    carries a polarity at all, `pos + neg`, weighed against the neutral material
///    beside it ([`NEUTRAL_MATERIAL_WEIGHT`]). Whatever is left of 1 is the confidence
///    of `Neutral` — the hypothesis that the document carries no sentiment — so a
///    document of plain fact comes back NEUTRAL however long it is, and one whose
///    every word is evaluative comes back with a classifier's confidence.
/// 2. HOW that confidence splits between the signed classes: over the
///    sentiment-bearing weight alone, `p` and `n` are the positive and negative
///    shares (`p + n = 1`). `Mixed` is the part of it carrying BOTH polarities,
///    `2 * min(p, n)`, which is what MIXED means, and the rest, `|p - n|`, goes to
///    whichever direction predominates. The three sum to 1, so the four confidences
///    sum to 1 with no renormalisation, and a document carrying both polarities in
///    balance is MIXED rather than the stronger of the two.
///
/// Each class then keeps the [`SENTIMENT_CLASS_PRIOR`] every hypothesis holds, so no
/// member is reported as a flat impossibility, and the verdict is the arg-max of the
/// four the response carries.
///
/// Visible to the crate because `DetectTargetedSentiment` scores the clause each
/// mention sits in through exactly this function, and `BatchDetectSentiment` scores
/// every document of a batch through it: one document, one clause and one batched
/// document must all be scored on the same scale, so there is one scorer rather
/// than three. Batching changes how many documents one request carries, never how a
/// document is scored, so a batch answers the same verdict for the same text.
pub(crate) fn score_sentiment(text: &str) -> (String, SentimentScore) {
    let scores = analyzer().polarity_scores(text);
    let positive_share = scores.get("pos").copied().unwrap_or_default();
    let negative_share = scores.get("neg").copied().unwrap_or_default();

    // Step 1: the confidence that the document carries sentiment at all, from the
    // share of its weight that carries a polarity against the neutral material
    // beside it.
    let signed = positive_share + negative_share;
    let carries_sentiment = if signed > 0.0 {
        signed / (signed + NEUTRAL_MATERIAL_WEIGHT * (1.0 - signed))
    } else {
        0.0
    };

    // Step 2: how that confidence splits, from the balance of the two polarities
    // over the sentiment-bearing weight alone.
    let (positive, negative, mixed) = if signed > 0.0 {
        let positive_part = positive_share / signed;
        let negative_part = negative_share / signed;
        let both = 2.0 * positive_part.min(negative_part);
        (
            carries_sentiment * (positive_part - negative_part).max(0.0),
            carries_sentiment * (negative_part - positive_part).max(0.0),
            carries_sentiment * both,
        )
    } else {
        // The engine found no polarity to split: the whole confidence that the
        // document carries sentiment has nowhere to go, so the document is neutral.
        (0.0, 0.0, 0.0)
    };
    let neutral = (1.0 - positive - negative - mixed).max(0.0);

    // The prior every hypothesis keeps, which is also what renormalises the four
    // back onto a distribution.
    let smooth = |confidence: f64| {
        (confidence + SENTIMENT_CLASS_PRIOR) / (1.0 + 4.0 * SENTIMENT_CLASS_PRIOR)
    };
    let (positive, negative, neutral, mixed) = (
        smooth(positive),
        smooth(negative),
        smooth(neutral),
        smooth(mixed),
    );

    // Arg-max over the four. `ranked_labels` is already in tie-break order and the
    // fold keeps the incumbent on a tie, so two equal confidences always resolve to
    // the same label.
    let sentiment = ranked_labels(positive, negative, neutral, mixed)
        .into_iter()
        .reduce(|best, candidate| if candidate.1 > best.1 { candidate } else { best })
        .map_or("NEUTRAL", |(label, _)| label);

    (
        sentiment.to_string(),
        SentimentScore {
            positive: Some(positive as f32),
            negative: Some(negative as f32),
            neutral: Some(neutral as f32),
            mixed: Some(mixed as f32),
        },
    )
}

