//! @op RevokePermissions
//!
//! Takes the named permissions back out of the grant records
//! [`crate::state::grant_key`] identifies in
//! [`crate::state::ComAmazonawsLakeformationAwslakeformationState`]'s `permission_grants`,
//! and drops a record when nothing is left of it. A revoke of a permission the
//! grantee does not hold — including a grant that was never made — takes nothing away
//! and is refused with the modelled `InvalidInputException`, so a caller is never told a
//! permission it still holds was removed. WHICH sentence that refusal carries follows
//! whether this service models the grantee on the resource at all: one it does — the
//! `IAM_ALLOWED_PRINCIPALS` group it always models, or a principal holding something there
//! — is told which of the named permissions it does not have, while a grantee holding
//! nothing there is told it holds nothing (see [`crate::state::apply_revoke`]).
//!
//! A revoke reaches every SCOPE the matching grant wrote at: naming a TABLE takes back
//! both the table's own record and the column-scoped record `GrantPermissions` wrote for
//! its column-level permissions, because the two calls are split the same way (see
//! [`crate::state::scoped_grant_records`]).
//!
//! One grant is not a record: a Data Catalog DATABASE is created carrying the account's
//! "use only IAM access control" default — `ALL` to `IAM_ALLOWED_PRINCIPALS` — which no
//! `GrantPermissions` call made, so there is nothing in `permission_grants` to trim. It is
//! held on top of whatever was granted explicitly, and a revoke that names it is
//! remembered in `revoked_default_grants`, so the default is revocable exactly once while
//! an explicit grant on the same resource is trimmed as usual. See
//! [`crate::state::default_database_grant`] for what the default covers and why it stops
//! at databases. The grants a TABLE was created carrying — its creator's Super and the
//! table-level defaults its database hands it ([`crate::state::created_table_grants`]) —
//! are not records
//! either, and are taken away the same way — with what one of them still holds recorded,
//! so a revoke of part of it leaves the rest in place.
//!
//! A revoke names a Data Catalog resource, so one the catalog does not hold is refused for
//! the ENTITY — exactly as a grant on it is ([`crate::state::missing_grant_entity`]) —
//! rather than for the permissions nothing could hold there.
//!
//! How a revoke is READ, resolved and applied is shared with `BatchRevokePermissions`,
//! which revokes the same thing one entry at a time: see
//! [`crate::state::read_revoke_request`], [`crate::state::plan_revoke`] and
//! [`crate::state::apply_revoke`], which also fix the order the refusals above come in.
