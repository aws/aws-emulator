impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateChannel<Eng>
{
    type Input = UpdateChannelInput;
    type Output = UpdateChannelOutput;
    type Error = UpdateChannelError;

    const NAME: &'static str = "UpdateChannel";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CHANNEL_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CHANNEL_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine, ctx.parts()).ok_or_else(unavailable)?;

        // `DryRun` asks for the request to be CHECKED, not performed: every
        // refusal the real update would answer is answered below just the same,
        // and only the writes are skipped. It is a member the operation defines,
        // so it is never itself a reason to refuse the request.
        let dry_run = input.dry_run == Some(true);

        // The two caller-chosen lists this operation STORES carry the same
        // ceilings `CreateChannel` applies, because the per-request work every
        // later read spends walking them is bounded by those ceilings and not by
        // one caller's request body. Checked before anything is written, so a
        // refused update leaves the channel exactly as it was.
        for (member, count, limit) in [
            (
                "inputAttachments",
                input.input_attachments.as_ref().map_or(0, Vec::len),
                crate::state::MAX_INPUT_ATTACHMENTS,
            ),
            (
                "destinations",
                input.destinations.as_ref().map_or(0, Vec::len),
                crate::state::MAX_CHANNEL_DESTINATIONS,
            ),
        ] {
            if count > limit {
                return Err(bad_request(
                    &crate::state::too_many_channel_entries_message(member, count, limit),
                ));
            }
        }

        let now = ::std::time::SystemTime::now();
        let mut state = state.lock();
        // The channel transitions the clock had already made due decide whether
        // this channel has stopped, so materialise them first: each was owed at
        // that instant whether or not this update ran.
        state.settle(now);

        // Absent and already deleted are ONE refusal: a delete this service has
        // accepted leaves the record readable in `DELETING` and then in the
        // terminal `DELETED`, but the id names nothing a caller may still change.
        // This operation models no `NotFoundException`, so the request itself is
        // what cannot be served: the modelled 400. The message tells the two
        // apart; the status and the code do not.
        {
            let channel = state
                .mutable_channel(&input.channel_id)
                .map_err(|dead| bad_request(&dead.message))?;

            // A channel that has not stopped is encoding through exactly the
            // configuration this call would replace, so the edit waits until it
            // has stopped — the same notion `UpdateInput` applies to the
            // channels that attach the input it is asked to edit.
            if !channel.has_stopped() {
                return Err(UpdateChannelErrorModeled::ConflictException(ConflictException {
                    message: Some(format!(
                        "Channel {} is in state {} and must have stopped before it can be updated",
                        channel.id, channel.state
                    )),
                })
                .into());
            }
        }

        // The configuration this update WOULD leave on the channel — the members
        // its request names, over the ones the channel already had — is checked
        // by the rule `CreateChannel` validates a new channel's configuration
        // against, before anything is written: an update that would leave a
        // channel this service could not run is refused with the operation's
        // modelled 422, one `ValidationErrors` entry per problem, and the channel
        // keeps exactly the configuration it had.
        let stored = state.channels.get(&input.channel_id).ok_or_else(unavailable)?;
        // The two members the channel's own SCHEDULE resolves its references
        // against, as this update would leave them.
        let encoder_settings = input
            .encoder_settings
            .as_ref()
            .or(stored.encoder_settings.as_ref());
        let input_attachments = input
            .input_attachments
            .as_deref()
            .unwrap_or(&stored.input_attachments);
        let mut problems = state.channel_configuration_problems(&crate::state::ChannelConfiguration {
            encoder_settings,
            input_attachments,
            channel_security_groups: input
                .channel_security_groups
                .as_deref()
                .unwrap_or(&stored.channel_security_groups),
            anywhere_settings: input
                .anywhere_settings
                .as_ref()
                .or(stored.anywhere_settings.as_ref()),
            // The stored channel goes in beside the merged configuration, so
            // only the references this update ADDS are resolved: an id the
            // channel already names is part of the configuration it already
            // claims, and a referenced resource that has gone since (an input
            // security group, whose delete this service accepts while a channel
            // still names it) must not turn an edit of another member into a
            // refusal for a member the request never supplied.
            held: Some(stored),
        });
        // The channel's schedule resolves its channel-scoped references —
        // an input attachment by name, an output by name, the features a kind of
        // action needs — against exactly the members this update replaces, so
        // the actions it ALREADY holds are resolved against the configuration
        // this update would leave: an action the channel could then not execute
        // is one `BatchUpdateSchedule` refuses to create, so a configuration
        // that would strand it is refused here too, in the same 422, and the
        // channel keeps the configuration its schedule was built against.
        problems.extend(stored.schedule.unexecutable_action_problems(
            &crate::state::ChannelScheduleScope::of_configuration(
                encoder_settings,
                input_attachments,
                // The class, and so the pipelines a pause action may name, is
                // not a member this operation writes (`UpdateChannelClass` is),
                // so the channel keeps the ones it has.
                stored.pipelines(),
            ),
        ));
        if !problems.is_empty() {
            return Err(unprocessable(problems));
        }

        // The same rule `CreateChannel` applies to a new channel's attachments:
        // an input is attached to at most ONE channel at a time, so an update
        // whose `InputAttachments` would attach an input ANOTHER channel already
        // holds is refused with this operation's modelled `ConflictException`
        // and the channel keeps the attachments it had. The channel being
        // updated goes in beside the merged list, so re-declaring (or keeping)
        // its own attachments is never a conflict with itself.
        if let Some(input_id) =
            state.double_booked_input(input_attachments, Some(input.channel_id.as_str()))
        {
            return Err(UpdateChannelErrorModeled::ConflictException(ConflictException {
                message: Some(crate::state::input_already_attached_message(&input_id)),
            })
            .into());
        }

        // Every refusal this update could earn has now been answered, so a
        // validate-only request is done: the channel keeps the configuration it
        // already had and its state is not moved, so there is no updated channel
        // to describe.
        if dry_run {
            return Ok(UpdateChannelOutput { channel: None });
        }

        // The channel the writes below apply to, resolved again now that the
        // read-only validation above has ended its borrow of the store. The
        // lookup is the same guard the refusals went through.
        let channel = state
            .mutable_channel(&input.channel_id)
            .map_err(|dead| bad_request(&dead.message))?;

        // Each member the request named is stored; each one it omitted keeps the
        // value the channel already had.
        if let Some(name) = input.name {
            channel.name = Some(name);
        }
        if let Some(cdi) = input.cdi_input_specification {
            channel.cdi_input_specification = Some(cdi);
        }
        if let Some(destinations) = input.destinations {
            channel.destinations = destinations;
        }
        if let Some(encoder_settings) = input.encoder_settings {
            channel.encoder_settings = Some(encoder_settings);
        }
        if let Some(attachments) = input.input_attachments {
            channel.input_attachments = attachments;
        }
        if let Some(specification) = input.input_specification {
            channel.input_specification = Some(specification);
        }
        if let Some(log_level) = input.log_level {
            channel.log_level = Some(log_level);
        }
        if let Some(security_groups) = input.channel_security_groups {
            channel.channel_security_groups = security_groups;
        }
        if let Some(anywhere_settings) = input.anywhere_settings {
            channel.anywhere_settings = Some(anywhere_settings);
        }
        if let Some(linked) = input.linked_channel_settings {
            channel.linked_channel_settings = Some(linked);
        }
        if let Some(inference_settings) = input.inference_settings {
            channel.inference_settings = Some(inference_settings);
        }
        if let Some(router_settings) = input.special_router_settings {
            channel.special_router_settings = Some(router_settings);
        }
        if let Some(maintenance) = input.maintenance {
            apply_maintenance(&mut channel.maintenance, maintenance);
        }
        if let Some(version) = input.channel_engine_version.and_then(|version| version.version) {
            // The requested build identifier decides the stored pin through the
            // one helper every writer of this member goes through, so a reset
            // means the same thing here as it does on a create.
            channel.channel_engine_version = crate::state::requested_engine_version_pin(version);
        }
        // `RoleArn`'s own documentation makes it the one member an OMISSION
        // writes: "If you do not specify this on an update call but the role was
        // previously set that role will be removed".
        channel.role_arn = input.role_arn;

        // The configuration has been applied, which is what `UPDATING` reports;
        // the channel is still stopped, so the clock owes it the `IDLE` the
        // update started from.
        crate::state::begin_update(channel, now);

        // Read back out of the store, so the response reports the channel that
        // was written rather than one this handler assembled from the request.
        let channel = state
            .channel_description(&input.channel_id)
            .ok_or_else(unavailable)?;
        Ok(UpdateChannelOutput {
            channel: Some(channel),
        })
    }
}

/// Apply a `MaintenanceUpdateSettings` patch to a channel's stored
/// `MaintenanceStatus`.
///
/// Member by member, for the same reason the operation is member by member: each
/// of the three is optional and documented on its own ("Choose one day of the
/// week for maintenance", "Choose a specific date for maintenance to occur",
/// "Choose the hour that maintenance will start"), so a patch that names one
/// leaves the other two at the values the channel already had.
/// `MaintenanceDeadline` is assigned by the real service's maintenance
/// scheduler, which this emulator does not run, so no caller's update can reach
/// it and it stays as the create left it.
fn apply_maintenance(stored: &mut Option<MaintenanceStatus>, patch: MaintenanceUpdateSettings) {
    let stored = stored.get_or_insert_with(MaintenanceStatus::default);
    if patch.maintenance_day.is_some() {
        stored.maintenance_day = patch.maintenance_day;
    }
    if patch.maintenance_start_time.is_some() {
        stored.maintenance_start_time = patch.maintenance_start_time;
    }
    if patch.maintenance_scheduled_date.is_some() {
        stored.maintenance_scheduled_date = patch.maintenance_scheduled_date;
    }
}

