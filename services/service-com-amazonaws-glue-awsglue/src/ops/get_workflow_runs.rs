impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetWorkflowRuns<Eng>
{
    type Input = GetWorkflowRunsInput;
    type Output = GetWorkflowRunsOutput;
    type Error = GetWorkflowRunsError;

    const NAME: &'static str = "GetWorkflowRuns";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_WORKFLOW_RUNS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_WORKFLOW_RUNS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // This operation models a server fault, so an unreachable store is reported as
            // that rather than as a client error the caller could act on — the same way the
            // single-run read reports it.
            return Err(GetWorkflowRunsErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the Glue workflow store is unavailable".into()),
                },
            )
            .into());
        };

        // "The maximum number of workflow runs to be included in the response"
        // (`MaxResults`, `PageSize` range 1..1000). Absent, the page is the largest the
        // model accepts for it; the clamp re-states that range here so the page size is
        // never 0 even if the boundary validator ever stops enforcing it.
        let page_size = usize::try_from(input.max_results.unwrap_or(MAX_PAGE_SIZE))
            .unwrap_or(MAX_PAGE_SIZE as usize)
            .clamp(1, MAX_PAGE_SIZE as usize);

        let now = ::std::time::SystemTime::now();
        let region = crate::state::request_region(ctx.parts());
        // A run this workflow's actions began owes its job's script ONE execution, which the
        // service owed it the instant the run began — so it is performed here, with no store
        // guard held, before this read reports the state those runs have reached. Nothing is
        // performed twice: the claim on a run's execution is taken under the store's guard,
        // so this read moves no run that was not already owed the move.
        //
        // The script is compiled and run INSIDE this process by the embedded Python
        // interpreter ([`crate::state::job_script`]): nothing is spawned, no shell is
        // involved, no host path is resolved, and the script reaches no host socket,
        // process, library, file or environment variable — only this emulator, over the
        // in-process callback. What this request spends is bounded before anything runs: at
        // most [`crate::state::MAX_JOB_SCRIPT_RUNS_PER_CALL`] scripts over at most
        // [`crate::state::MAX_JOBS_PER_SCRIPT_CALL`] jobs, no further one started past
        // [`crate::state::JOB_SCRIPT_CALL_CEILING`], and each script stopped at
        // [`crate::state::JOB_SCRIPT_RUN_CEILING`].
        // A batch of events this workflow's EVENT trigger was holding fires on its own once
        // its window has run out, and the run that firing begins belongs in this history —
        // so it is materialised FIRST, in a guard of its own, and the jobs whose runs this
        // workflow's actions began are collected after it: a run the firing begins in this
        // very request is then performed by the step below rather than being left owed to a
        // later call.
        let action_jobs = {
            let mut store = state.lock();
            store.settle_due_event_batches(&region, &input.name, now);
            store.action_job_run_job_names(&input.name)
        };
        crate::state::perform_owed_job_runs(&*self.engine, ctx, &region, &action_jobs).await;
        let mut store = state.lock();
        // A batch of events this workflow's EVENT trigger was holding fires on its own once
        // its window has run out, and the run that firing begins belongs in this history —
        // so it is materialised here, before the history is read, exactly as the statuses
        // the runs already in it were owed are.
        store.settle_due_event_batches(&region, &input.name, now);
        // `Name` is `@required` with `length 1..255`, so an absent or over-long one is
        // refused at the boundary: reaching here, the only question is whether this account
        // holds a workflow of that name — and the NAME is that workflow's whole key. Every
        // operation the model declares over a workflow (`GetWorkflow`, `UpdateWorkflow`,
        // `DeleteWorkflow`, `StartWorkflowRun`, `GetWorkflowRun`) addresses it by `Name`
        // alone, with no `CatalogId` and no Region member, so a workflow and its run history
        // are per-ACCOUNT ([`crate::state::ComAmazonawsGlueAwsglueState::workflows`]) and are
        // resolved here through the very same accessor those readers use. There is no
        // narrower key to scope this lookup by.
        // The only write a read makes: the statuses the clock had already made due to this
        // workflow's runs and to the job runs their actions began, so each run is reported
        // in the state it had already reached. A name no workflow of this account carries is
        // the miss below, which the read is answered with rather than materialising
        // anything.
        store.settle_due_workflow_runs(&region, &input.name, now);
        let Some(workflow) = store.workflow(&input.name) else {
            return Err(GetWorkflowRunsErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    message: Some(crate::state::messages::WORKFLOW_NOT_FOUND.to_string()),
                    from_federation_source: None,
                },
            )
            .into());
        };

        // A run history is reported newest first — the order the sibling run listing of
        // this service documents (`GetJobRuns`, "with the newest jobs returned first") —
        // taken from the instant each run STARTED rather than from the order the store
        // happens to hold the runs in, with the run's own id breaking a tie between two
        // runs started in the same nanosecond so the order is total and the same on every
        // call. Each run's ordering key is computed ONCE here, so neither the sort nor the
        // token lookup below re-renders it per comparison.
        let mut ordered: Vec<(String, &WorkflowRunEntry)> = workflow
            .runs
            .iter()
            .map(|run| (page_cursor(run), run))
            .collect();
        ordered.sort_by(|left, right| right.0.cmp(&left.0));

        // The token is the ordering key of the last run of the previous page, so the page
        // resumes at the first run strictly older than it — which stays correct across runs
        // started or dropped between two calls. A token this service never issued is
        // DELIBERATELY a position in that order rather than a refusal, for the same reason:
        // the cursor is a key in the listing's own order, so every string names one, and
        // the sibling run listings of this crate resolve a cursor the same way.
        let start = match input.next_token.as_deref() {
            Some(cursor) => ordered.partition_point(|(key, _)| key.as_str() >= cursor),
            None => 0,
        };
        let end = start.saturating_add(page_size).min(ordered.len());
        // The token names the last entry of the page, taken from the page itself so there
        // is no index arithmetic to underflow on an empty page, and is absent once the page
        // reaches the end of the listing.
        let next_token = if end < ordered.len() {
            ordered[start..end].last().map(|(key, _)| key.clone())
        } else {
            None
        };
        // The page's runs, taken out of the store so the record is no longer borrowed while
        // the graph beside it is read.
        let page: Vec<WorkflowRunEntry> = ordered[start..end]
            .iter()
            .map(|(_, run)| (*run).clone())
            .collect();

        // The runs the page's runs' actions began have been given the state the clock owed
        // them by the materialisation above, so what each of them reports is the state it had
        // already reached.

        // "Specifies whether to include the workflow graph in response or not": the reader
        // that did not ask for one — which is also what a request naming no `IncludeGraph`
        // asked for — is answered without it, and the reader that asked gets the graph of
        // the RUN, the same graph the single-run read reports for it, so each run's job
        // nodes report the runs that run's own actions began. The Region is what the graph
        // is read by, not the workflow: a trigger is served only through the endpoint that
        // created it, so the graph reports the components attached to this workflow through
        // THIS endpoint, exactly as `GetWorkflow` and the single-run read report them.
        //
        // One graph per reported run, which is what makes them differ; the work that costs
        // is bounded by the STORE and not by the request, because a workflow keeps at most
        // [`crate::state::MAX_RUNS_PER_WORKFLOW`] runs however large a `MaxResults` asks
        // for, and each graph walks only the triggers attached to this one workflow.
        let include_graph = input.include_graph.unwrap_or(false);

        // Element for element the SAME projection the single-run read serves.
        let runs: Vec<WorkflowRun> = page
            .iter()
            .map(|run| store.to_workflow_run(&region, run, include_graph))
            .collect();

        // `Runs` is `length 1..1000`, so a success reporting NOTHING is not a shape this
        // operation has: there is no 2xx encoding of "this workflow exists but has no run to
        // report here". A read with nothing to report is therefore refused with the
        // operation's own modelled `EntityNotFoundException` — the entity missing being the
        // run history and not the workflow, which was found — so a client reading a run
        // history either gets a non-empty `Runs` or an error it can branch on, and never a
        // success whose list member is simply absent. This covers both ways a page can come
        // up empty: a workflow no run has been started of, and a cursor that names a place
        // past the end of the history.
        if runs.is_empty() {
            return Err(GetWorkflowRunsErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    message: Some(crate::state::messages::no_workflow_runs_found()),
                    from_federation_source: None,
                },
            )
            .into());
        }

        Ok(GetWorkflowRunsOutput {
            runs: Some(runs),
            next_token,
        })
    }
}

/// One run's place in this listing, as the continuation token renders it: the shared
/// history cursor ([`crate::state::history_page_cursor`]) over the instant this run started
/// and its own id.
///
/// Ordering runs by this key DESCENDING is the newest-first order this listing serves, and
/// comparing a token against it is what resumes a page — so any string a request sends
/// names a well-defined place in that order, exactly as it does for the sibling run
/// listings of this crate.
fn page_cursor(run: &WorkflowRunEntry) -> String {
    crate::state::history_page_cursor(run.started_on, &run.id)
}
