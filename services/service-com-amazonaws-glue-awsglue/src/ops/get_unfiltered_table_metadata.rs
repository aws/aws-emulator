/// Whether the request presents the Lake Formation authorization this read is served
/// under.
///
/// The authorization of this operation is not the caller's IAM identity: it is the Lake
/// Formation data access the REQUEST carries, which is what the two modelled members say.
/// `Permissions` is "The Lake Formation data permissions of the caller on the table. Used
/// to authorize the call when no view context is found", and the view context it defers to
/// is `QuerySessionContext`, which carries "a Lake Formation generated authorization
/// identifier" (`QueryAuthorizationId`: "A cryptographically generated query identifier
/// generated by Glue or Lake Formation"). A request stating no permission and carrying no
/// such identifier presents no authorization at all.
fn lake_formation_authorized(input: &GetUnfilteredTableMetadataInput) -> bool {
    let stated_permissions = input
        .permissions
        .as_ref()
        .is_some_and(|permissions| !permissions.is_empty());
    let vended_authorization = input.query_session_context.as_ref().is_some_and(|context| {
        context
            .query_authorization_id
            .as_deref()
            .is_some_and(|id| !id.is_empty())
    });
    stated_permissions || vended_authorization
}

