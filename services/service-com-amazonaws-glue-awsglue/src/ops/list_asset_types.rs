    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_ASSET_TYPES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Asset types live in one per-account namespace, so nothing here depends on the
        // request's Region.
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // This operation models a server fault, so an unreachable store is reported
            // as that rather than as a client error the caller could act on.
            return Err(ListAssetTypesErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the Glue asset type store is unavailable".into()),
                },
            )
            .into());
        };

        // "The maximum number of results to return in the response" (`MaxResults`, range
        // 1..1000). Absent, the page is the largest the model accepts for it; the clamp
        // re-states that range here so the page size is never 0 even if the boundary
        // validator ever stops enforcing it.
        let page_size = usize::try_from(input.max_results.unwrap_or(MAX_PAGE_SIZE))
            .unwrap_or(MAX_PAGE_SIZE as usize)
            .clamp(1, MAX_PAGE_SIZE as usize);

        // Reporting only: the stored asset types are projected out and nothing is written.
        let store = state.lock();
        // The records are keyed by the name they were registered under — the member that
        // identifies an asset type to a caller, which `PutAssetType` makes the record's
        // identity — so the store already holds them in the order one page follows another
        // in, exactly as the sibling business-catalog listings order theirs by name.
        let asset_types: Vec<&crate::state::AssetTypeEntry> = store.asset_types.values().collect();

        // The token is the last name of the previous page, so the page resumes at the first
        // stored name strictly after it — which stays correct across asset types registered
        // or deleted between two calls.
        let start = match input.next_token.as_deref() {
            Some(cursor) => {
                asset_types.partition_point(|asset_type| asset_type.name.as_str() <= cursor)
            }
            None => 0,
        };
        // Taken with `skip`/`take` rather than by slicing, so a cursor the request chose can
        // never index outside the set.
        let page: Vec<AssetTypeItem> = asset_types
            .iter()
            .skip(start)
            .take(page_size)
            .map(|asset_type| AssetTypeItem {
                // `AssetTypeItem` is a SUMMARY of two members (`smithy_query
                // shape=AssetTypeItem`): the forms an asset type is made of are reported by
                // `GetAssetType` and not here. The id is the record's identity in the
                // catalog-qualified form a READ of it reports
                // (`crate::state::AssetTypeEntry::qualified_id`), so an entry of this
                // listing carries the identifier `GetAssetType` answers with and addresses
                // the same record.
                id: Some(asset_type.qualified_id()),
                name: Some(asset_type.name.clone()),
            })
            .collect();
        let end = start.saturating_add(page.len());
        // "A continuation token, present if the current segment is not the last": it names
        // the last entry of the page, taken from the page itself so there is no index
        // arithmetic to underflow on an empty page.
        let next_token = if end < asset_types.len() {
            page.last().and_then(|item| item.name.clone())
        } else {
            None
        };

        Ok(ListAssetTypesOutput {
            items: Some(page),
            next_token,
        })
    }
