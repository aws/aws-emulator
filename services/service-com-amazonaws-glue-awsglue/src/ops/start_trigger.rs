//! @op StartTrigger
//!
//! Starts the trigger its `Name` addresses in the Region the request is served in: a
//! started trigger that waits on something outside the caller is left armed, in the one
//! `TriggerState` of a started trigger ([`crate::state::TRIGGER_STATE_ACTIVATED`]), which a
//! later `GetTrigger` reports, while a trigger that waits on nothing but a caller — an
//! `ON_DEMAND` one — is FIRED here instead: it initiates the actions its definition names
//! ([`crate::state::ComAmazonawsGlueAwsglueState::initiate_trigger_actions`]), begins a run
//! of the workflow it belongs to, and is left in the state it waits in
//! ([`crate::state::TriggerEntry::start`]), ready for the next caller.
//!
//! A start is refused with `EntityNotFoundException` when this Region holds no trigger
//! under that name, and with `ConcurrentRunsExceededException` when the run the firing
//! would begin is past the concurrency ceiling its workflow named.
//!
//! Each job run a firing begins is EXECUTED here, exactly as a run a caller started
//! directly is ([`crate::state::perform_owed_job_runs`]): the job's script runs with the
//! action's arguments on its command line, and the run comes to rest in whatever that
//! execution came to. That execution happens IN THIS PROCESS, in the embedded Python
//! interpreter ([`crate::state::job_script`]) — nothing is spawned, no shell is involved, no
//! host path is resolved, and the script reaches no host socket, process, library, file or
//! environment variable, only this emulator over the in-process callback — and what one
//! firing can spend is bounded before anything runs (at most
//! [`crate::state::MAX_JOB_SCRIPT_RUNS_PER_CALL`] scripts, nothing further started past
//! [`crate::state::JOB_SCRIPT_CALL_CEILING`], each stopped at
//! [`crate::state::JOB_SCRIPT_RUN_CEILING`]). A CRAWL is not in that position — this crate
//! records no crawl — so a crawler action contributes nothing to the workflow run's
//! statistics, which report what each action that DID run came to; the run itself comes to
//! rest once the runs its actions began have
//! ([`crate::state::ComAmazonawsGlueAwsglueState::settle_due_workflow_runs`]).
//!
