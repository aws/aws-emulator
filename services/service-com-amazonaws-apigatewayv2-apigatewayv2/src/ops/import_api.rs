// The `MaxAge` a CORS configuration may carry is NOT bounded by this reader: the shape the
// member targets declares `range -1..86400`, and the service enforces neither end of it (see
// the note on `crate::ops::types::Cors`), so an imported configuration is held to exactly
// what `CreateApi` holds a caller-supplied one to.

/// One node of a parsed API definition: the shapes a JSON document carries.
///
/// Every scalar is kept as its TEXT, because a definition is read for strings and for the
/// SHAPE of everything else; a number or a boolean is read back out of its text by
/// [`Node::integer_member`] / [`Node::boolean_member`], so a member a document writes
/// unquoted and one it writes quoted are read the same way.
#[derive(Debug, Clone, Default)]
pub enum Node {
    /// A null, and the value a document writes as an empty one.
    #[default]
    Null,
    /// A scalar, as its text.
    Scalar(String),
    /// A sequence, in order.
    Sequence(Vec<Node>),
    /// A mapping, in the order [`serde_json`] visited it. A document that repeats a key
    /// carries the LAST of them, which is what the JSON reader keeps.
    Mapping(Vec<(String, Node)>),
}

impl Node {
    /// A member of this mapping by name; `None` for any other node.
    fn member(&self, key: &str) -> Option<&Node> {
        match self {
            Node::Mapping(entries) => entries
                .iter()
                .find(|(name, _)| name == key)
                .map(|(_, value)| value),
            _ => None,
        }
    }

    /// This node's text, when it is a scalar.
    fn text(&self) -> Option<&str> {
        match self {
            Node::Scalar(value) => Some(value),
            _ => None,
        }
    }

    /// A string member of this mapping; `None` when it is absent or not a scalar.
    fn string_member(&self, key: &str) -> Option<String> {
        self.member(key).and_then(Node::text).map(str::to_owned)
    }

    /// This node's mapping entries, when it is a mapping.
    fn entries(&self) -> Option<&[(String, Node)]> {
        match self {
            Node::Mapping(entries) => Some(entries),
            _ => None,
        }
    }

    /// This node's items, when it is a sequence.
    fn items(&self) -> Option<&[Node]> {
        match self {
            Node::Sequence(items) => Some(items),
            _ => None,
        }
    }

    /// The strings of a sequence member, in order; `None` when the member is absent. A
    /// non-scalar item carries no string and is skipped.
    ///
    /// EVERY entry is read: what a definition declares here is persisted verbatim, so
    /// truncating it would report a record that quietly differs from the document. The
    /// count is already bounded by [`MAX_DEFINITION_BYTES`], which bounds the whole
    /// parsed document.
    fn string_list_member(&self, key: &str) -> Option<Vec<String>> {
        self.member(key).and_then(Node::items).map(|items| {
            items
                .iter()
                .filter_map(|item| item.text().map(str::to_owned))
                .collect()
        })
    }

    /// This mapping's entries whose values are scalars; empty for any other node. Every
    /// entry is read, for the reason [`Node::string_list_member`] gives.
    fn scalar_entries(&self) -> BTreeMap<String, String> {
        self.entries()
            .unwrap_or_default()
            .iter()
            .filter_map(|(name, value)| value.text().map(|text| (name.clone(), text.to_owned())))
            .collect()
    }

    /// A map member whose values are scalars; empty when the member is absent or is not a
    /// mapping.
    fn string_map_member(&self, key: &str) -> BTreeMap<String, String> {
        self.member(key).map(Node::scalar_entries).unwrap_or_default()
    }

    /// An integer member, read out of its text; `Err` names the member when the text is
    /// not an integer.
    fn integer_member(&self, key: &str) -> Result<Option<i64>, String> {
        match self.member(key) {
            None | Some(Node::Null) => Ok(None),
            Some(node) => node
                .text()
                .and_then(|text| text.trim().parse::<i64>().ok())
                .map(Some)
                .ok_or_else(|| {
                    format!("Unable to parse API definition: '{key}' must be an integer")
                }),
        }
    }

    /// A boolean member, read out of its text the way YAML's core schema spells one;
    /// `Err` names the member when the text is not a boolean.
    fn boolean_member(&self, key: &str) -> Result<Option<bool>, String> {
        match self.member(key) {
            None | Some(Node::Null) => Ok(None),
            Some(node) => match node.text().map(str::trim) {
                Some("true" | "True" | "TRUE") => Ok(Some(true)),
                Some("false" | "False" | "FALSE") => Ok(Some(false)),
                _ => Err(format!(
                    "Unable to parse API definition: '{key}' must be true or false"
                )),
            },
        }
    }
}

/// `serde_json`'s tree, as a [`Node`]. The document is read through `serde_json`, which
/// enforces its own recursion limit, so a nested body cannot drive this conversion deeper
/// than that however deeply it nests.
impl From<::serde_json::Value> for Node {
    fn from(value: ::serde_json::Value) -> Self {
        match value {
            ::serde_json::Value::Null => Node::Null,
            ::serde_json::Value::Bool(value) => Node::Scalar(value.to_string()),
            ::serde_json::Value::Number(value) => Node::Scalar(value.to_string()),
            ::serde_json::Value::String(value) => Node::Scalar(value),
            ::serde_json::Value::Array(items) => {
                Node::Sequence(items.into_iter().map(Node::from).collect())
            }
            ::serde_json::Value::Object(members) => Node::Mapping(
                members
                    .into_iter()
                    .map(|(name, value)| (name, Node::from(value)))
                    .collect(),
            ),
        }
    }
}

/// How to interpret the base path of the API during import, from `ImportApi$Basepath`:
/// "Valid values are ignore, prepend, and split. The default value is ignore."
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BasePathMode {
    /// The definition's base path is not part of the routes' paths.
    Ignore,
    /// The definition's base path is prepended to every route's path.
    Prepend,
    /// The FIRST segment of the base path names a stage rather than a path, and only what
    /// follows it is prepended to every route's path.
    Split,
}

/// How API Gateway names a `Basepath` outside the documented three in the refusal it
/// answers such a request with: the fixed text, which the value the request sent follows
/// after a colon.
const UNRECOGNIZED_BASE_PATH_OPTION: &str = "Unrecognized base path option";

/// The base path mode a request asks for; `Ignore` when it names none.
///
/// `Err` carries the message for a value outside the documented three, naming the value
/// that was not recognized.
/// The three values are matched EXACTLY, as the member documents them: a spelling the
/// documented value set does not carry is refused rather than guessed at, so a definition
/// that imports here imports at API Gateway too.
pub fn base_path_mode(basepath: Option<&str>) -> Result<BasePathMode, String> {
    match basepath {
        None | Some("ignore") => Ok(BasePathMode::Ignore),
        Some("prepend") => Ok(BasePathMode::Prepend),
        Some("split") => Ok(BasePathMode::Split),
        Some(other) => Err(format!("{UNRECOGNIZED_BASE_PATH_OPTION}: {other}")),
    }
}

/// The per-api quota a definition would take an api past, as the `LimitType` and the
/// message of the operation's `TooManyRequestsException`, or `None` for one that fits.
///
/// `ImportApi` and `ReimportApi` both write the WHOLE definition in one call, so each one
/// either fits or is refused with nothing written, and both ask this — the one owner of the
/// thresholds and of their wording, so the two cannot drift apart.
pub fn definition_quota_exceeded(definition: &ImportedApi) -> Option<(&'static str, String)> {
    if definition.routes_exceed_quota {
        return Some((
            "Route",
            format!(
                "The API definition declares more routes than the maximum number of routes \
                 for an API ({}).",
                crate::state::MAX_ROUTES_PER_API
            ),
        ));
    }
    let integrations = definition
        .routes
        .iter()
        .filter(|route| route.integration.is_some())
        .count();
    if integrations > crate::state::MAX_INTEGRATIONS_PER_API {
        return Some((
            "Integration",
            format!(
                "The API definition declares {integrations} integrations; the maximum number \
                 of integrations for an API is {}.",
                crate::state::MAX_INTEGRATIONS_PER_API
            ),
        ));
    }
    None
}

/// Write the routes `routes` describe, and the integration each one declared, into `api`,
/// REPLACING the routes and integrations the api held before.
///
/// The ONE materialisation of a read definition, asked by `ImportApi` for the api it mints
/// and by `ReimportApi` for the api it PUTS over, so an imported and a reimported document
/// of the same bytes leave the same records.
///
/// A route the api ALREADY holds under the key a declaration carries is the same route put
/// over again, not a new one: it keeps its `RouteId`, and the integration its target names
/// keeps its `IntegrationId`, while the configuration both carry is rewritten from the
/// document just read. Only a declaration the api holds nothing for mints a fresh id, and
/// only a key the document no longer declares is dropped — so an identifier a caller
/// captured before a re-put still addresses the resource that key names, instead of being
/// orphaned by one the same document minted again. Each integration is claimed by ONE
/// declaration: where two routes the api held shared a target, the second declaration to
/// ask for it mints an integration of its own, so the api holds as many integrations as the
/// document declares.
///
/// What the document does NOT declare is not carried: an OpenAPI definition describes no
/// route response and no integration response (both are WebSocket-only children and an
/// imported api is an HTTP one), so a carried route and integration are rebuilt from the
/// declaration alone and hold none. Their id seeds ARE carried, so an id one of those
/// children was given is never handed out again.
pub fn write_definition_routes(api: &mut crate::state::Api, routes: Vec<ImportedRoute>) {
    // What the api held before this document was put over it, keyed by the natural key a
    // definition declares a route under — its route key, which is what identifies an
    // operation of the document (`{Method} {Path}`). Taking the collections out leaves the
    // api holding exactly what this document declares, whatever it declared before.
    let mut previous_routes: BTreeMap<String, crate::state::Route> =
        ::std::mem::take(&mut api.routes)
            .into_values()
            .map(|route| (route.route_key.clone(), route))
            .collect();
    let previous_integrations = ::std::mem::take(&mut api.integrations);

    for imported in routes {
        let previous = previous_routes.remove(&imported.route_key);
        // The integration the operation declared, written FIRST: the route's `Target` is
        // `integrations/{IntegrationId}`, so the integration has to exist before the route
        // that points at it.
        let target = imported.integration.map(|integration| {
            // The integration this operation was already wired to is the one it is wired
            // to afterwards, unless an earlier declaration of this document has claimed it
            // already (two routes may share one target); a route the api held no integration
            // for, and a second claimant, are given a fresh id.
            let carried = previous
                .as_ref()
                .and_then(crate::state::Route::target_integration_id)
                .filter(|id| {
                    previous_integrations.contains_key(*id) && !api.integrations.contains_key(*id)
                })
                .map(str::to_string);
            let integration_id = match carried {
                Some(integration_id) => integration_id,
                None => api.mint_integration_id(),
            };
            let mut record = integration.into_record(integration_id.clone());
            // A response id the carried integration handed out is not minted again.
            record.integration_response_id_seed = previous_integrations
                .get(&integration_id)
                .map_or(0, |previous| previous.integration_response_id_seed);
            api.integrations.insert(integration_id.clone(), record);
            format!(
                "{}{integration_id}",
                crate::state::INTEGRATION_TARGET_PREFIX
            )
        });
        let route_id = match &previous {
            Some(previous) => previous.route_id.clone(),
            None => api.mint_route_id(),
        };
        api.routes.insert(
            route_id.clone(),
            crate::state::Route {
                route_id,
                route_key: imported.route_key,
                target,
                authorization_type: crate::state::DEFAULT_AUTHORIZATION_TYPE.to_string(),
                // The caller's own definition asked for this route, so API Gateway does not
                // manage it (`Route$ApiGatewayManaged`).
                api_gateway_managed: false,
                // A response id the carried route handed out is not minted again.
                route_response_id_seed: previous
                    .as_ref()
                    .map_or(0, |previous| previous.route_response_id_seed),
                ..Default::default()
            },
        );
    }
}

/// The integration an operation's `x-amazon-apigateway-integration` extension describes,
/// as the members `CreateIntegration` would be called with.
#[derive(Debug, Clone)]
pub struct ImportedIntegration {
    /// One of `INTEGRATION_TYPE_VALUES`, upper-cased from the extension's spelling.
    pub integration_type: String,
    pub integration_uri: Option<String>,
    pub integration_method: Option<String>,
    pub integration_subtype: Option<String>,
    /// One of `CONNECTION_TYPE_VALUES`, or `None` for an extension that names none.
    pub connection_type: Option<String>,
    pub connection_id: Option<String>,
    pub credentials_arn: Option<String>,
    pub payload_format_version: String,
    pub timeout_in_millis: Option<i32>,
    pub request_parameters: BTreeMap<String, String>,
    pub response_parameters: BTreeMap<String, BTreeMap<String, String>>,
    /// `tlsConfig.serverNameToVerify`, the one member `TlsConfig` carries.
    pub server_name_to_verify: Option<String>,
}

impl ImportedIntegration {
    /// The persisted integration this becomes under `integration_id`, resolving the
    /// members the extension left out to the values the model documents for them —
    /// exactly as `CreateIntegration` resolves them for a request that omits them.
    fn into_record(self, integration_id: String) -> crate::state::Integration {
        // The method a Lambda proxy integration is invoked with is the service's to
        // supply, whatever wrote the integration: the one `CreateIntegration` resolves
        // for a request that names none (`crate::state::default_integration_method`).
        let integration_method = self.integration_method.or_else(|| {
            crate::state::default_integration_method(
                &self.integration_type,
                self.integration_subtype.as_deref(),
            )
            .map(str::to_string)
        });
        crate::state::Integration {
            integration_id,
            integration_type: self.integration_type,
            integration_uri: self.integration_uri,
            integration_method,
            integration_subtype: self.integration_subtype,
            // "The default value is INTERNET" (`Integration$ConnectionType`).
            connection_type: self
                .connection_type
                .unwrap_or_else(|| crate::state::DEFAULT_CONNECTION_TYPE.to_string()),
            connection_id: self.connection_id,
            // "Supported only for WebSocket APIs" — an imported api is an HTTP one, so
            // nothing here configures them.
            content_handling_strategy: None,
            credentials_arn: self.credentials_arn,
            description: None,
            passthrough_behavior: None,
            payload_format_version: Some(self.payload_format_version),
            request_parameters: self.request_parameters,
            request_templates: BTreeMap::new(),
            response_parameters: self.response_parameters,
            template_selection_expression: None,
            // "The default timeout is … 30 seconds for HTTP APIs"
            // (`CreateIntegration$TimeoutInMillis`).
            timeout_in_millis: self
                .timeout_in_millis
                .unwrap_or(crate::state::DEFAULT_HTTP_TIMEOUT_MILLIS),
            tls_config: self.server_name_to_verify.map(|name| TlsConfig {
                server_name_to_verify: Some(name),
            }),
            // The caller's own definition asked for this integration, so API Gateway does
            // not manage it (`Integration$ApiGatewayManaged`).
            api_gateway_managed: false,
            // An OpenAPI definition declares no integration responses — they are a
            // WebSocket-only child resource and an imported api is an HTTP one — so an
            // imported integration holds none.
            integration_responses: BTreeMap::new(),
            integration_response_id_seed: 0,
        }
    }
}

/// One route an imported operation becomes: its route key, and the integration the
/// operation declared for it (`None` when it declared none, which the import warns
/// about).
#[derive(Debug, Clone)]
pub struct ImportedRoute {
    pub route_key: String,
    pub integration: Option<ImportedIntegration>,
}

/// What an import reads out of an OpenAPI definition: the api's own members, and one
/// [`ImportedRoute`] per operation its paths declare.
#[derive(Debug, Clone)]
pub struct ImportedApi {
    /// `info.title`, the api's name.
    pub name: String,
    /// `info.description`.
    pub description: Option<String>,
    /// `info.version`.
    pub version: Option<String>,
    /// [`CORS_EXTENSION`], absent when the document carries none.
    pub cors_configuration: Option<Cors>,
    /// [`ENDPOINT_CONFIGURATION_EXTENSION`]'s `disableExecuteApiEndpoint`; `false` when
    /// the document names none, which is the member's documented default.
    pub disable_execute_api_endpoint: bool,
    /// The routes the document's paths declare, in the order they are declared. Never
    /// longer than [`crate::state::MAX_ROUTES_PER_API`]: the read stops at the quota and
    /// reports it through [`Self::routes_exceed_quota`].
    pub routes: Vec<ImportedRoute>,
    /// Does the document declare MORE routes than one api may hold? The read stops at
    /// the quota rather than collecting every operation a body can declare, so this is
    /// what the import refuses on.
    pub routes_exceed_quota: bool,
    /// What the import could not carry over — reported in `Warnings`, and what
    /// `FailOnWarnings` rolls the import back for.
    pub warnings: Vec<String>,
    /// Properties of the definition that are ignored during import, reported in
    /// `ImportInfo`.
    pub import_info: Vec<String>,
}

/// Read an OpenAPI definition out of an `ImportApi`/`ReimportApi` `Body`.
///
/// "The OpenAPI definition" (`ImportApi$Body`) is read in its JSON spelling, through
/// `serde_json` under its own recursion limit, bounded by [`MAX_DEFINITION_BYTES`], by
/// [`MAX_BASE_PATH_CHARS`] on the prefix every route's path carries, and by this
/// service's own route quota, so the read cannot amplify what the body carries. A body in
/// any OTHER spelling (the YAML one API Gateway also accepts) is REFUSED rather than guessed at:
/// reading it needs a YAML parser this crate does not carry, and a refusal is the honest
/// answer — never a partial import a caller would have to second-guess.
///
/// `Err` carries the message for a body that is not a definition this service can import:
/// the caller has to fix the definition from this text alone.
pub fn parse_definition(body: &str, basepath: BasePathMode) -> Result<ImportedApi, String> {
    if body.len() > MAX_DEFINITION_BYTES {
        return Err(format!(
            "Body may be at most {MAX_DEFINITION_BYTES} bytes, got {}",
            body.len()
        ));
    }
    // A body this reader cannot read at all carries no version to read, so it is refused
    // for the one reason API Gateway refuses it: the importer cannot be built because the
    // document's OAS version cannot be determined.
    let document = ::serde_json::from_str::<::serde_json::Value>(body)
        .map(Node::from)
        .map_err(|_| UNDETERMINABLE_OAS_VERSION.to_string())?;
    read_definition(&document, basepath)
}

/// What an import takes out of a parsed definition document.
fn read_definition(document: &Node, basepath: BasePathMode) -> Result<ImportedApi, String> {
    // A body that is a scalar or a list declares no member, so no version either.
    if document.entries().is_none() {
        return Err(UNDETERMINABLE_OAS_VERSION.to_string());
    }
    // Every OpenAPI document declares its version — `openapi` from 3.0 on, `swagger`
    // before it — so a document carrying neither is one whose version cannot be
    // determined, which is the same refusal.
    if document.member("openapi").is_none() && document.member("swagger").is_none() {
        return Err(UNDETERMINABLE_OAS_VERSION.to_string());
    }

    // The `info` object is where an OpenAPI document carries the api's name, description
    // and version. `info.title` is the api's `Name`, which the modelled `Api` shape
    // requires, so a definition that names none describes no api this service can hold.
    let info = document.member("info");
    let name = info
        .and_then(|info| info.string_member("title"))
        .filter(|title| !title.is_empty())
        .ok_or_else(|| {
            "Unable to parse API definition: 'info.title' is required and becomes the API's name"
                .to_string()
        })?;
    bound_chars("info.title", &name, MAX_NAME_CHARS)?;
    let description = info.and_then(|info| info.string_member("description"));
    if let Some(description) = &description {
        bound_chars("info.description", description, MAX_DESCRIPTION_CHARS)?;
    }
    let version = info.and_then(|info| info.string_member("version"));
    if let Some(version) = &version {
        bound_chars("info.version", version, MAX_VERSION_CHARS)?;
    }

    let mut definition = ImportedApi {
        name,
        description,
        version,
        cors_configuration: read_cors(document)?,
        disable_execute_api_endpoint: document
            .member(ENDPOINT_CONFIGURATION_EXTENSION)
            .map(|configuration| configuration.boolean_member("disableExecuteApiEndpoint"))
            .transpose()?
            .flatten()
            .unwrap_or(false),
        routes: Vec::new(),
        routes_exceed_quota: false,
        warnings: Vec::new(),
        // Reported in the document's own member order, so the same definition always
        // reports the same `ImportInfo`.
        import_info: IGNORED_DOCUMENT_MEMBERS
            .iter()
            .filter(|member| document.member(member).is_some())
            .map(|member| {
                format!("Ignoring '{member}': this property of the API definition is not imported")
            })
            .collect(),
    };

    // What every route's path is prefixed with, once the request's `Basepath` is applied
    // to the base path the definition declares. Bounded here, because it is repeated into
    // every route's path below (see [`MAX_BASE_PATH_CHARS`]).
    let prefix = route_prefix(document, basepath);
    bound_chars("the base path", &prefix, MAX_BASE_PATH_CHARS)?;

    // `paths` is optional from OpenAPI 3.1 on, and a document without it describes an api
    // with no routes rather than a malformed definition.
    let Some(paths) = document.member("paths") else {
        return Ok(definition);
    };
    if matches!(paths, Node::Null) {
        return Ok(definition);
    }
    let paths = paths.entries().ok_or_else(|| {
        "Unable to parse API definition: 'paths' must be an object of paths".to_string()
    })?;

    // A route key is unique within its api, so the first operation to claim one keeps it
    // and a later collision — which only the base path modes can create — is warned
    // about rather than written twice.
    let mut claimed: BTreeSet<String> = BTreeSet::new();
    'paths: for (path, item) in paths {
        if !path.starts_with('/') {
            return Err(format!(
                "Unable to parse API definition: path '{path}' must start with '/'"
            ));
        }
        let route_path = route_path(&prefix, path);
        // A path whose value is neither a Path Item Object nor the empty one declares no
        // operation this import can read, so it imports nothing and says so rather than
        // reporting a success that silently holds fewer routes than the document.
        if item.entries().is_none() && !matches!(item, Node::Null) {
            report(
                &mut definition.warnings,
                format!("Path '{path}' declares no operations and was not imported"),
            );
            continue;
        }
        for (declared, declaration) in item.entries().unwrap_or_default() {
            let operation = declared.to_ascii_lowercase();
            let Some((_, method)) = OPERATION_KEYS
                .iter()
                .find(|(candidate, _)| *candidate == operation.as_str())
            else {
                if UNSUPPORTED_OPERATION_KEYS.contains(&operation.as_str()) {
                    report(
                        &mut definition.warnings,
                        format!("Unsupported method '{operation}' for path '{path}'"),
                    );
                }
                // Any other key of a path item (`summary`, `parameters`, a vendor
                // extension) describes the path rather than an operation, so it imports
                // nothing and warns about nothing.
                continue;
            };
            // Stop at the api's own route quota instead of reading every operation the
            // body declares: the import is refused for exceeding it either way, and
            // stopping here is what keeps the read's work bounded by the quota rather
            // than by the number of paths a caller can pack into one body.
            if definition.routes.len() >= crate::state::MAX_ROUTES_PER_API {
                definition.routes_exceed_quota = true;
                break 'paths;
            }
            let route_key = format!("{method} {route_path}");
            if !claimed.insert(route_key.clone()) {
                report(
                    &mut definition.warnings,
                    format!("Duplicate route key '{route_key}': the later operation was ignored"),
                );
                continue;
            }
            let integration = match declaration.member(INTEGRATION_EXTENSION) {
                Some(extension) => {
                    // Every key the extension declares that an HTTP api's integration has
                    // no member for is carried over as nothing, and reported as ignored
                    // under the location the document wrote it at.
                    for key in ignored_integration_keys(extension) {
                        report(
                            &mut definition.import_info,
                            ignored_key_message(
                                &format!("paths.{path}.{declared}.{INTEGRATION_EXTENSION}"),
                                key,
                            ),
                        );
                    }
                    // A problem with THIS integration is not a problem with the
                    // definition: the integration is skipped, the route is still imported
                    // (with no `Target`, which `CreateIntegration`/`UpdateRoute` fills in
                    // afterwards) and the problem is reported as a warning.
                    match read_integration(extension) {
                        Ok(integration) => Some(integration),
                        Err(reason) => {
                            report(
                                &mut definition.warnings,
                                integration_warning(method, path, &reason),
                            );
                            None
                        }
                    }
                }
                None => {
                    // The route is still imported: a route with no `Target` is a route an
                    // HTTP api may hold, and `CreateIntegration`/`UpdateRoute` is what
                    // wires one up afterwards.
                    report(
                        &mut definition.warnings,
                        format!("No integration defined for route '{route_key}'"),
                    );
                    None
                }
            };
            definition.routes.push(ImportedRoute {
                route_key,
                integration,
            });
        }
    }
    Ok(definition)
}

/// Record one reported message — a `Warnings` or an `ImportInfo` entry — keeping what a
/// response reports bounded by [`MAX_REPORTED_MESSAGES`] however many paths and keys the
/// definition declares.
fn report(messages: &mut Vec<String>, message: String) {
    if messages.len() < MAX_REPORTED_MESSAGES {
        messages.push(message);
    }
}

/// The refusal `FailOnWarnings` turns an import's warnings into, as API Gateway words it:
/// the fixed sentence, then every warning the import reported, each on its own line and
/// indented.
///
/// The ONE owner of this wording for both `ImportApi` and `ReimportApi`: the two share the
/// member, the reader that produces the warnings and therefore the refusal they carry.
pub fn warnings_found_message(warnings: &[String]) -> String {
    let mut message = String::from("Warnings found during import:");
    for warning in warnings {
        message.push_str("\n\t");
        message.push_str(warning);
    }
    message
}

/// The warning an import reports for an integration it could not create, leaving the route
/// the integration belonged to without a target.
///
/// A per-path integration problem does not fail the import: API Gateway reports it at the
/// resource it belongs to and says what it did with it — the api, and every route the
/// document declares, is created either way. The resource is named as the document names
/// it: the operation's method and the path it is declared under, NOT the route key the
/// base path mode went on to build, which is the import's own value rather than the
/// document's.
fn integration_warning(method: &str, path: &str, reason: &str) -> String {
    format!(
        "Unable to create integration for resource at path '{method} {path}': {reason}. Ignoring."
    )
}

/// The `ImportInfo` entry reporting one key of the definition that the import carries over
/// as nothing, naming the location the document wrote it at.
fn ignored_key_message(location: &str, key: &str) -> String {
    format!("{location}: key [{key}] will be ignored by API Gateway")
}

/// The keys an integration extension declares that an HTTP api's integration has no member
/// for ([`INTEGRATION_EXTENSION_KEYS`] is the set it does), in the order they are REPORTED:
/// [`IGNORED_INTEGRATION_KEY_ORDER`].
///
/// What an import reports for an extension is a function of the SET of keys it declares,
/// not of the order the submitted document writes them in: the same keys, laid out
/// differently, report the same `ImportInfo` entries in the same order. That also keeps the
/// report independent of how the JSON reader this crate is built with carries a mapping
/// (key order, or the document's order under `serde_json`'s `preserve_order` feature).
fn ignored_integration_keys(extension: &Node) -> Vec<&str> {
    let declared: Vec<&str> = extension
        .entries()
        .unwrap_or_default()
        .iter()
        .map(|(key, _)| key.as_str())
        .filter(|key| !INTEGRATION_EXTENSION_KEYS.contains(key))
        .collect();
    let mut reported: Vec<&str> = IGNORED_INTEGRATION_KEY_ORDER
        .iter()
        .copied()
        .filter(|key| declared.contains(key))
        .collect();
    // A key that configures no integration of either api kind — a vendor extension of the
    // document's own, or a misspelling — has no place in that order, so it is reported
    // after the keys that do, in its own key order rather than the document's.
    let mut rest: Vec<&str> = declared
        .iter()
        .copied()
        .filter(|key| !IGNORED_INTEGRATION_KEY_ORDER.contains(key))
        .collect();
    rest.sort_unstable();
    reported.extend(rest);
    reported
}

/// Refuse a value longer than the member's modelled length, naming the member and the
/// bound — the constraint comes from the shape the member targets
/// (`StringWithLengthBetween1And128` for the api's name, and so on).
fn bound_chars(member: &str, value: &str, max_chars: usize) -> Result<(), String> {
    let chars = value.chars().count();
    if chars > max_chars {
        return Err(format!(
            "Unable to parse API definition: '{member}' may be at most {max_chars} characters, \
             got {chars}"
        ));
    }
    Ok(())
}

/// The CORS configuration the document's [`CORS_EXTENSION`] declares, projected onto the
/// modelled `Cors` shape.
fn read_cors(document: &Node) -> Result<Option<Cors>, String> {
    let Some(extension) = document.member(CORS_EXTENSION) else {
        return Ok(None);
    };
    if extension.entries().is_none() {
        return Err(format!(
            "Unable to parse API definition: '{CORS_EXTENSION}' must be an object"
        ));
    }
    let max_age = extension.integer_member("maxAge")?;
    let cors = Cors {
        allow_credentials: extension.boolean_member("allowCredentials")?,
        allow_headers: extension.string_list_member("allowHeaders"),
        allow_methods: extension.string_list_member("allowMethods"),
        allow_origins: extension.string_list_member("allowOrigins"),
        expose_headers: extension.string_list_member("exposeHeaders"),
        max_age: max_age.map(|seconds| i32::try_from(seconds).unwrap_or(i32::MAX)),
    };
    // An imported CORS document is held to the same rule a caller-supplied one is
    // (`crate::state::validate_cors_configuration`): a definition cannot write a
    // configuration `CreateApi` would have refused.
    if let Err(message) = crate::state::validate_cors_configuration(&cors) {
        return Err(format!(
            "Unable to parse API definition: '{CORS_EXTENSION}' is not valid: {message}"
        ));
    }
    Ok(Some(cors))
}

/// The integration an operation's [`INTEGRATION_EXTENSION`] declares.
///
/// Every rule applied here is the one `CreateIntegration` holds the same integration to:
/// an imported integration is held to the rules of the operation that would otherwise
/// have created it, so no definition can write a record a caller could not.
///
/// `Err` carries the REASON this integration cannot be created, which the caller of this
/// reader reports as the warning [`integration_warning`] words: a problem here belongs to
/// one resource of the document, not to the document, so it is never the import's refusal.
fn read_integration(extension: &Node) -> Result<ImportedIntegration, String> {
    if extension.entries().is_none() {
        return Err(format!("'{INTEGRATION_EXTENSION}' must be an object"));
    }
    // The extension spells the type in lower case (`http_proxy`), while the modelled
    // `IntegrationType` is upper case; they are the same catalog. A `type` that catalog
    // does NOT carry names no `IntegrationType` at all, so such an extension is read
    // exactly as one naming no type is — the integration has no type to be created with,
    // which is the reason reported, never the unrecognized value itself.
    let integration_type = extension
        .string_member("type")
        .map(|value| value.to_ascii_uppercase())
        .filter(|value| INTEGRATION_TYPE_VALUES.contains(&value.as_str()))
        .ok_or_else(|| INTEGRATION_TYPE_REQUIRED.to_string())?;
    // An imported api speaks HTTP, and three of the five integration types are
    // documented as supported only for WebSocket APIs, so an integration of one of
    // those types is refused here exactly as `CreateIntegration` refuses it, through the
    // gate they share.
    crate::state::validate_integration_type_for_protocol(
        crate::state::HTTP_PROTOCOL_TYPE,
        &integration_type,
    )?;

    // Everything else the extension declares, read before anything is refused beyond
    // the catalogs above, so the whole integration is checked at once.
    let integration_uri = extension.string_member("uri");
    let integration_subtype = extension.string_member("integrationSubtype");
    let connection_type = extension
        .string_member("connectionType")
        .map(|value| value.to_ascii_uppercase());
    if let Some(connection_type) = &connection_type {
        if !CONNECTION_TYPE_VALUES.contains(&connection_type.as_str()) {
            return Err(format!(
                "invalid connection type '{connection_type}'. Valid values are: {}.",
                CONNECTION_TYPE_VALUES.join(", ")
            ));
        }
    }
    let connection_id = extension.string_member("connectionId");
    let payload_format_version = extension
        .string_member("payloadFormatVersion")
        .unwrap_or_else(|| DEFAULT_PAYLOAD_FORMAT_VERSION.to_string());

    // The rules an integration RECORD has to satisfy, whatever wrote it: which members
    // name what it invokes, the payload format its type supports, and the link a private
    // connection connects through. The ONE owner of them is
    // `crate::state::validate_integration`, the same one `CreateIntegration` and
    // `UpdateIntegration` go through, so an imported integration cannot be a record a
    // caller could not have created. A template selection expression is not read here:
    // an imported api speaks HTTP and that member is supported only for WebSocket APIs.
    crate::state::validate_integration(
        &integration_type,
        integration_subtype.as_deref(),
        integration_uri.as_deref(),
        Some(payload_format_version.as_str()),
        connection_type
            .as_deref()
            .unwrap_or(crate::state::DEFAULT_CONNECTION_TYPE),
        connection_id.as_deref(),
        ::std::option::Option::None,
    )?;

    let timeout_in_millis = extension
        .integer_member("timeoutInMillis")
        .map_err(|_| format!("'{INTEGRATION_EXTENSION}.timeoutInMillis' must be an integer"))?;
    if let Some(timeout) = timeout_in_millis {
        if !(MIN_TIMEOUT_MILLIS..=MAX_TIMEOUT_MILLIS).contains(&timeout) {
            return Err(format!(
                "'{INTEGRATION_EXTENSION}.timeoutInMillis' must be between \
                 {MIN_TIMEOUT_MILLIS} and {MAX_TIMEOUT_MILLIS}, got {timeout}"
            ));
        }
    }

    Ok(ImportedIntegration {
        integration_type,
        integration_uri,
        integration_method: extension.string_member("httpMethod"),
        integration_subtype,
        connection_type,
        connection_id,
        credentials_arn: extension.string_member("credentials"),
        payload_format_version,
        // The value is inside the modelled range, checked above, so it is an `i32`.
        timeout_in_millis: timeout_in_millis.map(|timeout| {
            i32::try_from(timeout).unwrap_or(crate::state::DEFAULT_HTTP_TIMEOUT_MILLIS)
        }),
        request_parameters: extension.string_map_member("requestParameters"),
        response_parameters: extension
            .member("responseParameters")
            .and_then(Node::entries)
            .unwrap_or_default()
            .iter()
            .map(|(selection, parameters)| (selection.clone(), parameters.scalar_entries()))
            .collect(),
        server_name_to_verify: extension
            .member("tlsConfig")
            .and_then(|config| config.string_member("serverNameToVerify")),
    })
}

/// The path every imported route is prefixed with: the base path the definition declares,
/// read as the request's `Basepath` says to.
///
/// "Specifies how to interpret the base path of the API during import"
/// (`ImportApi$Basepath`): `ignore` leaves the base path out of the routes' paths,
/// `prepend` puts all of it in front of them, and `split` takes the base path's FIRST
/// segment to be a stage name — not part of any path — and prepends only what follows it.
fn route_prefix(document: &Node, basepath: BasePathMode) -> String {
    if basepath == BasePathMode::Ignore {
        return String::new();
    }
    let base = document_base_path(document).unwrap_or_default();
    let mut segments = base.split('/').filter(|segment| !segment.is_empty());
    if basepath == BasePathMode::Split {
        // The stage name, which names no path segment.
        let _ = segments.next();
    }
    let rest: Vec<&str> = segments.collect();
    if rest.is_empty() {
        String::new()
    } else {
        format!("/{}", rest.join("/"))
    }
}

/// The base path a definition declares: Swagger 2.0's own `basePath` member, or the PATH
/// of the first server an OpenAPI 3 document lists.
fn document_base_path(document: &Node) -> Option<String> {
    if let Some(base) = document.string_member("basePath") {
        return Some(base);
    }
    let url = document
        .member("servers")
        .and_then(Node::items)
        .and_then(<[Node]>::first)
        .and_then(|server| server.string_member("url"))?;
    Some(url_path(&url))
}

/// The path component of a server url: what follows the authority of an absolute url, and
/// the whole value of a relative one (`/dev`).
fn url_path(url: &str) -> String {
    match url.split_once("://") {
        Some((_, authority_and_path)) => match authority_and_path.find('/') {
            Some(start) => authority_and_path[start..].to_string(),
            None => String::new(),
        },
        None => url.to_string(),
    }
}

/// The path an imported route carries: the prefix and the document's path, re-joined from
/// their segments so a doubled or trailing separator names the same route as the path
/// written without it, and a path of only separators is the api's root.
fn route_path(prefix: &str, path: &str) -> String {
    let segments: Vec<&str> = prefix
        .split('/')
        .chain(path.split('/'))
        .filter(|segment| !segment.is_empty())
        .collect();
    if segments.is_empty() {
        "/".to_string()
    } else {
        format!("/{}", segments.join("/"))
    }
}
