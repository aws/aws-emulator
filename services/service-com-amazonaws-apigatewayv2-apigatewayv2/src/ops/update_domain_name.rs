    const NAME: &'static str = "UpdateDomainName";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_DOMAIN_NAME_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_DOMAIN_NAME_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let region = crate::state::request_region(ctx.parts());

        // `None` here means the patch named no routing mode, so the stored one stands:
        // the catalog check and its wording are shared with `create_domain_name`, but a
        // create's default is NOT re-applied by an update.
        let routing_mode = match crate::state::resolve_routing_mode(input.routing_mode.as_deref()) {
            Ok(mode) => mode,
            Err(message) => return Err(bad_request(&message)),
        };

        // A `DomainNameConfigurations` the request omits is not an empty list: it is a
        // member the patch says nothing about. One it CARRIES is resolved through the
        // same helper `CreateDomainName` uses, so an entry's defaults and enum catalogs
        // cannot drift between the two operations — and neither can the refusal of a
        // list that names no endpoint, which a patch would strip the domain name down to.
        let requested_configurations = match input.domain_name_configurations.as_deref() {
            ::std::option::Option::None => ::std::option::Option::None,
            Some(requested) => match crate::state::resolve_domain_name_endpoints(requested) {
                Ok(resolved) => Some(resolved),
                Err(message) => return Err(bad_request(&message)),
            },
        };

        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Unreachable in the assembled emulator — see the note in `create_api`.
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "UpdateDomainName",
            ));
        };

        // Mutual TLS has a precondition on the certificate each endpoint PRESENTS, and a
        // patch may carry those endpoints or leave the stored ones in place — so what this
        // call would LEAVE BEHIND is read first, and the certificates it would present are
        // weighed with the service that holds them. That answer is awaited, so it is
        // settled with no lock held and before anything is written: a refused patch leaves
        // no half-configured domain name behind.
        //
        // The refusals this operation decides on its OWN — a name the account does not
        // hold, and a resource mid-migration — are taken first, under that same read: they
        // need no other service, and a patch AWS refuses outright must not turn into a hop
        // either. See `crate::state::acm_certificate_issuance`.
        let now = ::std::time::SystemTime::now();
        let patched = {
            let store = state.lock();
            let Some(record) = store.domain_names.get(&input.domain_name) else {
                return Err(not_found());
            };
            // "If the status is UPDATING, the domain cannot be modified further until the
            // existing operation is complete. If it is AVAILABLE, the domain can be
            // updated" (`DomainNameConfiguration$DomainNameStatus`). A domain name
            // mid-migration is therefore refused with the modelled `ConflictException` —
            // "the requested operation would cause a conflict with the current state of a
            // service resource" — and nothing is written. The status is read off the clock,
            // so the refusal lifts of its own accord once the migration this service owes
            // comes due.
            if record.status(now) == crate::state::DOMAIN_NAME_STATUS_UPDATING {
                return Err(mid_migration(&input.domain_name));
            }
            (
                requested_configurations
                    .clone()
                    .unwrap_or_else(|| record.configurations.clone()),
                input
                    .mutual_tls_authentication
                    .clone()
                    .or_else(|| record.mutual_tls_authentication.clone()),
            )
        };
        let (configurations, mutual_tls) = patched;
        if let Err(message) = crate::state::acm_certificate_issuance::resolve_mutual_tls_ownership(
            ctx,
            &region,
            &configurations,
            mutual_tls.as_ref(),
        )
        .await
        {
            return Err(bad_request(&message));
        }

        let mut store = state.lock();

        // Both refusals again under the WRITE lock: the read above was taken before the
        // awaited hop, so a patch that began a migration in between must refuse this one
        // rather than be overwritten by it, and the record resolved here is the one written
        // through.
        let Some(record) = store.domain_names.get_mut(&input.domain_name) else {
            return Err(not_found());
        };
        if record.status(now) == crate::state::DOMAIN_NAME_STATUS_UPDATING {
            return Err(mid_migration(&input.domain_name));
        }

        // The update is a PATCH (`PATCH /v2/domainnames/{DomainName}`): a member the
        // request carries replaces the stored one, and a member it omits leaves the
        // stored value exactly as it was. `Tags` is not an input member of this
        // operation, so an update never touches the domain name's tags; neither does it
        // re-apply a create's defaults, which would silently undo a value a later
        // `GetDomainName` can still report.
        if let Some(routing_mode) = routing_mode {
            record.routing_mode = routing_mode;
        }
        if let Some(mutual_tls) = input.mutual_tls_authentication {
            record.mutual_tls_authentication = Some(mutual_tls);
        }
        if let Some(configurations) = requested_configurations {
            // The endpoints a domain name is served on only migrate when they actually
            // change: re-sending the stored configuration asks for no migration, so the
            // domain name stays `AVAILABLE` and remains updatable.
            if configurations != record.configurations {
                record.configurations = configurations;
                record.migration_due_at = Some(now + crate::state::DOMAIN_NAME_MIGRATION);
            }
        }

        // Report the record as STORED, so what the caller gets is what a later
        // GetDomainName will report. `DomainNameArn` and `ApiGatewayDomainName` are
        // carried over untouched: they name the resource and the host a caller's DNS
        // record points at, neither of which an update moves.
        let referenced_certificates = record.referenced_certificate_arns();
        let resource_arn = record.domain_name_arn.clone();
        let stored = record.to_wire(now);

        // A patch that moved this domain name onto another certificate also moved which
        // certificate it is using, and ACM protects and reports exactly the certificates
        // something is using: recording the resource's whole set REPLACES what it
        // referenced before. The certificate it was rotated off is still presented by
        // the endpoints until the migration this patch started finishes, which is when
        // its release falls due.
        if let Some(associations) = crate::state::certificate_association_directory(&*self.engine) {
            associations.lock().record_resource(
                &resource_arn,
                &referenced_certificates,
                now,
                crate::state::DOMAIN_NAME_MIGRATION,
            );
        }

        Ok(UpdateDomainNameOutput {
            api_mapping_selection_expression: stored.api_mapping_selection_expression,
            domain_name: Some(stored.domain_name),
            domain_name_arn: stored.domain_name_arn,
            domain_name_configurations: stored.domain_name_configurations,
            mutual_tls_authentication: stored.mutual_tls_authentication,
            routing_mode: stored.routing_mode,
            tags: stored.tags,
        })
    }
