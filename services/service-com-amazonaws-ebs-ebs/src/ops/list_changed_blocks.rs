        // snapshots that share no ancestor cannot be compared at all, which is the
        // modelled `UNRELATED_SNAPSHOTS` reason.
        if !store.snapshots_share_lineage(first_snapshot_id, &input.second_snapshot_id) {
            return Err(validation(
                "UNRELATED_SNAPSHOTS",
                unrelated_snapshots_message(first_snapshot_id, &input.second_snapshot_id),
            ));
        }

        // The comparison itself ([`changed_blocks`]): every reported block is a block OF
        // the snapshot the URI names, so each one carries that side's own token and the
        // first side's token only where that side holds the same index — "this value is
        // absent if the first snapshot does not have the changed block that is on the
        // second snapshot" (`ChangedBlock`).
        let changed: Vec<ChangedBlock> = changed_blocks(first, second);

        // Where the page starts, by the rule both listings of this service share
        // ([`crate::state::page_resume_index`]): a `NextToken` wins over
        // `StartingBlockIndex` and is checked against what THIS listing reports, which
        // here is the comparison just computed.
        let starting_block_index = page_resume_index(
            input.next_token.as_deref(),
            input.starting_block_index,
            &input.second_snapshot_id,
            |next_index| {
                changed
                    .iter()
                    .any(|block| block.block_index == Some(next_index))
            },
        )
        .map_err(|refusal| validation(refusal.reason, refusal.message))?;

        // "The list in the response will start from this block index or the next valid
        // block index in the snapshots" (`StartingBlockIndex`), and the comparison is
        // already in ascending index order, so the page is the run that starts there.
        let mut remaining = changed
            .iter()
            .skip_while(|block| block.block_index.unwrap_or_default() < starting_block_index);
        let page: Vec<ChangedBlock> = remaining.by_ref().take(page_size).cloned().collect();
