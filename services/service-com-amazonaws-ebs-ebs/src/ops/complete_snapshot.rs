impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CompleteSnapshot<Eng>
{
    type Input = CompleteSnapshotInput;
    type Output = CompleteSnapshotOutput;
    type Error = CompleteSnapshotError;

    const NAME: &'static str = "CompleteSnapshot";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_SNAPSHOT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_SNAPSHOT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Authorization comes FIRST: AWS decides it at the IAM layer, ahead of the service
        // looking at the snapshot, so a caller whose identity-based policies do not allow
        // the seal is refused without being told anything about the snapshot and nothing
        // about it changes ([`crate::service::authorization`]).
        let region = crate::state::kms_reference::request_region(ctx);
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &[crate::service::authorization::snapshot_arn(
                &region,
                &input.snapshot_id,
            )],
        )
        .map_err(CompleteSnapshotErrorModeled::AccessDeniedException)?;

        // The HEADER-bound members this operation takes off the boundary are judged
        // first, which is where the boundary would have judged them — before any state is
        // read, so a request the boundary would have refused still reaches no snapshot.
        //
        // Their FORM first: `ChangedBlocksCount`, `Checksum`, `ChecksumAggregationMethod`
        // and `ChecksumAlgorithm` all carry `skip_validation`, so the constraints are the
        // MODEL's and so is the report — the same walk and the same sentence the boundary
        // would have produced — but it travels in the modelled error, which carries the
        // `Reason` a client branches on.
        if let Some(message) = header_constraint_refusal(&input) {
            return Err(validation("INVALID_PARAMETER_VALUE", message));
        }
        // `ChecksumAlgorithm` is then judged on what the value MEANS, which is this
        // service's own question rather than the boundary's: the service answers an
        // algorithm it does not support with its own modelled `ValidationException`, which
        // carries the `Reason` a client branches on and a message naming the rejected
        // algorithm and the supported set. The boundary's refusal would carry neither.
        if let Some(algorithm) = input.checksum_algorithm.as_deref() {
            if algorithm != CHECKSUM_ALGORITHM_SHA256 {
                return Err(validation(
                    "INVALID_PARAMETER_VALUE",
                    unsupported_checksum_algorithm_message(algorithm),
                ));
            }
        }

        let state = crate::state::service_state(&*self.engine).ok_or_else(no_state)?;
        let now = SystemTime::now();
        let mut store = state.lock();
        store.apply_due_transitions(now);

        let Some(snapshot) = store.snapshots.get_mut(&input.snapshot_id) else {
            // A value that is not even shaped like a snapshot id is a malformed
            // parameter, not a snapshot the service does not hold.
            if !is_well_formed_snapshot_id(&input.snapshot_id) {
                return Err(validation(
                    "INVALID_SNAPSHOT_ID",
                    malformed_snapshot_id_message("snapshotId", &input.snapshot_id),
                ));
            }
            return Err(not_found(snapshot_not_found_message(&input.snapshot_id)));
        };

        // The aggregate `Checksum`, once its FORM has been judged above, is judged on what
        // it SAYS: it is the producer's checksum over the content it wrote, so the service
        // recomputes that aggregate from the blocks the snapshot holds and a request
        // declaring any other value does not correspond to this snapshot's content. Such a
        // request is refused and seals nothing — the member is optional, so a completion
        // that declares no aggregate has nothing to disagree with and is unaffected.
        //
        // The composition is the one `CompleteSnapshotRequest$Checksum` documents, not a
        // guessed one: the per-block checksums, in ascending block-index order,
        // concatenated into a single string, hashed with SHA256
        // ([`crate::state::Snapshot::written_blocks_linear_checksum`]). That is also what
        // `ChecksumAggregationMethod` names — `LINEAR`, the one method the modelled enum
        // declares and the only value the form walk above admits — so the aggregation a
        // request that reaches here asked for, or left to the one method there is, is this
        // one.
        if let Some(declared) = input
            .checksum
            .as_deref()
            // Compared against the blocks the snapshot HOLDS, which is the content the
            // aggregate describes. A snapshot finalised to `error` released its blocks
            // ([`crate::state::Snapshot::finalise_to_error`]), so there is no content left
            // for an aggregate to describe and such a completion is answered by the status
            // it is in, below.
            .filter(|_| snapshot.status != SnapshotStatus::Error)
        {
            let computed = snapshot.written_blocks_linear_checksum();
            if computed != declared {
                return Err(validation(
                    "INVALID_PARAMETER_VALUE",
                    checksum_mismatch_message(&computed, declared),
                ));
            }
        }

        // `ChangedBlocksCount` is the caller's own accounting of the writes it made ("The
        // number of blocks that were written to the snapshot"), bounded only by the
        // model's `range` min 0 and already judged against it above. It is NOT
        // a precondition of the REQUEST: whatever it says WITHIN that range, the request is
        // accepted — the 202 below, never a refusal. What it decides is the status the
        // record FINALISES
        // to: a snapshot whose declared count is the number of blocks that were written to
        // it completes, and one whose count disagrees was not filled as its producer
        // claimed and finalises to `error`, which no read then resolves and whose blocks the
        // store therefore releases ([`crate::state::Snapshot::apply_completion`]).
        //
        // The status the snapshot is in when this request is ACCEPTED is what the 202
        // reports. `CompleteSnapshot` is modelled `@http(code: 202)` — Accepted — so the
        // response acknowledges the snapshot the completion was applied TO: the request has
        // been taken, and the sealing it asks for is finished only after the answer. The
        // completion itself is applied by this call ("Completing the snapshot changes the
        // status to completed"), so every LATER call reads the finalised status off the
        // record, and nothing is left outstanding for the clock to materialise.
        let accepted_status = snapshot.status;
        match snapshot.status {
            SnapshotStatus::Pending => {
                snapshot.apply_completion(input.changed_blocks_count, now);
            }
            // Already completed: completing it again changes nothing, so the stored status
            // is the answer.
            SnapshotStatus::Completed => {}
            // A snapshot whose completion was already accepted and finalised to `error`
            // reads that status back for the same reason a completed one does: the
            // completion was taken, and this call applies no second one.
            SnapshotStatus::Error if snapshot.completion_accepted() => {}
            // A snapshot whose `Timeout` cancelled it before anything completed it can no
            // longer be completed.
            SnapshotStatus::Error => {
                return Err(validation(
                    "INVALID_SNAPSHOT_ID",
                    format!(
                        "snapshot {} was cancelled and can no longer be completed",
                        input.snapshot_id
                    ),
                ));
            }
        }

        // A completed snapshot no longer owes its `Timeout` — there is nothing left to
        // cancel — so the store's schedule is recomputed: `next_transition_due` keeps
        // naming the earliest change the clock really does owe.
        store.refresh_transition_schedule();

        // Rendered from the stored record, never from a literal: the status this request
        // was accepted against. The record itself now holds the finalised status, which is
        // what every later call — including a repeat of this one — reads back.
        Ok(CompleteSnapshotOutput {
            status: Some(accepted_status.as_wire().to_string()),
        })
    }
}

