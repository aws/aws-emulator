impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CompleteSnapshot<Eng>
{
    type Input = CompleteSnapshotInput;
    type Output = CompleteSnapshotOutput;
    type Error = CompleteSnapshotError;

    const NAME: &'static str = "CompleteSnapshot";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_SNAPSHOT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_SNAPSHOT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Authorization comes FIRST: AWS decides it at the IAM layer, ahead of the service
        // looking at the snapshot, so a caller whose identity-based policies do not allow
        // the seal is refused without being told anything about the snapshot and nothing
        // about it changes ([`crate::service::authorization`]).
        let region = crate::state::kms_reference::request_region(ctx);
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &[crate::service::authorization::snapshot_arn(
                &region,
                &input.snapshot_id,
            )],
        )
        .map_err(CompleteSnapshotErrorModeled::AccessDeniedException)?;

        let state = crate::state::service_state(&*self.engine).ok_or_else(no_state)?;
        let now = SystemTime::now();
        let mut store = state.lock();
        store.apply_due_transitions(now);

        // `ChecksumAlgorithm` is checked HERE rather than at the boundary (the member
        // carries `skip_validation` on `CompleteSnapshotInput`): the service answers an
        // algorithm it does not support with its own modelled `ValidationException`,
        // which carries the `Reason` a client branches on and a message naming the
        // rejected algorithm and the supported set. The boundary's refusal would carry
        // neither.
        if let Some(algorithm) = input.checksum_algorithm.as_deref() {
            if algorithm != CHECKSUM_ALGORITHM_SHA256 {
                return Err(validation(
                    "INVALID_PARAMETER_VALUE",
                    unsupported_checksum_algorithm_message(algorithm),
                ));
            }
        }

        let Some(snapshot) = store.snapshots.get_mut(&input.snapshot_id) else {
            // A value that is not even shaped like a snapshot id is a malformed
            // parameter, not a snapshot the service does not hold.
            if !is_well_formed_snapshot_id(&input.snapshot_id) {
                return Err(validation(
                    "INVALID_SNAPSHOT_ID",
                    malformed_snapshot_id_message("snapshotId", &input.snapshot_id),
                ));
            }
            return Err(not_found(snapshot_not_found_message(&input.snapshot_id)));
        };

        // DECLINED, deliberately: the optional aggregate `Checksum` /
        // `ChecksumAggregationMethod` headers are NOT verified here. Their values are
        // constrained by the model (`LINEAR`) and the boundary validator already refuses
        // anything else, but the rule that turns the per-block checksums into the
        // aggregate is not in the model and the published prose does not pin the
        // byte-level composition (whether the per-block checksums are concatenated as
        // their Base64 text or as their raw digests).
        // Refusing on a guessed composition would reject requests a real client builds
        // correctly, which is worse than not checking; so the snapshot is sealed on the
        // evidence this service does have — the blocks it actually stored, checksum-
        // verified one by one as `PutSnapshotBlock` persisted them.
        let _ = (&input.checksum, &input.checksum_aggregation_method);

        // `ChangedBlocksCount` is the caller's own accounting of the writes it made ("The
        // number of blocks that were written to the snapshot"), bounded only by the
        // model's `range` min 0 and already checked against it at the boundary. It is NOT
        // a precondition this call verifies against the blocks the snapshot holds: the
        // request is accepted on any modelled value, so a count that disagrees with what
        // was written still seals the snapshot rather than being refused.
        let _ = input.changed_blocks_count;

        // The status the snapshot is in when this request is ACCEPTED, which is what the
        // 202 reports. `CompleteSnapshot` is modelled `@http(code: 202)` — Accepted — so
        // the response acknowledges the snapshot the seal was applied TO: the request has
        // been taken, and the sealing it asks for is finished only after the answer. The
        // seal itself is applied by this call ("Completing the snapshot changes the status
        // to completed"), so every LATER call reads `completed` back off the record, and
        // nothing is left outstanding for the clock to materialise.
        let accepted_status = snapshot.status;
        match snapshot.status {
            SnapshotStatus::Pending => {
                snapshot.status = SnapshotStatus::Completed;
                // WHEN the seal was applied, stamped by the call that applied it: this
                // call is what completes the snapshot ("Completing the snapshot changes
                // the status to completed"), so the instant is this one and never a
                // later reader's. It is the completion time the EC2 side of the same
                // snapshot reports (`Snapshot$CompletionTime`, "the time stamp when the
                // snapshot was completed").
                snapshot.completed_at = Some(now);
            }
            // Already sealed: completing it again changes nothing, so the stored status
            // is the answer.
            SnapshotStatus::Completed => {}
            // A snapshot whose `Timeout` cancelled it can no longer be sealed.
            SnapshotStatus::Error => {
                return Err(validation(
                    "INVALID_SNAPSHOT_ID",
                    format!(
                        "snapshot {} was cancelled and can no longer be completed",
                        input.snapshot_id
                    ),
                ));
            }
        }

        // A sealed snapshot no longer owes its `Timeout` — there is nothing left to
        // cancel — so the store's schedule is recomputed: `next_transition_due` keeps
        // naming the earliest change the clock really does owe.
        store.refresh_transition_schedule();

        // Rendered from the stored record, never from a literal: the status this request
        // was accepted against. The record itself now holds `completed`, which is what
        // every later call — including a repeat of this one — reads back.
        Ok(CompleteSnapshotOutput {
            status: Some(accepted_status.as_wire().to_string()),
        })
    }
}

