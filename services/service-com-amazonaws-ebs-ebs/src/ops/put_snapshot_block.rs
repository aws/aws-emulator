        // validity and authenticity of the data. If the checksums do not correspond, the
        // request fails." The checksum is computed over the bytes that ARRIVED, whatever
        // length the request declared for them — a payload the request's checksum does
        // not name is not the payload that was signed for, and that is the signing
        // layer's refusal (the class a client re-signs or re-sends on) rather than a
        // statement about the payload's length or about the snapshot. So it is answered
        // before the declared length is judged and before any state is read, and it
        // carries neither the `Message` nor the `Reason` of the modelled validation shape.
