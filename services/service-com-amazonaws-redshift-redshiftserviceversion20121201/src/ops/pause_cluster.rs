impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> PauseCluster<Eng> {
    /// The pause itself: the output it reports.
    ///
    /// Everything that touches the store lives here, so the lock is held for the
    /// write ALONE and nothing is awaited while it is.
    fn pause(&self, input: &PauseClusterInput) -> Result<PauseClusterOutput, PauseClusterError> {
        use crate::state as st;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(PauseClusterErrorModeled::DependentServiceUnavailableFault(
                DependentServiceUnavailableFault {
                    message: Some(st::STORE_UNAVAILABLE.to_string()),
                },
            )
            .into());
        };

        let started = ::service_common::clock::now(&*self.engine);
        let mut store = state.lock();
        store.settle(started);

        // The cluster to suspend has to be there — and it has to be serving: a
        // pause is legal only from a running cluster, so a cluster the service
        // is already working on, or one whose compute is already suspended,
        // takes none.
        let Some(position) = store.cluster_position(&input.cluster_identifier) else {
            return Err(PauseClusterErrorModeled::ClusterNotFoundFault(
                ClusterNotFoundFault {
                    // No recorded refusal gives this operation a sentence of its
                    // own, so it carries the one every other cluster-scoped
                    // operation does — see the per-operation catalog
                    // [`st::ClusterNotFoundWording`].
                    message: Some(st::cluster_not_found_message(
                        st::ClusterNotFoundWording::IdentifierThenNotFound,
                        &input.cluster_identifier,
                    )),
                },
            )
            .into());
        };
        let cluster_status = store.clusters[position]
            .cluster
            .cluster_status
            .clone()
            .unwrap_or_default();
        if cluster_status != st::STATUS_AVAILABLE {
            return Err(PauseClusterErrorModeled::InvalidClusterStateFault(
                InvalidClusterStateFault {
                    // Fixed text with no variable part: the recorded refusal
                    // names the state a pause is legal from rather than the
                    // cluster or the state it is in.
                    message: Some(st::PAUSE_REQUIRES_ACTIVE_CLUSTER.to_string()),
                },
            )
            .into());
        }

        let stored = &mut store.clusters[position];
        // The suspension is applied like any other change to a provisioned
        // cluster, and the published `ClusterStatus` vocabulary has no state for
        // it being applied — so the cluster reports the applying state now and
        // the suspended one at the due instant. The instant is stored and
        // nothing sleeps for it, so a caller acting straight after this call
        // still observes the transition.
        stored.cluster.cluster_status = Some(st::STATUS_MODIFYING.to_string());
        stored.cluster.cluster_availability_status =
            Some(st::availability_status(st::STATUS_MODIFYING).to_string());
        stored.settles_to = Some(st::STATUS_PAUSED.to_string());
        stored.available_at = started + st::PROVISIONING_SPAN;

        // Re-derive every member this service computes from the cluster's own
        // configuration, through the same rule the create and the modify paths
        // use, so this response reports the member set a later read does.
        let cluster_type = stored.cluster_type.clone();
        st::populate_derived_members(
            &mut stored.cluster,
            &cluster_type,
            ::aws_smithy_types::DateTime::from(::std::time::SystemTime::now()),
        );
        let cluster = stored.cluster.clone();

        Ok(PauseClusterOutput {
            cluster: Some(cluster),
        })
    }
}
