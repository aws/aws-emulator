/// One recorded change as the listing summarises it. Every member is read back
/// out of the ledger's record, so what a listing reports and what the accepting
/// call answered are one update rather than two renderings of it.
fn summarised(update: &crate::state::Update) -> UpdateSummary {
    UpdateSummary {
        update_id: update.update_id.clone(),
        r#type: update.update_type.clone(),
        status: update.status.clone(),
        created_at: crate::state::timestamp(update.created_at),
    }
}
