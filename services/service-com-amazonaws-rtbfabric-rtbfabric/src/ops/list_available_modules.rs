/// One catalog module as the listing summarises it. Every member is read out of
/// the same catalog entry `GetAvailableModule` reads, so a listed module and that
/// module's own reading report one module rather than two renderings of it. The
/// modelled `AvailableModuleSummary` declares no `description` and no
/// `createdAt` — the single-module reader reports both
/// (`smithy_query(query="shape", shape="AvailableModuleSummary")`).
fn summarised(
    module: &crate::state::AvailableModule,
    region: &str,
) -> AvailableModuleSummary {
    AvailableModuleSummary {
        module_id: module.module_id.to_string(),
        module_arn: module.arn(region),
        module_name: module.module_name.to_string(),
        subscription_type: module.subscription_type.to_string(),
        subscription_status: module.subscription_status.to_string(),
        // Present only for a module held under a Marketplace subscription, which
        // this emulator's catalog holds none of.
        marketplace_product_id: module.marketplace_product_id.map(str::to_string),
    }
}
