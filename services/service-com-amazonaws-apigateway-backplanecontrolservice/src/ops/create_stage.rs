/// The refusal for a `stageName` carrying a character outside the set a stage name is
/// spelled from: a fixed sentence naming that set, which quotes the rejected name back
/// nowhere. One copy, so the call that creates a stage and the one that creates a
/// deployment WITH a stage say the same thing about the same name.
pub const INVALID_STAGE_NAME: &str = "Stage name only allows a-zA-Z0-9_";

/// Refuse a `stageName` that is not one API Gateway accepts.
///
/// From the member's own documentation: "Stage names can only contain alphanumeric
/// characters, hyphens, and underscores. Maximum length is 128 characters." An empty
/// name is no name at all: a stage name is the first path segment of an invoke URL.
pub fn validate_stage_name(stage_name: &str) -> Result<(), String> {
    if stage_name.is_empty() {
        return Err("stageName must not be empty".to_string());
    }
    crate::state::bound_chars("stageName", stage_name, crate::state::MAX_STAGE_NAME_CHARS)?;
    if !stage_name
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        return Err(INVALID_STAGE_NAME.to_string());
    }
    Ok(())
}

/// The `Stage` body for a stored stage — the one place this crate renders that shape, so
/// `CreateStage`, `CreateDeployment`, `GetStage` and `UpdateStage` cannot report a record
/// differently.
///
/// `methodSettings` is reported even when empty: every stage has the map, and it is what
/// `UpdateStage` fills. `cacheClusterStatus` is computed from the stored record (see
/// [`StageEntry::cache_cluster_status`]).
///
/// `web_acl_arn` is NOT a field of the record: it is the web ACL WAF currently has in
/// front of this stage ([`crate::state::associated_web_acl_arn`]), which the caller
/// resolves with this service's store unlocked and hands in, so every reader of a stage
/// reports the one live association and none of them can report a stale one.
pub fn stage_body(entry: &StageEntry, web_acl_arn: Option<String>) -> CreateStageOutput {
    CreateStageOutput {
        deployment_id: Some(entry.deployment_id.clone()),
        client_certificate_id: entry.client_certificate_id.clone(),
        stage_name: Some(entry.stage_name.clone()),
        description: entry.description.clone(),
        cache_cluster_enabled: entry.cache_cluster_enabled,
        cache_cluster_size: entry.cache_cluster_size.clone(),
        cache_cluster_status: Some(entry.cache_cluster_status().to_string()),
        method_settings: Some(
            entry
                .method_settings
                .iter()
                .map(|(key, setting)| (key.clone(), setting.clone()))
                .collect::<HashMap<String, MethodSetting>>(),
        ),
        variables: (!entry.variables.is_empty()).then(|| {
            entry
                .variables
                .iter()
                .map(|(key, value)| (key.clone(), value.clone()))
                .collect()
        }),
        documentation_version: entry.documentation_version.clone(),
        access_log_settings: entry.access_log_settings.clone(),
        canary_settings: entry.canary_settings.clone().map(|canary| CanarySettings {
            // "The ID of the canary deployment" (`CanarySettings$deploymentId`): a canary
            // configured on a stage serves a deployment, so one that carries no deployment
            // of its own — a canary configured before it was pointed at one, or one whose
            // own deployment was taken away — serves the deployment the STAGE serves.
            // Derived on every report rather than stored, so re-pointing the stage moves
            // such a canary with it.
            deployment_id: canary
                .deployment_id
                .or_else(|| Some(entry.deployment_id.clone())),
            ..canary
        }),
        tracing_enabled: entry.tracing_enabled,
        // "The ARN of the WebAcl associated with the Stage" (`Stage$webAclArn`): set by
        // associating a web ACL with this stage's ARN through AWS WAF, so it is read from
        // that association on every report rather than stored here.
        web_acl_arn,
        tags: (!entry.tags.is_empty()).then(|| {
            entry
                .tags
                .iter()
                .map(|(key, value)| (key.clone(), value.clone()))
                .collect()
        }),
        created_date: entry.created_date,
        last_updated_date: entry.last_updated_date,
    }
}

