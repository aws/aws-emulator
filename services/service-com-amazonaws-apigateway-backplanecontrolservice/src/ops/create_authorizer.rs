pub const AUTH_TYPE_COGNITO_USER_POOLS: &str = "cognito_user_pools";

/// The `authType` an authorizer whose request supplied none is stored with: the label its
/// own `type` implies.
///
/// `authType` is an "optional customer-defined field, used in OpenAPI imports and exports
/// without functional impact", and what it is used AS in those documents is the
/// `x-amazon-apigateway-authtype` of the security scheme the authorizer becomes — so the
/// value the service fills in for a request that supplies none is the label that document
/// names this kind of authorization by: `custom` for a Lambda authorizer (a `TOKEN` or a
/// `REQUEST` one, which authorize by calling a function of the developer's own) and
/// `cognito_user_pools` for one that authorizes against a user pool. A `JWT` authorizer
/// authorizes by neither route — it verifies the presented token itself, against the issuers
/// its own `jwtConfiguration` declares — so no such label is implied for it and the member
/// stays as the request set it. A type outside the catalog implies nothing, which the
/// boundary validator has already refused.
pub fn implied_auth_type(authorizer_type: &str) -> Option<&'static str> {
    match authorizer_type {
        AUTHORIZER_TYPE_TOKEN | AUTHORIZER_TYPE_REQUEST => Some(AUTH_TYPE_CUSTOM),
        AUTHORIZER_TYPE_COGNITO_USER_POOLS => Some(AUTH_TYPE_COGNITO_USER_POOLS),
        _ => None,
    }
}

/// Refuse an authorizer whose configuration its own `type` does not admit.
///
/// Every clause is the member's own documentation, which makes a member required for
/// some types and undefined for others:
///
/// * `authorizerUri` — "For TOKEN or REQUEST authorizers, this must be a well-formed
///   Lambda function URI": the Lambda to invoke, so those two types cannot authorize
///   without it.
/// * `identitySource` — "For a TOKEN or COGNITO_USER_POOLS authorizer, this is required
///   …. For the REQUEST authorizer, this is required when authorization caching is
///   enabled", and caching is enabled exactly when the stored TTL is above zero. For a
///   `TOKEN` authorizer, which authorizes on "a single authorization token submitted in a
///   custom header", the value also has to BE that header's mapping expression
///   ([`is_method_request_header`]).
/// * `providerARNs` — "A list of the Amazon Cognito user pool ARNs for the
///   COGNITO_USER_POOLS authorizer": the pools whose tokens are accepted, so that type
///   cannot authorize without at least one.
///
/// Every one of them is refused with [`INVALID_REQUEST_INPUT`] — except the missing
/// `authorizerUri`, which has a sentence of its own ([`AUTHORIZER_URI_REQUIRED`]): API
/// Gateway names THAT field in the refusal and makes no claim about which member is at
/// fault in the others.
///
/// The check reads the STORED record rather than one request's members, because the same
/// rule has to hold however the record came to look that way: the TTL it is judged
/// against is the stored one from [`authorizer_result_ttl`], not the requested one, since
/// a request that sets no TTL still enables caching at the default. `UpdateAuthorizer`
/// applies it to the PATCHED record for exactly that reason.
pub fn require_members_of_type(entry: &AuthorizerEntry) -> Result<(), String> {
    let ttl = entry.authorizer_result_ttl_in_seconds;
    let authorizer_type = entry.r#type.as_str();
    if matches!(
        authorizer_type,
        AUTHORIZER_TYPE_TOKEN | AUTHORIZER_TYPE_REQUEST
    ) && !supplied(&entry.authorizer_uri)
    {
        return Err(AUTHORIZER_URI_REQUIRED.to_string());
    }
    // The members a `JWT` authorizer's own documentation says it does not have: the Lambda
    // it would otherwise call and the credentials to call it with, the user pools whose
    // tokens it would otherwise accept, the expression another type matches an audience
    // with, and the cached results it keeps none of. Each is "not supported for JWT
    // authorizers" on the member itself, so a record of that type carrying one is a
    // configuration nothing would read.
    if authorizer_type == AUTHORIZER_TYPE_JWT
        && (supplied(&entry.authorizer_uri)
            || supplied(&entry.authorizer_credentials)
            || supplied(&entry.identity_validation_expression)
            || !entry.provider_arns.is_empty()
            || ttl != MIN_AUTHORIZER_RESULT_TTL_SECONDS)
    {
        return Err(INVALID_REQUEST_INPUT.to_string());
    }
    let caching_enabled = ttl > MIN_AUTHORIZER_RESULT_TTL_SECONDS;
    let identity_source_required = match authorizer_type {
        AUTHORIZER_TYPE_TOKEN | AUTHORIZER_TYPE_COGNITO_USER_POOLS | AUTHORIZER_TYPE_JWT => true,
        AUTHORIZER_TYPE_REQUEST => caching_enabled,
        _ => false,
    };
    if identity_source_required && !supplied(&entry.identity_source) {
        return Err(INVALID_REQUEST_INPUT.to_string());
    }
    // A `TOKEN` authorizer reads ONE value — "a single authorization token submitted in a
    // custom header" (`AuthorizerType`) — and the member "specifies the request header
    // mapping expression for the custom header holding the authorization token", so a value
    // that is not such an expression names a header no request could be read from: it is
    // refused with API Gateway's own sentence for an unreadable token source, which states
    // the form the source must take and quotes the submitted expression back once
    // ([`invalid_token_source`]). A `COGNITO_USER_POOLS` authorizer's source is not held to
    // the form here: the data plane reads a presented token from wherever that expression
    // names ([`crate::service::invoke`]), and a `REQUEST` authorizer's is "a comma-separated
    // string of one or more mapping expressions" over any parameter location.
    if authorizer_type == AUTHORIZER_TYPE_TOKEN {
        if let Some(source) = entry.identity_source.as_deref() {
            if !is_method_request_header(source) {
                return Err(invalid_token_source(source));
            }
        }
    }
    // A `JWT` authorizer reads one value too: "for a JWT authorizer, this is required and
    // must be a single request-header mapping expression, `method.request.header.<name>`
    // …. Query string parameters are not supported, and there is no default"
    // (`Authorizer$identitySource`) — the same form, refused with this service's sentence
    // for a configuration it does not admit, since the expression a JWT authorizer reads a
    // token from is no `TOKEN` authorizer's token source.
    if authorizer_type == AUTHORIZER_TYPE_JWT
        && entry
            .identity_source
            .as_deref()
            .is_some_and(|source| !is_method_request_header(source))
    {
        return Err(INVALID_REQUEST_INPUT.to_string());
    }
    if authorizer_type == AUTHORIZER_TYPE_COGNITO_USER_POOLS && entry.provider_arns.is_empty() {
        return Err(INVALID_REQUEST_INPUT.to_string());
    }
    Ok(())
}

/// The refusal for an authorizer configuration the requested `type` does not admit: the
