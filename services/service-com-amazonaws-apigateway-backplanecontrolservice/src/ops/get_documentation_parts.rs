use crate::state::DocumentationPartEntry;

/// The separator between the segments of a location cursor.
const CURSOR_SEPARATOR: char = ':';

/// Where one documentation part sorts in its API's collection: the ADDRESS of the entity
/// it documents, segment by segment — the entity type, then the entity's name, path,
/// method and status code, each compared as the text it is, with an empty segment for
/// every member the entity type leaves unset.
///
/// That is the same five segments, in the same order, that a `position` cursor spells
/// ([`location_cursor`]), so the collection's order is the order of its own cursors and a
/// cursor read back ([`cursor_order`]) names a POINT in it rather than a record.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct LocationOrder {
    entity_type: String,
    name: String,
    path: String,
    method: String,
    status_code: String,
}

impl LocationOrder {
    /// The five segments, outermost first, as a cursor joins them.
    fn segments(&self) -> [&str; 5] {
        [
            self.entity_type.as_str(),
            self.name.as_str(),
            self.path.as_str(),
            self.method.as_str(),
            self.status_code.as_str(),
        ]
    }
}

/// Where `location` sorts.
fn location_order(location: &DocumentationPartLocation) -> LocationOrder {
    LocationOrder {
        entity_type: location.r#type.clone(),
        name: location.name.clone().unwrap_or_default(),
        path: location.path.clone().unwrap_or_default(),
        method: location.method.clone().unwrap_or_default(),
        status_code: location.status_code.clone().unwrap_or_default(),
    }
}

/// The `position` cursor of the part at `location`: its five location members — the
/// entity type, the entity's name, the path, the method and the status code — joined by
/// `:`, with an empty segment for every member the entity type leaves unset (a model's
/// location sets a name and no path, a resource's a path and no name).
pub fn location_cursor(location: &DocumentationPartLocation) -> String {
    location_order(location)
        .segments()
        .join(&CURSOR_SEPARATOR.to_string())
}

/// The point in the order a `position` cursor names: its segments read back out.
///
/// Every text places — a cursor is read as the address it spells, and one that spells an
/// address past the collection's last part is the end of the collection — so a cursor the
/// collection has been walked past is served the page that holds nothing rather than
/// refused, which is what ends a walk of it.
fn cursor_order(cursor: &str) -> LocationOrder {
    let mut segments = cursor.split(CURSOR_SEPARATOR);
    let mut segment = || segments.next().unwrap_or_default().to_string();
    LocationOrder {
        entity_type: segment(),
        name: segment(),
        path: segment(),
        method: segment(),
        status_code: segment(),
    }
}

/// Whether a stored part counts as `DOCUMENTED` for the request's `locationStatus`
/// filter.
///
/// From `GetDocumentationPartsRequest$locationStatus`: "Valid values are `DOCUMENTED` for
/// retrieving DocumentationPart resources with content and `UNDOCUMENTED` for
/// DocumentationPart resources without content." A part's content is its `properties`
/// content map, so a part whose map holds at least one key has content and one whose map
/// is empty (`{}`) does not. The map is stored as the JSON object
/// [`crate::ops::create_documentation_part::validated_properties`] read, so text that is
/// no longer readable as one is judged by whether it carries anything at all.
fn has_content(properties: &str) -> bool {
    match ::serde_json::from_str::<::serde_json::Value>(properties) {
        Ok(::serde_json::Value::Object(map)) => !map.is_empty(),
        _ => !properties.trim().is_empty(),
    }
}

/// Whether `part` satisfies every filter the request set.
///
/// Each filter names the documentation parts of the API entities it describes — their
/// `type`, their `name`, their `path` — so a part is reported only when its stored
/// location matches every one the request carries, and a request that carries none
/// reports the API's parts as they stand.
fn matches_filters(part: &DocumentationPartEntry, input: &GetDocumentationPartsInput) -> bool {
    if let Some(entity_type) = &input.r#type {
        if part.location.r#type != *entity_type {
            return false;
        }
    }
    if let Some(name) = &input.name_query {
        if part.location.name.as_deref() != Some(name.as_str()) {
            return false;
        }
    }
    if let Some(path) = &input.path {
        if part.location.path.as_deref() != Some(path.as_str()) {
            return false;
        }
    }
    match input.location_status.as_deref() {
        Some("DOCUMENTED") => has_content(&part.properties),
        Some("UNDOCUMENTED") => !has_content(&part.properties),
        // The modelled enum has no third value, and the boundary validator refuses one:
        // an absent `locationStatus` filters nothing.
        _ => true,
    }
}

