impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TestInvokeMethod<Eng>
{
    type Input = TestInvokeMethodInput;
    type Output = TestInvokeMethodOutput;
    type Error = TestInvokeMethodError;

    const NAME: &'static str = "TestInvokeMethod";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_INVOKE_METHOD_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_INVOKE_METHOD_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `latency` is "the execution latency, in ms, of the test invoke request", so it is
        // MEASURED over the simulation rather than stated: the clock is started before the
        // records are read and read once the response has been computed.
        let started = ::std::time::Instant::now();
        // WHAT is simulated, read under ONE read of the store and taken off it as OWNED
        // records: the api (what a refusal is rendered from), the resource path the
        // simulated request is bound against, the verb and the method that carries the
        // integration. The store is released with that read, because an integration naming
        // another service's action is performed by CALLING that service in process and no
        // lock of this service's is held while another service answers.
        let (api, resource_path, verb, method) = {
            let state = crate::state::service_state(&*self.engine)
                .ok_or_else(crate::state::state_unavailable)?;
            let store = state.lock();
            // A method is addressed THROUGH its resource, so the
            // `(restApiId, resourceId)` pair is resolved as ONE lookup for that resource:
            // an api this account does not hold leaves the addressed resource
            // unresolvable too, and the refusal reports that resource.
            let api = store
                .resource_api(&input.rest_api_id)
                .map_err(|message| not_found(&message))?;
            let resource = api
                .resources
                .get(&input.resource_id)
                .ok_or_else(|| not_found(crate::state::NO_SUCH_RESOURCE))?;
            // The verb is addressed exactly as `GetMethod` addresses it, so a method is
            // reachable by the spelling it was put under.
            let verb = super::put_method::method_key(&input.http_method);
            let method = resource
                .methods
                .get(&verb)
                .ok_or_else(|| not_found(crate::state::NO_SUCH_METHOD))?;
            (
                api.clone(),
                resource.path.clone(),
                verb,
                method.clone(),
            )
        };
        // The integration is WHAT a simulated invocation invokes. A method that carries
        // none cannot be invoked at all, so this is a precondition of the operation —
        // refused on its error channel before anything is simulated — and not a response
        // to render. An integration that exists and cannot be PERFORMED is reported
        // through the API's gateway response further down, which is the data plane's own
        // answer for it.
        if method.integration.is_none() {
            return Err(bad_request(crate::state::NO_INTEGRATION_DEFINED));
        }

        let mut log = ExecutionLog::started();
        // What the simulated request carries, read by the one reader of a simulated
        // request's members ([`simulated_request`]).
        let headers = simulated_request::SimulatedHeaders::of(
            input.headers.as_ref(),
            input.multi_value_headers.as_ref(),
        );
        let content_type = headers.value(CONTENT_TYPE);
        let accepted = headers.value(ACCEPT);
        // The trace context the simulated request named, which is the chain the answer's own
        // tracing header reports ([`crate::service::invoke::trace_context::reported_header`]).
        let supplied_trace = headers.value(TRACE_HEADER);
        log.line(format!("HTTP Method: {verb}, Resource Path: {resource_path}"));
        let (path, query) = simulated_request::split_query(input.path_with_query_string.as_deref());
        // The PARAMETERS the method request carried at the address it was made at: the path
        // parameters the resource's own template binds out of the address, and the query
        // parameters the query string carries. The same two maps the integration's own
        // mappings read ([`TemplateInputs`] below), so the log states the values the
        // simulation was performed from.
        let path_parameters = matched_path_parameters(&resource_path, path.unwrap_or(""));
        let query_parameters = sent_query_parameters(query.unwrap_or_default());
        // The four facts of the METHOD REQUEST, each stated whatever the request carries: an
        // execution log states the path parameters the call was made with, the query string
        // it carried, the headers it carried and the body it carried, in that order — a
        // client reading the log reads each of them off a line of it, and a request that
        // carried none of a kind states the EMPTY map rather than leaving the step out, so a
        // reader tells "nothing was carried" from a line it can read.
        log.line(format!(
            "Method request path: {}",
            stated_parameters(&path_parameters)
        ));
        log.line(format!(
            "Method request query string: {}",
            stated_parameters(&query_parameters)
        ));
        log.line(crate::service::invoke::stage_logs::traced_header_names_line(
            &headers.names(),
        ));
        // The method request AS THE CALLER DESCRIBED IT, at the first of the four
        // transformation points an execution log states: the simulated request's own body,
        // through the one line builder a stage's data trace states a payload with
        // ([`crate::service::invoke::stage_logs::traced_payload_line`]), so a transformation
        // point is worded and bounded the same way whichever side drove the call. The log IS
        // this operation's answer about the configuration it was asked to exercise, and it
        // travels back to the caller that supplied the body beside the response rendered from
        // it, so stating each payload discloses nothing the same response does not already
        // carry — which is why a stage, whose trace goes to a log group, states one only
        // under the method's own `dataTrace` setting.
        log.line(crate::service::invoke::stage_logs::traced_payload_line(
            "Method request body before transformations",
            input.body.as_deref().unwrap_or_default().as_bytes(),
        ));
        let stage_variables = simulated_request::map_names(input.stage_variables.as_ref());
        if !stage_variables.is_empty() {
            log.line(format!(
                "Stage variables: [{}]",
                stage_variables.join(", ")
            ));
        }
        if let Some(certificate) = input.client_certificate_id.as_deref() {
            log.line(format!(
                "Client certificate {certificate} is not presented: a simulated invocation \
                 makes no HTTPS request to a backend"
            ));
        }
        log.line(format!(
            "Integration type: {}",
            method
                .integration
                .as_ref()
                .and_then(|integration| integration.r#type.as_deref())
                .unwrap_or("none")
        ));

        // The stage variables the caller asked to simulate are what the integration's
        // configuration is read against: `stageVariables` is "a key-value map of stage
        // variables to simulate an invocation on a deployed Stage", so a configuration
        // naming one is resolved exactly as the data plane resolves it at a stage whose
        // own map carries those entries.
        let simulated_variables: BTreeMap<String, String> = input
            .stage_variables
            .iter()
            .flatten()
            .map(|(name, value)| (name.clone(), value.clone()))
            .collect();
        // What a MAPPING TEMPLATE of this simulated call renders against: the same members
        // the data plane reads off the wire, taken from the ones a caller simulates the
        // request with, so one stored template renders one way whichever side drives it.
        // The path parameters are bound against the RESOURCE's own template, because
        // `pathWithQueryString` is where a caller "specif[ies] path parameters and query
        // string parameters". A simulated call reaches no stage, so it carries no stage of
        // its own to name.
        let inputs = TemplateInputs {
            payload: Some(
                input
                    .body
                    .as_deref()
                    .unwrap_or_default()
                    .as_bytes()
                    .to_vec(),
            ),
            path: path_parameters,
            querystring: query_parameters,
            header: headers.single_valued(),
            stage_variables: simulated_variables.clone(),
            context: BTreeMap::from([
                ("apiId".to_string(), input.rest_api_id.clone()),
                ("httpMethod".to_string(), verb.clone()),
                ("resourcePath".to_string(), resource_path.clone()),
                (
                    "path".to_string(),
                    path.unwrap_or(resource_path.as_str()).to_string(),
                ),
            ]),
        };
        let call = MethodRequest::simulated(
            content_type.as_deref(),
            accepted.as_deref(),
            inputs,
            // What a PROXY integration's event names a SIMULATED call by: the resource and
            // the verb the caller named, the path it simulated, and every value its
            // `multiValueHeaders` and query string carry. The method ARN is the one AWS
            // narrows a grant for a TEST invocation by — the api's own method under
            // [`TEST_INVOKE_STAGE`] — so the function's resource policy decides a simulated
            // invocation exactly as it decides a deployed stage's, and a function that
            // admits API Gateway nothing for this method is not invoked at all.
            ProxyInputs {
                resource_id: input.resource_id.clone(),
                http_method: verb.clone(),
                request_path: path.unwrap_or(resource_path.as_str()).to_string(),
                domain_name: String::new(),
                multi_value_querystring: simulated_request::every_query_parameter(query),
                multi_value_header: headers.every_value(),
                source_arn: Some(
                    crate::service::resource_policy::Call {
                        region: api.arn_region(),
                        api_id: &input.rest_api_id,
                        stage: TEST_INVOKE_STAGE,
                        verb: &verb,
                        resource_path: &resource_path,
                        request_path: path.unwrap_or(resource_path.as_str()),
                        source_vpce: None,
                        // A SIMULATED call arrived over no connection, so it carries no
                        // address for a policy clause to be decided against.
                        source_ip: None,
                        caller: crate::service::resource_policy::Caller::Anonymous,
                    }
                    .method_arn(),
                ),
                // What the api declares BINARY, which decides whether a base64 body the
                // function returns is reported as the bytes it names or as the base64
                // text it is — the same records the data plane reads it from.
                binary_media_types: api.binary_media_types.clone(),
                // A simulated call reached no stage, so there is no stage whose tracing
                // setting could decide a sampling decision the caller did not take.
                tracing_enabled: false,
            },
        );
        // The request the simulated invocation is PERFORMED as: an integration's own
        // mappings read a request — its headers, its query string and its payload — so the
        // members the caller described the invocation with are assembled into one
        // ([`simulated_integration::simulated_request_of`]), and the integration request
        // carried to an HTTP endpoint is built from it exactly as it is off the wire.
        let simulated_call = simulated_integration::simulated_request_of(
            &verb,
            input
                .path_with_query_string
                .as_deref()
                .filter(|addressed| !addressed.is_empty())
                .unwrap_or(resource_path.as_str()),
            &resource_path,
            &headers.every_value(),
            input
                .body
                .as_deref()
                .unwrap_or_default()
                .as_bytes()
                .to_vec(),
        );
        // The method's own REQUEST VALIDATOR, before the integration is performed: "a
        // RequestValidator ... validates a request before the integration is invoked"
        // (`RequestValidator`), and that holds for a SIMULATED request too — a body the
        // method's `Model` does not admit, or a parameter it declares required and the
        // simulated request omits, is refused with the integration never performed. Both
        // halves are the data plane's own ([`parameters_refusal`], [`pending_body_check`]),
        // so one validator decides a call that reached a socket and one that never did.
        let refused_by_validator = parameters_refusal(&api, Some(&method), &call).or_else(|| {
            pending_body_check(&api, Some(&method), &call)
                .and_then(|pending| pending.refusal(call.payload()))
        });
        let performed = match refused_by_validator {
            Some(refusal) => Err(Refused::Validator(refusal)),
            None => match with_stage_variables(&method, &simulated_variables) {
                // The api's own Region is the endpoint an `AWS` integration naming no Region
                // of its own is called at.
                Ok(resolved) => {
                    // The integration ANSWERS, and the integration's own responses map that
                    // answer to the method response — the same two steps, in the same order,
                    // the data plane takes ([`integration_response::mapped`]), so a
                    // simulated invocation reports what an invoke of the records as they
                    // stand is served. An integration naming an HTTP ENDPOINT is performed
                    // by handing the integration request to THIS EMULATOR, which is the step
                    // the simulated request assembled above is what carries
                    // ([`simulated_integration`]): the endpoint is reached either by
                    // re-entering this plane's own serving or over the in-process transport
                    // the context holds, which dispatches into this process's own router. No
                    // connection is opened, no name is resolved and no address is dialled —
                    // an address this emulator publishes nothing on reaches nothing at all,
                    // and is reported as the integration this api cannot perform.
                    simulated_integration::performed(
                        &*self.engine,
                        ctx,
                        api.arn_region(),
                        &input.rest_api_id,
                        &resolved,
                        &call,
                        &simulated_call,
                    )
                    .await
                        .and_then(|performed| {
                            integration_response::mapped(
                                Some(&resolved),
                                &call,
                                &performed.answer,
                            )
                            .map(|mapped| {
                                (
                                    mapped,
                                    performed.configuration_error,
                                    performed.exchanged_payloads(),
                                )
                            })
                        })
                        .map_err(Refused::Integration)
                }
                Err(unserved) => Err(Refused::Integration(unserved)),
            },
        };
        let (status, body, mut headers, completed) = match performed {
            Ok((served, configuration_error, exchanged)) => {
                let mut headers = served.headers;
                headers.insert(CONTENT_TYPE_HEADER.to_string(), vec![served.content_type]);
                // The two INTEGRATION PHASES of a call that crossed to a BACKEND, which the
                // stage's own execution log records at this very point
                // ([`crate::service::invoke::stage_logs`]): the integration request as the
                // integration's own transformation made it, and the backend's answer as it
                // arrived, before this api's integration responses mapped it. An integration
                // performed from the API's own records crosses neither point.
                if let Some((sent, received)) = exchanged.as_ref() {
                    log.line(crate::service::invoke::stage_logs::traced_payload_line(
                        "Endpoint request body after transformations",
                        sent,
                    ));
                    log.line(crate::service::invoke::stage_logs::traced_payload_line(
                        "Endpoint response body before transformations",
                        received,
                    ));
                }
                // How the execution ENDED, which the log states once the method response it
                // produced has been stated: a backend answer API Gateway could not use is a
                // configuration error of the integration, in the same sentence the stage's own
                // execution log states it in ([`crate::service::invoke::stage_logs`]) — the
                // call WAS performed, so that is what the log says instead of a completed
                // execution.
                let completed = match configuration_error {
                    Some(reason) => {
                        format!("Execution failed due to configuration error: {reason}")
                    }
                    None => "Successfully completed execution".to_string(),
                };
                (served.status, served.body, headers, Some(completed))
            }
            Err(refused) => {
                // The same sentence the data plane logs for this call, and the same gateway
                // response it answers through — including a developer's customization of
                // that response type, which `refusal_rendering` reads off this API.
                let refusal = match refused {
                    Refused::Integration(unserved) => {
                        log.line(format!(
                            "Execution failed due to configuration error: {}",
                            unserved.reason
                        ));
                        unserved.refusal
                    }
                    Refused::Validator(refusal) => {
                        log.line(
                            "Request did not pass the method's request validator, so the \
                             integration was not invoked"
                                .to_string(),
                        );
                        refusal
                    }
                };
                log.line(format!(
                    "Answered through this API's {} gateway response",
                    refusal.response_type()
                ));
                let rendered = refusal_rendering(Some(&api), refusal);
                // The gateway response's own mapped headers reach the REPORT as well as
                // the wire: a developer's customization of the type is what the caller is
                // answered with, whether the call reached a socket or not.
                let mut headers = BTreeMap::from([(
                    CONTENT_TYPE_HEADER.to_string(),
                    vec![JSON_CONTENT_TYPE.to_string()],
                )]);
                for (name, value) in rendered.headers {
                    headers.insert(name, vec![value]);
                }
                // A call the api REFUSED completed no execution: the log already states why
                // it was refused and what it was answered through, which is what ends its
                // account of the execution.
                (rendered.status, rendered.body, headers, None)
            }
        };
        // The tracing header API Gateway attaches to every answer it serves: the trace
        // context of THIS call — the chain it belongs to, the span of its own work and the
        // decision in force — which is how a client correlates the answer it holds with the
        // records of the work downstream of it. A SIMULATED call reaches no stage, so it
        // reaches none that records a trace of its own: the decision is the caller's where
        // the simulated request took one, and "not recorded" where it did not
        // ([`reported_header`]).
        headers.insert(
            TRACE_HEADER.to_string(),
            vec![reported_header(
                supplied_trace.as_deref(),
                false,
                ::std::time::SystemTime::now(),
            )],
        );
        // The METHOD RESPONSE as the caller is answered it, body then headers — the last
        // transformation point of the call, after which the log states how the execution
        // ended and the status it completed with.
        log.line(crate::service::invoke::stage_logs::traced_payload_line(
            "Method response body after transformations",
            &body,
        ));
        // The response headers with their VALUES, where the request-side line above logs
        // names only: a response header is rendered from the API's own records (a static
        // mapping a control-plane call stored), so no caller credential travels in one.
        // That asymmetry is deliberate and is not licence to log a request header's value.
        log.line(format!(
            "Method response headers: [{}]",
            headers
                .iter()
                .map(|(name, values)| format!("{name}={}", values.join(", ")))
                .collect::<Vec<String>>()
                .join(", ")
        ));
        if let Some(completed) = completed {
            log.line(completed);
        }
        log.line(format!("Method completed with status: {status}"));

        Ok(TestInvokeMethodOutput {
            status: i32::from(status),
            // The rendered body as text: `body` is modelled a `String`, and a stored
            // response template is text a caller wrote.
            body: Some(String::from_utf8_lossy(&body).into_owned()),
            // The single-valued view: the FIRST value under each name, which is what a
            // single-valued read of a multi-valued header is.
            headers: Some(
                headers
                    .iter()
                    .filter_map(|(name, values)| {
                        values.first().map(|first| (name.clone(), first.clone()))
                    })
                    .collect::<HashMap<String, String>>(),
            ),
            // The multi-valued view of the same headers: every value each name carries.
            multi_value_headers: Some(
                headers
                    .into_iter()
                    .collect::<HashMap<String, Vec<String>>>(),
            ),
            log: Some(log.rendered()),
            latency: i64::try_from(started.elapsed().as_millis()).unwrap_or(i64::MAX),
        })
    }
}

/// The modelled 400 this operation answers for a request a precondition of the operation
/// refuses, carrying the fixed sentence the service words that condition as.
fn bad_request(message: &str) -> TestInvokeMethodError {
    TestInvokeMethodErrorModeled::BadRequestException(BadRequestException {
        message: Some(message.to_string()),
    })
    .into()
}

/// The modelled 404 this operation answers for an identifier no record of this account
/// carries, worded as every other reader of the same records words it.
fn not_found(message: &str) -> TestInvokeMethodError {
    TestInvokeMethodErrorModeled::NotFoundException(NotFoundException {
        message: Some(message.to_string()),
    })
    .into()
}
