impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for AddFlowOutputs<Eng>
{
    type Input = AddFlowOutputsInput;
    type Output = AddFlowOutputsOutput;
    type Error = AddFlowOutputsError;

    const NAME: &'static str = "AddFlowOutputs";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ADD_FLOW_OUTPUTS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ADD_FLOW_OUTPUTS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 201u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(AddFlowOutputsErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: "the mediaconnect flow store is unavailable".to_string(),
                },
            )
            .into());
        };

        // "A list of outputs that you want to add to the flow": a request that adds no
        // output has nothing to do, which is a semantic error rather than a no-op.
        if input.outputs.is_empty() {
            return Err(bad_request(
                "An add flow outputs request must include at least one output.",
            ));
        }

        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        // The status change the clock already owes this flow is materialised before the
        // flow is read, exactly as the reporting operations do it.
        store.settle_due_transitions(now);

        // This operation adds outputs to "an existing flow", addressed by its own ARN.
        let Some(flow) = store.flows.get(&input.flow_arn) else {
            return Err(not_found(&input.flow_arn));
        };

        // "You can create up to 50 outputs per flow": the ceiling is on the flow, so it
        // counts the outputs already stored plus the ones this call would add.
        let held = flow.outputs.len();
        if held + input.outputs.len() > crate::state::MAX_FLOW_OUTPUTS {
            return Err(cannot_add(format!(
                "A flow can hold at most {} outputs; flow {} already has {held} and this \
                 request adds {}.",
                crate::state::MAX_FLOW_OUTPUTS,
                input.flow_arn,
                input.outputs.len()
            )));
        }

        // NDI needs the larger flow: "set this optional parameter to LARGE if you want to
        // enable NDI sources or outputs on the flow" (`CreateFlowRequest$FlowSize`), so an
        // output using the NDI transport cannot be added to a flow whose size does not
        // carry NDI — the rule, its markers and its wording all read from the one place
        // CreateFlow and UpdateFlow read them from (`crate::state`).
        if let Some((offset, output)) = input
            .outputs
            .iter()
            .enumerate()
            .find(|(_, output)| crate::state::output_request_uses_ndi(output))
        {
            let feature = match output.name.as_deref() {
                Some(name) => format!("The NDI output {name:?}"),
                None => format!("The NDI output at Outputs[{offset}]"),
            };
            if let Some(rejection) =
                crate::state::ndi_flow_size_rejection(&feature, flow.flow_size.as_deref())
            {
                return Err(bad_request(rejection));
            }
        }

        // An output carries a tag member of its own (`AddOutputRequest$OutputTags`) and an
        // ARN of its own, so it is a resource the tagging operations address: its tag map
        // is bounded by the same rules a tag write is (see
        // `crate::state::tag_set_rejection`), checked before anything is stored.
        for (index, output) in input.outputs.iter().enumerate() {
            if let Some(rejection) = crate::state::tag_set_rejection(
                &format!("Outputs[{index}]"),
                output.output_tags.as_ref(),
            ) {
                return Err(bad_request(rejection));
            }
        }

        // An output references the flow's own sub-resources BY NAME: its media stream
        // associations name media streams of this flow
        // (`MediaStreamOutputConfigurationRequest$MediaStreamName`) and its VPC interface
        // attachment names a VPC interface of this flow. Each name is resolved against
        // what the flow actually holds, through the one place this crate resolves such a
        // reference (`crate::state`), BEFORE anything is stored — so a refused request
        // leaves the flow without an association to something it has not got.
        let held_media_streams = flow.media_stream_names();
        let held_vpc_interfaces = flow.vpc_interface_names();
        for (index, output) in input.outputs.iter().enumerate() {
            if let Some(rejection) = crate::state::output_request_reference_rejection(
                &format!("Outputs[{index}]"),
                output,
                &held_media_streams,
                &held_vpc_interfaces,
            ) {
                return Err(bad_request(rejection));
            }
            // `CidrAllowList` is "the range of IP addresses that should be allowed to
            // initiate output requests to this flow", each entry a Classless Inter-Domain
            // Routing (CIDR) block the service has to parse to admit a requester — so an
            // entry that is not a range appends nothing, judged by the one place this
            // crate judges a range of IP addresses, the same one CreateFlow stores an
            // output under.
            if let Some(rejection) = crate::state::cidr_block_list_rejection(
                &format!("Outputs[{index}].CidrAllowList"),
                output.cidr_allow_list.as_deref(),
            ) {
                return Err(bad_request(rejection));
            }
        }

        // An output's name is unique within its flow, so each new output is named
        // against the flow's existing outputs AND against the ones earlier in this
        // request.
        let held_names: BTreeSet<String> = flow.output_names();
        let mut taken = held_names.clone();
        let mut names = Vec::with_capacity(input.outputs.len());
        for request in &input.outputs {
            let Some(name) = crate::state::resolve_output_name(request.name.as_deref(), &taken)
            else {
                let requested = request.name.clone().unwrap_or_default();
                return Err(bad_request(if held_names.contains(&requested) {
                    format!(
                        "Flow {} already has an output named {requested:?}. An output name \
                         must be unique within its flow.",
                        input.flow_arn
                    )
                } else {
                    format!(
                        "This request adds more than one output named {requested:?}. An \
                         output name must be unique within its flow."
                    )
                }));
            };
            taken.insert(name.clone());
            names.push(name);
        }

        // Nothing above wrote anything, so a refused request leaves the flow exactly as
        // it was. From here the whole batch is stored: the validation above borrowed the
        // flow to read it, and the append takes it again mutably, both under the one
        // store lock this call holds.
        let mut added = Vec::with_capacity(input.outputs.len());
        for (request, name) in input.outputs.iter().zip(names) {
            let suffix = store.next_suffix();
            added.push(StoredOutput::from_add_request(
                request, name, &region, suffix,
            ));
        }
        let Some(flow) = store.flows.get_mut(&input.flow_arn) else {
            return Err(AddFlowOutputsErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: "the flow could not be read back while adding its outputs"
                        .to_string(),
                },
            )
            .into());
        };
        let first_added = flow.outputs.len();
        flow.outputs.extend(added);

        // "The details of the newly added outputs" — read back out of the STORED flow,
        // not from the request, and only the outputs this call appended.
        let outputs: Vec<Output> = flow.outputs[first_added..]
            .iter()
            .map(StoredOutput::to_output)
            .collect();
        Ok(AddFlowOutputsOutput {
            flow_arn: Some(flow.flow_arn.clone()),
            outputs: Some(outputs),
        })
    }
}
