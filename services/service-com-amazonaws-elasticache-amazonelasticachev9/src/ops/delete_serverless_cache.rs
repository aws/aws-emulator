impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DeleteServerlessCache<Eng>
{
    type Input = DeleteServerlessCacheInput;
    type Output = DeleteServerlessCacheOutput;
    type Error = DeleteServerlessCacheError;

    const NAME: &'static str = "DeleteServerlessCache";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_SERVERLESS_CACHE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_SERVERLESS_CACHE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::STORE_UNAVAILABLE,
            ));
        };

        // Same identity rule as `CreateServerlessCache`: `ServerlessCacheName`
        // "is stored as a lowercase string", so the cache this request resolves
        // is the one stored under the lowercased name.
        let name = input.serverless_cache_name.to_ascii_lowercase();
        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();

        // `FinalSnapshotName` is the "name of the final snapshot to be taken
        // before the serverless cache is deleted", so it names a snapshot this
        // call MINTS and is held to the same rules
        // `CreateServerlessCacheSnapshot` holds one to, in the same order: the
        // name's form first, then the store's own rule about storing a snapshot
        // under it (`serverless_cache_snapshot_refusal`) — the name being free,
        // and the store not being at its quota. This operation models a fault
        // only for the first, so the bound is reported as the value this call
        // cannot accept.
        let final_snapshot_name = match input.final_snapshot_name.as_deref() {
            Some(requested) => {
                let snapshot_name = requested.to_ascii_lowercase();
                if !crate::state::is_valid_snapshot_name(&snapshot_name) {
                    return Err(invalid_value(format!(
                        "Invalid value {requested} for FinalSnapshotName: a name must contain \
                         from 1 to 255 alphanumeric characters or hyphens."
                    )));
                }
                match store.serverless_cache_snapshot_refusal(&snapshot_name) {
                    Some(crate::state::ServerlessSnapshotRefusal::AlreadyExists(message)) => {
                        return Err(
                            DeleteServerlessCacheErrorModeled::ServerlessCacheSnapshotAlreadyExistsFault(
                                ServerlessCacheSnapshotAlreadyExistsFault {
                                    message: Some(message),
                                },
                            )
                            .into(),
                        )
                    }
                    Some(crate::state::ServerlessSnapshotRefusal::QuotaExceeded(message)) => {
                        return Err(invalid_value(format!(
                            "Invalid value {requested} for FinalSnapshotName: {message}"
                        )))
                    }
                    None => {}
                }
                Some(snapshot_name)
            }
            None => None,
        };

        // A cache whose removal the clock has already carried through is gone,
        // and one that has become `AVAILABLE` since it was created is available
        // now: the record read below is the one this instant owes.
        let Some(cache) = store.settled_serverless_cache_mut(&name, now) else {
            // The fault names the cache the request asked for, which is all the
            // service knows about one that does not exist.
            return Err(
                DeleteServerlessCacheErrorModeled::ServerlessCacheNotFoundFault(
                    ServerlessCacheNotFoundFault {
                        message: Some(format!(
                            "Serverless cache with name {} not found.",
                            input.serverless_cache_name
                        )),
                    },
                )
                .into(),
            );
        };

        // A cache is deletable only from its settled, usable status: one still
        // `CREATING`, or already `DELETING` from an earlier call, is refused with
        // the modelled state fault rather than deleted twice.
        if cache.status != crate::state::SERVERLESS_STATUS_AVAILABLE {
            return Err(
                DeleteServerlessCacheErrorModeled::InvalidServerlessCacheStateFault(
                    InvalidServerlessCacheStateFault {
                        message: Some(format!(
                            "Serverless cache {name} is in {} state, not {}.",
                            cache.status,
                            crate::state::SERVERLESS_STATUS_AVAILABLE
                        )),
                    },
                )
                .into(),
            );
        }

        // The final snapshot is taken of the cache as it stands NOW, before the
        // delete begins: "the final snapshot to be taken before the serverless
        // cache is deleted", which is its configuration AND its data set. It
        // outlives the cache — the data set is the snapshot's own copy
        // (`crate::state::captured_serverless_cache_data`), so closing the
        // cache's socket below does not take it away — and a later
        // `DescribeServerlessCacheSnapshots` still reports it.
        let source = cache.clone();
        let final_snapshot = final_snapshot_name.map(|snapshot_name| {
            crate::state::ServerlessCacheSnapshotRecord::from_cache(
                &source,
                crate::state::NewServerlessCacheSnapshot {
                    name: snapshot_name,
                    // This request names no KMS key and no tags of its own, so
                    // the snapshot carries the source cache's key and no tags.
                    kms_key_id: None,
                    data: crate::state::captured_serverless_cache_data(&store, &name, now),
                    tags: Vec::new(),
                    now,
                },
            )
        });

        // The cache is leaving: it answers `DELETING` now, and the clock owes its
        // removal, so a caller reading it straight after this call still sees it
        // going away and a later one sees it gone.
        let Some(cache) = store.serverless_caches.get_mut(&name) else {
            // Unreachable: resolved under this same lock above.
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::STORE_UNAVAILABLE,
            ));
        };
        cache.begin_deletion(now);
        let serverless_cache = cache.to_modeled();
        if let Some(record) = final_snapshot {
            let stored = store.insert_serverless_cache_snapshot(record);
            let snapshot_name = stored.name.clone();
            store.record_event(
                crate::state::SOURCE_TYPE_SERVERLESS_CACHE_SNAPSHOT,
                &snapshot_name,
                "Serverless cache snapshot created",
                now,
            );
        }
        // Deleting a serverless cache is one of the events this service records;
        // see `crate::state::EventRecord`. The log outlives the record, so the
        // events of a deleted cache are still reported.
        store.record_event(
            crate::state::SOURCE_TYPE_SERVERLESS_CACHE,
            &name,
            "Serverless cache deleted",
            now,
        );
        // The socket this cache was served on closes with it: dropping the handle
        // closes the port and severs every connection on it, so a client cannot
        // keep reaching a cache that is going away.
        crate::state::close_serverless_cache_data_plane(&mut store, &name);

        Ok(DeleteServerlessCacheOutput {
            serverless_cache: Some(serverless_cache),
        })
    }
}

