        // ask conflicts with the state the asset is in.
        if asset.transfer_in_progress() {
            return Err(UpdateAssetOwnerErrorModeled::ConflictException(ConflictException {
                message: transfer_in_progress_message(
                    &asset.id,
                    "transferred to another project",
                ),
            })
            .into());
        }

        // "The project must be in the same domain and must be different from the project
        // that currently owns the asset": the target is resolved inside THIS domain, so a
        // project of another domain names no project the request can transfer to.
        let target = domain
            .projects
            .get(&input.target_project_identifier)
            .ok_or_else(|| {
                UpdateAssetOwnerErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: ResourceKind::Project.not_found_message(),
                    },
                )
            })?;
        if target.id == asset.owning_project_id {
            return Err(UpdateAssetOwnerErrorModeled::ValidationException(ValidationException {
                message: format!(
                    "targetProjectIdentifier {} already owns asset {}",
                    target.id, asset.id
                ),
            })
            .into());
        }
        // A project on its way out cannot be given an asset: the ask conflicts with the
        // state that project is in (the rule `CreateAssetRevision` applies to the project
        // that owns the asset being revised).
        if target.project_status != PROJECT_STATUS_ACTIVE {
            return Err(UpdateAssetOwnerErrorModeled::ConflictException(ConflictException {
                message: format!(
                    "Project {} is {}, so it cannot take ownership of an asset",
                    target.id, target.project_status
                ),
            })
            .into());
        }

        // "You need to be an owner of the project that currently owns the asset": the
        // permission is held through that project, so a caller that does not own it is
        // denied — and an asset whose owning project this domain no longer holds has no
        // owner to ask.
