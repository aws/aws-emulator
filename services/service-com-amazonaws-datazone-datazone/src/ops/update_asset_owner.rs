        // there; the status it carries is what decides whether it can take a transfer.
        let domain = store.domains.get(&input.domain_identifier).ok_or_else(|| {
            UpdateAssetOwnerErrorModeled::InternalServerException(InternalServerException {
                message: "the DataZone store lost the domain mid-request".to_string(),
            })
        })?;
        // A domain still being created, or already being deleted, cannot take a transfer:
        // the request conflicts with the domain's current state (the rule
        // `CreateAssetRevision` applies to a revision in that domain).
        if domain.status != DOMAIN_STATUS_AVAILABLE {
            return Err(UpdateAssetOwnerErrorModeled::ConflictException(ConflictException {
                message: format!(
                    "Domain {} is {}, so it cannot accept an asset ownership transfer",
                    input.domain_identifier, domain.status
                ),
            })
            .into());
        }

        // "The ID of the asset whose ownership is transferred": the asset is stored under
        // the `AssetId` that IS the identifier addressing it, so the lookup is the one
        // `GetAsset` makes.
        let asset = domain.assets.get(&input.identifier).ok_or_else(|| {
            UpdateAssetOwnerErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                message: ResourceKind::Asset.not_found_message(),
            })
        })?;

