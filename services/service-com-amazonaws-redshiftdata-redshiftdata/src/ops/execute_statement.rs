impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ExecuteStatement<Eng>
{
    type Input = ExecuteStatementInput;
    type Output = ExecuteStatementOutput;
    type Error = ExecuteStatementError;

    const NAME: &'static str = "ExecuteStatement";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_STATEMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_STATEMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(unavailable());
        };

        // A statement runs against exactly one data warehouse, one database and
        // one authorization method, which `ConnectionRequest::resolve` is the
        // single place that decides for every submit operation. The
        // session-reuse form, where a caller that already holds a `SessionId`
        // names neither warehouse, carries its connection on the SESSION, so it
        // is resolved from the session store instead of from the request.
        let requested = ConnectionRequest {
            cluster_identifier: input.cluster_identifier.as_ref(),
            workgroup_name: input.workgroup_name.as_ref(),
            session_id: input.session_id.as_ref(),
            database: input.database.as_ref(),
            db_user: input.db_user.as_ref(),
            secret_arn: input.secret_arn.as_ref(),
        };
        let connection = match requested.resolve() {
            Ok(connection) => connection,
            Err(BadConnection::SessionOnly) => {
                let session = non_empty(input.session_id.as_ref()).unwrap_or_default();
                match state.lock().session_connection(&session) {
                    Some(connection) => connection,
                    // A `SessionId` that names no live session names no
                    // warehouse and no database either, so there is nothing to
                    // run the statement on: a missing resource, not a malformed
                    // request.
                    None => return Err(no_such_session(&session)),
                }
            }
            Err(problem) => {
                // How a request SELECTS its target, and whether it names a
                // database and one authorization method, are faults of the
                // REQUEST: they are reported as they stand, before any cluster,
                // workgroup or session is resolved, so a request that selected
                // two targets is told exactly that whatever either of them
                // resolves to.
                return Err(validation(&problem.message(SELECTORS)));
            }
        };

        if input.sql.trim().is_empty() {
            return Err(validation("Sql must contain a SQL statement"));
        }

        // Parameters are bound BY NAME, so the request only makes sense when
        // the names it supplies are the names its statement references: the two
        // are resolved against each other here, while the submit is still being
        // answered, so a mismatch is reported to the caller that wrote it rather
        // than discovered later as a statement that failed.
        //
        // Reading the statement's tokens is bounded but BLOCKING work on the
        // caller's own text, so it runs on the blocking pool — where this
        // operation runs the engine itself — and never on an async worker.
        let parameters = input.parameters.clone().unwrap_or_default();
        let resolved = {
            let statements = vec![input.sql.clone()];
            let parameters = parameters.clone();
            tokio::task::spawn_blocking(move || {
                crate::state::sql_parameters::resolve(&statements, &parameters)
            })
            .await
        };
        match resolved {
            Ok(Ok(())) => {}
            Ok(Err(mismatch)) => return Err(validation(&mismatch.message())),
            // The resolution itself failed to run, which says nothing about the
            // request: a server fault, never an accepted submission.
            Err(_joined) => return Err(unavailable()),
        }

        // A statement runs on an ENDPOINT, so the target it selected is resolved
        // against the service that owns it before the statement is admitted: a
        // cluster or workgroup that does not exist in this Region has no
        // endpoint to run on, whatever the request asks for. A target the owner
        // could not be asked about is UNDECIDED, and is admitted rather than
        // refused on the strength of a peer that did not answer.
        //
        // The same answer carries the databases that warehouse holds, which is
        // what the statement's `Database` is resolved against below.
        let warehouse = crate::state::warehouse::describe_target(ctx, &connection.target).await;
        if warehouse.resolution == crate::state::warehouse::TargetResolution::Absent {
            return Err(validation(ABSENT_ENDPOINT_MESSAGE));
        }

        // The parameter values that warehouse's ENGINE is running with, read
        // from the same owner in the same round: a statement that reports a
        // parameter, and the workload manager that assigns a labelled query to a
        // queue, both read the values in force on the cluster rather than
        // anything this service decided.
        let engine_settings =
            crate::state::warehouse::engine_settings(ctx, &connection.target).await;

        // A `Database` is NOT a synchronous rejection: the Data API accepts the
        // submission and the connection to the database is made when the
        // statement runs, so a database the warehouse has none of is a statement
        // that FAILS with the backend's own fatal line. Decided here, where the
        // owner's answer is, and carried out by the statement's own execution.
        let absent_database = {
            let mut store = state.lock();
            // What the owner reports the warehouse holds belongs in this
            // service's catalogue of it, beside the databases callers created.
            store.hold_databases(&connection.target, &warehouse.provisioned_databases);
            warehouse.decides_database_absent(
                &store.database_names(&connection.target),
                &connection.database,
            )
        };
        // The database the statement connects to, read before the submission
        // takes it, so a connection that fails can name it.
        let connection_database = connection.database.clone();

        let client_token = non_empty(input.client_token.as_ref());

        // An idempotent replay answers with the statement the first call
        // submitted, read back out of state — it never submits a second one. A
        // token that names a BATCH submission is not a replay of one statement,
        // so it is not answered as one. The replayed statement's own text and
        // parameters are re-recorded from THIS request, which is what the
        // service reports for a token replayed with a different one.
        if let Some(token) = client_token.as_deref() {
            let mut store = state.lock();
            store.materialise_due_transitions();
            let replayed = store
                .statement_id_for_client_token(token)
                .map(str::to_string)
                .filter(|id| {
                    store
                        .statement(id)
                        .is_some_and(|statement| !statement.is_batch)
                });
            if let Some(id) = replayed {
                store.rewrite_submitted_sql(&id, std::slice::from_ref(&input.sql), &parameters);
                if let Some(output) = store.statement(&id).map(output_for) {
                    return Ok(output);
                }
            }
        }

        // `SessionKeepAliveSeconds` asks for a session, which the Data API
        // identifies with a UUID it generates; `SessionId` names one a previous
        // statement opened. Both are recorded by the state store when the
        // statement is recorded, so the `SessionId` a statement reports is one
        // this service really holds.
        let session_id = non_empty(input.session_id.as_ref());
        if let Some(session) = session_id.as_deref() {
            // A statement submitted into a session that no longer exists, or
            // that the clock has closed, has no session to run in.
            if state.lock().session_connection(session).is_none() {
                return Err(no_such_session(session));
            }
        }

        // What the statement may reach BEYOND its own database: Amazon S3, IAM
        // and the Data Catalog as this engine holds them, together with the
        // facts about the warehouse it runs on. Resolved here, because the
        // execution runs on a blocking pool where there is no request to ask
        // anything over.
        let facts = crate::state::data_plane::StatementFacts {
            region: crate::state::warehouse::request_region(ctx),
            warehouse: connection
                .target
                .cluster_identifier()
                .or_else(|| connection.target.workgroup_name())
                .unwrap_or_default(),
            database: connection.database.clone(),
            user: connection.db_user.clone().unwrap_or_default(),
            // Filled in below from the record this submission is accepted as:
            // the backend process a statement runs under is the one the service
            // reports for it.
            pid: 0,
            settings: engine_settings,
        };

        let submission = Submission {
            statements: vec![input.sql.clone()],
            kind: SubmissionKind::Single,
            target: connection.target,
            database: connection.database,
            db_user: connection.db_user,
            secret_arn: connection.secret_arn,
            statement_name: non_empty(input.statement_name.as_ref()),
            parameters: parameters.clone(),
            with_event: input.with_event.unwrap_or(false),
            // Where the statement ran, who submitted it and the warehouse it
            // ran on: recorded with the statement, because an event about it is
            // published in that Region, names that principal and names that
            // warehouse, and the task that publishes it has no request.
            region: crate::state::warehouse::request_region(ctx),
            principal: crate::state::statement_events::submitting_principal(),
            resource_arn: warehouse.arn.clone(),
            // "If no format is specified, the default is JSON."
            result_format: non_empty(input.result_format.as_ref())
                .unwrap_or_else(|| "JSON".to_string()),
            session_id,
            session_keep_alive_seconds: input.session_keep_alive_seconds,
            client_token,
        };

        // The engine bounds its own execution: a wall-clock deadline and a step
        // budget, enforced by its progress handler. The bound belongs to THIS
        // execution, and the statement keeps the handle that abandons it, so
        // `CancelStatement` stops this statement's work and never another's.
        let engine_timeout = crate::state::engine_timeout();
        let bound = crate::state::ExecutionBound::new();

        // Admitted, given a place in its database's queue and recorded as
        // SUBMITTED under ONE state lock, which is then RELEASED: the `Id` this
        // call answers with names a statement the service holds from here on —
        // so a caller can poll it, cancel it or read its result whatever
        // happens to this request — and the SQL runs on a blocking pool with
        // only its own database's lock held, so a slow statement starves no
        // async worker and serialises no other caller.
        let (reserved, id, accepted, scope) = {
            let mut store = state.lock();
            store.materialise_due_transitions();
            // Every accepted submission runs independently of this request, so
            // how many of them are in flight is what this service's
            // active-statement limit bounds. Asked BEFORE anything is reserved
            // for this one, and in the same lock that records it, so a refused
            // submission reserves nothing and an admitted one cannot race past
            // the limit.
            if store.active_statements() >= crate::state::MAX_ACTIVE_STATEMENTS {
                return Err(
                    ExecuteStatementErrorModeled::ActiveStatementsExceededException(
                        ActiveStatementsExceededException {
                            message: Some(format!(
                                "the number of active statements exceeds the limit of {}",
                                crate::state::MAX_ACTIVE_STATEMENTS
                            )),
                        },
                    )
                    .into(),
                );
            }
            // A statement whose database the warehouse has none of gets no
            // engine: opening one would ADD that database to the warehouse,
            // which is exactly what the caller's typo must not do. It is
            // recorded against a connection of its own, which is the backend
            // that answers it with the fatal line.
            let (reserved, id) = if absent_database {
                let pid = store.mint_pid();
                let id = store.record_pending(submission, pid, bound.interrupt());
                (None, id)
            } else {
                let (handle, pid, slot) =
                    match store.reserve_database(&submission.target, &submission.database) {
                        Ok(reserved) => reserved,
                        // A capacity limit of this emulator, not a malformed
                        // request, so it is answered with the modelled capacity
                        // error rather than a ValidationException that would tell
                        // the client its ClusterIdentifier or Database was wrong.
                        Err(NoDatabase::TooManyOpen(limit)) => {
                            return Err(
                                ExecuteStatementErrorModeled::ActiveStatementsExceededException(
                                    ActiveStatementsExceededException {
                                        message: Some(format!(
                                            "this emulator holds at most {limit} databases at \
                                             once; no further \
                                             ClusterIdentifier/WorkgroupName and Database \
                                             combination can be opened"
                                        )),
                                    },
                                )
                                .into(),
                            )
                        }
                        Err(NoDatabase::EngineUnavailable(reason)) => {
                            return Err(ExecuteStatementErrorModeled::InternalServerException(
                                InternalServerException {
                                    message: format!(
                                        "the SQL engine could not open the database for this \
                                         statement: {reason}"
                                    ),
                                },
                            )
                            .into())
                        }
                    };
                let id = store.record_pending(submission, pid, bound.interrupt());
                (Some((handle, slot)), id)
            };
            // The answer to THIS request, read out of the record this request
            // just wrote and while the lock that wrote it is still held: the
            // submission as it was accepted, which is SUBMITTED — "the query was
            // submitted, but not yet processed". A request that asked to wait
            // reads the record again once its wait is up; one that asked for no
            // wait is answered with this, so what it reports can never depend on
            // how far the execution handed over below happened to get while the
            // response was being written.
            let accepted = store.statement(&id).map(output_for);
            // The CONNECTION this submission's statements run on: the session
            // they reuse, or one of their own. It carries the temporary
            // relations that connection holds, so a statement of a session
            // resolves what an earlier one of the same session created and a
            // statement on any other connection cannot.
            let scope = store.connection_scope(&id);
            (reserved, id, accepted, scope)
        };

        let sql = input.sql.clone();

        // The data plane the statement runs against, carrying the backend
        // process id this submission was accepted under.
        let plane = crate::state::data_plane::DataPlane::resolve(
            &*self.engine,
            crate::state::data_plane::StatementFacts {
                pid: accepted
                    .as_ref()
                    .and_then(|output| output.redshift_pid)
                    .unwrap_or_default(),
                ..facts
            },
        );

        // The execution is the statement's, not the request's: it runs to a
        // terminal status on its own, so two statements submitted at once are
        // really concurrent and neither depends on the caller's patience. The
        // statement's outcome is written back by the task that produced it, and
        // dropping the queue slot at the end hands the database on.
        let engine = ::std::sync::Arc::clone(&self.engine);
        let recorded = id.clone();
        let absent = connection_database.clone();
        // The callback this request was served over, carried into the execution:
        // a statement that asked for an event is published when it STOPS, which
        // happens inside that execution and not inside this request.
        let callback = ctx.callback().clone();
        let execution = tokio::spawn(async move {
            let Some((handle, slot)) = reserved else {
                // No connection was ever made, so nothing ran: the statement
                // fails with what the backend answers a connection to a
                // database that is not there.
                if let Some(state) = crate::state::service_state(&*engine) {
                    state.lock().complete(
                        &recorded,
                        crate::state::connection_failures(
                            1,
                            &crate::state::warehouse::absent_database_message(&absent),
                        ),
                    );
                }
                crate::state::statement_events::publish_pending(&callback, &*engine).await;
                return;
            };
            let mut slot = Some(slot);
            if let Some(slot) = slot.as_mut() {
                slot.wait_for_turn().await;
            }
            // The submission's turn on its database is now its: the query "has
            // been chosen to be run".
            if let Some(state) = crate::state::service_state(&*engine) {
                state.lock().pick(&recorded);
            }
            // A lock another connection holds inside an open transaction is one
            // this statement has to wait for: it stays non-terminal while it
            // waits, so a caller polling it sees it running and can cancel it.
            // The wait hands its turn on the database on and takes a new one
            // afterwards, so the connection holding the lock can release it.
            match crate::state::await_lock_release(
                &engine,
                &recorded,
                vec![sql.clone()],
                &scope,
                &bound,
                &mut slot,
            )
            .await
            {
                crate::state::LockWait::Free => {}
                // Cancelled while it waited: the record already reports ABORTED
                // and nothing ran, so there is no outcome to write.
                crate::state::LockWait::Abandoned => {
                    crate::state::statement_events::publish_pending(&callback, &*engine).await;
                    return;
                }
                crate::state::LockWait::GaveUp(message) => {
                    if let Some(state) = crate::state::service_state(&*engine) {
                        state
                            .lock()
                            .complete(&recorded, crate::state::connection_failures(1, &message));
                    }
                    crate::state::statement_events::publish_pending(&callback, &*engine).await;
                    return;
                }
            }
            if let Some(slot) = slot.as_mut() {
                slot.wait_for_turn().await;
            }
            let running = ::std::sync::Arc::clone(&engine);
            let started = recorded.clone();
            let produced = tokio::task::spawn_blocking(move || {
                // STARTED from here: the engine is about to run this
                // statement's work, and it reports STARTED for as long as that
                // really takes.
                if let Some(state) = crate::state::service_state(&*running) {
                    state.lock().start(&started);
                }
                vec![crate::state::run_on(
                    &handle,
                    &sql,
                    &parameters,
                    engine_timeout,
                    &bound,
                    &scope,
                    &plane,
                )]
            })
            .await
            .unwrap_or_else(|_panicked| crate::state::unreported_executions(1));
            if let Some(state) = crate::state::service_state(&*engine) {
                state.lock().complete(&recorded, produced);
            }
            drop(slot);
            // The statement has stopped, so the status change a submission that
            // asked for an event is owed is published here — by the execution
            // itself, so it reaches the bus whether or not anybody polls.
            crate::state::statement_events::publish_pending(&callback, &*engine).await;
        });

        // "The number of seconds to wait for the SQL statement to complete
        // execution before returning the response. If the SQL statement does not
        // complete within the specified time, the response returns the current
        // status": a caller that named a wait waits here and is then answered
        // with the status the statement has reached. A caller that named none
        // waits for NOTHING, so it is answered with the submission as this
        // request accepted it.
        let Some(budget) = crate::state::wait_budget(input.wait_time_seconds) else {
            return accepted.ok_or_else(unavailable);
        };
        let _ = tokio::time::timeout(budget, execution).await;

        let mut store = state.lock();
        store.materialise_due_transitions();
        let Some(statement) = store.statement(&id) else {
            return Err(unavailable());
        };
        Ok(output_for(statement))
    }
}

/// The response, assembled from the stored statement — never from the request.
fn output_for(statement: &Statement) -> ExecuteStatementOutput {
    ExecuteStatementOutput {
        id: Some(statement.id.clone()),
        created_at: Some(to_timestamp(statement.created_at)),
        cluster_identifier: statement.target.cluster_identifier(),
        db_user: statement.db_user.clone(),
        // Redshift derives `DbGroups` from the database user's group
        // membership, which this emulator does not model, so no groups are
        // reported rather than an invented list.
        db_groups: None,
        database: statement.database.clone(),
        secret_arn: statement.secret_arn.clone(),
        workgroup_name: statement.target.workgroup_name(),
        session_id: statement.session_id.clone(),
        status: Some(statement.status.as_str().to_string()),
        redshift_pid: Some(statement.redshift_pid),
        has_result_set: statement.has_result_set(),
    }
}

/// Refuse the request as invalid, with the `ValidationException` this operation
/// models.
fn validation(message: &str) -> ExecuteStatementError {
    ExecuteStatementErrorModeled::ValidationException(ValidationException {
        message: Some(message.to_string()),
    })
    .into()
}

/// The state store could not be reached — a server fault, not a client error.
fn unavailable() -> ExecuteStatementError {
    ExecuteStatementErrorModeled::InternalServerException(InternalServerException {
        message: "the Redshift Data API state store is unavailable".to_string(),
    })
    .into()
}

/// Refuse a `SessionId` that names no live session: a session this service does
/// not hold, or one the clock has closed, which "can no longer run SQL
/// statements".
///
/// The fixed words the Data API states for a session it holds none of
/// ([`UNKNOWN_SESSION_MESSAGE`]) — no part of the id reaches the message —
/// carried by the missing-resource error at the status its `@httpError`
/// declares, which is the status this path answers.
fn no_such_session(session_id: &str) -> ExecuteStatementError {
    ExecuteStatementErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
        message: UNKNOWN_SESSION_MESSAGE.to_string(),
        resource_id: session_id.to_string(),
    })
    .into()
}
