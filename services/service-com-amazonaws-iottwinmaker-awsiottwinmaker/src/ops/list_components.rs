/// One component in the listed scope: a TOP-LEVEL component of the entity, or a
/// COMPOSITE component inside one of them. Both are reported as the same
/// modelled `ComponentSummary`, and both are named by their own `Name`, which is
/// what this listing orders and resumes by.
///
/// A composite component is carried as a [`::std::borrow::Cow`] because a level
/// of the tree may report a path STEP that was never created itself — the walk
/// reports one entry per next path segment the entity holds a composite
/// component at or beneath, and only the created ones are records the store can
/// lend out.
enum Listed<'a> {
    Component(&'a crate::state::ComponentRecord),
    Composite(::std::borrow::Cow<'a, crate::state::CompositeComponentRecord>),
}

impl Listed<'_> {
    /// The component's own name: what the summary reports as `componentName`,
    /// and the key this listing pages by.
    fn name(&self) -> &str {
        match self {
            Self::Component(component) => component.component_name.as_str(),
            Self::Composite(composite) => composite.component_name.as_str(),
        }
    }

    /// This component as the modelled `ComponentSummary`, built from the stored
    /// record with `status` — the holding entity's, since a component has none
    /// of its own.
    ///
    /// `propertyGroups` and `definedIn` are resolved against `workspace` the
    /// same way `GetEntity` resolves them for the same component: naming a
    /// `componentTypeId` is what gives a component that type's groups, so a
    /// group the entity never restated is reported here too and marked
    /// `isInherited`, and `definedIn` names the component type the inherited
    /// definition set came from. `syncSource` is absent for the reason
    /// `GetEntity` omits it: an entity this service created is not projected
    /// from a linked service.
    fn summary(&self, workspace: &crate::state::Workspace, status: &Status) -> ComponentSummary {
        match self {
            Self::Component(component) => ComponentSummary {
                component_name: component.component_name.clone(),
                // The component type the component INSTANTIATES, which every
                // writer of a component requires it to name
                // (`crate::state::component_type_id_required_message`): the
                // summary's `componentTypeId` is `@required` and bounded
                // `@length(min: 1, max: 256)` with
                // `@pattern(^[a-zA-Z_\.\-0-9:]+$)`, so the stored id is what
                // this row reports and there is nothing else it could be.
                component_type_id: component.component_type_id.clone(),
                defined_in: workspace
                    .component_defined_in(Some(&component.component_type_id)),
                description: component.description.clone(),
                property_groups: Some(property_groups(
                    workspace,
                    Some(&component.component_type_id),
                    &component.property_groups,
                )),
                status: status.clone(),
                sync_source: None,
                // Absent for a top-level component: `componentPath` is the path
                // to a COMPOSITE component "starting from the top-level
                // component", so it is what identifies one of those, while a
                // top-level component is identified by its name alone — the same
                // split `GetEntity` reports.
                component_path: None,
            },
            Self::Composite(composite) => ComponentSummary {
                component_name: composite.component_name.clone(),
                component_type_id: composite.component_type_id.clone(),
                defined_in: workspace.component_defined_in(Some(&composite.component_type_id)),
                description: composite.description.clone(),
                property_groups: Some(property_groups(
                    workspace,
                    Some(&composite.component_type_id),
                    &composite.property_groups,
                )),
                status: status.clone(),
                sync_source: None,
                // The whole path that addresses this composite component,
                // which is what a caller walks one level deeper with.
                component_path: Some(composite.component_path.clone()),
            },
        }
    }
}

