impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Every call is recorded, successful or refused: the real service logs
        // control-plane access, and this one mutates tenant state.
        ::tracing::info!(
            operation = "TagResource",
            resource_arn = %input.resource_arn,
            tag_count = input.tags.len(),
            "serving a request"
        );
        // The Region this request is signed for picks the store it acts on: an
        // ARN minted in another Region names no resource here, so a
        // cross-Region ARN is a resource this Region does not hold.
        let region = crate::state::request_region(ctx.parts());

        // The reserved namespace is AWS's own, so a key under it is not one this
        // call may write — decided on the request alone, before the store is
        // reached, and over the WHOLE batch, so a request mixing a legal key with
        // a reserved one applies neither. The reason names the keys at fault, as
        // many as the request carried, and the construction that builds it is
        // what states it within the bound of the member it travels on — as the
        // miss below is, which names a resource by an ARN the model bounds as
        // widely as that member itself.
        if let Some(message) = crate::state::reserved_tag_keys_violation(
            "tags",
            input.tags.keys().map(String::as_str),
        ) {
            return Err(TagResourceErrorModeled::ValidationException(ValidationException {
                message: Some(message),
            })
            .into());
        }

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalServerException(InternalServerException {
                message: Some("the iottwinmaker store is unavailable".to_string()),
            })
        })?;
        let mut state = state.lock();
        let state = state.region_mut(&region);

        let resource_arn = input.resource_arn;
        let Some(tags) = state.tags_for_resource_mut(&resource_arn) else {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::resource_not_found_message(&resource_arn)),
                },
            )
            .into());
        };

        // Only a key the resource does not already carry grows its tag set, so
        // rewriting the value of a key it has can never exceed the quota however
        // many of them the request names.
        let added = input
            .tags
            .keys()
            .filter(|key| !tags.contains_key(key.as_str()))
            .count();
        let resulting = tags.len() + added;
        // Past the per-resource tag quota the refusal is the QUOTA one: the
        // request is inside the per-call bound, so telling the caller to shrink
        // it would not help — what it has to do is untag the resource or stop
        // tagging it. The quota breach names no value of the request, so the
        // message is empty.
        if crate::state::tags_per_resource_quota_exceeded(resulting) {
            return Err(TagResourceErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: Some(String::new()),
                },
            )
            .into());
        }

        for (key, value) in input.tags {
            tags.insert(key, value);
        }

        Ok(TagResourceOutput {})
    }
}
