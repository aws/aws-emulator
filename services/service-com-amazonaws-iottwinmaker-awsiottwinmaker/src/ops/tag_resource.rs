//! @op TagResource
//!
//! Adds tags to the resource a `TwinMakerArn` names, as an UPSERT on the tag set
//! that resource already holds: a key the resource does not carry is added, a key
//! it does carry has its value replaced, and every other tag is left alone. The
//! tags live on the resource record itself — the ARN index says which record an
//! ARN points at — so `ListTagsForResource` reads back exactly what this wrote.
//!
//! A tag key in the reserved `aws:` namespace
//! ([`crate::state::RESERVED_TAG_KEY_PREFIX`], matched however it is cased) is not a
//! key a caller owns, so a call naming one is refused with `ValidationException`
//! (HTTP 400) and NONE of the batch is applied — a legal key sharing the request
//! with a reserved one is not stored either.
//!
//! An ARN that names no stored resource is refused with `ResourceNotFoundException`
//! (HTTP 404). A call that would leave the resource carrying more than
//! [`crate::state::MAX_TAGS_PER_RESOURCE`] tags breaches the service's
//! "Tags per resource" QUOTA and is refused with `ServiceQuotaExceededException`
//! (HTTP 402) carrying an empty message — decided BEFORE anything is stored, so a
//! refused call changes nothing. That is the only tag-count failure THIS handler
//! decides: a request naming more tags than the `TagMap` shape itself admits
//! breaches a modelled `@length` bound, which the centralized request walk
//! refuses before `handle` is reached.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `TagResource::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! ## Reaching this service's state
//!
//! The engine is held on `self` (constructor-injected), NOT passed per request — so
//! engine access is guaranteed by the time any request runs. Reach the store through
//! [`crate::state::service_state`] and read and write it through the guard it hands back:
//!
//! ```ignore
//!     let state = crate::state::service_state(&*self.engine)
//!         .ok_or(/* a modelled server error */)?;
//!     state.lock().your_field = /* ... */;
//! ```
//!
//! `ctx` ([`smithy_server_runtime::OperationContext`]) carries request metadata only —
//! headers, URI, method, and anything middleware placed in `ctx.parts().extensions`.
//! The engine is NOT reached through `ctx`.
