fn decode_next_token(
    token: &str,
    region: &str,
    source_type: &str,
    destination_type: &str,
    filters_scope: &str,
) -> Option<String> {
    crate::state::decode_page_token(
        NEXT_TOKEN_PREFIX,
        region,
        &[source_type, destination_type, filters_scope],
        token,
    )
}
