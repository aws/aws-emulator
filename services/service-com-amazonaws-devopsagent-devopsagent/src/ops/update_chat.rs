impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateChat<Eng>
{
    type Input = UpdateChatInput;
    type Output = UpdateChatOutput;
    type Error = UpdateChatError;

    const NAME: &'static str = "UpdateChat";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CHAT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CHAT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            UpdateChatErrorModeled::InternalServerException(InternalServerException {
                message: "the DevOps Agent state store is unavailable".to_string(),
            })
        })?;

        let mut store = state.lock();
        let now = ::std::time::SystemTime::now();

        // `@idempotencyToken`: "If this token matches a previous request, the service
        // ignores the request, but does not return an error" — so a repeat with the
        // token the first update carried reports the chat as it stands and applies
        // nothing a second time.
        //
        // A token matches a PREVIOUS REQUEST, and the chat a request names is part of
        // it: the same token presented for another chat execution is a different
        // request, so it applies and the token comes to name that chat instead.
        let replayed = input
            .client_token
            .as_deref()
            .and_then(|token| store.replayed_id(Self::NAME, token, now))
            .is_some_and(|execution_id| execution_id == input.execution_id);

        // A chat execution is reachable only through the agent space that owns it, and
        // the caller is authorised against that space before anything inside it can be
        // known, so an `agentSpaceId` that resolves to no space fails CLOSED rather
        // than disclosing which spaces exist; only inside a space the caller reached is
        // a missing chat reported as one.
        let space = store
            .agent_spaces
            .get_mut(&input.agent_space_id)
            .ok_or_else(|| {
                UpdateChatErrorModeled::AccessDeniedException(AccessDeniedException {
                    message: crate::state::ACCESS_DENIED_MESSAGE.to_string(),
                })
            })?;
        let chat = space.chats.get_mut(&input.execution_id).ok_or_else(|| {
            UpdateChatErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                message: crate::state::chat_not_found_message(&input.execution_id),
            })
        })?;

        // Archiving "hides it from the default chat list", and unarchiving "restores
        // it to the default chat list": while a chat is hidden, the only change it
        // accepts is the one that restores it, so any other request acts on an
        // archived chat and conflicts with the state it is in — which is exactly what
        // the modelled `CHAT_ARCHIVED` reason reports. A request that restores it may
        // carry the rest of the change with it.
        let unarchiving =
            input.archive_status.as_deref() == Some(crate::state::CHAT_ARCHIVE_STATUS_ACTIVE);
        if chat.is_archived() && !unarchiving && !replayed {
            return Err(UpdateChatErrorModeled::ConflictException(ConflictException {
                message: crate::state::chat_archived_message(&input.execution_id),
                reason: Some(crate::state::CONFLICT_REASON_CHAT_ARCHIVED.to_string()),
            })
            .into());
        }

        // Each member is a patch: what the request names is set, and what it leaves
        // out stays as it was. A request that names neither changes nothing at all, so
        // it does not move `updatedAt` either.
        let changed = !replayed && (input.summary.is_some() || input.archive_status.is_some());
        if changed {
            if let Some(summary) = input.summary {
                chat.summary = Some(summary);
            }
            if let Some(archive_status) = input.archive_status {
                chat.archive_status = archive_status;
            }
            chat.updated_at = now;
        }
        let output = UpdateChatOutput {
            execution_id: chat.execution_id.clone(),
            summary: chat.summary.clone(),
            updated_at: crate::state::to_date_time(chat.updated_at),
            archive_status: chat.archive_status.clone(),
        };

        // The token names the chat this update applied to, so a repeat carrying it is
        // recognised as the same request. Recorded only once the update was accepted:
        // a refused request applied nothing for a repeat to replay.
        if let Some(token) = input.client_token.as_deref() {
            if !replayed {
                store.record_client_token(Self::NAME, token, &input.execution_id, now);
            }
        }

        Ok(output)
    }
}
