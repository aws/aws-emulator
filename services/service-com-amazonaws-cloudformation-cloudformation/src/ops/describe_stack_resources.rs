/// The refusal for a request that does not name EXACTLY ONE of the two members that
/// select the stack.
///
/// "You must specify either StackName or PhysicalResourceId, but not both. … A
/// ValidationError is returned if you specify both StackName and PhysicalResourceId in
/// the same request." Each member is "Required: Conditional" on the absence of the other,
/// and ONE refusal covers both halves of that rule: a request naming neither has
/// specified no stack, and one naming both has specified no single stack either, so each
/// is told which member it must specify rather than being told about the combination.
/// Fixed text, down to the trailing period: nothing of the request appears in it.
///
/// The both-selectors spelling is answered AFTER the stack the `StackName` names is
/// resolved: a name nothing holds is refused about the stack, which is the earlier of the
/// two refusals.
const NO_SINGLE_SELECTOR: &str = "Either StackName or PhysicalResourceId must be specified.";

/// One deployed resource as the modelled `StackResource` shape.
///
/// Every member is read back from what the stack operation that deployed it persisted:
/// the logical id and type the template declared, the physical id CloudFormation's
/// documented naming rules gave it, and the resource-level status that operation left it
/// in with the instant it reached that status.
///
/// The members this emulator has nothing to report for are absent rather than invented:
///
/// * `ResourceStatusReason` — "Success/failure message associated with the resource":
///   reported for a resource whose work is UNDER WAY, which is the message CloudFormation
///   records when it has initiated it ([`crate::state::DeployedResource::status_reason`]),
///   and absent for one whose status speaks for itself. The reason a resource was not
///   created at all is reported on the STACK (its `StackStatusReason` and its events),
///   which is where this service records what the owning service refused.
/// * `Description` — "User defined description associated with the resource": a resource
///   description is not one of the resource attributes CloudFormation names (the model's
///   `ResourceAttribute` enum lists `CreationPolicy`, `DeletionPolicy`, `Metadata`,
///   `Properties`, `Tags`, `UpdatePolicy`, `UpdateReplacePolicy`), so a template read here
///   declares none.
/// * `ModuleInfo` — "the module from which the resource was created, if the resource was
///   created from a module": modules are not implemented, so no resource came from one.
///
/// `DriftInformation` is this resource's own drift result, as the last drift detection
/// that COMPLETED over it left it: `NOT_CHECKED` with no timestamp for a resource no
/// detection has covered, and for one whose type does not support drift detection here.
fn stack_resource_view(stack: &StoredStack, deployed: &DeployedResource) -> StackResource {
    StackResource {
        stack_name: Some(stack.stack_name.clone()),
        stack_id: Some(stack.stack_id.clone()),
        logical_resource_id: deployed.resource.logical_id.clone(),
        physical_resource_id: crate::state::physical_resource_id(&deployed.resource),
        resource_type: deployed.resource.resource_type.clone(),
        timestamp: crate::state::timestamp(deployed.status_timestamp),
        resource_status: deployed.status.clone(),
        // "Success/failure message associated with the resource": what the record carries,
        // which is the "work started" message for a resource whose operation is under way
        // and nothing for one whose status speaks for itself.
        resource_status_reason: deployed.status_reason.clone(),
        description: None,
        drift_information: crate::state::resource_drift_information(deployed),
        module_info: None,
    }
}

