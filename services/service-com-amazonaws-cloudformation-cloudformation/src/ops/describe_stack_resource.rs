impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeStackResource<Eng>
{
    type Input = DescribeStackResourceInput;
    type Output = DescribeStackResourceOutput;
    type Error = DescribeStackResourceError;

    const NAME: &'static str = "DescribeStackResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACK_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACK_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // CloudFormation checks the constraints on the stack identifier a request names
        // BEFORE it resolves the stack, so an identifier no stack could carry is answered as
        // the malformed request it is (`crate::state::stack_identifier`).
        crate::state::refuse_malformed_identifier(
            crate::state::STACK_NAME_PATH,
            Some(&input.stack_name),
        )?;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there is no stack store to read, so this
            // answers 501 rather than a truthful-looking description of nothing.
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "DescribeStackResource",
            ));
        };

        // A resource of a stack of this Region whose owning service had not reported it
        // ready when the create answered holds that stack's operation open: those services
        // are asked, before the store is locked, what they report now
        // ([`crate::state::provisioning::advance_stabilisations`]).
        crate::state::provisioning::advance_stabilisations(ctx, &state).await;

        let mut store = state.lock();
        // Reporting operation: the only write is materialising a status transition the
        // clock had already made due, which was owed whether or not anyone called — and
        // it is that transition which installs the resources a deployment produced.
        store.settle(::std::time::SystemTime::now());

        // "The name or the unique stack ID that's associated with the stack": a running
        // stack by either, a deleted one by its id only, and in either form only in the
        // Region the request was signed for. A name that resolves to nothing is a
        // `ValidationError`, as it is on every other read of a stack — worded with this
        // operation's own template for that class, which quotes the name the request sent.
        let region = crate::state::request_region(ctx.parts());
        let stack = store.resolve(&region, &input.stack_name).ok_or_else(|| {
            crate::scaffolded::Scaffolded::validation_error(
                crate::state::quoted_stack_does_not_exist(&input.stack_name),
            )
        })?;

        // "Returns a description of the specified resource in the specified stack": one
        // resource, named by the logical id the template declared it under, out of the
        // resources that stack reports right now — what its last completed deployment
        // materialised, or, for an operation waiting at a wait condition, what that
        // operation has created so far (`StoredStack::reported_resources`). A logical id
        // the stack has not deployed names no resource, so the request is refused rather
        // than answered with an empty description.
        let reported = stack.reported_resources();
        let deployed = reported
            .iter()
            .find(|deployed| deployed.resource.logical_id == input.logical_resource_id)
            .ok_or_else(|| {
                crate::scaffolded::Scaffolded::validation_error(
                    crate::state::resource_does_not_exist(
                        &input.logical_resource_id,
                        &input.stack_name,
                    ),
                )
            })?;

        Ok(DescribeStackResourceOutput {
            stack_resource_detail: Some(stack_resource_detail(stack, deployed)),
        })
    }
}
