impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeStackEvents<Eng>
{
    type Input = DescribeStackEventsInput;
    type Output = DescribeStackEventsOutput;
    type Error = DescribeStackEventsError;

    const NAME: &'static str = "DescribeStackEvents";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACK_EVENTS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACK_EVENTS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // CloudFormation checks the constraints on the stack identifier a request names
        // BEFORE it resolves the stack, so an identifier no stack could carry is answered as
        // the malformed request it is (`crate::state::stack_identifier`).
        crate::state::refuse_malformed_identifier(
            crate::state::STACK_NAME_PATH,
            Some(&input.stack_name),
        )?;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there are no recorded events to read.
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "DescribeStackEvents",
            ));
        };

        // A resource of a stack of this Region whose owning service had not reported it
        // ready when the create answered holds that stack's operation open: those services
        // are asked, before the store is locked, what they report now, which is what makes
        // the events the walk still owes due
        // ([`crate::state::provisioning::advance_stabilisations`]).
        crate::state::provisioning::advance_stabilisations(ctx, &state).await;
        // The events of a rollback the failure of an update already made due are the
        // rollback's own: it is carried out here, before the log is read, since it was owed
        // at the instant that update failed whether or not anybody called
        // (`crate::state::settle_due_rollbacks`).
        crate::state::settle_due_rollbacks(ctx, &*self.engine).await;

        let mut store = state.lock();
        // Reporting operation: the only write is materialising a status transition the
        // clock had already made due — which is also what appends the terminal event this
        // call then reports.
        store.settle(::std::time::SystemTime::now());

        // A stack name or id names a stack only in the Region the request was signed for.
        let region = crate::state::request_region(ctx.parts());
        let stack = store.resolve(&region, &input.stack_name).ok_or_else(|| {
            crate::scaffolded::Scaffolded::validation_error(
                crate::state::changed_stack_does_not_exist(&input.stack_name),
            )
        })?;
        // The stack the token this read hands out is scoped to: its stack id, which names
        // the one stack whose event stream is being paged whichever way the request named
        // it.
        let stack_id = stack.stack_id.clone();
        // "Returns all stack related events for a specified stack in reverse chronological
        // order": the stack's own status events and the per-resource events of each
        // operation are ONE stream, newest first. The store appends in order, so reading it
        // backwards is that order — and the sort by `Timestamp` is what keeps it so when an
        // operation whose resources took longer than its own status transition recorded its
        // resource events after that transition had already fallen due. A stable sort, so
        // events sharing an instant keep the reverse-append order.
        //
        // An event reporting a PRE-DEPLOYMENT VALIDATION RESULT is not one of them: nothing
        // was done to the resource, so it reports no `ResourceStatus` at all, and what it
        // does report are the validation members only `DescribeEvents` carries
        // (`crate::state::early_validation`). The STATUS such a failure left the stack in is
        // a transition like any other and is reported here, carrying that detailed status.
        let mut newest_first: Vec<&StoredEvent> = stack
            .events
            .iter()
            .rev()
            .filter(|event| !event.resource_status.is_empty())
            .collect();
        newest_first.sort_by_key(|event| ::std::cmp::Reverse(event.timestamp));
        let newest_first: Vec<StackEvent> =
            newest_first.into_iter().map(stack_event_view).collect();
        // `@paginated(inputToken: NextToken, outputToken: NextToken,
        // items: StackEvents)`: one response carries one bounded page, and the token is
        // SCOPED to this stack — a stack's events are the stack's, so a token minted while
        // paging another stack's is told apart from a corrupt one
        // ([`crate::state::PageScope`]).
        let (stack_events, next_token) = crate::state::paginate_in(
            crate::state::PageOf::StackEvents,
            crate::state::PageScope(&stack_id),
            newest_first,
            input.next_token.as_deref(),
        )
        .map_err(crate::scaffolded::Scaffolded::validation_error)?;

        Ok(DescribeStackEventsOutput {
            stack_events: Some(stack_events),
            next_token,
        })
    }
}
