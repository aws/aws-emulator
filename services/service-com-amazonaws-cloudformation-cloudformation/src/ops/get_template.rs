impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetTemplate<Eng>
{
    type Input = GetTemplateInput;
    type Output = GetTemplateOutput;
    type Error = GetTemplateError;

    const NAME: &'static str = "GetTemplate";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TEMPLATE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TEMPLATE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // CloudFormation checks the constraints on the stack identifier a request names
        // BEFORE it resolves the stack, so an identifier no stack could carry is answered as
        // the malformed request it is (`crate::state::stack_identifier`). A request that
        // names a change set by ARN alone carries no stack identifier here.
        crate::state::refuse_malformed_identifier(
            crate::state::STACK_NAME_PATH,
            input.stack_name.as_deref(),
        )?;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there is no template store to read.
            return Err(crate::scaffolded::Scaffolded::not_implemented("GetTemplate"));
        };
        let region = crate::state::request_region(ctx.parts());
        let mut store = state.lock();
        // Reporting operation: the only write is materialising a status transition the
        // clock had already made due.
        store.settle(::std::time::SystemTime::now());

        // "The name or Amazon Resource Name (ARN) of a change set for which CloudFormation
        // returns the associated template. If you specify a name, you must also specify the
        // StackName." A change set's template is the one it would put on its stack, which
        // is what `CreateChangeSet` stored.
        if let Some(change_set_name) = &input.change_set_name {
            crate::state::require_stack_for_change_set_name(
                change_set_name,
                input.stack_name.as_deref(),
            )
            .map_err(crate::scaffolded::Scaffolded::validation_error)?;
            // The change set is addressed WITHIN the stack named beside it, so that stack is
            // resolved first: a request naming one this Region holds none of is refused about
            // the STACK — in this operation's own wording for that class, the one its stack
            // read below answers — rather than answered the change-set-not-found of a lookup
            // that never had a stack to look inside.
            if let Some(absent) = store.unresolved_stack(&region, input.stack_name.as_deref()) {
                return Err(crate::scaffolded::Scaffolded::validation_error(
                    crate::state::stack_does_not_exist(absent),
                ));
            }
            let change_set = store
                .resolve_change_set(&region, change_set_name, input.stack_name.as_deref())
                .ok_or_else(|| {
                    GetTemplateError::from(GetTemplateErrorModeled::ChangeSetNotFoundException(
                        ChangeSetNotFoundException {
                            message: Some(crate::state::change_set_does_not_exist(
                                change_set_name,
                            )),
                        },
                    ))
                })?;
            // "For change sets, the Original template is always available. After
            // CloudFormation finishes creating the change set, the Processed template
            // becomes available" — the stage a transform PRODUCES is the one that waits for
            // the creation to finish. Where the template declares no transform the two
            // stages are one document ("If the template doesn't include transforms, Original
            // and Processed return the same template"), so there is nothing to wait for and
            // the processed stage is available at once. Either way the stage this read
            // serves was computed by `CreateChangeSet`, once, before the store lock: this
            // read expands nothing.
            let stages_are_one_document =
                change_set.processed_template == crate::state::template::Processed::Same;
            let serveable_processed = (change_set.creation_settled() || stages_are_one_document)
                .then(|| change_set.processed_template_body())
                .flatten()
                .map(str::to_string);
            let mut stages_available = vec![TEMPLATE_STAGE_ORIGINAL.to_string()];
            if serveable_processed.is_some() {
                stages_available.push(TEMPLATE_STAGE_PROCESSED.to_string());
            }
            // The stage the response serves, which is ALWAYS one the response advertises as
            // available: `Original` is the submitted body, `Processed` the one bound above.
            // So a request for `Processed` over a change set that has no such stage — a
            // transform this service cannot apply, or one whose expansion the creation has
            // not finished — is refused rather than answered the other stage's document,
            // and a request that names NO stage takes the documented default (`Processed`)
            // and is refused the same way.
            let requested = input.template_stage.as_deref();
            let template_body = match (requested, serveable_processed) {
                (Some(TEMPLATE_STAGE_ORIGINAL), _) => change_set.template_body.clone(),
                (_, Some(processed)) => processed,
                (_, None) => {
                    // Two different conditions, answered differently. A transform this
                    // service CANNOT apply has no processed stage at all: that is the
                    // unimplemented one, so it is the 501. A stage it can compute but the
                    // change set's creation has not reached yet is a request refusal, not
                    // an unimplemented operation — "After CloudFormation finishes creating
                    // the change set, the Processed template becomes available" — so it is
                    // this service's own `ValidationError`, the code it refuses a request
                    // it cannot satisfy with.
                    return Err(match change_set.processed_template.unavailable_reason() {
                        Some(reason) => crate::scaffolded::Scaffolded::not_implemented(&format!(
                            "GetTemplate(TemplateStage={TEMPLATE_STAGE_PROCESSED}) for a \
                             change set whose template cannot be processed here: {reason}"
                        )),
                        None => crate::scaffolded::Scaffolded::validation_error(format!(
                            "The {TEMPLATE_STAGE_PROCESSED} template is not available for \
                             change set [{}] in {} state",
                            change_set.change_set_name, change_set.status
                        )),
                    });
                }
            };
            return Ok(GetTemplateOutput {
                // CloudFormation holds a submitted template as ASCII, so the text this read
                // serves carries one `?` per codepoint outside it
                // (`crate::state::stored_template_body`).
                template_body: Some(crate::state::stored_template_body(&template_body)),
                stages_available: Some(stages_available),
            });
        }
        let Some(name_or_id) = input.stack_name.as_deref() else {
            return Err(crate::scaffolded::Scaffolded::validation_error(
                "Either StackName or ChangeSetName must be specified",
            ));
        };

        // "You can get the template for running or deleted stacks" — a deleted stack is
        // addressable by its stack id, which is what `resolve` honours. "If the template
        // doesn't exist, a ValidationError is returned."
        let stack = store.resolve(&region, name_or_id).ok_or_else(|| {
            crate::scaffolded::Scaffolded::validation_error(crate::state::stack_does_not_exist(
                name_or_id,
            ))
        })?;
        let stack_status = stack.status.clone();
        // A stack a `CREATE` change set created carries no template of its own until that
        // change set is executed ("CloudFormation creates a stack with a unique stack ID,
        // but no template or resources") — but it does carry the change set that created it
        // (`Stack$ChangeSetId`), and that change set's template IS the document the stack
        // would be deployed from, which is what a read of its template serves while it is in
        // review. Only a stack with no such change set either has no template at all, and
        // "if the template doesn't exist, a ValidationError is returned".
        let stack_template = stack
            .template_body
            .is_some()
            .then(|| (stack.processed_stage_body().map(str::to_string), None))
            .or_else(|| {
                let change_set = store.resolve_change_set(
                    &region,
                    stack.change_set_id.as_deref()?,
                    None,
                )?;
                Some((
                    change_set.processed_template_body().map(str::to_string),
                    Some(change_set.template_body.clone()),
                ))
            });
        let Some((serveable_processed, change_set_body)) = stack_template else {
            return Err(crate::scaffolded::Scaffolded::validation_error(
                crate::state::template_does_not_exist(name_or_id, &stack_status),
            ));
        };
        let template_body = match change_set_body {
            Some(body) => body,
            None => stack.template_body.clone().unwrap_or_default(),
        };

        // "For stacks, the Original and Processed templates are always available" — except
        // for a template whose transform this emulator cannot apply, whose Processed stage
        // is answered 501 below: a stage the read cannot serve is not advertised as
        // available.
        let mut stages_available = vec![TEMPLATE_STAGE_ORIGINAL.to_string()];
        if serveable_processed.is_some() {
            stages_available.push(TEMPLATE_STAGE_PROCESSED.to_string());
        }

        // "For templates that include transforms, the stage of the template that
        // CloudFormation returns. To get the user-submitted template, specify Original. To
        // get the template after CloudFormation has processed all transforms, specify
        // Processed. [...] By default, CloudFormation specifies Processed."
        let stage = input
            .template_stage
            .as_deref()
            .unwrap_or(TEMPLATE_STAGE_PROCESSED);
        let template_body = if stage == TEMPLATE_STAGE_ORIGINAL {
            template_body
        } else {
            // A transform this emulator cannot apply leaves the stack with no processed
            // stage: answered 501, never with the unprocessed body passed off as
            // processed.
            let Some(processed) = serveable_processed else {
                let reason = stack
                    .processed_template
                    .unavailable_reason()
                    .unwrap_or_default()
                    .to_string();
                return Err(crate::scaffolded::Scaffolded::not_implemented(&format!(
                    "GetTemplate(TemplateStage={TEMPLATE_STAGE_PROCESSED}) for a stack whose \
                     template cannot be processed here: {reason}"
                )));
            };
            processed
        };

        Ok(GetTemplateOutput {
            // CloudFormation holds a submitted template as ASCII, so the text this read
            // serves carries one `?` per codepoint outside it
            // (`crate::state::stored_template_body`) — at either stage, since both are that
            // one document.
            template_body: Some(crate::state::stored_template_body(&template_body)),
            stages_available: Some(stages_available),
        })
    }
}


