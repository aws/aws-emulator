//!   stack's name or its unique stack ID. Deleted stacks: You must specify the unique stack
//!   ID.
//! * `TemplateStage` (TemplateStage, one of: Original | Processed) — For templates that
//!   include transforms, the stage of the template that CloudFormation returns. To get the
//!   user-submitted template, specify Original. To get the template after CloudFormation has
//!   processed all transforms, specify Processed. If the template doesn't include transforms,
//!   Original and Processed return the same template. By default, CloudFormation specifies
//!   Processed.
//!
//! ## Output
//!
//! * `StagesAvailable` (StageList) — The stage of the template that you can retrieve. For
//!   stacks, the Original and Processed templates are always available. For change sets, the
//!   Original template is always available. After CloudFormation finishes creating the change
