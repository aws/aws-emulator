//!
//! ## Input
//!
//! * `ChangeSetName` (ChangeSetNameOrId, len 1..1600, pattern
//!   ^[a-zA-Z][-a-zA-Z0-9]*|arn:[-a-zA-Z0-9:/]*$) — The name or Amazon Resource Name (ARN) of
//!   a change set for which CloudFormation returns the associated template. If you specify a
//!   name, you must also specify the StackName.
//! * `StackName` (StackName) — The name or the unique stack ID that's associated with the
