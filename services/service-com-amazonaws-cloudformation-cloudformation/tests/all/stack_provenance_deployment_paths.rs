/// Read the stack until it reports a status that is not `*_IN_PROGRESS`, and answer with that
/// status and the body it was read from.
///
/// The CONDITION is what is waited for, not a span: a stack operation's terminal status is owed
/// a moment after the call that started it, and a read is what materialises it, so the loop
/// looks again until the status settles or [`SETTLE_DEADLINE`] passes.
async fn settled(case: &str, router: &MultiServiceRouter, stack: &str) -> (String, String) {
    let started = Instant::now();
    loop {
        let (http_status, body) = describe_stack(router, stack).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: DescribeStacks({stack}) must answer 200, got {http_status} {body}"
        );
        let reported = xml_text(&body, "StackStatus").unwrap_or_default();
        if !reported.ends_with(IN_PROGRESS) {
            return (reported, body);
        }
        assert!(
            started.elapsed() < SETTLE_DEADLINE,
            "case {case:?}: the stack {stack} is still {reported:?} after waiting for it to \
             settle: {body}"
        );
        tokio::time::sleep(SETTLE_POLL_INTERVAL).await;
    }
}

/// Read the change set until it reports itself executable (`ExecutionStatus: AVAILABLE`),
/// which the clock owes a moment after the call that created it.
///
/// The CONDITION again, not a span: the stack this plan left in review reports
/// `REVIEW_IN_PROGRESS` until the plan is executed, so it is the change set's own status that
/// says when the execution may be asked for.
async fn executable(case: &str, router: &MultiServiceRouter, stack: &str) {
    let started = Instant::now();
    loop {
        let (http_status, body) = describe_change_set(router, CHANGE_SET, Some(stack)).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: DescribeChangeSet({CHANGE_SET}) must answer 200, got {http_status} \
             {body}"
        );
        let reported = xml_text(&body, "ExecutionStatus").unwrap_or_default();
        if reported == execution_status::AVAILABLE {
            return;
        }
        assert!(
            started.elapsed() < SETTLE_DEADLINE,
            "case {case:?}: the change set {CHANGE_SET} is still {reported:?} after waiting for \
             it to become executable: {body}"
        );
        tokio::time::sleep(SETTLE_POLL_INTERVAL).await;
    }
}

/// Deploy one row's stack by the operation the row names, and answer with the stack id
/// `DescribeStacks` reports for it.
async fn deployed(router: &MultiServiceRouter, row: &Row) -> String {
    let case = row.case;
    let tags = tag_members(row.stack_tags);
    match row.deployed_by {
        DeployedBy::CreateStack | DeployedBy::CreateThenUpdate => {
            let (http_status, body) = create_stack(router, row.stack, row.template, &tags).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: CreateStack must be accepted, got {http_status} {body}"
            );
        }
        DeployedBy::ExecutedChangeSet => {
            let mut created_with = vec![
                member("ChangeSetType", "CREATE"),
                member("TemplateBody", row.template),
            ];
            created_with.extend(tags.clone());
            let (http_status, body) =
                create_change_set(router, row.stack, CHANGE_SET, &created_with).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: CreateChangeSet must be accepted, got {http_status} {body}"
            );
            // A change set is executable once its own creation has completed; until it is
            // executed the stack it created rests in review, with no deployment of its own.
            executable(case, router, row.stack).await;
            let (http_status, reviewed) = describe_stack(router, row.stack).await;
            assert_eq!(
                (http_status, xml_text(&reviewed, "StackStatus").as_deref()),
                (200, Some(status::REVIEW_IN_PROGRESS)),
                "case {case:?}: a change set that has not been executed leaves the stack in \
                 review, got {http_status} {reviewed}"
            );
            let (http_status, body) =
                execute_change_set(router, CHANGE_SET, Some(row.stack)).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: ExecuteChangeSet must be accepted, got {http_status} {body}"
            );
        }
    }
    let (reported, _) = settled(case, router, row.stack).await;
    assert_eq!(
        reported, status::CREATE_COMPLETE,
        "case {case:?}: expected the create to complete, got {reported:?}"
    );

    if let Some(updated) = row.updated_template {
        let mut members = vec![
            member("StackName", row.stack),
            member("TemplateBody", updated),
        ];
        members.extend(tags);
        let (http_status, body) = call(router, "UpdateStack", &members).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: UpdateStack must be accepted, got {http_status} {body}"
        );
        let (reported, body) = settled(case, router, row.stack).await;
        assert_eq!(
            reported, status::UPDATE_COMPLETE,
            "case {case:?}: expected the update to complete, got {reported:?} {body}"
        );
    }

    let (http_status, described) = describe_stack(router, row.stack).await;
    assert_eq!(
        http_status, 200,
        "case {case:?}: the deployed stack must be readable, got {http_status} {described}"
    );
    xml_text(&described, "StackId").unwrap_or_else(|| {
        panic!("case {case:?}: the stack must report a StackId, got {described}")
    })
}

/// The versioning state Amazon S3 reports for `bucket`, or `None` where the read answers with
/// no `Status` at all — "the versioning state of a bucket that has never had one set".
///
/// The READ itself must succeed either way: a bucket the stack created is a bucket Amazon S3
/// holds, so a non-200 here is a failure of the case rather than a bucket with no versioning.
async fn bucket_versioning(
    case: &str,
    router: &MultiServiceRouter,
    bucket: &str,
) -> Option<String> {
    let answer = s3(router, "GET", &format!("/{bucket}?versioning"), b"").await;
    assert_eq!(
        answer.status, 200,
        "case {case:?}: s3:GetBucketVersioning({bucket}) must answer 200, got {} with body {}",
        answer.status, answer.body
    );
    xml_text(&answer.body, "Status")
}

/// Every row: the bucket the stack published carries the stack's own tags, its declaration's
/// own tags and the three CloudFormation records — whichever operation provisioned it.
#[tokio::test]
async fn every_provisioning_path_stamps_the_reserved_stack_tags_onto_the_bucket() {
    for row in ROWS {
        let case = row.case;
        // One router per row, so a bucket name one row spells cannot collide with another's.
        let router = router();
        let stack_id = deployed(&router, row).await;

        for bucket in row.buckets {
            let logical_id = bucket.logical_id;
            // The handle the stack publishes for the resource, which for this type IS the
            // bucket name ("Ref returns the bucket name").
            let name = physical_id(&router, row.stack, logical_id).await;
            assert!(
                !name.is_empty(),
                "case {case:?}: the stack must publish a physical id for {logical_id:?}"
            );

            let (http_status, held) = bucket_tags(&router, &name).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: s3:GetBucketTagging({name}) must answer 200, got {http_status}"
            );
            let expected: BTreeMap<String, String> = expected_bucket_tags(
                row.stack_tags,
                bucket.declared,
                row.stack,
                &stack_id,
                logical_id,
            );
            assert_eq!(
                held, expected,
                "case {case:?}: expected {logical_id} to carry {expected:?}, got {held:?}"
            );

            let reported = bucket_versioning(case, &router, &name).await;
            assert_eq!(
                reported.as_deref(),
                bucket.versioning,
                "case {case:?}: expected {logical_id} to report versioning \
                 {:?}, got {reported:?}",
                bucket.versioning
            );
        }
    }
}
