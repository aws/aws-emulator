//! WHICH NAMES an engine this front door serves has a setting for at all — the engine's own
//! configuration namespace, by name.
//!
//! This is a different question from the one the parameter CATALOGS answer. A catalog
//! ([`crate::ops::describe_engine_default_parameters::MYSQL_PARAMETERS`] and its siblings)
//! publishes a parameter's whole record — its apply type, data type, allowed values, default
//! and description — and each of those catalogs is a SAMPLE of what Amazon RDS publishes for
//! a family, because an engine release carries hundreds of parameters and every column of
//! every one of them would have to be carried here. The vocabulary below carries NO record:
//! it is the list of names the engine has a setting for, which is what decides whether a
//! parameter group of that engine's families HAS the parameter a request names
//! ([`super::validate_cluster_parameter_name`], [`super::validate_db_parameter_name`]) — a
//! group's membership is its engine's parameter list, so a name the engine has no setting for
//! names no parameter of the group and the request that would set or reset it is refused.
//!
//! Source: the engine's own configuration reference — PostgreSQL's server-configuration
//! settings (the names its `pg_settings` catalog reports) plus the settings Amazon RDS and
//! Amazon Aurora add to that engine, and MySQL's server system variables plus the ones Aurora
//! MySQL, Amazon RDS for MySQL and MariaDB add. Each list is the engine's namespace rather
//! than any one family's list: which FAMILIES carry a name, and what each name admits, is the
//! catalogs' answer and not this module's.
//!
//! A name a list here does not carry, on an engine it covers, is a name the request cannot
//! have meant as a parameter of that engine. An engine this module covers no list for (the
//! Oracle, Microsoft SQL Server and Db2 engines, whose configuration namespaces this front
//! door does not carry) makes no claim either way, so nothing is refused for one of its
//! families.
//!
//! So a list here is the vocabulary this front door answers membership BY, and a setting the
//! engine really has that is missing from one reads as a parameter of that engine refused:
//! that is a gap in this data, and the fix is the name, added to the list it belongs to.

use crate::ops::describe_engine_default_parameters::ParameterVocabulary;

/// Whether this front door carries `engine`'s namespace AND that namespace has no setting
/// named `name`: the positive evidence that a parameter group of one of the engine's families
/// does not have the parameter.
pub fn engine_has_no_setting_named(engine: &str, name: &str) -> bool {
    engine_settings(engine).is_some_and(|namespace| !carries(engine, namespace, name))
}

/// The settings namespace of `engine`, or `None` where this front door carries none.
///
/// The engines that RUN one server share one namespace, and which engines those are is the
/// SAME reading the parameter catalogs are selected by
/// ([`crate::ops::describe_engine_default_parameters::ParameterVocabulary::is_spoken_by`]), so
/// the namespace and the catalog of an engine can never belong to different servers: Aurora
/// PostgreSQL runs the PostgreSQL engine, and the MySQL-compatible engines — Amazon RDS for
/// MySQL, Aurora MySQL and MariaDB, a fork of the same server — run the one system-variable
/// namespace.
fn engine_settings(engine: &str) -> Option<&'static [&'static str]> {
    [
        (ParameterVocabulary::PostgresCompatible, POSTGRES_SETTINGS),
        (ParameterVocabulary::MysqlCompatible, MYSQL_SETTINGS),
    ]
    .into_iter()
    .find_map(|(vocabulary, namespace)| {
        vocabulary.is_spoken_by(engine).then_some(namespace)
    })
}

/// Whether `namespace` has a setting named `name`.
///
/// The comparison is made WITHOUT case, the way both servers read a setting name: PostgreSQL
/// documents its configuration names as case-insensitive and MySQL reads a system variable
/// the same way, so a differently-cased spelling names the one setting it can only have meant.
///
/// A PostgreSQL name carrying a `.` is admitted whichever extension it names: the engine reads
/// a dotted name as the customized option of an extension — a name it accepts as a
/// placeholder before the extension that defines it is loaded — so such a name is a setting
/// the server has, and this front door has no list of the extensions an instance may load.
/// MySQL has no such form: its system variables are single, unqualified names.
fn carries(engine: &str, namespace: &'static [&'static str], name: &str) -> bool {
    if name.contains('.') && ParameterVocabulary::PostgresCompatible.is_spoken_by(engine) {
        return true;
    }
    namespace
        .iter()
        .any(|setting| setting.eq_ignore_ascii_case(name))
}

