impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RebootDBInstance<Eng>
{
    type Input = RebootDBInstanceInput;
    type Output = RebootDBInstanceOutput;
    type Error = RebootDBInstanceError;

    const NAME: &'static str = "RebootDBInstance";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REBOOT_DB_INSTANCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REBOOT_DB_INSTANCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let region =
            crate::state::request_region(ctx).map_err(RebootDBInstanceError::validation)?;
        // `DBInstanceIdentifier`: "This parameter is stored as a lowercase string."
        let identifier = input.db_instance_identifier.to_ascii_lowercase();

        // No store means this service was mounted on an engine it has no state in, so it
        // cannot serve the operation at all; 501 is the honest answer, never a reboot
        // nothing performed.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::not_implemented(Self::NAME));
        };
        let mut store = state.lock();
        // The transitions the clock already made due — owed at this instant whether or not
        // anybody called — so the state this reboot is judged against is the current one.
        store.settle_due_transitions(&region);

        // RDS is regional: an instance is addressable only in the region it was created
        // in, so an identifier that names one elsewhere is not found here.
        let key = (region.clone(), identifier.clone());
        let Some(instance) = store.db_instances.get(&key) else {
            return Err(RebootDBInstanceErrorModeled::DBInstanceNotFoundFault(
                DBInstanceNotFoundFault {
                    // RDS words this fault per operation, and this one answers
                    // "<resource type> not found: <name>" where the describe answers
                    // "<resource type> <name> not found." — the wording is the service's,
                    // the name is the request's.
                    message: Some(format!("DBInstance not found: {identifier}")),
                },
            )
            .into());
        };

        // `ForceFailover`: "Constraint: You can't enable force failover if the instance
        // isn't configured for Multi-AZ." The model cannot express a constraint between a
        // member and the addressed instance's own configuration, so it is refused here —
        // with the Query API's `InvalidParameterValue` and the fixed sentence Amazon RDS
        // words that refusal with, never the unmodelled `ValidationException`, which is no
        // Amazon RDS error code.
        if input.force_failover.unwrap_or(false) && !instance.multi_az {
            return Err(RebootDBInstanceError::invalid_parameter_value(
                crate::state::FORCE_FAILOVER_REQUIRES_MULTI_AZ_MESSAGE,
            ));
        }

        // "Rebooting a DB instance restarts the database engine service", so there has to
        // be a running engine to restart: a reboot is accepted only from the statuses
        // [`crate::state::REBOOTABLE_DB_INSTANCE_STATUSES`] names, and an instance still
        // coming up, or on its way out, cannot take one. The status the clock has yet to
        // settle is real.
        if !crate::state::reboot_is_accepted_from(&instance.status) {
            let status = instance.status.clone();
            return Err(RebootDBInstanceErrorModeled::InvalidDBInstanceStateFault(
                InvalidDBInstanceStateFault {
                    message: Some(crate::state::reboot_db_instance_state_message(
                        &identifier,
                        &status,
                    )),
                },
            )
            .into());
        }

        // The DB subnet group the instance reports is that GROUP's own record, resolved
        // here — before the instance record is taken mutably below — so the answer carries
        // the group as it reads now (`instance_to_wire` is the same answer).
        let db_subnet_group = store
            .db_instances
            .get(&key)
            .and_then(|record| store.db_subnet_group_of(record));
        let record = store
            .db_instances
            .get_mut(&key)
            .expect("the instance was found above and the store is locked");
        // "Rebooting a DB instance results in a momentary outage, during which the DB
        // instance status is set to rebooting": the instance is reported as `rebooting`
        // now and the clock owes it `available` once the outage is over.
        record.status = "rebooting".to_string();
        record.pending_status = Some(crate::state::PendingStatus::in_a_moment("available"));
        // "Some parameter changes can cause an outage and are applied on the next call to
        // RebootDBInstance": a modification staged for the maintenance window
        // (`ApplyImmediately` disabled) is applied by the restart this call performs, so
        // the instance comes back up under those settings and has nothing pending. A
        // staged rename is applied with the rest; the record moves to its new key on the
        // next settle, which every handler runs before it reads the store.
        record.apply_deferred_modification();
        // "Rebooting a DB instance restarts the database engine service": the engine's run
        // starts again here, which is what `pg_postmaster_start_time()` reports and what
        // puts a parameter change that was waiting for a reboot into force.
        record.engine_started_at = crate::state::now_as_wire_timestamp();
        let instance_arn = record.arn();
        let db_instance = record.to_wire(db_subnet_group.as_ref());
        // "Rebooting a DB instance restarts the database engine service": the sessions
        // the engine held do not survive the restart, and whatever they had not committed
        // is rolled back with them. The endpoint stays bound — a reboot does not move the
        // address a client reconnects to.
        store.sever_engine_sessions(&key);
        // The restart happened, so the region's event log records it.
        store.record_event(
            &region,
            crate::state::events::DB_INSTANCE_RESTARTED,
            &identifier,
            instance_arn,
        );
        Ok(RebootDBInstanceOutput {
            db_instance: Some(db_instance),
        })
    }
}
