fn reports_replication_log_capabilities(engine: &str) -> bool {
    crate::state::is_aurora(engine)
}

/// `DBEngineVersionDescription` — "The description of the database engine version."
///
/// An AURORA version's description names the community engine release that version is
/// compatible with and the Aurora release itself, because an Aurora version is a service
/// release of its own numbered against a community engine it is compatible with — the two
/// are different numbers and a client reads both:
///
/// * an Aurora PostgreSQL version string IS the community PostgreSQL version (`16.4`), so
///   the description states that compatibility, in the form AWS publishes for this engine;
/// * an Aurora MySQL version string carries BOTH numbers, the MySQL release before
///   `.mysql_aurora.` and the Aurora release after it (`5.7.mysql_aurora.2.11.1`), so the
///   description states the MySQL release in parentheses and then the Aurora release —
///   `Aurora (MySQL 5.7) 2.11.1` — rather than repeating the joined version string, which
///   names no release the engine publishes on its own. Both halves come from the version
///   string, so every row of either family is described by the same rule — and the engine
///   gates it, so a version of another engine that happened to carry the same mark (a
///   custom engine version is named by its caller) is described by the generic form below.
///
/// Every other engine's version string names its own release (`8.0.39`,
/// `19.0.0.0.ru-2024-10.rur-2024-10.r1`), so there the description is the product and
/// that version — except Microsoft SQL Server, whose product is named by its RELEASE YEAR
/// ([`sqlserver_product_year`]).
fn version_description(facts: &EngineFacts, engine_version: &str) -> String {
    if facts.engine == "aurora-postgresql" {
        return format!(
            "{} (Compatible with PostgreSQL {engine_version})",
            facts.product
        );
    }
    if facts.engine == "aurora-mysql" {
        if let Some((community_release, aurora_release)) =
            engine_version.split_once(AURORA_MYSQL_MARK)
        {
            return format!("Aurora (MySQL {community_release}) {aurora_release}");
        }
    }
    if let Some(year) = sqlserver_product_year(facts.engine, engine_version) {
        return format!("{SQLSERVER_PRODUCT} {year} {engine_version}");
    }
    format!("{} {engine_version}", facts.product)
}

/// How Microsoft SQL Server names its product in a version description: the product, then
/// the release year, then the version string.
///
/// The EDITION is not part of it — that is what `DBEngineDescription` carries (`facts`'
/// product, "Microsoft SQL Server Standard Edition") — so two editions of one release are
/// described by the same product and year and differ only in the version string.
const SQLSERVER_PRODUCT: &str = "SQL Server";

/// The release YEAR of the Microsoft SQL Server product a version of `engine` belongs to, or
/// `None` for a version of another engine, or one whose major version names no SQL Server
/// release this table covers.
///
/// Microsoft numbers the product by year and the engine by major version, and the two are
/// one published mapping ([`SQLSERVER_RELEASE_YEARS`], from Microsoft's own SQL Server
/// release history): the engine's `15.00` builds are SQL Server 2019 and its `16.00` builds
/// SQL Server 2022, so a description built from the major version alone names the release a
/// caller reads the product by.
///
/// Gated on the ENGINE, because the mapping is a fact about one product: a version of
/// another engine that happens to start with the same number — and a custom engine version,
/// whose string its caller chose — is described by the generic form instead. Every SQL
/// Server engine this front door serves is covered, the Developer Edition and the RDS Custom
/// ones included, since all of them run that product.
fn sqlserver_product_year(engine: &str, engine_version: &str) -> Option<&'static str> {
    if !engine.contains("sqlserver") {
        return None;
    }
    SQLSERVER_RELEASE_YEARS
        .iter()
        .find(|(major, _)| {
            engine_version
                .strip_prefix(*major)
                .is_some_and(|rest| rest.starts_with('.'))
        })
        .map(|(_, year)| *year)
}

/// The Microsoft SQL Server release each engine major version belongs to, as Microsoft's
/// published SQL Server release history names them; see [`sqlserver_product_year`].
///
/// Every major version this service's engine-version catalogue carries has a row, and the
/// releases past them are here too, so a build of a release the catalogue has not sampled
/// yet is still described by its own product rather than by the engine's edition name.
const SQLSERVER_RELEASE_YEARS: &[(&str, &str)] = &[
    ("11.00", "2012"),
    ("12.00", "2014"),
    ("13.00", "2016"),
    ("14.00", "2017"),
    ("15.00", "2019"),
    ("16.00", "2022"),
    ("17.00", "2025"),
];

/// What separates the two releases an Aurora MySQL version string carries: the MySQL
/// release it is compatible with, and the Aurora release itself.
const AURORA_MYSQL_MARK: &str = ".mysql_aurora.";

/// The character-set and time-zone members of ONE reported engine version: its
/// `DefaultCharacterSet`, and the three LISTS a request can ask for.
///
/// "For RDS Custom, the default is not to list supported character sets. If you enable
/// this parameter, RDS Custom returns no results" — and `ListSupportedTimezones` carries
/// the same sentence. So an RDS Custom engine version lists NONE of them, whatever the
/// request asked for, while `DefaultCharacterSet` is still reported: no flag gates it, and
/// it is the engine's own default collation.
///
/// Shared by both projections below, because the rule is the ENGINE's and the request's,
/// not the catalogue's: a stored custom engine version answers these members exactly as a
/// catalogue row of the same engine does.
struct CharacterSetMembers {
    default_character_set: Option<CharacterSet>,
    supported_character_sets: Option<Vec<CharacterSet>>,
    supported_nchar_character_sets: Option<Vec<CharacterSet>>,
    supported_timezones: Option<Vec<Timezone>>,
}

/// The character-set and time-zone members of a version of `facts`' engine, as this
/// request asks for them.
fn character_set_members(facts: &EngineFacts, input: &DescribeDBEngineVersionsInput) -> CharacterSetMembers {
    let rds_custom = is_rds_custom_engine(facts.engine);
    let lists_character_sets = input.list_supported_character_sets == Some(true) && !rds_custom;
    let supported_character_sets = (lists_character_sets && !facts.character_sets.is_empty())
        .then(|| facts.character_sets.iter().map(character_set).collect());
    // `SupportedNcharCharacterSets` — "the character sets supported by the Oracle DB
    // engine for the `NcharCharacterSetName` parameter of the `CreateDBInstance`
    // operation": the same question as `SupportedCharacterSets` asked of the national
    // character set, so the same flag reports it, and only for an engine that takes an
    // `NcharCharacterSetName` ("This setting doesn't apply to RDS Custom DB instances").
    let supported_nchar_character_sets = (lists_character_sets
        && !facts.nchar_character_sets.is_empty())
    .then(|| facts.nchar_character_sets.iter().map(character_set).collect());
    let supported_timezones = (input.list_supported_timezones == Some(true)
        && !rds_custom
        && !facts.timezones.is_empty())
    .then(|| {
        facts
            .timezones
            .iter()
            .map(|name| Timezone {
                timezone_name: Some((*name).to_string()),
            })
            .collect()
    });
    CharacterSetMembers {
        default_character_set: facts.character_sets.first().map(character_set),
        supported_character_sets,
        supported_nchar_character_sets,
        supported_timezones,
    }
}

/// Project one catalogue entry onto the modelled `DBEngineVersion` wire shape.
///
/// `SupportedCharacterSets` and `SupportedTimezones` are reported only when the request
/// asks for them, through [`character_set_members`]. Every other member the catalogue
/// knows is reported on every entry, because a client reads them to choose a version and
/// gate on its capabilities.
fn to_wire(
    entry: &CatalogVersion,
    facts: &EngineFacts,
    index: usize,
    input: &DescribeDBEngineVersionsInput,
    certificates: &[String],
) -> CreateCustomDBEngineVersionOutput {
    let profile = entry.profile;
    let character_sets = character_set_members(facts, input);
    CreateCustomDBEngineVersionOutput {
        engine: Some(entry.engine.to_string()),
        engine_version: Some(entry.engine_version.to_string()),
        major_engine_version: Some(entry.major_engine_version.to_string()),
        // The minor version of this release within its major-version family, and the
        // capability members this service reports beside the ones the model declares: a
        // client gates a DB proxy, a cluster deployment, a data group and — on an Aurora
        // version — enhanced binary logging and a change-data-capture stream on them, so
        // each is reported for every entry whose engine reports it rather than left for
        // the client to assume. Each value is the VERSION's own, read from its profile.
        minor_engine_version: Some(minor_engine_version(
            entry.engine_version,
            entry.major_engine_version,
        )),
        supports_rds_proxy: Some(profile.supports_rds_proxy),
        supports_cluster: Some(profile.supports_cluster),
        supports_data_groups: Some(profile.supports_data_groups),
        supports_enhanced_binlog: reports_replication_log_capabilities(entry.engine)
            .then_some(profile.supports_enhanced_binlog),
        supports_change_data_capture_streams: reports_replication_log_capabilities(entry.engine)
            .then_some(profile.supports_change_data_capture_streams),
        db_parameter_group_family: Some(entry.parameter_group_family.to_string()),
        db_engine_description: Some(facts.description.to_string()),
        db_engine_version_description: Some(version_description(facts, entry.engine_version)),
        status: Some(entry.status.to_string()),
        supported_engine_modes: Some(strings(profile.engine_modes)),
        supported_feature_names: Some(strings(profile.feature_names)),
        // `SupportedCACertificateIdentifiers`: the CA certificates an instance of this
        // version can be given through `CreateDBInstance`'s `CACertificateIdentifier`. The
        // member's documentation points at "Using SSL/TLS to encrypt a connection to a DB
        // instance", and the certificate authorities that page publishes are the ones THIS
        // service already reports through `DescribeCertificates` — so the list is read from
        // that ONE catalogue (`crate::state::CA_CERTIFICATES`) rather than restated here,
        // and the two reports cannot name different certificates. An entry whose
        // `ValidTill` has passed is left out: an expired certificate is not one a new
        // instance can be launched with; so is an authority this ENGINE is not offered
        // (`crate::state::ca_certificates_offered_to`).
        supported_ca_certificate_identifiers: Some(crate::state::ca_certificates_offered_to(
            entry.engine,
            certificates,
        )),
        exportable_log_types: Some(strings(facts.exportable_log_types)),
        supports_log_exports_to_cloudwatch_logs: Some(!facts.exportable_log_types.is_empty()),
        supports_read_replica: Some(profile.supports_read_replica),
        supports_global_databases: Some(profile.supports_global_databases),
        supports_parallel_query: Some(profile.supports_parallel_query),
        supports_babelfish: Some(profile.supports_babelfish),
        supports_limitless_database: Some(profile.supports_limitless_database),
        supports_local_write_forwarding: Some(profile.supports_local_write_forwarding),
        supports_integrations: Some(profile.supports_integrations),
        supports_certificate_rotation_without_restart: Some(
            profile.supports_certificate_rotation_without_restart,
        ),
        // "Specifies any Aurora Serverless v2 properties or limits that differ between
        // Aurora engine versions": reported for a version that runs Serverless v2, and
        // absent — rather than zeroed — for one that does not.
        serverless_v2_features_support: profile.serverless_v2_capacity.map(|(min, max)| {
            ServerlessV2FeaturesSupport {
                min_capacity: Some(min),
                max_capacity: Some(max),
            }
        }),
        default_character_set: character_sets.default_character_set,
        supported_character_sets: character_sets.supported_character_sets,
        supported_nchar_character_sets: character_sets.supported_nchar_character_sets,
        supported_timezones: character_sets.supported_timezones,
        valid_upgrade_target: Some(valid_upgrade_targets(entry, facts, index)),
        // The members a CUSTOM engine version carries — `DBEngineVersionArn`,
        // `CreateTime`, `KMSKeyId`, `Image`, the installation-file members and
        // `CustomDBEngineVersionManifest` — belong to a record
        // `CreateCustomDBEngineVersion` stores, so no catalogue entry invents them.
        ..Default::default()
    }
}

/// What the engine-version catalogue says about a CUSTOM engine version's name.
///
/// A CEV is named for the engine build it packages — `19.my_cev1` for RDS Custom for
/// Oracle, `<major>.<minor>.<build>.<revision>.<customized_string>` for the SQL Server
/// engines (`CreateCustomDBEngineVersion$EngineVersion`) — so its major version, its DB
/// parameter group family and the capabilities of the engine version it is built on are
/// the ones this service already publishes for that major version, rather than a second
/// set of facts about the same engine.
pub(crate) struct CustomVersionBasis {
    /// `MajorEngineVersion` — "the major engine version of the CEV".
    pub(crate) major_engine_version: String,
    /// `DBParameterGroupFamily`.
    pub(crate) parameter_group_family: String,
    /// The capability members of the engine version the CEV is built on.
    pub(crate) profile: &'static VersionProfile,
}

/// The profile of a custom engine version whose engine publishes no catalogue row at all
/// — the `custom-oracle-*` engines. RDS Custom gives the customer host access to a single
/// DB instance: no engine mode beyond `provisioned`, no read replica and no Aurora
/// capability, which is exactly the base profile.
static RDS_CUSTOM_BASE: VersionProfile = VersionProfile::provisioned();

/// Resolve [`CustomVersionBasis`] for the CEV named `engine_version` of `engine`.
///
/// The catalogue row whose own `MajorEngineVersion` the CEV name begins with is the
/// published version family the CEV belongs to, and the longest such match is the right
/// one (`15.00` and `15` would both prefix `15.00.4249.2.my_cev1`). An engine with no
/// catalogue rows — RDS Custom for Oracle, whose versions are only ever CEVs — resolves
/// the major version from the name's leading component, which is the form that
/// operation's `EngineVersion` member documents (`19.`*customized_string*), and the family
/// RDS writes for it, `<engine>-<major version>`.
pub(crate) fn custom_version_basis(engine: &str, engine_version: &str) -> CustomVersionBasis {
    let published = CATALOG
        .iter()
        .filter(|entry| {
            entry.engine.eq_ignore_ascii_case(engine)
                && engine_version
                    .to_ascii_lowercase()
                    .starts_with(&format!("{}.", entry.major_engine_version.to_ascii_lowercase()))
        })
        .max_by_key(|entry| entry.major_engine_version.len());
    if let Some(entry) = published {
        return CustomVersionBasis {
            major_engine_version: entry.major_engine_version.to_string(),
            parameter_group_family: entry.parameter_group_family.to_string(),
            profile: entry.profile,
        };
    }
    let major = engine_version
        .split('.')
        .next()
        .unwrap_or(engine_version)
        .to_string();
    CustomVersionBasis {
        parameter_group_family: format!("{engine}-{major}"),
        major_engine_version: major,
        profile: &RDS_CUSTOM_BASE,
    }
}

/// Whether this service PUBLISHES `engine_version` for `engine` as reference data.
///
/// `pub(crate)` because the name of a new custom engine version has to be free among ALL
/// of that engine's versions, not only among the ones an account minted: a CEV name "is
/// unique per customer per Amazon Web Services Regions", and a version AWS already
/// publishes is one every customer in the region already has.
pub(crate) fn publishes_engine_version(engine: &str, engine_version: &str) -> bool {
    CATALOG.iter().any(|entry| {
        entry.engine.eq_ignore_ascii_case(engine)
            && entry.engine_version.eq_ignore_ascii_case(engine_version)
    })
}

/// Whether this service publishes ANY engine version of `engine`.
///
/// An engine with no row in the catalogue is one this account has no build of: there is
/// nothing to create a DB instance of and nothing for a custom engine version to be built
/// on. `CreateCustomDBEngineVersion` reads this as the engine-availability gate it applies
/// before anything else the request carries, and the report of this engine's versions is
/// empty for exactly the same reason.
pub(crate) fn publishes_engine(engine: &str) -> bool {
    CATALOG
        .iter()
        .any(|entry| entry.engine.eq_ignore_ascii_case(engine))
}

/// Every `DBParameterGroupFamily` this service publishes an engine version of, each once,
/// in catalogue order.
///
/// The families are what decide which default DB parameter groups the account holds
/// (`crate::state::default_db_parameter_groups`): RDS creates one such group per family it
/// serves, so the group list follows from this catalogue rather than from a second list
/// that could disagree with it.
pub(crate) fn published_parameter_group_families() -> Vec<&'static str> {
    let mut families: Vec<&'static str> = Vec::new();
    for entry in CATALOG {
        if !families.contains(&entry.parameter_group_family) {
            families.push(entry.parameter_group_family);
        }
    }
    families
}

/// Every `(Engine, MajorEngineVersion)` pair this service publishes an engine version of,
/// each once, in catalogue order.
///
/// The pairs are what decide which default option groups the account holds
/// (`crate::state::default_option_groups`), the way the families above decide the default
/// parameter groups.
pub(crate) fn published_engine_major_versions() -> Vec<(&'static str, &'static str)> {
    let mut pairs: Vec<(&'static str, &'static str)> = Vec::new();
    for entry in CATALOG {
        let pair = (entry.engine, entry.major_engine_version);
        if !pairs.contains(&pair) {
            pairs.push(pair);
        }
    }
    pairs
}

/// Project one stored CUSTOM engine version onto the modelled `DBEngineVersion` wire
/// shape.
///
/// The ONE projection of a CEV record: `CreateCustomDBEngineVersion` answers with it and
/// this report lists it, so the create's answer and every later read of that record cannot
/// disagree. Everything in it is read from the record, from the `profile` of the engine
/// version the CEV is built on, and from the engine's own facts; nothing is invented, and a
/// member the record carries no value for is left out rather than defaulted.
pub(crate) fn custom_version_to_wire(
    record: &crate::state::CustomDbEngineVersionRecord,
    profile: &'static VersionProfile,
    input: &DescribeDBEngineVersionsInput,
    certificates: &[String],
) -> CreateCustomDBEngineVersionOutput {
    let facts = engine_facts(&record.engine);
    let character_sets = facts.map(|facts| character_set_members(facts, input));
    let exportable_log_types: &[&str] = facts.map_or(&[], |facts| facts.exportable_log_types);
    CreateCustomDBEngineVersionOutput {
        engine: Some(record.engine.clone()),
        engine_version: Some(record.engine_version.clone()),
        major_engine_version: Some(record.major_engine_version.clone()),
        // The same member set a catalogue row carries, computed the same way: the minor
        // version from this record's own name, and each capability from the profile of the
        // engine version the CEV is built on.
        minor_engine_version: Some(minor_engine_version(
            &record.engine_version,
            &record.major_engine_version,
        )),
        supports_rds_proxy: Some(profile.supports_rds_proxy),
        supports_cluster: Some(profile.supports_cluster),
        supports_data_groups: Some(profile.supports_data_groups),
        supports_enhanced_binlog: reports_replication_log_capabilities(&record.engine)
            .then_some(profile.supports_enhanced_binlog),
        supports_change_data_capture_streams: reports_replication_log_capabilities(&record.engine)
            .then_some(profile.supports_change_data_capture_streams),
        db_parameter_group_family: Some(record.parameter_group_family.clone()),
        db_engine_description: facts.map(|facts| facts.description.to_string()),
        // `DBEngineVersionDescription` is "the description of the database engine version",
        // which for a CEV is the `Description` the create gave it — "an optional
        // description of your CEV". A CEV created without one is described the way every
        // other version of its engine is.
        db_engine_version_description: record.description.clone().or_else(|| {
            facts.map(|facts| version_description(facts, &record.engine_version))
        }),
        db_engine_version_arn: Some(record.arn()),
        create_time: Some(record.create_time),
        kms_key_id: record.kms_key_id.clone(),
        custom_db_engine_version_manifest: record.manifest.clone(),
        database_installation_files_s3_bucket_name: record
            .database_installation_files_s3_bucket_name
            .clone(),
        database_installation_files_s3_prefix: record
            .database_installation_files_s3_prefix
            .clone(),
        database_installation_files: Some(record.database_installation_files.clone()),
        // `Image` — "the EC2 image": reported for a CEV built on an AMI, carrying that
        // AMI's id and the status of the CEV it backs ("a value that indicates the status
        // of a custom engine version"). A CEV with no AMI reports no image rather than an
        // empty one.
        image: record.image_id.as_ref().map(|image_id| CustomDBEngineVersionAMI {
            image_id: Some(image_id.clone()),
            status: Some(record.status.clone()),
        }),
        db_engine_media_type: crate::state::reports_engine_media_type(&record.engine)
            .then(|| crate::state::MEDIA_TYPE_CUSTOMER_PROVIDED.to_string()),
        status: Some(record.status.clone()),
        tag_list: Some(record.tags.clone()),
        supported_ca_certificate_identifiers: Some(crate::state::ca_certificates_offered_to(
            &record.engine,
            certificates,
        )),
        exportable_log_types: Some(strings(exportable_log_types)),
        supports_log_exports_to_cloudwatch_logs: Some(!exportable_log_types.is_empty()),
        supported_engine_modes: Some(strings(profile.engine_modes)),
        supported_feature_names: Some(strings(profile.feature_names)),
        supports_read_replica: Some(profile.supports_read_replica),
        supports_global_databases: Some(profile.supports_global_databases),
        supports_parallel_query: Some(profile.supports_parallel_query),
        supports_babelfish: Some(profile.supports_babelfish),
        supports_limitless_database: Some(profile.supports_limitless_database),
        supports_local_write_forwarding: Some(profile.supports_local_write_forwarding),
        supports_integrations: Some(profile.supports_integrations),
        supports_certificate_rotation_without_restart: Some(
            profile.supports_certificate_rotation_without_restart,
        ),
        serverless_v2_features_support: profile.serverless_v2_capacity.map(|(min, max)| {
            ServerlessV2FeaturesSupport {
                min_capacity: Some(min),
                max_capacity: Some(max),
            }
        }),
        default_character_set: character_sets
            .as_ref()
            .and_then(|members| members.default_character_set.clone()),
        supported_character_sets: character_sets
            .as_ref()
            .and_then(|members| members.supported_character_sets.clone()),
        supported_nchar_character_sets: character_sets
            .as_ref()
            .and_then(|members| members.supported_nchar_character_sets.clone()),
        supported_timezones: character_sets
            .and_then(|members| members.supported_timezones),
        // `ValidUpgradeTarget` is "a list of engine versions that this database engine
        // version can be upgraded to", and a CEV has none: upgrading an RDS Custom DB
        // instance means creating the next CEV, so no version this service holds is an
        // upgrade target of one an account minted. Reported empty, because the member is
        // a list and an entry with no target has none rather than omitting it.
        valid_upgrade_target: Some(Vec::new()),
        ..Default::default()
    }
}


