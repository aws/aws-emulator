/// The cluster parameters the DB CLUSTER parameter group family `family` publishes as this
/// REPORT answers for it, or the refusal message for a value that is not such a family.
///
/// A family is published reference data: the service serves the families it publishes
/// (`crate::ops::describe_engine_default_parameters::publishes_parameter_group_family`) and
/// refuses every other value, whatever its shape — a value naming an engine this door serves
/// followed by a release that engine has never had names no family at all, so answering it
/// with defaults would tell a caller probing a family name that the name exists. A published
/// family whose engine has no cluster form publishes no CLUSTER family either, which is the
/// narrowing [`cluster_engine_default_parameters`] carries.
fn published_cluster_family_parameters(
    family: &str,
) -> Result<&'static [crate::state::ClusterParameterSpec], String> {
    if !super::describe_engine_default_parameters::publishes_parameter_group_family(family) {
        return Err(
            super::describe_engine_default_parameters::not_a_valid_parameter_group_family(family),
        );
    }
    cluster_engine_default_parameters(family)
}

/// The cluster parameters the engine named by `family` publishes, or the refusal message for
/// a value that is not a DB CLUSTER parameter group family.
///
/// A family is an engine this front door serves followed by that engine's version — the rule
/// `crate::ops::describe_engine_default_parameters::family_engine` reads, shared so the two
/// engine-default reports cannot disagree about what a family is. A DB CLUSTER parameter
/// group family is narrower: its engine must have a cluster form, which is the value list
/// `CreateDBClusterMessage$Engine` publishes ([`crate::state::DB_CLUSTER_ENGINES`]). A family
/// of an engine that runs only as a single DB instance publishes no cluster parameters at
/// all, so it is refused rather than answered with an empty list, which would read as "that
/// engine's clusters carry no parameters".
///
/// A cluster family whose engine this emulator publishes no catalog for is a different
/// answer, and deliberately a 200 with an empty list: the family IS one this front door
/// serves, and the honest report of a catalog this emulator does not hold is no parameters
/// rather than invented ones.
fn cluster_engine_default_parameters(
    family: &str,
) -> Result<&'static [crate::state::ClusterParameterSpec], String> {
    let Some(engine) = super::describe_engine_default_parameters::family_engine(family) else {
        return Err(
            super::describe_engine_default_parameters::not_a_valid_parameter_group_family(family),
        );
    };
    if !crate::state::DB_CLUSTER_ENGINES
        .iter()
        .any(|known| known.eq_ignore_ascii_case(engine))
    {
        return Err(
            super::describe_engine_default_parameters::not_a_valid_parameter_group_family(family),
        );
    }
    // The MySQL-compatible cluster engines share one cluster vocabulary (Aurora MySQL's is
    // MySQL's), and so do the PostgreSQL-compatible ones; Amazon DocumentDB's is the SHARED
    // catalog, which that module publishes per FAMILY, so the family selects it rather than
    // the engine alone. Which versions of an engine exist is a question for the
    // engine-version report, not for this one.
    if engine == crate::state::DOCDB_ENGINE {
        return Ok(crate::state::published_parameters(family)
            .unwrap_or(crate::state::DOCDB_CLUSTER_PARAMETERS));
    }
    Ok(engine_cluster_parameter_vocabulary(engine))
}

/// The DB CLUSTER parameter vocabulary this front door publishes for `engine`: the one
/// catalog every cluster family of that engine reads a parameter's published record from.
///
/// The engine-level sibling of
/// [`super::describe_engine_default_parameters::engine_parameter_vocabulary`], read by
/// [`cluster_engine_default_parameters`] for one family's report and by the resolution that
/// answers which engine a parameter name belongs to at all
/// (`crate::state::published_for_another_engine`). An engine with no cluster catalog — one
/// that runs only as a single DB instance, or one added to the cluster list without a
/// catalog — publishes an EMPTY vocabulary rather than invented entries.
pub(crate) fn engine_cluster_parameter_vocabulary(
    engine: &str,
) -> &'static [crate::state::ClusterParameterSpec] {
    match engine {
        _ if engine.ends_with("mysql") => MYSQL_CLUSTER_PARAMETERS,
        _ if super::describe_engine_default_parameters::is_postgres_engine(engine) => {
            POSTGRES_CLUSTER_PARAMETERS
        }
        "docdb" => crate::state::DOCDB_CLUSTER_PARAMETERS,
        "neptune" => NEPTUNE_CLUSTER_PARAMETERS,
        _ => &[],
    }
}

