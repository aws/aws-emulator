///
/// `CreateDBClusterMessage$StorageType` in the DocumentDB and Neptune models: "Valid
/// values for storage type - standard | iopt1 … Default value is standard" — and the
/// CLUSTER carries it, so the instance orders neither size nor IOPS of its own. The name is
/// that value list's own ([`crate::state::SIBLING_CLUSTER_DEFAULT_STORAGE_TYPE`]).
const CLUSTER_STANDARD: StorageProfile = StorageProfile {
    name: crate::state::SIBLING_CLUSTER_DEFAULT_STORAGE_TYPE,
    size_range: None,
    iops: None,
    throughput: None,
    dedicated_log_volume: false,
};

/// The IO-OPTIMIZED storage of an Amazon DocumentDB or Amazon Neptune cluster member: the
/// second type those models' `CreateDBClusterMessage$StorageType` publishes ("Valid values
/// for storage type - standard | iopt1"), under the name that value list carries
/// ([`crate::state::SIBLING_CLUSTER_IO_OPTIMIZED_STORAGE_TYPE`]). It is the same
/// cluster-managed storage under a different I/O configuration, so it carries the same
/// absence of per-instance bounds as [`CLUSTER_STANDARD`].
const CLUSTER_IO_OPTIMIZED: StorageProfile = StorageProfile {
    name: crate::state::SIBLING_CLUSTER_IO_OPTIMIZED_STORAGE_TYPE,
    size_range: None,
    iops: None,
    throughput: None,
    dedicated_log_volume: false,
};

/// The storage types an Aurora DB instance is offered with: one option per type the
/// CLUSTER's own `StorageType` publishes, because that is what an order picks between.
const AURORA_STORAGE: &[StorageProfile] = &[AURORA, AURORA_IO_OPTIMIZED];

/// The storage types a DocumentDB or Neptune cluster member is offered with: one option per
/// type that engine's own `CreateDBCluster` publishes, for the same reason
/// [`AURORA_STORAGE`] carries two — the type is part of what an order picks, and an option of
/// an engine of another control plane is that control plane's own catalog entry, which this
/// front door's view of it must agree with (`core/router/tests/all/
/// rds_front_door_shared_catalogs.rs` holds the two views to one answer, and the document
/// engine's own catalog publishes both types in
/// `::service_common::docdb_engine_catalog::STORAGE_TYPES`).
const CLUSTER_STORAGE: &[StorageProfile] = &[CLUSTER_STANDARD, CLUSTER_IO_OPTIMIZED];

/// The storage types a provisioned-storage (non-cluster) class is offered with, in the
/// order the published storage table lists them.
///
/// A BURSTABLE class is offered the same four, and two sources say so. The model: the
/// storage members are bound by SIZE and RATIO and never by DB instance class —
/// `CreateDBInstanceMessage$StorageType` publishes one value list for every DB instance
/// ("Valid Values: `gp2 | gp3 | io1 | io2 | standard`") and carves out only Aurora ("This
/// setting doesn't apply to Amazon Aurora DB instances. Storage is managed by the DB
/// cluster."), and `CreateDBInstanceMessage$Iops`'s constraints are a multiple of the
/// storage amount, not a list of classes; the only constraint Provisioned IOPS SSD adds is
/// its own 100 GiB minimum size ([`IO1`]/[`IO2`]'s `size_range`), which `MinStorageSize`
/// reports. And the RECORDING: the behavioural unit
/// `rds.valid-db-instance-modifications-bound-what-modify-accepts` runs on a
/// `db.t4g.micro` — a burstable class — and requires its reported `StorageSize` to carry a
/// range starting ABOVE the 20 GiB it runs, which only the Provisioned IOPS SSD minimum
/// provides; while this table withheld `io1`/`io2` from burstable classes that unit failed
/// with "must report at least one StorageSize range enlarging beyond the current
/// allocation 20; it reported only [(20, 65536, 1)]".
const ALL_PROVISIONED_STORAGE: &[StorageProfile] = &[GP2, GP3, IO1, IO2];

/// Legacy MAGNETIC storage: still published by `StorageType` ("Valid Values: gp2 | gp3 |
/// io1 | io2 | standard") and ordered with no option here, since
/// `DescribeOrderableDBInstanceOptions` offers the four current types — but a modification
/// can still convert to it, so its bounds live beside theirs and [`storage_bounds`] hands
/// them out.
///
/// Source: `CreateDBInstanceMessage$AllocatedStorage`, whose magnetic line is the widest
/// for the MariaDB, MySQL and PostgreSQL engines ("Magnetic storage (standard): Must be an
/// integer from 5 to 3072"); the Oracle and SQL Server engines publish a narrower one of
/// their own, which [`magnetic_storage_range`] applies. It takes neither provisioned IOPS nor
/// provisioned throughput: a magnetic volume's performance is not configurable.
const MAGNETIC: StorageProfile = StorageProfile {
    name: LEGACY_MAGNETIC_STORAGE,
    size_range: Some((5, 3_072)),
    iops: None,
    throughput: None,
    dedicated_log_volume: false,
};

/// The storage types a DB instance of `engine` can be ordered with.
///
/// It is a property of the ENGINE alone: an engine whose storage its cluster manages
/// carries that one type, and every other engine is offered the four per-instance types,
/// whatever class it runs on.
///
/// `pub` because a MODIFICATION is bounded by the same table an order is:
/// `DescribeValidDBInstanceModifications` reports one `ValidStorageOptions` per type this
/// returns for the stored instance's engine.
pub fn storage_profiles(engine: &str) -> &'static [StorageProfile] {
    if crate::state::is_aurora(engine) {
        return AURORA_STORAGE;
    }
    if matches!(engine, "docdb" | "neptune") {
        return CLUSTER_STORAGE;
    }
    ALL_PROVISIONED_STORAGE
}

/// The bounds `storage_type` carries for a DB instance of `engine`, or `None` when the
/// engine publishes no such type at all.
///
/// Every type an option is ordered with ([`storage_profiles`]), plus the legacy
/// [`MAGNETIC`] type `StorageType` publishes for an engine whose storage is its own. This
/// is what `ModifyDBInstance` judges a storage modification against, so a type the member
/// admits is bounded rather than unbounded.
pub fn storage_bounds(engine: &str, storage_type: &str) -> Option<&'static StorageProfile> {
    let profiles = storage_profiles(engine);
    if let Some(profile) = profiles
        .iter()
        .find(|profile| profile.name.eq_ignore_ascii_case(storage_type))
    {
        return Some(profile);
    }
    // An engine whose storage is its own also takes the legacy magnetic type.
    (profiles.iter().any(|profile| profile.size_range.is_some())
        && storage_type.eq_ignore_ascii_case(LEGACY_MAGNETIC_STORAGE))
    .then_some(&MAGNETIC)
}

/// Whether `StorageType` publishes `storage_type` for a DB instance of `engine`.
///
/// `CreateDBInstanceMessage$StorageType` publishes one value list for a DB instance whose
/// storage is its own ("Valid Values: `gp2 | gp3 | io1 | io2 | standard`") and carves out
/// the engines whose "Storage is managed by the DB cluster", which carry their cluster's
/// type instead. `standard` — legacy magnetic storage — is in that list and is ordered
/// with no option here, so it is published with [`MAGNETIC`]'s bounds rather than refused.
pub fn publishes_storage_type(engine: &str, storage_type: &str) -> bool {
    storage_bounds(engine, storage_type).is_some()
}

/// Refuse a `StorageType` a request names for a DB instance of `engine`: one the member's
/// value list does not publish for that engine names no storage this service can provision
/// ([`publishes_storage_type`]).
///
/// `Err` carries the sentence Amazon RDS answers — the member's subject and the value it
/// would not take — so every operation that takes the member (a create, a restore and a
/// modification alike) refuses the same values with the same words, lifted into its own
/// modelled unsupported-type fault.
pub fn check_requested_storage_type(engine: &str, storage_type: &str) -> Result<(), String> {
    if publishes_storage_type(engine, storage_type) {
        return Ok(());
    }
    Err(format!("Invalid storage type: {storage_type}"))
}

/// The legacy magnetic storage type `StorageType` still publishes.
pub const LEGACY_MAGNETIC_STORAGE: &str = "standard";

/// The `AllocatedStorage` range, in GiB, a DB instance of `engine` takes on `storage_type` —
/// `None` for storage that is not sized per instance (a type a CLUSTER manages) and for a
/// type the engine publishes no value for at all.
///
/// `CreateDBInstanceMessage$AllocatedStorage` publishes the range per (ENGINE, STORAGE TYPE)
/// pair rather than per engine or per type alone — one list per engine, one entry per type in
/// it ("General Purpose (SSD) storage (gp2, gp3): Must be an integer from 20 to 65536",
/// "Provisioned IOPS storage (io1, io2): Must be an integer from 100 to 65536", "Magnetic
/// storage (standard): Must be an integer from 5 to 3072") — so a size is judged against the
/// pair: the bounds the TYPE publishes ([`StorageProfile::size_range`]), capped by what the
/// ENGINE accepts ([`max_allocated_storage`]), with the magnetic type's own per-engine bounds
/// ([`magnetic_storage_range`]).
pub fn allocated_storage_range(engine: &str, storage_type: &str) -> Option<(i32, i32)> {
    let profile = storage_bounds(engine, storage_type)?;
    let (min, max) = profile.size_range?;
    if profile.name == LEGACY_MAGNETIC_STORAGE {
        return Some(magnetic_storage_range(engine));
    }
    Some((min, max.min(max_allocated_storage(engine))))
}

/// The sizes legacy magnetic storage publishes for `engine`, in GiB.
///
/// It is the one type whose bounds differ by engine in
/// `CreateDBInstanceMessage$AllocatedStorage`: "Magnetic storage (standard): Must be an
/// integer from 5 to 3072" for the MariaDB, MySQL and PostgreSQL engines, "from 10 to 3072"
/// for Oracle and "from 20 to 1024" for SQL Server, both editions.
fn magnetic_storage_range(engine: &str) -> (i32, i32) {
    let lowered = engine.to_ascii_lowercase();
    if lowered.starts_with("sqlserver") || lowered.starts_with("custom-sqlserver") {
        return (20, 1_024);
    }
    if lowered.starts_with("oracle") || lowered.starts_with("custom-oracle") {
        return (10, 3_072);
    }
    (5, 3_072)
}

/// The smallest volume `engine` itself publishes for a DB instance whose storage is its own,
/// in GiB: 5 for the MariaDB, MySQL and PostgreSQL engines, 10 for Oracle and 20 for
/// Microsoft SQL Server.
///
/// It is the floor the engine has carried since before any one storage type published a
/// higher one of its own, which is why it is the low end of the one type whose range is
/// written per engine ([`magnetic_storage_range`]) and the floor the option CATALOG publishes
/// for General Purpose SSD ([`reported_storage_size`]).
fn engine_storage_floor(engine: &str) -> i32 {
    magnetic_storage_range(engine).0
}

/// The storage bounds an OPTION reports for one (engine, storage type) pair —
/// `MinStorageSize` and `MaxStorageSize` — or `None` for storage a cluster manages, which is
/// not ordered per instance at all.
///
/// The ceiling is the type's own, capped by what the engine accepts
/// ([`allocated_storage_range`]). The FLOOR is the type's own for every type that published
/// one when it was introduced — `gp3` from 20 GiB, the Provisioned IOPS SSD types from 100 —
/// and the ENGINE's own ([`engine_storage_floor`]) for `gp2`, the General Purpose SSD type
/// these engines have been ordered with since before any higher general-purpose floor: the
/// catalog publishes that engine floor for it, which is the value the recorded catalog
/// carries for a `gp2` option of the MySQL engine.
///
/// It is the CATALOG's floor, not the order's: an `AllocatedStorage` a request asks for is
/// held to the range `CreateDBInstanceMessage$AllocatedStorage` documents per type
/// ([`check_requested_allocated_storage`]), which is why that check reads
/// [`allocated_storage_range`] and this report reads this.
fn reported_storage_size(engine: &str, storage_type: &str) -> Option<(i32, i32)> {
    let (min, max) = allocated_storage_range(engine, storage_type)?;
    if storage_type.eq_ignore_ascii_case(GP2.name) {
        return Some((engine_storage_floor(engine), max));
    }
    Some((min, max))
}

/// Refuse an `AllocatedStorage` a request asks for an instance of `engine`, held to the
/// range that applies to it: the range the `StorageType` the request NAMES publishes
/// ([`check_allocated_storage`]), or — where the request names none — the widest range that
/// engine's types reach between them ([`check_allocated_storage_for_any_storage_type`]).
///
/// `effective_storage_type` is the type the volume ends up on, which the refusal names: the
/// named one, or the type such a request is placed on by default.
///
/// Every door that sizes an instance's own volume reads this one rule — the create, the three
/// restores and the read replica — so a size one of them would store is a size the others
/// would too.
pub fn check_requested_allocated_storage(
    engine: &str,
    named_storage_type: Option<&str>,
    effective_storage_type: &str,
    allocated_storage: i32,
) -> Result<(), String> {
    match named_storage_type {
        Some(named) => check_allocated_storage(engine, named, allocated_storage),
        None => check_allocated_storage_for_any_storage_type(
            engine,
            effective_storage_type,
            allocated_storage,
        ),
    }
}

/// Refuse an `AllocatedStorage` the engine and the storage type it is asked for do not take
/// ([`allocated_storage_range`]).
///
/// A pair that publishes no range — storage a cluster manages, or a type the engine does not
/// publish at all — bounds nothing here: the first is not sized per instance and the second is
/// its caller's own modelled unsupported-type refusal.
fn check_allocated_storage(
    engine: &str,
    storage_type: &str,
    allocated_storage: i32,
) -> Result<(), String> {
    let Some((min, max)) = allocated_storage_range(engine, storage_type) else {
        return Ok(());
    };
    if (min..=max).contains(&allocated_storage) {
        return Ok(());
    }
    let named = storage_bounds(engine, storage_type).map_or(storage_type, |profile| profile.name);
    Err(invalid_storage_size_message(engine, named, allocated_storage))
}

/// Refuse an `AllocatedStorage` that NO storage type `engine` publishes could carry, for a
/// request that names no `StorageType` of its own.
///
/// A request that names a type is held to THAT type's range ([`check_allocated_storage`]); a
/// request that names none leaves the type to the service, which places the volume on a type
/// that can hold the size asked for, so only a size outside every range the engine publishes
/// is refused — and the recorded service accepts a size under the default type's own floor
/// for exactly that reason. The sentence names the type such a request is placed on by
/// default (`crate::state::default_storage_type`), which is what the caller sees reported.
fn check_allocated_storage_for_any_storage_type(
    engine: &str,
    default_storage_type: &str,
    allocated_storage: i32,
) -> Result<(), String> {
    let Some((min, max)) = widest_allocated_storage_range(engine) else {
        return Ok(());
    };
    if (min..=max).contains(&allocated_storage) {
        return Ok(());
    }
    Err(invalid_storage_size_message(
        engine,
        default_storage_type,
        allocated_storage,
    ))
}

/// The widest `AllocatedStorage` range the storage types `engine` publishes reach between
/// them: the lowest floor and the highest ceiling of [`allocated_storage_range`] over every
/// type the member lists for the engine — `None` for an engine whose storage its cluster
/// manages, which is not sized per instance at all.
pub fn widest_allocated_storage_range(engine: &str) -> Option<(i32, i32)> {
    storage_profiles(engine)
        .iter()
        .map(|profile| profile.name)
        .chain([LEGACY_MAGNETIC_STORAGE])
        .filter_map(|storage_type| allocated_storage_range(engine, storage_type))
        .reduce(|(low, high), (min, max)| (low.min(min), high.max(max)))
}

/// How Amazon RDS refuses a storage size the engine and the storage type do not take: the
/// sentence names both, and the size the request asked for.
pub fn invalid_storage_size_message(
    engine: &str,
    storage_type: &str,
    allocated_storage: i32,
) -> String {
    format!(
        "Invalid storage size for engine name {engine} and storage type {storage_type}: \
         {allocated_storage}"
    )
}

/// The largest `AllocatedStorage` `engine` accepts, in GiB.
///
/// The published per-engine caps: 65,536 GiB for the MySQL, MariaDB, PostgreSQL and
/// Oracle engines, 16,384 GiB for Microsoft SQL Server and 64,000 GiB for Db2. A storage
/// type's own maximum ([`StorageProfile::size_range`]) is capped at this; a cluster
/// engine's storage carries no bounds at all, so this is not consulted for one.
///
/// `pub` for the same reason as [`storage_profiles`]: the storage a modification can grow
/// to is capped by the engine exactly as the storage an order can ask for is.
pub fn max_allocated_storage(engine: &str) -> i32 {
    if engine.starts_with("sqlserver") {
        return 16_384;
    }
    if engine.starts_with("db2") {
        return 64_000;
    }
    65_536
}

/// Whether `engine` supports IAM database authentication
/// (`SupportsIAMDatabaseAuthentication`): the MySQL, MariaDB and PostgreSQL engines do;
/// the Oracle, SQL Server and Db2 engines do not.
///
/// The GRAPH engine of the Amazon Neptune control plane this door serves does too, and at
/// the cluster level: its own
/// `CreateDBClusterMessage$EnableIAMDatabaseAuthentication` "enables Amazon Identity and
/// Access Management (IAM) authentication for the entire DB cluster (this cannot be set at
/// an instance level)"
/// (`smithy_query(query="doc",shape="CreateDBClusterMessage",member="EnableIAMDatabaseAuthentication",model_path="services/service-com-amazonaws-neptune-amazonrdsv19/smithy-model/com-amazonaws-neptune-amazonrdsv19.json")`),
/// so every option of it is offered with that auth mode. The DOCUMENT engine's control
/// plane models no such member on either create
/// (`com.amazonaws.docdb#CreateDBClusterMessage`,
/// `com.amazonaws.docdb#CreateDBInstanceMessage`), so an option of it reports none: the
/// capability is read per engine from the control plane that owns it rather than defaulted
/// for this one front door.
fn supports_iam_database_authentication(engine: &str) -> bool {
    matches!(
        engine,
        "mysql" | "mariadb" | "postgres" | "aurora-mysql" | "aurora-postgresql" | "neptune"
    )
}

/// Whether a DB instance of `engine` can be ordered as a MULTI-AZ deployment
/// (`MultiAZCapable`, "whether a DB instance is Multi-AZ capable").
///
/// A Multi-AZ deployment is a standby DB INSTANCE the service keeps in another zone of the
/// region for an instance that owns its own storage. For a cluster engine the zones are
/// not the instance's at all: `CreateDBInstanceMessage$MultiAZ` states it — "This setting
/// doesn't apply to Amazon Aurora because the DB instance Availability Zones (AZs) are
/// managed by the DB cluster" — and the two sibling control planes served by this one door
/// document their instance members the same way ("Not applicable … managed by the DB
/// cluster" on the Amazon Neptune and Amazon DocumentDB `CreateDBInstance` members). An
/// option of a cluster engine therefore reports no instance-level Multi-AZ capability; the
/// zones its members are placed in come from the CLUSTER's own `AvailabilityZones`.
fn multi_az_capable(engine: &str) -> bool {
    !is_cluster_engine(engine)
}

/// Whether an option of `engine` reports Enhanced Monitoring
/// (`SupportsEnhancedMonitoring`, "Enhanced Monitoring at intervals from 1 to 60
/// seconds").
///
/// Enhanced Monitoring is the OS-metric stream Amazon RDS collects from a DB instance's
/// host under a monitoring role, which this control plane's own engines publish. An engine
/// of ANOTHER control plane served by this one door
/// ([`serves_another_control_plane`]) publishes its own capability set and neither of them
/// offers it: the document engine's control plane models no monitoring member to enable it
/// with at all (`com.amazonaws.docdb#CreateDBInstanceMessage` carries neither
/// `MonitoringInterval` nor `MonitoringRoleArn`), and the graph engine's own front-door
/// option report publishes the member unsupported for every class. So it is read per
/// engine rather than claimed for every option.
fn supports_enhanced_monitoring(engine: &str) -> bool {
    !serves_another_control_plane(engine)
}

/// Whether `engine` offers Performance Insights at all, before the CLASS is consulted.
///
/// The graph engine does not: its own control plane documents both the option member and
/// the create flag that would enable it as "(Not supported by Neptune)"
/// (`smithy_query(query="shape",shape="OrderableDBInstanceOption",model_path="services/service-com-amazonaws-neptune-amazonrdsv19/smithy-model/com-amazonaws-neptune-amazonrdsv19.json")`
/// on `SupportsPerformanceInsights`, and the same note on that model's
/// `CreateDBInstanceMessage$EnablePerformanceInsights`), so no option of it claims the
/// capability whatever class it runs on. The document engine's control plane DOES model
/// `EnablePerformanceInsights`, so its options report the capability its classes carry —
/// the question is the engine's, not this front door's.
fn engine_offers_performance_insights(engine: &str) -> bool {
    engine != crate::state::NEPTUNE_ENGINE
}

/// Whether an option of `engine` reports Kerberos authentication
/// (`SupportsKerberosAuthentication`, "whether a DB instance supports Kerberos
/// Authentication").
///
/// Kerberos authentication on Amazon RDS is the engine joining an AWS Managed Microsoft AD
/// directory, which the `Domain` member of a create names. It is published for the MySQL,
/// MariaDB, PostgreSQL, Oracle and SQL Server engines of this control plane — Aurora MySQL
/// and Aurora PostgreSQL among them, whose own user guide carries the same section — and for
/// neither the Db2 engines nor the graph engine of the other control plane this door serves,
/// which publish no domain membership at all.
fn supports_kerberos_authentication(engine: &str) -> bool {
    !engine.starts_with("db2") && engine != crate::state::NEPTUNE_ENGINE
}

/// The Database Activity Streams modes an option reports, exactly as
/// `OrderableDBInstanceOption$SupportedActivityStreamModes` documents them: "Aurora
/// PostgreSQL returns the value `[sync, async]`. Aurora MySQL and RDS for Oracle return
/// `[async]` only. If Database Activity Streams isn't supported, the return value is an
/// empty list."
///
/// The CLASS decides too: a database activity stream is collected from the DB instance's own
/// host, which the SERVERLESS capacity class does not give the caller — the capacity it is
/// ordered with has no instance host to stream from — so an option of that class supports no
/// mode and reports the empty list the member documents for exactly that case.
fn activity_stream_modes(engine: &str, class: &InstanceClass) -> Vec<String> {
    if class.name.eq_ignore_ascii_case(SERVERLESS_CLASS) {
        return Vec::new();
    }
    let modes: &[&str] = match engine {
        "aurora-postgresql" => &["sync", "async"],
        "aurora-mysql" => &["async"],
        engine if engine.starts_with("oracle") => &["async"],
        _ => &[],
    };
    modes.iter().map(|mode| (*mode).to_string()).collect()
}

/// The processor features a caller can configure on `class` for `engine`.
///
/// Configuring the CPU cores and threads per core of a DB instance is published for the
/// core-licensed engines — RDS for Oracle and RDS for Microsoft SQL Server — on the Intel
/// classes that expose multithreaded cores. Every other combination reports no
/// configurable feature, so the list is empty and the member is left absent.
///
/// The two features are the published ones: `coreCount`, whose default is the class's
/// full core count and whose allowed values are the EVEN counts up to it (cores are
/// disabled in pairs), and `threadsPerCore`, which allows one thread or
/// [`THREADS_PER_CORE`].
///
/// `pub` because the processor features a stored instance's class can be MODIFIED to are
/// the same ones it can be ordered with: `DescribeValidDBInstanceModifications` reports
/// this list as its `ValidProcessorFeatures`.
pub fn available_processor_features(
    engine: &str,
    class: &InstanceClass,
) -> Vec<AvailableProcessorFeature> {
    if !(engine.starts_with("oracle") || engine.starts_with("sqlserver")) {
        return Vec::new();
    }
    let Some(cores) = class.cores.filter(|cores| *cores > 1) else {
        return Vec::new();
    };
    let allowed_core_counts: Vec<String> = (1..=cores)
        .filter(|count| count % 2 == 0)
        .map(|count| count.to_string())
        .collect();
    vec![
        AvailableProcessorFeature {
            name: Some("coreCount".to_string()),
            default_value: Some(cores.to_string()),
            allowed_values: Some(allowed_core_counts.join(",")),
        },
        AvailableProcessorFeature {
            name: Some("threadsPerCore".to_string()),
            default_value: Some(THREADS_PER_CORE.to_string()),
            allowed_values: Some(
                (1..=THREADS_PER_CORE)
                    .map(|threads| threads.to_string())
                    .collect::<Vec<_>>()
                    .join(","),
            ),
        },
    ]
}

/// The Availability Zones of `region` an option is offered in.
///
/// They are the zones AWS publishes for the Region
/// ([`::service_common::aws_availability_zones`]): a Region exposes at least three and
/// several expose more, so a report that named three letters refused a zone that is in fact
/// orderable in the Region. `CreateDBInstance` in this emulator places an instance that
/// names no zone in the region's FIRST zone, so the zones reported here are the ones an
/// instance can land in.
fn availability_zones(region: &str) -> Vec<AvailabilityZone> {
    ::service_common::aws_availability_zones::availability_zones(region)
        .into_iter()
        .map(|name| AvailabilityZone { name: Some(name) })
        .collect()
}

/// Project one (engine version, DB instance class, license model, storage type) onto the
/// modelled `OrderableDBInstanceOption` wire shape.
///
/// The version is given as the three things an option reports about it — the engine, the
/// `EngineVersion` and the capability `profile` of its release line — rather than as a
/// catalogue row, because a release the catalogue samples no row for is described by its
/// line's profile ([`described_versions`]).
fn to_wire(
    engine: &str,
    engine_version: &str,
    profile: &crate::ops::describe_db_engine_versions::VersionProfile,
    class: &InstanceClass,
    license_model: &str,
    storage: &StorageProfile,
    region: &str,
) -> OrderableDBInstanceOption {
    // The sizes this (engine, storage type) pair publishes.
    let storage_size = reported_storage_size(engine, storage.name);
    let processor_features = available_processor_features(engine, class);
    // The capability answers of an engine of ANOTHER control plane are that control plane's,
    // held once for both views of this front door that answer for it: the document engine's
    // are `::service_common::docdb_engine_catalog::OPTION_CAPABILITIES`, and an option of it
    // reports every member of that set rather than leaving the ones this door models for its
    // own engines absent. An engine of this door's own control plane answers from the tables
    // below as before.
    let docdb = (engine == ::service_common::docdb_engine_catalog::ENGINE)
        .then_some(::service_common::docdb_engine_catalog::OPTION_CAPABILITIES);
    OrderableDBInstanceOption {
        engine: Some(engine.to_string()),
        engine_version: Some(engine_version.to_string()),
        db_instance_class: Some(class.name.clone()),
        license_model: Some(license_model.to_string()),
        availability_zones: Some(availability_zones(region)),
        // Multi-AZ, a read replica and Enhanced Monitoring are INSTANCE-level
        // capabilities, so each is the engine's own rather than this front door's default:
        // a cluster engine's deployment and replication belong to its cluster, and the
        // read-replica answer is read from the engine catalogue so this report and
        // `DescribeDBEngineVersions` cannot disagree about the version.
        multi_az_capable: Some(multi_az_capable(engine)),
        read_replica_capable: Some(profile.supports_read_replica),
        vpc: Some(true),
        supports_storage_encryption: Some(true),
        // Everything below comes from the option's OWN storage type.
        storage_type: Some(storage.name.to_string()),
        supports_iops: Some(storage.iops.is_some()),
        min_iops_per_db_instance: storage.iops.as_ref().map(|iops| iops.min_per_instance),
        max_iops_per_db_instance: storage.iops.as_ref().map(|iops| iops.max_per_instance),
        min_iops_per_gib: storage.iops.as_ref().map(|iops| iops.min_per_gib),
        max_iops_per_gib: storage.iops.as_ref().map(|iops| iops.max_per_gib),
        supports_storage_throughput: Some(storage.throughput.is_some()),
        min_storage_throughput_per_db_instance: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.min_per_instance),
        max_storage_throughput_per_db_instance: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.max_per_instance),
        min_storage_throughput_per_iops: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.min_per_iops),
        max_storage_throughput_per_iops: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.max_per_iops),
        // Storage autoscaling raises `AllocatedStorage`, so it applies exactly where
        // storage is ordered per instance rather than managed by a cluster. It is reported
        // for every option of an engine whose DB instance keeps its own storage, including
        // a cluster engine of THIS door, because `DescribeValidDBInstanceModifications`
        // answers the same fact for a STORED instance of that engine and the two reports
        // must agree about it. An engine of the DocumentDB control plane publishes no
        // storage autoscaling at all — its cluster owns the storage and its create models no
        // allocation to raise — so the member is left ABSENT on an option of that engine
        // rather than answered false about a facility it does not have.
        supports_storage_autoscaling: docdb
            .is_none()
            .then_some(storage.size_range.is_some()),
        min_storage_size: storage_size.map(|(min, _)| min),
        max_storage_size: storage_size.map(|(_, max)| max),
        supports_enhanced_monitoring: Some(supports_enhanced_monitoring(engine)),
        // Performance Insights is the ENGINE's first and the class's second: an engine
        // that does not offer it claims it on no class.
        supports_performance_insights: Some(
            engine_offers_performance_insights(engine) && class.supports_performance_insights,
        ),
        supports_iam_database_authentication: Some(supports_iam_database_authentication(engine)),
        // The engine modes and the global-database capability are the VERSION's, read
        // from the engine catalogue, so this report and `DescribeDBEngineVersions` cannot
        // disagree about the version an option is offered for.
        supported_engine_modes: Some(
            profile
                .engine_modes
                .iter()
                .map(|mode| (*mode).to_string())
                .collect(),
        ),
        supports_global_databases: Some(docdb.map_or(
            profile.supports_global_databases,
            |capabilities| capabilities.global_databases,
        )),
        // "Whether DB instances can be configured as a Multi-AZ DB cluster": an instance of a
        // CLUSTER engine is only ever configured as a member of its cluster, so every option
        // of one reports it — the wire recording of this report for `aurora-postgresql` on
        // `db.serverless` carries `SupportsClusters` true, as the document engine's own
        // recorded options do for every class — and an instance of an engine that owns its own
        // storage reports it where that engine can back a Multi-AZ DB cluster on that CLASS
        // ([`offers_multi_az_db_clusters`]).
        supports_clusters: Some(
            is_cluster_engine(engine) || offers_multi_az_db_clusters(engine, &class.name),
        ),
        // A dedicated log volume carries the instance's transaction logs, so it is offered
        // on the storage type the ORDER names rather than per engine: the Provisioned IOPS
        // SSD types take one ([`StorageProfile::dedicated_log_volume`]), and a cluster
        // engine's cluster-managed storage takes none.
        supports_dedicated_log_volume: Some(storage.dedicated_log_volume),
        supported_activity_stream_modes: Some(activity_stream_modes(engine, class)),
        // `AvailableProcessorFeatures` is "a list of the available processor features for the
        // DB instance class", and a class that exposes none has an EMPTY list of them rather
        // than no list: AWS reports the member on every orderable option, so a class with no
        // configurable feature reports it empty.
        available_processor_features: Some(processor_features),
        // An option is offered for the network types the resource's own `NetworkType`
        // publishes — the value list a create of this door's own engines is held to
        // (`crate::state::NETWORK_TYPES`, "IPV4 | DUAL"), reported in the order a recorded
        // option carries them — so the catalogue and the create cannot disagree about a
        // network a resource can be placed on. An engine of another control plane publishes
        // its own (the document engine's `DBCluster$NetworkType`: "Valid Values: IPV4 |
        // DUAL").
        supported_network_types: Some(match docdb {
            Some(_) => ::service_common::docdb_engine_catalog::NETWORK_TYPES
                .iter()
                .map(|network_type| (*network_type).to_string())
                .collect(),
            None => reported_network_types(),
        }),
        // `AvailabilityZoneGroup` names a Local Zone group and `OutpostCapable` an AWS
        // Outpost; this service offers neither, which is also what the document engine's
        // own capability set publishes, so no option claims one.
        outpost_capable: Some(docdb.is_some_and(|capabilities| capabilities.outpost_capable)),
        // Kerberos authentication is published per ENGINE, and AWS answers the capability on
        // every option, so an engine of this door's own control plane reports it too
        // ([`supports_kerberos_authentication`]) rather than leaving it absent; an engine of
        // another control plane answers from its own capability set.
        supports_kerberos_authentication: Some(docdb.map_or_else(
            || supports_kerberos_authentication(engine),
            |capabilities| capabilities.kerberos_authentication,
        )),
        // Additional storage volumes are volumes ordered BESIDE the instance's own storage,
        // which no class this door offers takes: the member is reported false rather than
        // left absent, because AWS answers the capability on every option, and the options
        // for them ([`AvailableAdditionalStorageVolumesOptions`]) are then none at all.
        supports_additional_storage_volumes: Some(
            docdb.is_some_and(|capabilities| capabilities.additional_storage_volumes),
        ),
        // The Data API HTTP endpoint IS modelled for this door's own engines: whether a
        // cluster of the engine has one to turn on is the answer `EnableHttpEndpoint` is
        // held to (`crate::state::cluster_has_toggleable_http_endpoint`), read here over the
        // engine modes the VERSION is offered in, so the catalogue and the toggle cannot
        // disagree about an engine's endpoint.
        supports_http_endpoint: Some(docdb.map_or_else(
            || {
                profile.engine_modes.iter().any(|mode| {
                    crate::state::cluster_has_toggleable_http_endpoint(engine, mode)
                })
            },
            |capabilities| capabilities.http_endpoint,
        )),
        // Optimized reads, optimized writes and the custom-processor-feature requirement are
        // members AWS reports on EVERY orderable option (each one's own documentation on
        // `OrderableDBInstanceOption` says so), so they are answered for this door's own
        // engines too rather than left absent:
        //
        // * Optimized Reads places temporary objects on the instance's LOCAL NVMe SSD
        //   storage, so it is offered on the general-purpose and memory-optimized classes
        //   that have one ([`offers_optimized_reads`]);
        // * Optimized Writes is the MySQL-compatible RDS engines' atomic-write capability
        //   ([`offers_optimized_writes`]); and
        // * no class this door publishes has to have its processor features named at order
        //   time, so the requirement is reported false.
        supports_optimized_reads: Some(docdb.map_or_else(
            || offers_optimized_reads(engine, &class.name),
            |capabilities| capabilities.optimized_reads,
        )),
        supports_optimized_writes: Some(docdb.map_or_else(
            || offers_optimized_writes(engine, class),
            |capabilities| capabilities.optimized_writes,
        )),
        requires_custom_processor_features: Some(
            docdb.is_some_and(|capabilities| capabilities.requires_custom_processor_features),
        ),
        ..Default::default()
    }
}

/// Whether the DB instance class `name` has LOCAL NVMe SSD storage, which is what RDS and
/// Aurora Optimized Reads place their temporary objects on.
///
/// The published instance-class naming states it in the ATTRIBUTE letters that follow a
/// family's generation number: `d` there is local instance storage, which is what
/// `db.m5d.large`, `db.r6gd.2xlarge` and `db.x2iedn.xlarge` carry and what `db.m6i.large`
/// and `db.r7g.large` do not. A class without one has nowhere to put the temporary objects,
/// and the serverless capacity class is not a family-and-size class at all.
fn class_has_local_nvme_storage(name: &str) -> bool {
    class_family(name)
        // The family is a prefix of letters, the generation number, then the attribute
        // letters; only the last of the three is read here.
        .trim_start_matches(|c: char| c.is_ascii_alphabetic())
        .contains('d')
}

/// The FAMILY part of the DB instance class `name`: the `m6gd` of `db.m6gd.8xlarge`, which
/// the published `db.<family>.<size>` naming puts between the two dots. Empty for a value
/// that is not written that way.
fn class_family(name: &str) -> &str {
    name.strip_prefix("db.")
        .and_then(|rest| rest.split('.').next())
        .unwrap_or_default()
}

/// The letters a DB instance class family OPENS with — the `m` of `m6gd`, the `x` of
/// `x2iedn`, the `t` of `t4g` — which is what the published instance-class naming states the
/// class's PURPOSE in: `t` burstable performance, `c` compute optimized, `m` general purpose,
/// and `r`, `x` and `z` memory optimized.
fn class_family_purpose(name: &str) -> &str {
    let family = class_family(name);
    let letters = family
        .find(|character: char| !character.is_ascii_alphabetic())
        .unwrap_or(family.len());
    &family[..letters]
}

/// The family-purpose letters of the classes Amazon RDS publishes its memory- and
/// compute-intensive capabilities on: GENERAL PURPOSE (`m`) and MEMORY OPTIMIZED (`r`, `x`,
/// `z`).
///
/// Those capabilities — Multi-AZ DB clusters, Optimized Reads and Optimized Writes — publish
/// their supported classes as whole FAMILIES of those two purposes and never as a burstable
/// (`t`) or compute-optimized (`c`) family, whose shared or compute-weighted hosts they are
/// not offered on.
const CAPABLE_CLASS_FAMILY_PURPOSES: [&str; 4] = ["m", "r", "x", "z"];

/// Whether `name` is a general-purpose or memory-optimized class
/// ([`CAPABLE_CLASS_FAMILY_PURPOSES`]).
fn class_is_general_purpose_or_memory_optimized(name: &str) -> bool {
    CAPABLE_CLASS_FAMILY_PURPOSES.contains(&class_family_purpose(name))
}

/// Whether an option of `engine` on the class `class_name` reports that a DB instance of it
/// can be configured as a MULTI-AZ DB CLUSTER (`SupportsClusters`).
///
/// A Multi-AZ DB cluster is the deployment with two READABLE standby DB instances, which
/// Amazon RDS publishes for the MySQL and PostgreSQL engines (and for no other engine whose
/// instance owns its storage), on the general-purpose and memory-optimized classes that carry
/// LOCAL NVMe SSD storage — `db.m5d`, `db.m6gd`, `db.r5d`, `db.r6gd` and their siblings. A
/// burstable class is not one of them, and neither is a compute-optimized class with local
/// storage: the published class list is read as the families of those two purposes
/// ([`class_is_general_purpose_or_memory_optimized`]) rather than as one spelling of a class
/// name, so a class of a published family this report offers answers the same way its
/// siblings do.
fn offers_multi_az_db_clusters(engine: &str, class_name: &str) -> bool {
    matches!(engine, "mysql" | "postgres")
        && class_is_general_purpose_or_memory_optimized(class_name)
        && class_has_local_nvme_storage(class_name)
}

/// Whether an option of `engine` on `class` reports Optimized Reads.
///
/// The feature places a query's temporary objects on the instance's LOCAL NVMe SSD storage
/// ([`class_has_local_nvme_storage`]), so it is offered on a class that HAS one, for an
/// engine whose DB INSTANCE owns its storage. Which classes those are is published as the
/// general-purpose and memory-optimized families with that storage
/// ([`class_is_general_purpose_or_memory_optimized`]) — the `d` generations of the `m`, `r`
/// and `x` families — and not the compute-optimized ones, whose local storage the feature is
/// not published on. An engine whose CLUSTER manages the storage offers it on no class at all
/// — a cluster member's temporary objects are not placed on the host it happens to run on —
/// which is what the recorded options of the two cluster control planes this door serves
/// report for every class they publish, the local-NVMe classes of the graph engine's own
/// class list included.
fn offers_optimized_reads(engine: &str, class_name: &str) -> bool {
    !is_cluster_engine(engine)
        && class_is_general_purpose_or_memory_optimized(class_name)
        && class_has_local_nvme_storage(class_name)
}

/// Whether an option of `engine` on `class` reports Optimized Writes.
///
/// Amazon RDS Optimized Writes is the MySQL-compatible engines' atomic-write capability: it
/// is published for Amazon RDS for MySQL and Amazon RDS for MariaDB — the engines that run
/// the storage engine whose double-write buffer it replaces — on the general-purpose and
/// memory-optimized classes, whose hosts carry the torn-write protection it is built on, and
/// on neither the burstable classes nor the compute-optimized ones
/// ([`class_is_general_purpose_or_memory_optimized`]). No other engine of this door publishes
/// it.
fn offers_optimized_writes(engine: &str, class: &InstanceClass) -> bool {
    matches!(engine, "mysql" | "mariadb")
        && !class.burstable
        && class_is_general_purpose_or_memory_optimized(&class.name)
}

/// `SupportedNetworkTypes` of an option of this door's own engines: the value list
/// `NetworkType` publishes for a DB instance and a DB cluster
/// ([`crate::state::NETWORK_TYPES`]), in the order that value list names them ("IPV4 |
/// DUAL") — which is the order a recorded option carries them in, and the order the engines
/// of another control plane publish their own list in
/// (`::service_common::docdb_engine_catalog::NETWORK_TYPES`), so the two views of this one
/// door report one order.
fn reported_network_types() -> Vec<String> {
    crate::state::NETWORK_TYPES
        .iter()
        .map(|network_type| (*network_type).to_string())
        .collect()
}
