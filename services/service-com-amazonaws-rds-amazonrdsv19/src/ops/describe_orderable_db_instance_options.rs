const SERVERLESS_CLASS: &str = "db.serverless";

/// The threads each configurable (Intel) core runs, which is also why a class's
/// `coreCount` is half its vCPU count: the published `threadsPerCore` processor feature
/// allows `1,2`.
const THREADS_PER_CORE: i32 = 2;

/// One DB instance class this service offers, as an option reports it.
pub struct InstanceClass {
    /// `DBInstanceClass`.
    pub name: String,
    /// Whether the class is burstable (see [`InstanceFamily::burstable`]).
    pub burstable: bool,
    /// The CPU CORES whose count a caller can configure on this class, or `None` for a
    /// class whose processor features are not configurable (a burstable or Graviton
    /// class, or a size whose vCPU count the published naming does not state).
    pub cores: Option<i32>,
    /// Whether `SupportsPerformanceInsights`.
    pub supports_performance_insights: bool,
}

/// The profile of the class NAMED `name` for `engine`.
///
/// A class this service's family table publishes carries that row's profile. A class
/// outside it is still a real class — `crate::state::check_db_instance_class` admits every
/// value of the published `db.<family>.<size>` form, because which classes exist is AWS's
/// moving per-region matrix and this table is an explicitly partial subset of it — so one
/// is profiled from its NAME: burstable exactly for the burstable (`t`) generations, and
/// with no configurable processor cores, since the vCPU count of a family this table does
/// not publish is not known here.
pub fn instance_class_profile(engine: &str, name: &str) -> InstanceClass {
    if let Some(published) = instance_classes(engine)
        .into_iter()
        .find(|class| class.name.eq_ignore_ascii_case(name))
    {
        return published;
    }
    let family = name
        .strip_prefix("db.")
        .and_then(|rest| rest.split('.').next())
        .unwrap_or_default();
    InstanceClass {
        name: name.to_string(),
        burstable: family.starts_with('t'),
        cores: None,
        supports_performance_insights: true,
    }
}

/// The vCPU count the published instance-size naming gives `size`: a `large` is 2 vCPUs
/// and each `<n>xlarge` is `4 * n`, with `xlarge` as `n = 1`. `None` for the burstable
/// sizes (`micro`, `small`, `medium`), whose vCPUs are shared and whose count is
/// therefore not a configurable processor feature.
fn vcpus(size: &str) -> Option<i32> {
    /// `(size, vCPUs)` for the sizes whose name states the count.
    const SIZE_VCPUS: &[(&str, i32)] = &[
        ("large", 2),
        ("xlarge", 4),
        ("2xlarge", 8),
        ("4xlarge", 16),
        ("8xlarge", 32),
        ("12xlarge", 48),
        ("16xlarge", 64),
        ("24xlarge", 96),
        ("32xlarge", 128),
    ];

    SIZE_VCPUS
        .iter()
        .find(|(name, _)| *name == size)
        .map(|(_, vcpus)| *vcpus)
}

/// The number of vCPUs the DB instance class `db_instance_class` has, or `None` for a class
/// whose hardware this service publishes nothing about.
///
/// The sibling of [`class_memory_bytes`], read off the same published naming: a `large` is 2
/// vCPUs and each `<n>xlarge` is `4 * n` ([`vcpus`]), and the three burstable sizes below
/// `large` carry [`BURSTABLE_SHARED_VCPUS`].
///
/// `pub` for the same reason as [`class_memory_bytes`]: a constraint another operation states
/// over the vCPU count of a class — the minimum reserved capacity a future-dated DB capacity
/// reservation must total — is evaluated against this one published table rather than a
/// second copy of it.
pub fn class_vcpus(db_instance_class: &str) -> Option<i32> {
    let lowered = db_instance_class.to_ascii_lowercase();
    let (family, size) = lowered.strip_prefix("db.")?.split_once('.')?;
    if family.starts_with('t')
        && BURSTABLE_SIZE_MEMORY_GIB
            .iter()
            .any(|(named, _)| *named == size)
    {
        return Some(BURSTABLE_SHARED_VCPUS);
    }
    vcpus(size)
}

/// The vCPUs a BURSTABLE class below `large` has: the three sizes whose count the
/// `<n>xlarge` naming does not give.
///
/// Source: the same "DB instance classes — hardware specifications" table
/// [`BURSTABLE_SIZE_MEMORY_GIB`] is read off, which publishes two vCPUs for each of the
/// burstable `micro`, `small` and `medium` sizes.
const BURSTABLE_SHARED_VCPUS: i32 = 2;

/// One gibibyte, the unit the published instance-class table states memory in.
const GIB: u64 = 1024 * 1024 * 1024;

/// The memory a BURSTABLE class below `large` has, in GiB: the three sizes whose memory the
/// per-vCPU rule below does not give, because their vCPUs are shared.
///
/// Source: the "DB instance classes — hardware specifications" table in the Amazon RDS User
/// Guide, which publishes the vCPU count and the memory of every class. The burstable
/// generations (`t2`, `t3`, `t4g`) publish the same memory for these three sizes.
const BURSTABLE_SIZE_MEMORY_GIB: &[(&str, u64)] = &[("micro", 1), ("small", 2), ("medium", 4)];

/// The memory a class has PER vCPU, in GiB, by the family's own generation letter — which is
/// what the published table's families are grouped by.
///
/// Source: the same hardware-specification table. It states one ratio per family class, so a
/// class's memory follows from its vCPU count: a compute family carries 2 GiB per vCPU
/// (`db.c6gd.large`, 2 vCPUs, 4 GiB), a general-purpose or burstable family 4
/// (`db.m5.large`, 2 vCPUs, 8 GiB; `db.t3.xlarge`, 4 vCPUs, 16 GiB) and a memory-optimised
/// one 8 (`db.r5.large`, 2 vCPUs, 16 GiB). The ratio is stated per family rather than per
/// class so a SIZE this service does not publish an option for still has the memory its
/// family gives it.
const FAMILY_MEMORY_GIB_PER_VCPU: &[(&str, u64)] = &[
    // Compute optimised.
    ("c", 2),
    // General purpose, and the burstable families from `large` up.
    ("m", 4),
    ("t", 4),
    // Memory optimised.
    ("r", 8),
    ("z", 8),
    // The memory-optimised `x2iedn` line, whose ratio is its own
    // (`db.x2iedn.xlarge`, 4 vCPUs, 128 GiB).
    ("x2iedn", 32),
    // The Graviton memory-optimised `x2g` line (`db.x2g.large`, 2 vCPUs, 32 GiB).
    ("x2g", 16),
];

/// The memory the DB instance class `db_instance_class` has, in BYTES, or `None` for a class
/// whose memory this service publishes nothing about.
///
/// This is what a published parameter default written as a formula over
/// `DBInstanceClassMemory` is evaluated with
/// ([`crate::state::parameter_formula`]), so the engine of an instance runs with the value
/// its own class gives. The figure is the class's published memory: the share of it Amazon
/// RDS reserves for the operating system and its own processes is not published per class,
/// so nothing is subtracted here rather than a reservation being invented.
///
/// `None` for the serverless capacity class, which is not a family-and-size class and has no
/// fixed memory at all, and for a family or size outside the tables above — a class whose
/// hardware this service does not know is one no formula can be evaluated for.
pub fn class_memory_bytes(db_instance_class: &str) -> Option<u64> {
    let lowered = db_instance_class.to_ascii_lowercase();
    let (family, size) = lowered.strip_prefix("db.")?.split_once('.')?;
    if let Some((_, gib)) = BURSTABLE_SIZE_MEMORY_GIB
        .iter()
        .find(|(named, _)| *named == size)
        .filter(|_| family.starts_with('t'))
    {
        return gib.checked_mul(GIB);
    }
    let vcpus = u64::try_from(vcpus(size)?).ok()?;
    // The longest matching family key wins, so a line with a ratio of its own
    // (`x2iedn`) is not read as its generation letter.
    let (_, gib_per_vcpu) = FAMILY_MEMORY_GIB_PER_VCPU
        .iter()
        .filter(|(named, _)| family.starts_with(named))
        .max_by_key(|(named, _)| named.len())?;
    // Checked, so a table entry or a size the published naming grows past `u64` answers no
    // memory rather than a wrapped one.
    gib_per_vcpu.checked_mul(vcpus)?.checked_mul(GIB)
}

/// The classes `engine` can be ordered in, built from the family tables above.
///
/// `pub` because this catalogue is the service's one published answer to "what can a DB
/// instance be": `DescribeValidDBInstanceModifications` reports the bounds of the class a
/// stored instance already runs, and reads them from here so the two reports cannot
/// disagree about a class.
pub fn instance_classes(engine: &str) -> Vec<InstanceClass> {
    let cluster = is_cluster_engine(engine) && publishes_serverless_capacity(engine);
    let mut classes: Vec<InstanceClass> = instance_families(engine)
        .iter()
        .flat_map(|family| {
            family.sizes.iter().map(move |size| InstanceClass {
                name: format!("db.{}.{size}", family.family),
                burstable: family.burstable,
                cores: if family.burstable || family.graviton {
                    None
                } else {
                    vcpus(size).map(|vcpus| vcpus / THREADS_PER_CORE)
                },
                // Performance Insights is not offered on the two smallest burstable
                // sizes; every other class this service offers takes it.
                supports_performance_insights: !(family.burstable
                    && matches!(*size, "micro" | "small")),
            })
        })
        .collect();
    if cluster {
        classes.push(InstanceClass {
            name: SERVERLESS_CLASS.to_string(),
            burstable: false,
            cores: None,
            supports_performance_insights: true,
        });
    }
    classes
}

/// Whether a cluster member of `engine` can be ordered with SERVERLESS capacity, which is
/// what the `db.serverless` capacity class is ([`SERVERLESS_CLASS`]).
///
/// The Aurora engines of this control plane are ordered with it (Aurora Serverless v2), and
/// so is a member of a graph cluster (Neptune Serverless). The DocumentDB control plane
/// offers no serverless capacity for a cluster member at all — its elastic clusters are a
/// resource of their own API, created with shards rather than with a DB instance class — so
/// no option of that engine names the capacity class.
fn publishes_serverless_capacity(engine: &str) -> bool {
    engine != ::service_common::docdb_engine_catalog::ENGINE
}

/// The DB instance FAMILIES `engine` can be ordered in: the family rows this report is
/// built from, which is the part of AWS's per-region, per-engine matrix this service
/// publishes.
fn instance_families(engine: &str) -> &'static [InstanceFamily] {
    if engine.eq_ignore_ascii_case(crate::state::NEPTUNE_ENGINE) {
        // The graph engine's control plane publishes its own class list ([`GRAPH_FAMILIES`]).
        return GRAPH_FAMILIES;
    }
    if engine.eq_ignore_ascii_case(::service_common::docdb_engine_catalog::ENGINE) {
        // So does the document engine's ([`DOCUMENT_FAMILIES`]).
        return DOCUMENT_FAMILIES;
    }
    if is_cluster_engine(engine) {
        CLUSTER_FAMILIES
    } else {
        PROVISIONED_FAMILIES
    }
}

/// Whether this report publishes any option at all in the instance GENERATION
/// `db_instance_class` names — the family part of `db.<family>.<size>`.
///
/// The published matrix is families crossed with sizes, and it is an explicitly PARTIAL
/// subset of AWS's own, which moves with every instance-type launch, in both directions:
/// a SIZE outside the rows is still a size AWS may offer in a family that is in them
/// (`db.m5.24xlarge`), and which of its families each ENGINE offers is the part of the
/// matrix this service does not hold. What the report does publish about a class is
/// therefore its generation: the families any DB instance can be ordered in. A class whose
/// family appears in no row of either table names a generation this service offers no
/// option in — a previous-generation family no engine version it publishes can be created
/// with — which is what the real service refuses a create of.
///
/// The generations of EVERY control plane this door serves are in scope, the graph engine's
/// own ([`GRAPH_FAMILIES`]) included: the question this answers is whether the generation
/// exists at all, not whether the engine a create names is offered in it — which engine is
/// offered which family is exactly the part of AWS's matrix this service does not hold, so a
/// create naming a published generation is admitted and the per-engine option report
/// ([`instance_classes`]) remains the one answer to what that engine is orderable as.
pub fn publishes_instance_family(db_instance_class: &str) -> bool {
    // The serverless capacity class has no family-and-size form at all; it is published as
    // an option of its own, so the class itself is the generation.
    if db_instance_class.eq_ignore_ascii_case(SERVERLESS_CLASS) {
        return true;
    }
    let Some(family) = db_instance_class
        .strip_prefix("db.")
        .and_then(|rest| rest.split('.').next())
    else {
        return false;
    };
    PROVISIONED_FAMILIES
        .iter()
        .chain(CLUSTER_FAMILIES)
        .chain(DOCUMENT_FAMILIES)
        .chain(GRAPH_FAMILIES)
        .any(|row| row.family.eq_ignore_ascii_case(family))
}

/// Whether this report offers `engine` under `license_model` ([`license_models`]).
pub fn offers_license_model(engine: &str, license_model: &str) -> bool {
    license_models(engine)
        .iter()
        .any(|offered| offered.eq_ignore_ascii_case(license_model))
}

/// The license models `engine` can be ordered under, as `CreateDBInstance`'s
/// `LicenseModel` member documents them per engine ("`license-included`",
/// "`bring-your-own-license`", "`general-public-license`", "`postgresql-license`",
/// "`marketplace-license`").
///
/// An engine of another control plane this one front door serves is licensed by that
/// control plane rather than by a database vendor, so its licence is the one THAT engine
/// publishes and not a value from the list above.
///
/// `pub` for the same reason as [`instance_classes`]: a create that names a licence
/// resolves it against the licences published here.
pub fn license_models(engine: &str) -> &'static [&'static str] {
    match engine {
        "postgres" | "aurora-postgresql" => &["postgresql-license"],
        "mysql" | "mariadb" | "aurora-mysql" => &["general-public-license"],
        // An engine AWS licenses itself is ordered under its own licence: the graph
        // engine of the Amazon Neptune control plane this door serves reports
        // `amazon-license`, the one licence a Neptune instance runs under.
        "neptune" => &["amazon-license"],
        // The licence setting "doesn't apply to" the Amazon DocumentDB engine, whose
        // orderable options carry `na`.
        "docdb" => &["na"],
        // Oracle Enterprise Edition is BYOL only; Standard Edition Two is offered both
        // ways.
        "oracle-ee" | "oracle-ee-cdb" => &["bring-your-own-license"],
        "oracle-se2" | "oracle-se2-cdb" => &["license-included", "bring-your-own-license"],
        // Db2 is ordered through a Marketplace subscription or BYOL.
        "db2-ae" | "db2-ce" | "db2-se" => &["bring-your-own-license", "marketplace-license"],
        // Every SQL Server edition RDS offers includes its licence.
        _ => &["license-included"],
    }
}

