/// `AuthFlowType`'s choice-based entry point: "USER_AUTH — The entry point for
/// choice-based authentication" (`InitiateAuth.AuthFlow` in this service's model).
const USER_AUTH: &str = "USER_AUTH";

/// The `AuthParameters` entry a `USER_AUTH` request names the challenge it wants
/// with: "USER_AUTH: USERNAME (required), PREFERRED_CHALLENGE"
/// (`InitiateAuth.AuthParameters`).
const PREFERRED_CHALLENGE: &str = "PREFERRED_CHALLENGE";

/// The email one-time-password challenge (`ChallengeNameType`), which is also the
/// `SignInPolicyType.AllowedFirstAuthFactors` value that admits it.
const EMAIL_OTP: &str = "EMAIL_OTP";

/// The attribute an email one-time password is delivered to.
const EMAIL: &str = "email";

/// The `ChallengeParameters` entries a delivered challenge reports its delivery
/// under, the same two values `CodeDeliveryDetailsType` carries.
const CODE_DELIVERY_DELIVERY_MEDIUM: &str = "CODE_DELIVERY_DELIVERY_MEDIUM";
const CODE_DELIVERY_DESTINATION: &str = "CODE_DELIVERY_DESTINATION";

/// The `AuthParameters` entry that names the device the sign-in comes from:
/// "Add `DEVICE_KEY` if you want to bypass multi-factor authentication with a
/// remembered device" (`InitiateAuth.AuthParameters` in this service's model).
const DEVICE_KEY: &str = "DEVICE_KEY";

/// `AuthFlow=USER_PASSWORD_AUTH`: "Client-side username-password authentication with
/// the password sent directly in the request" (`InitiateAuth.AuthFlow`), whose
/// `AuthParameters` are `USERNAME` and `PASSWORD`, both documented "required".
///
/// The password is checked against the one STORED for the user, and the app client the
/// request names is what resolves the pool.
///
/// The stored state decides the sign-in under ONE lock, which is released before the
/// pool's own Lambda triggers are invoked: the pre-authentication trigger gates the sign-in
/// this request asked for, and the pre-token-generation trigger gates the tokens a complete
/// one mints, so neither is waited on while every other request of this service waits for
/// the lock.
async fn password_sign_in(
    store: &Store,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    client_id: &str,
    auth_parameters: &::std::collections::HashMap<String, String>,
    client_metadata: Option<&::std::collections::HashMap<String, String>>,
    caller: crate::state::lambda_triggers::Caller<'_>,
    now: ::std::time::SystemTime,
) -> Result<InitiateAuthOutput, InitiateAuthError> {
    let username = auth_parameters
        .get("USERNAME")
        .ok_or_else(|| missing_auth_parameter("USERNAME", USER_PASSWORD_AUTH))?;
    let password = auth_parameters
        .get("PASSWORD")
        .ok_or_else(|| missing_auth_parameter("PASSWORD", USER_PASSWORD_AUTH))?;

    let outcome = {
        let mut decided = decide_password_sign_in(store, client_id, username, password, now, true)?;
        // A pool whose `LambdaConfig` names a migrate-user function has not decided a
        // username it does not hold yet: that trigger "can create user profiles when users
        // sign in ... with credentials that don't exist yet"
        // (`LambdaConfigType$UserMigration`), so the function is asked about the username
        // this request presented, with the password it presented, and the sign-in is then
        // decided again over the state that migration left. A username the function
        // declined is left as unknown as it was.
        if let Decided::MigrateUser { user_pool_id } = &decided {
            let user_pool_id = user_pool_id.clone();
            crate::state::lambda_triggers::user_migration::fire_user_migration(
                ctx,
                store,
                &user_pool_id,
                username,
                crate::state::lambda_triggers::user_migration::MigrationSource::Authentication,
                Some(password),
                caller,
                client_metadata,
            )
            .await
            .map_err(trigger_failed)?;
            decided =
                decide_password_sign_in(store, client_id, username, password, now, false)?;
        }
        match decided {
            Decided::Outcome(outcome) => outcome,
            // The second pass asks for no migration, so this cannot be reached.
            Decided::MigrateUser { .. } => return Err(user_not_found()),
        }
    };

    // The request has proved it holds this user's password, so the sign-in it asked for has
    // reached the pre-authentication stage: the trigger there "can evaluate and modify user
    // sign-in events" (`LambdaConfigType$PreAuthentication`), so nothing further happens
    // until the function the pool names has allowed it.
    let (user_pool_id, username) = match &outcome {
        Outcome::Challenge {
            user_pool_id,
            username,
            ..
        }
        | Outcome::MfaSetup {
            user_pool_id,
            username,
            ..
        }
        | Outcome::Authenticate {
            user_pool_id,
            username,
        } => (user_pool_id.clone(), username.clone()),
    };
    crate::state::lambda_triggers::fire_pre_authentication(
        ctx,
        store,
        &user_pool_id,
        &username,
        caller,
        client_metadata,
    )
    .await
    .map_err(trigger_failed)?;

    match outcome {
        Outcome::Challenge {
            user_pool_id,
            username,
            required_attributes,
            user_attributes,
            session_validity,
        } => {
            let session = store.lock().start_session(
                now,
                crate::state::AuthSession {
                    user_pool_id,
                    client_id: client_id.to_string(),
                    username: username.clone(),
                    challenge_name: NEW_PASSWORD_REQUIRED.to_string(),
                    expires_at: now + session_validity,
                    // Outstanding: this session has answered nothing yet.
                    spent: false,
                    // This challenge is answered with a password the user chooses,
                    // not with a code anything delivered.
                    code: None,
                },
            );
            let challenge_parameters = crate::state::new_password_required_challenge_parameters(
                &username,
                &required_attributes,
                &user_attributes,
            );
            Ok(InitiateAuthOutput {
                challenge_name: Some(NEW_PASSWORD_REQUIRED.to_string()),
                session: Some(session),
                challenge_parameters: Some(challenge_parameters),
                authentication_result: None,
                available_challenges: None,
            })
        }
        Outcome::MfaSetup {
            user_pool_id,
            username,
            settings_can_setup,
            session_validity,
        } => {
            let session = store.lock().start_session(
                now,
                crate::state::AuthSession {
                    user_pool_id,
                    client_id: client_id.to_string(),
                    username: username.clone(),
                    challenge_name: MFA_SETUP.to_string(),
                    expires_at: now + session_validity,
                    // Outstanding: this session has answered nothing yet.
                    spent: false,
                    // This challenge is answered by registering a factor, not
                    // with a code anything delivered.
                    code: None,
                },
            );
            Ok(InitiateAuthOutput {
                challenge_name: Some(MFA_SETUP.to_string()),
                session: Some(session),
                challenge_parameters: Some(crate::state::mfa_setup_challenge_parameters(
                    &username,
                    &settings_can_setup,
                )),
                authentication_result: None,
                available_challenges: None,
            })
        }
        Outcome::Authenticate {
            user_pool_id,
            username,
        } => {
            // The authentication is complete, so the tokens it answers with are the next
            // stage, and the pre-token-generation trigger gates them: "called after user
            // authentication flows have completed" is this generation's own documented
            // trigger source.
            let overrides = crate::state::lambda_triggers::fire_pre_token_generation(
                ctx,
                store,
                &user_pool_id,
                &username,
                crate::state::lambda_triggers::TokenGeneration::Authentication,
                caller,
                client_metadata,
            )
            .await
            .map_err(trigger_failed)?;

            let state = &mut *store.lock();
            let mut authentication_result = state
                .issue_tokens(
                    &user_pool_id,
                    client_id,
                    &username,
                    now,
                    ctx.credential_store(),
                    ctx.parts(),
                    &overrides,
                )
                .ok_or_else(internal_error)?;
            // The sign-in is complete, so the device it came from is now part of
            // this user's state on a pool that remembers devices, and the key of a
            // device the pool did not recognise is what the caller needs to confirm
            // it. `AuthParameters`: "Add `DEVICE_KEY` if you want to bypass
            // multi-factor authentication with a remembered device" — the device
            // the request presented, if any.
            authentication_result.new_device_metadata = state.track_sign_in_device(
                &user_pool_id,
                &username,
                auth_parameters.get(DEVICE_KEY).map(String::as_str),
                now,
            );
            Ok(authenticated(authentication_result))
        }
    }
}

/// What the stored state decided a password sign-in is, or that it cannot be decided
/// without the pool's migrate-user function.
enum Decided {
    /// The sign-in itself, as the stored state settles it.
    Outcome(Outcome),
    /// The pool holds no such user and names a migrate-user function, so the function
    /// decides whether this username names a user at all.
    MigrateUser { user_pool_id: String },
}

/// Decide the password sign-in of `username` through `client_id` from the STORED state,
/// before anything is written.
///
/// `may_migrate` is whether a username the pool does not hold may still be migrated: the
/// first pass of a pool that configures a migrate-user function asks for that migration, and
/// the pass that follows it decides over the state the migration left.
///
/// Everything here happens under this service's lock, which this call OWNS: the lock is
/// taken and released inside it, so its caller holds none of it while it invokes a trigger
/// function.
fn decide_password_sign_in(
    store: &Store,
    client_id: &str,
    username: &str,
    password: &str,
    now: ::std::time::SystemTime,
    may_migrate: bool,
) -> Result<Decided, InitiateAuthError> {
    let state = &mut *store.lock();
    let pool = state
        .pool_of_client(client_id)
        .ok_or_else(|| client_not_found(client_id))?;
    let client = pool
        .clients
        .get(client_id)
        .ok_or_else(|| client_not_found(client_id))?;
    if !client.allows_user_password_auth() {
        return Err(invalid_parameter(
            crate::state::auth_flow_not_enabled_message(USER_PASSWORD_AUTH),
        ));
    }
    let hides_user_existence = client.hides_user_existence();
    let session_validity = client.auth_session_validity();
    let temporary_password_validity = pool.temporary_password_validity();
    let user_pool_id = pool.id.clone();

    let Some(user) = pool.user(username) else {
        // A pool that names a migrate-user function has not decided this username yet:
        // the function is asked about it before the sign-in is refused.
        if may_migrate && pool.migrates_absent_users() {
            return Ok(Decided::MigrateUser { user_pool_id });
        }
        // `PreventUserExistenceErrors=ENABLED` "suppresses messages that might
        // indicate a valid user exists"; `LEGACY` answers `UserNotFoundException`.
        return Err(if hides_user_existence {
            incorrect_credentials()
        } else {
            user_not_found()
        });
    };
    // The stored user's own state is read FIRST, as the administrative sign-in
    // reads it: a user that never confirmed its sign-up, one Amazon Cognito put in
    // `RESET_REQUIRED` and a disabled one cannot sign in whatever credential the
    // request presents, so each is reported for what it is rather than as a wrong
    // password. The credential therefore decides nothing about the ANSWER for such a
    // user, which is what keeps the error code from telling a caller whether the
    // password it presented was the right one.
    refuse_unusable_user(user)?;
    // The stored credential, actually checked. A user that exists and may sign in
    // gets the one refusal a wrong password owes, which is also what an absent user
    // gets where the app client hides user existence: nothing in that answer
    // distinguishes a user that exists from one that does not.
    if user.password.as_deref() != Some(password) {
        return Err(incorrect_credentials());
    }
    if user.temporary_password_expired(temporary_password_validity, now) {
        return Err(not_authorized(
            "Temporary password has expired and must be reset by an administrator.",
        ));
    }

    Ok(Decided::Outcome(
        if user.status == crate::state::UserStatus::ForceChangePassword {
            Outcome::Challenge {
                user_pool_id,
                username: user.username.clone(),
                required_attributes: pool.missing_required_attributes(user),
                user_attributes: user.attributes.clone(),
                session_validity,
            }
        } else if pool.requires_mfa() && user.mfa_setting_list.is_empty() {
            // The pool requires a second factor from every sign-in and this user
            // has activated none, so the sign-in cannot complete: it is answered
            // with the challenge to SET one up, naming the methods the pool
            // offers for it, and no token is minted until that is done.
            Outcome::MfaSetup {
                user_pool_id,
                username: user.username.clone(),
                settings_can_setup: pool.mfa_settings_available_for_setup(user),
                session_validity,
            }
        } else {
            Outcome::Authenticate {
                user_pool_id,
                username: user.username.clone(),
            }
        },
    ))
}

/// `AuthFlow=USER_AUTH` with `PREFERRED_CHALLENGE=EMAIL_OTP`: the choice-based entry
/// point, answered by DELIVERING a one-time password and asking for it back.
///
/// "USER_AUTH — The entry point for choice-based authentication", whose
/// `AuthParameters` are "USERNAME (required), PREFERRED_CHALLENGE"
/// (`InitiateAuth.AuthFlow` and `.AuthParameters` in this service's model). The code
/// this mints lives on the challenge SESSION, so it is answerable exactly while that
/// session lasts, and `RespondToAuthChallenge` is what accepts it.
///
/// Every other preference is left to its own implementation: a challenge nothing here
/// starts has no stored state a response to it could be checked against.
fn email_otp_sign_in(
    state: &mut State,
    client_id: &str,
    auth_parameters: &::std::collections::HashMap<String, String>,
    now: ::std::time::SystemTime,
) -> Result<(InitiateAuthOutput, Option<IssuedCode>), InitiateAuthError> {
    let username = auth_parameters
        .get("USERNAME")
        .ok_or_else(|| missing_auth_parameter("USERNAME", USER_AUTH))?;
    let preferred = auth_parameters
        .get(PREFERRED_CHALLENGE)
        .map(String::as_str)
        .unwrap_or_default();
    if preferred != EMAIL_OTP {
        return Err(crate::scaffolded::Scaffolded::not_implemented(&format!(
            "InitiateAuth with AuthFlow={USER_AUTH} and PREFERRED_CHALLENGE={preferred}"
        )));
    }

    let (user_pool_id, stored_username, destination, session_validity) = {
        let pool = state
            .pool_of_client(client_id)
            .ok_or_else(|| client_not_found(client_id))?;
        let client = pool
            .clients
            .get(client_id)
            .ok_or_else(|| client_not_found(client_id))?;
        if !client.allows_user_auth() {
            return Err(invalid_parameter(
                crate::state::auth_flow_not_enabled_message(USER_AUTH),
            ));
        }
        // `SignInPolicyType.AllowedFirstAuthFactors` is what the POOL admits as a
        // first authentication factor, so a pool that does not list this one does
        // not offer it.
        if !pool.allows_first_auth_factor(EMAIL_OTP) {
            return Err(invalid_parameter(format!(
                "{EMAIL_OTP} is not an allowed first authentication factor of this user pool"
            )));
        }
        let hides_user_existence = client.hides_user_existence();
        let session_validity = client.auth_session_validity();
        let user_pool_id = pool.id.clone();

        let user = pool.user(username).ok_or_else(|| {
            if hides_user_existence {
                incorrect_credentials()
            } else {
                user_not_found()
            }
        })?;
        refuse_unusable_user(user)?;
        // A one-time password is a message, so it needs an address: only a VERIFIED
        // email address is one this challenge is delivered to.
        let destination = user.verified_destination_of(EMAIL).ok_or_else(|| {
            invalid_parameter(format!(
                "Cannot start {EMAIL_OTP} authentication as there is no registered/verified \
                 {EMAIL}"
            ))
        })?;
        (
            user_pool_id,
            user.username.clone(),
            destination,
            session_validity,
        )
    };

    // Starting the challenge is what sends the code: it is stored on the session the
    // response resumes, so answering that session is the only way to use it and a
    // second challenge gets its own session and its own code.
    let code = crate::state::VerificationCode::issued_email_otp(EMAIL, &destination, now);
    let delivery = code.delivery_details();
    // The code itself is handed to the pool's custom email sender, which on a pool that
    // configures one is the only place this one-time password is delivered at all.
    let issued = IssuedCode {
        user_pool_id: user_pool_id.clone(),
        username: stored_username.clone(),
        code: code.code.clone(),
    };
    let session = state.start_session(
        now,
        crate::state::AuthSession {
            user_pool_id,
            client_id: client_id.to_string(),
            username: stored_username,
            challenge_name: EMAIL_OTP.to_string(),
            expires_at: now + session_validity,
            code: Some(code),
            // Outstanding: this session has answered nothing yet.
            spent: false,
        },
    );

    // The delivery is reported as this API reports every sent code: the medium, and
    // the stored address masked.
    let mut challenge_parameters = ::std::collections::HashMap::new();
    if let Some(delivery) = delivery {
        if let Some(medium) = delivery.delivery_medium {
            challenge_parameters.insert(CODE_DELIVERY_DELIVERY_MEDIUM.to_string(), medium);
        }
        if let Some(destination) = delivery.destination {
            challenge_parameters.insert(CODE_DELIVERY_DESTINATION.to_string(), destination);
        }
    }
    Ok((
        InitiateAuthOutput {
            challenge_name: Some(EMAIL_OTP.to_string()),
            session: Some(session),
            challenge_parameters: Some(challenge_parameters),
            authentication_result: None,
            // "This response parameter prompts a user to select from multiple available
            // challenges": this request named the challenge it wanted, so there is no
            // selection to offer.
            available_challenges: None,
        },
        Some(issued),
    ))
}

/// One issued code and the stored user it was issued to.
struct IssuedCode {
    user_pool_id: String,
    username: String,
    code: String,
}

/// `AuthFlow=REFRESH_TOKEN_AUTH` and its `REFRESH_TOKEN` alias: "Receive new ID and
/// access tokens when you pass a `REFRESH_TOKEN` parameter with a valid refresh token
/// as the value" (`InitiateAuth.AuthFlow`), whose one required `AuthParameter` is
/// `REFRESH_TOKEN`.
///
/// "Valid" is read off the token record this emulator wrote when it issued the token:
/// it must be a refresh token, issued for the app client the request names, not revoked,
/// and not past its expiry. A token that was issued for this app client and has since
/// been REVOKED is refused as revoked, while one that resolves to no record of this app
/// client at all is refused as invalid. `auth_flow` is the member the request actually
/// named, so a refusal echoes `REFRESH_TOKEN_AUTH` or its `REFRESH_TOKEN` alias as
/// submitted.
///
/// A refresh mints tokens, so it reaches the pre-token-generation stage — "called when a
/// user tries to refresh the identity and access tokens" is this generation's own
/// documented trigger source — and the trigger there gates the tokens, with the state lock
/// released for the invocation. A refresh is not a sign-in event, so no pre-authentication
/// trigger fires for it.
#[allow(clippy::too_many_arguments)]
async fn refresh_sign_in(
    store: &Store,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    client_id: &str,
    auth_parameters: &::std::collections::HashMap<String, String>,
    client_metadata: Option<&::std::collections::HashMap<String, String>>,
    caller: crate::state::lambda_triggers::Caller<'_>,
    auth_flow: &str,
    now: ::std::time::SystemTime,
) -> Result<InitiateAuthOutput, InitiateAuthError> {
    let refresh_token = auth_parameters
        .get("REFRESH_TOKEN")
        .ok_or_else(|| missing_auth_parameter("REFRESH_TOKEN", auth_flow))?;

    let (user_pool_id, username) = {
        let state = &*store.lock();
        let pool = state
            .pool_of_client(client_id)
            .ok_or_else(|| client_not_found(client_id))?;
        let client = pool
            .clients
            .get(client_id)
            .ok_or_else(|| client_not_found(client_id))?;
        // An app client that ROTATES its refresh tokens renews a session through
        // `GetTokensFromRefreshToken` — the operation that "issues a new refresh
        // token and invalidates the original refresh token after an optional
        // grace period when refresh token rotation is enabled" (that operation in
        // this service's model) — while this flow "receive[s] new ID and access
        // tokens" and leaves the submitted refresh token in force
        // (`InitiateAuth.AuthFlow`), which is not what a rotating client does
        // with one. So this flow is not available on such a client:
        // `UnsupportedOperationException` is "thrown when you attempt to perform
        // an operation that isn't enabled for the user pool client" (this
        // service's model). Asked before the `ExplicitAuthFlows` gate below,
        // because what the rotation withdraws is the flow itself, however the
        // client's flow list is configured.
        if client.rotates_refresh_tokens() {
            return Err(unsupported_operation(
                crate::state::ROTATION_UNSUPPORTED_BY_FLOW_MESSAGE,
            ));
        }
        if !client.allows_refresh_token_auth() {
            return Err(invalid_parameter(
                crate::state::auth_flow_not_enabled_message(auth_flow),
            ));
        }
        let user_pool_id = pool.id.clone();

        // A record this emulator issued for THIS app client of THIS pool is what
        // the presented value has to resolve to; anything else — a value never
        // issued, a token of another kind, or one issued elsewhere — resolves to
        // nothing at all.
        let presented = state.token(refresh_token).filter(|record| {
            record.kind == crate::state::TokenKind::Refresh
                && record.client_id == client_id
                && record.user_pool_id == user_pool_id
        });
        // A resolved record that was REVOKED is refused as revoked, which is a
        // different answer from the one a token the service cannot resolve gets:
        // the caller holds a token this service did issue and has since
        // invalidated, so the refusal reports that rather than denying the token
        // was ever issued.
        if presented.is_some_and(|record| record.revoked) {
            return Err(refresh_token_revoked());
        }
        let (username, sub) = presented
            .filter(|record| record.expires_at > now)
            .map(|record| (record.username.clone(), record.sub.clone()))
            .ok_or_else(invalid_refresh_token)?;

        // The record is only a pointer into the pool: the user it names may have been
        // disabled, reset or deleted since the token was issued — and a user created
        // later under that name carries a different id, so it is not the user this
        // token was issued to.
        let user = state
            .pool(&user_pool_id)
            .and_then(|pool| pool.user(&username))
            .filter(|user| user.sub == sub)
            .ok_or_else(invalid_refresh_token)?;
        refuse_unusable_user(user)?;
        (user_pool_id, user.username.clone())
    };

    let overrides = crate::state::lambda_triggers::fire_pre_token_generation(
        ctx,
        store,
        &user_pool_id,
        &username,
        crate::state::lambda_triggers::TokenGeneration::RefreshTokens,
        caller,
        client_metadata,
    )
    .await
    .map_err(trigger_failed)?;

    let authentication_result = store
        .lock()
        .refresh_tokens(
            &user_pool_id,
            client_id,
            &username,
            now,
            refresh_token,
            ctx.parts(),
            &overrides,
        )
        .ok_or_else(internal_error)?;
    Ok(authenticated(authentication_result))
}

/// The refusals a stored user's own state owes any sign-in flow, whatever the flow
/// presented: a disabled user, one Amazon Cognito put in `RESET_REQUIRED`, and one that
/// never confirmed its sign-up.
fn refuse_unusable_user(user: &crate::state::User) -> Result<(), InitiateAuthError> {
    if !user.enabled {
        return Err(not_authorized("User is disabled."));
    }
    match user.status {
        crate::state::UserStatus::ResetRequired => Err(password_reset_required()),
        crate::state::UserStatus::Unconfirmed => Err(user_not_confirmed()),
        _ => Ok(()),
    }
}

/// A completed sign-in: the tokens, and none of the challenge members, which are "only
/// returned if the user doesn't need to pass another challenge"
/// (`InitiateAuthResponse.AuthenticationResult`) — beside the `ChallengeParameters` map,
/// which is present and EMPTY because no challenge is outstanding.
fn authenticated(authentication_result: AuthenticationResultType) -> InitiateAuthOutput {
    InitiateAuthOutput {
        challenge_name: None,
        session: None,
        challenge_parameters: Some(crate::state::completed_challenge_parameters()),
        authentication_result: Some(authentication_result),
        available_challenges: None,
    }
}

/// What the stored state decided a password sign-in is, read under the state lock
/// before anything is written.
enum Outcome {
    /// The password is right but the user must change it first.
    Challenge {
        user_pool_id: String,
        username: String,
        required_attributes: Vec<String>,
        user_attributes: ::std::collections::BTreeMap<String, String>,
        session_validity: ::std::time::Duration,
    },
    /// The password is right and the user may sign in.
    Authenticate {
        user_pool_id: String,
        username: String,
    },
    /// The password is right, the pool requires a second factor and the user has
    /// activated none, so one has to be set up before the sign-in completes.
    MfaSetup {
        user_pool_id: String,
        username: String,
        settings_can_setup: Vec<String>,
        session_validity: ::std::time::Duration,
    },
}

/// This operation's `ResourceNotFoundException` for a `ClientId` no stored pool holds.
fn client_not_found(client_id: &str) -> InitiateAuthError {
    InitiateAuthErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
        message: Some(crate::state::app_client_not_found_message(client_id)),
    })
    .into()
}

/// This operation's `UserNotFoundException` for an absent user. Carries the
/// fixed message of [`crate::state::USER_NOT_FOUND_MESSAGE`], which names no
/// username.
fn user_not_found() -> InitiateAuthError {
    InitiateAuthErrorModeled::UserNotFoundException(UserNotFoundException {
        message: Some(crate::state::USER_NOT_FOUND_MESSAGE.to_string()),
    })
    .into()
}

/// The refusal for a wrong password: `NotAuthorizedException`, which is also what an
/// absent user gets when the client hides user existence.
fn incorrect_credentials() -> InitiateAuthError {
    not_authorized("Incorrect username or password.")
}

/// The refusal for a `REFRESH_TOKEN` this emulator cannot resolve to a live refresh
/// token of the app client the request names.
///
/// One fixed sentence, which names neither the value presented nor the app client it was
/// presented to — and which ends in no period: this is the sentence Amazon Cognito denies
/// a refresh token with, and a sentence's punctuation is as much its text as its words
/// are.
fn invalid_refresh_token() -> InitiateAuthError {
    not_authorized("Invalid Refresh Token")
}

/// The refusal for a `REFRESH_TOKEN` this emulator issued for the app client the
/// request names and has since revoked — a sign-out of its user, or a revocation
/// of the token itself. Told apart from [`invalid_refresh_token`] because the
/// token did authorize this app client until it was invalidated.
fn refresh_token_revoked() -> InitiateAuthError {
    not_authorized("Refresh Token has been revoked")
}

