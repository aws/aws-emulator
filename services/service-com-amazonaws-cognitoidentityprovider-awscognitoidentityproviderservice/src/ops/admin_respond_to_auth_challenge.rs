fn invalid_challenge_state() -> AdminRespondToAuthChallengeError {
    AdminRespondToAuthChallengeErrorModeled::CodeMismatchException(CodeMismatchException {
        message: Some(crate::state::INVALID_CHALLENGE_STATE_MESSAGE.to_string()),
    })
    .into()
}

/// The refusal for a `Session` an earlier response already answered.
fn session_already_used() -> AdminRespondToAuthChallengeError {
    not_authorized(crate::state::SESSION_ALREADY_USED_MESSAGE)
}

/// The refusal for a stored `Session` that does not belong to this request: one
/// started for another pool or app client, for another user than the response
/// names, one whose challenge the stored user no longer owes, or a value that
/// names no stored session at all.
fn invalid_session() -> AdminRespondToAuthChallengeError {
    not_authorized(crate::state::SESSION_NOT_FOR_THIS_REQUEST_MESSAGE)
}

/// The refusal for a `Session` whose validity window has closed.
fn expired_session() -> AdminRespondToAuthChallengeError {
    not_authorized(crate::state::SESSION_EXPIRED_MESSAGE)
}

/// This operation's `NotAuthorizedException`, carrying `message`.
fn not_authorized(message: &str) -> AdminRespondToAuthChallengeError {
    AdminRespondToAuthChallengeErrorModeled::NotAuthorizedException(NotAuthorizedException {
        message: Some(message.to_string()),
    })
    .into()
}

/// The refusal for an input member this challenge response requires and the
/// request did not carry.
fn missing_parameter(parameter: &str) -> AdminRespondToAuthChallengeError {
    invalid_parameter(format!("Missing required parameter {parameter}"))
}

/// The refusal for a `NEW_PASSWORD_REQUIRED` response that carries no
/// `NEW_PASSWORD` entry.
///
/// The challenge is answered by the entries of its response map, so a map that
/// is missing the one the new password travels in is reported as the other
/// refusals of that map are — "Invalid attributes given, …" — naming the KEY
/// the password has to be given under rather than an input member of the
/// request.
fn missing_new_password() -> AdminRespondToAuthChallengeError {
    invalid_parameter(format!(
        "Invalid attributes given, new password should be given with key {NEW_PASSWORD}"
    ))
}

/// This operation's `InvalidPasswordException`, carrying `message`.
fn invalid_password(message: String) -> AdminRespondToAuthChallengeError {
    AdminRespondToAuthChallengeErrorModeled::InvalidPasswordException(InvalidPasswordException {
        message: Some(message),
    })
    .into()
}

/// This operation's refusal of a password the pool's history policy restricts
/// the user from reusing.
fn password_reused() -> AdminRespondToAuthChallengeError {
    AdminRespondToAuthChallengeErrorModeled::PasswordHistoryPolicyViolationException(
        PasswordHistoryPolicyViolationException {
            message: Some(crate::state::PASSWORD_REUSED_MESSAGE.to_string()),
        },
    )
    .into()
}

/// This operation's `InvalidParameterException`, carrying `message`.
fn invalid_parameter(message: String) -> AdminRespondToAuthChallengeError {
    AdminRespondToAuthChallengeErrorModeled::InvalidParameterException(InvalidParameterException {
        message: Some(message),
        reason_code: None,
    })
    .into()
}

