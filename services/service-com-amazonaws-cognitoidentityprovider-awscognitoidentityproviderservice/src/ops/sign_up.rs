impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> SignUp<Eng> {
    /// Register the user `input` asks for, and report what that left behind.
    ///
    /// Everything here happens under this service's lock, which this call OWNS: the lock
    /// is taken and released inside it, so its caller holds none of it while it invokes a
    /// trigger function.
    fn register(&self, input: &SignUpInput) -> Result<Registered, SignUpError> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_error());
        };

        let now = ::std::time::SystemTime::now();
        let mut guard = state.lock();

        // This operation models no `UserPoolId` at all: the app client the request
        // names is what resolves the pool the user is registered in.
        let pool = guard
            .pool_of_client(&input.client_id)
            .ok_or_else(|| client_not_found(&input.client_id))?;
        let user_pool_id = pool.id.clone();

        // `SecretHash` is an HMAC "calculated using the secret key of a user pool client
        // and username plus the client ID in the message" (`SignUp.SecretHash`), so it
        // is what a request proves the app client's secret with. A client that holds a
        // secret therefore registers nobody until the request carries the hash THAT
        // secret, this username and this client id produce; a client with no secret has
        // nothing to prove. Checked before the password and the attributes: a caller
        // that cannot address the client learns nothing about the pool's policy or
        // schema from the answer.
        let client = pool
            .clients
            .get(&input.client_id)
            .ok_or_else(|| client_not_found(&input.client_id))?;
        if let Some(defect) =
            client.secret_hash_defect(&input.username, input.secret_hash.as_deref())
        {
            return Err(secret_hash_refused(defect, &input.client_id));
        }

        // A pool whose `AdminCreateUserConfig` reserves user creation to
        // administrators registers nobody through this operation: "set to True if
        // only the administrator is allowed to create user profiles. Set to False
        // if users can sign themselves up via an app"
        // (`AdminCreateUserConfigType.AllowAdminCreateUserOnly` in this service's
        // model), so a self-service registration against such a pool is refused
        // before the request's password, attributes or username are looked at.
        if pool.admin_create_user_config.allow_admin_create_user_only {
            return Err(not_authorized(SIGN_UP_NOT_PERMITTED_MESSAGE));
        }

        // In a pool that signs its users in WITH an attribute value, the
        // submitted `Username` is that value rather than a name of its own, so
        // it has to be a value one of those attributes can hold
        // ([`crate::state::UserPool::username_defect`]). Checked before the
        // request's password and attributes, the `Username` being the parameter
        // the registration is addressed by.
        if let Some(defect) = pool.username_defect(&input.username) {
            return Err(invalid_parameter(defect));
        }

        // "The password must comply with the password requirements of your user pool"
        // (`SignUp.Password`). The member is optional — "To create a user with no
        // password, omit this parameter or submit a blank value" — so only a password
        // that was actually proposed is checked against the policy.
        let password = input
            .password
            .as_deref()
            .filter(|password| !password.is_empty());
        if let Some(message) = password.and_then(|password| {
            pool.check_password(
                password,
                crate::state::PasswordPolicyWording::UserSuppliesPassword,
            )
        }) {
            return Err(invalid_password(message));
        }

        // Every attribute written has to be one the pool's schema declares, and every
        // attribute that schema marks required has to be given a value: a sign-up that
        // left one out would store a user the pool's own schema says is incomplete.
        let requested_attributes = input.user_attributes.clone().unwrap_or_default();
        let requested_names: Vec<String> = requested_attributes
            .iter()
            .map(|attribute| attribute.name.clone())
            .collect();
        if let Some(unknown) = pool.unknown_attribute(&requested_names) {
            return Err(invalid_parameter(format!(
                "Invalid attributes given, {unknown} is not a valid attribute of this user pool"
            )));
        }
        // A submitted value whose attribute has a FORM of its own has to have
        // that form, whichever operation submitted it
        // ([`crate::state::attribute_value_defect`]).
        if let Some(defect) = requested_attributes.iter().find_map(|attribute| {
            crate::state::attribute_value_defect(
                &attribute.name,
                attribute.value.as_deref().unwrap_or_default(),
            )
        }) {
            return Err(invalid_parameter(defect.to_string()));
        }
        // An attribute submitted with an empty value is stored for no user
        // (`crate::state::stored_attribute_values`).
        let mut attributes = crate::state::stored_attribute_values(&requested_attributes);
        let missing = pool.unset_required_attributes(&attributes);
        if let Some(name) = missing.first() {
            return Err(invalid_parameter(format!(
                "Attributes did not conform to the schema: {name}: The attribute is required"
            )));
        }

        // "The username of the user that you want to sign up. The value of this
        // parameter is typically a username, but can be any alias attribute in
        // your user pool" (`SignUp.Username`), and `UsernameAttributes`
        // "specifies whether a user can use an email address or phone number as a
        // username when they sign up" (this service's model): in such a pool the
        // submitted value is the value of that sign-in attribute and Amazon
        // Cognito mints the username itself, which is the user's own id.
        // Everywhere else the submitted name IS the username, normalized the way
        // this pool compares usernames — a case-insensitive pool lower-cases it
        // on the way in.
        let sub = crate::state::new_uuid();
        let sign_in_attribute = pool.sign_in_attribute(&input.username).map(str::to_string);
        let (username, key) = match &sign_in_attribute {
            Some(_) => (sub.clone(), sub.clone()),
            None => {
                let username = pool.user_key(&input.username);
                (username.clone(), username)
            }
        };
        // A second user under a name the pool already holds is refused: the
        // username itself where that is the sign-in name, and the sign-in value
        // where an attribute is ([`UserPool::sign_in_name_holder_key`]).
        let taken = pool.users.contains_key(&key)
            || sign_in_attribute
                .as_deref()
                .is_some_and(|_| pool.sign_in_name_holder_key(&input.username).is_some());
        if taken {
            return Err(username_exists());
        }
        // This emulator holds a pool's users in memory, so the store is bounded; the
        // operation's own `LimitExceededException` is "thrown when a user exceeds the
        // limit for a requested Amazon Web Services resource" (this service's model).
        if pool.users.len() >= crate::state::MAX_USERS_PER_POOL {
            return Err(limit_exceeded(format!(
                "User pool {user_pool_id} holds at most {} users.",
                crate::state::MAX_USERS_PER_POOL
            )));
        }

        // `sub` is the user's own id, not something the caller may set.
        attributes.insert("sub".to_string(), sub.clone());
        // The sign-in name of a pool that mints its usernames is the value of the
        // attribute its users sign in with, so that is where the submitted value
        // is held — unless the request submitted a value for it itself.
        if let Some(attribute) = sign_in_attribute {
            attributes
                .entry(attribute)
                .or_insert_with(|| input.username.clone());
        }
        // A registrant's own email address or phone number is not proven by the
        // registration that submitted it: the user "confirms ownership of the email
        // address or phone number that they provided" only by answering the code
        // (`ConfirmSignUp` in this service's model), which is what sets that
        // attribute's flag to [`crate::state::FLAG_CONFIRMED`]. So a sign-up records
        // the flag of every value it stores for a verifiable attribute
        // ([`crate::state::verified_flag`]) as UNCONFIRMED, and every read projects
        // that flag beside the value until the value is confirmed. A registration
        // that submitted a flag of its own keeps the value it sent.
        let unconfirmed_flags: Vec<&'static str> = attributes
            .keys()
            .filter_map(|name| crate::state::verified_flag(name))
            .collect();
        for flag in unconfirmed_flags {
            attributes
                .entry(flag.to_string())
                .or_insert_with(|| crate::state::FLAG_UNCONFIRMED.to_string());
        }
        let user = crate::state::User {
            username,
            sub: sub.clone(),
            attributes,
            // Nothing is pending for a user that has just registered: the
            // attributes above are its values, not values awaiting a
            // confirmation of a changed email address or phone number.
            pending_attributes: ::std::collections::BTreeMap::new(),
            password: password.map(str::to_string),
            // The user chose this password itself, so there is nothing to change at the
            // next sign-in: it is permanent, unlike the one `AdminCreateUser` sets.
            password_permanent: true,
            password_set_at: password.map(|_| now),
            // A user that just registered has held no password before the one it
            // registered with, so it owes its history nothing.
            password_history: Vec::new(),
            // "When you get this exception in the response, the user is successfully
            // created and is in an UNCONFIRMED state" (this operation's own doc): a
            // signed-up user is unconfirmed until a confirmation confirms it.
            status: crate::state::UserStatus::Unconfirmed,
            enabled: true,
            mfa_options: Vec::new(),
            preferred_mfa_setting: None,
            mfa_setting_list: Vec::new(),
            user_create_date: now,
            user_last_modified_date: now,
            groups: ::std::collections::BTreeSet::new(),
            // A registered user has no remembered device: a device is known only once a
            // sign-in has minted a key for one.
            devices: ::std::collections::BTreeMap::new(),
            // Nothing has asked for a verification code yet; the sign-up's own
            // confirmation code is issued below, once the user is stored.
            outstanding_codes: ::std::collections::BTreeMap::new(),
            // A registered user has registered no passkey: one exists only once
            // a registration this user started has completed.
            web_authn_credentials: Vec::new(),
            // No external identity is linked to a user that just registered
            // itself: a link exists only once `AdminLinkProviderForUser` has
            // made one.
            provider_links: ::std::collections::BTreeMap::new(),
            // Nor has it registered a TOTP authenticator, nor had a private key
            // for one minted, and it has expressed no passkey MFA preference of
            // its own.
            software_token_registered: false,
            software_token_key: None,
            web_authn_mfa_enabled: None,
            // The registration this call logs is appended once the user is
            // stored, so the history it starts out with is empty.
            auth_events: Vec::new(),
        };
        let pool = guard
            .pool_mut(&user_pool_id)
            .ok_or_else(internal_error)?;
        pool.users.insert(key.clone(), user);

        // Registering the user is what sends its confirmation code: `ConfirmSignUp`
        // "submits a code that Amazon Cognito sent to your user when they signed up in
        // your user pool", and the pool's own `AutoVerifiedAttributes` decide where it
        // goes (`UserPool::confirmation_destination`). A pool that verifies nothing, or
        // a user holding no value for what it verifies, has no destination — so no code
        // is minted and no delivery is reported.
        let stored = pool.users.get(&key).ok_or_else(internal_error)?;
        let delivery = pool
            .confirmation_destination(stored)
            .map(|(attribute, destination)| {
                crate::state::VerificationCode::issued(&attribute, &destination, now)
            });
        let user = pool.user_mut(&input.username).ok_or_else(internal_error)?;
        let issued = delivery
            .map(|code| user.issue_code(crate::state::CodePurpose::SignUpConfirmation, code));
        let code_delivery_details = issued
            .as_ref()
            .and_then(crate::state::VerificationCode::delivery_details);
        // The code itself is handed to the pool's custom email sender, which on a pool
        // that configures one is the only place this code is delivered at all.
        let issued_code = issued.map(|code| code.code);

        // Read back from the STORED user, so the response reports what a later read of
        // this pool reports.
        let stored = pool.users.get(&key).ok_or_else(internal_error)?;
        Ok(Registered {
            answer: SignUpOutput {
                // "Indicates whether the user was automatically confirmed. You can
                // auto-confirm users with a pre sign-up Lambda trigger" (`UserConfirmed`):
                // the stored status is what decides it.
                user_confirmed: stored.status == crate::state::UserStatus::Confirmed,
                user_sub: stored.sub.clone(),
                // "Information about the delivery destination for that link or code" of
                // the message this sign-up sent, rendered from the code just stored, so a
                // reported delivery is always one a `ConfirmSignUp` can answer.
                code_delivery_details,
                // `Session` is "a session Id that you can pass to ConfirmSignUp when you
                // want to immediately sign in your user with the USER_AUTH flow": that
                // flow is not served here, so no session is started for it.
                session: None,
            },
            username: stored.username.clone(),
            user_pool_id,
            issued_code,
        })
    }
}

/// What the pool's custom email sender's failure is for THIS operation: the modelled
/// error each outcome amounts to, carrying the message the dispatch built.
///
/// The user is registered and its code recorded — the code is what `ConfirmSignUp` checks
/// a presented one against — so what the failure changes is what this call ANSWERS: a
/// function Lambda cannot invoke at all is "an unexpected exception with Lambda", and one
/// that ran and reported an error is "a user validation exception with the Lambda service"
/// (this service's model).
fn trigger_failed(failure: crate::state::lambda_triggers::Failure) -> SignUpError {
    match failure {
        crate::state::lambda_triggers::Failure::Reported(message) => {
            SignUpErrorModeled::UserLambdaValidationException(UserLambdaValidationException {
                message: Some(message),
            })
            .into()
        }
        crate::state::lambda_triggers::Failure::NotInvokable(message) => {
            SignUpErrorModeled::UnexpectedLambdaException(UnexpectedLambdaException {
                message: Some(message),
            })
            .into()
        }
    }
}

