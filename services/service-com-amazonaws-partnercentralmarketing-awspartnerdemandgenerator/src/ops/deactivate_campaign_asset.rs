//! landing page's published object is taken down at the delivery platform, and the images
//! the partner put on it are deleted. A landing page stops capturing leads, and its
//! `PublicUrl` is no longer returned. A partner site that embedded a banner shows nothing
//! there. The platform's own CDN can keep serving a copy a visitor already cached, which
