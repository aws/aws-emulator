        let mut store = state.lock();
        store.settle_due_transitions();

        // A replayed `clientToken` is a retry of the call that created the collection, so
        // it answers that collection instead of creating or conflicting with a second one.
        // The replay is scoped to the name THIS request carries: a token spent again on a
        // different `name` is a request for another collection, which is still created
        // rather than answered with the first one.
        if let Some(token) = input.client_token.as_deref() {
            let replayed = store
                .replayed_collection(Self::OPERATION_NAME, token)
                .filter(|record| record.name == input.name)
                .map(|record| StoredCollection {
                    id: record.id.clone(),
                    detail: record.create_detail(),
                    // The collection the first call created stands, and so does the address
                    // it was published at: this call creates and opens nothing.
                    created: false,
                });
            if let Some(replayed) = replayed {
                return Ok(replayed);
            }
        }

        // A collection is encrypted at rest, and the setting that says HOW comes either
        // from this request's `encryptionConfig` or from an `encryption` security policy
        // whose rules already cover `collection/<name>`. With neither, there is no
        // encryption setting for the collection at all, which is the missing input
        // `ValidationException` describes ("the HTTP request contains invalid input or is
        // missing required input").
