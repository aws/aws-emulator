impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateRepository<Eng>
{
    type Input = CreateRepositoryInput;
    type Output = CreateRepositoryOutput;
    type Error = CreateRepositoryError;

    const NAME: &'static str = "CreateRepository";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_REPOSITORY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_REPOSITORY_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // This operation is served from every Region ECR Public publishes an endpoint in,
        // so nothing here reads the Region the request was signed for — see
        // `crate::state::unsupported_in_region` for the one call that is Region-scoped.
        // Authorization comes first: an action the caller's identity-based policies do not
        // allow is refused before this handler reads or writes anything, so no repository
        // comes into existence for a refused create.
        if let Some(denied) = crate::state::authorization::denied_on_repository(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.repository_name,
        ) {
            return Err(denied);
        }
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(server_error());
        };

        // `TooManyTagsException` documents the limit: "the maximum number of tags that
        // can be applied to a repository is 50". The modelled `TagList` length (0..200)
        // is wider, so it is enforced here.
        let requested_tags = input.tags.as_ref().map(Vec::len).unwrap_or(0);
        if requested_tags > crate::state::MAX_TAGS_PER_REPOSITORY {
            return Err(CreateRepositoryErrorModeled::TooManyTagsException(
                TooManyTagsException {
                    message: Some(crate::state::TOO_MANY_TAGS_MESSAGE.to_string()),
                },
            )
            .into());
        }

        let tags = match crate::state::stored_tags(input.tags.as_ref()) {
            Ok(tags) => tags,
            Err(problem) => return Err(tag_error(problem)),
        };

        let created_at = ::std::time::SystemTime::now();

        let mut store = state.lock();
        if store.repositories.contains_key(&input.repository_name) {
            return Err(
                CreateRepositoryErrorModeled::RepositoryAlreadyExistsException(
                    RepositoryAlreadyExistsException {
                        message: Some(format!(
                            "The repository with name '{}' already exists in the registry with \
                             id '{}'",
                            input.repository_name, store.registry_id
                        )),
                    },
                )
                .into(),
            );
        }

        // The store lives for the life of the process and this is the only operation
        // that adds a repository to it, so the count is capped: a reader must still be
        // able to answer what was stored, which rules out a TTL or an eviction policy.
        if store.repositories.len() >= crate::state::MAX_REPOSITORIES {
            return Err(CreateRepositoryErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "The operation didn't succeed because it would have exceeded this \
                         registry's limit of {} repositories",
                        crate::state::MAX_REPOSITORIES
                    )),
                },
            )
            .into());
        }

        // The catalog record this create resolves to, derived by the same helper
        // `PutRepositoryCatalogData` uses: it depends on the request and on the registry
        // the repository belongs to, which is also the scope the logo asset it names is
        // served in.
        let record = crate::state::catalog_record_of(
            &store.registry_id,
            &input.repository_name,
            input.catalog_data.as_ref(),
            ctx.endpoint().as_str(),
        );
        // A logo payload this registry will not publish is refused before the repository
        // exists: the modelled byte cap is enforced at the boundary, and what remains is
        // the service's own rule about the image itself.
        if let Some(message) = crate::state::logo_asset::logo_violation(record.logo.as_ref()) {
            return Err(CreateRepositoryErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message.to_string()),
                },
            )
            .into());
        }

        let repository = crate::state::StoredRepository {
            name: input.repository_name.clone(),
            arn: store.repository_arn(&input.repository_name),
            registry_id: store.registry_id.clone(),
            uri: store.repository_uri(&input.repository_name),
            // The tier the repository is hosted in. This operation takes no tier member —
            // a repository is created in a registry, and the registry decides the tier —
            // so a repository of this registry carries the tier that registry hosts
            // (`crate::state::DEFAULT_REPOSITORY_TYPE`), which is what every image of it
            // is reported with.
            repository_type: crate::state::DEFAULT_REPOSITORY_TYPE.to_string(),
            created_at,
            catalog_data: record.catalog_data,
            tags,
            // A new repository carries no repository policy until `SetRepositoryPolicy`
            // applies one.
            policy_text: None,
            images: ::std::collections::BTreeMap::new(),
            tag_index: ::std::collections::BTreeMap::new(),
            // A new repository holds no image layer until a `CompleteLayerUpload` against
            // it finalises one.
            layers: ::std::collections::BTreeMap::new(),
            // The logo payload the catalog record this create supplied names, which is
            // what `crate::service` serves at the `logoUrl` that record carries.
            logo: record.logo,
        };
        let output = CreateRepositoryOutput {
            repository: Some(repository.as_repository()),
            catalog_data: Some(repository.catalog_data.clone()),
        };
        store
            .repositories
            .insert(input.repository_name, repository);
        drop(store);

        Ok(output)
    }
}

/// The modelled refusal for a `tags` list this registry cannot apply, each
/// [`crate::state::TagProblem`] on the error this operation models for it.
fn tag_error(problem: crate::state::TagProblem) -> CreateRepositoryError {
    let message = Some(problem.message().to_string());
    match problem {
        crate::state::TagProblem::InvalidTagParameter(_) => {
            CreateRepositoryErrorModeled::InvalidTagParameterException(
                InvalidTagParameterException { message },
            )
        }
        crate::state::TagProblem::TooManyTags(_) => {
            CreateRepositoryErrorModeled::TooManyTagsException(TooManyTagsException { message })
        }
    }
    .into()
}

