        let mut store = state.lock();
        let Some(export) = store.settled_export(&input.export_id) else {
            return Err(DescribeExportErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    // The sentence this service states when a read names a resource it
                    // does not hold, whatever the resource and whatever identified it.
                    message: Some(crate::state::RESOURCE_NOT_FOUND_MESSAGE.to_string()),
                },
            )
            .into());
        };

        // `downloadUrl` is "a pre-signed S3 URL that points to the bot or bot locale
        // archive", so it is an address the CALLER fetches: it is announced on a job that
