    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DIRECTORY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DIRECTORY_OUTPUT_SCHEMA;
