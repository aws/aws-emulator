impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ConnectDirectory<Eng>
{
    type Input = ConnectDirectoryInput;
    type Output = ConnectDirectoryOutput;
    type Error = ConnectDirectoryError;

    const NAME: &'static str = "ConnectDirectory";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONNECT_DIRECTORY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONNECT_DIRECTORY_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(crate::state::state_unavailable)?;

        // The password of the service account in the self-managed directory. It is
        // modelled `@sensitive`, no operation reports it back, and the self-managed
        // directory it would be presented to is not something this emulator can reach —
        // so it is bound here only to be dropped, and never reaches the store.
        let _ = input.password;

        // An AD Connector's servers are placed one per subnet, in two Availability Zones,
        // so a settings block naming fewer than two distinct subnets cannot carry them.
        // Checked before anything is minted or inserted, so a refused call stores nothing.
        if let Some(defect) =
            crate::state::subnet_pair_defect(&input.connect_settings.subnet_ids)
        {
            return Err(invalid_parameter(defect));
        }

        // WHERE the connector's servers go: the subnets the request names, resolved against
        // the service that OWNS subnets, so each connector server can be given an address out
        // of its own subnet's block — the `ConnectIps` this directory reports — and so the
        // other half of the placement rule can be decided. Asked ONCE, BEFORE the store lock
        // below is taken, so no guard is held across the hop; an identifier the owner
        // reports no subnet for contributes nothing, and the create still stores the placement
        // the request named.
        //
        // The VPC those subnets sit in is resolved first, against that same owner: a
        // placement naming a VPC the account does not have names a resource that does not
        // exist, which is the resource-semantics failure class (`ClientException`). Nothing is
        // refused where EC2 could not be asked.
        let region = crate::state::region_from_request(ctx.parts());
        if let Some(defect) =
            crate::state::vpc_absence(ctx, &region, &input.connect_settings.vpc_id).await
        {
            return Err(
                ConnectDirectoryErrorModeled::ClientException(crate::state::refusal(defect))
                    .into(),
            );
        }
        let subnet_networks = crate::state::resolve_subnet_networks(
            ctx,
            &region,
            &input.connect_settings.subnet_ids,
        )
        .await;
        // WHICH VPC the connector's servers end up on is the VPC of those subnets, as their
        // owner reports it — the network the security group this create provisions for them
        // has to be in. Read before the placement is moved into the record below.
        let placement_vpc = crate::state::placement_vpc_id(&subnet_networks);

        // Two DIFFERENT subnets still have to be in two different zones, which only that
        // service can answer: a pair EC2 reports in ONE zone is refused as the
        // resource-semantics failure it is (`ClientException`), a different class to the
        // validation refusal a MALFORMED subnet id gets — and nothing is refused where EC2
        // could not be asked.
        if let Some(defect) = crate::state::single_zone_defect(
            &subnet_networks,
            &input.connect_settings.subnet_ids,
        ) {
            return Err(
                ConnectDirectoryErrorModeled::ClientException(crate::state::refusal(defect))
                    .into(),
            );
        }

        // Nothing caller-sized reaches the store unchecked: the tag list is bounded
        // before the store lock is taken at all. `ConnectDirectory` models no
        // `TagLimitExceededException`, so the bound is reported as the invalid parameter
        // it is.
        let requested_tags = input.tags.unwrap_or_default();
        if requested_tags.len() > crate::state::MAX_TAGS {
            return Err(invalid_parameter(format!(
                "Tags may carry at most {max} entries, got {got}",
                max = crate::state::MAX_TAGS,
                got = requested_tags.len()
            )));
        }
        let tags: ::std::collections::BTreeMap<String, String> = requested_tags
            .into_iter()
            .map(|tag| (tag.key, tag.value))
            .collect();

        let now = ::std::time::SystemTime::now();
        // The Region quota and the directory's own identifier: ONE short-lived lock, released
        // with this block, so the hop into the owner of security groups below holds no guard.
        // The group that hop asks for is named after the directory it belongs to, so the
        // identifier is minted first — and the quota is what decides whether there is a
        // connector to provision at all, so a create refused for it asks EC2 for nothing.
        //
        // Each category of directory carries its own published Region quota, so this
        // create counts against the connected one alone — the same bound
        // `GetDirectoryLimits` reports as `ConnectedDirectoriesLimit`.
        let directory_id = {
            let mut store = state.lock();
            store.advance_clock(now);
            if store.category_limit_reached(crate::state::DirectoryLimitCategory::Connected) {
                return Err(
                    ConnectDirectoryErrorModeled::DirectoryLimitExceededException(
                        crate::state::refusal(format!(
                            "Maximum number of directories in the region has been reached: {}",
                            crate::state::MAX_CONNECTED_DIRECTORIES
                        )),
                    )
                    .into(),
                );
            }
            store.mint_directory_id()
        };

        // The connector's servers sit behind a security group Directory Service provisions for
        // them — `DirectoryConnectSettingsDescription$SecurityGroupId`, "the security group
        // identifier for the AD Connector directory". A security group is Amazon EC2's
        // resource, so it is CREATED THERE, in the VPC the subnets resolved above belong to,
        // and the id EC2 minted is what this directory reports: the group a client authorizes
        // traffic to the connector's servers against is one the owner of security groups
        // really holds. `None` where there was no resolved placement to put a group in, so
        // nothing is reported that names no group anywhere.
        let security_group_id = crate::state::provision_controllers_group(
            ctx,
            &region,
            &directory_id,
            placement_vpc.as_deref(),
        )
        .await;

        let mut store = state.lock();
        let seq = store.next_seq();
        let record = crate::state::Directory {
            directory_id: directory_id.clone(),
            name: input.name,
            short_name: input.short_name,
            description: input.description,
            // `Size` is `@required` on this operation, so an AD Connector reports the
            // size the request asked for.
            size: Some(input.size),
            // Only AWS Managed Microsoft AD has an edition.
            edition: None,
            directory_type: crate::state::TYPE_AD_CONNECTOR.to_string(),
            stage: crate::state::STAGE_REQUESTED.to_string(),
            stage_due_at: Some(now + crate::state::TRANSITION_SPAN),
            launch_time: now,
            stage_last_updated: now,
            // No alias until `CreateAlias` assigns one; the directory id stands in for it
            // until then.
            alias: None,
            // An AD Connector reports its placement as `ConnectSettings`, not as
            // `VpcSettings`: the modelled `DirectoryDescription` carries both members and
            // this type fills the connector one.
            vpc_settings: None,
            connect_settings: Some(DirectoryConnectSettingsDescription {
                vpc_id: Some(input.connect_settings.vpc_id),
                subnet_ids: Some(input.connect_settings.subnet_ids),
                customer_user_name: Some(input.connect_settings.customer_user_name),
                // The security group the hop above provisioned for the connector's servers,
                // as EC2 minted it. The Availability Zones and the addresses of the connector
                // servers are REPORTED from the subnets resolved above
                // (`Directory::availability_zones` / `Directory::server_addresses`); the IPv6
                // half belongs to a connector placed on an IPv6 block, which no create here
                // records one for.
                security_group_id,
                availability_zones: None,
                connect_ips: None,
                connect_ips_v6: None,
            }),
            // The subnets this connector's servers are placed in, as the owner of subnets
            // reported them: the blocks their addresses are counted out of.
            subnet_networks,
            // An AD Connector serves no DNS of its own: the servers a client points a
            // resolver at are the self-managed directory's, which this create names
            // (`DirectoryConnectSettings$CustomerDnsIps`) and `DnsIpAddrs` reports.
            customer_dns_ips: input.connect_settings.customer_dns_ips.unwrap_or_default(),
            // `NetworkType`'s own documentation: "The default value is IPv4 or IPv6 based
            // on the provided subnet capabilities" — a choice made by the VPC data plane
            // this emulator does not have, so an unspecified network type stays absent
            // rather than being invented.
            network_type: input.network_type,
            // `EnableSso` (still scaffolded) is what turns this on.
            sso_enabled: false,
            // A domain controller is a server of the directory's own domain, which an AD
            // Connector does not run: it forwards to the self-managed directory's.
            desired_number_of_domain_controllers: None,
            domain_controllers: ::std::collections::BTreeMap::new(),
            tags,
            // The Region this connector is created in — its `Primary` one — is the one
            // the request was signed for.
            primary_region: region.clone(),
            additional_regions: ::std::collections::BTreeMap::new(),
            // `AddIpRoutes` is what routes an address block to this directory.
            ip_routes: ::std::collections::BTreeMap::new(),
            // `EnableLDAPS` / `EnableClientAuthentication` are what record a setting for a
            // type; nothing is configured at create.
            ldaps_settings: ::std::collections::BTreeMap::new(),
            client_authentication_settings: ::std::collections::BTreeMap::new(),
            // `RegisterCertificate` is what registers a certificate with the directory; a
            // fresh one has none.
            certificates: ::std::collections::BTreeMap::new(),
            schema_extensions: ::std::collections::BTreeMap::new(),
            // `RegisterEventTopic` is what associates an Amazon SNS topic with the
            // directory; a fresh one publishes to none.
            event_topics: ::std::collections::BTreeMap::new(),
            log_subscription: None,
            conditional_forwarders: ::std::collections::BTreeMap::new(),
            computers: ::std::collections::BTreeMap::new(),
            // No update activity until an update of the directory's setup is asked for;
            // a fresh directory has had none.
            update_activities: Vec::new(),
            next_computer_rid: crate::state::FIRST_COMPUTER_RID,
            // The accounts an AD Connector serves live in the self-managed directory it
            // connects to, so it holds none of its own — and so holds no password of one
            // either, which is why no credential pair can be authenticated as an account of
            // this directory type (`crate::state::credential_defect`).
            users: crate::state::initial_users(crate::state::TYPE_AD_CONNECTOR, None, now),
            // Configurable settings are a Managed Microsoft AD feature (see
            // `crate::state::SETTINGS_DIRECTORY_TYPES`), so an AD Connector carries none.
            settings: crate::state::initial_settings(crate::state::TYPE_AD_CONNECTOR, now),
            // `EnableDirectoryDataAccess` is what opens a directory to the Directory
            // Service Data API; a fresh one is closed to it.
            data_access_status: crate::state::DATA_ACCESS_DISABLED.to_string(),
            data_access_due_at: None,
            // `EnableCAEnrollmentPolicy` is what enrolls a directory's clients with a
            // Private CA connector; a fresh one holds no such policy.
            ca_enrollment_policy: None,
            seq,
        };
        store.directories.insert(directory_id.clone(), record);

        // Read the id back out of the store, so the response cannot name a directory the
        // insert did not persist.
        let stored = store
            .directories
            .get(&directory_id)
            .ok_or_else(crate::state::state_unavailable)?;

        // The account now holds this directory, which is a fact the DATA plane needs and
        // cannot read from its own records: it creates no directory, so a `DirectoryId` it
        // is called with is one of this account's only because a create recorded it — and
        // the two names the directory was created with — the domain, which that plane
        // reports as the realm of every object inside it, and the NetBIOS short name, which
        // names the organizational unit the objects it creates sit in — are recorded with it
        // for the same reason, read back off the record this create persisted.
        // WHEN the directory is in service is recorded with it, for a reader of another
        // kind: a service that BUILDS on a directory of this account is not told the stage
        // this record carries, and this create answers while the stage chain it owes still
        // stands — so the instant that chain reaches [`crate::state::STAGE_ACTIVE`] is
        // recorded here, read from the one helper that states the chain
        // ([`crate::state::directory_active_at`]), and the clock brings the directory into
        // service for every reader at that one instant.
        if let Some(inventory) = crate::state::ad_directory_inventory(&*self.engine) {
            let mut inventory = inventory.lock();
            inventory.register_in_domain(&directory_id, &stored.name, stored.short_name.as_deref());
            inventory.record_in_service_at(&directory_id, crate::state::directory_active_at(now));
        }

        Ok(ConnectDirectoryOutput {
            directory_id: Some(stored.directory_id.clone()),
        })
    }
}

