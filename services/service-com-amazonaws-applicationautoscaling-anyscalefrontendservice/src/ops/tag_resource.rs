impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state::{
            check_tag_count, check_tag_key, check_tag_keys_unreserved, check_tag_value,
            tag_target_arns::TaggedTargetArn, MAX_TAGS_PER_RESOURCE,
        };

        // Input validation first, so a request no resource could accept is refused the
        // same way whichever `ResourceARN` it names. `TagMap` carries no `@length`, so
        // the per-resource maximum is this operation's to enforce.
        check_tag_count(input.tags.len()).map_err(validation)?;
        // "You cannot have more than one tag on an Application Auto Scaling scalable
        // target with the same tag key" is already true of a map; what is not modelled
        // is the reserved `aws:` namespace, which a caller may not write. Checked before
        // the store is touched, so a batch holding one reserved key lands no key at all.
        check_tag_keys_unreserved(input.tags.keys().map(String::as_str)).map_err(validation)?;
        // `TagKey`'s and `TagValue`'s own lengths, for the same batch: the boundary
        // validator does not reach a MAP's keys, so an over-long key arrives here. The
        // lowest-ordered refusal is the one reported, so the same batch is always
        // refused with the same message whatever order its keys arrive in.
        let refusal = input
            .tags
            .iter()
            .filter_map(|(key, value)| {
                check_tag_key("tags", key)
                    .and_then(|()| check_tag_value("tags", key, value))
                    .err()
            })
            .min();
        if let Some(message) = refusal {
            return Err(validation(message));
        }

        // An engine that holds no state holds no scalable target either, so the target the
        // ARN names is absent — which is the refusal below, rather than a server error this
        // operation does not model.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(target_not_found(&input.resource_arn));
        };
        let mut state = state.lock();

        // `ResourceARN` "identifies the Application Auto Scaling scalable target that you want
        // to apply tags to", so an ARN that names a scalable-target IDENTITY of this endpoint —
        // its partition, account and Region, and an identifier of the form a scalable target's
        // own takes — and that no REGISTERED target answers to is the scalable target reported
        // ABSENT, whether this service minted that ARN or not. An ARN that names no such
        // identity names no resource this endpoint could hold at all, and the tagging call
        // itself is refused. One resolution for the whole tagging family
        // (`crate::state::tag_target_arns`). A scalable target is regional, so an ARN of
        // another Region is not one this endpoint answers for.
        let region = crate::state::request_region(ctx.parts());
        let resolved = state.resolve_tagged_target_arn(&input.resource_arn, &region);
        let record = match resolved {
            TaggedTargetArn::Registered(key) => state.targets.get_mut(&key),
            TaggedTargetArn::Absent => return Err(target_not_found(&input.resource_arn)),
            TaggedTargetArn::NotServedHere => return Err(target_arn_never_minted()),
        };
        // A resolution taken under this same lock named a target the store holds, so the
        // record is there; a store that does not hold it is one holding no such target,
        // which is the same absent-resource refusal.
        let Some(record) = record else {
            return Err(target_not_found(&input.resource_arn));
        };

        // The merge is computed before anything is stored: "To add a tag, specify a new
        // tag key and a tag value. To edit a tag, specify an existing tag key and a new
        // tag value" — so a key already present takes the request's value, and a key the
        // request does not name keeps the value it had. A batch that would leave the
        // target above the per-resource maximum is refused whole, so a refusal never
        // leaves half of it applied.
        let mut merged = record.tags.clone();
        for (key, value) in &input.tags {
            merged.insert(key.clone(), value.clone());
        }
        if merged.len() > MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::TooManyTagsException(
                TooManyTagsException {
                    message: Some(format!(
                        "The request would leave the scalable target carrying {} tags; a \
                         resource holds at most {MAX_TAGS_PER_RESOURCE}",
                        merged.len()
                    )),
                    resource_name: Some(input.resource_arn.clone()),
                },
            )
            .into());
        }
        record.tags = merged;

        Ok(TagResourceOutput {})
    }
}

