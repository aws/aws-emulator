impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UntagResource<Eng>
{
    type Input = UntagResourceInput;
    type Output = UntagResourceOutput;
    type Error = UntagResourceError;

    const NAME: &'static str = "UntagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state::{check_tag_key, check_tag_keys_unreserved};

        // `TagKeyList` carries its own `@length(0..200)`, refused at the boundary, and a
        // key the target does not carry is not an error — so there is no count to check
        // here. What is not modelled is the reserved `aws:` namespace, which is not a
        // caller's to remove either. Checked before the store is touched, so a batch
        // holding one reserved key removes none of its keys.
        check_tag_keys_unreserved(input.tag_keys.iter().map(String::as_str))
            .map_err(validation)?;
        // `TagKey`'s own length, the same bound `TagResource` writes under.
        for key in &input.tag_keys {
            check_tag_key("tagKeys", key).map_err(validation)?;
        }

        // An engine that holds no state holds no scalable target either, so an ARN
        // addressed to it resolves to nothing: the same refusal as any other ARN that
        // resolves to no registered target (see `tag_resource`).
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(tagging_denied());
        };
        let mut state = state.lock();

        // Only a target of THIS Region: a scalable target is a regional resource, so
        // another Region's ARN names none this endpoint holds (see `tag_resource`). An ARN
        // that resolves to no registered target identifies no scalable target to untag,
        // whether this service never minted it or minted it for a target that has since
        // been deregistered, so both are the one refusal the two tag MUTATIONS share.
        let region = crate::state::request_region(ctx.parts());
        let resolved = state
            .arn_index
            .get(&input.resource_arn)
            .filter(|key| key.region == region)
            .cloned();
        let Some(record) = resolved.and_then(|key| state.targets.get_mut(&key)) else {
            return Err(tagging_denied());
        };

        // "To delete a tag, specify the tag key and the Application Auto Scaling
        // scalable target": only the keys named are removed, and a key the target does
        // not carry leaves the tag set as it was, so removal is idempotent.
        for key in &input.tag_keys {
            record.tags.remove(key);
        }

        Ok(UntagResourceOutput {})
    }
}

