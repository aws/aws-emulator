        // was written to a location that does not exist. Resolved with no store guard held,
        // over the emulator's own in-process transport, so this handler never holds two
        // services' store locks at once and opens no connection.
        if let Some(message) = crate::state::snapshot_bucket_refusal(
            ctx,
            &region,
            &destination.destination_s3_prefix_location.bucket_arn,
        )
        .await
        {
            return Err(ExportSnapshotErrorModeled::InvalidArgumentException(
                InvalidArgumentException {
                    message: Some(message),
                },
            )
            .into());
        }

        let mut store = state.lock();
        store.settle_snapshot_named(&snapshot_name);

        let Some(snapshot) = store.snapshots_v2.get(&snapshot_name) else {
            return Err(ExportSnapshotErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::missing_enhanced_snapshot_message(
                        &snapshot_name,
                    )),
                },
            )
            .into());
        };

        // "The snapshot must be in the READY status" — this operation's own doc: there is no
        // snapshot data to read out of one that is still being created, or that is being
        // deleted, so the snapshot is not available for this operation.
        if snapshot.status != crate::state::SNAPSHOT_READY {
            return Err(ExportSnapshotErrorModeled::ResourceInUseException(
                ResourceInUseException {
                    message: Some(crate::state::ineligible_snapshot_status_message(
                        &snapshot_name,
                        &snapshot.status,
                        &[crate::state::SNAPSHOT_READY],
                    )),
                },
            )
            .into());
        }

