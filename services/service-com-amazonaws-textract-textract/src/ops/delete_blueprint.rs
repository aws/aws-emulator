impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DeleteBlueprint<Eng>
{
    type Input = DeleteBlueprintInput;
    type Output = DeleteBlueprintOutput;
    type Error = DeleteBlueprintError;

    const NAME: &'static str = "DeleteBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // AWS takes the authorization decision at the IAM layer, ahead of the service
        // deleting anything, against the ARN the request CARRIED, so a refused call
        // removes nothing and is not told whether the blueprint exists.
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.blueprint_arn,
        )
        .map_err(DeleteBlueprintErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DeleteBlueprintErrorModeled::InternalServerError(
                InternalServerError {
                    message: Some("Textract state is unavailable".to_string()),
                    code: None,
                },
            )
            .into());
        };

        let mut store = state.lock();
        match input.blueprint_version.as_deref() {
            // AWS, on `DeleteBlueprintRequest$BlueprintVersion`: "The version of the
            // blueprint to delete." — so only that cut goes, and the blueprint and its
            // other versions stay.
            Some(wanted) => {
                store
                    .remove_blueprint_version(&input.blueprint_arn, wanted)
                    .map_err(DeleteBlueprintErrorModeled::ResourceNotFoundException)?;
            }
            // "If omitted, the entire blueprint and all of its versions are deleted." The
            // removal IS the lookup, under one lock, so two concurrent deletes of one
            // blueprint cannot both report having removed it.
            None => {
                if store.remove_blueprint(&input.blueprint_arn).is_none() {
                    return Err(DeleteBlueprintErrorModeled::ResourceNotFoundException(
                        intelligence::blueprint_not_found(),
                    )
                    .into());
                }
            }
        }

        Ok(DeleteBlueprintOutput {})
    }
}
