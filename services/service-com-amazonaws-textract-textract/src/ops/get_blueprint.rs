impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetBlueprint<Eng>
{
    type Input = GetBlueprintInput;
    type Output = GetBlueprintOutput;
    type Error = GetBlueprintError;

    const NAME: &'static str = "GetBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // AWS takes the authorization decision at the IAM layer, ahead of the service
        // reading anything, against the ARN the request CARRIED, so a refusal does not
        // depend on — and does not disclose — whether the blueprint exists.
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.blueprint_arn,
        )
        .map_err(GetBlueprintErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(GetBlueprintErrorModeled::InternalServerError(
                InternalServerError {
                    message: Some("Textract state is unavailable".to_string()),
                    code: None,
                },
            )
            .into());
        };

        let store = state.lock();
        let blueprint = store.blueprint_by_arn(&input.blueprint_arn).ok_or_else(|| {
            GetBlueprintErrorModeled::ResourceNotFoundException(intelligence::blueprint_not_found())
        })?;

        // A version the request PINS is reported as it was cut: a version is immutable, so
        // its schema and its encryption configuration are the blueprint's as of that cut
        // and a later update does not move them. With no version named, AWS documents that
        // "the latest version is returned" — the highest-numbered cut — and a blueprint
        // that has never been versioned has only its own live state, which is the latest
        // there is and carries no version number.
        let selected = match input.blueprint_version.as_deref() {
            Some(wanted) => Some(blueprint.version(wanted).ok_or_else(|| {
                GetBlueprintErrorModeled::ResourceNotFoundException(
                    intelligence::blueprint_version_not_found(),
                )
            })?),
            None => blueprint.latest_version(),
        };
        let (schema, encryption, version, last_modified) = match selected {
            Some(version) => (
                version.schema.clone(),
                version.encryption.clone(),
                Some(version.wire_version()),
                version.created_at,
            ),
            None => (
                blueprint.schema.clone(),
                blueprint.encryption.clone(),
                None,
                blueprint.last_modified_at,
            ),
        };

        Ok(GetBlueprintOutput {
            blueprint_arn: blueprint.blueprint_arn.clone(),
            blueprint_name: blueprint.blueprint_name.clone(),
            blueprint_version: version,
            schema,
            // A blueprint created without an `EncryptionConfiguration` is encrypted with an
            // AWS owned key, so there is no `KmsKeyId` of the caller's to report.
            kms_key_id: encryption.as_ref().map(|encryption| encryption.kms_key_id.clone()),
            kms_encryption_context: encryption
                .and_then(|encryption| encryption.kms_encryption_context),
            creation_time: ::aws_smithy_types::DateTime::from(blueprint.created_at),
            last_modified_time: ::aws_smithy_types::DateTime::from(last_modified),
        })
    }
}
