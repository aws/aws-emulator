impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateBlueprint<Eng>
{
    type Input = UpdateBlueprintInput;
    type Output = UpdateBlueprintOutput;
    type Error = UpdateBlueprintError;

    const NAME: &'static str = "UpdateBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // AWS takes the authorization decision at the IAM layer, ahead of the service
        // writing anything, against the ARN the request CARRIED.
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.blueprint_arn,
        )
        .map_err(UpdateBlueprintErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateBlueprintErrorModeled::InternalServerError(
                InternalServerError {
                    message: Some("Textract state is unavailable".to_string()),
                    code: None,
                },
            )
            .into());
        };

        // The same rule `CreateBlueprint` enforces: a schema that is not an object naming
        // fields describes no extraction, so it cannot be written by an update either.
        if let Some(schema) = &input.schema {
            if !intelligence::schema_is_an_object(schema) {
                return Err(UpdateBlueprintErrorModeled::ValidationException(
                    intelligence::invalid(intelligence::SCHEMA_NOT_AN_OBJECT_MESSAGE),
                )
                .into());
            }
        }

        let now = std::time::SystemTime::now();
        let mut store = state.lock();
        let Some(blueprint) = store.blueprint_by_arn_mut(&input.blueprint_arn) else {
            return Err(UpdateBlueprintErrorModeled::ResourceNotFoundException(
                intelligence::blueprint_not_found(),
            )
            .into());
        };

        // AWS, on `UpdateBlueprint`: it "[u]pdates an existing blueprint, replacing its
        // schema and, optionally, its encryption configuration" — so a member the request
        // supplies replaces the stored one and a member it omits is left as it was.
        if let Some(schema) = input.schema {
            blueprint.schema = schema;
        }
        if let Some(supplied) = input.encryption_configuration {
            // The one exception AWS states to replacing a supplied configuration whole: an
            // omitted `KmsEncryptionContext` keeps the stored one, and an empty map clears
            // it.
            blueprint.encryption = Some(intelligence::merge_encryption(
                blueprint.encryption.as_ref(),
                supplied,
            ));
        }
        // The blueprint is still the one that was created then, so `CreationTime` does not
        // move; `LastModifiedTime` is when this change was made.
        blueprint.last_modified_at = now;

        Ok(UpdateBlueprintOutput {
            blueprint_arn: blueprint.blueprint_arn.clone(),
        })
    }
}
