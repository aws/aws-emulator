impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateBlueprint<Eng>
{
    type Input = CreateBlueprintInput;
    type Output = CreateBlueprintOutput;
    type Error = CreateBlueprintError;

    const NAME: &'static str = "CreateBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // AWS takes the authorization decision at the IAM layer, ahead of the service
        // writing anything, so a caller whose identity-based policies do not allow this
        // action mints no blueprint and spends no idempotency token. A create names no
        // resource yet, so it is judged against the resource IAM writes for such a request.
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            crate::service::authorization::ANY_RESOURCE,
        )
        .map_err(CreateBlueprintErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CreateBlueprintErrorModeled::InternalServerError(
                InternalServerError {
                    message: Some("Textract state is unavailable".to_string()),
                    code: None,
                },
            )
            .into());
        };

        // A blueprint's schema "defines the fields to extract and their expected
        // structure", so it must be an object naming fields: a schema that is not one
        // describes no extraction and is refused rather than stored as a blueprint that
        // would extract nothing. The value is read with `serde_json` rather than scanned.
        if !intelligence::schema_is_an_object(&input.schema) {
            return Err(CreateBlueprintErrorModeled::ValidationException(
                intelligence::invalid(intelligence::SCHEMA_NOT_AN_OBJECT_MESSAGE),
            )
            .into());
        }

        let region = crate::state::request_region(ctx.parts());
        let now = std::time::SystemTime::now();
        // ONE lock spans the token check and the mint, so two concurrent creates carrying
        // the same token cannot both mint.
        let mut store = state.lock();

        // AWS, on `ClientRequestToken`: "If you use the same token for a request that
        // matches a previous request, the service ignores the request, but does not return
        // an error."
        if let Some(token) = input.client_request_token.as_deref() {
            if let Some(blueprint_arn) = store.intelligence_token_answer(Self::NAME, token) {
                return Ok(CreateBlueprintOutput { blueprint_arn });
            }
        }

        // AWS, on `BlueprintName`: "A unique name for the blueprint."
        if store.blueprint_name_taken(&input.blueprint_name) {
            return Err(CreateBlueprintErrorModeled::ConflictException(
                ConflictException {
                    message: Some(intelligence::BLUEPRINT_NAME_IN_USE_MESSAGE.to_string()),
                    code: None,
                },
            )
            .into());
        }

        // Nothing is evicted from the blueprint store, so its ceiling is refused rather
        // than made room for.
        if store.blueprints.len() >= intelligence::MAX_STORED_BLUEPRINTS {
            return Err(CreateBlueprintErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "this account already holds {} blueprints, the most this emulator stores",
                        intelligence::MAX_STORED_BLUEPRINTS
                    )),
                    code: None,
                },
            )
            .into());
        }

        let blueprint_id = store.mint_intelligence_id(&input.blueprint_name);
        let blueprint_arn = intelligence::blueprint_arn(&region, &blueprint_id);
        store.blueprints.insert(
            blueprint_id.clone(),
            intelligence::BlueprintRecord {
                blueprint_id,
                blueprint_arn: blueprint_arn.clone(),
                blueprint_name: input.blueprint_name,
                schema: input.schema,
                encryption: input.encryption_configuration,
                tags: input.tags.unwrap_or_default(),
                created_at: now,
                last_modified_at: now,
                // A newly created blueprint has no versions: `CreateBlueprintVersion` is
                // what cuts one, and version numbers start at 1.
                versions: std::collections::BTreeMap::new(),
                next_version: 1,
            },
        );
        if let Some(token) = input.client_request_token.as_deref() {
            store.remember_intelligence_token(Self::NAME, token, &blueprint_arn);
        }

        Ok(CreateBlueprintOutput { blueprint_arn })
    }
}
