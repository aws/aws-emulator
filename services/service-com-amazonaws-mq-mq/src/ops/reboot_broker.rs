impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RebootBroker<Eng>
{
    type Input = RebootBrokerInput;
    type Output = RebootBrokerOutput;
    type Error = RebootBrokerError;

    const NAME: &'static str = "RebootBroker";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REBOOT_BROKER_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REBOOT_BROKER_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = state::service_state(&*self.engine) else {
            return Err(RebootBrokerErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: Some("the service state store is unavailable".to_string()),
                    ..Default::default()
                },
            )
            .into());
        };

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        let Some(broker) = store.settled_broker_mut(&input.broker_id, now) else {
            return Err(RebootBrokerErrorModeled::NotFoundException(NotFoundException {
                error_attribute: Some("broker-id".to_string()),
                message: Some(state::broker_not_found_message(&input.broker_id)),
                resource_share_errors: None,
            })
            .into());
        };

        // A broker can be restarted only from the state a restart starts from, so a
        // broker that is still being provisioned — or is already restarting — is
        // refused, naming the state it is in. No `errorAttribute`: no member of the
        // request is at fault, the broker's state is.
        let broker_state = broker.broker_state(now);
        if broker_state != state::BROKER_STATE_RUNNING {
            let message =
                state::broker_not_restartable_message(&broker.broker_name, broker_state);
            return Err(RebootBrokerErrorModeled::BadRequestException(
                BadRequestException {
                    error_attribute: None,
                    message: Some(message),
                    resource_share_errors: None,
                },
            )
            .into());
        }

        // "Note: This API is asynchronous": what this call persists is the restart, and
        // the clock owes the broker its return to RUNNING with the staged user changes
        // applied. The answer carries no member.
        broker.restart(now);
        Ok(RebootBrokerOutput {})
    }
}
