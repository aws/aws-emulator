/// How the service refuses a `regex` it will not run. The whole sentence is
/// fixed text: it interpolates neither the pattern nor any other request value.
const UNSUPPORTED_PATTERN_MESSAGE: &str = "Unsafe regex, keywords, or ignoreWords.";

/// The byte budget one compiled pattern may occupy. Compiling a pattern that
/// came off the wire is caller-driven work, so it is bounded twice: by
/// [`crate::state::MAX_REGEX_CHARS`] on the input and by this limit on the
/// program built from it, past which `regex` answers an error instead of
/// growing the heap.
const PATTERN_PROGRAM_BYTES: usize = 1 << 20;

/// The refusal `regex` earns when it is not a pattern this service can run, or
/// `None` when it is one.
///
/// The syntax is decided by the `regex` crate rather than by a hand-written
/// reader of the pattern language: it parses the whole expression, refuses what
/// it cannot represent, and matches in time linear in the subject, so no
/// pattern a caller sends can make matching blow up later.
fn pattern_violation(pattern: &str) -> Option<String> {
    ::regex::RegexBuilder::new(pattern)
        .size_limit(PATTERN_PROGRAM_BYTES)
        .dfa_size_limit(PATTERN_PROGRAM_BYTES)
        .build()
        .err()
        .map(|_| UNSUPPORTED_PATTERN_MESSAGE.to_string())
}

/// The documented rule for `severityLevels`: as many as three entries, one for
/// each severity, with the occurrences thresholds "in ascending order by
/// severity, moving from LOW to HIGH".
fn severity_levels_violation(levels: &[SeverityLevel]) -> Option<String> {
    if levels.len() > crate::state::MAX_SEVERITY_LEVELS {
        return Some(format!(
            "The severityLevels array can contain as many as {} SeverityLevel objects, \
             one for each severity.",
            crate::state::MAX_SEVERITY_LEVELS
        ));
    }

    // Each entry's severity is validated against `DataIdentifierSeverity`
    // before this handler runs, so a rank is always resolvable; `None` would
    // mean a severity this emulator does not order, which it refuses rather
    // than silently accepting out of order.
    let mut ranked: Vec<(usize, i64)> = Vec::with_capacity(levels.len());
    for level in levels {
        let Some(rank) = crate::state::severity_rank(&level.severity) else {
            return Some(format!(
                "The severity {} is not one of {}.",
                level.severity,
                crate::state::SEVERITIES_ASCENDING.join(", ")
            ));
        };
        if ranked.iter().any(|(seen, _)| *seen == rank) {
            return Some(format!(
                "The severityLevels array can specify the {} severity only once.",
                level.severity
            ));
        }
        ranked.push((rank, level.occurrences_threshold));
    }

    ranked.sort_unstable();
    if ranked
        .windows(2)
        .any(|pair| pair.first().map(|(_, low)| *low) >= pair.last().map(|(_, high)| *high))
    {
        return Some(
            "The occurrences thresholds in the severityLevels array must be in ascending \
             order by severity, moving from LOW to HIGH."
                .to_string(),
        );
    }

    None
}

