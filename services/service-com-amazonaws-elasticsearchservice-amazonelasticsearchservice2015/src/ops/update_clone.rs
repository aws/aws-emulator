impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateClone<Eng>
{
    type Input = UpdateCloneInput;
    type Output = UpdateCloneOutput;
    type Error = UpdateCloneError;

    const NAME: &'static str = "UpdateClone";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CLONE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CLONE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateCloneErrorModeled::InternalException(InternalException {
                message: Some("the Elasticsearch domain store is unavailable".to_string()),
            })
            .into());
        };

        // THE INPUT CONSTRAINTS FIRST, before the domain is resolved: exactly one
        // setting per request, and a retention period the service accepts.
        let requested = match Requested::of(&input) {
            Ok(requested) => requested,
            Err(message) => return Err(validation(message)),
        };

        let now = ::std::time::SystemTime::now();
        let settled = crate::state::active_deadline(now);
        let region = crate::state::request_region(&ctx.parts().headers);
        let key = crate::state::domain_key(&region, &input.domain_name);
        let mut store = state.lock();
        // The change's id is minted before the domain is taken, so one borrow of the
        // record carries the whole change. A request this then refuses consumes an id: a
        // `ChangeId` is opaque and the counter is the store's own, so a gap in it is
        // observable nowhere.
        let change_id = store.mint_change_id();
        let reported = {
            let Some(domain) = store.domains.get_mut(&key) else {
                // The resource named is not there: HTTP 404
                // (`crate::scaffolded::RESOURCE_NOT_FOUND_STATUS`), not the
                // `@httpError(409)` the model annotates on the shape.
                return Err(crate::scaffolded::Scaffolded::not_found(
                    UpdateCloneErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: Some(format!("Domain not found: {}", input.domain_name)),
                        },
                    ),
                ));
            };

            // There is nothing to manage unless the domain has an upgrade a caller can
            // still drive: none was started, the caller cut back to the primary cluster,
            // or the retention period of the cluster cut over from has run out.
            let Some(clone) = domain.clone_upgrade_mut(now) else {
                return Err(validation(format!(
                    "Domain {} does not have a cloned blue/green upgrade in progress",
                    input.domain_name
                )));
            };

            // THE STATE RULES of the upgrade, and then the change itself. Each arm moves
            // ONE setting; everything the response reports is computed from the record
            // afterwards, so what a caller is told is what the next read will say.
            let property = match requested {
                Requested::TrafficSplit(clone_read_traffic_percent) => {
                    if clone.provisioning(now) {
                        return Err(validation(format!(
                            "The cloned cluster of domain {} is not ready to take search \
                             traffic yet",
                            input.domain_name
                        )));
                    }
                    if clone.cutover.is_some() {
                        return Err(validation(format!(
                            "The traffic split of domain {} cannot be changed once a \
                             cutover has been requested",
                            input.domain_name
                        )));
                    }
                    clone.current_clone_percent = clone.live_clone_percent(now);
                    clone.target_clone_percent = clone_read_traffic_percent;
                    clone.split_due_at = settled;
                    crate::state::TRAFFIC_SPLIT_PROPERTY
                }
                Requested::Cutover(target) => {
                    if clone.provisioning(now) {
                        return Err(validation(format!(
                            "The cloned cluster of domain {} is not ready to be cut over \
                             to yet",
                            input.domain_name
                        )));
                    }
                    if clone.cutover.is_some() {
                        return Err(validation(format!(
                            "A cutover has already been requested for domain {}",
                            input.domain_name
                        )));
                    }
                    // Cutting over moves the WHOLE of the search traffic onto the cluster
                    // it targets, which lands with the cutover itself.
                    clone.current_clone_percent = clone.live_clone_percent(now);
                    clone.target_clone_percent =
                        if target == crate::state::CUTOVER_TARGET_CLONED_CLUSTER {
                            crate::state::WHOLE_TRAFFIC_PERCENT
                        } else {
                            0
                        };
                    clone.split_due_at = settled;
                    clone.cutover = Some(crate::state::CloneCutover {
                        target,
                        due_at: settled,
                    });
                    crate::state::CUTOVER_PROPERTY
                }
                Requested::RetentionInHours(hours) => {
                    clone.retention_in_hours = Some(hours);
                    crate::state::RETENTION_PROPERTY
                }
                Requested::RetentionAction(action) => {
                    // "Ends the retention period now. Valid only after cutover completes."
                    if clone.version_effective_at().is_none_or(|at| now < at) {
                        return Err(validation(format!(
                            "RetentionAction is valid for domain {} only after the cutover \
                             to the cloned cluster completes",
                            input.domain_name
                        )));
                    }
                    clone.retention_action = Some(action);
                    clone.retention_ended_at = Some(now);
                    crate::state::RETENTION_PROPERTY
                }
            };

            // The upgrade as it now stands, read back out of the record just written.
            let reported = clone.clone();
            domain.last_updated = now;
            domain.record_change(crate::state::DomainChange {
                change_id: change_id.clone(),
                started_at: now,
                due_at: settled,
                properties: vec![property.to_string()],
                clone_change: true,
                starts_clone_upgrade: false,
            });
            reported
        };

        Ok(UpdateCloneOutput {
            domain_name: input.domain_name,
            change_id,
            cutover_options: reported.cutover_options(now),
            traffic_split_options: Some(reported.traffic_split_options(now)),
            retention_options: reported.retention_options(now),
        })
    }
}

