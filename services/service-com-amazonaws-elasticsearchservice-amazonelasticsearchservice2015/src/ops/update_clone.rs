/// The ONE setting a request asks to change.
enum Requested {
    /// The share of the read traffic the cloned cluster is to take.
    TrafficSplit(i32),
    /// The cluster the domain is to be cut over to.
    Cutover(String),
    /// How long the cluster cut over from is to be kept.
    RetentionInHours(i32),
    /// Ending that period now.
    RetentionAction(String),
}

impl Requested {
    /// What `input` asks to change, or the message refusing it.
    ///
    /// "Specify exactly one of `TrafficSplitOptions`, `CutoverOptions`, or
    /// `RetentionOptions` in each request" — so a request naming none, or more than one,
    /// is refused rather than part-applied, and a retention period shorter than the
    /// published minimum is refused at the member that carries it.
    fn of(input: &UpdateCloneInput) -> Result<Self, String> {
        let named: Vec<&str> = [
            input
                .traffic_split_options
                .as_ref()
                .map(|_| crate::state::TRAFFIC_SPLIT_PROPERTY),
            input
                .cutover_options
                .as_ref()
                .map(|_| crate::state::CUTOVER_PROPERTY),
            input
                .retention_options
                .as_ref()
                .map(|_| crate::state::RETENTION_PROPERTY),
        ]
        .into_iter()
        .flatten()
        .collect();
        if named.len() != 1 {
            return Err(format!(
                "Specify exactly one of TrafficSplitOptions, CutoverOptions, or \
                 RetentionOptions, got [{named}]",
                named = named.join(", ")
            ));
        }
        if let Some(split) = input.traffic_split_options.as_ref() {
            // `Strategy` is `@required` and `TrafficStrategy` declares exactly ONE value
            // (`ShiftReadTrafficPercent`, `smithy_query(query="shape",shape="TrafficStrategy")`),
            // which the boundary validator enforces before this handler runs — so the
            // strategy a request carries is always "shift this percentage of the read
            // traffic", which is what the percent below is read as. A model that adds a
            // second strategy has to be read HERE rather than ignored.
            return Ok(Self::TrafficSplit(split.clone_read_traffic_percent));
        }
        if let Some(cutover) = input.cutover_options.as_ref() {
            return Ok(Self::Cutover(cutover.target.clone()));
        }
        match input.retention_options.as_ref() {
            Some(RetentionOptions::RetentionInHours(hours))
                if *hours < crate::state::MIN_RETENTION_HOURS =>
            {
                Err(format!(
                    "RetentionOptions.RetentionInHours value {hours} failed to satisfy \
                     constraint: the minimum retention period is {minimum} hour",
                    minimum = crate::state::MIN_RETENTION_HOURS
                ))
            }
            Some(RetentionOptions::RetentionInHours(hours)) => Ok(Self::RetentionInHours(*hours)),
            Some(RetentionOptions::RetentionAction(action)) => {
                Ok(Self::RetentionAction(action.clone()))
            }
            // Unreachable: exactly one setting is named, and the two above returned.
            None => Err("Specify exactly one of TrafficSplitOptions, CutoverOptions, or \
                         RetentionOptions"
                .to_string()),
        }
    }
}
