//! @op GetParameterHistory
//! Retrieve the history of all changes to a parameter. This is the ONLY file to touch
//! for this operation.
//!
//! The answer is computed from the versions `PutParameter` persisted (see
//! [`crate::state::ParameterRecord`]): every version the store still retains, oldest
//! first, each reported with the value, type, key, description, pattern, tier, policies
//! and labels THAT version carries. Nothing here mutates the store — a read must not
//! change what a later caller sees.
//!
//! A name in the hierarchy AWS publishes its own parameters in is resolved against THAT
//! catalog ([`crate::state::public_parameters`]) rather than against the store, as every
//! read of a name is: the catalog publishes one version of such a name, so its history is
//! that one version.
//!
//! ## Paging
//!
//! A page carries at most `MaxResults` entries, up to the modelled maximum
//! ([`crate::state::parameter_history_page_size`]). When versions are left over, the
//! answer carries a `NextToken` holding the version the next page starts at: a version
//! number, so a second page resumes at the right change even if a put appended another
//! version in between, which an offset into a list could not. The token is opaque, and
//! carries that version behind an authenticator only this store can produce
//! ([`crate::state::parameter_pagination`]), so a value this read did not ISSUE is the
//! modelled `InvalidNextToken` rather than a page the caller was never offered — and so is
//! a token of this read's whose version the parameter no longer reaches.
//!
//! ## `WithDecryption` and `SecureString`
//!
//! Each `SecureString` version is stored as the KMS ciphertext its own put sealed, so
//! `WithDecryption` selects which form every reported entry's value takes — the stored
//! ciphertext, base64-encoded, when it is absent or false, and that version's plaintext,
//! opened under the key the version names, when it is true. A key that refuses one entry
//! refuses the whole page with `AccessDeniedException`, and a value no key of this
//! endpoint opens any more is `InvalidKeyId`. For `String` and `StringList` the flag is
//! ignored by the service too ("This flag is ignored for String and StringList parameter
//! types").
