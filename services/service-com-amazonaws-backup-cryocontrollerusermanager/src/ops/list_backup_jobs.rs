                        // instant, so a filter on one selects none of them.
                        && complete_before
                            .is_none_or(|before| job.completion_date.is_some_and(|at| at <= before))
                        && complete_after
                            .is_none_or(|after| job.completion_date.is_some_and(|at| at >= after))
