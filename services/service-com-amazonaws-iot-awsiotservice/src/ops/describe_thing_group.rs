impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeThingGroup<Eng>
{
    type Input = DescribeThingGroupInput;
    type Output = DescribeThingGroupOutput;
    type Error = DescribeThingGroupError;

    const NAME: &'static str = "DescribeThingGroup";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_THING_GROUP_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_THING_GROUP_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DescribeThingGroupErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the IoT emulator has no state store attached".to_string()),
            })
        })?;

        // A pure read of the thing-group registry: the record is cloned out and
        // reported, and a name the registry does not hold is a 404 worded by the
        // thing-group family ([`crate::state::not_found`]), never a hollow 200.
        let store = state.lock();
        let group = store
            .thing_groups
            .get(&input.thing_group_name)
            .ok_or_else(|| {
                DescribeThingGroupErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: Some(crate::state::missing_thing_group_message(
                            &input.thing_group_name,
                        )),
                    },
                )
            })?;

        // `rootToParentThingGroups` is "The root parent thing group" chain, so it is
        // reported only for a group that HAS a parent; a root group carries neither
        // member.
        let root_to_parent_thing_groups =
            group
                .configuration
                .parent_group_name
                .as_deref()
                .map(|parent_group_name| {
                    store
                        .root_to_parent_thing_groups(parent_group_name)
                        .into_iter()
                        .map(|(group_name, group_arn)| GroupNameAndArn {
                            group_name: Some(group_name),
                            group_arn: Some(group_arn),
                        })
                        .collect::<Vec<GroupNameAndArn>>()
                });

        Ok(DescribeThingGroupOutput {
            thing_group_name: Some(group.thing_group_name.clone()),
            thing_group_id: Some(group.thing_group_id.clone()),
            thing_group_arn: Some(group.thing_group_arn.clone()),
            version: group.version,
            thing_group_properties: Some(ThingGroupProperties {
                thing_group_description: group.configuration.description.clone(),
                // The payload is reported only when the group has attributes: an
                // `attributePayload` is how attributes are carried, and a group
                // created without any carries none.
                attribute_payload: (!group.configuration.attributes.is_empty()).then(|| {
                    AttributePayload {
                        attributes: Some(group.attributes()),
                        // `merge` "is only valid when calling UpdateThing or
                        // UpdateThingGroup", so a read never asks for a merge.
                        merge: false,
                    }
                }),
            }),
            thing_group_metadata: Some(ThingGroupMetadata {
                parent_group_name: group.configuration.parent_group_name.clone(),
                root_to_parent_thing_groups,
                creation_date: Some(::aws_smithy_types::DateTime::from(group.creation_date)),
            }),
            // `indexName`, `queryString`, `queryVersion` and `status` are the DYNAMIC
            // thing group members: a group created by `CreateThingGroup` is static and
            // carries none of them, while one created by `CreateDynamicThingGroup`
            // reports the query that decides its membership and the status that query
            // is in. The status is `ACTIVE` because the query is recorded by the create
            // itself, so there is no build the clock still owes the group.
            index_name: group
                .dynamic_query
                .as_ref()
                .map(|query| query.index_name.clone()),
            query_string: group
                .dynamic_query
                .as_ref()
                .map(|query| query.query_string.clone()),
            query_version: group
                .dynamic_query
                .as_ref()
                .and_then(|query| query.query_version.clone()),
            status: group
                .dynamic_query
                .as_ref()
                .map(|_| crate::state::DYNAMIC_GROUP_ACTIVE.to_string()),
        })
    }
}
