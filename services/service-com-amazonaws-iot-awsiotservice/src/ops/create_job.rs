        // an IoT job records one and where this plane's readers find it.
        let Some(jobs) = crate::state::job_store(&*self.engine) else {
            return Err(unavailable());
        };
        // The executions this job creates are the device-facing records the IoT Jobs
        // data plane serves, so they go in the SHARED store, not in this service's.
        let Some(executions) = crate::state::job_execution_store(&*self.engine) else {
            return Err(unavailable());
        };

        let invalid = |message: String| -> CreateJobError {
            CreateJobErrorModeled::InvalidRequestException(InvalidRequestException {
                message: Some(message),
            })
            .into()
        };
        let over_limit = |message: String| -> CreateJobError {
            CreateJobErrorModeled::LimitExceededException(LimitExceededException {
                message: Some(message),
            })
            .into()
        };

        // "The job document. Required if you don't specify a value for
        // documentSource" / "The link is an Amazon S3 object URL and is required if
        // you don't specify a value for document": one of the two must be there.
        if input.document.is_none() && input.document_source.is_none() {
            return Err(invalid(
                "One of document or documentSource is required".to_string(),
            ));
        }

        // A SCHEDULED job queues no execution until its window opens, and this
        // emulator does not schedule: it would have to report a job as dispatched
        // that nothing dispatched. So the member it cannot honour is refused with the
        // modelled client error rather than answered with a wrong outcome.
        if input.scheduling_config.is_some() {
            return Err(invalid(
                "schedulingConfig is not supported: this emulator dispatches a job's \
                 executions when the job is created"
                    .to_string(),
            ));
        }

        // How a refusal of the targets is answered: one wording and one status per
        // reason, shared with every other operation that targets devices with a job.
        let refused = |refusal: crate::state::JobTargetsRefusal| -> CreateJobError {
            match refusal {
                crate::state::JobTargetsRefusal::Invalid(message) => invalid(message),
                crate::state::JobTargetsRefusal::NotFound(message) => {
                    CreateJobErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                        message: Some(message),
                    })
                    .into()
                }
                crate::state::JobTargetsRefusal::OverLimit(message) => over_limit(message),
            }
        };

        // Which DEVICES this job runs on: a thing target names one, a thing-group
        // target names its members. Resolved BEFORE any lock is taken, so a malformed
        // request never reaches the stores at all, and bounded by
        // `MAX_JOB_TARGETS` before the walk, so the FAN-OUT of one request — the
        // records it creates and the document each record carries — is capped before
        // any work proportional to it.
        let fanout = crate::state::resolve_job_targets(&input.targets).map_err(refused)?;
        let mut targeted_things = fanout.things;
        let targeted_groups = fanout.groups;

        // `documentParameters` are the values the document's substitution parameters
        // resolve to, so they are persisted with the job: a reader reports the document
        // as written OR with every parameter resolved, and a device is handed the
        // resolved one. `ParameterMap` is modelled with no maximum entry count, so how
        // many substitutions a stored job imposes on its readers is bounded HERE, at
        // the write, and refused past the ceiling with the modelled error.
        let document_parameters: ::std::collections::BTreeMap<String, String> = input
            .document_parameters
            .as_ref()
            .map(|parameters| {
                parameters
                    .iter()
                    .map(|(key, value)| (key.clone(), value.clone()))
                    .collect()
            })
            .unwrap_or_default();
        if document_parameters.len() > crate::state::MAX_JOB_DOCUMENT_PARAMETERS {
            return Err(over_limit(format!(
                "a job may carry at most {} document parameters, got {}",
                crate::state::MAX_JOB_DOCUMENT_PARAMETERS,
                document_parameters.len()
            )));
        }
        // The document a device is handed is the RESOLVED one, so a request whose
        // parameters expand the document past what `JobDocument` may carry is refused
        // before anything is written, rather than stored as a job no reader can report.
        let resolved_document = match input.document.as_deref() {
            Some(document) => {
                match crate::state::resolve_job_document(document, &document_parameters) {
                    Ok(resolved) => Some(resolved),
                    Err(length) => {
                        return Err(invalid(format!(
                            "the job document is {length} bytes once its document \
                             parameters are resolved; a job document may be at most {} \
                             bytes",
                            crate::state::MAX_JOB_DOCUMENT_BYTES
                        )));
                    }
                }
            }
            None => None,
        };

        let region = crate::state::request_region(ctx.parts());
        let now = ::service_common::iot_job_executions::now_epoch_seconds();
        // The identity and the lifecycle come from the shared record's constructor (a
        // job that is rolling out), the rest from this request.
        let job = crate::state::RegisteredJob {
            description: input.description.clone(),
            document: input.document.clone(),
            document_source: input.document_source.clone(),
            targets: input.targets.clone(),
            target_selection: input.target_selection.clone(),
            in_progress_timeout_minutes: input
                .timeout_config
                .as_ref()
                .and_then(|config| config.in_progress_timeout_in_minutes),
            document_parameters,
            ..crate::state::RegisteredJob::in_progress(
                input.job_id.clone(),
                crate::state::job_arn(&region, &input.job_id),
                now,
            )
        };

        // Nothing is written until every target resolves and the id is free, so a
        // request this operation refuses creates neither the job nor an execution for
        // the targets that did resolve. Only the DECISION and the writes are inside
        // the locks; the bounded work above is not.
        let store = state.lock();
        // LOCK ORDER: this service's store first, the shared jobs store second, the
        // shared execution store third, as `crate::state::job_store` documents.
        let mut registry = jobs.lock();

        // "A job identifier which must be unique for your account": a second
        // CreateJob under a live job's id is the conflict
        // `ResourceAlreadyExistsException` (HTTP 409) names.
        if let Some(existing) = registry.job(&job.job_id) {
            return Err(CreateJobErrorModeled::ResourceAlreadyExistsException(
                ResourceAlreadyExistsException {
                    message: Some(format!("Job {} already exists", existing.job_id)),
                    resource_id: Some(existing.job_id.clone()),
                    resource_arn: Some(existing.job_arn.clone()),
                },
            )
            .into());
        }
        if registry.is_full() {
            return Err(over_limit(format!(
                "the maximum of {} jobs is already reached",
                crate::state::MAX_JOBS
            )));
        }
        // A group's executions are its MEMBERS' executions, so a group target is
        // EXPANDED into the things the group holds
        // ([`crate::state::ComAmazonawsIotAwsiotserviceState::things_in_thing_group`]):
        // one execution per member, and a member also named directly by the request
        // still gets one execution. A group whose devices are not known — one the
        // registry does not hold, or a dynamic group whose members are the things its
        // query selects — is refused instead
        // ([`crate::state::ComAmazonawsIotAwsiotserviceState::thing_group_target_refusal`]),
        // never answered with a 200 that reports a group-targeted job as dispatched
        // while queueing nothing.
