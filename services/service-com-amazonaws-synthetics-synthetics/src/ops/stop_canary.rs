impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StopCanary<Eng>
{
    type Input = StopCanaryInput;
    type Output = StopCanaryOutput;
    type Error = StopCanaryError;

    const NAME: &'static str = "StopCanary";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_CANARY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_CANARY_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            StopCanaryError::from(StopCanaryErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some(STORE_UNAVAILABLE.to_string()),
                },
            ))
        })?;

        let now = SystemTime::now();
        let mut guard = state.lock();
        guard.settle(now);
        let canary = guard.canaries.get_mut(&input.name).ok_or_else(|| {
            StopCanaryError::from(StopCanaryErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    // The missing-canary message is a fixed sentence, not built from
                    // the lookup key: see `state::CANARY_NOT_FOUND`.
                    message: Some(CANARY_NOT_FOUND.to_string()),
                },
            ))
        })?;

        // Only a running canary has a schedule to stop.
        if canary.state != CanaryState::Running {
            let state = canary.state;
            return Err(StopCanaryErrorModeled::ConflictException(ConflictException {
                message: Some(canary_state_conflict(CanaryTransition::Stopped, state)),
            })
            .into());
        }

        canary.state = CanaryState::Stopped;
        canary.state_reason = None;
        canary.state_reason_code = None;
        canary.last_stopped = Some(now);
        // Nothing is owed to a canary that has been stopped: the clock's own stop is what
        // this call just did.
        canary.stop_due = None;
        // The record observably changed, so its modification instant advances with it.
        canary.last_modified = now;
        canary.close_open_run(now);

        Ok(StopCanaryOutput {})
    }
}
