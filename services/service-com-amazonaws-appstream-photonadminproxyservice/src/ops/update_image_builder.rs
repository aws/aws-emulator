/// Merge an `ImageBuilderAgentAccessConfigForUpdate` onto the builder's stored
/// `ImageBuilderAgentAccessConfig`.
///
/// The update shape "supports partial updates, so you only need to specify the fields you
/// want to change. Fields that you omit keep their stored values"
/// (`smithy_query(query="shape", shape="ImageBuilderAgentAccessConfigForUpdate")`), with
/// two readings the members state themselves:
///
/// * the settings are merged BY AGENT ACTION — "a setting that you specify replaces the
///   stored setting for the same agent action" — so a request configuring one action leaves
///   the stored settings of the others in place;
/// * the bucket follows the screenshots: "if ScreenshotsUploadEnabled is false after the
///   merge, the stored bucket ARN is removed", since there are no screenshots to store.
///
/// A builder with no stored configuration has nothing to merge onto, so the members
/// `ImageBuilderAgentAccessConfig` requires must all be present; a missing one is refused
/// as an incorrect combination of parameters rather than invented here.
fn merge_agent_access_config(
    stored: Option<&ImageBuilderAgentAccessConfig>,
    update: &ImageBuilderAgentAccessConfigForUpdate,
) -> Result<ImageBuilderAgentAccessConfig, UpdateImageBuilderError> {
    let missing = |member: &str| {
        UpdateImageBuilderError::from(
            UpdateImageBuilderErrorModeled::InvalidParameterCombinationException(
                InvalidParameterCombinationException {
                    message: Some(format!(
                        "AgentAccessConfig.{member} is required to enable agent access on \
                         this image builder"
                    )),
                },
            ),
        )
    };

    let settings = match (update.settings.as_deref(), stored) {
        (Some(supplied), Some(stored)) => merged_settings(&stored.settings, supplied),
        (Some(supplied), None) => supplied.to_vec(),
        (None, Some(stored)) => stored.settings.clone(),
        (None, None) => return Err(missing("Settings")),
    };
    let screenshots_upload_enabled = update
        .screenshots_upload_enabled
        .or_else(|| stored.and_then(|stored| stored.screenshots_upload_enabled));

    Ok(ImageBuilderAgentAccessConfig {
        settings,
        screen_resolution: match (update.screen_resolution.clone(), stored) {
            (Some(resolution), _) => resolution,
            (None, Some(stored)) => stored.screen_resolution.clone(),
            (None, None) => return Err(missing("ScreenResolution")),
        },
        screen_image_format: match (update.screen_image_format.clone(), stored) {
            (Some(format), _) => format,
            (None, Some(stored)) => stored.screen_image_format.clone(),
            (None, None) => return Err(missing("ScreenImageFormat")),
        },
        s3_bucket_arn: match screenshots_upload_enabled {
            Some(false) => None,
            _ => update
                .s3_bucket_arn
                .clone()
                .or_else(|| stored.and_then(|stored| stored.s3_bucket_arn.clone())),
        },
        screenshots_upload_enabled,
        user_control_mode: update
            .user_control_mode
            .clone()
            .or_else(|| stored.and_then(|stored| stored.user_control_mode.clone())),
    })
}

/// The stored agent access settings with the supplied ones applied BY AGENT ACTION: a
/// supplied setting replaces the stored setting for the same action, and one for an action
/// the builder holds no setting for is appended, so the stored settings of every other
/// action are left as they were.
///
/// The stored order is kept, with the newly named actions after it, so a read of the
/// builder reports the settings in a stable order rather than one a request chooses.
fn merged_settings(
    stored: &[AgentAccessSetting],
    supplied: &[AgentAccessSetting],
) -> Vec<AgentAccessSetting> {
    let mut merged = stored.to_vec();
    for setting in supplied {
        match merged
            .iter_mut()
            .find(|stored| stored.agent_action == setting.agent_action)
        {
            Some(stored) => *stored = setting.clone(),
            None => merged.push(setting.clone()),
        }
    }
    merged
}
