        // A refresh RE-RUNS the DISCOVERY of the application it names, so it runs the one
        // discovery this crate has ([`crate::state::discovery::run_document`]) on the
        // instances that application's registration named — the very instances, and the
        // very hop, the registration's own discovery ran on, so the same question is
        // answered the same way for the same application. The instances are read off the
        // registration FIRST, with the store guard living for exactly that read, so no lock
        // is held across the hop; the read mints nothing and the hop reads and refuses
        // nothing, so a refresh refused below is refused on exactly the grounds it always
        // was, and an id this Region holds no application under is asked nothing about.
        let instances = registered_instances(&state, &region, &input.application_id);
        let discovery_refusal =
            crate::state::discovery::run_document(ctx, &region, &instances).await;

        let mut state = state.lock();
        state.settle(now);

        let Some(mut application) = state
            .region(&region)
            .applications
            .get(&input.application_id)
            .cloned()
        else {
            return Err(
                StartApplicationRefreshErrorModeled::ResourceNotFoundException(
                    crate::state::not_found(crate::state::application_not_found_message(
                        &input.application_id,
                    )),
                )
                .into(),
            );
        };

        // A refresh RE-RUNS the discovery of an application the service already
        // discovered, so an application whose registration has not completed
        // successfully has nothing to re-discover: it is refused with the modelled
        // `ConflictException`, in the one wording this service states that precondition
        // with. Asked of the application's own registration outcome and BEFORE the
        // in-flight gate, so concurrent callers are all refused the same way whatever
        // order they arrive in.
        if !application.registered_successfully() {
            return Err(StartApplicationRefreshErrorModeled::ConflictException(
                crate::state::not_registered_successfully(),
            )
            .into());
        }

        // A change the clock still owes this application is an operation already under
        // way on it, which is what `ConflictException` reports — decided and worded in
        // the one place every control call of this service refuses that condition from.
        crate::state::application_control_available(
            &application,
            crate::state::ApplicationControl::Refresh,
        )
        .map_err(StartApplicationRefreshErrorModeled::ConflictException)?;

        // A refresh re-runs the application's DISCOVERY, which is what
        // `Application$DiscoveryStatus` reports the latest result of: the application is
        // discovering again now and reaches the next discovery result one
        // `TRANSITION_SPAN` from now, materialised for every reader at that instant by
        // `crate::state::StoredApplication::settle` without anything sleeping. The SAP
        // system itself is neither started nor stopped, so the `Status` the application
        // is in is left exactly as it was.
