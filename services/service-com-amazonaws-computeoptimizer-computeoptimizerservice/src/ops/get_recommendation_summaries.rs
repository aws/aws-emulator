/// How many entries `inferredWorkloadSavings` reports, from that member's own doc: "The
/// array contains the top five savings opportunites for the instances that run inferred
/// workload types."
const TOP_INFERRED_WORKLOAD_SAVINGS: usize = 5;

/// One resource type's summary, computed from the account's records OF THAT TYPE: the
/// analysed resources the service rightsizes and the ones it found idle. Nothing here is
/// stored as a summary, so a count, a saving and a percentage are always the same rows seen
/// several ways.
fn summarise(
    resource_type: &str,
    account_id: &str,
    resources: &[&crate::state::AnalysedResource],
    idle_resources: &[&crate::state::IdleResourceAnalysis],
) -> RecommendationSummary {
    let current_monthly_cost: f64 = resources
        .iter()
        .map(|resource| resource.current_monthly_cost)
        .sum();
    let rightsizing_savings: f64 = resources
        .iter()
        .map(|resource| resource.monthly_savings())
        .sum();
    // What the idle resources of this type cost their account per month, and so what
    // adopting their recommendations would save: the recommendation for a resource nothing
    // is using is to stop paying for it, so the two are ONE figure, summed from the same
    // per-row cost the per-resource idle reader reports each one by
    // ([`crate::state::IdleResourceAnalysis::savings`]) — so this group saves exactly the
    // whole of what it costs, as each of its rows does.
    let idle_monthly_cost: f64 = idle_resources
        .iter()
        .map(|analysis| analysis.savings().1)
        .sum();
    let idle_savings = idle_monthly_cost;

    // Whether the service RIGHTSIZES this group or only CLASSIFIES it
    // ([`crate::state::reports_rightsizing_recommendations`]): the blocks beside the finding
    // counts all describe a recommended configuration, so a group the service recommends none
    // for carries none of them rather than carrying them at zero.
    let reports_rightsizing = crate::state::reports_rightsizing_recommendations(resource_type);
    let finding_summaries = finding_summaries(resource_type, resources, reports_rightsizing);
    let inferred_workload_savings = inferred_workload_savings(resources);
    // Whether the idle analysis covers this group at all: a group it covers carries a count
    // at each `IdleFinding` — zero where nothing of it was found idle — and a group outside
    // the idle vocabulary carries no idle counts and no idle saving, because none is defined
    // for it rather than because this account has none.
    let reports_idle = crate::state::reports_idle_recommendations(resource_type);
    RecommendationSummary {
        summaries: (!finding_summaries.is_empty()).then_some(finding_summaries),
        // "Describes the findings summary of the idle resources" — reported for a resource
        // type the idle analysis covers, whether or not it found any of this account's
        // resources of it idle.
        idle_summaries: reports_idle.then(|| idle_summaries(idle_resources)),
        recommendation_resource_type: Some(resource_type.to_string()),
        account_id: Some(account_id.to_string()),
        savings_opportunity: reports_rightsizing
            .then(|| savings_opportunity(rightsizing_savings, current_monthly_cost)),
        // What dropping the idle resources would save: stated by a group the idle analysis
        // covers, whether or not it found any of this account's resources of it idle.
        idle_savings_opportunity: reports_idle
            .then(|| savings_opportunity(idle_savings, idle_monthly_cost)),
        // "The savings opportunity for recommendations of a given resource type": every
        // recommendation the service holds for this resource type, so the rightsizing
        // opportunity and the idle one together, as a percentage of what all of those
        // resources cost — and nothing at all for a group the service makes neither kind of
        // recommendation for, which has no opportunity to aggregate.
        aggregated_savings_opportunity: (reports_rightsizing || reports_idle).then(|| {
            savings_opportunity(
                rightsizing_savings + idle_savings,
                current_monthly_cost + idle_monthly_cost,
            )
        }),
        current_performance_risk_ratings: reports_rightsizing
            .then(|| performance_risk_ratings(resources)),
        inferred_workload_savings: (!inferred_workload_savings.is_empty())
            .then_some(inferred_workload_savings),
    }
}

/// How many of the account's resources of this type the analysis found idle at each
/// `IdleFinding` — "the count of idle resources in the finding group" — including a finding
/// group none of them is in, whose count is then zero, because a summary states the number
/// of resources AT each finding rather than only the findings that occurred, the rule
/// [`finding_summaries`] reports the rightsizing counts by.
fn idle_summaries(idle_resources: &[&crate::state::IdleResourceAnalysis]) -> Vec<IdleSummary> {
    IDLE_FINDING_VALUES
        .iter()
        .map(|finding| IdleSummary {
            name: Some((*finding).to_string()),
            value: idle_resources
                .iter()
                .filter(|analysis| analysis.finding == *finding)
                .count() as f64,
        })
        .collect()
}

/// How many of `resources` carry each `Finding` this resource type's summary reports, in
/// the order the service documents them — including a finding none of them carries, whose
/// count is then zero, because the summary states the number of resources AT each finding
/// rather than only the findings that occurred. Each finding also carries how many of the
/// resources at it name each `FindingReasonCode`, by the same rule: a count at every value
/// of the vocabulary `ReasonCodeSummary$name` admits, zero where no resource names it.
/// A count also carries its reason codes only where the service recommends a configuration
/// for the group (`reports_reason_codes`): a reason code states what a recommendation would
/// change, so a group the service only classifies counts findings and no reasons.
fn finding_summaries(
    resource_type: &str,
    resources: &[&crate::state::AnalysedResource],
    reports_reason_codes: bool,
) -> Vec<Summary> {
    crate::state::findings_reported_for(resource_type)
        .iter()
        .map(|(finding, reported_as)| {
            let at_finding: Vec<&&crate::state::AnalysedResource> = resources
                .iter()
                .filter(|resource| resource.finding == *finding)
                .collect();
            Summary {
                name: Some((*reported_as).to_string()),
                value: at_finding.len() as f64,
                reason_code_summaries: reports_reason_codes.then(|| {
                    crate::state::finding_reason_codes_reported_for()
                        .iter()
                        .map(|reason_code| ReasonCodeSummary {
                            name: Some((*reason_code).to_string()),
                            value: at_finding
                                .iter()
                                .filter(|resource| {
                                    resource
                                        .finding_reason_codes
                                        .iter()
                                        .any(|held| held == reason_code)
                                })
                                .count() as f64,
                        })
                        .collect()
                }),
            }
        })
        .collect()
}

/// How many of `resources` run each `CurrentPerformanceRisk`. Every rating is reported,
/// including the ones no resource runs, because the shape's members are counts with a
/// default of `0` rather than optional ones.
fn performance_risk_ratings(
    resources: &[&crate::state::AnalysedResource],
) -> CurrentPerformanceRiskRatings {
    let count_at = |rating: &str| -> i64 {
        resources
            .iter()
            .filter(|resource| resource.current_performance_risk == rating)
            .count() as i64
    };
    CurrentPerformanceRiskRatings {
        high: count_at(crate::state::PERFORMANCE_RISK_HIGH),
        medium: count_at(crate::state::PERFORMANCE_RISK_MEDIUM),
        low: count_at(crate::state::PERFORMANCE_RISK_LOW),
        very_low: count_at(crate::state::PERFORMANCE_RISK_VERY_LOW),
    }
}

/// The top savings opportunities among the resources running inferred workload types, by
/// the set of types inferred for them: what adopting their recommendations would save per
/// month, largest first, at most [`TOP_INFERRED_WORKLOAD_SAVINGS`] of them. A set whose
/// resources save nothing is no opportunity, so it is not reported.
fn inferred_workload_savings(
    resources: &[&crate::state::AnalysedResource],
) -> Vec<InferredWorkloadSaving> {
    let mut by_workload: ::std::collections::BTreeMap<&[String], f64> =
        ::std::collections::BTreeMap::new();
    for resource in resources {
        if resource.inferred_workload_types.is_empty() {
            continue;
        }
        *by_workload
            .entry(resource.inferred_workload_types.as_slice())
            .or_insert(0.0) += resource.monthly_savings();
    }
    let mut savings: Vec<(&[String], f64)> = by_workload
        .into_iter()
        .filter(|(_, value)| *value > 0.0)
        .collect();
    savings.sort_by(|left, right| right.1.total_cmp(&left.1));
    savings.truncate(TOP_INFERRED_WORKLOAD_SAVINGS);
    savings
        .into_iter()
        .map(|(workload_types, value)| InferredWorkloadSaving {
            inferred_workload_types: Some(workload_types.to_vec()),
            estimated_monthly_savings: Some(estimated_monthly_savings(value)),
        })
        .collect()
}

/// A savings opportunity: what the recommendations would save per month, and that saving
/// "as a percentage of monthly cost" (`SavingsOpportunity$savingsOpportunityPercentage`).
/// A resource type that costs nothing today has no percentage to state, so it reports the
/// member's own default of `0`.
fn savings_opportunity(savings: f64, current_monthly_cost: f64) -> SavingsOpportunity {
    let percentage = if current_monthly_cost > 0.0 {
        rounded_money(savings / current_monthly_cost * 100.0)
    } else {
        0.0
    };
    SavingsOpportunity {
        savings_opportunity_percentage: percentage,
        estimated_monthly_savings: Some(estimated_monthly_savings(savings)),
    }
}

/// A monthly saving amount, in the currency the catalog's prices are denominated in.
fn estimated_monthly_savings(value: f64) -> EstimatedMonthlySavings {
    EstimatedMonthlySavings {
        currency: Some(crate::state::CURRENCY_USD.to_string()),
        value: rounded_money(value),
    }
}

/// A money (or percentage) figure to the cent, so summing stored prices cannot report a
/// figure like `140.16000000000003`. One cent-rounding rule for the whole service, in
/// `crate::state` beside the analysis whose prices it rounds.
fn rounded_money(value: f64) -> f64 {
    crate::state::round_hundredths(value)
}
