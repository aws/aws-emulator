impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StopPipeline<Eng>
{
    type Input = StopPipelineInput;
    type Output = StopPipelineOutput;
    type Error = StopPipelineError;

    const NAME: &'static str = "StopPipeline";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_PIPELINE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_PIPELINE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let now = ::std::time::SystemTime::now();

        let state = crate::state::service_state(&*self.engine).ok_or_else(store_unavailable)?;
        let mut store = state.lock();

        let pipeline_name = input.pipeline_name.clone();
        let stored = store
            .pipelines
            .get_mut(&pipeline_name)
            .ok_or_else(|| not_found(&pipeline_name))?;
        // The transition the clock owes this pipeline is materialised first, so the status
        // this change is judged against is the settled one.
        stored.settle(now);

        // Only a running pipeline can be stopped: one still settling into a status, or
        // already stopped, is not in a stoppable state, which is what this operation's
        // ConflictException reports.
        if stored.status != crate::state::STATUS_ACTIVE {
            return Err(StopPipelineErrorModeled::ConflictException(ConflictException {
                message: Some(format!(
                    "Pipeline {pipeline_name} cannot be stopped while its status is {}",
                    stored.status
                )),
            })
            .into());
        }

        stored.status = crate::state::STATUS_STOPPING.to_string();
        stored.status_reason = Some("The pipeline is being stopped.".to_string());
        stored.pending = Some(crate::state::PendingTransition {
            to: crate::state::STATUS_STOPPED.to_string(),
            due_at: now + crate::state::TRANSITION_SPAN,
        });
        stored.last_updated_at = now;

        Ok(StopPipelineOutput {
            pipeline: Some(stored.to_pipeline()),
        })
    }
}

