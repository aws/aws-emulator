        let mut reserved_instance_spend_minor = 0_i64;
        let mut savings_plan_spend_minor = 0_i64;
        let mut payer_spend_minor = 0_i64;
        let mut subscribed_account_months = 0_usize;
        let mut is_estimated = false;
