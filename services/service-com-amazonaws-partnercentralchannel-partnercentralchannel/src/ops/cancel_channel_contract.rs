impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CancelChannelContract<Eng>
{
    type Input = CancelChannelContractInput;
    type Output = CancelChannelContractOutput;
    type Error = CancelChannelContractError;

    const NAME: &'static str = "CancelChannelContract";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_CHANNEL_CONTRACT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_CHANNEL_CONTRACT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CancelChannelContractErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the service is not mounted on a state-bearing engine".into(),
                },
            )
            .into());
        };

        // The identifier member accepts either a bare `cc-…` id or the full ARN.
        let Some(id) = crate::state::resolve_identifier(
            &input.identifier,
            crate::state::CHANNEL_CONTRACT_ID_PREFIX,
        )
        .map(str::to_string) else {
            return Err(CancelChannelContractErrorModeled::ValidationException(
                crate::state::format_validation_exception(
                    "identifier",
                    format!(
                        "Value '{}' at 'identifier' failed to satisfy constraint: Member must be a \
                         channel contract id or ARN",
                        input.identifier
                    ),
                ),
            )
            .into());
        };

        let mut probe = input.clone();
        probe.client_token = None;
        let request_fingerprint = crate::state::fingerprint(&probe);
        let client_token = input.client_token.as_deref();

        let mut guard = state.lock();
        guard.advance_clock();

        // The entitlement gate, after the request's form and before the ledger
        // and the lookup: a refused request spends no client token.
        if let Some(denied) = guard.entitlement_refusal() {
            return Err(CancelChannelContractErrorModeled::AccessDeniedException(denied).into());
        }

        match guard.classify_token(client_token, Self::NAME, &request_fingerprint) {
            crate::state::TokenOutcome::Fresh => {}
            // A retry of the same cancellation: report the contract the first
            // call canceled, read back out of the store, rather than cancelling
            // again — which would otherwise be refused, the contract no longer
            // being pending.
            crate::state::TokenOutcome::Replay(record) => {
                if let Some(contract) = record
                    .resource_id
                    .as_deref()
                    .and_then(|id| guard.channel_contracts.get(id))
                {
                    return Ok(output_for(contract));
                }
                return Err(
                    CancelChannelContractErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: "The channel contract canceled with this client token no \
                                      longer exists."
                                .into(),
                            resource_id: record.resource_id,
                            resource_type: Some(
                                crate::state::CHANNEL_CONTRACT_RESOURCE_TYPE.into(),
                            ),
                        },
                    )
                    .into(),
                );
            }
            crate::state::TokenOutcome::ParameterMismatch
            | crate::state::TokenOutcome::TokenInUse => {
                return Err(CancelChannelContractErrorModeled::ConflictException(
                    ConflictException {
                        message: "The specified clientToken has already been used with different \
                                  parameters."
                            .into(),
                        resource_id: client_token.unwrap_or_default().to_string(),
                        resource_type: "ClientToken".to_string(),
                    },
                )
                .into());
            }
        }

        // A contract is addressed by (catalog, id), so a record that does not sit
        // in that catalog is not found.
        let now = crate::state::now();
        let found = guard
            .channel_contracts
            .get(&id)
            .filter(|contract| contract.catalog == input.catalog);
        let Some(contract) = found else {
            return Err(CancelChannelContractErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: format!(
                        "Channel contract {id} was not found in catalog {}.",
                        input.catalog
                    ),
                    resource_id: Some(id.clone()),
                    resource_type: Some(crate::state::CHANNEL_CONTRACT_RESOURCE_TYPE.into()),
                },
            )
            .into());
        };

        // Only a pending contract can be canceled, and only while it is still
        // within the documented cancellation window.
        if contract.status != crate::state::CONTRACT_STATUS_PENDING {
            return Err(business_refusal(format!(
                "Channel contract {id} cannot be canceled because its status is {}.",
                contract.status
            )));
        }
        if !contract.created_within(crate::state::CANCELLATION_WINDOW, now) {
            return Err(business_refusal(format!(
                "Channel contract {id} cannot be canceled because it was created more than {} \
                 days ago.",
                crate::state::CANCELLATION_WINDOW.as_secs() / (24 * 60 * 60)
            )));
        }

        let Some(contract) = guard.channel_contracts.get_mut(&id) else {
            return Err(CancelChannelContractErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the channel contract that was just read could not be updated".into(),
                },
            )
            .into());
        };
        contract.status = crate::state::CONTRACT_STATUS_CANCELED.to_string();
        contract.updated_at = now;
        contract.responded_at = Some(now);
        // The reason a contract was canceled with is recorded once: a later
        // request neither changes nor removes it.
        if contract.cancellation_reason.is_none() {
            contract.cancellation_reason = input.reason.clone();
        }

        guard.record_token(
            client_token,
            Self::NAME,
            &request_fingerprint,
            Some(id.clone()),
        );

        // Answer from the store, not from the request struct.
        let contract = guard.channel_contracts.get(&id).ok_or_else(|| {
            CancelChannelContractError::from(
                CancelChannelContractErrorModeled::InternalServerException(
                    InternalServerException {
                        message: "the channel contract that was just canceled could not be read \
                                  back"
                            .into(),
                    },
                ),
            )
        })?;
        Ok(output_for(contract))
    }
}

/// The response for a stored contract. The ONE place this operation's output is
