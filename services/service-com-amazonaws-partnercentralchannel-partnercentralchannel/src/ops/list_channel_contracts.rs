        // `contractTypeFilters` is a type-specific union: the variant a request
        // sends must be the one its `contractType` names, so a mismatch is refused
        // rather than quietly ignored. Each `relationshipIdentifiers` entry is an
        // `rs-…` id or the matching ARN; the filter compares bare ids, so each is
        // resolved first and one that is neither is refused rather than dropped.
