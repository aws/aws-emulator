impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListChecks<Eng>
{
    type Input = ListChecksInput;
    type Output = ListChecksOutput;
    type Error = ListChecksError;

    const NAME: &'static str = "ListChecks";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_CHECKS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_CHECKS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `ctx` carries only request metadata; this operation reads nothing from it.
        let _ = ctx;
        // The support-level gate, ahead of everything else this handler does —
        // ahead of serving the check catalog in particular. See
        // [`crate::state::support_level_refusal`].
        if let Some(denied) = crate::state::support_level_refusal(&*self.engine) {
            return Err(ListChecksErrorModeled::AccessDeniedException(denied).into());
        }
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ListChecksErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the Trusted Advisor store is unavailable".to_string(),
                },
            )
            .into());
        };
        let state = state.lock();

        // Every filter is an equality (or membership) test against the stored
        // check; an absent filter matches every check.
        let matching: Vec<(String, CheckSummary)> = state
            .checks
            .iter()
            .filter(|(_, check)| {
                input
                    .pillar
                    .as_ref()
                    .is_none_or(|pillar| check.pillars.iter().any(|stored| stored == pillar))
                    && input.aws_service.as_ref().is_none_or(|service| {
                        check.aws_services.iter().any(|stored| stored == service)
                    })
                    && input.source.as_ref().is_none_or(|source| &check.source == source)
            })
            .map(|(id, check)| {
                (
                    id.clone(),
                    check_summary(check, input.language.as_deref()),
                )
            })
            .collect();

        let page = crate::state::paginate(
            &crate::state::list_scope(
                "checks",
                &[
                    ("pillar", input.pillar.as_deref()),
                    ("awsService", input.aws_service.as_deref()),
                    ("source", input.source.as_deref()),
                ],
            ),
            matching,
            input.next_token.as_deref(),
            input.max_results,
        )
        .map_err(|malformed| {
            ListChecksErrorModeled::ValidationException(ValidationException {
                message: validation::page_token_refusal(malformed.token()),
            })
        })?;

        Ok(ListChecksOutput {
            next_token: page.next_token,
            check_summaries: page.items,
        })
    }
}
