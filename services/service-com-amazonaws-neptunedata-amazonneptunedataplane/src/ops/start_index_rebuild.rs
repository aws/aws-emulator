        // two tokens differing only in surrounding whitespace are two requests. A token with
        // nothing but whitespace in it identifies no request, so it counts as absent.
        let client_token = input
            .client_token
            .filter(|token| !token.trim().is_empty());

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();

