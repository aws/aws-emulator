/// What a restore left behind: the state the resource is in from now on, and the instant it
/// was last modified.
struct Restored {
    state: String,
    last_modified: ::std::time::SystemTime,
}

/// Cancel a pending scheduled deletion on one resource of the tree, "returning the resource
/// to the ACTIVE state".
///
/// "Restore only works while the target is `PENDING_DELETION`; once the scheduled deletion
/// has begun executing (`DELETING`) or has completed, the call fails" — and "restoring a
/// resource that is already `ACTIVE` is a no-op success", which touches nothing, not even
/// the resource's `LastModified`, because nothing about it changed.
///
/// The four members are passed one by one because the three resources of the tree are three
/// different records carrying the same four: ONE rule, applied wherever it holds, rather
/// than three copies of it. `Err` carries the state that does not permit a restore, which is
/// what the refusal names.
fn restore(
    state: &mut String,
    pending: &mut Option<crate::state::PendingTransition>,
    pending_deletion_at: &mut Option<::std::time::SystemTime>,
    last_modified: &mut ::std::time::SystemTime,
    now: ::std::time::SystemTime,
) -> Result<Restored, String> {
    if state.as_str() == runtimes::STATE_ACTIVE {
        return Ok(Restored {
            state: state.clone(),
            last_modified: *last_modified,
        });
    }
    if state.as_str() != runtimes::STATE_PENDING_DELETION {
        return Err(state.clone());
    }
    *state = runtimes::STATE_ACTIVE.to_string();
    // The deletion the clock owed is cancelled with the schedule that carried it, so no
    // later call materialises it.
    *pending = None;
    *pending_deletion_at = None;
    *last_modified = now;
    Ok(Restored {
        state: state.clone(),
        last_modified: now,
    })
}
