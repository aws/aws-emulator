impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ComposeEnvironments<Eng>
{
    type Input = ComposeEnvironmentsInput;
    type Output = ComposeEnvironmentsOutput;
    type Error = ComposeEnvironmentsError;

    const NAME: &'static str = "ComposeEnvironments";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPOSE_ENVIRONMENTS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPOSE_ENVIRONMENTS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let region = crate::state::request_region(ctx);
        // IAM decides whether this caller may compose the application's group of
        // environments BEFORE anything is read or written, so a caller its
        // policies do not permit is refused — ahead of every statement this call
        // makes about the request's own parameters — and no environment of the
        // group is created or updated.
        if let Some(message) = crate::service::authorization::refusal(
            &*self.engine,
            ctx,
            <Self as smithy_server_runtime::Operation>::NAME,
            &crate::state::application_resource(&region, input.application_name.as_deref()),
        ) {
            return Err(ComposeEnvironmentsError::access_denied(message));
        }
        // WHERE an environment this composition launches publishes its addresses:
        // the zone this emulator announces its own names in, and the address the
        // environment plane answers on — whose socket is opened on the first call
        // that needs one, which reaches the core and so cannot happen while the
        // store is held.
        let addressing = crate::state::published_addressing(&*self.engine, ctx).await;

        // "Takes a list of version labels that specify application source
        // bundles for each of the environments to create or update." Without one
        // there is no environment to compose at all. An absent parameter is a
        // statement about the REQUEST, so it is answered before anything the
        // request names is resolved.
        let version_labels = input.version_labels.clone().unwrap_or_default();
        if version_labels.is_empty() {
            return Err(ComposeEnvironmentsError::missing_parameter(
                "Specify at least one VersionLabel: each one names the source bundle of an environment to compose.",
            ));
        }

        // "ApplicationName: The name of the application to which the specified
        // source bundles belong." That application is the PARENT of everything
        // this call then resolves — the versions the labels name, the group's
        // environments — so a request that names no application names no
        // version to resolve a manifest out of, and one naming an application
        // that does not exist is refused here, before any precondition that
        // depends on what those children carry.
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            ComposeEnvironmentsError::internal_failure("the Elastic Beanstalk store is unavailable")
        })?;
        let mut store = state.lock();
        // Every event this call records belongs to this one request's activity.
        let request_id = crate::state::new_request_id();
        // A name freed by an environment whose termination the clock has
        // already completed is available again, and an application whose
        // deletion it has completed is gone, so settle those first.
        store.materialize_due_transitions();

        let Some(application_name) = input.application_name.clone() else {
            return Err(ComposeEnvironmentsError::missing_parameter(
                NO_VALID_APPLICATION_VERSION_MESSAGE,
            ));
        };
        if !store.applications.contains_key(&application_name) {
            // The code is the one the service's recorded refusal of this
            // precondition carries — the same generic query code this
            // operation answers its other unsatisfiable preconditions with —
            // rather than one inferred from the sentence.
            return Err(ComposeEnvironmentsError::missing_parameter(
                "Application could not be found",
            ));
        }

        // "TooManyEnvironmentsException: The specified account has reached its
        // limit of environments." A composition names one environment per
        // version label, so a request naming more labels than the account may
        // hold environments cannot be composed whatever those labels resolve to
        // — which is also what bounds the work the resolution below does.
        if version_labels.len() > crate::state::MAX_ENVIRONMENTS {
            return Err(ComposeEnvironmentsErrorModeled::TooManyEnvironmentsException(
                TooManyEnvironmentsException {
                    message: Some(format!(
                        "The number of environments in this account has reached the limit of {}.",
                        crate::state::MAX_ENVIRONMENTS
                    )),
                },
            )
            .into());
        }

        // "A list of version labels, specifying one or more application source
        // bundles that BELONG TO THE TARGET APPLICATION": the labels are scoped
        // to the versions of the application the request names, so a label
        // naming a version of another application (or no version at all) names
        // nothing this call can compose from.
        //
        // What a composition needs out of a version — the environment manifest
        // and the configuration files beside it — is what the version's
        // PRE-PROCESSING reads, so a version of this application whose
        // pre-processing has not finished successfully cannot be composed from
        // either: it carries no validated manifest yet. Both are decided in the
        // one pass that resolves each label, in the order the request listed
        // them.
        let mut scoped: Vec<String> = Vec::new();
        let mut unprocessed: Option<(String, String)> = None;
        for version_label in &version_labels {
            let Some(version) = store
                .application_versions
                .get(&(application_name.clone(), version_label.clone()))
            else {
                continue;
            };
            if unprocessed.is_none() && !version.is_successfully_processed() {
                unprocessed = Some((version_label.clone(), version.status.clone()));
            }
            scoped.push(version_label.clone());
        }
        // When the scoping leaves no version, there is no application version to
        // compose at all, which is what the service's fixed sentence for that
        // class reports.
        if scoped.is_empty() {
            return Err(ComposeEnvironmentsError::missing_parameter(
                NO_VALID_APPLICATION_VERSION_MESSAGE,
            ));
        }
        // A version that is the application's but not yet processed is a
        // statement about the VERSION's state rather than about a parameter the
        // request got wrong, so it is reported as the configuration refusal
        // naming the label and the status the version is in — the transient
        // state a client waits out and retries, told apart from a label that
        // names no version of the application at all.
        if let Some((version_label, status)) = unprocessed {
            return Err(ComposeEnvironmentsError::configuration_validation(
                crate::state::unprocessed_version_refusal(&version_label, &status),
            ));
        }

        // "Each source bundle must include an environment manifest that
        // specifies the name of the environment and the name of the solution
        // stack to use, and optionally can specify environment links to
        // create": every label is resolved to that manifest FIRST, so a
        // request one of whose labels describes no environment composes none of
        // them rather than half the group.
        let mut composing: Vec<ComposedManifest> = Vec::new();
        for version_label in &scoped {
            let manifest = store
                .application_versions
                .get(&(application_name.clone(), version_label.clone()))
                .and_then(|version| version.bundle.as_ref())
                .and_then(crate::state::environment_manifest);
            // A version whose source bundle this emulator holds no files of, a
            // bundle with no readable environment manifest, and a manifest that
            // names no environment all leave this call with no environment to
            // compose for that label.
            let manifest_name = manifest
                .as_ref()
                .and_then(|manifest| manifest.environment_name.clone());
            let (Some(manifest), Some(manifest_name)) = (manifest, manifest_name) else {
                return Err(ComposeEnvironmentsError::missing_parameter(
                    NO_VALID_APPLICATION_VERSION_MESSAGE,
                ));
            };
            // "Specify a group name only if the environment name defined in
            // each target environment's manifest ends with a + (plus)
            // character": a manifest name ending in that placeholder is a
            // TEMPLATE for the per-group name of an environment, which the
            // group the request names COMPLETES — so the environment this call
            // creates or updates for such a manifest is the group's own, and
            // one application composed into two groups holds two environments
            // per manifest. A manifest that names an environment outright is
            // composed under that name, whatever group the request names. The
            // completion is the one every operation that names an environment
            // through a manifest rather than through its own `EnvironmentName`
            // parameter performs.
            let environment_name = crate::state::composed_environment_name(
                &manifest_name,
                input.group_name.as_deref(),
            );
            // An environment of that name belonging to ANOTHER application is
            // not one this composition may deploy to: "this name must be unique
            // within a region in your account", which is what every launch is
            // refused for a name already taken with.
            let taken_elsewhere = store
                .environment_name_index
                .get(&environment_name)
                .and_then(|id| store.environments.get(id))
                .is_some_and(|existing| {
                    !existing.is_terminated() && existing.application_name != application_name
                });
            if taken_elsewhere {
                return Err(ComposeEnvironmentsError::invalid_parameter_value(format!(
                    "Environment {environment_name} already exists."
                )));
            }
            composing.push(ComposedManifest {
                version_label: version_label.clone(),
                environment_name,
                manifest,
            });
        }

        // "TooManyEnvironmentsException: The specified account has reached its
        // limit of environments." A label whose manifest names an environment
        // the group already runs UPDATES it, so only the ones this composition
        // would launch count against the quota — and each NAME counts once,
        // however many of this request's labels resolve to it, since composing
        // a name the request has already composed updates that one environment
        // rather than launching a second.
        let mut launching: ::std::collections::BTreeSet<&str> = ::std::collections::BTreeSet::new();
        for composed in &composing {
            let already_running = store
                .environment_name_index
                .get(&composed.environment_name)
                .and_then(|id| store.environments.get(id))
                .is_some_and(|existing| !existing.is_terminated());
            if !already_running {
                launching.insert(composed.environment_name.as_str());
            }
        }
        if store.running_environment_count() + launching.len() > crate::state::MAX_ENVIRONMENTS {
            return Err(ComposeEnvironmentsErrorModeled::TooManyEnvironmentsException(
                TooManyEnvironmentsException {
                    message: Some(format!(
                        "The number of environments in this account has reached the limit of {}.",
                        crate::state::MAX_ENVIRONMENTS
                    )),
                },
            )
            .into());
        }

        // The model binds one `EnvironmentDescription` shape here; the scaffold
        // emits a per-operation struct for it, and this is the name that shape
        // carries in this crate.
        type EnvironmentDescription = CreateEnvironmentOutput;
        let mut environments = Vec::new();
        for composed in &composing {
            // "Links provide connection information in system properties that
            // can be used to connect to another environment in the same group":
            // a link's target is named the way the manifests name environments,
            // so a target that is a group template is completed by the group
            // exactly as the environment's own name is, and the link reports
            // the environment of this group it really names.
            let environment_links = composed
                .manifest
                .links
                .iter()
                .map(|(link_name, target)| EnvironmentLink {
                    link_name: Some(link_name.clone()),
                    environment_name: Some(crate::state::composed_environment_name(
                        target,
                        input.group_name.as_deref(),
                    )),
                })
                .collect();
            // "The name of each environment and other required information
            // must be included in the source bundles in an environment
            // manifest named env.yaml": the manifest is the whole of what
            // configures a composed environment, so the IAM instance profile
            // its instances are given — "instance profile that gives the
            // environment's instances the permissions they need" — is the one
            // the manifest associates with them, and a manifest that
            // associates none leaves the launch without one. Handing that role
            // over is the CALLER's act, so IAM decides whether this caller may
            // pass the profile the manifest does name. Either way the launch
            // cannot be provisioned, and the refusal is reported on the
            // environment rather than as this call's answer. The decision
            // reads the IAM store alone; nothing of this service's state goes
            // into it.
            let launch_refusal = match crate::state::associated_instance_profile(
                &composed.manifest.option_settings,
            ) {
                None => Some(crate::state::missing_instance_profile_diagnosis()),
                Some(instance_profile) => {
                    crate::service::authorization::pass_instance_profile_refusal(
                        &*self.engine,
                        ctx,
                        &instance_profile,
                    )
                }
            };
            let environment = store.compose_environment(crate::state::ComposedEnvironment {
                region: &region,
                addressing: &addressing,
                application_name: &application_name,
                version_label: &composed.version_label,
                environment_name: &composed.environment_name,
                manifest: &composed.manifest,
                environment_links,
                launch_refusal,
                request_id: &request_id,
            });
            environments.push(crate::state::environment_description!(
                EnvironmentDescription,
                &environment
            ));
        }

        Ok(ComposeEnvironmentsOutput {
            // Every environment this call composed or updated, one per version
            // label whose manifest described one.
            environments: Some(environments),
            // Every environment this call composed is reported, so there is no
            // page left for a continuation token to name.
            next_token: None,
        })
    }
}

/// One environment this call is composing: the version label whose source
/// bundle carried the manifest, the manifest itself, and the environment it
/// names — the manifest's name with a group template completed by the group the
/// request named.
///
/// Every label is resolved to one of these BEFORE the first environment is
/// touched, so a request with a label that resolves to no manifest leaves the
/// group exactly as it was.
struct ComposedManifest {
    version_label: String,
    environment_name: String,
    manifest: crate::state::EnvironmentManifest,
}

