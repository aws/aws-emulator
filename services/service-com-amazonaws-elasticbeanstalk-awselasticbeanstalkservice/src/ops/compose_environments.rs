//! @op ComposeEnvironments
//! Implemented: scopes the requested version labels to the versions of the application
//! the request names, reads the environment manifest (`env.yaml`) out of each of those
//! versions' source bundles, and launches one environment per manifest that names one —
//! or deploys the version to the environment the group already runs under that name,
//! since this operation "creates or updates a group of environments". A manifest whose
//! `EnvironmentName` ends in the `+` a group name completes is a TEMPLATE for the
//! group's own name for that environment, so the group name the request carries
//! completes it (`crate::state::composed_environment_name`) — the same completion every
//! other operation that names an environment through a manifest performs — and the
//! targets the manifest's links name are completed the same way, since a link names
//! another environment of the same group.
//! Each composed environment carries that name, the manifest's solution stack, tier, option
//! settings and links to the other environments of the group, starts `Launching` and
//! reaches `Ready` the way every other launch does — unless the manifest associates no IAM
//! instance profile with the environment's instances, or IAM will not let this caller pass
//! the one it does, which no launch can be provisioned without: such an environment
//! carries that refusal as an error event and the clock takes it to `Terminated` instead
//! (`crate::state::environment_launch_failure`). Either way it is answered as an
//! `EnvironmentDescription`. A request none of whose labels names a version of the
//! application resolves no version at all, so it is refused with the service's
//! `MissingParameter` and its fixed sentence for that class; a version that IS the
//! application's but whose pre-processing has not finished successfully carries no
//! validated manifest yet, so it is refused with the configuration refusal naming that
//! label and the status the version is in, which is the transient state a client waits
//! out rather than a parameter it got wrong. A resolved and processed version whose
//! bundle holds no readable manifest describes no environment either, so it is refused
//! rather than composing an environment whose name was invented. The application the
//! request names is resolved FIRST, so a name no application exists under is reported as
//! that rather than as a version that cannot be composed. Whether the caller may compose
//! the group at all is IAM's decision, taken before any of that is read or written
//! (`crate::service::authorization`). This is the ONLY file to touch
