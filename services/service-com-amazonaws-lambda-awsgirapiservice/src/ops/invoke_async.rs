impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for InvokeAsync<Eng>
{
    type Input = InvokeAsyncInput;
    type Output = InvokeAsyncOutput;
    type Error = InvokeAsyncError;

    const NAME: &'static str = "InvokeAsync";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::INVOKE_ASYNC_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::INVOKE_ASYNC_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(InvokeAsyncErrorModeled::ServiceException(ServiceException {
                r#type: None,
                message: Some("Lambda state is not reachable on this engine".to_string()),
            })
            .into());
        };

        let now = ::std::time::SystemTime::now();
        let region = crate::state::request_region(ctx);
        // Lambda decides an invocation at the IAM layer, BEFORE the function is reached. This
        // entry point's own action is the deprecated `lambda:InvokeAsync` the IAM Service
        // Authorization Reference publishes for it, so a grant of the synchronous action is
        // not a grant of this one (`crate::state::invoke_authorization`). Asked first, with
        // no store guard held, so a refused invocation queues nothing and runs nothing.
        crate::state::authorize_invocation(
            &*self.engine,
            ctx,
            crate::state::INVOKE_ASYNC_ACTION,
            &region,
            &input.function_name,
            None,
        )?;
        let mut store = state.lock();

        // `InvokeAsync` carries no `Qualifier` parameter of its own, so the only
        // qualifier it can name is the one its `FunctionName` carries, exactly as the
        // member's pattern allows.
        let (record, version) =
            crate::state::resolve_function(&mut store, &input.function_name, None, &region, now)
                .map_err(|failure| match failure {
                    // A `FunctionName` the model's pattern admits but that names no
                    // documented resource form is a bad request this operation models no
                    // error for, so it is refused as a 400 `ValidationException` rather
                    // than with a 501.
                    crate::state::ResolveFailure::Malformed(message) => {
                        crate::scaffolded::Scaffolded::validation(message)
                    }
                    crate::state::ResolveFailure::NotFound(message) => {
                        InvokeAsyncErrorModeled::ResourceNotFoundException(
                            ResourceNotFoundException {
                                r#type: None,
                                message: Some(message),
                            },
                        )
                        .into()
                    }
                })?;

        // The model documents the provisioning window on `CreateFunction` ("During this
        // time, you can't invoke or modify the function") and on `StateReasonCode`
        // ("When the code is Creating, you can't invoke or modify the function"), so an
        // invocation that arrives inside it is refused rather than queued.
        if record.state != crate::state::STATE_ACTIVE {
            return Err(InvokeAsyncErrorModeled::ResourceConflictException(
                ResourceConflictException {
                    r#type: None,
                    message: Some(format!(
                        "The operation cannot be performed at this time. The function is \
                         currently in the following state: {}",
                        record.state
                    )),
                },
            )
            .into());
        }

        // "The payload limit is 256KB. For larger payloads, for up to 1MB, use Invoke."
        // `RequestTooLargeException` is not among this operation's modelled errors, and
        // the invocation payload ceiling is a published Lambda quota, so the request
        // that would exceed it is refused with the modelled "request would exceed a
        // service quota".
        if input.invoke_args.len() > MAX_INVOKE_ASYNC_PAYLOAD_BYTES {
            return Err(InvokeAsyncErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    r#type: None,
                    message: Some(format!(
                        "InvokeArgs must be smaller than {MAX_INVOKE_ASYNC_PAYLOAD_BYTES} \
                         bytes for InvokeAsync; use Invoke for a larger payload"
                    )),
                },
            )
            .into());
        }

        // "The JSON that you want to provide to your Lambda function as input": a body
        // that is not JSON is refused with the modelled 400 carrying the parse diagnostic
        // (`crate::state::invocation_payload`), and an empty one is the no-event
        // invocation, exactly as `Invoke` treats its own payload.
        if let Some(message) = crate::state::unparseable_payload_message(&input.invoke_args) {
            return Err(InvokeAsyncErrorModeled::InvalidRequestContentException(
                InvalidRequestContentException {
                    r#type: None,
                    message: Some(message),
                },
            )
            .into());
        }

        // Queueing the event is the whole of what this call promises, and it is what is
        // persisted: "A success response (202 Accepted) indicates that the request is
        // queued for invocation." Nothing about the run is reported to the caller, because
        // nothing has run when the answer is given; the function is invoked with the event
        // once the store is released, and the queue entry keeps what that run came to (see
        // `crate::state::async_invocation::deliver`).
        //
        // Whether the invocation happens at all is Lambda's recursive-loop guardrail's
        // decision, taken here for the same reason as on `Invoke`: an invocation arriving
        // as part of a request chain that has already come back round into this function
        // is one a `Terminate` function has stopped, and the stop is metered as one
        // `RecursiveInvocationsDropped` datapoint (`crate::state::recursion`). The chain is
        // the one THIS request carries; what this operation's own documentation withholds
        // is propagating a trace id onward to the function ("Trace ID is not propagated to
        // the function"), which is not what the chain of the request is read for.
        let chain = crate::state::request_chain(ctx);
        let stopped = crate::state::guardrail(record, chain.as_deref(), now)
            == crate::state::Guardrail::Stopped;
        // The version this invocation resolved to: an alias that splits its invocations
        // between two versions resolves per invocation (`crate::state::alias_routing`), so
        // the configuration, the package and the version reported are all that version's.
        let executed_version = record
            .routed_version(&version)
            .unwrap_or_else(|| version.clone());
        // The configuration the invocation RESOLVED — a published version's frozen one, or
        // the unpublished version's — which is what the run is performed under.
        let resolved_config = record
            .config_of(&executed_version)
            .cloned()
            .unwrap_or_else(|| record.config.clone());
        let function_name = record.config.name.clone();
        let resource = crate::state::invoked_resource(&function_name, &version);
        // The invocation this call accepts is the one its answer names: the id the run
        // reports as `context.aws_request_id` and logs its own lines under (see
        // `crate::service::request_id_header`).
        let request_id = crate::service::request_id_header::starting_invocation();
        let delivered = if stopped {
            record.record_stopped_async_invocation(&version, &request_id, input.invoke_args, now);
            None
        } else {
            // The event the queue holds is the one the function is INVOKED with, so
            // everything that run needs is copied out of the record while it is still held:
            // the run itself happens with no store guard, on a task of its own.
            let invocation = crate::state::Invocation {
                function_name: function_name.clone(),
                // "The version of the function that executed" — the version this call
                // resolved, which for an unqualified `FunctionName` is the unpublished one.
                executed_version: executed_version.clone(),
                invoked_function_arn: record.versioned_arn(&version),
                region: region.clone(),
                runtime: resolved_config.runtime.clone(),
                handler: resolved_config.handler.clone(),
                code_revision: resolved_config.revision_id.clone(),
                variables: resolved_config.environment.clone(),
                memory_size: resolved_config.memory_size,
                timeout: resolved_config.timeout,
                architecture: resolved_config
                    .architectures
                    .first()
                    .cloned()
                    .unwrap_or_default(),
                zip_bytes: record.code_of(&executed_version).zip_bytes.clone(),
                layer_zips: crate::state::layer_archives(&resolved_config.layers),
                payload: input.invoke_args.clone(),
                // This operation carries neither member, so the run is given neither: a
                // `ClientContext` and a `TenantId` reach a function only when the call that
                // invoked it named one.
                client_context: None,
                tenant_id: None,
                request_id: request_id.clone(),
                // The X-Ray trace context this invocation runs with: the chain the caller
                // named, under the rule the function's `TracingConfig` mode gives
                // (`crate::state::execution::trace_context`).
                trace: Some(crate::state::invocation_trace_context(
                    crate::state::supplied_trace_header(ctx).as_deref(),
                    &resolved_config.tracing_mode,
                    now,
                )),
                // A queued event is delivered off the response path, on an environment
                // Lambda initialises for that delivery (`crate::state::execution_slot`).
                initialization_type: crate::state::execution_slot::INITIALIZATION_TYPE_ON_DEMAND,
                // The AWS SDK this runtime supplies the handler reaches the rest of this
                // emulator through, built from the callback the framework handed THIS
                // request and signing as the session of the function's own execution role
                // — the same seam a synchronous invocation's run gets.
                aws: crate::state::function_sdk_access(
                    &*self.engine,
                    ctx,
                    &region,
                    &resolved_config.role,
                    &function_name,
                ),
                // Where the run's log is delivered, and what the function's execution role
                // may do there (`crate::state::execution::log_delivery`).
                logs: Some(crate::state::log_target(
                    &*self.engine,
                    &region,
                    &resolved_config,
                )),
                // What the run this delivery makes is metered by once it has run, carried on
                // the invocation because the run happens off the response path
                // (`crate::state::metrics`).
                metrics: Some(crate::state::InvocationMetrics::new(
                    &*self.engine,
                    &function_name,
                    &resource,
                )),
            };
            record.queue_async_invocation(&version, &request_id, input.invoke_args, now);
            Some(invocation)
        };
        drop(store);
        if let Some(invocation) = delivered {
            // An invocation nothing stopped is one Lambda ADMITTED to the function, which is
            // metered as one `Invocations` datapoint of the function and of the resource this
            // call addressed (`crate::state::metrics`), exactly as `Invoke` meters its own.
            crate::state::publish_invocation(&*self.engine, &function_name, &resource);
            // It is also one asynchronous event ACCEPTED onto the invocation queue, which is
            // the other thing this call does and is metered as one `AsyncEventsReceived`
            // datapoint (`crate::state::metrics`).
            crate::state::publish_async_event_received(&*self.engine, &function_name, &resource);
            // `InvokeAsync` is the deprecated invocation API and carries no
            // `DurableExecutionName` member at all, so it starts no durable execution and
            // its delivery settles none.
            crate::state::async_invocation::deliver(&state, invocation, None);
        } else {
            crate::state::publish_recursive_invocation_dropped(&*self.engine, &function_name);
        }

        Ok(InvokeAsyncOutput {
            status: ACCEPTED_STATUS,
        })
    }
}

