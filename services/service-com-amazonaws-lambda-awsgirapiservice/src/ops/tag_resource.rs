impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 204u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::ServiceException(ServiceException {
                r#type: None,
                message: Some("Lambda state is not reachable on this engine".to_string()),
            })
            .into());
        };
        let region = crate::state::request_region(ctx);

        // What Lambda will STORE a tag under is judged before anything is looked up or
        // written: a key must be named, must not be in the namespace AWS keeps for its
        // own tags, and must be named only once.
        if input.tags.is_empty() {
            return Err(TagResourceErrorModeled::InvalidParameterValueException(
                InvalidParameterValueException {
                    r#type: None,
                    message: Some(crate::state::EMPTY_TAGS_MESSAGE.to_string()),
                },
            )
            .into());
        }
        // The reserved-namespace half of that rule binds a CALLER, so which path the
        // request arrived on is part of it ([`crate::state::tag_key_origin`]).
        if !crate::state::tag_keys_are_storable_from(
            input.tags.keys().map(String::as_str),
            crate::state::tag_key_origin(ctx),
        ) {
            return Err(invalid_tags());
        }
        // What remains is the SHAPE of each key, which the request walk never checks a
        // map's key against ([`crate::state::tag_key_shape_refusal`]).
        if let Some(message) = crate::state::tag_key_shape_refusal(
            input
                .tags
                .iter()
                .map(|(key, value)| (key.as_str(), value.as_str())),
        ) {
            return Err(crate::scaffolded::Scaffolded::validation(message));
        }

        let mut store = state.lock();
        // The one tag map the store holds for the named resource — the same map
        // `ListTags` reports and `CreateFunction` filled in, never a second copy.
        let tags = crate::state::resolve_resource_tags(
            &mut store,
            &input.resource,
            &region,
            ::std::time::SystemTime::now(),
        )
        .map_err(refusal)?;

        // The resource's own tag count is what the published limit bounds, so what counts
        // is the set the merge would LEAVE behind: a key the resource already carries is
        // replaced rather than added.
        let added = input
            .tags
            .keys()
            .filter(|key| !tags.contains_key(key.as_str()))
            .count();
        let merged = tags.len().saturating_add(added);
        if merged > crate::state::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::InvalidParameterValueException(
                InvalidParameterValueException {
                    r#type: None,
                    message: Some(crate::state::TAG_LIMIT_EXCEEDED_MESSAGE.to_string()),
                },
            )
            .into());
        }

        // Merge: every key the request names takes the value the request gives it, and
        // every other key the resource carries is left alone.
        for (key, value) in &input.tags {
            tags.insert(key.clone(), value.clone());
        }

        Ok(TagResourceOutput)
    }
}

