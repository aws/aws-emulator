impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for SendTaskSuccess<Eng>
{
    type Input = SendTaskSuccessInput;
    type Output = SendTaskSuccessOutput;
    type Error = SendTaskSuccessError;

    const NAME: &'static str = "SendTaskSuccess";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEND_TASK_SUCCESS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEND_TASK_SUCCESS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `taskToken` (1..2048) and `output` (0..262144) are modelled, so the
        // centralized walk has already refused anything outside them. That the output
        // is JSON, and that the token is one this service issued, are not modelled, so
        // they are checked here. No member of the request is read off `ctx`: a task
        // token names its task, its execution and its region on its own. What `ctx`
        // IS read for is the in-process callback the continuation's own service
        // integrations are called through.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::STORE_UNAVAILABLE,
            ));
        };

        // `output`'s own documentation: "Length constraints apply to the payload size,
        // and are expressed as bytes in UTF-8 encoding" — the half of that bound the
        // centralized walk cannot enforce, since `@length` counts a string's
        // CHARACTERS. This operation's model declares no `ValidationException`, so the
        // refusal goes out through the crate's one non-modelled channel, carrying the
        // same message the walk states for a payload past its bound.
        if let Some(message) = crate::state::payload_size::payload_refusal("output", &input.output) {
            return Err(crate::scaffolded::Scaffolded::validation(message));
        }

        // "The JSON output of the task": a document that is not JSON is refused with
        // the modelled `InvalidOutput` BEFORE anything is read or written, so a
        // refused reply changes nothing — the task stays outstanding and the token
        // still answers it.
        let Ok(result) = serde_json::from_str::<serde_json::Value>(&input.output) else {
            return Err(SendTaskSuccessErrorModeled::InvalidOutput(InvalidOutput {
                message: Some(crate::state::invalid_output_message(&input.output)),
            })
            .into());
        };

        // The token is read BEFORE the store is consulted, exactly as every ARN here
        // is: a value that is not a token this service mints is a defect in the
        // REQUEST, which `InvalidToken` reports, and not a task that has been closed.
        if crate::state::read_task_token(&input.task_token).is_none() {
            return Err(SendTaskSuccessErrorModeled::InvalidToken(InvalidToken {
                message: Some(crate::state::invalid_token_message()),
            })
            .into());
        }

        let now = crate::state::now();

        // An execution of a state machine on a customer managed KMS key has
        // everything it retains sealed under that key, and the reply's `output` is
        // recorded as the task's result, so that document is sealed under the key too:
        // KMS decides whether this caller may have the key used for it before anything
        // is written. `output` is required of this operation, so there is no reply here
        // that seals nothing. The decision is made with no store of this service
        // locked.
        if let Some(refusal) =
            crate::state::encryption::task_reply_write_denied(&*self.engine, ctx, &input.task_token)
        {
            return Err(crate::kms_key_refusal!(SendTaskSuccessErrorModeled, refusal).into());
        }

        // Phase 1, under the lock: resolve the task, refuse what cannot be answered,
        // and read what the continuation needs. The lock is released before the walk,
        // so no other request waits on an interpretation.
        let (
            definition,
            execution_input,
            previous_event_id,
            execution_arn,
            start_date,
            machine_arn,
            context,
            reply,
        ) = {
            let mut store = state.lock();
            // Settle first: a task whose own bound the clock already made due is
            // closed — and the execution waiting at it failed — before this call
            // decides whether the token still answers anything.
            store.settle(now);

            // A CALLBACK task's token answers it from the instant the `Task` state's
            // own call CARRIED it, which is BEFORE that call has come back and so
            // before the suspended task exists: the work the token reached may report
            // the task's outcome from inside that very call, which is how the pattern
            // is written for a function handed `$$.Task.Token`
            // ([`crate::state::callbacks`]). Such an answer is RECORDED against the
            // handover and reported answered here, interpreting nothing: the walk whose
            // call carries the token finishes the state with it, so the execution is
            // continued once, by the request that owns that walk.
            match store.answer_callback_handover(&input.task_token, Ok(result.clone())) {
                crate::state::CallbackHandoverReply::Recorded => {
                    return Ok(SendTaskSuccessOutput {})
                }
                // One token answers one task: a handover something has already answered
                // takes no second answer.
                crate::state::CallbackHandoverReply::Answered => {
                    return Err(SendTaskSuccessErrorModeled::TaskTimedOut(TaskTimedOut {
                        message: Some(crate::state::task_timed_out_message()),
                    })
                    .into())
                }
                // No call carrying this token is in flight, so what answers it is the
                // task the store records — an activity's, or a callback the walk has
                // suspended at.
                crate::state::CallbackHandoverReply::NoHandover => {}
            }

            let Some(task) = store.activity_tasks.get(&input.task_token) else {
                return Err(SendTaskSuccessErrorModeled::TaskTimedOut(TaskTimedOut {
                    message: Some(crate::state::task_timed_out_message()),
                })
                .into());
            };
            let activity_arn = task.activity_arn.clone();
            let execution_arn = task.execution_arn.clone();
            let state_name = task.state_name.clone();
            // The state's RAW input, which its `ResultPath` combines the reply with:
            // the task carries it, so the reply is placed against the document the
            // state was really entered with.
            let state_input = task.state_input.clone();
            // What this state's retriers have already spent on the task, so the
            // continuation takes that budget up rather than restarting it.
            let retries_taken = task.retries_taken.clone();
            // The activity this task is queued under can be DELETED while the task is
            // outstanding, which leaves the task with no activity to be answered for:
            // the modelled `TaskDoesNotExist`, whose own documentation is "the
            // activity does not exist". A CALLBACK task belongs to no activity, so
            // nothing of the kind can have gone missing for one.
            let missing_activity = activity_arn
                .as_ref()
                .filter(|activity_arn| !store.activities.contains_key(*activity_arn));
            if let Some(activity_arn) = missing_activity {
                return Err(SendTaskSuccessErrorModeled::TaskDoesNotExist(
                    TaskDoesNotExist {
                        message: Some(crate::state::resource_error_message(
                            crate::state::ACTIVITY_DOES_NOT_EXIST,
                            activity_arn,
                        )),
                    },
                )
                .into());
            }
            // A task whose execution is no longer running is answered by nobody: it
            // was stopped, or the clock closed an earlier bound of it, so the token
            // names a task that has already been closed.
            let Some(execution) = store
                .executions
                .get(&execution_arn)
                .filter(|execution| !execution.is_terminal())
            else {
                return Err(SendTaskSuccessErrorModeled::TaskTimedOut(TaskTimedOut {
                    message: Some(crate::state::task_timed_out_message()),
                })
                .into());
            };
            let Some(machine) = store.state_machines.get(&execution.state_machine_arn) else {
                return Err(SendTaskSuccessErrorModeled::TaskTimedOut(TaskTimedOut {
                    message: Some(crate::state::task_timed_out_message()),
                })
                .into());
            };
            // The context object (`$$`) the continuation reads is the SAME execution's
            // identity: a reply continues this execution rather than starting one, so
            // `$$.Execution.Id` and `$$.Execution.Name` do not change.
            let context = crate::state::asl::Context {
                execution_arn: execution.arn.clone(),
                execution_name: execution.name.clone(),
                state_machine_arn: machine.arn.clone(),
                state_machine_name: machine.name.clone(),
                role_arn: machine.role_arn.clone(),
                // A reply CONTINUES the attempt it was scheduled on rather than
                // beginning another, so the states it runs on read the count the
                // record already carries — not one more.
                redrive_count: execution.redrive_count,
                // The workflow type the continuation is interpreted under, which
                // decides whether a `Task` state after the reply may ask for the
                // run-a-job (`.sync`) integration pattern.
                express: machine.sm_type == crate::state::STATE_MACHINE_TYPE_EXPRESS,
            };
            // The execution runs the definition it was STARTED on, which for one
            // started through a version ARN — or through an alias that routed to a
            // version — is that version's immutable snapshot and not what the state
            // machine has been updated to since.
            let definition = execution
                .state_machine_version_arn
                .as_deref()
                .and_then(|version_arn| store.state_machine_versions.get(version_arn))
                .map_or_else(
                    || machine.definition.clone(),
                    |version| version.definition.clone(),
                );
            (
                definition,
                execution.input.clone(),
                execution.last_event_id(),
                execution_arn,
                execution.start_date,
                machine.arn.clone(),
                context,
                // Which kind of task the token named decides which continuation the
                // reply begins: an activity's task is answered at the state that
                // SCHEDULED it, a callback task at the state whose integration call
                // CARRIED the token — whose `Retry` may make that call again.
                match activity_arn {
                    Some(_) => Answered::Activity(crate::state::asl::ActivityReply {
                        state_name,
                        state_input,
                        result,
                    }),
                    None => Answered::Callback(crate::state::asl::CallbackReply {
                        state_name,
                        state_input,
                        outcome: Ok(result),
                        retries_taken,
                    }),
                },
            )
        };

        // Phase 2, OUTSIDE the lock: the continuation is INTERPRETED here, from the
        // state the task was scheduled at. It places the worker's reply against the
        // raw input that state was entered with and runs on from its `Next`; the
        // states after the reply may themselves be service integrations, so their
        // calls are made from this request's own task exactly as a start's are
        // (`state::integration::interpret`), in the state machine's own Region. The
        // outcome the walk computes is owed to the clock, so the execution reports
        // `RUNNING` until then.
        let interpreted = {
            let definition = definition.clone();
            let execution_input = execution_input.clone();
            let region = crate::state::arn_region(&machine_arn);
            // The states after the reply call as the SAME execution role the states
            // before it did, which this service assumes again for this continuation.
            let unassumable = crate::state::task_authorization::unassumable_role(
                ctx.callback(),
                &region,
                &context.role_arn,
                &context.state_machine_arn,
            )
            .await;
            let acting = crate::state::task_authorization::acting(
                &self.engine,
                &region,
                &context.role_arn,
                &context.state_machine_name,
                unassumable,
            );
            crate::state::integration::interpret(ctx, &region, acting, move |tasks| match &reply {
                Answered::Activity(reply) => crate::state::plan_reply(
                    &definition,
                    &execution_input,
                    start_date,
                    now,
                    &context,
                    reply,
                    previous_event_id,
                    tasks,
                ),
                Answered::Callback(reply) => crate::state::plan_callback_reply(
                    &definition,
                    &execution_input,
                    start_date,
                    now,
                    &context,
                    reply,
                    previous_event_id,
                    tasks,
                ),
            })
            .await
        };
        let Ok(planned) = interpreted else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::INTERPRETER_UNAVAILABLE,
            ));
        };
        // The definition no longer declares the state the task was scheduled at, so
        // there is nothing to continue the execution with: the reply is refused and
        // the execution is left exactly as it was, rather than carried to an outcome
        // no definition describes.
        let Some(planned) = planned else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::TASK_STATE_NOT_REACHED,
            ));
        };
        // A job the continuation STARTED and then abandoned is stopped through its own
        // integration, as a start's own is: no job is left running behind a task that
        // will never finish. Done with no store of this service locked.
        crate::state::integration::stop_abandoned(
            ctx.callback(),
            &crate::state::arn_region(&machine_arn),
            &planned.abandoned,
            planned.abandoned_stop_at(),
        )
        .await;

        // Phase 3, under the lock again: record it. Every check is re-made, because
        // the task could have been answered or closed while the walk ran. The lock is
        // held for THIS block alone, because the publication below must not hold the
        // store while it is in flight; the block answers whether the continuation
        // parked at a job of its own.
        let watching = {
            let mut store = state.lock();
            store.settle(now);
            let waiting = planned.waiting;
            let parked = planned.parked;
            let task_bytes = waiting
                .as_ref()
                .map_or(0, crate::state::PlannedActivityTask::measure)
                + parked.as_ref().map_or(0, crate::state::PlannedJob::measure);
            let map_runs = planned.map_runs;
            let map_run_bytes = crate::state::planned_map_run_bytes(&map_runs);
            let answered = store.answer_activity_task(
                &input.task_token,
                planned.opening,
                planned.pending,
                task_bytes + map_run_bytes,
                // The unsuccessful step this continuation stopped at, if it stopped at
                // one: what a later redrive continues the execution from.
                planned.stopped_at,
            );
            match answered {
                Ok(()) => {
                    // The continuation reached ANOTHER activity task: it is queued for
                    // a worker to claim exactly as the first one was.
                    if let Some(waiting) = waiting {
                        store.schedule_activity_task(&execution_arn, waiting);
                    }
                    // A Distributed Map state the continuation entered started a Map
                    // Run of its own, which `ListMapRuns` reports for this execution
                    // beside the ones its earlier states started.
                    store.append_map_runs(&execution_arn, &machine_arn, map_runs);
                    // The continuation PARKED at the job a run-a-job task started,
                    // which is polled to its end exactly as one a start parked at is.
                    let watching = parked.is_some();
                    if let Some(parked) = parked {
                        let region = crate::state::arn_region(&machine_arn);
                        store.park_job(&execution_arn, parked, &region);
                    }
                    watching
                }
                Err(crate::state::TaskReplyRejection::Gone) => {
                    return Err(SendTaskSuccessErrorModeled::TaskTimedOut(TaskTimedOut {
                        message: Some(crate::state::task_timed_out_message()),
                    })
                    .into())
                }
                // The continuation's own events and outcome are what the execution
                // would grow by, so a reply the store has no room for is refused rather
                // than retained past its ceiling. This operation models no limit error,
                // so the refusal is the standard 400 validation envelope.
                Err(crate::state::TaskReplyRejection::NoRoom) => {
                    return Err(crate::scaffolded::Scaffolded::validation(format!(
                        "continuing execution {execution_arn} would take the store past the {} \
                         bytes this emulator retains",
                        crate::state::MAX_STORE_BYTES
                    )))
                }
            }
        };
        if watching {
            crate::state::run_a_job::watch(
                std::sync::Arc::clone(&self.engine),
                ctx.callback().clone(),
                crate::state::integration::chain_depth(ctx),
                execution_arn.clone(),
            );
        }
        // The continuation may have carried the execution to its terminal status, which
        // is a status change this service publishes onto the account's default event
        // bus; the clock this starts publishes one the continuation left owed to a
        // later instant.
        crate::state::events::publish(&self.engine, ctx.callback()).await;
        Ok(SendTaskSuccessOutput {})
    }
}
