impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TestState<Eng>
{
    type Input = TestStateInput;
    type Output = TestStateOutput;
    type Error = TestStateError;

    const NAME: &'static str = "TestState";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_STATE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_STATE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `TestState` "accepts the definition of a single state and executes it. You
        // can test a state without creating a state machine or updating an existing
        // state machine": the call names no resource of THIS service, so it stores
        // nothing of its own and no state machine or execution of it exists afterwards.
        // What the state under test DOES is still done: a `Task` state's integration
        // call is made, under the role the request named, so the resources that call
        // acts on are the invoked service's own to change — which is the whole point of
        // testing "an Amazon Web Services service integration request and response".
        // The engine the operation was constructed from is where the role's own records
        // are read from, and the endpoint's Region is the one those calls are made in.

        // `revealSecrets` "specifies whether or not to include secret information in
        // the test result. For HTTP Tasks, a secret includes the data that an
        // EventBridge connection adds to modify the HTTP request headers, query
        // parameters, and body." Nothing of a connection's own is reported here either
        // way. What the member DOES
        // decide is what the call asks IAM for: "if you set revealSecrets to true, you
        // must make sure that the IAM user that calls the TestState API has permission
        // for the states:RevealSecrets action ... without this permission, Step
        // Functions throws an access denied error" — the decision every call of this
        // service is taken behind, so it is taken once in front of this handler
        // (`crate::service::identity_authorization`) and never twice here.
        //
        // What it cannot be asked for is secrets of an invocation that was never made:
        // a MOCKED state's outcome is the request's own, so there is no HTTP request or
        // response of a connection's for the member to reveal anything of, and the two
        // members together are refused rather than one being ignored.
        if input.reveal_secrets && input.mock.is_some() {
            return Err(refuse(REVEAL_SECRETS_WITH_A_MOCK.to_string()));
        }

        // The modelled lengths (`definition` 1..1048576, `input`/`variables`/`context`
        // 0..262144, `stateName` 1..80, `roleArn` 1..256) and the `InspectionLevel`
        // enum are refused by the centralized walk before this handler runs; the level
        // is re-read here so a value outside the enum can never be taken for one.
        let level = input
            .inspection_level
            .clone()
            .unwrap_or_else(|| DEFAULT_INSPECTION_LEVEL.to_string());
        if !INSPECTION_LEVEL_VALUES.contains(&level.as_str()) {
            return Err(refuse(format!(
                "inspectionLevel must be one of [{}], got '{level}'",
                INSPECTION_LEVEL_VALUES.join(", ")
            )));
        }

        // "The Amazon Resource Name (ARN) of the execution role with the required IAM
        // permissions for the state": an ARN this operation models `InvalidArn` for,
        // judged by the same rule every role ARN of this service is.
        if let Some(role_arn) = input.role_arn.as_deref() {
            if let Some(reason) = crate::state::invalid_role_arn_reason(role_arn) {
                return Err(TestStateErrorModeled::InvalidArn(InvalidArn {
                    message: Some(reason),
                })
                .into());
            }
            // Naming that role HANDS this service a role to run the state as, which is
            // the caller's own `iam:PassRole`: a caller whose identity-based policies
            // do not let it pass the role is refused before the state is run. See
            // `crate::service::authorization`.
            if let Some(why) =
                crate::service::authorization::pass_role_denial(&*self.engine, ctx, role_arn)
            {
                return Err(crate::scaffolded::Scaffolded::access_denied(why));
            }
        }

        // "A string that contains the JSON input data for the state" — a state tested
        // with no input data is tested on the empty JSON object, which is what the
        // walk receives.
        let state_input = input.input.clone().unwrap_or_else(|| "{}".to_string());
        if let Err(error) = serde_json::from_str::<Value>(&state_input) {
            return Err(TestStateErrorModeled::InvalidExecutionInput(
                InvalidExecutionInput {
                    // The input is `@sensitive`, so the refusal about it quotes
                    // nothing of the document: it names where the parse stopped and
                    // the mark it left unmatched, with the source of each clause
                    // withheld, which is what this service is recorded answering for
                    // an input it could not read — see
                    // `crate::state::json_parse_diagnostic`.
                    message: Some(crate::state::resource_error_message(
                        crate::state::INVALID_STATE_MACHINE_EXECUTION_INPUT,
                        &crate::state::json_parse_diagnostic(&state_input, &error),
                    )),
                },
            )
            .into());
        }

        // "JSON object literal that sets variables used in the state under test.
        // Object keys are the variable names and values are the variable values." Each
        // way the value can fail to be one is refused in the service's own fixed
        // sentence for it, quoting nothing of the `@sensitive` document: text no JSON
        // parse reads ([`VARIABLES_NOT_JSON`]), a document that is not an object
        // ([`VARIABLES_NOT_AN_OBJECT`]), and an object whose KEY is not a variable name
        // — which names that key, the rule it broke being about the name itself.
        let variables = match input.variables.as_deref() {
            None => None,
            Some(text) => match serde_json::from_str::<Value>(text) {
                Ok(Value::Object(fields)) => {
                    if let Some(name) = fields.keys().find(|name| !asl::is_variable_name(name)) {
                        return Err(refuse(asl::invalid_variable_name_message(name)));
                    }
                    Some(Value::Object(fields))
                }
                Ok(_) => return Err(refuse(VARIABLES_NOT_AN_OBJECT.to_string())),
                Err(_) => return Err(refuse(VARIABLES_NOT_JSON.to_string())),
            },
        };

        // "A JSON string representing a valid Context object for the state under
        // test. This field may only be specified if a mock is specified in the same
        // request."
        let context_override = match (input.context.as_deref(), input.mock.as_ref()) {
            (None, _) => None,
            (Some(_), None) => {
                return Err(refuse(
                    "context may only be specified if a mock is specified in the same request"
                        .to_string(),
                ))
            }
            (Some(text), Some(_)) => match serde_json::from_str::<Value>(text) {
                Ok(value) if value.is_object() => Some(value),
                Ok(_) => {
                    return Err(refuse(
                        "context must be a JSON object: a Context object for the state under test"
                            .to_string(),
                    ))
                }
                Err(error) => {
                    return Err(refuse(format!(
                        "context must be a JSON string representing a valid Context object: {}",
                        crate::state::json_parse_diagnostic(text, &error)
                    )))
                }
            },
        };

        // The definition is JUDGED before it is read, and the first thing judged is
        // whether it is a document at all: this operation takes the definition of a
        // state rather than of a state machine, and it states THAT in its own words
        // — one fixed sentence about the state definition, carrying nothing of the
        // document it could not read ([`DEFINITION_NOT_JSON`]), where the operations
        // that take a state machine definition quote a parse diagnostic for it.
        let document = match serde_json::from_str::<Value>(&input.definition) {
            Ok(document) => document,
            Err(_) => return Err(invalid_definition_sentence(DEFINITION_NOT_JSON)),
        };

        // What is left is the SHAPE of the definition: with a `stateName` it is a
        // fully-formed state machine, refused in the words every state machine
        // definition of this service is refused in, and without one it "accepts the
        // definition of a single state", which is refused in ITS own terms — a state
        // object is not a state machine, so nothing about the refusal describes one.
        // The variables the REQUEST supplied are in scope for the state under test
        // ("variables set up as part of the test"), so the definition is judged with
        // their names already assigned: a read of one is resolved rather than reported
        // as a variable the definition defines nowhere.
        let given: ::std::collections::BTreeSet<String> = variables
            .as_ref()
            .and_then(Value::as_object)
            .map(|fields| fields.keys().cloned().collect())
            .unwrap_or_default();
        match input.state_name {
            Some(_) => asl::validate_with(
                &input.definition,
                crate::state::STATE_MACHINE_TYPE_STANDARD,
                given,
            )
            .map_err(invalid_definition),
            None => {
                asl::validate_single_state_with(&input.definition, given).map_err(
                    |about_the_state| {
                        TestStateErrorModeled::InvalidDefinition(InvalidDefinition {
                            message: Some(about_the_state),
                        })
                        .into()
                    },
                )
            }
        }?;

        // Which state is under test, and the name it carries.
        let (name, state) = match input.state_name.as_deref() {
            // "Denotes the particular state within a state machine definition to be
            // tested. If this field is specified, the definition must contain a
            // fully-formed state machine definition" — judged as one above, so the
            // state the request named only has to be one it declares.
            Some(state_name) => {
                let state = document
                    .get("States")
                    .and_then(Value::as_object)
                    .and_then(|states| states.get(state_name));
                let Some(state) = state else {
                    return Err(refuse(STATE_NOT_FOUND.to_string()));
                };
                (state_name, state)
            }
            // With no `stateName`, the definition IS the state: "accepts the
            // definition of a single state". Such a state is declared in no state
            // list, so it carries no name and its `Next` names no state that can be
            // resolved — it is reported as the state to transition to.
            None => ("", &document),
        };
        let Some(state) = state.as_object() else {
            // Unreachable: both walks above refuse a state that is not a JSON object.
            return Err(invalid_definition(format!(
                "{} must be a JSON object",
                asl::SINGLE_STATE_LABEL
            )));
        };
        let state_type = state.get("Type").and_then(Value::as_str).unwrap_or_default();

        // "The TestState API assumes an IAM role which must contain the required IAM
        // permissions for the resources your state is accessing": a `Task` state's own
        // work is an integration call, and that call is made AS the role the request
        // names — so the member is required for a state of that type, and for no other,
        // since no other state's work reaches a resource of another service.
        //
        // A MOCKED `Task` state is the exception: its outcome is the request's own, so
        // no call is made and there is nothing for a role to be assumed for.
        if state_type == TASK_STATE_TYPE && input.mock.is_none() && input.role_arn.is_none() {
            return Err(refuse(ROLE_ARN_FOR_A_TASK_STATE.to_string()));
        }

        // "Defines a mocked result or error for the state under test. A mock can only
        // be specified for Task, Map, or Parallel states. If it is specified for
        // another state type, an exception will be thrown."
        let mock = match input.mock.as_ref() {
            None => None,
            Some(mock) => {
                if !asl::INVOKING_STATE_TYPES.contains(&state_type) {
                    return Err(refuse(mock_unsupported_state_type(state_type)));
                }
                let read = read_mock(mock)?;
                // A mocked RESULT stands in for the answer of the integration the
                // state under test calls, so it is validated against that operation's
                // own result schema before the state is tested against it: a result
                // AWS refuses is no result to compute an answer from.
                if let asl::Mock::Result(result) = &read {
                    // A `Parallel` state's invocation is its branches, and what it
                    // produces is one element per branch: the mock stands in for THAT
                    // fan-out, so a result carrying another number of items is refused
                    // before the state is tested against it, whatever the items are.
                    if state_type == PARALLEL_STATE_TYPE
                        && mocked_branch_arity_violated(state, result)
                    {
                        return Err(refuse(MOCK_RESULT_PARALLEL_BRANCH_ARITY.to_string()));
                    }
                    if let Some(refusal) = mock_result_refusal(state, mock, result) {
                        return Err(refuse(refusal));
                    }
                }
                Some(read)
            }
        };
        // "TestState only supports the following when a mock is specified: Activity
        // tasks, .sync or .waitForTaskToken service integration patterns, Parallel, or
        // Map states." A `Map`'s iterations and a `Parallel`'s branches are the
        // state's own work, so without a mock standing in for their outcome those two
        // types are not among the ones the operation tests at all.
        if mock.is_none() && MOCK_ONLY_STATE_TYPES.contains(&state_type) {
            return Err(invalid_definition_sentence(MOCK_ONLY_STATE_TYPES_REFUSAL));
        }

        // "The number of retry attempts that have occurred for the state's Retry that
        // applies to the mocked error" — the range (0..) is modelled, so a negative
        // one never reaches here.
        let retries_taken = match input
            .state_configuration
            .as_ref()
            .and_then(|configuration| configuration.retrier_retry_count)
        {
            None => 0,
            Some(count) => match u64::try_from(count) {
                Ok(count) => count,
                Err(_) => {
                    return Err(refuse(
                        "stateConfiguration.retrierRetryCount must not be negative".to_string(),
                    ))
                }
            },
        };

        // "The number of Map state iterations that failed during the Map state
        // invocation". The modelled range (0..) is refused by the centralized walk
        // before this handler runs, so a negative figure never reaches here; one that
        // did would describe no invocation of any state, so it counts as no failed
        // iteration rather than as a figure of its own. What the count MEANS for the
        // state under test is decided by that state's own tolerated-failure threshold,
        // which only the walk that resolves the state's items can weigh it against.
        let map_iteration_failures = input
            .state_configuration
            .as_ref()
            .and_then(|configuration| configuration.map_iteration_failure_count)
            .and_then(|count| u64::try_from(count).ok());

        // "The name of the state from which an error originates when an error is
        // mocked for a Map or Parallel state": the state it names has to be one the
        // submitted definition declares, so a name no state of it carries is refused
        // rather than silently standing for no state at all.
        if let Some(named) = input
            .state_configuration
            .as_ref()
            .and_then(|configuration| configuration.error_caused_by_state.as_deref())
        {
            if !declares_state(&document, named, 0) {
                return Err(refuse(ERROR_CAUSED_BY_STATE_NOT_FOUND.to_string()));
            }
        }

        let start = crate::state::now();
        // What the context object (`$$`) reports: nothing but what this request fixed.
        // The test runs no execution and names no state machine, so there is no
        // execution id, name or state machine ARN for one to read — a request that
        // needs them supplies the whole context object itself, which is what `context`
        // is for.
        let context = asl::Context {
            execution_arn: String::new(),
            execution_name: String::new(),
            state_machine_arn: String::new(),
            state_machine_name: String::new(),
            role_arn: input.role_arn.clone().unwrap_or_default(),
            // The test runs no execution, so there is none that has been redriven.
            redrive_count: 0,
            // And none that belongs to a state machine, so there is no workflow type
            // to refuse a state under: `TestState` names a state rather than a machine.
            express: false,
        };

        // The walk is CPU work a caller's definition sizes, so it runs on a blocking
        // thread rather than on an async worker: a state whose evaluation spends the
        // work one interpretation may do (`asl::MAX_INTERPRET_WORK`) ends there instead
        // of holding a worker the runtime needs for health, timeouts and shutdown.
        // `interpret` is what runs it there AND serves the integration call a `Task`
        // state under test makes from this asynchronous call, exactly as it does for an
        // execution's walk.
        //
        // The calls are made as the role the request named — "the TestState API assumes
        // an IAM role which must contain the required IAM permissions for the resources
        // your state is accessing" — which this service assumes first: a role it cannot
        // assume fails the task rather than having its work done as nobody.
        let region = crate::state::request_region(ctx.parts());
        let role_arn = input.role_arn.clone().unwrap_or_default();
        let unassumable = crate::state::task_authorization::unassumable_role(
            ctx.callback(),
            &region,
            &role_arn,
            // The state under test belongs to no state machine, so the assume presents
            // none under the confused-deputy keys: there is no resource the credentials
            // are being taken on for.
            "",
        )
        .await;
        let acting = crate::state::task_authorization::acting(
            &self.engine,
            &region,
            &role_arn,
            unassumable,
            Some(ctx.credential_store()),
        );
        let interpreted = {
            let name = name.to_string();
            let state = state.clone();
            let state_input = state_input.clone();
            let mock = mock.clone();
            // The bytes the request wrote the mocked result in: a document the caller
            // supplied AS TEXT, so what reports or quotes it reports those bytes.
            let mock_result = input
                .mock
                .as_ref()
                .and_then(|mock| mock.result.clone());
            let variables = variables.clone();
            let definition_language = document.get("QueryLanguage").cloned();
            crate::state::integration::interpret(ctx, &region, acting, move |tasks| {
                asl::test_state(&asl::StateTest {
                    name: &name,
                    state: &state,
                    input: &state_input,
                    start,
                    context: &context,
                    context_override: context_override.as_ref(),
                    mock: mock.as_ref(),
                    mock_result: mock_result.as_deref(),
                    map_iteration_failures,
                    retries_taken,
                    variables: variables.as_ref(),
                    definition_language: definition_language.as_ref(),
                    tasks,
                })
            })
            .await
        };
        let Ok(trial) = interpreted else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::INTERPRETER_UNAVAILABLE,
            ));
        };
        let asl::Trial {
            status,
            output,
            next_state,
            error,
            cause,
            inspection,
            retry_index,
            retry_backoff_seconds,
            catch_index,
            refused,
        } = trial;
        // A member of the request the state under test is what judges — a
        // failed-iteration count describing more iterations than the state has — is a
        // defect of the REQUEST, so it is answered as this operation's own refusal
        // rather than as an outcome of the state.
        if let Some(refusal) = refused {
            return Err(refuse(refusal));
        }

        // `inspectionLevel` "determines the values to return when a state is tested",
        // and only the two data-flow levels report the processing stages. The HTTP
        // request and response `TRACE` adds are an HTTP Task's, which this emulator
        // does not call, so no state tested here has either.
        let inspection_data = DATA_FLOW_LEVELS.contains(&level.as_str()).then(|| {
            let error_details = (retry_index.is_some() || catch_index.is_some()).then_some(
                InspectionErrorDetails {
                    catch_index,
                    retry_index,
                    retry_backoff_interval_seconds: retry_backoff_seconds,
                },
            );
            InspectionData {
                input: inspection.input,
                after_input_path: inspection.after_input_path,
                after_parameters: inspection.after_parameters,
                after_arguments: inspection.after_arguments,
                result: inspection.result,
                after_result_selector: inspection.after_result_selector,
                after_result_path: inspection.after_result_path,
                // "JSON string that contains the set of workflow variables after
                // execution of the state. The set will include variables assigned in
                // the state and variables set up as test state input." The walk is
                // handed the request's own set and reports it back with whatever the
                // state's `Assign` wrote into it; a state that assigned none, tested
                // without a set of its own, has none to report.
                variables: inspection
                    .variables
                    .or_else(|| variables.as_ref().map(Value::to_string)),
                error_details,
                // The stages and bounds only a `Map` state has: what its `ItemsPath`
                // selected, the input each of its iterations is handed after its
                // `ItemSelector`, the batches its `ItemBatcher` grouped them into, and
                // the concurrency and failure thresholds it declared. Every one of them
                // is absent for a state of any other type, which has no such stage.
                after_items_path: inspection.after_items_path,
                after_item_selector: inspection.after_item_selector,
                after_item_batcher: inspection.after_item_batcher,
                max_concurrency: inspection.max_concurrency,
                tolerated_failure_count: inspection.tolerated_failure_count,
                tolerated_failure_percentage: inspection.tolerated_failure_percentage,
                ..InspectionData::default()
            }
        });

        Ok(TestStateOutput {
            output,
            error,
            cause,
            inspection_data,
            next_state,
            status: Some(status.to_string()),
        })
    }
}
