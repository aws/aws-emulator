impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RedriveExecution<Eng>
{
    type Input = RedriveExecutionInput;
    type Output = RedriveExecutionOutput;
    type Error = RedriveExecutionError;

    const NAME: &'static str = "RedriveExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REDRIVE_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REDRIVE_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `executionArn` (1..256) and `clientToken` (1..64, `^[!-~]+$`) are modelled,
        // so the centralized walk has already refused anything outside them.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::STORE_UNAVAILABLE,
            ));
        };

        // The ARN is validated BEFORE the lookup: a malformed ARN, an ARN of another
        // service and an ARN of another region are defects in the REQUEST, which
        // `InvalidArn` reports, not an execution that is absent here.
        let endpoint_region = crate::state::request_region(ctx.parts());
        if let Err(message) =
            crate::state::read_execution_arn(&input.execution_arn, &endpoint_region)
        {
            return Err(RedriveExecutionErrorModeled::InvalidArn(InvalidArn {
                message: Some(message),
            })
            .into());
        }

        let now = crate::state::now();

        // Phase 1, under the lock: resolve the execution, refuse what cannot be
        // redriven, and read what the re-run needs. The lock is released before the
        // walk, so no other request waits on an interpretation.
        let (definition, execution_input, previous_event_id, machine_arn, context, redrive_step) = {
            let mut store = state.lock();
            // Settle first: an execution whose terminal status the clock already owed
            // is terminal when this call decides whether it can be redriven.
            store.settle(now);

            let Some(execution) = store.executions.get(&input.execution_arn) else {
                return Err(RedriveExecutionErrorModeled::ExecutionDoesNotExist(
                    ExecutionDoesNotExist {
                        message: Some(crate::state::resource_error_message(
                            crate::state::EXECUTION_DOES_NOT_EXIST,
                            &input.execution_arn,
                        )),
                    },
                )
                .into());
            };

            // "The API will return idempotent responses for the last 10 client tokens
            // used to successfully redrive the execution": a repeat of a remembered,
            // unexpired token answers the `redriveDate` it answered the first time and
            // redrives nothing a second time.
            if let Some(redrive_date) = input
                .client_token
                .as_deref()
                .and_then(|token| execution.redrive_for_token(token, now))
            {
                return Ok(RedriveExecutionOutput {
                    redrive_date: crate::state::to_date_time(redrive_date),
                });
            }

            let machine = store.state_machines.get(&execution.state_machine_arn);
            // "This API action is not supported by EXPRESS state machines": an
            // execution of an Express workflow is one this action is not for, which is
            // a defect in the REQUEST rather than an execution that cannot be
            // redriven. It is refused by the RESOURCE TYPE an Express execution
            // carries ([`crate::state::EXPRESS_EXECUTION_RESOURCE`]) — the one refusal
            // every reader of an ARN this service does not serve answers with, worded
            // the same way whichever operation read it.
            if machine
                .is_some_and(|machine| machine.sm_type == crate::state::STATE_MACHINE_TYPE_EXPRESS)
            {
                return Err(RedriveExecutionErrorModeled::InvalidArn(InvalidArn {
                    message: Some(crate::state::resource_type_not_valid_message(
                        crate::state::EXPRESS_EXECUTION_RESOURCE,
                    )),
                })
                .into());
            }

            // The ONE predicate `DescribeExecution`'s `redriveStatus` is projected
            // from, so an execution this refuses is exactly one that reports
            // `NOT_REDRIVABLE`, with this reason — stated here with the execution
            // the request named, so the refusal says which execution it is about.
            if let Some(reason) = store.not_redrivable_reason(execution, now) {
                return Err(RedriveExecutionErrorModeled::ExecutionNotRedrivable(
                    ExecutionNotRedrivable {
                        message: Some(crate::state::not_redrivable_message(
                            &input.execution_arn,
                            reason,
                        )),
                    },
                )
                .into());
            }

            // A state machine the store no longer holds is already refused above (it
            // is past the end of its own deletion), so the definition is here.
            let Some(machine) = machine else {
                return Err(RedriveExecutionErrorModeled::ExecutionNotRedrivable(
                    ExecutionNotRedrivable {
                        message: Some(crate::state::not_redrivable_message(
                            &input.execution_arn,
                            crate::state::NOT_REDRIVABLE_DELETING,
                        )),
                    },
                )
                .into());
            };
            // The context object (`$$`) the re-run reads is the SAME execution's
            // identity: a redrive continues this execution rather than starting a
            // new one, so `$$.Execution.Id` and `$$.Execution.Name` do not change.
            let context = crate::state::asl::Context {
                execution_arn: execution.arn.clone(),
                execution_name: execution.name.clone(),
                state_machine_arn: machine.arn.clone(),
                state_machine_name: machine.name.clone(),
                // The role this execution runs under is the one it started with, for
                // the same reason the definition below is.
                role_arn: execution.ran.role_arn.clone(),
                // This call begins the NEXT attempt, so the states it runs read the
                // count this redrive takes the record to — the same one
                // `DescribeExecution` projects once it is recorded below.
                redrive_count: execution.redrive_count.saturating_add(1),
                // The workflow type the re-run is interpreted under, which decides
                // whether a `Task` state may ask for the run-a-job (`.sync`) pattern.
                express: machine.sm_type == crate::state::STATE_MACHINE_TYPE_EXPRESS,
            };
            // "Redriven executions use the same state machine definition [...] as the
            // original execution attempt": the configuration the record was started
            // with, which is not what the state machine — or the version it was
            // published from — may hold by now.
            let definition = execution.ran.definition.clone();
            (
                definition,
                execution.input.clone(),
                execution.last_event_id(),
                machine.arn.clone(),
                context,
                execution.redrive_step.clone(),
            )
        };

        // Phase 2, OUTSIDE the lock: the re-run is INTERPRETED here — "when you
        // redrive an execution, it continues the failed execution from the unsuccessful
        // step and uses the same input. Step Functions preserves the results and
        // execution history of the successful steps, and doesn't rerun these steps" — so
        // the walk begins at the step the last attempt stopped at, with the data that
        // step saw, and the steps before it are not run a second time. That step's own
        // work IS done again: a `Task` state there makes its service-integration call,
        // which is what a redrive of a workflow that calls another service does. The
        // outcome is owed to the clock, so the execution reports
        // `RUNNING` until then.
        let interpreted = {
            let definition = definition.clone();
            let execution_input = execution_input.clone();
            // The re-run's integration calls go out in the state machine's own
            // Region, exactly as the first attempt's did.
            let region = crate::state::arn_region(&context.state_machine_arn);
            // And they are made as the SAME execution role the first attempt ran as,
            // which is the one the record was started with — assumed again for this
            // attempt, so a role that can no longer be assumed fails the task.
            let unassumable = crate::state::task_authorization::unassumable_role(
                ctx.callback(),
                &region,
                &context.role_arn,
                &context.state_machine_arn,
            )
            .await;
            let acting = crate::state::task_authorization::acting(
                &self.engine,
                &region,
                &context.role_arn,
                &context.state_machine_name,
                unassumable,
            );
            // This attempt CONTINUES the execution, so each Distributed Map state it
            // re-enters is the Map Run that execution already has: it keeps that ARN,
            // and the items whose child workflow execution already succeeded are not
            // run again — "Step Functions preserves the results and execution history
            // of the successful steps, and doesn't rerun these steps when you redrive
            // an execution".
            let acting = crate::state::task_authorization::Acting {
                map_runs: crate::state::map_runs::resumed(&self.engine, &input.execution_arn),
                ..acting
            };
            crate::state::integration::interpret(ctx, &region, acting, move |tasks| {
                crate::state::plan_redrive(
                    &crate::state::RunAttempt {
                        definition: &definition,
                        input: &execution_input,
                        start: now,
                        context: &context,
                        opening: crate::state::EVENT_EXECUTION_REDRIVEN,
                        previous_event_id,
                    },
                    redrive_step.as_ref(),
                    tasks,
                )
            })
            .await
        };
        let Ok(planned) = interpreted else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::INTERPRETER_UNAVAILABLE,
            ));
        };
        // A job the re-run STARTED and then abandoned is stopped through its own
        // integration, as a start's own is: no job is left running behind a task that
        // will never finish. Done with no store of this service locked.
        crate::state::integration::stop_abandoned(
            ctx.callback(),
            &crate::state::arn_region(&machine_arn),
            &planned.abandoned,
            planned.abandoned_stop_at(),
        )
        .await;

        // Phase 3, under the lock again: record it. Every check is re-made, because
        // the execution could have been redriven or its state machine deleted while
        // the walk ran. The lock is held for THIS block alone, because the publication
        // below must not hold the store while it is in flight; the block answers the
        // `redriveDate` the redrive reached and whether the re-run parked at a job.
        let (redrive_date, watching) = {
            let mut store = state.lock();
            store.settle(now);
            let Some(execution) = store.executions.get(&input.execution_arn) else {
                return Err(RedriveExecutionErrorModeled::ExecutionDoesNotExist(
                    ExecutionDoesNotExist {
                        message: Some(crate::state::resource_error_message(
                            crate::state::EXECUTION_DOES_NOT_EXIST,
                            &input.execution_arn,
                        )),
                    },
                )
                .into());
            };
            if let Some(redrive_date) = input
                .client_token
                .as_deref()
                .and_then(|token| execution.redrive_for_token(token, now))
            {
                return Ok(RedriveExecutionOutput {
                    redrive_date: crate::state::to_date_time(redrive_date),
                });
            }
            if let Some(reason) = store.not_redrivable_reason(execution, now) {
                return Err(RedriveExecutionErrorModeled::ExecutionNotRedrivable(
                    ExecutionNotRedrivable {
                        message: Some(crate::state::not_redrivable_message(
                            &input.execution_arn,
                            reason,
                        )),
                    },
                )
                .into());
            }

            let waiting = planned.waiting;
            let parked = planned.parked;
            let task_bytes = waiting
                .as_ref()
                .map_or(0, crate::state::PlannedActivityTask::measure)
                + parked.as_ref().map_or(0, crate::state::PlannedJob::measure);
            let map_runs = planned.map_runs;
            let map_run_bytes = crate::state::planned_map_run_bytes(&map_runs);
            let redriven = store.redrive_execution(
                &input.execution_arn,
                now,
                input.client_token.as_deref(),
                crate::state::RedrivenAttempt {
                    opening: planned.opening,
                    pending: planned.pending,
                    extra_bytes: task_bytes + map_run_bytes,
                    // The unsuccessful step THIS attempt stopped at, which the next
                    // redrive continues from.
                    stopped_at: planned.stopped_at,
                },
            );
            match redriven {
                Ok(redrive_date) => {
                    // The re-run reached an activity task: it is queued for a worker to
                    // claim exactly as a first attempt's is.
                    if let Some(waiting) = waiting {
                        store.schedule_activity_task(&input.execution_arn, waiting);
                    }
                    // The re-run re-entered this execution's Distributed Map states, so
                    // each one's Map Run runs again: the record it already has moves,
                    // keeping the ARN a client may be holding.
                    store.record_map_runs(&input.execution_arn, &machine_arn, map_runs);
                    // The re-run started a run-a-job task's job again and PARKED at it,
                    // which is polled to its end exactly as a first attempt's is.
                    let watching = parked.is_some();
                    if let Some(parked) = parked {
                        let region = crate::state::arn_region(&machine_arn);
                        store.park_job(&input.execution_arn, parked, &region);
                    }
                    (redrive_date, watching)
                }
                Err(crate::state::RedriveRejection::NotFound) => {
                    return Err(RedriveExecutionErrorModeled::ExecutionDoesNotExist(
                        ExecutionDoesNotExist {
                            message: Some(crate::state::resource_error_message(
                                crate::state::EXECUTION_DOES_NOT_EXIST,
                                &input.execution_arn,
                            )),
                        },
                    )
                    .into())
                }
                // The re-run's own history and outcome are what this record would grow
                // by, so a redrive the store has no room for is refused rather than
                // retained past its ceiling.
                Err(crate::state::RedriveRejection::NoRoom) => {
                    return Err(RedriveExecutionErrorModeled::ExecutionLimitExceeded(
                        ExecutionLimitExceeded {
                            message: Some(format!(
                                "redriving execution {} would take the store past the {} bytes \
                                 this emulator retains",
                                input.execution_arn,
                                crate::state::MAX_STORE_BYTES
                            )),
                        },
                    )
                    .into())
                }
            }
        };
        if watching {
            crate::state::run_a_job::watch(
                std::sync::Arc::clone(&self.engine),
                ctx.callback().clone(),
                crate::state::integration::chain_depth(ctx),
                input.execution_arn.clone(),
            );
        }
        // The redrive moved the execution back into `RUNNING`, carrying the redrive
        // accounting this attempt reached: that status change is published onto the
        // account's default event bus, and the clock this starts publishes the re-run's
        // own terminal status when it falls due.
        crate::state::events::publish(&self.engine, ctx.callback()).await;
        Ok(RedriveExecutionOutput {
            redrive_date: crate::state::to_date_time(redrive_date),
        })
    }
}
