        // name the assume gave it
        // (`task_authorization::new_session_name`), which is the principal a refusal of
        // one of them reports.
        let acting = crate::state::task_authorization::acting(
            &self.engine,
            &region,
            &role_arn,
            unassumable,
        );
        let interpreted = {
            let definition = definition.clone();
            let execution_input = execution_input.clone();
            crate::state::integration::interpret(ctx, &region, acting, move |tasks| {
                crate::state::plan_run_settling_after(
                    &crate::state::RunAttempt {
                        definition: &definition,
                        input: &execution_input,
                        start: started,
                        context: &context,
                        opening: crate::state::EVENT_EXECUTION_STARTED,
                        previous_event_id: 0,
                    },
                    std::time::Duration::ZERO,
                    tasks,
                )
            })
            .await
        };
        let Ok(planned) = interpreted else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::INTERPRETER_UNAVAILABLE,
            ));
        };
        let mut history = planned.opening;
        // A SYNCHRONOUS execution answers its own outcome in this call, so there is
        // nowhere for it to WAIT: a definition whose walk reached an activity task
        // needs a worker to poll for that task and answer it, which cannot happen
        // inside the call that would have to report the result. The run therefore ends
        // in the service's own failure state, with the language's runtime error naming
        // what was not run — nothing is reported as though a worker had answered. A
        // run-a-job (`.sync`) integration needs no such wording here: this workflow
        // type does not serve that pattern at all, so the walk fails AT the state that
        // asked for it ([`crate::state::asl::EXPRESS_RUN_A_JOB_UNSUPPORTED`]) and
        // parks at nothing.
        let unwaitable = "a synchronous execution cannot wait for an activity worker's reply, so \
                          the activity task this definition schedules was not run";
        let outcome = match planned.pending {
            Some(outcome) => outcome,
            None => {
                let previous = history.last();
                let previous_event_id = previous
                    .map_or(crate::state::NO_PREVIOUS_EVENT, |event| {
                        crate::state::follows_event(event.id, &event.event_type)
                    });
                let id = previous.map_or(0, |event| event.id) + 1;
                crate::state::PendingOutcome {
                    due_at: started,
                    status: crate::state::EXECUTION_STATUS_FAILED.to_string(),
                    output: None,
                    error: Some(crate::state::asl::RUNTIME_ERROR.to_string()),
                    cause: Some(unwaitable.to_string()),
                    events: vec![crate::state::HistoryEvent {
                        id,
                        previous_event_id,
                        event_type: crate::state::EVENT_EXECUTION_FAILED.to_string(),
                        timestamp: started,
                        state_name: None,
                        details: crate::state::EventDetails::default(),
                    }],
                }
            }
        };

