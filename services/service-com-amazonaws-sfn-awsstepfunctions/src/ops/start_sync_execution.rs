        // the definition's own `Wait` states declare, which the walk accumulates
        // instead of sleeping for them (`outcome.due_at`).
        let stopped = std::cmp::max(crate::state::now(), outcome.due_at);
        history.extend(outcome.events);

        let executed = crate::state::Execution {
            arn: arn.clone(),
            state_machine_arn: machine_arn.clone(),
            name: execution_name,
            // A synchronous execution is already terminal when this call answers, so
            // its status is the one the walk computed: `SUCCEEDED`, `FAILED` or
            // `TIMED_OUT`, the three the modelled `SyncExecutionStatus` carries.
            status: outcome.status,
            start_date: started,
            stop_date: Some(stopped),
            input: execution_input,
            output: outcome.output,
            error: outcome.error,
            cause: outcome.cause,
            trace_header: crate::state::effective_trace_header(ctx.parts(), input.trace_header),
            // The alias and version this run was started through, recorded exactly as
            // `StartExecution` records them; this response declares no member for
            // either, so they are what the stored record attributes the run by.
            state_machine_version_arn: version_arn.clone(),
            state_machine_alias_arn: alias_arn.clone(),
            ran: std::sync::Arc::new(configuration),
            redrive_count: 0,
            redrive_date: None,
            redrive_tokens: Vec::new(),
            history,
            // Nothing is owed to the clock: see above.
            pending: None,
            // "This API action is not supported by EXPRESS state machines", so no
            // redrive continues this run from any step of it.
            redrive_step: None,
            // A synchronous start begins an execution of its own, not a child of a
            // Map Run.
            map_run_arn: None,
            item_count: None,
            // Measured and counted by `insert_execution`.
            retained_bytes: 0,
            // "This API action is not supported by EXPRESS state machines" either, so
            // no read of this run's history hands a page cursor out.
            issued_page_cursors: Vec::new(),
            // The run's history arrives complete, and is counted into the series its
            // tasks publish as the record is stored.
            observed_events: 0,
        };

