impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateGraphqlApi<Eng>
{
    type Input = CreateGraphqlApiInput;
    type Output = CreateGraphqlApiOutput;
    type Error = CreateGraphqlApiError;

    const NAME: &'static str = "CreateGraphqlApi";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_GRAPHQL_API_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_GRAPHQL_API_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CreateGraphqlApiErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: Some("the appsync store is unavailable on this engine".to_string()),
                },
            )
            .into());
        };

        // The configuration this API is to be created with has to be well formed:
        // an authentication type that is configured through a member of its own
        // needs that member, no authentication type may be named twice, an OIDC
        // issuer has to be an absolute URL and `ownerContact` has to fit its
        // documented length. `UpdateGraphqlApi` carries the same members and is
        // refused on the same grounds, so the rules live in
        // [`crate::state::graphql_api_config_refusal`].
        if let Some(message) = crate::state::graphql_api_config_refusal(
            &input.authentication_type,
            input.open_id_connect_config.as_ref(),
            input.user_pool_config.is_some(),
            input.lambda_authorizer_config.is_some(),
            input
                .additional_authentication_providers
                .as_deref()
                .unwrap_or_default(),
            input.owner_contact.as_deref(),
        ) {
            return Err(CreateGraphqlApiErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
                ..Default::default()
            })
            .into());
        }

        let region = crate::state::request_region(ctx);

        // Minting the API's identifiers is all the store is held for here, in a block of
        // its own, so the guard is out of scope before the socket below is opened: opening
        // one is the core's work and is awaited, and no state guard may be held across an
        // await.
        let api_id = {
            let mut guard = state.lock();

            // The store is bounded, so a repeated create cannot grow it without limit:
            // AppSync's quota is 25 GraphQL APIs per account per Region, and
            // `ApiLimitExceededException` ("The GraphQL API exceeded a limit") is the
            // modelled refusal for a create past it. This emulator serves one Region's
            // worth of state, so the cap applies to the whole store.
            if guard.graphql_apis.len() >= APIS_PER_REGION {
                return Err(CreateGraphqlApiErrorModeled::ApiLimitExceededException(
                    ApiLimitExceededException {
                        message: Some(format!(
                            "an account may hold at most {APIS_PER_REGION} GraphQL APIs in a Region"
                        )),
                    },
                )
                .into());
            }

            // Mint an id that is not already taken. The id is drawn from the state's own
            // counter, so it is new on every call even for an identical request.
            let mut api_id = guard.mint_id();
            while guard.graphql_apis.contains_key(&api_id) {
                api_id = guard.mint_id();
            }
            api_id
        };

        // Both of the API's endpoints are a DATA plane — a client POSTs GraphQL documents
        // to one and a subscriber exchanges frames over the other — and the core owns the
        // sockets they are served on ([`crate::service::graphql_api`]): they are opened for
        // the id just minted, and the addresses they landed on are what this API publishes
        // as its `GRAPHQL` and `REALTIME` endpoints, so the values a caller hands a GraphQL
        // or WebSocket client are addresses that client can reach. A socket that could not
        // be opened leaves the API UNCREATED rather than publishing an endpoint nothing
        // serves.
        let (graphql_authority, realtime_authority) =
            match crate::service::graphql_api::open_for_api(&self.engine, &api_id).await {
                Ok(authorities) => authorities,
                Err(reason) => {
                    state.lock().graphql_data_plane.forget_api(&api_id);
                    return Err(CreateGraphqlApiErrorModeled::InternalFailureException(
                        InternalFailureException {
                            message: Some(format!(
                                "this emulator could not open the sockets a GraphQL API's \
                                 endpoints are served on, so no API was created: {reason}"
                            )),
                        },
                    )
                    .into());
                }
            };

        let mut guard = state.lock();
        // The quota is weighed AGAIN under this lock, because the one above was released
        // while the socket was opened: two creates in flight at once must not both pass a
        // check made before either inserted, or the account would come to hold more APIs
        // than the limit the modelled refusal names. The socket this request opened is
        // forgotten with the refusal, so nothing stays listening for an API that was not
        // created.
        if guard.graphql_apis.len() >= APIS_PER_REGION {
            guard.graphql_data_plane.forget_api(&api_id);
            return Err(CreateGraphqlApiErrorModeled::ApiLimitExceededException(
                ApiLimitExceededException {
                    message: Some(format!(
                        "an account may hold at most {APIS_PER_REGION} GraphQL APIs in a Region"
                    )),
                },
            )
            .into());
        }
        let seq = guard.next_seq();

        let record = crate::state::GraphqlApiRecord {
            seq,
            arn: ::engine::emulator_arn(
                ARN_SERVICE,
                &region,
                &crate::state::api_resource(&api_id),
            ),
            // The endpoint records are the addresses the API's two endpoints are SERVED
            // on (`crate::state::api_dns`), which `uris` is derived from.
            dns: crate::state::api_dns(&graphql_authority, &realtime_authority),
            api_id: api_id.clone(),
            name: input.name,
            authentication_type: input.authentication_type,
            // The model documents the value each of these three takes when the
            // request omits it.
            api_type: input
                .api_type
                .unwrap_or_else(|| DEFAULT_API_TYPE.to_string()),
            visibility: input
                .visibility
                .unwrap_or_else(|| DEFAULT_VISIBILITY.to_string()),
            introspection_config: input
                .introspection_config
                .unwrap_or_else(|| DEFAULT_INTROSPECTION_CONFIG.to_string()),
            owner: ::engine::emulator_account_id().to_string(),
            owner_contact: input.owner_contact,
            xray_enabled: input.xray_enabled,
            query_depth_limit: input.query_depth_limit,
            resolver_count_limit: input.resolver_count_limit,
            merged_api_execution_role_arn: input.merged_api_execution_role_arn,
            log_config: input.log_config,
            user_pool_config: input.user_pool_config,
            open_id_connect_config: input.open_id_connect_config,
            lambda_authorizer_config: input.lambda_authorizer_config,
            additional_authentication_providers: input
                .additional_authentication_providers
                .unwrap_or_default(),
            enhanced_metrics_config: input.enhanced_metrics_config,
            tags: input.tags.unwrap_or_default().into_iter().collect(),
            // The create call carries no environmental variables: they are written by
            // `PutGraphqlApiEnvironmentVariables`, so a fresh API holds none.
            environment_variables: std::collections::BTreeMap::new(),
            created_at: std::time::SystemTime::now(),
            api_keys: std::collections::BTreeMap::new(),
            // A fresh API holds no cache, no data source, no function, no type and no
            // resolver: `CreateApiCache`, `CreateDataSource`, `CreateFunction`,
            // `CreateType` and `CreateResolver` are what create them. Nothing has torn
            // a cache of it down either.
            api_cache: None,
            api_cache_deleted: false,
            data_sources: std::collections::BTreeMap::new(),
            functions: std::collections::BTreeMap::new(),
            types: std::collections::BTreeMap::new(),
            resolvers: std::collections::BTreeMap::new(),
            // No schema creation has run for a fresh API either:
            // `StartSchemaCreation` is what schedules one, and a fresh API holds no
            // schema document because no creation of it has succeeded.
            schema: None,
            schema_document: None,
        };

        guard.graphql_apis.insert(api_id.clone(), record);

        // Answer from the STORED record, so this body is the one `GetGraphqlApi` and
        // `ListGraphqlApis` answer with later.
        let graphql_api = guard
            .graphql_apis
            .get(&api_id)
            .map(crate::state::GraphqlApiRecord::to_graphql_api);

        Ok(CreateGraphqlApiOutput { graphql_api })
    }
}

