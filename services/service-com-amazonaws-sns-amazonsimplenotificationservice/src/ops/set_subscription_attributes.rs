        if let Some(message) = state::subscription_required_attribute_refusal(
            &subscription.protocol,
            &would_hold,
            state::AttributeMember::Named,
        ) {
            return Err(invalid_parameter(message));
        }

        // "The new value for the attribute" (`AttributeValue` doc) — and a request that
        // carries none clears the attribute, so the subscription reports what SNS
        // reports for one that was never given it.
        match stored {
            Some(value) => {
                subscription.attributes.insert(input.attribute_name.clone(), value);
            }
            None => {
                subscription.attributes.remove(&input.attribute_name);
            }
        }

