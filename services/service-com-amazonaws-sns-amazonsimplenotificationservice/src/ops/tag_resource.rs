impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Argument validation, BEFORE the store is consulted: a `ResourceArn` that is
        // not a topic ARN of this endpoint's own region is bad input, not a topic that
        // does not exist.
        let region = state::request_region(ctx.parts());
        if let Some(message) =
            state::tagged_topic_arn_refusal(RESOURCE_ARN_MEMBER, &input.resource_arn, &region)
        {
            return Err(TagResourceErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }

        // Authorization, before the store is consulted: AWS decides whether the caller may
        // perform the action on the topic the request addresses ahead of the service
        // resolving it, so a refused call writes no tag and reports nothing about what the
        // account holds.
        if let Some(message) = state::authorization::topic_refusal(
            &*self.engine,
            ctx,
            state::authorization::TAG_RESOURCE,
            &input.resource_arn,
        ) {
            return Err(TagResourceErrorModeled::AuthorizationErrorException(
                AuthorizationErrorException {
                    message: Some(message),
                },
            )
            .into());
        }

        let Some(store) = state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalErrorException(
                InternalErrorException {
                    message: Some("the SNS store is unavailable".to_string()),
                },
            )
            .into());
        };
        let mut store = store.lock();

        let Some(topic) = store.topics.get(&input.resource_arn) else {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(state::RESOURCE_DOES_NOT_EXIST.to_string()),
                },
            )
            .into());
        };

        // A caller's own tag may not be written in the namespace Amazon Web Services
        // keeps for its own tags, under the rule every write of a topic's tags shares.
        if let Some(message) = state::reserved_tag_key_refusal(
            TAGS_MEMBER,
            input.tags.iter().map(|tag| tag.key.as_str()),
            state::tag_key_origin(ctx),
        ) {
            return Err(TagResourceErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }

        // The map the write WOULD leave the topic holding: "a new tag with a key
        // identical to that of an existing tag overwrites the existing tag", so a key
        // the topic already holds takes the new value instead of being added beside it.
        // It is built and measured BEFORE anything is stored, so a refused write leaves
        // the topic exactly as it was.
        let mut would_hold = topic.tags.clone();
        for tag in &input.tags {
            would_hold.insert(tag.key.clone(), tag.value.clone());
        }
        match state::tag_map_refusal(&would_hold) {
            Some(TagRefusal::TooMany(message)) => {
                return Err(TagResourceErrorModeled::TagLimitExceededException(
                    TagLimitExceededException {
                        message: Some(message),
                    },
                )
                .into())
            }
            Some(TagRefusal::TooLarge(message)) => {
                return Err(TagResourceErrorModeled::InvalidParameterException(
                    InvalidParameterException {
                        message: Some(message),
                    },
                )
                .into())
            }
            None => {}
        }

        store
            .topics
            .get_mut(&input.resource_arn)
            .expect("the topic was just found under this ARN")
            .tags = would_hold;

        // TagResource answers an empty document: the tag set it wrote is read back
        // through `ListTagsForResource`, not echoed here.
        Ok(TagResourceOutput {})
    }
}
