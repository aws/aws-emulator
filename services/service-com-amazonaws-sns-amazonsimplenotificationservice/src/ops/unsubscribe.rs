impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for Unsubscribe<Eng>
{
    type Input = UnsubscribeInput;
    type Output = UnsubscribeOutput;
    type Error = UnsubscribeError;

    const NAME: &'static str = "Unsubscribe";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNSUBSCRIBE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = UNSUBSCRIBE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Authorization, ahead of the store: AWS decides whether the caller may perform the
        // action on the subscription's topic before the service resolves the subscription, so
        // a refused call deletes nothing and is told it is not authorized rather than told
        // whether the subscription exists. A value that names no subscription at all is left
        // to the argument validation below.
        if let Some(message) = crate::state::authorization::subscription_refusal(
            &*self.engine,
            ctx,
            crate::state::authorization::UNSUBSCRIBE,
            &input.subscription_arn,
        ) {
            return Err(UnsubscribeErrorModeled::AuthorizationErrorException(
                AuthorizationErrorException {
                    message: Some(message),
                },
            )
            .into());
        }
        let Some(store) = crate::state::service_state(&*self.engine) else {
            return Err(UnsubscribeErrorModeled::InternalErrorException(
                InternalErrorException {
                    message: Some("the SNS store is unavailable".to_string()),
                },
            )
            .into());
        };
        let mut store = store.lock();

        // The sentinel SNS publishes in place of an unconfirmed subscription's ARN is
        // not an ARN: a caller that read it out of a `Subscribe` or a listing response
        // and handed it back has named a subscription that is still awaiting
        // confirmation, so that is what the refusal says.
        if crate::state::is_pending_confirmation_sentinel(&input.subscription_arn) {
            return Err(pending_confirmation_refusal());
        }

        // A `SubscriptionArn` that is not a subscription ARN fails argument validation
        // BEFORE any lookup, so garbage is refused as bad input rather than reported as
        // a subscription that is merely absent.
        if let Some(message) =
            state::subscription_arn_refusal("SubscriptionArn", &input.subscription_arn)
        {
            return Err(UnsubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }

        // A subscription belongs to the region of the topic it extends, which its own
        // ARN carries: one naming another region names nothing this endpoint serves, so
        // the delete is refused rather than silently answered as the idempotent one.
        let region = state::request_region(ctx.parts());
        if let Some(message) =
            state::foreign_region_refusal("SubscriptionArn", &input.subscription_arn, &region)
        {
            return Err(UnsubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }

        // A subscription still awaiting confirmation cannot be deleted through the API:
        // SNS refuses the call and leaves the subscription in place, so a caller that
        // holds its ARN (from `ReturnSubscriptionArn`) still has to wait for the
        // subscriber to confirm.
        if store
            .subscriptions
            .get(&input.subscription_arn)
            .is_some_and(|held| held.pending_confirmation)
        {
            return Err(pending_confirmation_refusal());
        }

        // Deleting a subscription is IDEMPOTENT in its ARN: a well-formed ARN whose
        // subscription is already gone — a repeated teardown, or one whose topic was
        // deleted with its subscriptions — leaves nothing to do and is answered the
        // same way as the delete that did the work.
        let Some(removed) = store.subscriptions.remove(&input.subscription_arn) else {
            return Ok(UnsubscribeOutput);
        };
        // The messages delivered to a subscription go with it, but the topic keeps
        // counting the deletion: that is its `SubscriptionsDeleted` attribute, which the
        // topic takes up once the count settles rather than as part of this call
        // ([`state::SUBSCRIPTION_DELETION_SETTLES_AFTER`]).
        store.forget_deliveries(&input.subscription_arn);
        if let Some(topic) = store.topics.get_mut(&removed.topic_arn) {
            topic.count_deleted_subscription();
        }

        Ok(UnsubscribeOutput)
    }
}
