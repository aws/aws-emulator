impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RecognizeText<Eng>
{
    type Input = RecognizeTextInput;
    type Output = RecognizeTextOutput;
    type Error = RecognizeTextError;

    const NAME: &'static str = "RecognizeText";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RECOGNIZE_TEXT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RECOGNIZE_TEXT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            RecognizeTextErrorModeled::InternalServerException(InternalServerException {
                message: "the Lex V2 runtime session store is unavailable".to_string(),
            })
        })?;

        // What the utterance is interpreted against: the bot locale the alias
        // this request addresses points at, which the client built through the
        // Lex Models V2 control plane. The PAIR is resolved, not the two ids
        // separately, and resolution happens BEFORE the session store is
        // touched, so a turn addressed to an alias that bot does not have, or to
        // a locale with no built model, is refused without starting a
        // conversation.
        let model: BotLocaleModel = built_locale(
            &*self.engine,
            &input.bot_id,
            &input.bot_alias_id,
            &input.locale_id,
        )
        .map_err(|error| locale_unavailable(error, &input.bot_id, &input.bot_alias_id))?;

        let now = SystemTime::now();
        let key = SessionKey::new(
            &input.bot_id,
            &input.bot_alias_id,
            &input.locale_id,
            &input.session_id,
        );

        // One turn of the conversation, which is the whole of what this
        // operation does: `text` is the input it processes, and the dialog state
        // and request attributes it carried are folded into the stored session.
        // The sibling `RecognizeUtterance` takes the same turn from a request
        // payload, so the turn itself lives in `crate::state` and neither
        // operation holds a second copy of it.
        let turn = crate::state::take_turn(
            &state,
            key,
            now,
            &input.text,
            &model,
            input.session_state,
            input.request_attributes,
        )
        .map_err(turn_refused)?;

        Ok(RecognizeTextOutput {
            messages: Some(turn.messages),
            session_state: Some(turn.session_state),
            interpretations: Some(turn.interpretations),
            // "The attributes sent in the request" (`requestAttributes`), as the
            // session has accumulated them: the map is reported on every turn,
            // empty for a conversation nothing has sent an attribute on, so a
            // client threading attributes across turns can read it without
            // first testing whether the member is there.
            request_attributes: Some(turn.request_attributes),
            session_id: Some(turn.session_id),
            // A bot member is recognized only for a bot in a network of bots,
            // which this runtime holds no definition of.
            recognized_bot_member: None,
        })
    }
}
