//! What an Application Load Balancer's own replies are counted into, as a CLIENT reads those
//! series back.
//!
//! The rule under test: **a reply the load balancer SYNTHESIZED — a `fixed-response` or a
//! `redirect` action of its listener — reached no target selection, so it is counted into
//! `RequestCount` ("this metric is only incremented for requests where the load balancer node was
//! able to choose a target") and into the `HTTPCode_Target_*` family (which counts a status "the
//! targets in the load balancer" generated and "does not include any response codes generated by
//! the load balancer") for neither the load balancer's own dimension nor any `TargetGroup` pair;
//! it feeds only the ELB-side counters — the class of the status the LOAD BALANCER generated and
//! the series of the terminating action that produced it — while a request a target WAS chosen
//! for is counted as one request processed and its status into the target class series of the
//! group that answered.**
//!
//! The metric names, their dimensions, their reporting criteria ("there is a non-zero value") and
//! the two sentences quoted above are Elastic Load Balancing's published CloudWatch metrics for
//! the Application Load Balancer family. `RequestCount`'s own criterion is restated on the
//! constant the publisher reads it from (`src/service/request_metrics.rs`).
//!
//! The sibling suite `alb_request_count_counts_a_chosen_target` pins the same inclusion rule one
//! request at a time, as the metric store holds the datapoints. What is pinned HERE is the split
//! a client actually watches: a MIX of load-balancer-generated and target-served traffic on one
//! load balancer, folded by `GetMetricStatistics` at the 60-second period those series are stored
//! at, so a reader of either family sees only the traffic that family is about.
//!
//! The rows differ along what the rule generalises over: which END produced the reply (the
//! listener's default action, a rule's action, the chosen target), the terminating ACTION that
//! produced it (`fixed-response`, `redirect`, `forward`), the status CLASS it ended in (2XX, 3XX,
//! 4XX, 5XX — each reached from both ends, so no row's expectation can be met by keying on a
//! status), the SERIES read (the request count, both class families, the action counters, the
//! connection error) and the resource it is read ABOUT (the load balancer alone, the target group
//! that answered, a target group of the same load balancer that answered something else).
//!
//! Every request is driven over the data plane by the address the load balancer PUBLISHED, every
//! resource is written through the control plane's own operations, and every series is read back
//! through CloudWatch's own `GetMetricStatistics` on the shared engine — so what a row asserts is
//! what a client's own read answers. The server behind the registered target is published where
//! the service that RUNS a workload publishes one
//! (`service_common::served_http_addresses`), which is the seam the load balancer resolves a
//! registration through.

use std::sync::Arc;
use std::time::{Duration, SystemTime};

use ::service_common::served_http_addresses::{AddressAnswer, ServedAddresses, ServesHttp};
use serde_json::{json, Value};

use crate::alb_data_plane::{
    add_rule, create_listener, create_load_balancer, fixed_response, forward_to, health_reaching,
    ip_target_group, path_pattern, redirect_to, register_address, seed_workload_interface, send,
    settle, WORKLOAD_ADDRESS, WORKLOAD_VPC,
};
use crate::alb_target_metric_rate_alarms::{
    emulator, load_balancer_dimension, now_secs, statistic, target_group_dimension,
    APPLICATION_NAMESPACE, LOAD_BALANCER_DIMENSION, PERIOD, TARGET_GROUP_DIMENSION, TOLERANCE,
};

/// The load balancer and its two `ip` target groups: one whose target answers the success, one
/// whose target answers everything else.
const LOAD_BALANCER: &str = "alb-generated-split";
const OK_GROUP: &str = "alb-generated-split-ok";
const OTHER_GROUP: &str = "alb-generated-split-other";

/// The port the registrations receive traffic on, which is the port the workload's server is
/// published at.
const TARGET_PORT: i32 = 80;

/// The paths the traffic asks for: one no rule matches (the listener's DEFAULT action answers
/// it), one per rule the load balancer answers itself, and one per status the chosen target
/// answers.
const UNMATCHED_PATH: &str = "/nothing-matches-this";
const GENERATED_OK_PATH: &str = "/generated/ok";
const GENERATED_MOVED_PATH: &str = "/generated/moved";
const OK_PATH: &str = "/served/ok/ok";
const OTHER_MISSING_PATH: &str = "/served/other/missing";
const OTHER_MOVED_PATH: &str = "/served/other/moved";
const OTHER_BROKEN_PATH: &str = "/served/other/broken";

/// The patterns the two `forward` rules match on, one per group.
const OK_PATTERN: &str = "/served/ok/*";
const OTHER_PATTERN: &str = "/served/other/*";

/// What the `fixed-response` rule answers with, and the status and host the `redirect` rule sends
/// the client away with.
const GENERATED_BODY: &str = "answered-by-the-load-balancer-itself";
const REDIRECT_STATUS: &str = "HTTP_302";
const REDIRECT_HOST: &str = "elsewhere.test";

/// How the workload's own server answers: the LAST segment of the path asks for one status, and
/// anything else — the `/` of the load balancer's health check among it — is a success, so the
/// registration is one the load balancer sends requests to.
const MISSING_SEGMENT: &str = "missing";
const MOVED_SEGMENT: &str = "moved";
const BROKEN_SEGMENT: &str = "broken";

/// How many requests of each outcome the traffic makes. Different numbers on purpose: a count
/// attributed to the wrong end or the wrong group cannot land on the number the right one expects.
const GENERATED_4XX: f64 = 4.0;
const GENERATED_2XX: f64 = 3.0;
const GENERATED_3XX: f64 = 2.0;
const TARGET_2XX: f64 = 5.0;
const TARGET_4XX: f64 = 3.0;
const TARGET_3XX: f64 = 2.0;
const TARGET_5XX: f64 = 1.0;

/// Every request a target was chosen for, and every one of them the SECOND group answered: what
/// the request counter must read under the load balancer and under that group.
const FORWARDED: f64 = TARGET_2XX + TARGET_4XX + TARGET_3XX + TARGET_5XX;
const OTHER_FORWARDED: f64 = TARGET_4XX + TARGET_3XX + TARGET_5XX;

/// Every reply the load balancer synthesized by a `fixed-response` action, whichever class it
/// ended in: what that action's own series must read.
const FIXED_RESPONSES: f64 = GENERATED_4XX + GENERATED_2XX;

/// The server the workload behind the registered address listens with, published exactly where
/// the service running such a workload publishes one.
#[derive(Debug)]
struct Workload;

impl ServesHttp for Workload {
    fn serve(&self, _method: &str, path: &str) -> Option<AddressAnswer> {
        let status = match path.rsplit('/').next().unwrap_or_default() {
            MISSING_SEGMENT => 404,
            MOVED_SEGMENT => 301,
            BROKEN_SEGMENT => 500,
            _ => 200,
        };
        Some(AddressAnswer {
            status,
            content_type: Some("text/plain".to_string()),
            body: format!("served-by-the-workload-with-{status}").into_bytes(),
        })
    }
}

/// One batch of the traffic: the path it asks for, the status every request of it must be
/// answered with, and how many requests it makes.
#[derive(Debug)]
struct Batch {
    case: &'static str,
    path: &'static str,
    status: u16,
    count: f64,
}

/// The traffic, in the order it is sent: three batches the load balancer answers ITSELF, reaching
/// three different status classes through two different actions, and four batches the chosen
/// target answers, reaching four classes of its own.
const TRAFFIC: &[Batch] = &[
    Batch {
        case: "the listener's default fixed-response answers a path no rule matches",
        path: UNMATCHED_PATH,
        status: 404,
        count: GENERATED_4XX,
    },
    Batch {
        case: "a rule's fixed-response answers a success the load balancer generated",
        path: GENERATED_OK_PATH,
        status: 200,
        count: GENERATED_2XX,
    },
    Batch {
        case: "a rule's redirect answers a redirection the load balancer generated",
        path: GENERATED_MOVED_PATH,
        status: 302,
        count: GENERATED_3XX,
    },
    Batch {
        case: "a forward whose chosen target answers a success",
        path: OK_PATH,
        status: 200,
        count: TARGET_2XX,
    },
    Batch {
        case: "a forward whose chosen target answers a client error of its own",
        path: OTHER_MISSING_PATH,
        status: 404,
        count: TARGET_4XX,
    },
    Batch {
        case: "a forward whose chosen target answers a redirection of its own",
        path: OTHER_MOVED_PATH,
        status: 301,
        count: TARGET_3XX,
    },
    Batch {
        case: "a forward whose chosen target answers a server error of its own",
        path: OTHER_BROKEN_PATH,
        status: 500,
        count: TARGET_5XX,
    },
];

/// Which resource a series is read ABOUT.
#[derive(Clone, Copy, Debug)]
enum About {
    /// The load balancer alone, which is what a count of what IT carried is keyed by.
    LoadBalancer,
    /// The group whose target answered the successes, as the `TargetGroup` + `LoadBalancer` pair.
    OkGroup,
    /// The group whose target answered every other status, as the same pair.
    OtherGroup,
}

/// One row of the table: the series, the resource it is read about, and the `Sum` the traffic must
/// have left in it — `0.0` meaning the series holds NO datapoint at all, which is what these
/// series' reporting criteria make of a count of nothing.
#[derive(Debug)]
struct SeriesRow {
    case: &'static str,
    metric: &'static str,
    about: About,
    expected: f64,
}

const SERIES: &[SeriesRow] = &[
    SeriesRow {
        case: "only the requests a target was chosen for are requests processed",
        metric: "RequestCount",
        about: About::LoadBalancer,
        expected: FORWARDED,
    },
    SeriesRow {
        case: "and each is counted for the group it was forwarded to",
        metric: "RequestCount",
        about: About::OkGroup,
        expected: TARGET_2XX,
    },
    SeriesRow {
        case: "the other group carries the forwards that reached it, and no reply the load \
               balancer generated",
        metric: "RequestCount",
        about: About::OtherGroup,
        expected: OTHER_FORWARDED,
    },
    SeriesRow {
        case: "the successes the target answered: an ALB-generated 200 is in none of them",
        metric: "HTTPCode_Target_2XX_Count",
        about: About::LoadBalancer,
        expected: TARGET_2XX,
    },
    SeriesRow {
        case: "narrowed to the group whose target answered them",
        metric: "HTTPCode_Target_2XX_Count",
        about: About::OkGroup,
        expected: TARGET_2XX,
    },
    SeriesRow {
        case: "the group whose target answered no success holds no datapoint",
        metric: "HTTPCode_Target_2XX_Count",
        about: About::OtherGroup,
        expected: 0.0,
    },
    SeriesRow {
        case: "the client errors the target answered: the ALB-generated 404s are not among them",
        metric: "HTTPCode_Target_4XX_Count",
        about: About::LoadBalancer,
        expected: TARGET_4XX,
    },
    SeriesRow {
        case: "narrowed to the group whose target answered them",
        metric: "HTTPCode_Target_4XX_Count",
        about: About::OtherGroup,
        expected: TARGET_4XX,
    },
    SeriesRow {
        case: "the group whose target answered no client error holds no datapoint",
        metric: "HTTPCode_Target_4XX_Count",
        about: About::OkGroup,
        expected: 0.0,
    },
    SeriesRow {
        case: "the redirection the target answered is the target's own class, not the redirect \
               action's",
        metric: "HTTPCode_Target_3XX_Count",
        about: About::OtherGroup,
        expected: TARGET_3XX,
    },
    SeriesRow {
        case: "the server error the target answered",
        metric: "HTTPCode_Target_5XX_Count",
        about: About::OtherGroup,
        expected: TARGET_5XX,
    },
    SeriesRow {
        case: "the client errors the load balancer generated are its own class",
        metric: "HTTPCode_ELB_4XX_Count",
        about: About::LoadBalancer,
        expected: GENERATED_4XX,
    },
    SeriesRow {
        case: "a load-balancer-generated class is about no target group",
        metric: "HTTPCode_ELB_4XX_Count",
        about: About::OtherGroup,
        expected: 0.0,
    },
    SeriesRow {
        case: "the redirections the load balancer generated are its own class",
        metric: "HTTPCode_ELB_3XX_Count",
        about: About::LoadBalancer,
        expected: GENERATED_3XX,
    },
    SeriesRow {
        case: "the server error the TARGET answered is no load-balancer-generated status, so that \
               class holds no datapoint",
        metric: "HTTPCode_ELB_5XX_Count",
        about: About::LoadBalancer,
        expected: 0.0,
    },
    SeriesRow {
        case: "every reply a fixed-response action produced, whichever class it ended in",
        metric: "HTTP_Fixed_Response_Count",
        about: About::LoadBalancer,
        expected: FIXED_RESPONSES,
    },
    SeriesRow {
        case: "and every one a redirect action produced",
        metric: "HTTP_Redirect_Count",
        about: About::LoadBalancer,
        expected: GENERATED_3XX,
    },
    SeriesRow {
        case: "an action the load balancer performed is about no target group",
        metric: "HTTP_Fixed_Response_Count",
        about: About::OkGroup,
        expected: 0.0,
    },
    SeriesRow {
        case: "every chosen target answered, so no connection failed",
        metric: "TargetConnectionErrorCount",
        about: About::LoadBalancer,
        expected: 0.0,
    },
];

/// Every dimension set this suite reads, resolved once the resources exist.
#[derive(Debug)]
struct Keys {
    load_balancer: Value,
    ok_group: Value,
    other_group: Value,
}

impl Keys {
    /// The `Dimensions` list a read about `about` carries.
    fn of(&self, about: About) -> Value {
        match about {
            About::LoadBalancer => self.load_balancer.clone(),
            About::OkGroup => self.ok_group.clone(),
            About::OtherGroup => self.other_group.clone(),
        }
    }
}

/// RULE: a reply the load balancer synthesized itself is counted into neither `RequestCount` nor
/// the target class series, only into the ELB-side counters, while a request a target was chosen
/// for is counted into both.
#[tokio::test]
async fn an_alb_generated_reply_feeds_only_the_elb_side_counters() {
    let (router, engine) = emulator();
    seed_workload_interface(&engine);

    // The load balancer, the listener whose DEFAULT action is a fixed response, and the two `ip`
    // target groups the two forward rules reach — both registering the one workload address, so
    // what narrows a series is the group the request was FORWARDED to.
    let (lb_arn, published) = create_load_balancer(&router, LOAD_BALANCER).await;
    let listener_arn = create_listener(&router, &lb_arn).await;
    let ok_group = ip_target_group(&router, OK_GROUP, WORKLOAD_VPC).await;
    let other_group = ip_target_group(&router, OTHER_GROUP, WORKLOAD_VPC).await;
    for (case, group) in [("the success group", &ok_group), ("the other group", &other_group)] {
        register_address(&router, case, group, WORKLOAD_ADDRESS).await;
    }

    let mut fields = path_pattern(GENERATED_OK_PATH);
    fields.extend(fixed_response("200", GENERATED_BODY, None));
    add_rule(&router, "the fixed response", &listener_arn, 10, &fields).await;
    let mut fields = path_pattern(GENERATED_MOVED_PATH);
    fields.extend(redirect_to(REDIRECT_STATUS, REDIRECT_HOST));
    add_rule(&router, "the redirect", &listener_arn, 20, &fields).await;
    let mut fields = path_pattern(OK_PATTERN);
    fields.extend(forward_to(&ok_group));
    add_rule(&router, "the forward to the success group", &listener_arn, 30, &fields).await;
    let mut fields = path_pattern(OTHER_PATTERN);
    fields.extend(forward_to(&other_group));
    add_rule(&router, "the forward to the other group", &listener_arn, 40, &fields).await;

    // The move to `active` the clock owes the load balancer, placed rather than slept for.
    settle(&engine, &lb_arn, SystemTime::now() - Duration::from_secs(1));

    // The workload's own server, listening for the whole run: published before the health checks
    // are waited on, so both registrations are ones the load balancer chooses a target among.
    let addresses = ServedAddresses::of(&*engine).expect("the shared engine vends the records");
    let _listening = addresses.publish(WORKLOAD_ADDRESS, TARGET_PORT, Arc::new(Workload));
    for (case, group) in [("the success group", &ok_group), ("the other group", &other_group)] {
        health_reaching(&router, case, group, "healthy").await;
    }

    let keys = Keys {
        load_balancer: json!([
            { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension(&lb_arn) },
        ]),
        ok_group: json!([
            { "Name": TARGET_GROUP_DIMENSION, "Value": target_group_dimension(&ok_group) },
            { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension(&lb_arn) },
        ]),
        other_group: json!([
            { "Name": TARGET_GROUP_DIMENSION, "Value": target_group_dimension(&other_group) },
            { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension(&lb_arn) },
        ]),
    };

    // The window every read below folds: wide enough on either side of the traffic that no
    // datapoint of it can fall outside, so the sums are of the whole run however the periods of
    // these series happen to be anchored around it.
    let start = now_secs() - 2.0 * PERIOD;
    let (before, points) = statistic(
        &router,
        "RequestCount",
        &keys.of(About::LoadBalancer),
        start,
        now_secs() + 2.0 * PERIOD,
    )
    .await;
    assert!(
        before.abs() < TOLERANCE && points == 0,
        "before any traffic: expected a load balancer that has answered nothing to count no \
         request, got {before} over {points} datapoint(s)"
    );

    for batch in TRAFFIC {
        for index in 0..batch.count as usize {
            let answered = send(&router, "GET", &published, batch.path, &[]).await;
            assert_eq!(
                answered.status, batch.status,
                "case {:?} request {index}: expected HTTP {}, got {} body {:?}",
                batch.case, batch.status, answered.status, answered.body
            );
        }
    }

    let end = now_secs() + 2.0 * PERIOD;
    for row in SERIES {
        let dimensions = keys.of(row.about);
        let (total, points) = statistic(&router, row.metric, &dimensions, start, end).await;
        assert!(
            (total - row.expected).abs() < TOLERANCE,
            "case {:?}: expected {} of {} about {:?} to sum to {}, got {total} over {points} \
             datapoint(s)",
            row.case,
            row.metric,
            APPLICATION_NAMESPACE,
            row.about,
            row.expected
        );
        if row.expected == 0.0 {
            assert_eq!(
                points, 0,
                "case {:?}: a series no request gave a value must hold no datapoint, got {points}",
                row.case
            );
        }
    }
}
