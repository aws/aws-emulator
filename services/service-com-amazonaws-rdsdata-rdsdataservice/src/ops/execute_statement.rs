/// Run the statement and build the response, inside the data plane.
fn execute(
    store: &crate::state::Store,
    input: &ExecuteStatementInput,
) -> Result<ExecuteStatementOutput, crate::state::SqlError> {
    let parameters = input.parameters.clone().unwrap_or_default();
    // The faults of the request's own `parameters` are decided before the statement is
    // prepared AND before the state lock is taken, so a request-shaped fault costs no
    // other caller anything: the statement never runs, and nothing waits on this one.
    crate::state::require_bindable_parameters(&parameters)?;
    // How the result set is returned: both members' values are enums the model
    // declares, and a value outside either never reaches here — the request walk
    // refuses it against the model first.
    let returns = crate::state::ReturnTypes::from_options(input.result_set_options.as_ref());
    let as_json = format_as_json(input.format_records_as.as_deref());
    let mut state = store.lock();
    let cluster = state.cluster_mut(&input.resource_arn)?;
    cluster.expire_timed_out_transactions();

    // ONE budget for this request: the deadline its statement runs under and the
    // response bytes it may produce, shared by reading the values out of the
    // engine and by rendering them, so the request has a single output bound.
    let mut budget = crate::state::RequestBudget::new();

    // With a `transactionId` the statement runs inside that transaction, against
    // the database that transaction READS: everything committed on it, plus the
    // transaction's own writes, which stay invisible to every other reader until it
    // commits. Without one it runs against the committed database and auto-commits —
    // what the model's doc says an untransacted call does. A statement about the
    // cluster's DATABASES is neither: the cluster applies it. A statement the reader
    // cannot read at all is not one of those, so it goes to the statement path below,
    // which refuses it in the same words AND ends the transaction it ran in.
    let namespace = crate::state::postgres::namespace_statement(&input.sql).unwrap_or_default();
    let outcome = match namespace {
        Some(statement) => {
            // A call quoting a `transactionId` is served only while that transaction is
            // RUNNING, whatever its statement does — so the id is resolved here too;
            // the statement itself still goes to the cluster, because the engines
            // behind this API apply a statement about their databases outside any
            // transaction block.
            if let Some(transaction_id) = input.transaction_id.as_deref() {
                cluster.open_transaction_mut(transaction_id)?.touch();
            }
            cluster.apply_namespace(&statement)?
        }
        None => match input.transaction_id.as_deref() {
            Some(transaction_id) => {
                let ran = cluster.run_in_transaction(
                    transaction_id,
                    &mut budget,
                    &input.sql,
                    &parameters,
                );
                // "A transaction is terminated when a statement in it fails"
                // (`BeginTransaction`'s own documentation), so a statement the ENGINE
                // refused aborts the transaction it was part of: the database ignores
                // every further command of it, and whatever it had written can no longer
                // be committed — a commit of it discards those writes exactly as a
                // rollback does.
                if ran
                    .as_ref()
                    .err()
                    .is_some_and(crate::state::SqlError::terminates_a_transaction)
                {
                    cluster.abort_transaction(transaction_id);
                }
                ran?
            }
            None => cluster
                .database_mut(&crate::state::database_key(input.database.as_ref()))?
                .run_within(&mut budget, &input.sql, &parameters)?,
        },
    };

    let mut output = ExecuteStatementOutput::default();
    if outcome.has_result_set() {
        // `formattedRecords` "is only present when the formatRecordsAs parameter
        // is set to JSON", and `records` / `columnMetadata` are blank then.
        if as_json {
            output.formatted_records = Some(outcome.formatted_records(&mut budget)?);
        } else {
            output.records = Some(outcome.records(returns)?);
            if input.include_result_metadata {
                output.column_metadata = Some(outcome.column_metadata());
            }
        }
    } else {
        // A statement with no result set is DML or DDL: it reports the rows it
        // changed and any key the engine generated for them. A statement that
        // RETURNED a result set leaves `numberOfRecordsUpdated` at the modelled
        // default instead — "a SELECT does not set it" is stated here, by not
        // setting it, rather than left to the serializer omitting a zero.
        output.number_of_records_updated = outcome.records_updated;
        output.generated_fields = Some(outcome.generated_fields.clone());
    }
    // An access record for the data plane: who was addressed and what the engine
    // did. The statement text and the secret are NOT recorded — both carry caller
    // secrets.
    tracing::info!(
        resource_arn = %input.resource_arn,
        database = input.database.as_deref().unwrap_or(""),
        in_transaction = input.transaction_id.is_some(),
        records_updated = outcome.records_updated,
        rows_returned = outcome.rows.len(),
        "rds-data executed a statement"
    );
    Ok(output)
}

/// `formatRecordsAs=JSON`. The model's `RecordsFormatType` is `NONE | JSON`, and
/// `NONE` — the documented default — returns the result set in `records`; a value the
/// enum does not declare never reaches here, because the request walk refuses it
/// against the model first.
fn format_as_json(format: Option<&str>) -> bool {
    format.is_some_and(|format| format.eq_ignore_ascii_case("JSON"))
}

/// Report a statement that did not run as the error this operation models for it.
///
/// WHICH class a failure is depends on WHOSE fault it is, which is the one rule this
/// mapping follows: an error the DATABASE raised while running the statement is
/// `DatabaseErrorException` ("There was an error in processing the SQL statement"), a
/// fault of the CALL — the request's own parameters or members — is a validation fault,
/// and a result the API cannot represent is `UnsupportedResultException`. The deprecated
/// `BadRequestException` ("This exception is deprecated") is answered for none of them.
fn statement_failed(error: crate::state::SqlError) -> ExecuteStatementError {
    let message = Some(error.message());
    match error {
        crate::state::SqlError::TransactionNotFound(_) => {
            ExecuteStatementErrorModeled::TransactionNotFoundException(
                TransactionNotFoundException { message },
            )
        }
        crate::state::SqlError::Timeout => {
            ExecuteStatementErrorModeled::StatementTimeoutException(StatementTimeoutException {
                message,
                db_connection_id: 0,
            })
        }
        crate::state::SqlError::ResultTooLarge | crate::state::SqlError::UnsupportedResult(_) => {
            ExecuteStatementErrorModeled::UnsupportedResultException(UnsupportedResultException {
                message,
            })
        }
        crate::state::SqlError::Unavailable(detail) => {
            tracing::error!(%detail, "the rds-data data plane could not serve a statement");
            ExecuteStatementErrorModeled::InternalServerErrorException(
                InternalServerErrorException::default(),
            )
        }
        // This emulator is out of its own room, which is not the caller's
        // request being wrong: the model's `ServiceUnavailableError` (503) is
        // what says the service could not serve it. The shape carries no
        // members, so which cap it was is logged rather than returned.
        crate::state::SqlError::Capacity(detail) => {
            tracing::warn!(%detail, "the rds-data data plane is at a stored-object cap");
            ExecuteStatementErrorModeled::ServiceUnavailableError(
                ServiceUnavailableError::default(),
            )
        }
        // The database raised it: the statement reached the engine and the engine
        // refused it, which is the class a client branches on to tell "the database
        // rejected my data" from "my call is wrong".
        crate::state::SqlError::Engine(_) => {
            ExecuteStatementErrorModeled::DatabaseErrorException(DatabaseErrorException { message })
        }
        // The CALL is wrong: a parameter that cannot be bound, or a member the model's
        // own constraints do not reach — more than one statement in one `sql`, more
        // parameter sets or more statement than one call runs. Nothing ran, and the
        // caller has to change its request rather than its data, which is what the
        // validation class says (the deprecated `BadRequestException` says neither).
        crate::state::SqlError::Parameter(message)
        | crate::state::SqlError::InvalidRequest(message) => {
            return crate::scaffolded::Scaffolded::validation(message)
        }
    }
    .into()
}
