/// Run the statement once per parameter set and build the response, inside the
/// data plane.
fn execute_batch(
    store: &crate::state::Store,
    input: &BatchExecuteStatementInput,
) -> Result<BatchExecuteStatementOutput, crate::state::SqlError> {
    let parameter_sets = input.parameter_sets.clone().unwrap_or_default();
    if parameter_sets.len() > crate::state::MAX_PARAMETER_SETS {
        // A property of the REQUEST, not of this emulator's room: the caller sent
        // more parameter sets than one call runs, so it is a bad request.
        return Err(crate::state::SqlError::InvalidRequest(format!(
            "parameterSets carries {} sets; this emulator runs at most {} in one call",
            parameter_sets.len(),
            crate::state::MAX_PARAMETER_SETS
        )));
    }
    // Every set's own bindings are decided before the batch reaches the engine, so a
    // batch carrying one unbindable set runs none of its statements.
    for parameters in &parameter_sets {
        crate::state::require_bindable_parameters(parameters)?;
    }
    // `parameterSets` is OPTIONAL, and a call that omits it (or sends an empty list)
    // still runs the statement: it binds nothing, so there is one execution of it and
    // the response carries that one `UpdateResult`. A set per execution is what the
    // response's own list is one of.
    let runs = if parameter_sets.is_empty() {
        vec![Vec::new()]
    } else {
        parameter_sets
    };
    let mut state = store.lock();
    let cluster = state.cluster_mut(&input.resource_arn)?;
    cluster.expire_timed_out_transactions();

    // Exactly one `UpdateResult` per execution, in the order the sets arrived:
    // the statement is run once per set against the same database, so N sets of an
    // INSERT leave N rows behind — and a set that FAILS refuses the whole batch,
    // leaving none of them behind. ONE budget covers the whole batch — one deadline
    // and one output cap, shared by every statement — so a long `parameterSets`
    // can buy neither more engine time nor more result memory than a single
    // statement gets.
    let mut budget = crate::state::RequestBudget::new();

    // A `transactionId` runs the batch inside that transaction, against the database
    // that transaction reads; without one the batch runs against the committed
    // database and auto-commits. A statement about the cluster's DATABASES is applied
    // by the cluster, once per execution like every other statement of a batch; one the
    // reader cannot read at all goes to the statement path, which refuses it in the same
    // words and ends the transaction it ran in.
    let namespace = crate::state::postgres::namespace_statement(&input.sql).unwrap_or_default();
    let outcomes = match namespace {
        Some(statement) => {
            // A call quoting a `transactionId` is served only while that transaction is
            // RUNNING, whatever its statement does; the statement itself still goes to
            // the cluster, which applies it outside any transaction block.
            if let Some(transaction_id) = input.transaction_id.as_deref() {
                cluster.open_transaction_mut(transaction_id)?.touch();
            }
            let mut outcomes = Vec::with_capacity(runs.len());
            for _ in &runs {
                outcomes.push(cluster.apply_namespace(&statement)?);
            }
            outcomes
        }
        None => match input.transaction_id.as_deref() {
            Some(transaction_id) => {
                let ran =
                    cluster.run_batch_in_transaction(transaction_id, &mut budget, &input.sql, &runs);
                // A statement of the batch that the engine refused aborts the transaction it
                // ran in, exactly as a single statement does.
                if ran
                    .as_ref()
                    .err()
                    .is_some_and(crate::state::SqlError::terminates_a_transaction)
                {
                    cluster.abort_transaction(transaction_id);
                }
                ran?
            }
            None => cluster
                .database_mut(&crate::state::database_key(input.database.as_ref()))?
                .run_batch_within(&mut budget, &input.sql, &runs)?,
        },
    };
    let update_results = outcomes
        .iter()
        .map(|outcome| UpdateResult {
            generated_fields: Some(outcome.generated_fields.clone()),
        })
        .collect::<Vec<_>>();
    // An access record for the data plane: who was addressed and how much the
    // engine ran. The statement text and the secret are NOT recorded — both carry
    // caller secrets.
    tracing::info!(
        resource_arn = %input.resource_arn,
        database = input.database.as_deref().unwrap_or(""),
        in_transaction = input.transaction_id.is_some(),
        statements = update_results.len(),
        "rds-data executed a batch"
    );
    Ok(BatchExecuteStatementOutput {
        update_results: Some(update_results),
    })
}

/// Report a statement that did not run as the error this operation models for it.
///
/// The same rule the single-statement path follows: an error the DATABASE raised is
/// `DatabaseErrorException`, a fault of the CALL is a validation fault, and the
/// deprecated `BadRequestException` is answered for neither.
fn statement_failed(error: crate::state::SqlError) -> BatchExecuteStatementError {
    let message = Some(error.message());
    match error {
        crate::state::SqlError::TransactionNotFound(_) => {
            BatchExecuteStatementErrorModeled::TransactionNotFoundException(
                TransactionNotFoundException { message },
            )
        }
        crate::state::SqlError::Timeout => {
            BatchExecuteStatementErrorModeled::StatementTimeoutException(
                StatementTimeoutException {
                    message,
                    db_connection_id: 0,
                },
            )
        }
        crate::state::SqlError::Unavailable(detail) => {
            tracing::error!(%detail, "the rds-data data plane could not serve a batch");
            BatchExecuteStatementErrorModeled::InternalServerErrorException(
                InternalServerErrorException::default(),
            )
        }
        // This emulator is out of its own room, which is not the caller's
        // request being wrong: the model's `ServiceUnavailableError` (503) is
        // what says the service could not serve it. The shape carries no
        // members, so which cap it was is logged rather than returned.
        crate::state::SqlError::Capacity(detail) => {
            tracing::warn!(%detail, "the rds-data data plane is at a stored-object cap");
            BatchExecuteStatementErrorModeled::ServiceUnavailableError(
                ServiceUnavailableError::default(),
            )
        }
        // This operation returns no result set, so a result-shaped failure can only
        // come from a statement the engine ran: it is the database's error either way.
        crate::state::SqlError::Engine(_)
        | crate::state::SqlError::UnsupportedResult(_)
        | crate::state::SqlError::ResultTooLarge => {
            BatchExecuteStatementErrorModeled::DatabaseErrorException(DatabaseErrorException {
                message,
            })
        }
        // The CALL is wrong: a parameter that cannot be bound, or a member the model's
        // own constraints do not reach. Nothing ran.
        crate::state::SqlError::Parameter(message)
        | crate::state::SqlError::InvalidRequest(message) => {
            return crate::scaffolded::Scaffolded::validation(message)
        }
    }
    .into()
}
