impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PauseConnector<Eng>
{
    type Input = PauseConnectorInput;
    type Output = PauseConnectorOutput;
    type Error = PauseConnectorError;

    const NAME: &'static str = "PauseConnector";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PAUSE_CONNECTOR_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PAUSE_CONNECTOR_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(store) = crate::state::service_state(&*self.engine) else {
            return Err(PauseConnectorErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: Some("the kafkaconnect store is unavailable".to_string()),
                },
            )
            .into());
        };
        let region = crate::state::request_region(ctx.parts());

        // The clock first, in a scope of its own, and then the worker log events
        // the settle it applied has written: a delivery AWAITS, so it cannot be
        // made while this service's store is locked
        // (`crate::state::deliver_worker_logs`).
        store.lock().settle_due();
        crate::state::deliver_worker_logs(&*self.engine, ctx).await;

        let mut state = store.lock();

        // A value that is not a kafkaconnect ARN at all names no connector, so
        // it is incorrect input rather than a resource that is absent: the
        // modelled 400, blaming the member that carried it. Refused before any
        // state is touched, so nothing is recorded.
        if let Some(message) = crate::state::arn_syntax_refusal(
            "connectorArn",
            &input.connector_arn,
            crate::state::ARN_SERVICE,
        ) {
            return Err(PauseConnectorErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
            .into());
        }

        // A regional endpoint acts only on its own region's connectors, so a
        // connectorArn minted in another region pauses nothing and is answered
        // exactly as an ARN this service never minted.
        let Some(connector) = state.connector_in(&region, &input.connector_arn) else {
            return Err(PauseConnectorErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::invalid_parameter_because(
                    "connectorArn",
                    crate::state::RESOURCE_DOES_NOT_EXIST,
                )),
            })
            .into());
        };

        // Only a connector whose workers are running has workers to pause: one
        // still being created, already pausing or paused, resuming, restarting,
        // updating, failed or being deleted has none, so the request is refused
        // rather than recorded against work that cannot happen. The ONE state
        // gate every handler that starts work on a connector runs, named here
        // with the states a pause accepts; only the modelled variant it is
        // answered with is this operation's own.
        if let Some(message) =
            connector.state_refusal(crate::state::PAUSE_ACCEPTED_CONNECTOR_STATES)
        {
            return Err(PauseConnectorErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
            .into());
        }

        let connector_arn = connector.arn.clone();
        let connector_name = connector.name.clone();

        // The ONE rule every handler that starts a connector operation runs: the
        // per-connector operation meter, and the ARN the new operation is
        // reported under. Only the modelled variant the refusal is answered
        // with is this operation's own.
        let arn = match state.start_connector_operation(&connector_arn, &connector_name, &region) {
            Ok(arn) => arn,
            Err(message) => {
                return Err(PauseConnectorErrorModeled::TooManyRequestsException(
                    TooManyRequestsException {
                        message: Some(message),
                    },
                )
                .into());
            }
        };

        let operation =
            crate::state::ConnectorOperationRecord::pause(arn.clone(), connector_arn.clone());

        // The connector is pausing for exactly as long as the pause it is
        // running: the change the clock owes it is the one that operation hands
        // out, so `settle_due` leaves it `PAUSED` at the instant the pause
        // reaches its terminal state and not before. A caller that reads it
        // meanwhile still sees the transient state, and a further call against
        // it is refused while that pause is still running.
        if let Some(connector) = state.connector_in_mut(&region, &connector_arn) {
            connector.state = crate::state::CONNECTOR_PAUSING.to_string();
            connector.pending = Some(operation.connector_settle());
            connector.settling_to = Some(crate::state::CONNECTOR_PAUSED.to_string());
        }
        let output = PauseConnectorOutput {
            connector_arn: Some(connector_arn),
            connector_operation_arn: Some(operation.arn.clone()),
        };
        state.connector_operations.insert(arn, operation);
        Ok(output)
    }
}
