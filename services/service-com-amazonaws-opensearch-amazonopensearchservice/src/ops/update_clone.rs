impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateClone<Eng>
{
    type Input = UpdateCloneInput;
    type Output = UpdateCloneOutput;
    type Error = UpdateCloneError;

    const NAME: &'static str = "UpdateClone";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CLONE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CLONE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state =
            crate::state::service_state(&*self.engine).ok_or_else(crate::state::state_unavailable)?;

        // "Specify exactly one of `TrafficSplitOptions`, `CutoverOptions`, or
        // `RetentionOptions` in each request" — a decision about the request alone, so it is
        // taken before anything about the domain is read.
        let asked = [
            input.traffic_split_options.is_some(),
            input.cutover_options.is_some(),
            input.retention_options.is_some(),
        ]
        .into_iter()
        .filter(|asked| *asked)
        .count();
        if asked != 1 {
            return Err(UpdateCloneErrorModeled::ValidationException(
                crate::state::one_clone_option_required(),
            )
            .into());
        }

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();

        // "The name of the domain that has a cloned blue/green upgrade in progress": a name
        // this account holds no domain under names nothing to manage.
        let domain = store.settled_mut(&input.domain_name, now).ok_or_else(|| {
            UpdateCloneErrorModeled::ResourceNotFoundException(crate::state::domain_not_found(
                &input.domain_name,
            ))
        })?;
        // A domain with no such upgrade being managed has nothing for this call to act on,
        // which is the service's generic envelope rather than a missing resource: the DOMAIN
        // is there.
        if domain
            .cloned_blue_green
            .as_ref()
            .is_none_or(|upgrade| !upgrade.in_progress())
        {
            return Err(UpdateCloneErrorModeled::BaseException(
                crate::state::no_clone_in_progress(&input.domain_name),
            )
            .into());
        }

        // One of the three, as the check above established.
        if let Some(upgrade) = domain.cloned_blue_green.as_mut() {
            if let Some(split) = input.traffic_split_options.as_ref() {
                // `TrafficStrategy` declares the one strategy, and what it shifts is the
                // clone's share of READ traffic: the primary serves the rest.
                upgrade.shift_read_traffic(split.clone_read_traffic_percent, now);
            } else if let Some(cutover) = input.cutover_options.as_ref() {
                upgrade.begin_cutover(&cutover.target, now);
            } else if let Some(retention) = input.retention_options.as_ref() {
                match retention {
                    // "Changes the retention period" — the cluster the domain cut over from
                    // is kept for this long after cutover completes.
                    RetentionOptions::RetentionInHours(hours) => {
                        upgrade.set_retention_in_hours(*hours);
                    }
                    // "… or ends it after cutover completes": the action a caller takes
                    // instead of waiting for the one the service scheduled.
                    RetentionOptions::RetentionAction(action) => {
                        upgrade.end_retention(action, now);
                    }
                }
            }
        }

        // Each of those moves is a configuration change of the domain, and it is one of the
        // cloned blue/green upgrade — which is what makes a progress read of it report the
        // upgrade's state. It changes no `DomainConfig` option, so it names none.
        domain.begin_change(crate::state::PROCESSING_STATUS_MODIFYING, &[], now);
        domain.mark_cloned_blue_green_change();

        let upgrade = domain
            .cloned_blue_green
            .as_ref()
            .ok_or_else(|| {
                // Unreachable: the gate above established the record is there.
                UpdateCloneErrorModeled::BaseException(crate::state::no_clone_in_progress(
                    &input.domain_name,
                ))
            })?
            .clone();
        let change_id = domain
            .latest_change()
            .map(|change| change.change_id.clone())
            .unwrap_or_default();

        Ok(UpdateCloneOutput {
            domain_name: domain.domain_name.clone(),
            // "Use it with `DescribeDomainChangeProgress` to track the change."
            change_id,
            // The three blocks report the state of the upgrade this call has just moved, from
            // the ONE record, so what this call answers and what a later read reports cannot
            // disagree. A block that does not apply yet — a cutover nobody has asked for, a
            // retention period this upgrade was started without — is absent.
            cutover_options: upgrade.to_cutover_options(),
            traffic_split_options: Some(upgrade.to_traffic_split_options()),
            retention_options: upgrade.to_retention_options(),
        })
    }
}
