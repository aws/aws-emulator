impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetMigration<Eng>
{
    type Input = GetMigrationInput;
    type Output = GetMigrationOutput;
    type Error = GetMigrationError;

    const NAME: &'static str = "GetMigration";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_MIGRATION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_MIGRATION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = service_state(&*self.engine).ok_or_else(state_unavailable)?;

        // IAM decides whether the caller may do this BEFORE the request's own values are
        // judged and before the job is looked up, so a caller no identity-based policy
        // permits is told it is not authorized rather than told anything about the
        // migration the request names — including whether it exists.
        crate::state::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &crate::state::authorization::account_application_resource(ctx),
        )
        .map_err(GetMigrationErrorModeled::AccessDeniedException)?;

        // The id is judged for its SHAPE before anything is resolved: `migrationId` is a
        // plain string the model constrains not at all, and a value that cannot name an
        // application ([`crate::state::is_migration_id`]) carries no reference to a job
        // in any account — so it is the malformed request it is (400), not a resource
        // that happens not to exist.
        if !is_migration_id(&input.migration_id) {
            return Err(GetMigrationErrorModeled::ValidationException(
                malformed_migration_id(&input.migration_id),
            )
            .into());
        }

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();

        // The applications are settled first, so what follows is decided on the set of
        // applications this account holds at `now`: one whose deletion has fallen due is
        // no longer held, and neither are the jobs that belonged to it.
        store.settle_applications(now);

        // A job belongs to the application it imports into, and its id names that
        // application, so the application is where the id is resolved: an id naming one
        // this account does not hold addresses no job because there is nothing to address
        // it in, which is what the refusal states. Answered on the status this service
        // answers that shape on (`crate::scaffolded::RESOURCE_NOT_FOUND_STATUS`).
        let application_id = migration_application_id(&input.migration_id);
        if !store.applications.contains_key(application_id) {
            return Err(GetMigrationErrorModeled::ResourceNotFoundException(
                migration_application_not_found(application_id),
            )
            .into());
        }

        let migration = store
            .settled_migration_mut(&input.migration_id, now)
            .ok_or_else(|| {
                GetMigrationErrorModeled::ResourceNotFoundException(migration_not_found(
                    &input.migration_id,
                ))
            })?;

        // Answered from the STORED record through the ONE projection a listing reports
        // the same job by, so the start's answer, this read and a row of
        // `ListMigrations` cannot disagree about where the job stands.
        let summary = migration.to_summary();
        Ok(GetMigrationOutput {
            migration_id: summary.migration_id,
            status: summary.status,
            application_id: summary.application_id,
            source: summary.source,
            exported_count: summary.exported_count,
            imported_count: summary.imported_count,
            error: summary.error,
            created_at: summary.created_at,
            updated_at: summary.updated_at,
        })
    }
}
