impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for AssociatePackages<Eng>
{
    type Input = AssociatePackagesInput;
    type Output = AssociatePackagesOutput;
    type Error = AssociatePackagesError;

    const NAME: &'static str = "AssociatePackages";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ASSOCIATE_PACKAGES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ASSOCIATE_PACKAGES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state =
            crate::state::service_state(&*self.engine).ok_or_else(crate::state::state_unavailable)?;

        let now = SystemTime::now();
        let mut store = state.lock();

        // Whatever the clock already owed the records this call reads is materialised
        // first, so the call decides on the state of the store at `now`: a package
        // whose copy has finished is AVAILABLE, and an association whose move has
        // landed is no longer in flight.
        store.settle_packages(now);
        // A name that names no domain is refused by the lookup this settling precedes.
        let _ = store.settled_mut(&input.domain_name, now);

        // The domain the call names is resolved whatever else the request carries, so
        // a name that names no domain is refused even by a call that goes on to name
        // no package at all: the domain is what the call acts on. It is the SAME
        // refusal the per-package decision below makes for an unresolvable domain, so
        // a batch that names one is refused identically however many packages it
        // carries.
        if !store.domains.contains_key(&input.domain_name) {
            return Err(AssociatePackagesErrorModeled::ValidationException(
                domain_does_not_exist(&input.domain_name),
            )
            .into());
        }

        // A domain holds ONE association per package, so the same package cannot be
        // named twice by one call: that request asks for two states of one
        // association, and the service refuses the batch as a WHOLE with its fixed
        // sentence for a request that repeats a package. It is a property of the
        // REQUEST, so it is decided over the whole list before any entry is checked
        // against the store: what the account holds cannot change the answer to a
        // request that repeats a package. The set this pass builds is also what
        // satisfies a prerequisite the call associates "simultaneously with the package
        // association", which is why the whole request is read before any entry is
        // planned.
        //
        // `PackageList` carries no length constraint, so how many entries it holds is
        // the caller's; this pass is one walk of the list the framework already read, and
        // the set it builds holds one entry per DISTINCT package named, so nothing here
        // grows beyond the request body.
        let mut requested: BTreeSet<String> = BTreeSet::new();
        for entry in &input.package_list {
            if !requested.insert(entry.package_id.clone()) {
                return Err(AssociatePackagesErrorModeled::ValidationException(
                    duplicate_packages_in_request(),
                )
                .into());
            }
        }

        // Each entry is then read and checked against the packages VISIBLE to this
        // account — the ones the SERVICE publishes beside the ones the account created
        // — and the pass refuses at the first entry it cannot serve. Every entry names
        // a DISTINCT visible package, so the work and the records kept are bounded by
        // the published catalog and the store: a request naming more than that is
        // refused by the entry that names a package that does not exist, which is the
        // same refusal the per-package decision below makes.
        let mut asked: Vec<AssociationRequest> = Vec::new();
        for entry in &input.package_list {
            if store.visible_package(&entry.package_id).is_none() {
                return Err(AssociatePackagesErrorModeled::ValidationException(
                    package_not_found(),
                )
                .into());
            }
            asked.push(AssociationRequest {
                package_id: entry.package_id.clone(),
                prerequisite_package_ids: entry
                    .prerequisite_package_id_list
                    .clone()
                    .unwrap_or_default(),
                association_configuration: entry.association_configuration.clone(),
            });
        }

        // NOTHING is written until every package the call names can be associated, so
        // a refused request leaves the domain's associations as they were. The plan is
        // bounded by the pass above — at most one entry per package the store holds —
        // so neither this allocation nor the pass over the entries is sized by the
        // request body.
        //
        // Each entry is decided by the one shared decision this service makes about
        // linking a package to a domain, so this call and the one that links a single
        // package cannot refuse the same request differently.
        let mut planned: Vec<Package> = Vec::new();
        for request in &asked {
            planned.push(
                store
                    .plan_package_association(&input.domain_name, request, &requested)
                    .map_err(refuse)?,
            );
        }

        let mut reported = Vec::with_capacity(planned.len());
        for (request, package) in asked.iter().zip(&planned) {
            let details = store
                .put_package_association(&input.domain_name, package, request, now)
                .ok_or_else(|| {
                    AssociatePackagesErrorModeled::ResourceNotFoundException(domain_not_found(
                        &input.domain_name,
                    ))
                })?;
            reported.push(details);
        }

        Ok(AssociatePackagesOutput {
            domain_package_details_list: Some(reported),
        })
    }
}

/// The shared refusal, as THIS operation's error channel names it.
///
/// The decision reports an unresolvable `DomainName` as a condition; the sentence is
/// this operation's, the same one it refuses such a batch with before any entry is
/// planned.
fn refuse(refusal: AssociationRefusal) -> AssociatePackagesError {
    match refusal {
        AssociationRefusal::DomainUnresolved(domain_name) => {
            AssociatePackagesErrorModeled::ValidationException(domain_does_not_exist(&domain_name))
        }
        AssociationRefusal::Conflict(payload) => {
            AssociatePackagesErrorModeled::ConflictException(payload)
        }
        AssociationRefusal::Validation(payload) => {
            AssociatePackagesErrorModeled::ValidationException(payload)
        }
    }
    .into()
}
