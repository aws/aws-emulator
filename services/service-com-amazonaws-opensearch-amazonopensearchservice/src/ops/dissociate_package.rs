impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DissociatePackage<Eng>
{
    type Input = DissociatePackageInput;
    type Output = DissociatePackageOutput;
    type Error = DissociatePackageError;

    const NAME: &'static str = "DissociatePackage";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DISSOCIATE_PACKAGE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DISSOCIATE_PACKAGE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state =
            crate::state::service_state(&*self.engine).ok_or_else(crate::state::state_unavailable)?;

        // IAM decides whether the caller may do this BEFORE the package or the domain is
        // looked up, so a caller no identity-based policy permits is told it is not
        // authorized rather than told anything about the resources the request names, and
        // this call removes nothing. The resource is the ARN of the domain the request
        // NAMES, taken from the request rather than from a stored record.
        crate::state::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &crate::state::domain_arn(
                &input.domain_name,
                &crate::state::request_region(ctx.parts()),
            ),
        )
        .map_err(DissociatePackageErrorModeled::AccessDeniedException)?;

        let now = SystemTime::now();
        let mut store = state.lock();

        // Whatever the clock already owed the records this call reads is materialised
        // first, so the call decides on the state of the store at `now`: an
        // association whose move has landed is no longer in flight, and one whose
        // removal has fallen due is no longer on the domain at all.
        store.settle_packages(now);
        // A name that names no domain is refused by the decision this settling
        // precedes.
        let _ = store.settled_mut(&input.domain_name, now);

        let package = store
            .plan_package_dissociation(&input.domain_name, &input.package_id)
            .map_err(refuse)?;

        // The decision above resolved the domain and the link under the SAME lock this
        // write holds, so there is no request that reaches this arm: a store that no
        // longer holds them is an internal failure rather than anything the caller can
        // fix.
        let details = store
            .remove_package_association(&input.domain_name, &package, now)
            .ok_or_else(|| {
                DissociatePackageErrorModeled::InternalException(internal_failure(
                    "the domain's package associations",
                ))
            })?;

        Ok(DissociatePackageOutput {
            domain_package_details: Some(details),
        })
    }
}

/// The shared refusal, as THIS operation's error channel names it.
///
/// The decision reports an unresolvable `DomainName` as a condition rather than
/// wording it, so this operation answers it with the sentence the service words ITS
/// refusal with: this call reaches the domain behind the capability gate the feature
/// sits behind, so a name it cannot resolve is refused as a domain that cannot serve
/// the feature, and the refusal carries no part of the request.
fn refuse(refusal: AssociationRefusal) -> DissociatePackageError {
    match refusal {
        AssociationRefusal::DomainUnresolved(_) => {
            DissociatePackageErrorModeled::ValidationException(
                domain_not_on_latest_software_version(),
            )
        }
        AssociationRefusal::Conflict(payload) => {
            DissociatePackageErrorModeled::ConflictException(payload)
        }
        AssociationRefusal::Validation(payload) => {
            DissociatePackageErrorModeled::ValidationException(payload)
        }
    }
    .into()
}
