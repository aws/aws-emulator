/// The filter names this operation documents, from `DescribePlacementGroupsRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribePlacementGroupsRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather
/// than listed here. Every entry must be answered by [`filter_values`].
const PLACEMENT_GROUP_FILTERS: [&str; 6] = [
    "group-arn",
    "group-name",
    "spread-level",
    "state",
    "strategy",
    "tag-key",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribePlacementGroupsRequest$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    PLACEMENT_GROUP_FILTERS.contains(&name).then_some(name)
}

/// The values the EC2 filter `name` compares against this placement group.
///
/// A filter naming an attribute this group does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for `spread-level` on a group whose strategy
/// is not `spread`. `name` is a name [`canonical_filter_name`] resolved.
///
/// `partition-count` is deliberately absent: `Filters` does not publish it, and "filter
/// names are case-sensitive" means an unpublished name is refused rather than answered.
fn filter_values<'a>(group: &'a PlacementGroup, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return group
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "group-arn" => text(group.group_arn.as_deref()),
        "group-name" => text(group.group_name.as_deref()),
        "spread-level" => text(group.spread_level.as_deref()),
        "state" => text(group.state.as_deref()),
        "strategy" => text(group.strategy.as_deref()),
        "tag-key" => group
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}

