    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_VOLUME_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = DELETE_VOLUME_OUTPUT_SCHEMA;
