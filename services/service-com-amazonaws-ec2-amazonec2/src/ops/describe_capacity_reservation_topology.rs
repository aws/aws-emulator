/// The topology of one stored Capacity Reservation, as of the `state` the clock has it in.
///
/// Every member is read off the stored reservation: the topology is a VIEW of where the
/// reservation's capacity sits, not a second record of it, so nothing here can drift from
/// what `DescribeCapacityReservations` reports for the same reservation.
fn topology_of(
    reservation: &CapacityReservation,
    state: &str,
) -> CapacityReservationTopology {
    CapacityReservationTopology {
        capacity_reservation_id: reservation.capacity_reservation_id.clone(),
        // "The ID of the Capacity Block … identifies instances within the UltraServer
        // domain": set on a reservation that holds a Capacity Block's capacity, and on no
        // other.
        capacity_block_id: reservation.capacity_block_id.clone(),
        state: Some(state.to_string()),
        instance_type: reservation.instance_type.clone(),
        group_name: placement_group_name(reservation.placement_group_arn.as_deref()),
        network_nodes: network_nodes(reservation, state),
        availability_zone_id: reservation.availability_zone_id.clone(),
        availability_zone: reservation.availability_zone.clone(),
    }
}

/// "The name of the placement group that the Capacity Reservation is in"
/// (`CapacityReservationTopology$GroupName`), read off the group's ARN — or `None` for a
/// reservation that is in no placement group.
///
/// A placement group's ARN carries the resource part `placement-group/<name>`, so the name
/// is what follows that segment; the reservation stores the ARN
/// (`CapacityReservation$PlacementGroupArn`) and the name follows from it rather than being
/// held twice. A value that does NOT carry that segment names no placement group, so it is
/// reported as none rather than echoed back as a group name.
fn placement_group_name(placement_group_arn: Option<&str>) -> Option<String> {
    placement_group_arn
        .and_then(|arn| arn.split_once("placement-group/"))
        .map(|(_, name)| name)
        .filter(|name| !name.is_empty())
        .map(str::to_string)
}

/// The path through the topology tree the reservation's capacity hangs off: the node of the
/// Availability Zone's network at the top, then the hosts of that zone serving its instance
/// type, then the hosts its own capacity is on.
///
/// "The nodes are hashed based on your account. Capacity Reservations from different accounts
/// running under the same server will return a different hashed list of strings"
/// (`CapacityReservationTopology$NetworkNodes`), so each node id is a pure function of the
/// owning account and of everything that places the reservation at that level — which is
/// what makes two reservations share exactly the levels they share a placement at, and makes
/// every read report the same ids without anything being stored.
///
/// `None` when "The Capacity Reservation is in a state other than `active` or `pending`"
/// (same member): a reservation that holds no capacity sits on no host, so there is no path
/// to report. A reservation whose instance type AWS does not support topology for would
/// report none either; which types those are is published in neither the model nor the
/// request, and this service's instance-type catalog
/// ([`crate::state::offered_instance_types`]) is the whole modelled `InstanceType` enum, so
/// every type it offers is answered with a path rather than a subset being invented here.
fn network_nodes(reservation: &CapacityReservation, state: &str) -> Option<Vec<String>> {
    use crate::state::{CAPACITY_RESERVATION_STATE_ACTIVE, CAPACITY_RESERVATION_STATE_PENDING};

    if state != CAPACITY_RESERVATION_STATE_ACTIVE && state != CAPACITY_RESERVATION_STATE_PENDING {
        return None;
    }
    let owner_id = reservation.owner_id.as_deref().unwrap_or_default();
    // The levels of the tree, from its root down. The deepest one is the Capacity Block the
    // reservation's capacity belongs to where there is one — the UltraServer domain its
    // instances share a server with — and the reservation itself otherwise.
    let levels = [
        reservation.availability_zone_id.as_deref().unwrap_or_default(),
        reservation.instance_type.as_deref().unwrap_or_default(),
        reservation
            .capacity_block_id
            .as_deref()
            .or(reservation.capacity_reservation_id.as_deref())
            .unwrap_or_default(),
    ];
    let mut path: Vec<&str> = Vec::with_capacity(levels.len() + 1);
    path.push(owner_id);
    let mut nodes: Vec<String> = Vec::with_capacity(levels.len());
    for level in levels {
        path.push(level);
        nodes.push(network_node_id(&path));
    }
    Some(nodes)
}

/// The id of the topology node `path` names: `nn-` and the digest of the account and of
/// every level of the path down to it, in the 17 digits a long-form EC2 id carries — whose
/// leading digit is `0`, because that form holds 68 bits for a 64-bit identifier, which is
/// also what [`crate::state::ComAmazonawsEc2Amazonec2State::next_id`] mints.
///
/// The standard library's hasher, seeded by its own default rather than randomly, so a node
/// id is a pure function of its path: every read of one placement answers the same id, and
/// two placements that differ at any level get different ones. Nothing here is a secret and
/// nothing depends on a node id being unforgeable — it is an opaque name for a position in
/// the tree.
fn network_node_id(path: &[&str]) -> String {
    use ::std::hash::{Hash, Hasher};

    let mut hasher = ::std::hash::DefaultHasher::new();
    for level in path {
        level.hash(&mut hasher);
    }
    format!("{NETWORK_NODE_ID_PREFIX}-{:017x}", hasher.finish())
}

/// The values the EC2 filter `name` compares against this reported topology.
///
/// A filter naming an attribute the row does not carry compares against NO values, so it
/// selects nothing. `name` is one of [`CAPACITY_RESERVATION_TOPOLOGY_FILTERS`].
fn filter_values<'a>(
    topology: &'a CapacityReservationTopology,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "availability-zone" => text(topology.availability_zone.as_deref()),
        "instance-type" => text(topology.instance_type.as_deref()),
        // Unreachable: the loop above has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check were
        // bypassed.
        _ => Vec::new(),
    }
}

/// Does this row satisfy every filter?
///
/// The AND/OR evaluation, the wildcard matching — which is what answers the documented
/// `p4d*` instance-family form — and the budget charging all live in
/// [`crate::state::matches_every_filter`], so this operation only says WHERE a filter's
/// values come from.
fn matches_every_filter(
    topology: &CapacityReservationTopology,
    selectors: &[crate::state::CompiledFilter],
    budget: &mut crate::state::MatchBudget,
) -> bool {
    crate::state::matches_every_filter(selectors, budget, &|name| filter_values(topology, name))
}
