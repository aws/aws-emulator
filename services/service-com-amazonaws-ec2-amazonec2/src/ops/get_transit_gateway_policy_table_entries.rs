/// specify multiple values for a filter, the values are joined with an OR" (`Filter$Values`)
/// — each value matched case-sensitively, with EC2's own `*`/`?` wildcards, by the pattern the
/// value was compiled into. So a filter carrying no value at all matches nothing, there being
/// no value for the attribute to match.
///
/// Every comparison, and the candidate itself, is charged to `budget`, so one request's
/// filtering cannot cost more than the ceiling however it combines filters, values and value
/// length.
