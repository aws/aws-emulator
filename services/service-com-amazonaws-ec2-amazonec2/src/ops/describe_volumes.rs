/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather
/// than listed here. Every entry must be answered by [`filter_values`].
const VOLUME_FILTERS: [&str; 19] = [
    "attachment.attach-time",
    "attachment.delete-on-termination",
    "attachment.device",
    "attachment.instance-id",
    "attachment.status",
    "availability-zone",
    "availability-zone-id",
    "create-time",
    "encrypted",
    "fast-restored",
    "multi-attach-enabled",
    "operator.managed",
    "operator.principal",
    "size",
    "snapshot-id",
    "status",
    "tag-key",
    "volume-id",
    "volume-type",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeVolumesRequest$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    VOLUME_FILTERS.contains(&name).then_some(name)
}

/// The values the EC2 filter `name` compares against this volume.
///
/// A filter naming an attribute this volume does not carry compares against NO values, so
/// it selects nothing — which is the answer for every `attachment.*` filter here, an
/// unattached volume having no attachment, and for `operator.*`, no volume this emulator
/// stores being service-managed. `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    volume: &'a CreateVolumeOutput,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return volume
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let attachments = || volume.attachments.iter().flatten();
    let operator = || volume.operator.as_ref();
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "attachment.attach-time" => attachments()
            .filter_map(|attachment| attachment.attach_time)
            .map(|attach_time| Cow::Owned(attach_time.to_string()))
            .collect(),
        "attachment.delete-on-termination" => attachments()
            .flat_map(|attachment| boolean_filter_values(attachment.delete_on_termination))
            .collect(),
        "attachment.device" => attachments()
            .filter_map(|attachment| attachment.device.as_deref().map(Cow::Borrowed))
            .collect(),
        "attachment.instance-id" => attachments()
            .filter_map(|attachment| attachment.instance_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "attachment.status" => attachments()
            .filter_map(|attachment| attachment.state.as_deref().map(Cow::Borrowed))
            .collect(),
        "availability-zone" => text(volume.availability_zone.as_deref()),
        "availability-zone-id" => text(volume.availability_zone_id.as_deref()),
        "create-time" => volume
            .create_time
            .map(|create_time| Cow::Owned(create_time.to_string()))
            .into_iter()
            .collect(),
        "encrypted" => boolean_filter_values(volume.encrypted),
        "fast-restored" => boolean_filter_values(volume.fast_restored),
        "multi-attach-enabled" => boolean_filter_values(volume.multi_attach_enabled),
        "operator.managed" => boolean_filter_values(operator().and_then(|operator| operator.managed)),
        "operator.principal" => {
            text(operator().and_then(|operator| operator.principal.as_deref()))
        }
        "size" => volume
            .size
            .map(|size| Cow::Owned(size.to_string()))
            .into_iter()
            .collect(),
        "snapshot-id" => text(volume.snapshot_id.as_deref()),
        // "`status` - The state of the volume" (`DescribeVolumesRequest$Filters`): the
        // member the model calls `State` and the wire calls `status`.
        "status" => text(volume.state.as_deref()),
        "tag-key" => volume
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "volume-id" => text(volume.volume_id.as_deref()),
        "volume-type" => text(volume.volume_type.as_deref()),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}

/// Does `volume` satisfy every filter?
///
/// "If you specify multiple filters, the filters are joined with an AND" (`Filter`), and
/// within one filter "if you specify multiple values for a filter, the values are joined
/// with an OR" (`Filter$Values`) — each value matched case-sensitively, with EC2's own
/// `*`/`?` wildcards, by the pattern the value was compiled into. So a filter carrying no
/// value at all matches nothing, there being no value for the attribute to match.
///
/// Every comparison is charged to `budget`, so one request's filtering cannot cost more
/// than the ceiling however it combines filters, values and value length; once the budget
/// is gone every further comparison answers "no match" and the caller is told the answer
/// is incomplete.
fn matches_every_filter(
    volume: &CreateVolumeOutput,
    selectors: &[crate::state::CompiledFilter],
    budget: &mut crate::state::MatchBudget,
) -> bool {
    selectors.iter().all(|filter| {
        let held = filter_values(volume, &filter.name);
        filter
            .patterns
            .iter()
            .any(|pattern| held.iter().any(|value| pattern.matches_within(value, budget)))
    })
}

