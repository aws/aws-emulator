/// The filter names this operation documents, from `DescribeVolumesRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeVolumesRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
