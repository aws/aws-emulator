/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as the
/// filter value" — the one spelling this crate holds
/// ([`crate::state::TAG_FILTER_PREFIX`]).
const TAG_FILTER_PREFIX: &str = crate::state::TAG_FILTER_PREFIX;

/// Is `name` a filter this operation resolves? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no tag,
/// so it is as unresolvable as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || IPAM_VERIFICATION_TOKEN_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this verification token.
///
/// A filter naming an attribute this token does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for a member a token was minted without.
fn filter_values<'a>(
    token: &'a IpamExternalResourceVerificationToken,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return token
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "ipam-arn" => text(token.ipam_arn.as_deref()),
        "ipam-external-resource-verification-token-arn" => {
            text(token.ipam_external_resource_verification_token_arn.as_deref())
        }
        "ipam-external-resource-verification-token-id" => {
            text(token.ipam_external_resource_verification_token_id.as_deref())
        }
        "ipam-id" => text(token.ipam_id.as_deref()),
        "ipam-region" => text(token.ipam_region.as_deref()),
        "state" => text(token.state.as_deref()),
        "status" => text(token.status.as_deref()),
        "tag-key" => token
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "tag-value" => token
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect(),
        "token-name" => text(token.token_name.as_deref()),
        "token-value" => text(token.token_value.as_deref()),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // unresolvable name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}

