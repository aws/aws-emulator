/// Every entry must be answered by [`filter_values`].
const ROUTE_SERVER_PEER_FILTERS: [&str; 11] = [
    "bgp-options.peer-asn",
    "bgp-options.peer-liveness-detection",
    "endpoint-eni-address",
    "endpoint-eni-id",
    "peer-address",
    "route-server-endpoint-id",
    "route-server-id",
    "route-server-peer-id",
    "state",
    "subnet-id",
    "vpc-id",
];

/// The tag filter whose values are the KEYS a peer carries, rather than one key's value.
const TAG_KEY_FILTER: &str = "tag-key";

/// Is `name` a filter this operation answers? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as undocumented as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || name == TAG_KEY_FILTER
        || ROUTE_SERVER_PEER_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this route server peer.
///
/// A filter naming an attribute this peer does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for, say, a BFD attribute on a peer whose
/// liveness detection is BGP keepalive.
fn filter_values<'a>(peer: &'a RouteServerPeer, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return peer
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let bgp_options = || peer.bgp_options.as_ref();
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        // A numeric attribute is filtered on the value a client sends for it, which is how
        // the wire renders it: the ASN in decimal.
        "bgp-options.peer-asn" => bgp_options()
            .and_then(|options| options.peer_asn)
            .map(|asn| Cow::Owned(asn.to_string()))
            .into_iter()
            .collect(),
        "bgp-options.peer-liveness-detection" => {
            text(bgp_options().and_then(|options| options.peer_liveness_detection.as_deref()))
        }
        "endpoint-eni-address" => text(peer.endpoint_eni_address.as_deref()),
        "endpoint-eni-id" => text(peer.endpoint_eni_id.as_deref()),
        "peer-address" => text(peer.peer_address.as_deref()),
        "route-server-endpoint-id" => text(peer.route_server_endpoint_id.as_deref()),
        "route-server-id" => text(peer.route_server_id.as_deref()),
        "route-server-peer-id" => text(peer.route_server_peer_id.as_deref()),
        "state" => text(peer.state.as_deref()),
        "subnet-id" => text(peer.subnet_id.as_deref()),
        "vpc-id" => text(peer.vpc_id.as_deref()),
        TAG_KEY_FILTER => peer
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
