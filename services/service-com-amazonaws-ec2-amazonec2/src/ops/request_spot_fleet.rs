    type Error = RequestSpotFleetError;

    const NAME: &'static str = "RequestSpotFleet";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REQUEST_SPOT_FLEET_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REQUEST_SPOT_FLEET_OUTPUT_SCHEMA;
