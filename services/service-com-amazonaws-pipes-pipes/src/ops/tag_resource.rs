impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    /// `TagResourceResponse` declares NO member
    /// (`smithy_query(query="shape",shape="TagResourceResponse")`), so a successful write
    /// leaves the caller nothing to parse, and the model pins no code for it — the `@http`
    /// code is the protocol's default rather than a stated one (`code: 200,
    /// codeDefaulted: true`). An answer with no content IS the no-content status, so this
    /// answers 204: a client that branches on the status then reads no body that is not
    /// there. The empty body such an answer carries is framed once for the whole service,
    /// in `crate::service`.
    const SUCCESS_STATUS: u16 = 204u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // IAM decides a signed call BEFORE this service reads it, and a tagging call names
        // the resource it acts on itself, so that ARN is what the decision is taken
        // against — as the request carried it, before any record is resolved.
        if let Some(refused) = crate::state::request_authorization::refused(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.resource_arn,
        ) {
            return Err(refused);
        }
        // The tags are written onto the stored record; nothing else here depends on request
        // metadata.
        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalException(InternalException {
                message: "the pipes store is not reachable from this engine".to_string(),
                retry_after_seconds: None,
            })
        })?;

        let mut state = store.lock();
        state.settle_due_transitions();

        // An ARN of ANOTHER service can name no pipe however this account's pipes change,
        // so the tagging layer refuses it with its own `BadRequestException` (400) rather
        // than with the 404 it answers an ARN of this vendor that resolves to no pipe.
        if let Some(message) = crate::state::foreign_resource_arn(&input.resource_arn) {
            return Err(TagResourceError::bad_request(message));
        }

        // Every tag in a deterministic order, so a request carrying several illegal ones
        // is always refused with the same message.
        let requested: ::std::collections::BTreeMap<&String, &String> =
            input.tags.iter().collect();

        // `TagKey`'s and `TagValue`'s `@length` bounds, the documented tag character set,
        // and the tag-key prefix AWS reserves for itself. The boundary validator walks a
        // map's own entry count and its values' shapes but not its KEYS, and neither the
        // character set nor the reservation is modelled at all, so the rules are enforced
        // here — with the `BadRequestException` the tagging layer answers a broken tag
        // rule with, never a 501.
        for (&key, &value) in &requested {
            if let Some(violation) = crate::state::tag_violation(key, value) {
                // What request validation echoes is the member's value: every tag the
                // request carried, in the one deterministic order above.
                let shown = crate::state::echoed_tags(
                    requested
                        .iter()
                        .map(|(key, value)| (key.as_str(), value.as_str())),
                );
                return Err(TagResourceError::bad_request(crate::state::tag_refusal(
                    crate::state::ADDED_TAGS_MEMBER,
                    violation,
                    &shown,
                )));
            }
        }

        let pipe = state.pipe_by_arn_mut(&input.resource_arn).ok_or_else(|| {
            TagResourceErrorModeled::NotFoundException(crate::state::resource_not_found())
        })?;

        // The documented cap is on the tags a pipe CARRIES, so it is the merged set that
        // has to fit: a request within `TagMap`'s own bound can still take the pipe past
        // it. Counted before anything is written, so a refused call changes nothing.
        let merged = pipe
            .tags
            .keys()
            .filter(|key| !input.tags.contains_key(key.as_str()))
            .count()
            + input.tags.len();
        if merged > crate::state::MAX_TAGS_PER_PIPE {
            let limit = crate::state::MAX_TAGS_PER_PIPE;
            return Err(TagResourceErrorModeled::ValidationException(
                crate::state::validation_error(vec![crate::state::validation_field(
                    "tags",
                    format!(
                        "must leave the pipe with at most {limit} tags; this request would \
                         leave it with {merged}"
                    ),
                )]),
            )
            .into());
        }

        // A new key is appended, a key already on the pipe has its value replaced — and a
        // key the request does not name is left alone, which is what makes a repeated
        // `TagResource` idempotent.
        for (key, value) in requested {
            pipe.tags.insert(key.clone(), value.clone());
        }

        // `LastModifiedTime` is left alone: AWS documents it as when the PIPE was last
        // updated, and tagging is a separate resource-tagging call, not a pipe update.
        Ok(TagResourceOutput {})
    }
}
