impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreatePipe<Eng>
{
    type Input = CreatePipeInput;
    type Output = CreatePipeOutput;
    type Error = CreatePipeError;

    const NAME: &'static str = "CreatePipe";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_PIPE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_PIPE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // IAM decides a signed call BEFORE this service reads it, so a caller whose own
        // policies do not allow the action is told it is not authorized and the create
        // stores nothing.
        if let Some(refused) = crate::state::request_authorization::refused(
            &*self.engine,
            ctx,
            Self::NAME,
            &crate::state::pipe_arn(&crate::state::request_region(ctx.parts()), &input.name),
        ) {
            return Err(refused);
        }
        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            CreatePipeErrorModeled::InternalException(InternalException {
                message: "the pipes store is not reachable from this engine".to_string(),
                retry_after_seconds: None,
            })
        })?;

        // `DesiredState` targets `RequestedPipeState`; the boundary validator refuses a
        // value outside that enum, and this re-states the same rule for any path that
        // reaches the handler with one, naming the member and its legal values.
        let desired_state = match input.desired_state.as_deref() {
            None => crate::state::requested_state::RUNNING.to_string(),
            Some(value) if REQUESTED_PIPE_STATE_VALUES.contains(&value) => value.to_string(),
            Some(_) => {
                return Err(CreatePipeErrorModeled::ValidationException(
                    crate::state::validation_error(vec![crate::state::validation_field(
                        "DesiredState",
                        format!(
                            "must be one of {}",
                            REQUESTED_PIPE_STATE_VALUES.join(", ")
                        ),
                    )]),
                )
                .into());
            }
        };

        // The rules that span the pipe's SOURCE, TARGET and filters — what the resources
        // the pipe names can actually hold, which no per-member constraint can express.
        // Stated once in `crate::state` and enforced by `UpdatePipe` too, so a pipe cannot
        // be created in a configuration an update could not have reached either.
        if let Some(violation) = crate::state::cross_resource_violation(
            &input.source,
            input.source_parameters.as_ref(),
            &input.target,
            input.target_parameters.as_ref(),
        ) {
            return Err(CreatePipeErrorModeled::ValidationException(violation).into());
        }

        // The tag rules a write that installs tags enforces for itself: `TagKey`'s and
        // `TagValue`'s `@length` bounds (the boundary validator walks a map's entry count
        // and its values' shapes but not its KEYS), the documented tag character set and
        // the tag-key prefix AWS reserves. The same `state::tag_violation` `TagResource`
        // applies, so a pipe cannot be CREATED carrying a tag a later `TagResource` would
        // refuse, and it is refused with the same `BadRequestException` the tagging layer
        // answers a broken tag rule with. Sorted, so a request carrying several illegal
        // tags is always refused with the same message.
        //
        // The reserved `aws:` namespace is the one rule that depends on WHO named the key
        // ([`crate::state::tag_key_origin`]): it is refused to an API caller, whose request
        // may not write AWS's own tags, and admitted on the in-process create another
        // emulated service makes for a resource it provisions — the path the
        // `aws:cloudformation:*` tags a stack's resources carry arrive on, which is inside
        // AWS rather than a client's request.
        let origin = crate::state::tag_key_origin(ctx);
        let requested: ::std::collections::BTreeMap<&String, &String> = input
            .tags
            .iter()
            .flat_map(|tags| tags.iter())
            .collect();
        for (&key, &value) in &requested {
            if let Some(violation) = crate::state::tag_violation_from(key, value, origin) {
                // What request validation echoes is the member's value: every tag the
                // request carried, in that one deterministic order.
                let shown = crate::state::echoed_tags(
                    requested
                        .iter()
                        .map(|(key, value)| (key.as_str(), value.as_str())),
                );
                return Err(CreatePipeError::bad_request(crate::state::tag_refusal(
                    crate::state::CREATE_TAGS_MEMBER,
                    violation,
                    &shown,
                )));
            }
        }

        let region = crate::state::request_region(ctx.parts());
        // Whether the pipe this call creates could poll its source at all — the role it is
        // to act as, and the source itself — decided against the account's own records
        // BEFORE the pipes store is locked, so nothing waits on it behind that lock. A pipe
        // that could not is one whose creation cannot be completed.
        let unservable = crate::state::bring_up::refusal(
            ctx,
            &*self.engine,
            &input.source,
            &input.role_arn,
        )
        .await;
        let mut state = store.lock();
        state.settle_due_transitions();

        if let Some(existing) = state.pipes.get(&input.name) {
            return Err(CreatePipeErrorModeled::ConflictException(ConflictException {
                message: format!("Pipe {} already exists.", existing.name),
                resource_id: existing.name.clone(),
                resource_type: crate::state::PIPE_RESOURCE_TYPE.to_string(),
            })
            .into());
        }

        // The store holds at most `MAX_PIPES` records, so no caller can grow it without
        // limit; past the cap this is the quota failure the model declares.
        if state.pipes.len() >= crate::state::MAX_PIPES {
            return Err(CreatePipeErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: format!(
                        "The number of pipes in this account and Region has reached the \
                         limit of {}.",
                        crate::state::MAX_PIPES
                    ),
                    resource_id: input.name.clone(),
                    resource_type: crate::state::PIPE_RESOURCE_TYPE.to_string(),
                    service_code: "pipes".to_string(),
                    // A descriptive name: AWS's own quota code is an `L-…` identifier
                    // this emulator has no source for, and the member is required.
                    quota_code: "PipeCount".to_string(),
                },
            )
            .into());
        }

        // A pipe AWS has just accepted is reported `CREATING` and reaches the state the
        // caller asked for a moment later; the record stores that due instant rather than
        // sleeping for it. A pipe that could not be brought up reaches `CREATE_FAILED`
        // instead, at the same span and carrying the reason — the creation was accepted, so
        // the failure is a state the pipe settles in rather than an answer to this call.
        let now = ::std::time::SystemTime::now();
        let pending = match &unservable {
            None => crate::state::pending_transition(&desired_state),
            Some(reason) => crate::state::failed_transition(
                crate::state::pipe_state::CREATE_FAILED,
                reason.clone(),
            ),
        };
        let record = crate::state::PipeRecord {
            arn: crate::state::pipe_arn(&region, &input.name),
            name: input.name.clone(),
            description: crate::state::stored_description(input.description.clone()),
            current_state: crate::state::pipe_state::CREATING.to_string(),
            // The move the clock owes: `CREATING` -> where this creation lands.
            pending: Some(pending),
            desired_state,
            // The pipe is `CREATING` because this caller asked for it, and the move it is
            // making was asked for too, so the reason is the user-initiated one from here
            // until a failed move replaces it with its own.
            state_reason: Some(crate::state::USER_INITIATED_STATE_REASON.to_string()),
            source: input.source.clone(),
            source_parameters: input.source_parameters.clone(),
            enrichment: input.enrichment.clone(),
            enrichment_parameters: input.enrichment_parameters.clone(),
            target: input.target.clone(),
            target_parameters: input.target_parameters.clone(),
            role_arn: input.role_arn.clone(),
            tags: input
                .tags
                .clone()
                .unwrap_or_default()
                .into_iter()
                .collect(),
            creation_time: now,
            last_modified_time: now,
            log_configuration: input.log_configuration.as_ref().map(log_configuration_of),
            kms_key_identifier: input.kms_key_identifier.clone(),
        };

        let output = CreatePipeOutput {
            arn: Some(record.arn.clone()),
            name: Some(record.name.clone()),
            desired_state: Some(record.desired_state.clone()),
            current_state: Some(record.current_state.clone()),
            creation_time: Some(crate::state::timestamp(record.creation_time)),
            last_modified_time: Some(crate::state::timestamp(record.last_modified_time)),
        };
        let name = record.name.clone();
        let runnable = record.desired_state == crate::state::requested_state::RUNNING
            && unservable.is_none();
        state.pipes.insert(name.clone(), record);
        // The data plane of a pipe the caller asked to RUN: the lock is released first,
        // and the poller waits out the `CREATING` span before it consumes anything, so
        // nothing a caller is told by this response depends on it.
        drop(state);
        if runnable {
            // Only a pipe that was brought up has a data plane: one that settles in
            // `CREATE_FAILED` polls nothing and publishes nothing.
            crate::state::data_plane::drive_pipe(ctx, &self.engine, &name);
        }
        Ok(output)
    }
}

/// The logging configuration AWS reports (`PipeLogConfiguration`) for the one the caller
/// supplied (`PipeLogConfigurationParameters`): the same destinations, as the read shape.
