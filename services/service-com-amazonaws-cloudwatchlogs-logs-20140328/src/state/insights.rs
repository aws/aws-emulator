/// The fields CloudWatch Logs generates for every log event it stores, in the order a
/// result's default columns name them: "fields that start with @ are fields generated by
/// CloudWatch Logs. For example, @timestamp is the timestamp of each log event"
/// (`GetLogGroupFields`), plus the `@ptr` `GetQueryResults` mints for each row.
pub const GENERATED_FIELDS: [&str; 6] = [
    FIELD_PTR,
    FIELD_TIMESTAMP,
    FIELD_MESSAGE,
    FIELD_LOG_STREAM,
    FIELD_LOG,
    FIELD_INGESTION_TIME,
];

/// "a @ptr field, which is the identifier for the log record" (`GetQueryResults`).
pub const FIELD_PTR: &str = "@ptr";

/// The event's own timestamp.
pub const FIELD_TIMESTAMP: &str = "@timestamp";

/// The event's raw text.
pub const FIELD_MESSAGE: &str = "@message";

/// The log stream the event was ingested into.
pub const FIELD_LOG_STREAM: &str = "@logStream";

/// The log group the event is stored in, qualified by the account that owns it.
pub const FIELD_LOG: &str = "@log";

/// When the event was accepted by `PutLogEvents`.
pub const FIELD_INGESTION_TIME: &str = "@ingestionTime";

/// The columns a query that selects none of its own reports: the timestamp and the message
/// of each matched event, which is what a Logs Insights result carries before any `fields`
/// or `display` command narrows it.
pub const DEFAULT_COLUMNS: [&str; 2] = [FIELD_TIMESTAMP, FIELD_MESSAGE];

/// THE EMULATOR'S OWN CEILING on how many stored events ONE run reads, so a query's cost is
/// bounded by this rather than by everything ever ingested into the groups it names. The
/// NEWEST events of the window are read, so the cut falls on the oldest.
pub const MAX_SCANNED_EVENTS: usize = 10_000;

/// THE EMULATOR'S OWN CEILING on how many message BYTES one run reads, the second factor of
/// the same product.
pub const MAX_SCANNED_BYTES: usize = 4 * 1024 * 1024;

/// How many rows one query answers in all: "You can retrieve up to 100,000 log event results
/// from a query, if available, by using pagination" (`GetQueryResults`).
pub const MAX_RESULT_ROWS: usize = 100_000;

/// The rows the START of a query bounds its answer to: `StartQuery$limit` when the start named
/// one — "The maximum number of log events to return from the query. The maximum limit is
/// 100,000" (`EventsLimitStartQuery`, `@range 1..100000`) — held to the most rows the API hands
/// back ([`MAX_RESULT_ROWS`]), and `None` when the start named none.
///
/// That parameter is AUTHORITATIVE over whatever row bound the QUERY STRING itself carries — a
/// `limit`/`head` command of a pipeline, a SQL `LIMIT` clause — so a start that names one
/// REPLACES the string's bound rather than intersecting with it, in both directions: a
/// parameter above it widens the answer, one below it narrows it. A start that names none
/// leaves the query string's own bound to decide.
pub fn requested_row_limit(query: &QueryRecord) -> Option<usize> {
    query.limit.map(|asked| {
        usize::try_from(asked)
            .unwrap_or(MAX_RESULT_ROWS)
            .min(MAX_RESULT_ROWS)
    })
}

/// How many rows ONE `GetQueryResults` call answers when the request names no `maxItems`:
/// "The maximum number of log events to return in the response. The maximum is 10,000 log
/// events per request", which is also the member's modelled maximum
/// (`GetQueryResultsMaxItems`, `range 0..10000`).
pub const MAX_PAGE_ITEMS: i32 = 10_000;

/// THE EMULATOR'S OWN BOUND on how deeply a query's expressions may nest, so a
/// caller-supplied expression cannot recurse an evaluation off its stack.
pub const MAX_EXPRESSION_DEPTH: usize = 64;

/// THE EMULATOR'S OWN BOUND on how many nodes ONE parsed expression may hold.
///
/// Depth alone does not bound a tree: a FLAT chain of same-precedence operators (`a or b or
/// c …`) adds one node per operator without nesting a bracket, and such a tree is walked
/// recursively once per record and dropped recursively when the stage ends. So the node
/// count is bounded too, which is what holds the recursion of both to a depth the stack
/// takes however long the query string is.
pub const MAX_EXPRESSION_NODES: usize = 512;

/// THE EMULATOR'S OWN BOUND on how many expression evaluations and per-record steps ONE run
/// may spend: the records a run reads, the stages it applies to them and the nodes of each
/// expression multiply out, and this bounds the PRODUCT rather than each factor.
pub const MAX_EXECUTION_STEPS: u64 = 8_000_000;

/// THE EMULATOR'S OWN BOUND on how long ONE run may take, whatever it spends its steps on:
/// the deadline a run is abandoned at, so a query whose cost this service underestimated
/// still ends.
pub const MAX_EXECUTION_TIME: std::time::Duration = std::time::Duration::from_secs(5);

/// How often the clock is read while a run spends its budget: every this many steps, so the
/// deadline costs one read per batch of work rather than one per expression node.
const STEPS_BETWEEN_CLOCK_READS: u64 = 4_096;

/// THE EMULATOR'S OWN BOUND on how long ONE computed field value may be. A value a query
/// COMPUTES — a concatenation, a formatted number, a captured substring — is not bounded by
/// the event it came from, so it is bounded here; the largest a single log event may be is a
/// megabyte ([`crate::state::MAX_LOG_EVENT_BYTES`]), and no result field of one event's
/// values is larger than that.
pub const MAX_VALUE_BYTES: usize = 1024 * 1024;

/// THE EMULATOR'S OWN BOUND on the bytes ONE run may COMPUTE in all: the per-value bound
/// times the rows a run may answer would otherwise multiply out, so the total is bounded as
/// well as each value.
pub const MAX_COMPUTED_BYTES: u64 = 16 * 1024 * 1024;

/// What ONE run may spend: expression evaluations, computed bytes and wall-clock time.
///
/// A query is caller-supplied, so the work it asks for is bounded here rather than left to
/// the query: a run that spends its budget is ABANDONED, which the caller sees as the
/// `Failed` status of an execution that produced nothing ([`Execution::failed`]).
///
/// The counters are shared and interior-mutable because one budget is spent by everything one
/// run does — every stage, every record and every comparison of a sort — and a sort
/// comparator cannot hold a mutable borrow; they are atomics rather than cells because a run
/// yields to the runtime as it goes and so may resume on another thread.
#[derive(Debug)]
pub struct Budget {
    /// Expression evaluations left.
    steps: std::sync::atomic::AtomicU64,
    /// Computed bytes left.
    bytes: std::sync::atomic::AtomicU64,
    /// When the run must stop.
    deadline: std::time::Instant,
    /// Why the run was abandoned, once it has been.
    spent: std::sync::Mutex<Option<String>>,
}

impl Default for Budget {
    fn default() -> Self {
        Self::new()
    }
}

impl Budget {
    /// A budget for one run.
    pub fn new() -> Self {
        Self {
            steps: std::sync::atomic::AtomicU64::new(MAX_EXECUTION_STEPS),
            bytes: std::sync::atomic::AtomicU64::new(MAX_COMPUTED_BYTES),
            deadline: std::time::Instant::now() + MAX_EXECUTION_TIME,
            spent: std::sync::Mutex::new(None),
        }
    }

    /// Spend one expression evaluation. `false` once the run is over budget, which every
    /// evaluation then answers nothing for.
    pub fn step(&self) -> bool {
        self.spend(1)
    }

    /// Spend one unit of work that is NOT an expression evaluation: a record a stage walked,
    /// a regular expression it ran, a value it compared. Every per-record loop of a run
    /// spends this, so the step budget and the deadline bound what a run does rather than
    /// only what it evaluates.
    pub fn tick(&self) -> bool {
        self.spend(1)
    }

    /// Spend one unit of the run's step budget, reading the clock once per batch.
    fn spend(&self, units: u64) -> bool {
        if self.exhausted() {
            return false;
        }
        let left = self
            .steps
            .fetch_sub(units, std::sync::atomic::Ordering::Relaxed)
            .saturating_sub(units);
        if left == 0 {
            self.abandon(format!(
                "the query asked for more than {MAX_EXECUTION_STEPS} units of work"
            ));
            return false;
        }
        // The clock is read once per batch of steps, so the deadline bounds a run whose
        // steps are individually cheap but numerous.
        if left.is_multiple_of(STEPS_BETWEEN_CLOCK_READS)
            && std::time::Instant::now() >= self.deadline
        {
            self.abandon(format!(
                "the query ran for longer than {} seconds",
                MAX_EXECUTION_TIME.as_secs()
            ));
            return false;
        }
        true
    }

    /// Spend `len` computed bytes. `false` once the value, or the run, is over budget.
    pub fn store(&self, len: usize) -> bool {
        if self.exhausted() {
            return false;
        }
        if len > MAX_VALUE_BYTES {
            self.abandon(format!(
                "the query computed a value longer than {MAX_VALUE_BYTES} bytes"
            ));
            return false;
        }
        let len = u64::try_from(len).unwrap_or(u64::MAX);
        let left = self
            .bytes
            .try_update(
                std::sync::atomic::Ordering::Relaxed,
                std::sync::atomic::Ordering::Relaxed,
                |left| Some(left.saturating_sub(len)),
            )
            .unwrap_or(0);
        if left < len {
            self.abandon(format!(
                "the query computed more than {MAX_COMPUTED_BYTES} bytes of values"
            ));
            return false;
        }
        true
    }

    /// Whether this run has been abandoned.
    pub fn exhausted(&self) -> bool {
        self.held().is_some()
    }

    /// Why it was abandoned, if it was.
    pub fn reason(&self) -> Option<String> {
        self.held()
    }

    /// The reason held, read through a lock a panicking run cannot poison for the next one.
    fn held(&self) -> Option<String> {
        self.spent
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .clone()
    }

    /// Abandon the run, keeping the FIRST reason it was abandoned for.
    fn abandon(&self, reason: String) {
        let mut spent = self
            .spent
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        if spent.is_none() {
            *spent = Some(reason);
        }
    }
}

/// THE EMULATOR'S OWN CEILING on how many fields are taken from ONE event, the generated
/// ones included: one JSON message can name arbitrarily many keys.
const MAX_FIELDS_PER_EVENT: usize = 200;

/// THE EMULATOR'S OWN CEILING on how deep the flattening of a JSON message descends, so a
/// discovered field's name length is bounded here rather than by whatever nesting the parser
/// admits.
const MAX_FIELD_DEPTH: usize = 8;

/// One record of a query's pipeline: the fields it carries, each under its own name.
///
/// Every value is TEXT, because that is what a result field carries (`ResultField$value` is a
/// string); a stage that needs a number reads one out of the text
/// ([`expression::number_of`]).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Record {
    /// The record's fields. A `BTreeMap` so a stage that enumerates them — a `SELECT *`, a
    /// `fields` command naming none — does so in one stable order.
    pub values: BTreeMap<String, String>,
}

impl Record {
    /// The value of `field`, or `None` when this record does not carry it.
    pub fn get(&self, field: &str) -> Option<&str> {
        self.values.get(field).map(String::as_str)
    }

    /// Set `field` to `value`, replacing whatever this record carried under that name.
    pub fn set(&mut self, field: &str, value: impl Into<String>) {
        self.values.insert(field.to_string(), value.into());
    }
}

/// What running a query produced: its rows, in the order the query orders them, and the
/// counts `QueryStatistics` reports over the run.
#[derive(Debug, Clone, Default)]
pub struct Execution {
    /// One row per result, each an ordered list of field/value pairs — the `ResultRows` of
    /// the model's `QueryResults` ("The results value is an array of arrays. Each log event
    /// is one object in the top-level array. Each of these log event objects is an array of
    /// field/value pairs").
    pub rows: Vec<Vec<(String, String)>>,
    /// The WHOLE record behind each row of LOG RECORDS the run produced, keyed by the `@ptr`
    /// that row carries — "a @ptr field, which is the identifier for the log record", and
    /// "you can use the value of @ptr in a GetLogRecord operation to get the full log record".
    ///
    /// A result set holds the records it points at, so the pointer a query handed out keeps
    /// addressing the record that query read ([`result_set_record`]) — the same durability the
    /// rows themselves have. An AGGREGATION's rows are no single log record and point at none,
    /// so they contribute nothing here; and what one run may hold is bounded by the events one
    /// run reads at all ([`MAX_SCANNED_EVENTS`]).
    pub records: BTreeMap<String, Record>,
    /// "the number of log events that matched the query criteria"
    /// (`QueryStatistics$recordsMatched`).
    pub records_matched: f64,
    /// "the number of log events scanned by the query" (`QueryStatistics$recordsScanned`).
    pub records_scanned: f64,
    /// "the total number of bytes in the scanned log events"
    /// (`QueryStatistics$bytesScanned`).
    pub bytes_scanned: f64,
    /// How many log groups the run read (`QueryStatistics$logGroupsScanned`).
    pub log_groups_scanned: f64,
    /// Why the query could not be run, when it could not be: a query string naming something
    /// this service cannot execute over the events it holds. Such a query has `Failed` for
    /// its status and no rows, and what the run had already READ is still counted.
    pub failed: Option<String>,
}

/// Why a stored query could not be RUN: the query string names something this service cannot
/// execute over the events it holds. A query that cannot run has `Failed` for its status,
/// which is what the model declares for a query whose execution did not produce results
/// (`QueryStatus`: `Cancelled | Complete | Failed | Running | Scheduled | Timeout |
/// Unknown`).
///
/// The reason is kept so the service can log or test it; it is not a refusal of the
/// `GetQueryResults` call, which succeeds and reports the status the query reached.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExecutionFailure {
    /// What about the query string could not be run.
    pub reason: String,
}

impl ExecutionFailure {
    /// A failure carrying `reason`.
    pub fn new(reason: impl Into<String>) -> Self {
        Self {
            reason: reason.into(),
        }
    }
}

/// What one run needs from the store, taken WHILE the store is locked so that running the
/// query itself needs no access to it.
///
/// Reading the results of a query is a read of this service's shared state, and every other
/// request of the service waits on that same state: so the store is read once, into this,
/// and the pipeline then runs over the records it holds with the state released.
#[derive(Debug)]
pub struct Prepared {
    /// What the query string says to do.
    plan: Plan,
    /// The records it does it over, and the counts over reading them.
    scan: Scan,
    /// The query being run, as it was stored.
    query: QueryRecord,
}

/// What a query string compiled or parsed to, ready to run.
#[derive(Debug)]
enum Plan {
    /// A pipeline of stages, in one of the two pipelined languages.
    Pipeline {
        /// Whose vocabulary the stages are written in.
        dialect: pipeline::Dialect,
        /// The stages, in order.
        stages: Vec<super::query_compile::CompiledStage>,
    },
    /// A SQL `SELECT`, as parsed.
    Sql(Box<::sqlparser::ast::Query>),
    /// A query string this service cannot run, and why.
    Unrunnable(String),
}

/// Read everything running `query` needs out of `store`.
///
/// This READS the store: it resolves which log groups the query reads and takes their events
/// of the query's time range, and changes nothing a later caller sees. A query string this
/// service cannot run is prepared as unrunnable, which [`run`] answers as the `Failed` status
/// of an execution that produced nothing rather than as a refusal of the call.
pub fn prepare(store: &State, query: &QueryRecord) -> Prepared {
    let unrunnable = |reason: String| Prepared {
        plan: Plan::Unrunnable(reason),
        scan: Scan::default(),
        query: query.clone(),
    };
    let planned = match query.query_language.as_str() {
        super::DEFAULT_QUERY_LANGUAGE => pipeline::plan_logs_insights(&query.query_string),
        QUERY_LANGUAGE_PPL => pipeline::plan_ppl(&query.query_string),
        QUERY_LANGUAGE_SQL => sql::plan(&query.query_string),
        other => Err(ExecutionFailure::new(format!(
            "the query language {other} has no execution in this service"
        ))),
    };
    let plan = match planned {
        Ok(plan) => plan,
        Err(failure) => return unrunnable(failure.reason),
    };

    // Which log groups the query reads, which is a question about what this account holds.
    let groups = match &plan {
        Plan::Pipeline { stages, .. } => {
            resolve_groups(store, &pipeline::source_selectors(stages), &query.log_group_names)
        }
        // The `FROM` clause IS where a SQL statement names the log groups it reads, so what
        // it names is what the statement reads — a clause naming a log group this account
        // does not hold reads no events rather than falling back to the request's members.
        Plan::Sql(parsed) => match sql::from_clause_groups(parsed) {
            Ok(selectors) => selected_groups(store, &selectors),
            Err(failure) => return unrunnable(failure.reason),
        },
        Plan::Unrunnable(_) => Vec::new(),
    };
    let mut scan = scan(store, &groups, query);

    // A `lookup` stage joins the rows of one of this account's lookup tables onto each
    // record, so the tables it names are read here too — the join itself then needs nothing
    // but what this carries.
    if let Plan::Pipeline { stages, .. } = &plan {
        for name in pipeline::lookup_table_names(stages) {
            if let Some(table) = store.lookup_tables.get(&name) {
                scan.lookup_tables
                    .insert(name, table.table_body.clone());
            }
        }
    }

    Prepared {
        plan,
        scan,
        query: query.clone(),
    }
}

/// Run a prepared query, answering its rows and the counts over the run.
///
/// Reached with this service's state RELEASED (see [`Prepared`]): everything the run needs is
/// in hand, so one caller's query neither holds the store nor waits on it. The run spends a
/// [`Budget`] — expression evaluations, computed bytes and wall-clock time — and yields as it
/// goes, so a cancelled or timed-out request has somewhere to land and a query that asks for
/// more than the budget is abandoned rather than run to the end.
pub async fn run(prepared: Prepared) -> Execution {
    let Prepared { plan, scan, query } = prepared;
    let budget = Budget::new();
    match plan {
        Plan::Unrunnable(reason) => Execution {
            failed: Some(reason),
            records_scanned: scan.scanned as f64,
            bytes_scanned: scan.bytes as f64,
            log_groups_scanned: scan.groups as f64,
            ..Execution::default()
        },
        Plan::Pipeline { dialect, stages } => {
            pipeline::run(dialect, &stages, scan, &query, &budget).await
        }
        Plan::Sql(parsed) => sql::run(&parsed, scan, &query, &budget).await,
    }
}

/// OpenSearch PPL, as the model's `QueryLanguage` enum spells it.
pub const QUERY_LANGUAGE_PPL: &str = "PPL";

/// OpenSearch SQL, as the model's `QueryLanguage` enum spells it.
pub const QUERY_LANGUAGE_SQL: &str = "SQL";

/// The log groups one run reads and the records it read out of them.
#[derive(Debug, Clone, Default)]
pub struct Scan {
    /// The records, newest event first.
    pub records: Vec<Record>,
    /// How many events were read.
    pub scanned: usize,
    /// How many message bytes those events carry.
    pub bytes: usize,
    /// How many log groups were read.
    pub groups: usize,
    /// The CSV body of each lookup table the pipeline's `lookup` stages name, for the tables
    /// this account holds.
    pub lookup_tables: BTreeMap<String, String>,
}

/// Read the records of `groups` whose events fall inside the query's time range.
///
/// The range is the one `StartQuery` was given, in the epoch SECONDS that operation
/// documents, and both of its ends are read: "The range is inclusive, so the specified end
/// time is included in the query".
pub fn scan(store: &State, groups: &[String], query: &QueryRecord) -> Scan {
    let start_ms = query.start_time_secs.saturating_mul(MILLIS_PER_SECOND);
    let end_ms = query.end_time_secs.saturating_mul(MILLIS_PER_SECOND);
    let account = ::engine::emulator_account_id();
    // Every event of the window, newest first: a stream keeps its events sorted by
    // `(timestamp, ingestion_seq)`, so the window is one contiguous run per stream, found by
    // two binary searches and then merged across the streams of every group read.
    let mut selected: Vec<(i64, u64, &str, &str, &super::StoredEvent)> = Vec::new();
    let mut groups_read = 0usize;
    for name in groups {
        let Some(group) = store.log_groups.get(name) else {
            continue;
        };
        groups_read = groups_read.saturating_add(1);
        for stream in group.streams.values() {
            let from = stream
                .events
                .partition_point(|event| event.timestamp < start_ms);
            let until = stream
                .events
                .partition_point(|event| event.timestamp <= end_ms);
            for event in &stream.events[from..until.max(from)] {
                selected.push((
                    event.timestamp,
                    event.ingestion_seq,
                    group.name.as_str(),
                    stream.name.as_str(),
                    event,
                ));
            }
        }
    }
    selected.sort_by(|left, right| {
        right
            .0
            .cmp(&left.0)
            .then_with(|| right.1.cmp(&left.1))
            .then_with(|| left.2.cmp(right.2))
            .then_with(|| left.3.cmp(right.3))
    });

    let mut scan = Scan {
        groups: groups_read,
        ..Scan::default()
    };
    for (timestamp, seq, group, stream, event) in selected {
        if scan.scanned >= MAX_SCANNED_EVENTS || scan.bytes >= MAX_SCANNED_BYTES {
            break;
        }
        scan.scanned = scan.scanned.saturating_add(1);
        scan.bytes = scan.bytes.saturating_add(event.message.len());
        scan.records
            .push(record_of(group, stream, event, timestamp, seq, account));
    }
    scan
}

/// The record one stored log event becomes: the generated fields, plus the keys its message
/// names when the message is a JSON object.
fn record_of(
    group: &str,
    stream: &str,
    event: &super::StoredEvent,
    timestamp_ms: i64,
    seq: u64,
    account: &str,
) -> Record {
    let mut record = Record::default();
    record.set(
        FIELD_PTR,
        log_record_pointer(group, stream, timestamp_ms, seq),
    );
    record.set(FIELD_TIMESTAMP, format_timestamp(timestamp_ms));
    record.set(FIELD_MESSAGE, event.message.clone());
    record.set(FIELD_LOG_STREAM, stream);
    // "@log — a log group identifier … in the form of account-id:log-group-name."
    record.set(FIELD_LOG, format!("{account}:{group}"));
    record.set(FIELD_INGESTION_TIME, format_timestamp(event.ingestion_time));
    // Only a JSON OBJECT names fields: a message that is bare text, or a bare JSON scalar or
    // array, is readable as `@message` alone.
    if let Ok(::serde_json::Value::Object(members)) =
        ::serde_json::from_str::<::serde_json::Value>(&event.message)
    {
        for (key, value) in &members {
            if record.values.len() >= MAX_FIELDS_PER_EVENT {
                break;
            }
            flatten_json(key, value, 1, &mut record);
        }
    }
    record
}

/// Flatten one JSON member into the fields it contributes, under the name `path` it is
/// reached by: a nested object contributes `parent.child`, a list contributes `parent.0`, and
/// a scalar contributes its own path. A container contributes no value of its own, so an
/// empty object or list adds nothing.
fn flatten_json(path: &str, value: &::serde_json::Value, depth: usize, into: &mut Record) {
    if into.values.len() >= MAX_FIELDS_PER_EVENT {
        return;
    }
    match value {
        ::serde_json::Value::Object(members) if depth < MAX_FIELD_DEPTH => {
            for (key, member) in members {
                if into.values.len() >= MAX_FIELDS_PER_EVENT {
                    break;
                }
                flatten_json(&format!("{path}.{key}"), member, depth + 1, into);
            }
        }
        ::serde_json::Value::Array(items) if depth < MAX_FIELD_DEPTH => {
            for (index, item) in items.iter().enumerate() {
                if into.values.len() >= MAX_FIELDS_PER_EVENT {
                    break;
                }
                flatten_json(&format!("{path}.{index}"), item, depth + 1, into);
            }
        }
        // A string keeps its own text; every other scalar is rendered the way JSON writes
        // it, which is how a number or a boolean reads back as the value of a field.
        ::serde_json::Value::String(text) => into.set(path, text.clone()),
        other => into.set(path, other.to_string()),
    }
}

/// How a result renders a timestamp: the instant in UTC, to the millisecond, with a space
/// between the date and the time — the form a Logs Insights result carries `@timestamp` and
/// `@ingestionTime` in, which is a TEXT value like every other result field.
pub fn format_timestamp(millis: i64) -> String {
    ::chrono::DateTime::<::chrono::Utc>::from_timestamp_millis(millis)
        .map(|instant| instant.format(TIMESTAMP_FORMAT).to_string())
        .unwrap_or_default()
}

/// The rendering [`format_timestamp`] writes: `YYYY-MM-DD hh:mm:ss.mmm`, in UTC.
const TIMESTAMP_FORMAT: &str = "%Y-%m-%d %H:%M:%S%.3f";

/// The instant a rendered timestamp stands for, in epoch milliseconds — the reading
/// [`format_timestamp`] is undone by, so a stage that orders or compares timestamps works on
/// the instant rather than on its text.
pub fn parse_timestamp(rendered: &str) -> Option<i64> {
    ::chrono::NaiveDateTime::parse_from_str(rendered, TIMESTAMP_FORMAT)
        .ok()
        .map(|instant| instant.and_utc().timestamp_millis())
}

/// The kind tag a log record pointer carries, so a pointer is told apart from any other
/// opaque token this service mints.
const POINTER_KIND: &str = "LogRecordPointer";

/// The `@ptr` of one log event: "the identifier for the log record. You can use the value of
/// @ptr in a GetLogRecord operation to get the full log record" (`GetQueryResults`).
///
/// A pointer therefore has to address ONE event in this store, which the log group, the log
/// stream and the event's own position in that stream's order (its timestamp and ingestion
/// sequence — `crate::state::EventKey`) do uniquely. The payload is encoded the way this
/// service encodes every opaque token ([`crate::state::encode_token`]), so a client only ever
/// round-trips it.
pub fn log_record_pointer(group: &str, stream: &str, timestamp_ms: i64, seq: u64) -> String {
    super::encode_token(&::serde_json::json!({
        "kind": POINTER_KIND,
        "logGroupName": group,
        "logStreamName": stream,
        "timestamp": timestamp_ms,
        "seq": seq,
    }))
}

/// What one log record pointer addresses.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LogRecordPointer {
    /// The log group holding the event.
    pub log_group_name: String,
    /// The log stream holding it.
    pub log_stream_name: String,
    /// The event's timestamp, in epoch milliseconds.
    pub timestamp_ms: i64,
    /// The event's ingestion sequence number, which orders events sharing a timestamp.
    pub seq: u64,
}

/// Read a pointer [`log_record_pointer`] minted. `None` for anything else, which a reader
/// refuses as an invalid `logRecordPointer`.
pub fn log_record_pointer_parts(pointer: &str) -> Option<LogRecordPointer> {
    let value = super::decode_token(pointer)?;
    if value.get("kind")?.as_str()? != POINTER_KIND {
        return None;
    }
    Some(LogRecordPointer {
        log_group_name: value.get("logGroupName")?.as_str()?.to_string(),
        log_stream_name: value.get("logStreamName")?.as_str()?.to_string(),
        timestamp_ms: value.get("timestamp")?.as_i64()?,
        seq: value.get("seq")?.as_u64()?,
    })
}

/// What a well-formed log record pointer addresses that this store no longer holds, so a
/// reader of one log event ([`pointed_record`]) can name the missing resource.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PointerMiss {
    /// The log group the pointer names is not one this account holds.
    LogGroup,
    /// The log group is held, but not the log stream the pointer names.
    LogStream,
    /// Both are held, but the stream no longer carries the event the pointer addresses.
    LogRecord,
}

impl PointerMiss {
    /// The resource KIND the refusal states, for the sentence every operation of this service
    /// refuses a missing resource with ([`super::resource_not_found_message`]).
    pub fn resource_kind(self) -> &'static str {
        match self {
            Self::LogGroup => "log group",
            Self::LogStream => "log stream",
            Self::LogRecord => "log record",
        }
    }
}

/// The WHOLE record of the one log event a pointer addresses: "All fields are retrieved, even
/// if the original query that produced the logRecordPointer retrieved only a subset of fields"
/// (`GetLogRecord`).
///
/// It is the same record a query reads that event as ([`record_of`]), so a field a query's row
/// reports and the same field of the whole record carry one value, and the record's `@ptr` is
/// the pointer it was reached by. Reading it changes nothing a later caller sees.
pub fn pointed_record(store: &State, pointer: &LogRecordPointer) -> Result<Record, PointerMiss> {
    let group = store
        .log_groups
        .get(&pointer.log_group_name)
        .ok_or(PointerMiss::LogGroup)?;
    let stream = group
        .streams
        .get(&pointer.log_stream_name)
        .ok_or(PointerMiss::LogStream)?;
    // A stream's events are stored in their total order ([`crate::state::EventKey`]), so the
    // one event a pointer addresses is found by one binary search — and an event the stream no
    // longer holds is found by nothing.
    let wanted = super::EventKey {
        timestamp: pointer.timestamp_ms,
        seq: pointer.seq,
    };
    let at = stream
        .events
        .binary_search_by(|event| event.key().cmp(&wanted))
        .map_err(|_| PointerMiss::LogRecord)?;
    let event = &stream.events[at];
    Ok(record_of(
        &group.name,
        &stream.name,
        event,
        event.timestamp,
        event.ingestion_seq,
        ::engine::emulator_account_id(),
    ))
}

/// The record one of this account's QUERY RESULT SETS holds under `pointer`, if any holds it.
///
/// "You can use the value of @ptr in a GetLogRecord operation to get the full log record"
/// (`GetQueryResults`): a query hands a pointer out with the rows it produced, and the result
/// set holds the records those rows point at ([`Execution::records`]) — so the pointer keeps
/// addressing the record its query read even once the log group, the log stream or the event
/// itself is gone from the store. A pointer no result set holds addresses only what the store
/// still holds ([`pointed_record`]).
///
/// The lookup is over the queries this account holds, which the store itself caps
/// ([`super::MAX_QUERIES`]), and a query whose results have been dropped holds nothing.
pub fn result_set_record(store: &State, pointer: &str) -> Option<Record> {
    store.queries.values().find_map(|query| {
        query
            .snapshot
            .as_ref()
            .and_then(|snapshot| snapshot.records.get(pointer).cloned())
    })
}

/// The log groups a query reads: the ones its own source selector names when it carries one,
/// and otherwise the ones the start resolved from the request.
///
/// A query that selects its own sources OVERRIDES the request's members, because the
/// selector is part of the query itself: "the queryString must include a SOURCE command to
/// select log groups for the query" (`StartQuery`), and the SQL languages "specify the log
/// group names inside the querystring instead of here"
/// (`StartQuery$logGroupIdentifiers`).
pub fn resolve_groups(store: &State, selected: &[GroupSelector], fallback: &[String]) -> Vec<String> {
    if selected.is_empty() {
        return fallback.to_vec();
    }
    // A selector that names no log group of this account selects nothing of its own, so the
    // query reads the log groups the START resolved: only a SQL query names the log groups
    // to read in its query string instead of in the request, so for every other language the
    // request's own members are what the query was started over.
    let names: Vec<String> = selected_groups(store, selected)
        .into_iter()
        .filter(|name| store.log_groups.contains_key(name))
        .collect();
    if names.is_empty() {
        return fallback.to_vec();
    }
    names
}

/// The log groups `selected` names, and nothing else — what a SQL statement's `FROM` clause
/// resolves to, because that clause IS where such a statement names the log groups it reads.
pub fn selected_groups(store: &State, selected: &[GroupSelector]) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    for selector in selected {
        match selector {
            GroupSelector::Name(identifier) => {
                let name = super::log_group_name_from_identifier(identifier).to_string();
                if !names.contains(&name) {
                    names.push(name);
                }
            }
            GroupSelector::NamePrefix(prefix) => {
                for name in store.log_groups.keys() {
                    if name.starts_with(prefix.as_str()) && !names.contains(name) {
                        names.push(name.clone());
                    }
                }
            }
        }
    }
    names
}

/// One way a query's own source selector names log groups.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GroupSelector {
    /// One log group, by name or by either ARN form of one
    /// (`crate::state::log_group_name_from_identifier`).
    Name(String),
    /// Every log group whose name starts with this, which is what `logGroups(namePrefix:
    /// [...])` selects.
    NamePrefix(String),
}

/// Read a source selector's text as the log groups it names.
///
/// The forms are the ones the `SOURCE` command takes: a list of log groups named directly,
/// and `logGroups(namePrefix: ["…"], …)`, which "can select log groups based on log group
/// name prefix, account ID, and log class" — the prefixes select, and a key this service does
/// not resolve against state (an account id, a log class) selects nothing of its own and is
/// skipped rather than making the query unrunnable.
pub fn read_group_selectors(text: &str) -> Vec<GroupSelector> {
    let mut selectors: Vec<GroupSelector> = Vec::new();
    let mut rest = text.trim();
    // `logGroups(...)`: the keys inside the brackets select, so the bracketed text is read
    // key by key and everything outside it is read as a name list.
    while let Some(open) = rest.find('(') {
        let keyword = rest[..open].trim();
        let selector_call = keyword
            .rsplit(|character: char| character.is_whitespace() || character == '=')
            .next()
            .unwrap_or_default()
            .eq_ignore_ascii_case(LOG_GROUPS_SELECTOR);
        let Some(close) = rest[open..].find(')').map(|at| open + at) else {
            break;
        };
        if selector_call {
            for (key, values) in read_selector_keys(&rest[open + 1..close]) {
                // A key names itself in the singular or the plural, and selects by prefix or
                // by identifier; a key this service does not resolve against state (an
                // account id, a log class) selects nothing of its own.
                let key = key.trim_end_matches('s').to_string();
                if key.eq_ignore_ascii_case(NAME_PREFIX_KEY) {
                    selectors.extend(values.into_iter().map(GroupSelector::NamePrefix));
                } else if key.eq_ignore_ascii_case(LOG_GROUP_IDENTIFIER_KEY)
                    || key.eq_ignore_ascii_case(LOG_GROUP_NAME_KEY)
                {
                    selectors.extend(values.into_iter().map(GroupSelector::Name));
                }
            }
            // The text before the call is the keyword itself, so only what follows the call
            // can still name groups.
            rest = &rest[close + 1..];
            continue;
        }
        rest = &rest[close + 1..];
    }
    // Whatever is left names log groups directly: `SOURCE 'a', 'b'`.
    for token in rest.split(',') {
        let name = trim_identifier(token);
        if !name.is_empty() {
            selectors.push(GroupSelector::Name(name.to_string()));
        }
    }
    selectors
}

/// The function a query's source selector calls to select log groups by their properties.
const LOG_GROUPS_SELECTOR: &str = "loggroups";

/// The key of that call that selects by name prefix.
const NAME_PREFIX_KEY: &str = "nameprefix";

/// The key that names log groups by identifier.
const LOG_GROUP_IDENTIFIER_KEY: &str = "loggroupidentifier";

/// The key that names them by name.
const LOG_GROUP_NAME_KEY: &str = "loggroupname";

/// The `key: [value, …]` pairs of a selector call's argument text, each key with the values
/// it was given. A key given one value without brackets carries that one value.
fn read_selector_keys(arguments: &str) -> Vec<(String, Vec<String>)> {
    let mut keys: Vec<(String, Vec<String>)> = Vec::new();
    let mut rest = arguments;
    while let Some(colon) = rest.find(':') {
        let key = rest[..colon]
            .trim()
            .trim_start_matches(',')
            .trim()
            .to_string();
        let after = &rest[colon + 1..];
        let (values, next) = if let Some(open) = after.find('[') {
            match after[open..].find(']') {
                Some(close) => (
                    after[open + 1..open + close]
                        .split(',')
                        .map(trim_identifier)
                        .filter(|value| !value.is_empty())
                        .map(ToString::to_string)
                        .collect::<Vec<String>>(),
                    &after[open + close + 1..],
                ),
                None => (Vec::new(), ""),
            }
        } else {
            let end = after.find(',').unwrap_or(after.len());
            let value = trim_identifier(&after[..end]);
            (
                if value.is_empty() {
                    Vec::new()
                } else {
                    vec![value.to_string()]
                },
                &after[end..],
            )
        };
        if !key.is_empty() {
            keys.push((key, values));
        }
        rest = next;
    }
    keys
}

/// One identifier as a query string writes it, with the quoting a query may wrap it in — a
/// quoted string, a double-quoted or back-quoted identifier — taken off.
pub fn trim_identifier(token: &str) -> &str {
    token
        .trim()
        .trim_matches(|character| matches!(character, '"' | '\'' | '`'))
        .trim()
}
