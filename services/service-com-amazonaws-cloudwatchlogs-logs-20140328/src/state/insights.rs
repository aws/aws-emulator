//! RUNNING a CloudWatch Logs Insights query over the log events this service stores, which
//! is what `GetQueryResults` reports ("Returns the results from the specified query").
//!
//! A query is started by `StartQuery` and stored as a [`crate::state::QueryRecord`]: the
//! query string, the log groups it reads and the time range it reads them over. Running it
//! means turning the stored log events of those groups, inside that range, into RECORDS of
//! field/value pairs and then applying the query to them — so every value a result carries
//! is computed from an event this store holds, and a query over a group nothing was ingested
//! into answers no rows rather than invented ones.
//!
//! ## The record one log event becomes
//!
//! Each event carries the fields "generated by CloudWatch Logs" ([`GENERATED_FIELDS`]) and,
//! when its message is a JSON object, the keys discovered in that object — the same
//! discovery `GetLogGroupFields` and `GetLogFields` report, flattened to the dotted paths
//! those operations name. `@ptr` is minted here: it is "the identifier for the log record",
//! and "the value of @ptr in a GetLogRecord operation" is what retrieves the whole event
//! back, so it carries exactly what addressing one event needs
//! ([`log_record_pointer`]).
//!
//! ## The three query languages
//!
//! `StartQuery` takes "Logs Insights QL, OpenSearch PPL, and OpenSearch SQL"
//! (`QueryLanguage`). The first two are PIPELINES — commands separated by `|`, each reading
//! the records the previous one produced — so both run through [`pipeline`], over the same
//! records, with only their command vocabulary differing. SQL is a `SELECT` over the log
//! groups its `FROM` clause names, so it is parsed as SQL and evaluated in [`sql`].
//!
//! ## What bounds one run
//!
//! The query string is `@length(0..10000)` (`QueryString`), and the records one run reads
//! are capped at [`MAX_SCANNED_EVENTS`] events and [`MAX_SCANNED_BYTES`] message bytes, the
//! newest of the window first. Every stage then works over that bounded set, and the rows a
//! run answers are capped at [`MAX_RESULT_ROWS`] — the most "log event results from a query"
//! the API hands back.
//!
//! Those bound each FACTOR; the [`Budget`] bounds their product. One run may spend only so
//! many expression evaluations ([`MAX_EXECUTION_STEPS`]), so many computed bytes
//! ([`MAX_VALUE_BYTES`] for one value, [`MAX_COMPUTED_BYTES`] in all) and so much wall-clock
//! time ([`MAX_EXECUTION_TIME`]); a run that asks for more is ABANDONED and reports the
//! `Failed` status of an execution that produced nothing. The run also yields as it goes, so
//! a cancelled or timed-out request has somewhere to land.

