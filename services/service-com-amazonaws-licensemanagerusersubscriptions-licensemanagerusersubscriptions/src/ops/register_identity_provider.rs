//! @op RegisterIdentityProvider
//!
//! Registers an identity provider for a user-based subscription product and persists it
//! in [`crate::state`], so `ListIdentityProviders`, `StartProductSubscription` and
//! `DeregisterIdentityProvider` all resolve the same record.
//!
//! The registration is returned in the non-terminal `REGISTERING` status; the
//! `REGISTERED` transition is owed by the clock (see `crate::state::materialise_due`)
//! and materialises on any later read.
//!
//! The record is stored through `crate::state::insert_identity_provider`, the one writer
//! for a registration, so this call also recomputes what the instances associated through
//! the same directory provide: `InstanceSummary.Products` is read from the directory's
//! registrations, so adding one changes those views just as deregistering one does.
//!
//! `Settings` is NOT `@required` in the request, so a registration that omits it is
//! accepted: what the caller supplied is persisted as supplied, and a registration that
//! supplied none carries no subnet and no security group — the configuration a product
//! whose licensing goes through a license server endpoint needs no VPC endpoints for.
//! The summary reports exactly that empty configuration; nothing is invented for it.
//!
//! What a supplied `Settings` names, though, has to EXIST: the registration creates the
//! activation-server VPC endpoints in those subnets with that security group, so each id
//! is resolved against what the account has, asked of the service that owns those
//! resources ([`crate::state::ec2_fleet::resolve_settings_network`]), and a request naming
//! a network resource the account does not have, or mixing resources of two VPCs, is
//! refused. The subnets a self-managed Active Directory's
//! `DomainNetworkSettings.Subnets` names are resolved against the same owner, by the same
//! existence rule ([`crate::state::ec2_fleet::resolve_domain_subnets`]).
//!
//! Two request values are refused here that no modelled constraint can express:
//!
//! * `Product` is modelled as a plain `String`, but its documentation lists the only
//!   values it admits, so a value outside [`crate::state::PRODUCTS`] is refused naming the
//!   value that was sent.
//! * `ActiveDirectoryIdentityProvider.DirectoryId` names a directory of this account in
//!   AWS Directory Service: registering an identity provider for a directory the account
//!   does not have would mint a provider every later subscription flow would build on.
//!   The id is resolved against the directories the account HAS, read off the record the
//!   plane that creates directories publishes
//!   ([`crate::state::ad_directory_fleet::resolves_active_directory`]), and one that is
//!   absent, or not yet in service, is refused naming the requested id — so a directory a
//!   client created with `ds:CreateDirectory` or `ds:CreateMicrosoftAD` is registrable once
//!   it is built, and one it deleted stops being registrable at once. A provider the request
//!   marks `IsSharedActiveDirectory`, one whose id takes the `sd-` form, and one that names
//!   no `DirectoryId` at all are not directories of this account's OWN fleet, so that fleet
//!   is not what decides them: this check does not apply to them and the registration goes
//!   on. What would decide a shared directory is `ds:DescribeSharedDirectories`, still a
//!   scaffolded 501 in the Directory Service emulator, and a self-managed Active Directory
//!   is no Directory Service resource at all.
//!
//! A self-managed Active Directory's `ActiveDirectorySettings.DomainCredentialsProvider`
//! names a Secrets Manager secret of the account the same way — the credentials "needed for
//! user administration in the Active Directory" — and this service creates no secret, so it
//! is resolved against the service that owns secrets by that same existence rule
//! ([`crate::state::credentials_secret::resolve_domain_credentials`]).
//!
//! The directory is resolved BEFORE the network resources a supplied `Settings` names: the
//! registration is for that directory, so a request that gets both wrong is refused for
//! the directory — the prerequisite a caller has to fix first is the one it is told about.
//!
