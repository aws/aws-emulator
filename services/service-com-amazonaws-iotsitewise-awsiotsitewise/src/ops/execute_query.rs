impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ExecuteQuery<Eng>
{
    type Input = ExecuteQueryInput;
    type Output = ExecuteQueryOutput;
    type Error = ExecuteQueryError;

    const NAME: &'static str = "ExecuteQuery";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_QUERY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_QUERY_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            ExecuteQueryError::Modeled(ExecuteQueryErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;

        // The statement is parsed, planned and RUN by [`run_statement`], this
        // service's one query engine. `StartQuery` runs the statements of a
        // workspace's asynchronous queries through that same entry point, so neither
        // operation can answer a statement the other refuses, or read rows the other
        // cannot.
        let result = run_statement(&state, &input.query_statement).await?;

        // Paging over the computed result: `nextToken` is the index of the first row
        // of the next page beside the enumeration that index counts in, hex-encoded
        // (the member carries no pattern, and hex keeps it to the same alphabet
        // every other token this service issues uses). The enumeration here is the
        // rows the STATEMENT this request carries answers, so a token minted while
        // paging another statement — or by the operation that pages a stored query's
        // rows — names no page of this one and is refused rather than silently
        // resuming this result at that other enumeration's position. WHICH offsets of
        // its OWN enumeration this operation accepts is its own question, answered
        // below: a token is issued only for a row this result HAS, so an offset at or
        // past the end is one it never issued — including every offset at all for a
        // statement that answers no rows — and is refused rather than answered with
        // an empty page, which would report absence as success.
        let scope = RowPageScope::of_statement(&input.query_statement);
        let start = match input.next_token.as_deref() {
            Some(token) => {
                let resume = decode_token(token, &scope)?;
                if resume >= result.rows.len() {
                    return Err(invalid_token());
                }
                resume
            }
            None => 0,
        };
        let max_results = input
            .max_results
            .unwrap_or(DEFAULT_MAX_RESULTS)
            .clamp(1, MAX_ROWS_PER_PAGE) as usize;
        let end = start.saturating_add(max_results).min(result.rows.len());
        let next_token = (end < result.rows.len()).then(|| encode_row_offset(end, &scope));

        Ok(ExecuteQueryOutput {
            columns: Some(
                result
                    .columns
                    .iter()
                    .map(|(name, scalar_type)| ColumnInfo {
                        name: Some(name.clone()),
                        r#type: Some(ColumnType {
                            scalar_type: Some((*scalar_type).to_string()),
                        }),
                    })
                    .collect(),
            ),
            rows: Some(
                result.rows[start..end]
                    .iter()
                    .map(|row| Row {
                        data: row.iter().map(Cell::datum).collect(),
                    })
                    .collect(),
            ),
            next_token,
        })
    }
}

/// Parse `statement`, plan it and run it over the store, answering the rows it
/// computes and what the run COST.
///
/// This is this service's query engine, entered here by every operation that runs a
/// caller's SQL: `ExecuteQuery`, which answers the rows synchronously, `StartQuery`,
/// which runs the statement of a workspace's asynchronous query, and
/// `GetQueryResults`, which answers the rows of one such query. One entry point
/// rather than three, so each admits the same statements, over the same views, under
/// the same budget.
///
/// The statement is SQL, so it goes through a real SQL parser (the `sqlparser`
/// crate) rather than being matched on as text: a statement the parser cannot read
/// is a syntax error, which is the request being invalid.
///
/// How big a TREE the statement may build is bounded before the parser sees it, by
/// three measures taken off the statement's TOKENS — the same lexer the parser
/// itself runs, so no string, delimited identifier or comment can desynchronise the
/// measures from what the parse will see ([`parse_nesting`]): how deeply it nests,
/// how many keywords that nest without a bracket it carries, and how many operators
/// it chains. The third is what bounds the shape neither of the others sees — a
/// left-associative chain (`1+1+1+…`) needs no bracket and no keyword, and the
/// parser builds it iteratively, so nothing in the parse refuses it while the TREE
/// it produces is as deep as the chain is long. Past any of the three the statement
/// is refused with a modelled error and no tree is built at all, so neither the
/// parse, nor the move into the task below, nor the drop of the tree can walk
/// deeper than this service allows. The parser is given the nesting limit too, as a
/// second line of defence.
///
/// Failures are reported in `ExecuteQuery`'s own error channel, because the engine
/// lives in that operation's file; a caller whose channel is a different one asks
/// [`classify`] which kind of failure it is holding.
pub(crate) async fn run_statement(
    state: &::engine::ServiceState<crate::state::ComAmazonawsIotsitewiseAwsiotsitewiseState>,
    statement: &str,
) -> Result<QueryRun, ExecuteQueryError> {
    let dialect = ::sqlparser::dialect::GenericDialect {};
    let nesting = parse_nesting(&dialect, statement)?;
    if nesting.nesting > MAX_PARSE_DEPTH {
        return Err(invalid_request(format!(
            "The query statement nests {} expressions, which is more than the \
             {MAX_PARSE_DEPTH} levels this service parses.",
            nesting.nesting
        )));
    }
    if nesting.prefix_forms > MAX_PREFIX_FORMS {
        return Err(invalid_request(format!(
            "The query statement carries {} of the keywords that nest without a \
             bracket, which is more than the {MAX_PREFIX_FORMS} this service parses.",
            nesting.prefix_forms
        )));
    }
    if nesting.operators > MAX_OPERATORS {
        return Err(invalid_request(format!(
            "The query statement chains {} operators, which is more than the \
             {MAX_OPERATORS} this service parses.",
            nesting.operators
        )));
    }
    let mut statements = {
        let mut parser = ::sqlparser::parser::Parser::new(&dialect)
            .with_recursion_limit(MAX_PARSE_DEPTH)
            .try_with_sql(statement)
            .map_err(|error| invalid_request(format!("Invalid query statement: {error}")))?;
        // The parser itself is dropped here, before anything is awaited: it
        // borrows the dialect and is not `Send`, and the parsed statements are
        // all the rest of this run needs.
        parser
            .parse_statements()
            .map_err(|error| invalid_request(format!("Invalid query statement: {error}")))?
    };
    if statements.len() != 1 {
        return Err(invalid_request(format!(
            "A query statement carries exactly one statement, but this one carries {}.",
            statements.len()
        )));
    }
    // A query READS asset data; nothing else is a statement this engine runs,
    // so anything that is not a query is an invalid query statement. Taken by
    // VALUE, so the tree moves into the blocking task below instead of being
    // cloned into it.
    let ::sqlparser::ast::Statement::Query(query) = statements.remove(0) else {
        return Err(invalid_request(
            "A query statement must be a SELECT query.".to_string(),
        ));
    };
    let owned = *query;

    // Every step of the run is charged against ONE budget: a wall-clock deadline,
    // a row-work step budget and an expression-depth ceiling.
    let budget = Budget::new();
    // Everything that depends only on the STATEMENT is decided before the store is
    // read: `plan` refuses a clause this engine does not run and answers which
    // relations the statement names — its own, its joins' and its subqueries' — so a
    // statement it cannot plan never takes the shared state lock at all.
    let views = plan(&owned)?;
    // How long the run takes is MEASURED from here — the instant the store is first
    // read — to the instant the interpretation answers, because that span is the
    // work the engine did and is what a query's reported execution time is.
    let started = ::std::time::Instant::now();
    // The store is held only while the rows of those relations are copied off it.
    // Joining, filtering, grouping, ordering and projecting then run WITHOUT the
    // shared state lock, so no query can hold it for the length of its own
    // interpretation.
    let catalog = {
        let store = state.lock();
        snapshot(&store, &views, &budget)?
    };
    // How many BYTES of stored cells the run read, summed off the rows themselves
    // before they move into the task below, so it is what this run actually scanned
    // rather than a figure standing in for it; `Cell::chars` answers a cell's BYTE
    // length (see its own documentation), which is what a `bytesScanned` figure is
    // reported in.
    let bytes_scanned = catalog.bytes_held();
    // The interpretation itself is CPU-bound and synchronous, so it runs on a
    // blocking worker under a wall-clock timeout rather than on the async
    // runtime's: a request that spends its whole budget cannot pin a runtime
    // worker, and this call has somewhere to land when it is cancelled or the
    // server is shutting down. The statement and the rows it reads both MOVE into
    // the task.
    let result = ::tokio::time::timeout(
        MAX_QUERY_TIME,
        ::tokio::task::spawn_blocking(move || run_query(&owned, &catalog, &budget, 0)),
    )
    .await
    .map_err(|_| {
        query_timeout(format!(
            "The query ran for longer than {} seconds without finishing.",
            MAX_QUERY_TIME.as_secs()
        ))
    })?
    .map_err(|_| {
        ExecuteQueryError::Modeled(ExecuteQueryErrorModeled::InternalFailureException(
            InternalFailureException {
                message: "the query could not be run".to_string(),
            },
        ))
    })??;

    Ok(QueryRun {
        columns: result
            .columns
            .iter()
            .map(|column| (column.name.clone(), column.scalar_type))
            .collect(),
        rows: result.rows,
        bytes_scanned: u64::try_from(bytes_scanned).unwrap_or(u64::MAX),
        elapsed: started.elapsed(),
    })
}

/// What one run of a query statement produced: the result itself — the projected
/// columns and the rows — and what the run cost.
///
/// The cost is measured, not estimated: the bytes are summed off the rows the run
/// read off the store and the duration is the wall clock around the run. A caller
/// that reports a query's statistics reports these.
#[derive(Debug)]
pub(crate) struct QueryRun {
    columns: Vec<(String, &'static str)>,
    rows: Vec<Vec<Cell>>,
    bytes_scanned: u64,
    elapsed: ::std::time::Duration,
}

impl QueryRun {
    /// How many rows the statement answered.
    pub(crate) fn row_count(&self) -> u64 {
        u64::try_from(self.rows.len()).unwrap_or(u64::MAX)
    }

    /// How many rows this result HOLDS, in the type a slice index takes: the same
    /// number [`Self::row_count`] reports as the `Long` a statistic carries, so a
    /// caller's paging arithmetic is exact against the rows the result holds
    /// instead of against a conversion of that figure.
    pub(crate) fn rows_held(&self) -> usize {
        self.rows.len()
    }

    /// How many bytes of stored cells the run read off the store.
    pub(crate) fn bytes_scanned(&self) -> u64 {
        self.bytes_scanned
    }

    /// How long the run took, from the first read of the store to the answer.
    pub(crate) fn elapsed(&self) -> ::std::time::Duration {
        self.elapsed
    }

    /// The columns the statement projects: each the name the result reports it
    /// under and the `ScalarType` value of the type its cells carry.
    ///
    /// The engine names a column's type in ONE vocabulary (`ScalarType`); an
    /// operation whose own result member names it in another translates it where
    /// it serialises, so this answers what the engine computed and nothing else.
    pub(crate) fn columns(&self) -> &[(String, &'static str)] {
        &self.columns
    }

    /// The rows of this result inside `page`, each cell rendered as the text the
    /// wire carries for it and `None` for an absent value — which is what a null
    /// cell is.
    ///
    /// A range reaching past the end answers nothing, so a caller's own paging
    /// arithmetic cannot make this panic, and only the page asked for is
    /// rendered: the rest of the result is never copied.
    pub(crate) fn text_rows(&self, page: ::std::ops::Range<usize>) -> Vec<Vec<Option<String>>> {
        self.rows
            .get(page)
            .unwrap_or_default()
            .iter()
            .map(|row| row.iter().map(Cell::as_text).collect())
            .collect()
    }
}

/// Which kind of failure a [`run_statement`] error is, with the wording it carries.
///
/// The engine answers in `ExecuteQuery`'s error channel; an operation with a channel
/// of its own — a different error set, or an asynchronous query that reports a
/// failed RUN through its own status rather than through the response — needs to
/// know which kind it is holding without re-deciding the classification the engine
/// already made.
#[derive(Debug)]
pub(crate) enum QueryFailure<'a> {
    /// The statement is not one this service can answer at all: a syntax error, a
    /// view or column the catalog does not hold, a clause whose value is wrong, or a
    /// clause the query language this service answers does not carry.
    Invalid(&'a str),
    /// A construct the engine answered in the scaffold's 501 channel rather than
    /// with one of the operation's modelled errors.
    ///
    /// The engine itself produces NONE of these: a statement outside the query
    /// language is the modelled invalid request, because an error outside an
    /// operation's modelled set is one no generated client carries a class for. The
    /// channel can still carry a 501, so the classification stays total.
    Unsupported(&'a str),
    /// The statement outran the engine's budget, so the run did not finish.
    Timeout(&'a str),
    /// The run could not be carried out.
    Internal(&'a str),
}

/// Which [`QueryFailure`] `error` is. See that type.
pub(crate) fn classify(error: &ExecuteQueryError) -> QueryFailure<'_> {
    match error {
        ExecuteQueryError::NotImplemented(not_implemented) => {
            QueryFailure::Unsupported(&not_implemented.message)
        }
        ExecuteQueryError::ValidationException(validation) => {
            QueryFailure::Invalid(&validation.message)
        }
        ExecuteQueryError::Modeled(modeled) => match modeled {
            ExecuteQueryErrorModeled::InvalidRequestException(failure) => {
                QueryFailure::Invalid(&failure.message)
            }
            ExecuteQueryErrorModeled::ValidationException(failure) => {
                QueryFailure::Invalid(failure.message.as_deref().unwrap_or_default())
            }
            ExecuteQueryErrorModeled::QueryTimeoutException(failure) => {
                QueryFailure::Timeout(failure.message.as_deref().unwrap_or_default())
            }
            // The engine constructs none of the three below — it has no rate limit,
            // no identity check and nothing it declares unavailable — but a
            // classification has to be total, and each says the same thing to a
            // caller: the run could not be carried out.
            ExecuteQueryErrorModeled::InternalFailureException(failure) => {
                QueryFailure::Internal(&failure.message)
            }
            ExecuteQueryErrorModeled::ServiceUnavailableException(failure) => {
                QueryFailure::Internal(&failure.message)
            }
            ExecuteQueryErrorModeled::ThrottlingException(failure) => {
                QueryFailure::Internal(&failure.message)
            }
            ExecuteQueryErrorModeled::AccessDeniedException(failure) => {
                QueryFailure::Internal(failure.message.as_deref().unwrap_or_default())
            }
        },
    }
}

/// How many rows one page of a query's results carries when the caller gives no
/// `maxResults`, and the ceiling on how many THIS operation lets one ask for.
///
/// The emulator's own bound, not a published AWS default: this operation's
/// `maxResults` is modelled with a minimum of 1 and no maximum, so a response needs
/// a cap of its own for one call not to be able to serialise an unbounded result
/// set. Everything past a page is reachable through `nextToken`.
///
/// The DEFAULT is shared with the other operation that pages a query's rows
/// (`GetQueryResults`), so a client sees one page size whichever path it read the
/// rows of a query through, and the two cannot drift apart.
pub(crate) const DEFAULT_MAX_RESULTS: i32 = 250;
/// See [`DEFAULT_MAX_RESULTS`]. The ceiling is this operation's own, because the
/// member it bounds is the one modelled without a maximum of its own: the other
/// operation that pages a query's rows carries the model's `maxResults` range, which
/// the runtime enforces for it before its handler runs.
const MAX_ROWS_PER_PAGE: i32 = 1_000;

/// How many source rows' worth of WORK one query may do — the step budget this
/// query engine runs under, so no statement can walk the store without bound. Every
/// row read off the store, every row a predicate is evaluated against, every row a
/// sort pass compares and every row the projection rebuilds is charged against it,
/// and a statement that needs more is answered with the modelled
/// `QueryTimeoutException`, which is what IoT SiteWise declares for a query that
/// does not finish.
///
/// The emulator's own bound, like the duration beside it: a page of results is
/// bounded by `maxResults`, so this caps the work BEHIND one page.
const MAX_SCANNED_ROWS: usize = 20_000;

/// How long one query may run for. The wall-clock half of the budget, so a
/// statement whose cost is per row rather than per row COUNT (a long `LIKE`
/// pattern, a sort over the scan) still ends in the modelled
/// `QueryTimeoutException` rather than running on. The emulator's own bound.
const MAX_QUERY_TIME: ::std::time::Duration = ::std::time::Duration::from_secs(2);

/// How deep a caller-supplied statement may NEST, as the parser is told and as the
/// evaluator counts it.
///
/// Both halves are needed and they are deliberately different: the parser's limit
/// stops a deeply nested statement from being built at all, and the evaluator's own
/// ceiling (lower, so it is the one a statement meets first) stops a walk of an AST
/// this service did not parse itself from recursing without bound. Past either, the
/// statement is refused with a modelled error rather than consuming the stack.
const MAX_PARSE_DEPTH: usize = 100;
/// See [`MAX_PARSE_DEPTH`]. Higher than the parse bound because the walk this
/// counts is over an AST whose chains (`a AND b AND c …`) are as deep as they are
/// long, where the parse's own recursion is not: a predicate that is wide rather
/// than nested still runs.
const MAX_EXPRESSION_DEPTH: usize = 200;

/// How many keywords that nest WITHOUT a bracket ([`PREFIX_FORMS`]) one statement
/// may carry in total.
///
/// The nesting measure beside it counts a run of them in front of one expression;
/// this bounds the form that nests through them without a run — `CASE WHEN … THEN
/// CASE WHEN …`, which costs at least one such keyword per level — so neither shape
/// can drive the parse deeper than the parse is bounded to. Set above
/// [`MAX_PARSE_DEPTH`] because a statement that is WIDE in these keywords rather
/// than deep (a hundred separate `NOT`s joined by `AND`) nests no further than one.
const MAX_PREFIX_FORMS: usize = 150;

/// How deeply parsing `statement` can recurse and how big a tree it can build, as
/// three measures taken off its TOKENS: the deepest NESTING it reaches, how many
/// prefix forms it carries in total, and how many OPERATORS it chains.
///
/// The tokens come from the crate's own lexer
/// (`sqlparser::tokenizer::Tokenizer`), run with the same dialect the parse uses,
/// so the measures cannot disagree with the parse about what is structure and what
/// is not: a quoted string, a delimited identifier (whatever the dialect delimits
/// one with) and a comment are each ONE token (or whitespace) here, exactly as the
/// parser sees them, rather than something this file has to re-lex and could
/// desynchronise from. The statement is tokenised twice — once here, once inside
/// the parser — which is bounded work: `queryStatement` is modelled `@length
/// 1..10000`.
///
/// Measuring BEFORE the parse is the point: it bounds the work the parser will do,
/// and the size of the tree it hands back, so the depth a caller can drive this
/// service to — the parse, the move of the tree into the blocking task, its drop
/// and the evaluator's walk — is this service's bound and not an internal of the
/// crate that parses it.
///
/// `nesting` is the deepest the parse can descend at one point: open brackets that
/// are still open, plus the run of prefix forms ([`PREFIX_FORMS`]) immediately in
/// front of the expression being parsed — a chain of them (`NOT NOT NOT …`) descends
/// once per link. A statement that is WIDE rather than deep — a hundred separately
/// bracketed predicates joined by `AND` — closes each bracket before opening the
/// next, so it does not count as nested and is not refused.
///
/// `prefix_forms` is the TOTAL number of those keywords, which bounds the nesting a
/// form that needs no bracket to nest (`CASE WHEN … THEN CASE WHEN …`) can reach,
/// since each level costs at least one of them.
///
/// `operators` is the total number of operators, which bounds the depth of the one
/// shape the other two cannot see: a left-associative chain, which the parser builds
/// iteratively into a tree as deep as the chain is long (see [`MAX_OPERATORS`]).
/// Every token that is not a word, a literal, a bracket, a separator or whitespace
/// counts as one — so `+`, `<=`, `||` and `::` alike — beside the word forms
/// ([`OPERATOR_WORDS`]). Counting a separator-like token as an operator would only
/// refuse sooner, never later, so the bound cannot be slipped past by a token this
/// list does not name.
///
/// A statement the LEXER cannot read is a syntax error, and is refused as one.
fn parse_nesting(
    dialect: &dyn ::sqlparser::dialect::Dialect,
    statement: &str,
) -> Result<Nesting, ExecuteQueryError> {
    use ::sqlparser::tokenizer::{Token, Tokenizer};
    let tokens = Tokenizer::new(dialect, statement)
        .tokenize()
        .map_err(|error| invalid_request(format!("Invalid query statement: {error}")))?;
    let mut measured = Nesting {
        nesting: 0,
        prefix_forms: 0,
        operators: 0,
    };
    let mut depth = 0usize;
    // How many prefix forms stand, unbroken, in front of the expression being
    // parsed. Whitespace and comments do not break the run; anything else does.
    let mut run = 0usize;
    for token in tokens {
        match token {
            Token::Whitespace(_) | Token::EOF => continue,
            Token::LParen | Token::LBracket => depth += 1,
            Token::RParen | Token::RBracket => {
                depth = depth.saturating_sub(1);
                run = 0;
            }
            Token::Word(word) => {
                // A DELIMITED identifier is never a keyword, whatever it spells.
                let bare = word.quote_style.is_none();
                let upper = word.value.to_ascii_uppercase();
                if bare && PREFIX_FORMS.contains(&upper.as_str()) {
                    run += 1;
                    measured.prefix_forms += 1;
                } else {
                    run = 0;
                }
                if bare && OPERATOR_WORDS.contains(&upper.as_str()) {
                    measured.operators += 1;
                }
            }
            Token::Number(..)
            | Token::Char(_)
            | Token::SingleQuotedString(_)
            | Token::DoubleQuotedString(_)
            | Token::Comma
            | Token::SemiColon
            | Token::Period => run = 0,
            _ => {
                run = 0;
                measured.operators += 1;
            }
        }
        measured.nesting = measured.nesting.max(depth + run);
    }
    Ok(measured)
}

/// What [`parse_nesting`] measures of a statement.
#[derive(Debug)]
struct Nesting {
    nesting: usize,
    prefix_forms: usize,
    operators: usize,
}

/// The keywords that can open a sub-expression the parse descends into WITHOUT an
/// opening bracket of their own. The bracketed forms (`CAST(`, `IN (`, a function
/// call) need none of their own counting: their bracket is what [`parse_nesting`]
/// counts.
const PREFIX_FORMS: [&str; 3] = ["NOT", "CASE", "WHEN"];

/// The operators spelled as words rather than punctuation. Counted by
/// [`parse_nesting`] beside the punctuation ones, so a chain of either shape is
/// bounded by [`MAX_OPERATORS`].
///
/// The set-operation keywords are counted among them: each chains a tree the parser
/// builds ITERATIVELY — exactly the shape the nesting measure cannot see — and the
/// walk of that tree is as deep as the chain is long.
const OPERATOR_WORDS: [&str; 10] = [
    "AND",
    "OR",
    "IN",
    "LIKE",
    "BETWEEN",
    "IS",
    "UNION",
    "INTERSECT",
    "EXCEPT",
    "MINUS",
];

/// How many items one statement's projection may carry, and how many keys its
/// `ORDER BY` may name.
///
/// Both lists are the caller's to write and both multiply the work the engine does
/// per row — one pass over the rows per `ORDER BY` key, one rebuilt cell per
/// projection item per row — so each needs a ceiling of its own beside the row-work
/// budget. The emulator's own bounds, set far above any statement over views this
/// narrow (the widest view has nine columns).
const MAX_PROJECTION_ITEMS: usize = 64;
/// See [`MAX_PROJECTION_ITEMS`].
const MAX_ORDER_BY_KEYS: usize = 8;

/// How many levels of subquery one statement may nest: a `WITH` definition, a
/// relation in a `FROM` clause, a subquery in a predicate.
///
/// Each level is a relation computed in full before the level around it reads it, so
/// the depth bounds both the recursion of this engine's walk and how many relations
/// one statement can hold at once. The emulator's own bound.
const MAX_SUBQUERY_DEPTH: usize = 8;

/// How many relations one statement may JOIN, and how many a `WITH` clause may
/// define.
///
/// A join is a per-row MULTIPLIER — the pairs it considers are the product of its
/// two sides — so the count carries a ceiling of its own beside the row-work budget
/// that product is charged against. The emulator's own bounds.
const MAX_JOINS: usize = 8;
/// See [`MAX_JOINS`].
const MAX_CTES: usize = 8;

/// How many keys one `GROUP BY` may name. Each is evaluated once per row and enters
/// the key the rows are grouped by, so the list is a per-row multiplier the way the
/// `ORDER BY` is. The emulator's own bound.
const MAX_GROUP_BY_KEYS: usize = 8;

/// How many COLUMNS a result row may carry, once `*` has been expanded.
///
/// [`MAX_PROJECTION_ITEMS`] bounds the items a statement WRITES, which is not the
/// same count: a wildcard item stands for every column of the view, so a statement
/// of n wildcard items rebuilds n × (view width) cells per row. The expanded width
/// is what decides how many times one cell is copied, so it carries its own
/// ceiling. Set at the item ceiling, comfortably above every view's own width (the
/// widest has nine columns), so `SELECT *` and a handful of wildcards still run.
const MAX_PROJECTED_COLUMNS: usize = 64;

/// How many values one `IN` list may carry.
///
/// `IN` costs a single operator token and opens no nesting level, so neither
/// [`MAX_OPERATORS`] nor the nesting measure bounds the list's length — while every
/// element of it is evaluated against every surviving row, which makes the list a
/// per-row multiplier the way the projection and the `ORDER BY` are. This
/// emulator's own bound, set far above any list a statement over views this narrow
/// would write.
const MAX_IN_LIST_ITEMS: usize = 64;

/// How many operators one statement may chain.
///
/// A left-associative chain of the same operator (`a AND b AND c …`, `1+1+1+…`)
/// needs neither a bracket nor a prefix keyword, and the parser builds it
/// ITERATIVELY — so neither the nesting measure nor the parser's recursion limit
/// sees it, while the TREE it produces is as deep as the chain is long, and every
/// later walk of that tree (the move into the blocking task, the drop, the
/// evaluator) is as deep again. Counting the operators off the statement before it
/// is parsed is what bounds that depth: set above [`MAX_EXPRESSION_DEPTH`], so the
/// evaluator's own ceiling is what a merely long predicate meets, and far below any
/// depth a tree walk could not take.
const MAX_OPERATORS: usize = 300;

/// How many compared CHARACTERS count as one unit of the work budget.
///
/// The row COUNT alone does not bound the work a statement can cause. A stored
/// `stringValue` carries no modelled length bound, so matching one cell against a
/// `LIKE` pattern, ordering by one, materialising one or projecting one costs work
/// proportional to that cell's LENGTH rather than to the number of rows — and a
/// bound charged once per row, counting a row as one unit whatever its cells hold,
/// cannot see that work at all. Character work is therefore charged here too, in
/// units of this many characters, against the SAME ceiling
/// ([`MAX_SCANNED_ROWS`]) and the same deadline ([`MAX_QUERY_TIME`]) the row count
/// is charged against, and charged INSIDE the per-row loops that do it — a
/// `spawn_blocking` task cannot be aborted, so the wall-clock timeout wrapped
/// around the interpretation abandons the join handle rather than the work, and an
/// in-loop charge is the only thing that makes the deadline real.
///
/// The size is this emulator's own: a unit is a few thousand characters of
/// comparison, far more than any identifier, name, alias or rendered value these
/// views hold, so an ordinary statement over ordinary rows spends roughly one unit
/// per row and only cells orders of magnitude larger reach the ceiling.
const CHARS_PER_WORK_UNIT: usize = 4_096;

/// How many characters of one cell enter a sort key.
///
/// A sort's comparator cannot read the deadline or charge the budget, so one
/// comparison has to cost a BOUNDED amount however long the cells are: the key
/// keeps this much of the cell's text, which orders every pair of values whose text
/// differs within it and leaves two longer values agreeing on this whole prefix to
/// the stability of the sort. This emulator's own bound, set far above every
/// identifier, name, alias and rendered value these views hold.
const MAX_SORT_KEY_CHARS: usize = 4_096;

/// The budget one query runs under: a deadline, a scanned-row count and the
/// expression depth its walk has reached.
///
/// Every loop and every recursion in this engine charges against it, so the work
/// one statement can cause is bounded in three independent ways and each overrun
/// ends the query with a MODELLED error.
///
/// The count is held in a [`::std::cell::Cell`] so that charging needs only a
/// SHARED borrow: the predicate walk (`evaluate`/`value_of`/[`like`]) is reached
/// through shared borrows, and it is exactly the length-proportional work in there
/// that has to be charged.
#[derive(Debug)]
struct Budget {
    deadline: ::std::time::Instant,
    scanned: ::std::cell::Cell<usize>,
}

impl Budget {
    fn new() -> Self {
        Self {
            deadline: ::std::time::Instant::now() + MAX_QUERY_TIME,
            scanned: ::std::cell::Cell::new(0),
        }
    }

    /// Charge `rows` rows of work, failing once either the step budget or the
    /// deadline is spent.
    fn charge(&self, rows: usize) -> Result<(), ExecuteQueryError> {
        let scanned = self.scanned.get().saturating_add(rows);
        self.scanned.set(scanned);
        if scanned > MAX_SCANNED_ROWS {
            return Err(query_timeout(format!(
                "The query scanned more than {MAX_SCANNED_ROWS} rows without finishing."
            )));
        }
        if ::std::time::Instant::now() > self.deadline {
            return Err(query_timeout(format!(
                "The query ran for longer than {} seconds without finishing.",
                MAX_QUERY_TIME.as_secs()
            )));
        }
        Ok(())
    }

    /// Charge work proportional to `chars` COMPARED CHARACTERS, in units of
    /// [`CHARS_PER_WORK_UNIT`].
    ///
    /// The deadline is read whatever the amount rounds to, so a caller that charges
    /// a sub-unit amount inside a loop still observes it: this is the call that
    /// makes a bound reachable from inside the per-row work.
    fn charge_chars(&self, chars: usize) -> Result<(), ExecuteQueryError> {
        self.charge(chars.div_ceil(CHARS_PER_WORK_UNIT))
    }

    /// Refuse a walk that has nested past [`MAX_EXPRESSION_DEPTH`].
    fn depth(&self, depth: usize) -> Result<(), ExecuteQueryError> {
        if depth > MAX_EXPRESSION_DEPTH {
            return Err(invalid_request(format!(
                "The query statement nests expressions more than {MAX_EXPRESSION_DEPTH} \
                 levels deep."
            )));
        }
        Ok(())
    }
}

/// One value in a result row, in the type the column reports.
///
/// Kept as a value rather than as text so a comparison in a `WHERE` clause is made
/// between values of the column's own type — a number against a number, a timestamp
/// against a timestamp — and the rendering to the wire's `scalarValue` string happens
/// once, at the end.
#[derive(Debug, Clone, PartialEq)]
enum Cell {
    Null,
    Str(String),
    Int(i64),
    Double(f64),
    Bool(bool),
    /// Nanoseconds since the Unix epoch, the resolution IoT SiteWise timestamps
    /// carry (`TimeInNanos`).
    Timestamp(i128),
}

impl Cell {
    /// This value as the modelled `Datum` the wire carries: a `scalarValue` string,
    /// or `nullValue` for an absent one.
    fn datum(&self) -> Datum {
        let scalar = match self {
            Self::Null => {
                return Datum {
                    scalar_value: None,
                    array_value: None,
                    row_value: None,
                    null_value: Some(true),
                }
            }
            Self::Str(value) => value.clone(),
            Self::Int(value) => value.to_string(),
            Self::Double(value) => value.to_string(),
            Self::Bool(value) => value.to_string(),
            Self::Timestamp(nanos) => nanos.to_string(),
        };
        Datum {
            scalar_value: Some(scalar),
            array_value: None,
            row_value: None,
            null_value: None,
        }
    }

    /// How much comparing, copying or rendering this value costs, in BYTES.
    ///
    /// Bytes rather than characters, because the byte length is what a `String`
    /// knows without walking itself and is never smaller than the character count,
    /// so a charge taken on it is never an under-charge (the unit
    /// [`CHARS_PER_WORK_UNIT`] is a few thousand of either). A string costs its own
    /// length — the one cost in this engine the model does not bound, since
    /// `stringValue` carries no `@length` — and every other variant is a
    /// fixed-size scalar, so it costs one.
    fn chars(&self) -> usize {
        match self {
            Self::Str(value) => value.len(),
            _ => 1,
        }
    }

    /// This value as text, for a comparison against a string literal.
    fn as_text(&self) -> Option<String> {
        match self {
            Self::Null => None,
            Self::Str(value) => Some(value.clone()),
            Self::Int(value) => Some(value.to_string()),
            Self::Double(value) => Some(value.to_string()),
            Self::Bool(value) => Some(value.to_string()),
            Self::Timestamp(nanos) => Some(nanos.to_string()),
        }
    }

    /// This value as a number, for a comparison against a numeric literal.
    fn as_number(&self) -> Option<f64> {
        match self {
            Self::Int(value) => Some(*value as f64),
            Self::Double(value) => Some(*value),
            Self::Timestamp(nanos) => Some(*nanos as f64),
            Self::Str(value) => value.parse().ok(),
            Self::Bool(_) | Self::Null => None,
        }
    }

    /// The order between two values, or `None` when either is null or the two
    /// cannot be compared — in which case a comparison in a `WHERE` clause is
    /// neither true nor false and the row does not match, the way SQL's three-valued
    /// logic treats UNKNOWN.
    ///
    /// `numeric` says whether the COLUMN the comparison is about is a numeric one
    /// (`INT`, `DOUBLE`, `TIMESTAMP`), which is what decides how the two are
    /// compared: a numeric column compares by number, and every other column
    /// compares as text, so a `STRING` column holding digits is not quietly compared
    /// as the number it looks like. The same rule the sort uses ([`SortKey`]), so
    /// filtering and ordering cannot disagree about one column's type.
    fn compare(&self, other: &Self, numeric: bool) -> Option<::std::cmp::Ordering> {
        if matches!(self, Self::Null) || matches!(other, Self::Null) {
            return None;
        }
        if let (Self::Bool(left), Self::Bool(right)) = (self, other) {
            return Some(left.cmp(right));
        }
        if numeric {
            return self.as_number()?.partial_cmp(&other.as_number()?);
        }
        self.as_text()?.partial_cmp(&other.as_text()?)
    }
}

/// One column of a VIEW the store materialises: the name a statement selects it by
/// and the `ScalarType` the result reports for it.
#[derive(Debug, Clone, Copy)]
struct ViewColumn {
    name: &'static str,
    /// A `ScalarType` value. Source: `smithy_query(query="shape",
    /// shape="ScalarType")` — BOOLEAN | INT | DOUBLE | TIMESTAMP | STRING.
    scalar_type: &'static str,
}

/// One column of a RELATION this engine computes over: the name it answers to, the
/// `ScalarType` of its cells, and the qualifier a statement may write in front of
/// its name.
#[derive(Debug, Clone)]
struct Column {
    name: String,
    scalar_type: &'static str,
    /// The relation name this column belongs to — a view's own name, or the alias a
    /// `FROM` clause gave it, which is what a qualified identifier names it by. A
    /// column of a COMPUTED relation (a projection, a set operation) answers to no
    /// qualifier until a subquery alias gives it one.
    qualifier: Option<String>,
}

impl Column {
    /// Whether this column is one the view declares NUMERIC, which is what decides
    /// how its cells compare and sort: a `STRING` column holding digits is not
    /// quietly compared as the number it looks like.
    fn numeric(&self) -> bool {
        is_numeric(self.scalar_type)
    }
}

/// Whether `scalar_type` is one of the `ScalarType` values that carries a NUMBER.
fn is_numeric(scalar_type: &str) -> bool {
    matches!(scalar_type, "INT" | "DOUBLE" | "TIMESTAMP")
}

/// A relation: the columns every one of its rows carries, and the rows.
///
/// Everything this engine runs is a function from relations to a relation — a view
/// read off the store, a join of two of them, a grouped projection, a set operation,
/// a subquery — so ONE type carries all of them and the clauses compose, instead of
/// each clause having to know that the statement reads a single view.
#[derive(Debug, Clone, Default)]
struct Relation {
    columns: Vec<Column>,
    rows: Vec<Vec<Cell>>,
}

impl Relation {
    /// This relation read under `qualifier`: the name the `FROM` clause gives it,
    /// which is what its columns may be qualified by. An alias REPLACES the name the
    /// relation was read under, as SQL scopes it, so a statement that joins one view
    /// to itself addresses the two sides by their own aliases.
    fn qualified(mut self, qualifier: &str) -> Self {
        for column in &mut self.columns {
            column.qualifier = Some(qualifier.to_ascii_lowercase());
        }
        self
    }

    /// How many BYTES of cells this relation holds; see [`Cell::chars`].
    fn bytes(&self) -> usize {
        self.rows
            .iter()
            .flat_map(|row| row.iter().map(Cell::chars))
            .sum()
    }
}

/// The relations a statement can read BY NAME: the views this engine materialised
/// off the store, and the common table expressions the statement defined.
///
/// Cloned per `WITH` level — the clone copies the names and SHARES the relations
/// themselves — so a name one level defines shadows an outer one for that level
/// alone.
#[derive(Debug, Clone, Default)]
struct Catalog {
    relations: ::std::collections::BTreeMap<String, ::std::sync::Arc<Relation>>,
}

impl Catalog {
    /// How many bytes of stored cells this snapshot of the store holds. What a run
    /// over it SCANNED: the rows were copied off the store before the run began, so
    /// this is what it read and not a figure standing in for it.
    fn bytes_held(&self) -> usize {
        self.relations
            .values()
            .map(|relation| relation.bytes())
            .sum()
    }

    /// This catalog with `name` bound to `relation`, shadowing any outer binding.
    fn with(&self, name: &str, relation: Relation) -> Self {
        let mut extended = self.clone();
        extended
            .relations
            .insert(name.to_ascii_lowercase(), ::std::sync::Arc::new(relation));
        extended
    }
}

/// What one LEVEL of a statement runs with: the budget every step charges against,
/// the relations that level reads by name, and the subqueries it has already run.
///
/// The memo is what keeps an uncorrelated subquery from being run once per row. A
/// subquery resolves its columns against its OWN relations only, so one that
/// resolves at all answers the same rows whichever row of the statement around it is
/// being evaluated, and its result is read back by the text it was written as. A
/// level's memo is its own, so a name a nested `WITH` rebinds cannot make one level's
/// result answer for another's.
struct Run<'a> {
    budget: &'a Budget,
    catalog: &'a Catalog,
    memo: ::std::cell::RefCell<
        ::std::collections::BTreeMap<String, ::std::sync::Arc<Relation>>,
    >,
}

impl<'a> Run<'a> {
    fn new(catalog: &'a Catalog, budget: &'a Budget) -> Self {
        Self {
            budget,
            catalog,
            memo: ::std::cell::RefCell::new(::std::collections::BTreeMap::new()),
        }
    }
}

