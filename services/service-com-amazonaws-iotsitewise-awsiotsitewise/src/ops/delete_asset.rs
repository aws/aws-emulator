impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DeleteAsset<Eng>
{
    type Input = DeleteAssetInput;
    type Output = DeleteAssetOutput;
    type Error = DeleteAssetError;

    const NAME: &'static str = "DeleteAsset";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_ASSET_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_ASSET_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DeleteAssetError::Modeled(DeleteAssetErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;
        let region = crate::state::request_region(ctx.parts());

        // `clientToken` makes this delete idempotent, as the member documents: "A
        // unique case-sensitive identifier that you can provide to ensure the
        // idempotency of the request." A retry carries the token of the call it
        // repeats, so it replays that call's answer — the asset it removed, reported
        // DELETING — rather than the not-found refusal the removal itself would now
        // produce, and removes nothing further; a token already spent on a DIFFERENT
        // request belongs to another call, which is the modelled conflict. It is the
        // FIRST thing decided, because the call it repeats was already served.
        let mut store = state.lock();

        let fingerprint = crate::state::request_fingerprint(&[&input.asset_id], None);
        match store.idempotent_verdict(Self::NAME, input.client_token.as_deref(), &fingerprint) {
            crate::state::TokenVerdict::Replay(replayed) => {
                // The answer the first call gave: the asset it removed is gone by the
                // time its retry lands, which is exactly why that answer is replayed
                // from the record of the call rather than re-derived from the store.
                return Ok(DeleteAssetOutput {
                    asset_id: Some(replayed),
                    asset_status: AssetStatus {
                        state: crate::state::STATE_DELETING.to_string(),
                        error: None,
                    },
                });
            }
            crate::state::TokenVerdict::Spent(spent_on) => {
                // The ARN the conflict reports is the one an asset of this store
                // CARRIES under that id, read back from the record rather than
                // rebuilt, so the refusal cannot name an ARN no asset of this store
                // has: a delete frees the id it removed and `CreateAsset` takes a
                // caller-supplied `assetId`, so that id can be an asset again — one
                // minted through whichever regional endpoint created it. Only an id
                // this store holds no asset under leaves nothing to read.
                let arn = store.stored_asset_arn(&region, &spent_on);
                return Err(token_spent(&spent_on, arn));
            }
            crate::state::TokenVerdict::Serve => {}
        }

        // The label is either the raw UUID or the `externalId:<externalId>` alias form.
        let id = store.resolve_asset_id(&input.asset_id).ok_or_else(|| {
            DeleteAssetError::Modeled(DeleteAssetErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: crate::state::asset_not_found_message(&input.asset_id),
                },
            ))
        })?;

        // A destructive call cannot go through while another resource still depends on
        // the one it removes, and an asset in a hierarchy is depended on from BOTH
        // sides: as a parent whose children would be left pointing at a hierarchy
        // whose parent is gone, and as a child the parent's hierarchy still lists.
        // The operation's own documentation states the rule for the second direction
        // — "You can't delete an asset that's associated to another asset. For more
        // information, see DisassociateAssets" — and the first is the same dependency
        // seen from the other end. Either way this is a TERMINAL request error — the
        // caller has to disassociate first, and no retry of this call can succeed — so
        // it is `InvalidRequestException` (400), not the retryable
        // `ConflictingOperationException` (409); the same rule, and the same mapping,
        // as `DeleteAssetModel`'s refusal for a model that still has assets. The
        // precondition is evaluated BEFORE anything is removed, so a refused delete
        // leaves the asset exactly as it was. Each direction has AWS's own fixed
        // sentence, naming neither the asset, nor the asset at the other end of
        // the association, nor the hierarchy holding it
        // ([`DISASSOCIATE_THE_CHILDREN_FIRST`],
        // [`DISASSOCIATE_FROM_THE_PARENT_FIRST`]).
        if store.has_hierarchy_children(&id) {
            return Err(DeleteAssetError::Modeled(
                DeleteAssetErrorModeled::InvalidRequestException(InvalidRequestException {
                    message: DISASSOCIATE_THE_CHILDREN_FIRST.to_string(),
                }),
            ));
        }
        if store.hierarchy_parent(&id).is_some() {
            return Err(DeleteAssetError::Modeled(
                DeleteAssetErrorModeled::InvalidRequestException(InvalidRequestException {
                    message: DISASSOCIATE_FROM_THE_PARENT_FIRST.to_string(),
                }),
            ));
        }

        // The streams of the asset's properties are a dependency of the same kind,
        // and the one `DeleteTimeSeries` refuses on: "You can't delete a time series
        // until all of its data segments have been deleted from session datasets."
        // An asset property's stream is addressable as the time series its
        // `(assetId, propertyId)` pair names, and a dataset's data segment names
        // exactly such a stream, so removing the asset would leave that segment
        // covering data nothing holds and naming a stream no read can resolve.
        // Terminal for the same reason the hierarchy refusals are — the caller has
        // to delete those segments first — and evaluated BEFORE anything is
        // removed, so a refused delete leaves the asset, its properties and their
        // samples exactly as they were.
        if let Some((blocked_series, holder)) =
            store.data_segment_of_any_time_series(store.asset_property_time_series_ids(&id))
        {
            return Err(DeleteAssetError::Modeled(
                DeleteAssetErrorModeled::InvalidRequestException(InvalidRequestException {
                    message: crate::state::data_segments_remain_message(&blocked_series, &holder),
                }),
            ));
        }

        // The asset and everything keyed off it (its property series, its aliases, its
        // hierarchy associations, its project memberships, and the actions and
        // executions that name it) go away, so no later read can still see it.
        store.forget_asset(&id);

        // The token is spent only now that the delete has succeeded: a refused
        // request removed nothing, so the caller may send its token again.
        store.record_idempotent_call(
            Self::NAME,
            input.client_token.as_deref(),
            fingerprint,
            &id,
            ::std::time::SystemTime::now(),
        );

        Ok(DeleteAssetOutput {
            asset_id: Some(id),
            asset_status: AssetStatus {
                state: crate::state::STATE_DELETING.to_string(),
                error: None,
            },
        })
    }
}

