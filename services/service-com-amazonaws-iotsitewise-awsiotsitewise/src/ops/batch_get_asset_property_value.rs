/// Resolve one entry to the latest value of the property it names — `None`
/// when the property exists but holds no data point — or to the
/// `BatchGetAssetPropertyValueErrorCode` and message the entry should report.
///
/// The asset label goes through [`crate::state::ComAmazonawsIotsitewiseAwsiotsitewiseState::resolve_asset_id`],
/// the same resolver `GetAssetPropertyValue`/`BatchPutAssetPropertyValue` use, so
/// one asset is named one way across the service.
fn resolve_entry(
    store: &crate::state::ComAmazonawsIotsitewiseAwsiotsitewiseState,
    entry: &BatchGetAssetPropertyValueEntry,
    now: ::std::time::SystemTime,
) -> Result<Option<AssetPropertyValue>, (&'static str, String)> {
    // "To identify an asset property, you must specify one of the following: the
    // assetId and propertyId of an asset property; a propertyAlias."
    let stream = match (
        entry.asset_id.as_deref(),
        entry.property_id.as_deref(),
        entry.property_alias.as_deref(),
    ) {
        (Some(asset_label), Some(property_id), None) => {
            let asset_id = store.resolve_asset_id(asset_label).ok_or_else(|| {
                (
                    ERROR_NOT_FOUND,
                    crate::state::asset_not_found_message(asset_label),
                )
            })?;
            // The one definition of "the property this pair names": the asset's
            // own properties and the ones its model's composite models declare
            // are addressed by the same pair, so both resolve here.
            let resolved = store
                .resolve_asset_property(&asset_id, property_id)
                .ok_or_else(|| {
                    (
                        ERROR_NOT_FOUND,
                        format!("The asset {asset_label} has no property {property_id}."),
                    )
                })?;
            crate::state::SeriesKey::Property(asset_id, resolved.id)
        }
        // An alias names ONE data stream, whether an asset property is associated
        // with it or not: the shared resolver reaches the property's stream, or the
        // disassociated one standing under that alias.
        (None, None, Some(alias)) => store.resolve_alias_series(alias).ok_or_else(|| {
            (
                ERROR_NOT_FOUND,
                crate::state::not_found_message(crate::state::RESOURCE_TIME_SERIES, alias),
            )
        })?,
        _ => {
            return Err((
                ERROR_INVALID_REQUEST,
                "Each entry must specify either assetId and propertyId, or propertyAlias."
                    .to_string(),
            ))
        }
    };

    // The latest value is the last element of the ascending series, read through
    // the one reader every data-plane read of this service takes, so a `transform`
    // or `metric` property reports the value its formula computes exactly as
    // `GetAssetPropertyValue` reports it.
    Ok(store.resolved_series(&stream, now).last().cloned())
}

