/// The `InvokeAssistant` operation.
///
/// Owns the shared engine (the constructor seam). The generated routing table holds one of
/// these — where its generated shim declines the request — and `service.rs` holds another
/// wrapped in an `EventStreamRoute`; both reach the same state, because the state lives in
/// the shared engine and not on the operation.
pub struct InvokeAssistant<Eng> {
    engine: ::std::sync::Arc<Eng>,
}

impl<Eng> InvokeAssistant<Eng> {
    /// Construct the operation from the shared engine. INFALLIBLE — the engine is a
    /// construction-time dependency, so engine access is guaranteed by the time any request
    /// runs.
    pub fn new(engine: ::std::sync::Arc<Eng>) -> Self {
        Self { engine }
    }
}

impl<Eng: Send + Sync + 'static> InvokeAssistant<Eng> {
    /// Serve one turn: record it against its conversation, answer it from the account's
    /// datasets, and frame the answer.
    fn respond(
        &self,
        protocol: &dyn ServerHttpProtocol,
        input: InvokeAssistantInput,
    ) -> Result<Response, InvokeAssistantError> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_failure(
                "the IoT SiteWise store is unavailable".to_string(),
            ));
        };
        let now = ::std::time::SystemTime::now();

        let (conversation, answer) = {
            let mut store = state.lock();
            // The WRITE this operation performs: the conversation this turn belongs to, a
            // turn longer than it was. A request naming no conversation starts one.
            let conversation =
                store.record_assistant_turn(input.conversation_id.as_deref(), now);
            let answer = store.assistant_answer(&input.message, &conversation);
            (conversation, answer)
        };

        let mut frames = Vec::new();
        // The trace is the assistant's "reasoning, and data access process", which the
        // request asks for: the steps are composed either way, and `enableTrace` decides
        // whether the stream carries them, so an answer is the same with and without them.
        if input.enable_trace {
            for step in &answer.traces {
                frame(
                    protocol,
                    &mut frames,
                    TRACE_EVENT,
                    &Trace {
                        text: Some(step.clone()),
                    },
                    &Trace::SCHEMA,
                )?;
            }
        }
        // One `output` event carrying the whole answer: the turn is computed in one step, so
        // nothing here splits it into fabricated increments.
        frame(
            protocol,
            &mut frames,
            OUTPUT_EVENT,
            &InvocationOutput {
                message: Some(answer.message),
                citations: Some(answer.citations.iter().map(cited).collect()),
            },
            &InvocationOutput::SCHEMA,
        )?;

        event_stream_response(
            protocol,
            INVOKE_ASSISTANT,
            &InvokeAssistantOutput {
                conversation_id: conversation.id,
            },
            &InvokeAssistantOutput::SCHEMA,
            frames,
        )
        .map_err(|error| {
            internal_failure(format!("the response could not be serialized: {error}"))
        })
    }
}

/// One cited dataset as the modelled `Citation` it is reported as: the dataset's own ARN
/// beside the source the cited text was read through, and the text itself.
///
/// `source.location` is left absent: it is "the location information where the cited text is
/// originally stored", and this emulator holds the text on the dataset's own record rather
/// than at a URI, so there is no location to report.
fn cited(citation: &crate::state::AssistantCitation) -> Citation {
    Citation {
        reference: Some(Reference {
            dataset: Some(DataSetReference {
                dataset_arn: Some(citation.dataset_arn.clone()),
                source: Some(Source {
                    arn: Some(citation.source_arn.clone()),
                    location: None,
                }),
            }),
        }),
        content: Some(Content {
            text: Some(citation.text.clone()),
        }),
    }
}

/// Append one `ResponseStream` event to the stream, framed by this service's own protocol.
fn frame(
    protocol: &dyn ServerHttpProtocol,
    frames: &mut Vec<u8>,
    event_type: &str,
    event: &dyn SerializableStruct,
    schema: &Schema,
) -> Result<(), InvokeAssistantError> {
    // `is_exception` is false for both members framed here: neither `trace` nor `output` is
    // an `@error` shape, so each travels as a data event.
    let framed = frame_event(protocol, event_type, false, event, schema).map_err(|error| {
        internal_failure(format!(
            "the {event_type} event could not be framed: {error}"
        ))
    })?;
    frames.extend_from_slice(&framed);
    Ok(())
}

/// This operation's modelled 500, for a store or a response this handler could not serve at
/// all.
fn internal_failure(message: String) -> InvokeAssistantError {
    InvokeAssistantErrorModeled::InternalFailureException(InternalFailureException { message })
        .into()
}

/// This operation's modelled 400, for a body the protocol's codec could not read at all.
///
/// The sentence is the one the model documents for this error, which is what AWS answers a
/// request it could not read as JSON with; a request that WAS read and broke one of the
/// model's rules is refused through the service's own refusal seam instead, so it carries
/// the constraint envelope every sibling operation's refusal carries.
fn invalid_request() -> InvokeAssistantError {
    InvokeAssistantErrorModeled::InvalidRequestException(InvalidRequestException {
        message: "The request isn't valid. This can occur if your request contains malformed \
                  JSON or unsupported characters. Check your request and try again."
            .to_string(),
    })
    .into()
}

impl<Eng: Send + Sync + 'static> EventStreamOperation for InvokeAssistant<Eng> {
    fn serve<'r>(
        &'r self,
        svc: &'r dyn Service,
        req: &'r Request,
        ctx: &'r OperationContext<'r>,
    ) -> BoxFuture<'r, Response> {
        Box::pin(async move {
            let definition = svc.definition();
            let protocol = definition.protocol();
            let input = match read_request::<InvokeAssistantInput>(
                protocol,
                req,
                &InvokeAssistantInput::SCHEMA,
            ) {
                Ok(input) => input,
                Err(RequestRefusal::Invalid(violations)) => {
                    // Worded by this service's own seam, which states every constraint
                    // violation as `InvalidRequestException` — the shape this model
                    // declares for a bad request — so a refusal of this operation reads
                    // exactly like one of any other.
                    let chosen = svc.override_refusal(&Refusal::Invalid(violations.clone()));
                    return definition.refusal_response(
                        ProtocolError::Invalid(violations),
                        chosen,
                        req,
                    );
                }
                Err(RequestRefusal::Unreadable(_)) => {
                    return error_response(protocol, &invalid_request())
                }
            };
            let response = match self.respond(protocol, input) {
                Ok(response) => response,
                Err(error) => error_response(protocol, &error),
            };
            // One access record per request, so a refused turn is diagnosable. The
            // `@sensitive` message and no credential reaches it.
            tracing::debug!(
                operation = INVOKE_ASSISTANT,
                service = ctx.identity().signing_name(),
                method = ctx.parts().method.as_str(),
                status = response.status().as_u16(),
                "served an event-stream request"
            );
            response
        })
    }
}
