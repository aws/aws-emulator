//! @op InvokeAssistant
//!
//! `POST /assistant/invocation -> 200`. Serves one TURN of the conversation this operation
//! documents ("Invokes SiteWise Assistant to start or continue a conversation"): the turn is
//! recorded against the conversation the request names — minting a `conversationId` when it
//! names none, which is what the member's own documentation says the service does ("IoT
//! SiteWise automatically generates a unique ID for you") — the account's datasets are
//! searched for what the message names, and the answer leaves as the modelled
//! `ResponseStream`, a real `vnd.amazon.eventstream` body: a `trace` event per step of the
//! assistant's reasoning when `enableTrace` asked for them, then the one `output` event
//! carrying the message and one citation per dataset it quotes. The conversation the turn
//! was recorded under travels in the modelled response header.
//!
//! NO LANGUAGE MODEL RUNS IN THIS EMULATOR: the retrieval and the text are
//! [`crate::state::ComAmazonawsIotsitewiseAwsiotsitewiseState::assistant_answer`]'s, which
//! runs the one shared free-text search this workspace has over the datasets this account
//! holds and then quotes the matched text exactly as those datasets' records hold it. The
//! caller's `@sensitive` message is neither stored nor quoted back.
//!
//! ## Why this file is hand-authored
//!
//! The op-stub generator declined this operation because its output member is a `@streaming`
//! event-stream union it cannot frame (`src/ops/SKIPPED_STUBS.md`), and the generated
//! `ErasedOperation` shim of such an operation declines the request too:
//! `serialize_as_event_stream<P>` needs a `Sized` protocol, which the object-safe `run`
//! cannot hand it. So there is no `impl Operation` here and no centralized deserialize ->
//! validate -> handle -> serialize sequence: the framing lives in
//! `service_common::event_stream`, the shapes in `super::types::invoke_assistant_types`, the
//! request half is read through the framework's own deserializer and constraint walk — and a
//! violation is worded by this service's own refusal seam
//! ([`crate::service::EmulatedService::override_refusal`]), so a refusal here reads exactly
//! like one from a non-streaming sibling — and `src/service.rs` routes a request here
//! through an `EventStreamRoute`.
//!
//! ---
//!
//! # Modeled contract for `InvokeAssistant`
//!
//! ```text
//! smithy_query(query="operation",operation="InvokeAssistant",model_path="services/service-com-amazonaws-iotsitewise-awsiotsitewise/smithy-model/com-amazonaws-iotsitewise-awsiotsitewise.json")
//! ```
//!
//! ## Input
//!
//! * `message` (MessageInput, len 1..10000, @sensitive) **required** — A text message sent to
//!   the SiteWise Assistant by the user.
//! * `conversationId` (ConversationId, len 36..36, pattern
//!   ^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$) — The ID assigned to a
//!   conversation; never required, and generated by the service when absent.
//! * `enableTrace` (PrimitiveBoolean, default false) — Specifies if to turn trace on or not.
//!
//! ## Output
//!
//! * `body` (ResponseStream, @httpPayload, @streaming) **required** — the event stream. The
//!   union carries `trace`, `output` and the in-band shape of each of this operation's
//!   errors.
//! * `conversationId` (@httpHeader x-amz-iotsitewise-assistant-conversation-id)
//!   **required**.
//!
//! ## Errors
//!
//! * `AccessDeniedException` (HTTP 403), `ConflictingOperationException` (HTTP 409),
//!   `InternalFailureException` (HTTP 500), `InvalidRequestException` (HTTP 400),
//!   `LimitExceededException` (HTTP 410), `ResourceNotFoundException` (HTTP 404),
//!   `ThrottlingException` (HTTP 429).

