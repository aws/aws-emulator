    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::state::registry_unavailable(Self::NAME));
        };
        // Every `@connections` call is authorized by IAM on the stage it addressed, and that
        // decision is taken BEFORE the request it carries is read at all: a caller holding no
        // `execute-api:ManageConnections` grant learns nothing about which connections exist
        // (`crate::service::manage_connections_authorization`).
        if let Some(denied) =
            crate::service::manage_connections_authorization::denial(&*self.engine, ctx)
        {
            return Err(crate::scaffolded::Scaffolded::access_denied(denied));
        }
        // A `ConnectionId` that is not of the shape this service mints names no connection
        // anywhere, so the request is refused from the VALUE alone, before the registry is
        // consulted: a caller prunes its own record of a connection on the 410, so
        // answering that for a malformed id would make it delete a record it should keep
        // (`crate::state::invalid_connection_id`).
        if !crate::state::is_well_formed_connection_id(&input.connection_id) {
            return Err(crate::state::invalid_connection_id(&input.connection_id));
        }
        // Which api's connections this request addresses is decided by the endpoint it
        // reached; see `crate::state`.
        let addressed_at = crate::state::addressed_at(ctx.parts());

        let mut guard = state.lock();
        let Some(connection) =
            guard.connection_at_mut(&input.connection_id, addressed_at.as_deref())
        else {
            // Nothing is recorded for a connection that is not open at this endpoint: it
            // was never minted, it was deleted, or it belongs to another api.
            return Err(PostToConnectionErrorModeled::GoneException(GoneException {}).into());
        };
        // DELIVER it first, where the connection is carried on a live socket: a post is
        // "sends the provided data to the specified connection", so what the client reads is
        // the point and the record below is the account of it. Two refusals come out of the
        // attempt, and both are modelled:
        //
        // * the task serving the socket is gone, so the connection no longer exists:
        //   `GoneException` ("The connection with the provided id no longer exists"), and the
        //   record goes with it so every later call agrees;
        // * the client is not reading and the connection's queue is full:
        //   `LimitExceededException` ("the WebSocket client side buffer is full", the
        //   member's own documentation), and nothing is recorded as delivered.
        //
        // A connection carried on NO socket (the emulator-internal registration seam) is
        // recorded and nothing is written, which is what that seam exists for.
        match connection.deliver(input.data.clone()) {
            Ok(()) => {}
            Err(crate::state::DeliveryRefused::Closed) => {
                guard.connections.remove(&input.connection_id);
                return Err(PostToConnectionErrorModeled::GoneException(GoneException {}).into());
            }
            Err(crate::state::DeliveryRefused::Backlogged) => {
                tracing::info!(
                    connection_id = %input.connection_id,
                    "refusing a PostToConnection: the connection's client side buffer is full"
                );
                return Err(PostToConnectionErrorModeled::LimitExceededException(
                    LimitExceededException {},
                )
                .into());
            }
        }
        // Counts the delivery and keeps it in the connection's BOUNDED observation
        // window; see `crate::state::Connection::push_delivered` for why the retained
        // payloads are capped rather than accumulated.
        connection.push_delivered(input.data);
        // Data flowed to the connection, so this is the moment it was last active.
        connection.last_active_at = ::std::time::SystemTime::now();

        Ok(PostToConnectionOutput)
    }
