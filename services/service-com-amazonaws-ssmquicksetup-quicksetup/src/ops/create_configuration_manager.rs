/// Why this create's configuration definitions are unacceptable, or `None` when the
/// store can take them.
///
/// `ConfigurationDefinitionsInputList` is `@required` but carries no modelled length,
/// so an EMPTY list reaches the handler: a configuration manager is the deployment of
/// its definitions, so one with none to deploy is refused. Each definition's `Type`
/// must name a configuration type this service offers, because that is what selects
/// the service-owned template the definition deploys
/// (`crate::state::quick_setup_type_rejection`); its `TypeVersion` is resolved against
/// that same catalog in the handler, once the type is known to be published
/// (`crate::state::resolve_type_version`). The deployment targets a definition's
/// parameters name must be servable, because each targeted account and Region pair
/// becomes a stored configuration, and it must provide every parameter the table
/// documented for its own `Type` requires of it, because the definition deploys that
/// type's service-owned template with the parameters it provides
/// (`crate::state::configuration_parameters_rejection`, which counts those pairs the
/// way the handler below deploys them). A definition that deploys LOCALLY must also
/// name the role such a
/// deployment is administered with
/// (`crate::state::local_deployment_rejection`). The
/// remaining checks are
/// the store's own bounds on collections the model gives no length (see
/// `crate::state`'s `MAX_*` constants), the provider-reserved tag-key namespace a
/// caller may not assign into (`crate::state::reserved_tag_key_rejection`).
///
/// The `IAMRoleArn` form of `LocalDeploymentAdministrationRoleArn` is NOT one of these:
/// it is a VALUE CONSTRAINT on a member — one the model states as an `@arnReference`
/// rather than as a `@pattern` the boundary could enforce — so it is restated in the
/// boundary layer's own words and shape instead ([`role_arn_rejection`]), and ahead of
/// every rule here.
fn definitions_rejection(input: &CreateConfigurationManagerInput) -> Option<String> {
    if input.configuration_definitions.is_empty() {
        return Some(crate::state::NO_CONFIGURATION_DEFINITIONS_MESSAGE.to_string());
    }
    let too_many = |member: &str, actual: usize, cap: usize| {
        (actual > cap).then(|| {
            format!("{member} carries {actual} entries, more than the {cap} this service accepts")
        })
    };
    too_many(
        "ConfigurationDefinitions",
        input.configuration_definitions.len(),
        crate::state::MAX_CONFIGURATION_DEFINITIONS,
    )
    .or_else(|| {
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                too_many(
                    "ConfigurationDefinitions.Parameters",
                    definition.parameters.len(),
                    crate::state::MAX_PARAMETERS,
                )
            })
    })
    .or_else(|| {
        // `Type` resolves a service-owned template, so only a type this service
        // publishes can be deployed; the catalog `ListQuickSetupTypes` answers is the
        // accepted set, and `crate::state` is the one place that rule lives.
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                crate::state::quick_setup_type_rejection(
                    "ConfigurationDefinitions.Type",
                    &definition.r#type,
                )
            })
    })
    .or_else(|| {
        // A definition's parameters name where it is deployed, and the service
        // deploys one configuration per targeted account and Region, so the targets
        // are checked before anything is stored; so is every parameter the documented
        // table for the definition's own `Type` requires of it, which is why the type
        // is read alongside the map. `crate::state` is the one place that rule lives,
        // shared with `UpdateConfigurationDefinition`.
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                crate::state::configuration_parameters_rejection(
                    "ConfigurationDefinitions.Parameters",
                    &definition.parameters,
                    &definition.r#type,
                )
            })
    })
    .or_else(|| {
        too_many(
            "Tags",
            input.tags.as_ref().map_or(0, std::collections::HashMap::len),
            crate::state::MAX_TAGS,
        )
    })
    .or_else(|| {
        // `TagsMap`'s key pattern admits `:`, so it admits a key under the
        // AWS-reserved prefix as well — a tag that is not the caller's to assign.
        // `crate::state::reserved_tag_key_rejection` is the one place that rule
        // lives, shared with every other member of this service that takes tag keys
        // from the caller. `TagsMap` is `@sensitive`, so the refusal it builds for
        // this member renders no key out of the map.
        crate::state::reserved_tag_key_rejection(
            "Tags",
            input
                .tags
                .iter()
                .flat_map(std::collections::HashMap::keys)
                .map(String::as_str),
        )
    })
    .or_else(|| {
        // A definition whose parameters name the account initiating the deployment is
        // deployed LOCALLY, and a local deployment is administered with the role
        // `LocalDeploymentAdministrationRoleArn` names, so one that names none cannot be
        // administered: `crate::state::local_deployment_rejection` is the one place that
        // rule lives, shared with `UpdateConfigurationDefinition`.
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                crate::state::local_deployment_rejection(
                    &definition.parameters,
                    definition.local_deployment_administration_role_arn.as_deref(),
                )
            })
    })
}

/// Why a definition's `LocalDeploymentAdministrationRoleArn` is unacceptable, or `None`
/// when every definition this create carries names a role ARN of the form that member's
/// shape requires.
///
/// `LocalDeploymentAdministrationRoleArn` is an `IAMRoleArn`, whose `@arnReference` to
/// `AWS::IAM::Role` the model states with no `@pattern` to enforce it;
/// `crate::state::iam_role_arn_rejection` is the one place that rule lives, shared with
/// every other `IAMRoleArn` member of this service, and it states the refusal in the
/// boundary layer's own envelope — so the member is named by its VALIDATION PATH, which
/// for a member of a list element carries that element's 1-based position and the
/// collection step (`aws_smithy_schema_server::constraints::path`), exactly as the
/// centralized walk spells the path of a modelled constraint on the same member.
fn role_arn_rejection(input: &CreateConfigurationManagerInput) -> Option<String> {
    input
        .configuration_definitions
        .iter()
        .enumerate()
        .filter_map(|(index, definition)| {
            definition
                .local_deployment_administration_role_arn
                .as_deref()
                .map(|arn| (index, arn))
        })
        .find_map(|(index, arn)| {
            crate::state::iam_role_arn_rejection(
                &format!(
                    "configurationDefinitions.{}.member.localDeploymentAdministrationRoleArn",
                    index + 1
                ),
                arn,
            )
        })
}

