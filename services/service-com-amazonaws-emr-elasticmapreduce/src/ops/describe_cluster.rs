    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let now = ::std::time::SystemTime::now();
        // The address a client of this emulator can reach the cluster's master node at,
        // read before the store is taken because it is a fact of the request.
        let master_host = crate::state::served_master_host(ctx);

        // The SHAPE of the cluster id is settled BEFORE any cluster is resolved: a value
        // carrying characters no cluster id is drawn from names no cluster the service
        // could hold, so it is a bad REQUEST rather than an unresolvable target, and it
        // is refused as one — the request-validation envelope, HTTP 400, naming the
        // member the caller has to fix. A well-formed id reaches the lookup below, which
        // is where "no such cluster" is told.
        if !crate::state::is_cluster_id_shaped(&input.cluster_id) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::malformed_cluster_id_message(&input.cluster_id),
            ));
        }

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DescribeClusterErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the EMR cluster store is unavailable".to_string()),
                },
            )
            .into());
        };
        // Reporting only, and before this service's store is taken: a step this cluster has
        // started is OWED the run of the application it submitted — the cluster's own
        // shutdown waits on its queue having run — and neither the Amazon S3 read nor the
        // interpreter that runs it may happen under this service's lock.
        crate::state::run_due_step_applications(
            &*self.engine,
            ctx,
            &crate::state::request_region(ctx.parts()),
            &input.cluster_id,
            now,
        )
        .await;
        // The same for a step that submitted a COMMAND — the cluster's own shutdown waits on
        // its queue having run. Such a status is answered with a PARSE and a fixed allow-list
        // of session-local utilities (`crate::state::step_command_status`): no host command,
        // process or shell is ever started, and a command outside that list is refused with
        // the status a shell gives a command it could not find. The call resolves the cluster
        // itself and answers only for steps that cluster has already started, and it runs with
        // no store guard held.
        crate::state::resolve_due_step_commands(&*self.engine, &input.cluster_id, now);

        // The store is taken and RELEASED inside this block: the publication below reaches
        // EventBridge's own handler, which may call back into this service, so this
        // service's lock is never held across it.
        let output = {
            let mut store = state.lock();

            // Reporting only: `cluster_mut` materialises the transitions the clock already
            // made due (STARTING -> RUNNING/WAITING, TERMINATING -> TERMINATED), which were
            // owed at this instant whether or not anybody described the cluster.
            let Some(cluster) = store.cluster_mut(&input.cluster_id, now) else {
                return Err(DescribeClusterErrorModeled::InvalidRequestException(
                    crate::state::unknown_cluster(&input.cluster_id),
                )
                .into());
            };

            DescribeClusterOutput {
                cluster: Some(cluster.to_cluster(&crate::state::ClusterRead {
                    now,
                    master_host: master_host.as_deref(),
                })),
            }
        };

        // Describing a cluster materialises its step queue too, and this service's step
        // states are an event source: every state its steps have moved into is published
        // onto the account's default event bus, with this service's store released (see
        // `crate::state::step_events`).
        crate::state::publish_step_state_changes(
            &*self.engine,
            ctx,
            &crate::state::request_region(ctx.parts()),
            &input.cluster_id,
        )
        .await;
        // The same for the CLUSTER's own states: a transition this read materialised is
        // announced on the default event bus like any other, with the store released.
        crate::state::settle_cluster_events(
            &self.engine,
            ctx,
            &crate::state::request_region(ctx.parts()),
        );

        Ok(output)
    }
