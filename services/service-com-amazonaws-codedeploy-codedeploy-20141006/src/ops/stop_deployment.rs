impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StopDeployment<Eng>
{
    type Input = StopDeploymentInput;
    type Output = StopDeploymentOutput;
    type Error = StopDeploymentError;

    const NAME: &'static str = "StopDeployment";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_DEPLOYMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_DEPLOYMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `deploymentId` is @required but carries no modelled length or pattern, so
        // both an empty one and a malformed one reach the handler — the same reading
        // `GetDeployment` uses, so the two agree about one id: an absent or empty id
        // is what `DeploymentIdRequiredException` is for, an id that is not shaped
        // like one the service mints is what `InvalidDeploymentIdException` is for,
        // and only a well-formed id is then discriminated on existence.
        let deployment_id = input.deployment_id;
        if deployment_id.trim().is_empty() {
            return Err(StopDeploymentErrorModeled::DeploymentIdRequiredException(
                DeploymentIdRequiredException {
                    message: Some(crate::state::DEPLOYMENT_ID_MISSING.to_string()),
                },
            )
            .into());
        }
        if !crate::state::deployment_id_is_well_formed(&deployment_id) {
            return Err(StopDeploymentErrorModeled::InvalidDeploymentIdException(
                InvalidDeploymentIdException {
                    message: Some(crate::state::malformed_deployment_id_message(
                        &deployment_id,
                    )),
                },
            )
            .into());
        }
        // Whether the caller asked for the updated instances to go back to the
        // revision deployed before this deployment. Absent is no rollback.
        let auto_rollback_enabled = input.auto_rollback_enabled.unwrap_or(false);

        let outcome = crate::state::with_state(&*self.engine, |state| {
            let Some(deployment) = state.deployments.get(&deployment_id) else {
                return Err(StopDeploymentErrorModeled::DeploymentDoesNotExistException(
                    DeploymentDoesNotExistException {
                        message: Some(crate::state::deployment_not_found(&deployment_id)),
                    },
                ));
            };
            // A deployment that already reached its own OUTCOME has nothing left
            // to stop. `with_state` has brought the record up to the instants the
            // clock owed it first, so this reads the status a reader would see at
            // this same instant.
            //
            // A deployment a stop ALREADY ended is not one of those: asking for
            // the state it is already in is the same request answered twice, so it
            // is answered the same way rather than refused — `StopStatus` is about
            // whether the stop has taken effect, and for this one it has.
            if crate::state::deployment_is_terminal(&deployment.status)
                && deployment.status != crate::state::DEPLOYMENT_STATUS_STOPPED
            {
                return Err(
                    StopDeploymentErrorModeled::DeploymentAlreadyCompletedException(
                        DeploymentAlreadyCompletedException {
                            message: Some(crate::state::deployment_already_completed(
                                &deployment_id,
                                &deployment.status,
                            )),
                        },
                    ),
                );
            }
            if deployment.status == crate::state::DEPLOYMENT_STATUS_STOPPED {
                return Ok(None);
            }

            let stopped_at_ms = crate::state::now_ms();
            // The rollback the caller asked for, from the one place a stopped
            // deployment's rollback is recorded: the rollback deployment, and the
            // `RollbackInfo` both records then carry. It reads what the rollback
            // inherits off the stored record, so it must run before the stop
            // itself is written.
            let rollback_info = auto_rollback_enabled
                .then(|| {
                    crate::state::rollback::record_rollback(
                        state,
                        &deployment_id,
                        stopped_at_ms,
                    )
                })
                .flatten();
            if let Some(deployment) = state.deployments.get_mut(&deployment_id) {
                // The stop takes effect at this instant, so the deployment is
                // terminal from here on and the clock owes it nothing further.
                deployment.status = crate::state::DEPLOYMENT_STATUS_STOPPED.to_string();
                deployment.complete_time_ms = Some(stopped_at_ms);
                // How the deployment ENDED, which a reader of the record is owed
                // exactly as it is owed the reason an alarm-stopped deployment
                // ended (`state::alarm_gate`): a caller stopped this one.
                deployment.error_information = Some(ErrorInformation {
                    code: Some(crate::state::ERROR_CODE_MANUAL_STOP.to_string()),
                    message: Some(crate::state::MANUAL_STOP_MESSAGE.to_string()),
                });
            }

            Ok(rollback_info)
        })
        .ok_or_else(|| {
            crate::scaffolded::Scaffolded::validation(crate::state::STATE_UNAVAILABLE)
        })?;
        let rollback_info = outcome?;
        // The traffic the stopped deployment had already moved goes back: a
        // rollback of a deployment that was shifting traffic puts the alias back
        // the way that deployment found it, from the one place an alias is written
        // (`state::lambda_traffic_shift`). Called with this store unlocked, and a
        // no-op for a stop that rolled nothing back.
        crate::state::lambda_traffic_shift::apply_due_shifts(&*self.engine);
        // A rollback the stop created is a deployment of its own, in flight from
        // here: it owes its own alias restoration and its terminal status whether
        // or not anybody calls CodeDeploy again.
        if rollback_info.is_some() {
            crate::state::deployment_clock::drive_deployment_clock(&self.engine, ctx.callback());
        }
        // The stop is a lifecycle event of the deployment, and the rollback it
        // created is one too: both were queued by the pass above, and are
        // published here with the store unlocked.
        crate::state::trigger_notifications::deliver(&*self.engine, ctx.callback()).await;

        // `StopStatus` is Pending | Succeeded
        // (`smithy_query(query="shape",shape="StopStatus")`), where Pending means
        // the stop operation has not taken effect yet. Nothing here is still
        // winding instances down — the deployment is already terminal by the time
        // this answers — so reporting Pending would claim work no part of the
        // emulator is doing.
        //
        // The message is the FIXED sentence CodeDeploy answers a stop with: what
        // stopping a deployment means for the work still scheduled on it. It names
        // neither the deployment nor the rollback, which is why the rollback this
        // stop created is reported where a rollback is reported — on both records'
        // `rollbackInfo.rollbackMessage` (`state::rollback`).
        Ok(StopDeploymentOutput {
            status: Some(STOP_STATUS_SUCCEEDED.to_string()),
            status_message: Some(STOP_STATUS_MESSAGE.to_string()),
        })
    }
}

/// The `statusMessage` CodeDeploy answers a stop with: no further lifecycle event
/// is scheduled on the deployment that was stopped.
const STOP_STATUS_MESSAGE: &str =
    "No more commands will be scheduled for execution in the deployment instances";

/// The `StopStatus` value for a stop that has already taken effect
/// (`smithy_query(query="shape",shape="StopStatus")`: Pending | Succeeded).
const STOP_STATUS_SUCCEEDED: &str = "Succeeded";
