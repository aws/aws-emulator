/// Modelled maximum of `BucketList` (`len 0..100`), the shape `AggregationResult`
/// targets: the groups past it are summed into `OtherCount`, "the number of customer
/// accounts that have a value not included in `Buckets`".
const MAX_BUCKETS: usize = 100;

/// The value a bucket of accounts with no value for the grouped field carries.
///
/// `IncludeMissing` "specifies whether to include a group for customer accounts that
/// have no value for the grouped field", and `Bucket.Values` holds at least one value,
/// so that group is named by the empty value it stands for.
const MISSING_VALUE: &str = "";

/// Group `accounts` by the field one `AggregationRequest` names.
///
/// The most populous group comes first, ties broken on the value so the order is total;
/// an account carrying several values for the field (a multi-valued one) counts in each
/// of its groups, which is why the bucket counts can sum to more than `TotalCount`.
fn aggregate(
    accounts: &[&crate::state::StoredCustomerAccount],
    request: &AggregationRequest,
    include_missing: bool,
) -> Result<AggregationResult, ValidationException> {
    use crate::state;

    // Modelled `len 1..1`, so the boundary already refused a request naming no field or
    // more than one.
    let Some(group_by) = request.group_by.first() else {
        return Err(state::field_validation(
            "REQUEST_VALIDATION_FAILED",
            "Aggregations",
            "REQUIRED_FIELD_MISSING",
            "Each aggregation must name the one field to group the customer accounts by.",
        ));
    };

    let mut counts: ::std::collections::BTreeMap<String, i32> = ::std::collections::BTreeMap::new();
    let mut missing: i32 = 0;
    for account in accounts {
        let Some(values) = state::group_values(account, group_by) else {
            return Err(state::field_validation(
                "REQUEST_VALIDATION_FAILED",
                "Aggregations",
                "INVALID_ENUM_VALUE",
                format!("`{group_by}` is not a field customer accounts can be grouped by."),
            ));
        };
        if values.is_empty() {
            missing += 1;
            continue;
        }
        for value in values {
            *counts.entry(value).or_default() += 1;
        }
    }

    let mut groups: Vec<(String, i32)> = counts.into_iter().collect();
    if include_missing && missing > 0 {
        groups.push((MISSING_VALUE.to_string(), missing));
    }
    groups.sort_by(|left, right| right.1.cmp(&left.1).then_with(|| left.0.cmp(&right.0)));

    let other_count = groups
        .iter()
        .skip(MAX_BUCKETS)
        .map(|(_, count)| *count)
        .sum();
    groups.truncate(MAX_BUCKETS);

    Ok(AggregationResult {
        group_by: request.group_by.clone(),
        buckets: groups
            .into_iter()
            .map(|(value, count)| Bucket {
                values: vec![value],
                count,
            })
            .collect(),
        other_count,
    })
}
