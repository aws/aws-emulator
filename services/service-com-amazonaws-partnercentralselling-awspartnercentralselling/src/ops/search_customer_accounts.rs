/// The `CustomerAccountSummary` view of a stored account: the summary shapes carry a
/// subset of the full members, so each one is projected from the stored record. The
/// customer details are reduced to the company name, the summary "omitting sensitive
/// fields such as the Data Universal Numbering System (DUNS) number and the street
/// address".
fn summary_of(account: &crate::state::StoredCustomerAccount) -> CustomerAccountSummary {
    CustomerAccountSummary {
        arn: account.arn.clone(),
        id: account.id.clone(),
        catalog: account.catalog.clone(),
        enrichment_status: account.enrichment_status.clone(),
        partner_account_identifier: account.partner_account_identifier.clone(),
        created_date: crate::state::date_time(account.created_date_ms),
        last_modified_date: crate::state::date_time(account.last_modified_date_ms),
        customer_account: CustomerAccountDetailsSummary {
            company_name: account.account.company_name.clone(),
        },
        aws_enrichment: account
            .aws_enrichment
            .as_ref()
            .map(|enrichment| AwsEnrichmentSummary {
                customer: enrichment.customer.as_ref().map(|customer| {
                    AwsEnrichmentCustomerSummary {
                        industry: customer.industry.clone(),
                        account_planning_qualification: customer
                            .customer_account_planning_qualification
                            .clone(),
                        eligible_programs: customer.eligible_programs.clone(),
                        geo: customer.geo.clone(),
                        country: customer.country.clone(),
                        segment: customer.segment.clone(),
                    }
                }),
                insights: enrichment.insights.as_ref().map(|insights| {
                    AwsEnrichmentInsightsSummary {
                        marketplace_engagement_score: insights
                            .marketplace_engagement_score
                            .clone(),
                        solution_category: insights.solution_category.clone(),
                        solution_score: insights.solution_score.clone(),
                    }
                }),
            }),
    }
}
