/// One of the four range conditions, which "matches when the date field" stands in the
/// named relation to "the supplied `DateValue`".
fn compares_date(
    condition: &FilterCondition,
    name: &str,
    account: &crate::state::StoredCustomerAccount,
) -> Result<bool, ValidationException> {
    let FilterValue::DateValue(bound) = &condition.value else {
        return Err(wrong_value(&condition.key, name, "a DateValue"));
    };
    let FieldValue::Date(value) = field_of(condition, account)? else {
        return Err(unsupported_field(
            &condition.key,
            name,
            "is not a date field, and the range conditions compare date fields",
        ));
    };
    let bound = crate::state::millis_of(bound);
    Ok(match name {
        "GreaterThan" => value > bound,
        "GreaterThanOrEquals" => value >= bound,
        "LessThan" => value < bound,
        _ => value <= bound,
    })
}

