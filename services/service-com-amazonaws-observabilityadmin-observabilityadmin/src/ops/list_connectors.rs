/// The most connector summaries one page carries.
///
/// It is the maximum of the modelled `ListConnectorsMaxResults` range (1..100), which
/// the centralized walk already refuses values outside of — but this handler does not
/// depend on that: the size is clamped to this constant here, so the page it allocates
/// is decided by the server, never by the request.
const MAX_PAGE_SIZE: usize = 100;

/// A page token naming the connector id the NEXT page starts at.
///
/// `ConnectorNextToken` is modelled opaque, so the id is hex-encoded rather than handed
/// back in the clear — which makes the token opaque to a caller, not secret: hex is
/// trivially reversible and the token carries nothing beyond a connector id. The
/// encoding is also inside the member's own `^[A-Za-z0-9+/=_-]+$` pattern, so a token
/// this operation issues is one it accepts back.
fn encode_page_token(id: &str) -> String {
    hex::encode(id)
}

/// The connector id a page token names, or a 400 refusal when the token carries
/// nothing this operation could have issued.
///
/// What it can decide is the FORM: every token this operation hands out carries an id
/// this service minted, so a token decoding to anything else
/// (`crate::state::is_minted_resource_id`, which lives beside the generator) is one
/// this operation never issued and is refused rather than read as a position. A
/// well-formed id the store no longer holds is NOT refused: it names the first record a
/// page did not return, and the next page resumes AT it, which is what lets a walk
/// survive the connector its last page ended on being deleted between the two calls.
fn decode_page_token(token: &str) -> Result<String, ListConnectorsError> {
    hex::decode(token)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .filter(|id| crate::state::is_minted_resource_id(id))
        .ok_or_else(|| {
            ListConnectorsErrorModeled::ValidationException(ValidationException {
                message: Some(
                    "NextToken is not a pagination token issued by ListConnectors".to_string(),
                ),
                ..Default::default()
            })
            .into()
        })
}

