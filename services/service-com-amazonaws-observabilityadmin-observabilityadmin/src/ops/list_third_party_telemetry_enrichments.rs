/// Whether `name` is inside `ThirdPartyTelemetryEnrichmentName`'s modelled 1..64 length
/// and `^[a-zA-Z][a-zA-Z0-9\-]*$` pattern, which is the whole form a page token can
/// carry.
fn is_enrichment_name(name: &str) -> bool {
    let mut characters = name.chars();
    (1..=64).contains(&name.chars().count())
        && characters.next().is_some_and(|first| first.is_ascii_alphabetic())
        && characters.all(|rest| rest.is_ascii_alphanumeric() || rest == '-')
}

