/// The member a defect is reported against when it is about the document as a whole,
/// rather than about one field the document declares.
const BODY_FIELD: &str = "Configuration.Body";

/// The path a report names the document's own root by.
const ROOT_PATH: &str = "root";

/// The property a configuration document declares its pipeline under, which is the one
/// property the schema requires of the DOCUMENT: a document declaring no pipeline is
/// reported as this property being absent, and the recorded report names exactly this
/// property for such a document.
const PIPELINE_PROPERTY: &str = "pipeline";

/// The `FieldMap` key an absent required property is reported under: what such a defect
/// is about is the property's NAME, so that is the key and the name is its value.
const NAME_KEY: &str = "name";

/// The `FieldMap` key every other defect of a property is reported under: WHERE in the
/// document the property is written, which is what tells two properties of one name
/// apart.
///
/// `pub(crate)` because the key shape belongs to the report, not to one check: the
/// other operations that answer `ValidationError`s about a configuration document
/// ([`crate::ops::update_telemetry_pipeline`]) key theirs here too, so a client reads
/// one contract.
pub(crate) const PATH_KEY: &str = "path";

/// The one property a configuration document carries beside its pipeline sections:
/// the format's version key.
const VERSION_KEY: &str = "version";

/// The properties a pipeline section declares: its source, its optional processor
/// sequence, and its sink.
const SECTION_PROPERTIES: &[&str] = &[SOURCE_KEY, PROCESSOR_KEY, SINK_KEY];

/// The properties a pipeline section MUST declare. `processor` is not one of them: a
/// pipeline that transforms nothing still reads and still writes.
const REQUIRED_SECTION_PROPERTIES: &[&str] = &[SOURCE_KEY, SINK_KEY];

/// The plugins ONE `source` or `sink` property names. `Source`'s own documentation
/// (`smithy_query(query="shape", shape="Source")`) says the pipeline "currently
/// supports a single source per pipeline, but is structured as a list to accommodate
/// multiple pipelines in the configuration", and a section's records leave through one
/// sink for the same reason: a second one is a fan-out. One is also the FEWEST it may
/// name — a property naming none reads from, or writes to, nothing.
const MAX_PLUGINS_PER_PROPERTY: usize = 1;
const MIN_PLUGINS_PER_PROPERTY: usize = 1;

/// `ValidationError$Reason` for a required property of the schema that the document
/// does not declare.
const REASON_MISSING_FIELD: &str = "MISSING_FIELD";

/// `ValidationError$Reason` for a property the schema does not define, at a place the
/// schema admits no further properties.
const REASON_UNKNOWN_PROPERTY: &str = "UNKNOWN_PROPERTY";

/// `ValidationError$Reason` for a body that could not be read as a document at all:
/// the category code this service answers for a configuration body it cannot parse.
const REASON_PARSE_ERROR: &str = "PIPELINE_CONFIGURATION_PARSE_ERROR";

/// `ValidationError$Reason` for a document that WAS parsed and declares something a
/// pipeline definition may not — the same category, for the stage after parsing.
pub(crate) const REASON_VALIDATION_ERROR: &str = "PIPELINE_CONFIGURATION_VALIDATION_ERROR";

/// `ValidationError$Reason` for a field whose value does not have the form that field
/// takes.
const REASON_INVALID_PATTERN: &str = "INVALID_PATTERN";

/// `ValidationError$Reason` for a processor, or a processor option, THIS EMULATOR does
/// not run. It is its own code because the document may well be one the real service
/// accepts: the defect is what the emulator cannot run, not a verdict that the
/// configuration is invalid, and the message says which processor it is.
const REASON_UNSUPPORTED_PROCESSOR: &str = "UNSUPPORTED_PROCESSOR";

/// The ARN syntax this service's own model declares for an ARN and for the ARN of a
/// ROLE, from `smithy_query(query="shape", shape="ResourceArn,IamRoleArn")`: the
/// `pattern` trait on the shape every ARN member targets, and the one on the shape a
/// role member targets. A field of a pipeline definition that names an ARN carries one
/// of the first; one that names the ROLE a plugin assumes carries one of the second,
/// since what it names is an IAM role.
const ARN_PATTERN: &str = r"^arn:aws([a-z0-9\-]+)?:([a-zA-Z0-9\-]+):([a-z0-9\-]+)?:([0-9]{12})?:(.+)$";

const ROLE_ARN_PATTERN: &str = r"^arn:aws[a-zA-Z-]*:iam::\d{12}:role/[\w+=,.@/-]+$";

static ARN: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(ARN_PATTERN).expect("the modelled ARN pattern compiles"));

static ROLE_ARN: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(ROLE_ARN_PATTERN).expect("the modelled role ARN pattern compiles")
});

/// Every defect in `body`, in the order the document is read in.
///
/// A defect is reported per PROBLEM the document has with the schema a pipeline
/// definition follows, named the way a schema validator names it: the property the
/// document is missing, the property the schema does not define and where it is
/// written, the list that carries more items than the schema allows. The document is
/// read once, through the one bounded reader this crate has, and the checks below are
/// all independent of each other — so a document with four problems answers four
/// errors rather than the first conclusion a reader stopped at.
fn configuration_defects(body: &str) -> Vec<ValidationError> {
    let root = match parse_configuration(body) {
        Ok(root) => root,
        // A body the reader never read has no fields to report a defect against, so
        // the syntax error is the whole answer.
        Err(why) => return vec![defect(BODY_FIELD, REASON_PARSE_ERROR, why)],
    };

    let sections = declared_sections(&root);
    // The schema's vended-log branches first: what a pipeline reading AWS-vended log
    // events may run is a restriction on the properties the document declares, so it is
    // reported ahead of the defects of those properties themselves.
    let mut defects = vended_log_schema::vended_log_defects(&sections);
    defects.extend(schema_defects(&root, &sections));
    // The chain is a property of the document as a whole: which section reads which.
    // A document that declares no section has no chain to report anything about —
    // what it is missing is the pipeline itself, which `schema_defects` has just
    // reported.
    if !sections.is_empty() {
        if let Err(why) = processor_chain(&root) {
            defects.push(defect(BODY_FIELD, REASON_VALIDATION_ERROR, why));
        }
    }
    arn_defects(&root, "", &mut defects);
    defects
}

/// Every defect the document has against the schema's properties: the required ones it
/// does not declare, the ones the schema does not define, the ones carrying a number of
/// items the schema does not allow, and the processors this emulator does not run.
///
/// `sections` is the pipeline sections the document declares
/// ([`declared_sections`]), read once by the caller because the chain check needs the
/// same answer.
fn schema_defects(root: &Node, sections: &[(&str, &Node)]) -> Vec<ValidationError> {
    let mut defects = Vec::new();
    let entries = root.as_mapping().unwrap_or_default();
    let root_is_section = is_section(root);
    // The compiled patterns one request holds, counted across every processor position
    // of every section rather than per position: the per-pattern bounds alone would
    // leave the SUM of the compiled automata to the document's own length.
    let mut patterns = 0usize;

    // What the document may write at its root: the version key, one pipeline section
    // per name — and, when it writes its one pipeline at the top level, that section's
    // own properties.
    for (property, value) in entries {
        let defined = property == VERSION_KEY
            || (root_is_section && SECTION_PROPERTIES.contains(&property.as_str()))
            || (!root_is_section && is_section(value));
        if !defined {
            defects.push(unknown_property(property, ROOT_PATH));
        }
    }

    if sections.is_empty() {
        // The document declares no pipeline, so the property the schema requires of a
        // document is what is absent — not the properties of a section the document
        // never declared.
        defects.push(missing_field(PIPELINE_PROPERTY));
        return defects;
    }

    for (name, section) in sections {
        let prefix = defect_prefix(name);
        // A section the document declares under a NAME is checked against the same
        // section schema; a document writing its pipeline at the top level had those
        // properties checked by the root walk above, where the version key is defined
        // too.
        if !name.is_empty() {
            for (property, _) in section.as_mapping().unwrap_or_default() {
                if !SECTION_PROPERTIES.contains(&property.as_str()) {
                    defects.push(unknown_property(property, &property_path(prefix, property)));
                }
            }
        }
        defects.extend(section_defects(prefix, section, &mut patterns));
    }
    defects
}

/// The prefix a defect INSIDE the section declared under `name` is reported at.
///
/// The document's own pipeline — the one it declares under the [`PIPELINE_PROPERTY`]
/// the schema requires, and the one a document writing its `source`/`processor`/`sink`
/// at the top level is — carries no prefix: a defect in it is named relative to the
/// document, which is how the recorded report names a processor position
/// (`processor[0]`). Any OTHER section the document declares is a pipeline of its own,
/// so a defect in it is named under that section's name, which is what tells the two
/// sections' defects apart.
fn defect_prefix(name: &str) -> &str {
    if name == PIPELINE_PROPERTY {
        return "";
    }
    name
}

/// The path the property `property` of the section at `prefix` is WRITTEN at, which is
/// what a defect of that property is reported by: the property's own name inside the
/// document's pipeline, and that name under its section's for any other section — the
/// same relative naming a processor position takes ([`processor_path`]).
fn property_path(prefix: &str, property: &str) -> String {
    if prefix.is_empty() {
        return property.to_string();
    }
    format!("{prefix}.{property}")
}

/// One defect per property of `section` that the schema requires and the section does
/// not declare, and one per property naming a number of plugins the schema does not
/// allow for it.
///
/// A property the section does not declare at all is a MISSING one; a property it
/// declares that names no plugin, or more than the schema allows, is a property whose
/// VALUE is wrong, and is reported as the item count it carries.
fn section_defects(prefix: &str, section: &Node, patterns: &mut usize) -> Vec<ValidationError> {
    let mut defects = Vec::new();
    for property in REQUIRED_SECTION_PROPERTIES {
        let Some(value) = section.get(property) else {
            defects.push(missing_field(property));
            continue;
        };
        let named = plugins_named(value);
        if named < MIN_PLUGINS_PER_PROPERTY {
            defects.push(too_few_items(&property_path(prefix, property), named));
        } else if named > MAX_PLUGINS_PER_PROPERTY {
            defects.push(too_many_items(&property_path(prefix, property), named));
        }
    }
    defects.extend(processor_defects(prefix, section, patterns));
    defects
}

/// One defect per POSITION of a section's `processor` sequence this emulator cannot
/// run: a processor it does not run, or one of its options it does not take.
///
/// Each position is judged on its own, so a defect at one position never hides the
/// defect at another; the `FieldMap` carries that position's path, which is what tells
/// a caller WHICH processor of the sequence the message is about.
///
/// The category is this emulator's own ([`REASON_UNSUPPORTED_PROCESSOR`]) and NOT the
/// schema's "not defined" one: the catalogue the real service validates a processor
/// NAME against is not in this service's model, and the document may well be one it
/// accepts — what this emulator knows is which processors IT runs.
fn processor_defects(prefix: &str, section: &Node, patterns: &mut usize) -> Vec<ValidationError> {
    let Some(Node::Sequence(items)) = section.get(PROCESSOR_KEY) else {
        return Vec::new();
    };
    items
        .iter()
        .enumerate()
        .filter_map(|(index, item)| {
            // An entry naming no plugin, or more than one, is a defect of the
            // sequence's own form and is reported as that.
            let [(name, options)] = item.as_mapping()? else {
                return None;
            };
            step_defect(name, options, patterns)
                .err()
                .map(|why| unsupported_processor(&processor_path(prefix, index), why))
        })
        .collect()
}

/// The path of the `processor` entry at `index` of the section at `prefix`.
fn processor_path(prefix: &str, index: usize) -> String {
    if prefix.is_empty() {
        return format!("{PROCESSOR_KEY}[{index}]");
    }
    format!("{prefix}.{PROCESSOR_KEY}[{index}]")
}

/// The defect of a required property the document does not declare, worded the way a
/// schema validator words it.
///
/// The `FieldMap` carries the missing property's own NAME, under the [`NAME_KEY`] the
/// recorded report keys such a defect by: the one variable part of this defect is the
/// name of the property the document failed to declare, which is what a console or CLI
/// reads to point at the field to add.
fn missing_field(property: &str) -> ValidationError {
    ValidationError {
        message: Some(missing_property_message(property)),
        reason: Some(REASON_MISSING_FIELD.to_string()),
        field_map: Some(HashMap::from([(
            NAME_KEY.to_string(),
            property.to_string(),
        )])),
    }
}

/// The defect of a property the schema does not define, worded the way a schema
/// validator words it. The `FieldMap` carries the path the property is written at,
/// which is what tells two properties of one name apart.
fn unknown_property(property: &str, path: &str) -> ValidationError {
    at_path(
        path,
        REASON_UNKNOWN_PROPERTY,
        undefined_property_message(property),
    )
}

/// The sentence a schema validator words an ABSENT required property with. The
/// template is the report's own, so every check that reports one — a property of the
/// document, a property of a section, a property a vended-log branch requires
/// ([`vended_log_schema`]) — words it identically and only the property's name differs.
pub(crate) fn missing_property_message(property: &str) -> String {
    format!("required property '{property}' not found")
}

/// The sentence a schema validator words a property the schema does not DEFINE with,
/// at a place the schema admits no further properties. Shared for the reason
/// [`missing_property_message`] is.
pub(crate) fn undefined_property_message(property: &str) -> String {
    format!(
        "property '{property}' is not defined in the schema and the schema does not allow \
         additional properties"
    )
}

/// The sentence a schema validator words a property carrying more items than the schema
/// allows with: the limit that property has, and how many items it carries. Shared for
/// the reason [`missing_property_message`] is — the limit is the one the check that
/// reports it applies, which is the plugin count for a `source` or a `sink` and the
/// processors a vended-log branch admits for a `processor` sequence.
pub(crate) fn at_most_items_message(limit: usize, found: usize) -> String {
    format!("must have at most {limit} items but found {found}")
}

/// The defect of a processor position this emulator cannot run: the refusal the
/// processor's own compile answered, reported under this emulator's own category, with
/// the `FieldMap` carrying the position's path in the document.
fn unsupported_processor(path: &str, why: String) -> ValidationError {
    at_path(path, REASON_UNSUPPORTED_PROCESSOR, why)
}

/// The defect of a property carrying more items than the schema allows for it, worded
/// the way a schema validator words it, and reported at the path the property is written
/// at — what is wrong is that property's VALUE, so the report names where it is.
///
/// The CATEGORY is this service's own: the recording shows that wording only under a
/// data-source restriction's reason, which this problem is not, and the reason the real
/// service answers for a plain item-count violation is not in the model — so nothing
/// here claims it was verified.
fn too_many_items(path: &str, found: usize) -> ValidationError {
    at_path(
        path,
        REASON_VALIDATION_ERROR,
        at_most_items_message(MAX_PLUGINS_PER_PROPERTY, found),
    )
}

/// The defect of a property carrying fewer items than the schema allows for it, worded
/// and keyed the way [`too_many_items`] is.
fn too_few_items(path: &str, found: usize) -> ValidationError {
    at_path(
        path,
        REASON_VALIDATION_ERROR,
        format!("must have at least {MIN_PLUGINS_PER_PROPERTY} items but found {found}"),
    )
}

/// One defect per field of the document whose NAME names an ARN and whose value is
/// not one.
///
/// A pipeline definition names an ARN wherever a plugin needs an identity or a
/// resource to reach — the role a source assumes, the resource a sink writes to — and
/// the name of such a field ends in the token `arn`. `path` is where in the document
/// the walk currently is, so the defect says which of them carries the value.
///
/// The walk recurses over a tree the reader has already bounded — a document past its
/// node count or its nesting depth never becomes one — so the depth of this recursion
/// is bounded by those constants rather than by the request.
fn arn_defects(node: &Node, path: &str, defects: &mut Vec<ValidationError>) {
    match node {
        Node::Mapping(entries) => {
            for (key, value) in entries {
                let here = if path.is_empty() {
                    key.clone()
                } else {
                    format!("{path}.{key}")
                };
                if let Some(constraint) = arn_constraint(key) {
                    if !constraint.pattern.is_match(scalar_text(value)) {
                        defects.push(pattern_defect(&here, value, constraint));
                    }
                }
                arn_defects(value, &here, defects);
            }
        }
        Node::Sequence(items) => {
            for (index, item) in items.iter().enumerate() {
                arn_defects(item, &format!("{path}[{index}]"), defects);
            }
        }
        Node::Null | Node::Scalar { .. } => {}
    }
}

/// The pattern the value of `key` has to match, for a field of a pipeline definition
/// that names an ARN — a field whose last name token is `arn`. A field whose name ends
/// in the two tokens `role`, `arn` names an IAM role, so it takes the narrower of the
/// two patterns.
fn arn_constraint(key: &str) -> Option<ArnConstraint> {
    let tokens = name_tokens(key);
    let mut tail = tokens.iter().rev();
    if tail.next().map(String::as_str) != Some("arn") {
        return None;
    }
    if tail.next().map(String::as_str) == Some("role") {
        return Some(ArnConstraint {
            pattern: &ROLE_ARN,
            source: ROLE_ARN_PATTERN,
        });
    }
    Some(ArnConstraint {
        pattern: &ARN,
        source: ARN_PATTERN,
    })
}

/// A field name's tokens, lowercased: the words a document's key is built from,
/// however it separates them. This format writes `sts_role_arn`, and the same document
/// written as JSON may write `stsRoleArn`, so both read as the same field.
fn name_tokens(key: &str) -> Vec<String> {
    let mut tokens: Vec<String> = Vec::new();
    let mut token = String::new();
    for character in key.chars() {
        if matches!(character, '_' | '-' | '.') {
            if !token.is_empty() {
                tokens.push(::std::mem::take(&mut token));
            }
        } else if character.is_ascii_uppercase() && !token.is_empty() {
            tokens.push(::std::mem::take(&mut token));
            token.push(character.to_ascii_lowercase());
        } else {
            token.extend(character.to_lowercase());
        }
    }
    if !token.is_empty() {
        tokens.push(token);
    }
    tokens
}

/// One ARN constraint: the compiled pattern a value is measured against, and the
/// pattern as the report spells it.
struct ArnConstraint {
    pattern: &'static Regex,
    source: &'static str,
}

/// The text a scalar carries; anything else carries none, which no pattern matches.
fn scalar_text(node: &Node) -> &str {
    match node {
        Node::Scalar { text, .. } => text.as_str(),
        _ => "",
    }
}

/// How many plugins a section's `source` or `sink` names: one per entry of the mapping
/// a `source` is, and one per entry of each single-plugin mapping of the sequence a
/// `sink` is written as. Anything else names no plugin at all.
fn plugins_named(node: &Node) -> usize {
    match node {
        Node::Mapping(entries) => entries.len(),
        Node::Sequence(items) => items.iter().map(plugins_named).sum(),
        Node::Null | Node::Scalar { .. } => 0,
    }
}

/// One reported defect about the document as a WHOLE: what is wrong, which category it
/// falls in, and the input member the document arrived in — a body that was never read,
/// or a set of sections that do not form one chain, is about no single field of it.
fn defect(field: &str, reason: &str, message: String) -> ValidationError {
    ValidationError {
        message: Some(message.clone()),
        reason: Some(reason.to_string()),
        field_map: Some(HashMap::from([(field.to_string(), message)])),
    }
}

/// One reported defect PINNED TO A FIELD of the document: what is wrong, which category
/// it falls in, and WHERE in the document the field is.
///
/// The `FieldMap` carries that location under the report's own [`PATH_KEY`], whose value
/// is the field's full dotted document path — never the field's own bare name, which
/// says nothing about which of two fields of that name the defect is about and is not
/// the key a client following the report's contract reads.
pub(crate) fn at_path(path: &str, reason: &str, message: String) -> ValidationError {
    ValidationError {
        message: Some(message),
        reason: Some(reason.to_string()),
        field_map: Some(HashMap::from([(
            PATH_KEY.to_string(),
            path.to_string(),
        )])),
    }
}

/// The defect of a field whose value does not have the form that field takes: the
/// value, where in the document it is and the constraint it did not satisfy, worded
/// the way AWS words a constraint violation. A field carrying no scalar at all shows
/// an empty value, which is what it has.
fn pattern_defect(path: &str, value: &Node, constraint: ArnConstraint) -> ValidationError {
    let shown = scalar_text(value);
    at_path(
        path,
        REASON_INVALID_PATTERN,
        format!(
            "Value '{shown}' at '{path}' failed to satisfy constraint: Member must satisfy \
             regular expression pattern: {}",
            constraint.source
        ),
    )
}
