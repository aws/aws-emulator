//! @op ValidateTelemetryPipelineConfiguration
//!
//! Reads the request's `Configuration` as a pipeline definition and answers the
//! defects found in it — one `ValidationError` per defect, each naming the field of the
//! document it is about — or no `Errors` at all for a configuration this emulator would
//! run. The call "[v]alidates a pipeline configuration without creating the pipeline",
//! so it mints no pipeline, stores nothing and reads no stored one.
//!
//! ## What a defect is
//!
//! The document is the same YAML (or JSON, which YAML 1.2 is a superset of) definition
//! `CreateTelemetryPipeline` stores and `TestTelemetryPipeline` runs, so it is read
//! through that operation's bounded reader
//! ([`crate::ops::test_telemetry_pipeline`]) rather than through a second one that
//! could disagree with it. Four kinds of defect are reported:
//!
//! * the body is not a document this emulator reads — a syntax error, an alias, or
//!   nesting past what it reads — which is the one defect reported for such a body,
//!   since a body that was never read has no fields to report anything else against;
//! * the document declares no pipeline at all, which is the one property the pipeline
//!   schema requires of a DOCUMENT (`pipeline`) being absent, and the only defect
//!   reported for such a document: a document that declares no pipeline has no
//!   section whose own properties could be reported;
//! * the sections the document does declare do not form ONE chain: a sink naming a
//!   section the document does not declare, a cycle, a fan-out to two pipelines, or a
//!   section nothing reaches;
//! * a section does not declare a property the pipeline schema requires of it, or
//!   declares one the schema does not define, or declares one carrying a number of
//!   items the schema does not allow — each reported the way a schema validator
//!   reports that keyword: an ABSENT required property under the report's `name` key,
//!   which is the property's own name, and everything else at the PATH in the document
//!   it is about, named relative to the document's own pipeline;
//! * a section reading log events AWS vends runs a processor the schema's branch for
//!   that source does not admit, or more of them than it admits, or leaves out a
//!   property that branch's source requires — each reported under the restriction's own
//!   reason, keyed by the restriction's descriptors, and a position naming a processor
//!   that branch does not define at all reported as the undefined property it is
//!   ([`vended_log_schema`]);
//! * a position of a section's `processor` sequence names a processor, or an option,
//!   this emulator does not run, which carries its own reason code because the document
//!   may be one the real service accepts: what the emulator cannot RUN is a different
//!   observation from what the schema does not define;
//! * a field of the document whose name names an ARN (its last name token is `arn`:
//!   the role a source assumes, the resource a sink writes to) does not carry one,
//!   measured against the ARN syntax this service's own model declares — the narrower
//!   IAM role syntax for a field that names the role a plugin assumes.
//!
//! A defect is REPORTED, not refused: this operation's own output is where the error
