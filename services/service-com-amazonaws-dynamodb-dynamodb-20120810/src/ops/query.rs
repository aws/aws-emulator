//! @op Query
//! IMPLEMENTED: reads the items of one partition out of the stored table, in sort
//! key order (descending when `ScanIndexForward=false`), with `Count`/`ScannedCount`
//! and `LastEvaluatedKey` computed from the result.
//!
//! The key conditions come either from `KeyConditionExpression` (with
//! `ExpressionAttributeNames`/`ExpressionAttributeValues`) or from the legacy
//! `KeyConditions` map: both reduce to equality on the partition key optionally
//! ANDed with one `=`/`<`/`<=`/`>`/`>=`/`BETWEEN`/`begins_with` comparison on the
//! RANGE key attributes, which a schema declaring several of them constrains from the
//! first ([`KeyCondition::resolve`]). The expression grammar is parsed here — it is
//! DynamoDB's own, so there is no third-party parser for it — by
//! [`parse_key_condition_expression`], which takes a comparison with the operand on
//! either side of the operator. An expression defect the REQUEST alone settles (its
//! syntax, a substitution token it uses but does not define) is refused there, before
//! any table is looked up; an operand is held to the types the operator it was written
//! with compares ([`check_operand_type`]) where it BINDS to the key attribute its
//! comparison names, so a query addressing a table this account does not hold is
//! refused as the absent table it names whatever its operands are.
//!
//! `FilterExpression` is applied AFTER the key conditions have selected the page —
//! "a filter expression is applied after a Query finishes, but before the results are
//! returned" — so the items it removes are still read and still charged for, and
//! `ScannedCount` therefore counts what the page evaluated while `Count` counts what
//! it answered. It is the `ConditionExpression` language, parsed by the one parser
//! this crate has for it ([`crate::state::ParsedCondition`]), and it "does not allow
//! key attributes".
//!
//! A query naming an `IndexName` reads one partition of that SECONDARY INDEX instead,
//! in the index's own key order with the table's primary key breaking the tie: an item
//! the index does not cover is not there to be read, and each entry carries the
//! attributes the index projects. What each reported item is narrowed to is the
//! request's `Select` and whichever projection member it named — `ProjectionExpression`
//! with its `ExpressionAttributeNames` aliases, or the legacy `AttributesToGet` —
//! applied AFTER the filter, so an attribute the response does not carry can still
//! narrow the read. Which index was named, what the selection is and whether the read
//! has to go on to the parent table are the rules `Scan` reads an index by too
//! ([`crate::state::indexed_read`]).
//!
//! The legacy result filter (`QueryFilter` with `ConditionalOperator`) states the same
//! filter one generation back, lowered onto the one filter both readers of this service
//! share ([`crate::state::ReadFilter`]). `ConsistentRead` needs no handling
//! beyond its effect on `ConsumedCapacity`, this store having one copy of each item,
//! except on a global secondary index, which does not support it and refuses the
//! request.
//!
//! A key-condition operand is held to the documented key-value limits
//! ([`crate::state::Table::check_key_limits`]), and a table whose resource-based policy
//! denies the caller `dynamodb:Query` is answered `AccessDeniedException` instead of
//! its items.
//!
//! Every size a request can choose here is bounded: the expression's length, token
//! count and parenthesis nesting (see [`tokenize`] and [`Parser`]), and the page the
//! response carries ([`crate::state::MAX_PAGE_BYTES`]), so one `Query` cannot drive
//! unbounded work or an unbounded response.
