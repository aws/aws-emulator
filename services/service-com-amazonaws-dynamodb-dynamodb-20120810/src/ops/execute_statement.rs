/// `SELECT`: the stored items the statement reports, in the order it asked for.
fn select_items(
    store: &mut Store,
    region: &str,
    name: &str,
    now: ::std::time::SystemTime,
    select: &crate::state::SelectStatement,
    input: &ExecuteStatementInput,
) -> Result<ExecuteStatementOutput, ExecuteStatementError> {
    let condition = select
        .filter
        .as_ref()
        .map(crate::state::parsed_condition)
        .transpose()
        .map_err(lift)?;
    let resume = input
        .next_token
        .as_deref()
        .map(|token| crate::state::decode_cursor(&input.statement, token))
        .transpose()
        .map_err(lift)?;
    let table = store.active_table(region, name, now).map_err(lift)?;
    // A statement whose source qualifier names an index this table does not declare is
    // a bad STATEMENT rather than a resource that could not be found: the table was
    // resolved, and nothing it carries answers to that name. An index the table DOES
    // carry, of a kind no statement is served from, is refused as that index type instead
    // ([`crate::state::check_statement_source_index`]).
    if let Some(index) = select.index.as_deref() {
        crate::state::check_statement_source_index(table, index).map_err(lift)?;
        // "Global secondary indexes support eventually consistent reads only, so do not
        // specify ConsistentRead when querying a global secondary index"
        // (`Query$ConsistentRead`). A LOCAL secondary index shares the table's
        // partitions and does support one, so the refusal turns on WHICH KIND of index
        // the statement's source qualifier names.
        if input.consistent_read == Some(true) && crate::state::is_global_index(table, index) {
            return Err(crate::scaffolded::Scaffolded::validation(
                "Strongly consistent read is not supported on Global Secondary Indexes",
            ));
        }
        // What the statement REPORTS is served from the index, and a global one cannot
        // fetch what it does not project ([`crate::state::index_projection_refusal`]).
        if let Some(refusal) =
            crate::state::index_projection_refusal(table, index, select.projection.as_ref())
        {
            return Err(lift(refusal));
        }
        // A predicate is judged against what the SOURCE reports, so a filter on an
        // attribute the named index does not project could never be decided from the
        // range of its keys a KEY CONDITION addresses — while a walk of the whole index
        // evaluates the same predicate against each entry, which matches nothing
        // ([`crate::state::index_filter_refusal`]).
        if let Some(refusal) =
            crate::state::index_filter_refusal(table, index, select.filter.as_ref())
        {
            return Err(lift(refusal));
        }
    }
    // A projection item that is no document path is refused once the SOURCE it reads has
    // been resolved ([`crate::state::projection_defect`]).
    if let Some(defect) = crate::state::projection_defect(select.projection.as_ref()) {
        return Err(lift(defect));
    }
    // Which low-level plan the statement is served by is decided HERE, from what its
    // `WHERE` clause pins: "a WHERE clause on the partition key" is planned as a Query
    // over that one partition of the SOURCE the statement reads — one partition of the
    // table's items is contiguous in the store, so that is a range read, and one of an
    // index is the entries its own partition key selects — narrowed again to the single
    // entry when the range key is pinned too, and a clause that pins no partition key is
    // planned as a full scan of the source. The plan decides what is READ, and therefore
    // what the statement is charged for; the predicate is applied to each row the plan
    // read, and never narrows the read itself.
    //
    // An equality the clause pins on a key attribute is held to the type the table
    // declared for it FIRST: a value of another type addresses nothing the table can
    // hold, so the statement is refused rather than planned as a scan that answers no
    // rows.
    crate::state::check_pinned_key_types(table, select.filter.as_ref()).map_err(lift)?;
    // A clause whose `OR` branches each ask for their own range of the source's keys
    // asks for ranges that overlap, which no one range read answers
    // ([`crate::state::overlapping_range_key_conditions`]).
    if let (Some(filter), Some(sort_key)) = (
        select.filter.as_ref(),
        crate::state::source_sort_key_name(table, select.index.as_deref()),
    ) {
        if crate::state::overlapping_range_key_conditions(filter, &sort_key) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::OVERLAPPING_RANGE_KEY_MESSAGE,
            ));
        }
    }
    let pinned = select
        .filter
        .as_ref()
        .map(crate::state::pinned_equalities)
        .unwrap_or_default();
    // The PARTITION of the source the clause pins, with the attribute that pins it: the
    // index's own partition key where the `FROM` target names an index, the table's
    // otherwise ([`crate::state::source_partition_key_name`]) — the same question that
    // decides whether a statement reads every entry of its source
    // ([`crate::state::statement_scans_whole_source`]). A statement that pins it is served
    // as a query of that one partition, whichever source it names, and one that pins none
    // walks the whole source.
    let keyed: Option<(String, crate::state::AttributeValueKey)> =
        crate::state::source_partition_key_name(table, select.index.as_deref()).and_then(
            |attribute| {
                let value = pinned.get(&attribute)?;
                let key = table.key_value(&attribute, value).ok()?;
                Some((attribute, key))
            },
        );
    // Where the source is the table ITSELF, that partition is a range of the store's own
    // keys, which is what the walk below is bounded by; an index's entries are keyed by
    // the index's schema, so its partition is selected by the attribute instead.
    let partition = select
        .index
        .is_none()
        .then(|| keyed.as_ref().map(|(_, key)| key.clone()))
        .flatten();
    // A sort key pinned by equality addresses ONE item of that partition, which is the
    // narrowest plan there is; without a partition key it narrows nothing, because the
    // store is partitioned first.
    let sort = partition
        .as_ref()
        .and_then(|_| table.sort_key_name())
        .and_then(|attribute| {
            pinned
                .get(attribute)
                .and_then(|value| table.key_value(attribute, value).ok())
        });

    // "ORDER BY clause can only be used on a key attribute" — a statement that asks
    // for any other order is refused rather than served in a different one. An order
    // is also only served over ONE partition of the source: inside a partition the
    // entries already stand in sort-key order, so the order asked for is that order or
    // its reverse, and a page resumed from a `NextToken` continues in exactly it. Across
    // partitions the two orders differ, so a statement that asks for one without
    // pinning the partition key of the source it reads is refused instead of answered in
    // another order.
    if let Some((attribute, _)) = select.order_by.as_ref() {
        // "Must have WHERE clause in the statement when using ORDER BY clause": the order
        // is served over ONE partition of the source, and the predicate is what names that
        // partition — so a statement stating no predicate at all is refused for the clause
        // it does not state, before the attribute it orders by is judged.
        if select.filter.is_none() {
            return Err(crate::scaffolded::Scaffolded::validation(
                ORDER_BY_WITHOUT_WHERE_MESSAGE,
            ));
        }
        if !crate::state::orderable_attributes(table, select.index.as_deref())
            .contains(attribute.as_str())
        {
            return Err(crate::scaffolded::Scaffolded::validation(
                order_by_not_a_key_message(attribute),
            ));
        }
        if keyed.is_none() {
            return Err(crate::scaffolded::Scaffolded::validation(
                "ORDER BY is supported only for a statement whose WHERE clause states an \
                 equality on the partition key of the source it reads",
            ));
        }
    }

    let mut candidates: Vec<(&crate::state::ItemKey, &crate::state::Item)> = match &partition {
        Some(partition) => table
            .items
            .range(crate::state::ItemKey {
                partition: partition.clone(),
                sort: sort.clone(),
            }..)
            .take_while(|(key, _)| {
                &key.partition == partition && sort.as_ref().is_none_or(|sort| key.sort.as_ref() == Some(sort))
            })
            .collect(),
        None => table.items.iter().collect(),
    };
    // An index holds only the items that carry every attribute its key schema names, so
    // a statement reading an index has exactly those rows to read: an item it does not
    // hold is not there to be read, let alone charged for.
    if let Some(index) = select.index.as_deref() {
        candidates.retain(|(_, item)| crate::state::index_holds(table, index, item));
        // An index's entries are keyed by the index's own schema, so a clause that pins
        // that schema's partition key — and, inside it, its range key — addresses those
        // entries and nothing else: the plan READS that partition of the index, exactly as
        // a base-table query reads one partition of the store, so no other entry is
        // evaluated or charged for.
        for (attribute, value) in keyed.iter().cloned().chain(
            crate::state::source_sort_key_name(table, Some(index))
                .and_then(|attribute| {
                    let value = pinned.get(&attribute)?;
                    let key = table.key_value(&attribute, value).ok()?;
                    Some((attribute, key))
                })
                // A range key narrows a partition; on its own it narrows nothing, because
                // the index is partitioned first.
                .filter(|_| keyed.is_some()),
        ) {
            candidates.retain(|(_, item)| {
                item.get(&attribute)
                    .and_then(|held| table.key_value(&attribute, held).ok())
                    .is_some_and(|held| held == value)
            });
        }
    }
    if let Some((attribute, descending)) = select.order_by.as_ref() {
        candidates.sort_by(|(_, left), (_, right)| {
            crate::state::compare_by_attribute(left, right, attribute, *descending)
        });
    }
    if let Some(resume) = resume.as_ref() {
        // "Set this value to get remaining results" (`NextToken`): the next page
        // starts strictly after the row the previous one stopped on.
        match candidates.iter().position(|(key, _)| *key == resume) {
            Some(position) => {
                candidates.drain(..=position);
            }
            // The row that page stopped on has since been removed; resume at the
            // first one that sorts after it IN THE DIRECTION being read. `ORDER BY`
            // names a key attribute of the source, so the store's own key order is
            // the order being read, forwards or (for `DESC`) backwards.
            None => {
                let descending = select
                    .order_by
                    .as_ref()
                    .is_some_and(|(_, descending)| *descending);
                candidates.retain(|(key, _)| {
                    if descending {
                        *key < resume
                    } else {
                        *key > resume
                    }
                });
            }
        }
    }

    // What the page READ: "A single SELECT statement response can return up to the
    // maximum number of items (if using the Limit parameter) or a maximum of 1 MB of
    // data (and then apply any filtering to the results using WHERE clause)" (the
    // operation's own doc), so the caller's `Limit` and the dataset budget bound the
    // rows the plan EVALUATES, and the `WHERE` clause is applied to each of them
    // afterwards. The bytes counted here are therefore the bytes the plan read, which
    // is what the statement consumes: a predicate that keeps fewer rows costs exactly
    // what the same plan without it costs.
    let limit = input
        .limit
        .map_or(usize::MAX, |limit| usize::try_from(limit).unwrap_or(0));
    let mut page_size: i64 = 0;
    // The same bytes as this table METERS them ([`crate::state::Table::metered_item_size`]),
    // which is what the capacity figures are computed over: the page's own 1 MB budget is
    // about the bytes the response carries, while what a read COSTS counts a vector at the
    // four bytes per dimension it is held as.
    let mut metered_size: i64 = 0;
    // What the rows the plan evaluated COST, where the plan is a scan: one read unit per
    // 4 KB of EACH row, half a unit where the read is eventually consistent, and a whole
    // unit per 4 KB of each entry where the source is a secondary index — the charge a
    // `Scan` of the same rows carries ([`crate::ops::scan`]).
    let mut page_units: f64 = 0.0;
    // An index reports the attributes it PROJECTS — "only the attributes that are
    // projected into the index are reported" — so an index is also what the statement
    // READ: the bytes a row costs are the bytes its source holds for that row, which for
    // a statement whose source is a secondary index are the attributes that index
    // projects and not the whole stored item. A statement that names an attribute a LOCAL
    // index does not project is served the whole stored item instead, FETCHED from the
    // parent table ([`crate::state::statement_source_attributes`] answers `None` for it).
    let projected = crate::state::statement_source_attributes(
        table,
        select.index.as_deref(),
        select.projection.as_ref(),
        select.filter.as_ref(),
    );
    // What the INDEX itself holds for a row, which is what reading the index costs
    // whatever the read went on to fetch from the table
    // ([`crate::state::projected_attributes`]).
    let entry = crate::state::projected_attributes(table, select.index.as_deref());
    // "If any of the requested attributes are not projected into the local secondary
    // index, DynamoDB fetches each of these attributes from the parent table"
    // (`Query$Select`): the statement then reports more than its index holds, and each of
    // those fetches is a read of THAT item on the TABLE's own arm
    // ([`crate::state::fetch_capacity_units`]) — the same two arms the `Query` of the same
    // index is billed in.
    let fetches_from_table = select.index.is_some() && projected.is_none() && entry.is_some();
    // What this read spends on the TABLE rather than on the index it read: the base-table
    // fetches it made, charged per item.
    let mut fetched_units: f64 = 0.0;
    let mut evaluated = 0usize;
    // What each row the page KEPT reports: the attributes its source held for it.
    let mut rows: Vec<crate::state::Item> = Vec::new();
    for (_key, item) in &candidates {
        // The first row always fits, the way DynamoDB always returns at least one
        // item it found; after that the page stops once the rows it holds have CROSSED
        // the budget ([`crate::state::page_budget_spent`]).
        if evaluated >= limit || (evaluated > 0 && crate::state::page_budget_spent(page_size)) {
            break;
        }
        // What the SOURCE holds for this row, which is what the predicate is judged
        // against, what the response carries and what the read is charged for. A source
        // that holds the whole stored item — the table itself, and an index read that
        // fetched — IS that item, so it is read where it stands and copied only for the
        // rows the page keeps.
        let narrowed = projected
            .as_ref()
            .map(|allowed| held_item(item, Some(allowed)));
        let held: &crate::state::Item = narrowed.as_ref().unwrap_or(item);
        page_size = page_size.saturating_add(crate::state::item_size(held));
        // What the row is BILLED for ON ITS SOURCE is what the INDEX holds for it — the
        // stored item itself where the source is the table — weighed as this table meters
        // an item ([`crate::state::Table::metered_item_size`]): a vector at the four bytes
        // per dimension it is held as, while the page's own budget above stays the bytes
        // the response carries.
        let in_index = entry.as_ref().map(|allowed| held_item(item, Some(allowed)));
        let metered = table.metered_item_size(in_index.as_ref().unwrap_or(held));
        metered_size = metered_size.saturating_add(metered);
        // A plan that walks a SECONDARY INDEX is charged over what that index holds for
        // each row, in whole read units, exactly as the `Scan` of the same index is — one
        // rule for every reader that charges per row over a walk
        // ([`crate::state::walk_row_capacity_units`]); a plan that walks the table's own
        // items takes the rate the statement asked to read them with.
        page_units += crate::state::walk_row_capacity_units(
            select.index.is_some(),
            metered,
            input.consistent_read.unwrap_or(false),
        );
        // A row the read had to fetch from the table cost that item's own read beside the
        // index's, charged per item in whole units.
        if fetches_from_table {
            fetched_units += crate::state::fetch_capacity_units(
                table.metered_item_size(held),
                input.consistent_read.unwrap_or(false),
            );
        }
        evaluated += 1;
        // The predicate is judged against what the source REPORTS for the row — the
        // index's entry where the statement reads an index, which is the same item a
        // `Scan` of that index judges its filter against.
        if let Some(condition) = condition.as_ref() {
            if !condition.evaluate(Some(held)).map_err(lift)? {
                continue;
            }
        }
        rows.push(match narrowed {
            Some(narrowed) => narrowed,
            None => (*item).clone(),
        });
    }
    // A page that spent its 1 MB budget stopped there, whether or not a row remains, by
    // the rule every reader that pages follows ([`crate::state::page_budget_spent`]).
    let truncated = candidates.len() > evaluated || crate::state::page_budget_spent(page_size);

    // "The primary key of the item where the operation stopped": the last row the page
    // EVALUATED, which is where a resumed page carries on from whether or not the
    // predicate kept that row.
    let stopped_on = evaluated
        .checked_sub(1)
        .and_then(|last| candidates.get(last))
        .map(|(key, item)| ((*key).clone(), table.key_attributes(item)));
    // The statement's own projection narrows what the source holds for a row further.
    let items: Vec<crate::state::Item> = rows
        .iter()
        .map(|held| crate::state::project_item(held, select.projection.as_ref()))
        .collect();
    // A page that stopped short of the end of what it walked carries on from where it
    // stopped: rows left to evaluate, or the caller's `Limit` reached, whether or not a
    // row remains ([`crate::state::reports_stop_key`]).
    let (next_token, last_evaluated_key) = match (
        crate::state::reports_stop_key(input.limit, evaluated, truncated),
        stopped_on,
    ) {
        (true, Some((key, map))) => (
            Some(crate::state::encode_cursor(&input.statement, &key)),
            Some(map),
        ),
        _ => (None, None),
    };
    // What this statement is charged is what the plan it ran READ, charged as the native
    // read that IS that plan: a plan that pins the partition key of the source it reads —
    // the index's own where its `FROM` target names one — is a query (or, with the range
    // key pinned too, a single-entry read), charged once over the bytes it read at the
    // rate the statement asked for, exactly as the `Query` of the same source is charged;
    // a plan that walks the whole source is a scan, charged per row it evaluated. A plan
    // that evaluated nothing spends the one unit a read takes at least.
    let units = if keyed.is_some() || evaluated == 0 {
        crate::state::read_capacity_units(metered_size, input.consistent_read.unwrap_or(false))
    } else {
        page_units
    };
    // WHERE those units were spent: a statement whose source is a secondary index read
    // that INDEX, so they are billed to it exactly as the `Query` or `Scan` of the same
    // index bills them ([`crate::state::consumed_read_capacity`]) — and the table's own
    // arm carries what the read spent ON THE TABLE, which is nothing for a read the index
    // answered on its own and the base-table fetches where it had to go on to the table
    // for an attribute the index does not project.
    // Projected while the index is still borrowed from the table, before the admission
    // below reaches for the table again.
    let consumed_capacity = crate::state::consumed_read_capacity(
        input.return_consumed_capacity.as_deref(),
        name,
        select
            .index
            .as_deref()
            .and_then(|index| table.secondary_index(index))
            .as_ref(),
        units,
        fetched_units,
    );
    // The read is ADMITTED against the read capacity the table is provisioned for, the
    // same as the item API's reads: a statement past that capacity is refused rather
    // than served.
    if let Err(throttle) = store
        .active_table_mut(region, name, now)
        .map_err(lift)?
        .admit_read(units + fetched_units, now)
    {
        return Err(
            ExecuteStatementErrorModeled::ProvisionedThroughputExceededException(
                crate::state::read_throughput_exceeded(
                    &crate::state::table_arn(region, name),
                    throttle,
                ),
            )
            .into(),
        );
    }
    // The items this read HANDS BACK are the table's `ReturnedItemCount` for the operation
    // that returned them ([`crate::state::request_outcome_metrics`]): the items this
    // response carries, which is what the statement's predicate left of the page.
    let returned = i32::try_from(items.len()).unwrap_or(i32::MAX);
    store
        .pending_outcomes
        .record_returned_items(name, OPERATION, returned, now);
    Ok(ExecuteStatementOutput {
        items: Some(items),
        next_token,
        last_evaluated_key,
        consumed_capacity,
    })
}

/// What the SOURCE a statement read holds for one row: the stored item, narrowed to the
/// attributes a secondary index projects when the statement's source is one
/// ([`crate::state::projected_attributes`] answers `None` for the table itself, which
/// holds every attribute).
fn held_item(
    item: &crate::state::Item,
    projected: Option<&::std::collections::BTreeSet<String>>,
) -> crate::state::Item {
    match projected {
        Some(allowed) => item
            .iter()
            .filter(|(name, _)| allowed.contains(name.as_str()))
            .map(|(name, value)| (name.clone(), value.clone()))
            .collect(),
        None => item.clone(),
    }
}

/// `INSERT`: the item the statement carries, which must not already be stored —
/// "There was an attempt to insert an item with the same primary key as an item that
/// already exists in the DynamoDB table" is the modelled `DuplicateItemException`.
fn insert_item(
    store: &mut Store,
    region: &str,
    name: &str,
    now: ::std::time::SystemTime,
    insert: &crate::state::InsertStatement,
    input: &ExecuteStatementInput,
) -> Result<ExecuteStatementOutput, ExecuteStatementError> {
    let mut item = insert.item.clone();
    for (attribute, value) in &item {
        crate::state::check_attribute_value(attribute, value).map_err(lift)?;
    }
    crate::state::canonicalize_item(&mut item).map_err(lift)?;
    if crate::state::item_size(&item) > crate::state::MAX_ITEM_SIZE_BYTES {
        return Err(crate::scaffolded::Scaffolded::validation(
            crate::state::ITEM_SIZE_EXCEEDED_MESSAGE,
        ));
    }
    let key = {
        let table = store.active_table(region, name, now).map_err(lift)?;
        // The half of the item-size quota that needs the table: the entry a local
        // secondary index of it would hold for this item is charged beside the item
        // ([`crate::state::Table::item_size_exceeded`]).
        if table.item_size_exceeded(&item) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::ITEM_SIZE_EXCEEDED_MESSAGE,
            ));
        }
        table.check_index_keys(&item).map_err(lift)?;
        table.key_of_item(&item).map_err(lift)?
    };
    if store
        .active_table(region, name, now)
        .map_err(lift)?
        .items
        .contains_key(&key)
    {
        return Err(ExecuteStatementErrorModeled::DuplicateItemException(
            DuplicateItemException {
                message: Some("Duplicate primary key exists in table".to_string()),
            },
        )
        .into());
    }
    store
        .put_item(region, name, now, key, item.clone())
        .map_err(lift)?;

    let capacity = store
        .active_table(region, name, now)
        .map_err(lift)?
        .write_capacity(None, Some(&item));
    // What the statement consumed is also what this service publishes as the table's
    // throughput metric ([`crate::state::charge_reported_capacity`]): the figure reported
    // below is the figure counted, so the series cannot drift from the response.
    crate::state::charge_reported_capacity(
        store,
        region,
        name,
        &capacity,
        crate::state::Consumed::Write,
        now,
    );
    Ok(ExecuteStatementOutput {
        // "If a read operation was used, this property will contain the result of the
        // read operation … For the write operations this value will be empty"
        // (`Items`): the member is reported either way, and an INSERT — which states
        // no RETURNING clause — reports it empty.
        items: Some(Vec::new()),
        next_token: None,
        last_evaluated_key: None,
        consumed_capacity: crate::state::consumed_write_capacity(
            input.return_consumed_capacity.as_deref(),
            name,
            &capacity,
            crate::state::CapacityKind::Write,
            crate::state::KindReport::Itemised,
        ),
    })
}

/// `UPDATE`: the one item the `WHERE` clause pins, changed by the statement's
/// clauses.
fn update_item(
    store: &mut Store,
    region: &str,
    name: &str,
    now: ::std::time::SystemTime,
    update: &crate::state::UpdateStatement,
    input: &ExecuteStatementInput,
    return_old_on_failure: bool,
) -> Result<ExecuteStatementOutput, ExecuteStatementError> {
    let condition = crate::state::parsed_condition(&update.filter).map_err(lift)?;
    let clauses = crate::state::parsed_update(&update.clauses).map_err(lift)?;
    let (key, partition_key, sort_key) = {
        let table = store.active_table(region, name, now).map_err(lift)?;
        (
            crate::state::singleton_key(table, &update.filter).map_err(lift)?,
            table.partition_key_name().to_string(),
            table.sort_key_name().map(ToString::to_string),
        )
    };
    let before = store
        .active_table(region, name, now)
        .map_err(lift)?
        .items
        .get(&key)
        .cloned();
    // The `WHERE` clause is read against the item as it stands BEFORE this write,
    // which is the only state it can speak about — so a statement whose predicate the
    // stored item does not satisfy, and one whose key holds no item at all, are both
    // the modelled `ConditionalCheckFailedException` rather than a write.
    let satisfied = before
        .as_ref()
        .map(|item| condition.evaluate(Some(item)))
        .transpose()
        .map_err(lift)?
        .unwrap_or(false);
    if !satisfied {
        // The statement is refused and nothing is written, but it is METERED like the write
        // it would have made: a conditional write that fails consumes the write capacity the
        // stored item costs ([`crate::state::charge_refused_conditional_write`]).
        crate::state::charge_refused_conditional_write(
            store,
            region,
            name,
            &key.partition,
            before.as_ref(),
            now,
        );
        return Err(condition_failed(if return_old_on_failure {
            before
        } else {
            None
        }));
    }

    let mut item = before.clone().unwrap_or_default();
    let touched = clauses
        .apply(&mut item, crate::state::UpdateTarget::of(before.as_ref()))
        .map_err(lift)?;
    for attribute in touched.attributes() {
        if attribute.as_str() == partition_key.as_str()
            || Some(attribute.as_str()) == sort_key.as_deref()
        {
            return Err(crate::scaffolded::Scaffolded::validation(format!(
                "One or more parameter values were invalid: Cannot update attribute \
                 {attribute}. This attribute is part of the key"
            )));
        }
    }
    // The item the statement leaves is held to exactly what a `PutItem` of it would
    // be: the documented nesting, the 400 KB item size, and the key limits of every
    // index it is projected into. A statement that UPDATES states what to change, so
    // the size refusal is the one the update path states
    // ([`crate::state::ITEM_UPDATE_SIZE_EXCEEDED_MESSAGE`]).
    for (attribute, value) in &item {
        crate::state::check_attribute_value(attribute, value)
            .map_err(crate::state::stated_for_an_update)
            .map_err(lift)?;
    }
    crate::state::canonicalize_item(&mut item).map_err(lift)?;
    // A statement states its change without an expression, so nothing is charged on top of
    // the item it leaves ([`crate::state::update_size_exceeded`]): no clause frame and no
    // floor under any part of it.
    {
        let table = store.active_table(region, name, now).map_err(lift)?;
        if crate::state::update_size_exceeded(
            table,
            &item,
            &crate::state::UpdateRequestShape::StatedWithoutAnExpression,
        ) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::ITEM_UPDATE_SIZE_EXCEEDED_MESSAGE,
            ));
        }
        table.check_index_keys_of_update(&item).map_err(lift)?;
    }
    store
        .put_item(region, name, now, key, item.clone())
        .map_err(lift)?;

    let capacity = store
        .active_table(region, name, now)
        .map_err(lift)?
        .write_capacity(before.as_ref(), Some(&item));
    // See [`insert_item`]: the units the response reports are the units the table's series
    // carries ([`crate::state::charge_reported_capacity`]).
    crate::state::charge_reported_capacity(
        store,
        region,
        name,
        &capacity,
        crate::state::Consumed::Write,
        now,
    );
    let reported = crate::state::projected_return_values(
        update
            .returning
            .map(crate::state::ReturnedValues::as_return_value),
        before.as_ref(),
        Some(&item),
        &touched,
    );
    Ok(ExecuteStatementOutput {
        // A write reports `Items` either way: what its `RETURNING` clause asked for,
        // or nothing when it states none.
        items: Some(reported.map(|item| vec![item]).unwrap_or_default()),
        next_token: None,
        last_evaluated_key: None,
        consumed_capacity: crate::state::consumed_write_capacity(
            input.return_consumed_capacity.as_deref(),
            name,
            &capacity,
            crate::state::CapacityKind::Write,
            crate::state::KindReport::Itemised,
        ),
    })
}

/// `DELETE`: the one item the `WHERE` clause pins, removed from the table.
fn delete_item(
    store: &mut Store,
    region: &str,
    name: &str,
    now: ::std::time::SystemTime,
    delete: &crate::state::DeleteStatement,
    input: &ExecuteStatementInput,
    return_old_on_failure: bool,
) -> Result<ExecuteStatementOutput, ExecuteStatementError> {
    let (key, condition) = {
        let table = store.active_table(region, name, now).map_err(lift)?;
        (
            crate::state::singleton_key(table, &delete.filter).map_err(lift)?,
            crate::state::parsed_condition_beside_the_key(table, &delete.filter).map_err(lift)?,
        )
    };
    let before = store
        .active_table(region, name, now)
        .map_err(lift)?
        .items
        .get(&key)
        .cloned();
    // What the clause states BESIDES the key it addresses is the condition this delete is
    // held to, held to THE ADDRESSED ITEM: a key that holds none is nothing to remove and
    // nothing the condition can have failed, so it is served having removed nothing
    // ([`crate::state::delete_condition_satisfied`]).
    let satisfied =
        crate::state::delete_condition_satisfied(condition.as_ref(), before.as_ref())
            .map_err(lift)?;
    if !satisfied {
        // See [`update_item`]: the refused statement writes nothing and is metered all the
        // same ([`crate::state::charge_refused_conditional_write`]).
        crate::state::charge_refused_conditional_write(
            store,
            region,
            name,
            &key.partition,
            before.as_ref(),
            now,
        );
        return Err(condition_failed(if return_old_on_failure {
            before
        } else {
            None
        }));
    }
    let removed = store.delete_item(region, name, now, &key).map_err(lift)?;

    let capacity = store
        .active_table(region, name, now)
        .map_err(lift)?
        .write_capacity(removed.as_ref(), None);
    // See [`insert_item`]: the units the response reports are the units the table's series
    // carries ([`crate::state::charge_reported_capacity`]).
    crate::state::charge_reported_capacity(
        store,
        region,
        name,
        &capacity,
        crate::state::Consumed::Write,
        now,
    );
    // A delete removes every attribute of the item, so the `MODIFIED OLD` projection
    // of what it changed IS the item as it stood — both OLD forms report that item.
    let reported = delete
        .returning
        .and_then(|_| removed.clone())
        .filter(|item| !item.is_empty());
    Ok(ExecuteStatementOutput {
        items: Some(reported.map(|item| vec![item]).unwrap_or_default()),
        next_token: None,
        last_evaluated_key: None,
        consumed_capacity: crate::state::consumed_write_capacity(
            input.return_consumed_capacity.as_deref(),
            name,
            &capacity,
            crate::state::CapacityKind::Write,
            crate::state::KindReport::Itemised,
        ),
    })
}

/// The refusal a statement whose `WHERE` clause the stored item does not satisfy is
/// answered with, carrying that item when the request asked for it.
fn condition_failed(item: Option<crate::state::Item>) -> ExecuteStatementError {
    ExecuteStatementErrorModeled::ConditionalCheckFailedException(
        ConditionalCheckFailedException {
            message: Some(crate::state::CONDITION_FAILED_MESSAGE.to_string()),
            item,
        },
    )
    .into()
}

/// The API this operation is served as, which is the `Operation` dimension value the
/// per-operation CloudWatch series of a request it served are booked under
/// ([`crate::state::request_outcome_metrics`]).
const OPERATION: &str = "ExecuteStatement";

/// The modelled server error for a request that cannot reach this service's store.
fn store_unavailable() -> ExecuteStatementError {
    ExecuteStatementErrorModeled::InternalServerError(InternalServerError {
        message: Some("the DynamoDB table store is unavailable".to_string()),
    })
    .into()
}

/// Lift a store refusal into this operation's error channel.
fn lift(error: crate::state::RequestError) -> ExecuteStatementError {
    match error {
        crate::state::RequestError::NotFound(message) => {
            ExecuteStatementErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                message: Some(message),
            })
            .into()
        }
        crate::state::RequestError::Validation(message) => {
            crate::scaffolded::Scaffolded::validation(message)
        }
    }
}
