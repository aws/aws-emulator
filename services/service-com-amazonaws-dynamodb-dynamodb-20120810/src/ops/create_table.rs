/// The two members a table's secondary indexes are declared in, as the model spells them
/// on the wire — which is how every refusal about one of those lists names it.
const GLOBAL_SECONDARY_INDEXES_MEMBER: &str = "GlobalSecondaryIndexes";
const LOCAL_SECONDARY_INDEXES_MEMBER: &str = "LocalSecondaryIndexes";

/// Every secondary-index list this request carries, with the number of indexes it states
/// for each — the pairs [`crate::state::check_lists_not_empty`] holds to a list that names
/// at least one index, in the order this handler reads them.
fn declared_index_lists(input: &CreateTableInput) -> [(&'static str, Option<usize>); 2] {
    [
        (
            GLOBAL_SECONDARY_INDEXES_MEMBER,
            input.global_secondary_indexes.as_ref().map(Vec::len),
        ),
        (
            LOCAL_SECONDARY_INDEXES_MEMBER,
            input.local_secondary_indexes.as_ref().map(Vec::len),
        ),
    ]
}

/// The first input member present that this slice does not store, if any.
fn unsupported_member(input: &CreateTableInput) -> Option<&'static str> {
    if input.global_table_source_arn.is_some() {
        return Some("GlobalTableSourceArn");
    }
    if input.global_table_settings_replication_mode.is_some() {
        return Some("GlobalTableSettingsReplicationMode");
    }
    // An index's ON-DEMAND throughput is the one member this slice does not store: an
    // index's throughput is stored as a PROVISIONED one, so an on-demand ceiling asked
    // for per index is "not written yet" rather than accepted and dropped. Its WARM
    // throughput is stored and reported, by the same rule the table's own is.
    for index in input.global_secondary_indexes.iter().flatten() {
        if index.on_demand_throughput.is_some() {
            return Some("GlobalSecondaryIndexes carrying OnDemandThroughput");
        }
    }
    None
}

/// The TABLE one request declares: its primary key, the attributes it is declared over
/// and the indexes carried with it.
///
/// A table is declared in TWO places — `CreateTable`'s own members and
/// `ImportTable$TableCreationParameters`, "the parameters for the table to import the
/// data into" — and both declare the same resource, so the rules a declaration is held to
/// and the stored table built from it are stated ONCE, here, and each operation borrows
/// its own shape into this one before applying them. Same construction as
/// [`DeclaredVectorIndex`], one level up.
///
/// Public because a table is also declared from OUTSIDE this service's own wire: a generic
/// control plane that provisions a table of this account declares the same resource, and it
/// holds the declaration to these rules rather than to a second copy of them.
///
/// Slices rather than owned lists: the declaration lives in the request for as long as
/// the checks run, and nothing here changes it.
pub struct DeclaredTable<'d> {
    pub key_schema: &'d [KeySchemaElement],
    pub attribute_definitions: &'d [AttributeDefinition],
    pub global_secondary_indexes: &'d [GlobalSecondaryIndex],
    pub local_secondary_indexes: &'d [LocalSecondaryIndex],
    pub vector_indexes: &'d [VectorIndex],
}

impl<'d> DeclaredTable<'d> {
    /// The table `CreateTable`'s own members declare.
    pub(crate) fn of(input: &'d CreateTableInput) -> Self {
        Self {
            key_schema: input.key_schema.as_deref().unwrap_or_default(),
            attribute_definitions: input.attribute_definitions.as_deref().unwrap_or_default(),
            global_secondary_indexes: input
                .global_secondary_indexes
                .as_deref()
                .unwrap_or_default(),
            local_secondary_indexes: input
                .local_secondary_indexes
                .as_deref()
                .unwrap_or_default(),
            vector_indexes: input.vector_indexes.as_deref().unwrap_or_default(),
        }
    }

    /// Clamp every caller-sized list the checks below walk, before anything walks it.
    ///
    /// Each count comes straight from the request body, and the checks that follow match
    /// definitions against key schemas, so the work would otherwise be the PRODUCT of two
    /// request-chosen counts. Every bound here is one the contract already implies, so a
    /// list past it is invalid whatever its contents: at most
    /// [`crate::state::MAX_GLOBAL_SECONDARY_INDEXES`] indexes, at most
    /// [`crate::state::MAX_INDEX_KEY_ELEMENTS`] key elements per index, at most
    /// [`crate::state::MAX_VECTOR_INDEXES`] vector indexes with at most
    /// [`crate::state::MAX_VECTOR_SEARCH_SCHEMA_ELEMENTS`] search-schema elements each, and
    /// at most [`crate::state::MAX_ATTRIBUTE_DEFINITIONS`] attribute definitions.
    pub fn clamped(&self) -> Result<(), crate::state::RequestError> {
        let definitions = self.attribute_definitions.len();
        if definitions > crate::state::MAX_ATTRIBUTE_DEFINITIONS {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid AttributeDefinitions: a table may declare at most {} attribute \
                 definitions, got {definitions}",
                crate::state::MAX_ATTRIBUTE_DEFINITIONS
            )));
        }
        crate::state::check_index_count(
            GLOBAL_SECONDARY_INDEXES_MEMBER,
            self.global_secondary_indexes.len(),
            crate::state::MAX_GLOBAL_SECONDARY_INDEXES,
        )?;
        for index in self.global_secondary_indexes {
            if index.key_schema.len() > crate::state::MAX_INDEX_KEY_ELEMENTS {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid KeySchema for index {}: an index key may carry at most {} elements, \
                     got {}",
                    index.index_name,
                    crate::state::MAX_INDEX_KEY_ELEMENTS,
                    index.key_schema.len()
                )));
            }
        }
        crate::state::check_index_count(
            LOCAL_SECONDARY_INDEXES_MEMBER,
            self.local_secondary_indexes.len(),
            crate::state::MAX_LOCAL_SECONDARY_INDEXES,
        )?;
        for index in self.local_secondary_indexes {
            if index.key_schema.len() > crate::state::MAX_INDEX_KEY_ELEMENTS {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid KeySchema for index {}: an index key may carry at most {} elements, \
                     got {}",
                    index.index_name,
                    crate::state::MAX_INDEX_KEY_ELEMENTS,
                    index.key_schema.len()
                )));
            }
        }
        // The per-table vector-index quota, which bounds this walk and is the table's own
        // limit either way ([`crate::state::check_vector_index_count`]).
        crate::state::check_vector_index_count(self.vector_indexes.len())?;
        for index in self.vector_indexes {
            clamped_search_schema(
                &index.index_name,
                index.search_schema.as_ref().map_or(0, Vec::len),
            )?;
        }
        Ok(())
    }
}

/// Hold ONE vector index's search schema to the elements it may carry.
///
/// The caller-chosen list is both WALKED (once per element, against the table's attribute
/// definitions) and STORED, so it is clamped before either happens — and it is clamped
/// wherever a vector index is declared, so `CreateTable` and `UpdateTable`'s `Create` state
/// one rule with one sentence. Each caller applies it where its own request is still
/// request-level, which is why this is a check of a COUNT rather than part of
/// [`DeclaredVectorIndex::validated`]: that runs with the store already locked.
pub(crate) fn clamped_search_schema(
    index_name: &str,
    elements: usize,
) -> Result<(), crate::state::RequestError> {
    if elements > crate::state::MAX_VECTOR_SEARCH_SCHEMA_ELEMENTS {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid SearchSchema for index {index_name}: a vector index's search schema may \
             carry at most {} elements, got {elements}",
            crate::state::MAX_VECTOR_SEARCH_SCHEMA_ELEMENTS
        )));
    }
    Ok(())
}

/// The English ordinal DynamoDB names a `KeySchemaElement` by, for every position a key
/// schema can hold — [`crate::state::MAX_INDEX_KEY_ELEMENTS`] is the widest key schema
/// this service accepts, and a table's primary key is narrower still.
const ELEMENT_ORDINALS: [&str; crate::state::MAX_INDEX_KEY_ELEMENTS] = [
    "first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth",
];

/// How DynamoDB refers to the element at `position` (0-based) of a key schema.
///
/// Every position a key schema can hold has a word: [`clamped_lists`] bounds an index
/// key to [`crate::state::MAX_INDEX_KEY_ELEMENTS`] elements and a table's primary key is
/// narrower still, so the bare position past the table above is unreachable and is there
/// only so this never has to panic.
fn element_ordinal(position: usize) -> String {
    ELEMENT_ORDINALS
        .get(position)
        .map_or_else(|| (position + 1).to_string(), |word| (*word).to_string())
}

/// Refuse a key schema that names one attribute in more than one of its elements.
///
/// Each element of a key schema addresses a DIFFERENT attribute of the item: a key of
/// one attribute is a partition key, and a composite key is "another KeySchemaElement
/// for the sort key" (`CreateTable$KeySchema`) — so one attribute cannot be both, and a
/// schema that uses it twice leaves one element with nothing of its own to key on.
///
/// DynamoDB states that fact with one fixed sentence, which is what `duplicated` carries,
/// and which of them it is follows from the COUNT of `AttributeDefinitions` the request
/// declared against the number of elements the schema has. Fewer definitions than elements
/// cannot be one per element, so the repeat is told the element left without a definition
/// ([`KEY_WITHOUT_DEFINITION_MESSAGE`]) — the state a secondary index's key schema is
/// always in, since the definitions it is resolved against are the ones its OWN elements
/// name. A TABLE's primary key whose request declared at least as many definitions as it
/// has elements is the one schema with a check of the two key ROLES, and it names them
/// ([`DUPLICATE_KEY_ATTRIBUTE_MESSAGE`]); each caller decides that for its own schema.
///
/// Every caller settles it AFTER pairing the schema's elements with their definitions, so
/// a schema that both repeats an attribute and names one `AttributeDefinitions` does not
/// declare is refused for the key nothing declares.
fn check_distinct_key_attributes(
    key_schema: &[KeySchemaElement],
    duplicated: &str,
) -> Result<(), crate::state::RequestError> {
    let mut named: ::std::collections::HashSet<&str> = ::std::collections::HashSet::new();
    for element in key_schema {
        if !named.insert(element.attribute_name.as_str()) {
            return Err(crate::state::RequestError::Validation(
                duplicated.to_string(),
            ));
        }
    }
    Ok(())
}

/// Refuse an `AttributeDefinitions` list that defines one attribute name more than once.
///
/// "An array of attributes that describe the key schema for the table and indexes"
/// (`CreateTable$AttributeDefinitions`) declares the TYPE of each key attribute, and an
/// item has one attribute per name: a list naming one attribute twice states two
/// declarations for the one attribute, so there is no single type a key could be built on,
/// and the whole call is refused before any table is created or changed.
///
/// The fact is a duplicated NAME in a declared list, stated in AWS's own fixed text for it
/// over the name the list repeated. The TYPES the two entries state do not enter it: one
/// name is one attribute whether or not the entries agree about its type.
pub(crate) fn check_distinct_definitions(
    definitions: &[AttributeDefinition],
) -> Result<(), crate::state::RequestError> {
    let mut named: ::std::collections::HashSet<&str> = ::std::collections::HashSet::new();
    for definition in definitions {
        if !named.insert(definition.attribute_name.as_str()) {
            return Err(crate::state::RequestError::Validation(format!(
                "Attribute Name is duplicated: {}",
                definition.attribute_name
            )));
        }
    }
    Ok(())
}

/// AWS's fixed text for a TABLE's own primary key whose partition key and sort key are
/// one attribute: the sentence names the two key ROLES the one attribute was given, and
/// nothing of the attribute or of the table.
pub(crate) const DUPLICATE_KEY_ATTRIBUTE_MESSAGE: &str =
    "Both the Hash Key and the Range Key element in the KeySchema have the same name";

/// Refuse a key schema whose element at some position does not carry the key type that
/// position requires, naming that element the way DynamoDB does.
///
/// A key schema is validated element by element, in the order the request lists it: the
/// partition keys lead and the sort keys follow, so the first element is always a `HASH`
/// element, a `HASH` is in place only while the leading run of at most `partition_keys`
/// partition keys is still open, and every other position must be `RANGE`. The first
/// element that breaks that is refused with its ordinal position and the key type its
/// position required — `Invalid KeySchema: The second KeySchemaElement is not a RANGE key
/// type` — so a caller is told WHICH element to fix rather than the whole rule.
///
/// One defect is stated as the RULE and not as a position: a partition key that follows a
/// sort key leaves no single element at fault, since a schema may carry several partition
/// keys, so DynamoDB answers it with the fixed sentence that states the order the two
/// kinds of key have to come in ([`HASH_AFTER_RANGE_MESSAGE`]).
///
/// `index_name` is `None` for a table's own primary key and the index's name for an
/// index key, which DynamoDB scopes its refusal to.
fn validated_key_type_order(
    index_name: Option<&str>,
    key_schema: &[KeySchemaElement],
    partition_keys: usize,
) -> Result<(), crate::state::RequestError> {
    let mut hash_keys = 0usize;
    let mut saw_sort_key = false;
    for (position, element) in key_schema.iter().enumerate() {
        let hash_allowed = !saw_sort_key && hash_keys < partition_keys;
        match element.key_type.as_str() {
            "HASH" if hash_allowed => hash_keys += 1,
            // Only partition keys may lead a key schema, so the first element is never a
            // sort key.
            "RANGE" if position > 0 => saw_sort_key = true,
            // A partition key AFTER a sort key breaks the ORDER of the schema rather
            // than the type one position requires, and DynamoDB states that rule with
            // its own fixed sentence ([`HASH_AFTER_RANGE_MESSAGE`]) instead of naming an
            // element: with several partition keys allowed, no single position is the one
            // at fault.
            "HASH" if saw_sort_key => {
                return Err(crate::state::RequestError::Validation(
                    HASH_AFTER_RANGE_MESSAGE.to_string(),
                ));
            }
            _ => {
                let expected = if hash_allowed { "HASH" } else { "RANGE" };
                let scope =
                    index_name.map_or_else(String::new, |name| format!(" for index {name}"));
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid KeySchema{scope}: The {} KeySchemaElement is not a {expected} key \
                     type",
                    element_ordinal(position)
                )));
            }
        }
    }
    Ok(())
}

/// The member path a table's own `KeySchema` is reported under: the lowerCamel path the
/// request validator builds for a top-level member, which is what the recorded refusals of
/// that member state.
const TABLE_KEY_SCHEMA_MEMBER_PATH: &str = "keySchema";

/// A submitted `KeySchema` list as the refusal of that member quotes it.
///
/// This is the OBJECT rendering the service's own request validator states a refused
/// structure value with — `[KeySchemaElement(attributeName=<name>, keyType=<type>), …]` —
/// rather than the JSON the request arrived as, the same form the refusal of another
/// structured member of this service quotes its value in
/// (`crate::state::rendered_batch_write_request_items`). Every value in it comes from the
/// request; the field names and their order are the renderer's fixed frame, and are the
/// members in the order the model declares them (`smithy_query(query="shape",
/// shape="KeySchemaElement")` gives `AttributeName` then `KeyType`).
///
/// The list's length is the caller's, so the rendering is held to the ceiling every clause
/// of this service echoes a value at ([`crate::state::echoed_clause_value`]): elements stop
/// being rendered once that much text is in hand, and the elision marker names how much the
/// caller sent.
fn rendered_key_schema(elements: &[KeySchemaElement]) -> String {
    let mut rendered = String::from("[");
    for (at, element) in elements.iter().enumerate() {
        if at > 0 {
            rendered.push_str(", ");
        }
        if rendered.len() > crate::state::MAX_ECHOED_CLAUSE_VALUE {
            break;
        }
        rendered.push_str(&format!(
            "KeySchemaElement(attributeName={}, keyType={})",
            element.attribute_name, element.key_type
        ));
    }
    rendered.push(']');
    crate::state::echoed_clause_value(&rendered).into_owned()
}

/// The table's key schema, refused unless it is one `HASH` attribute optionally
/// followed by one `RANGE` attribute, each defined in `AttributeDefinitions` as a
/// scalar type — "The attributes in KeySchema must also be defined in the
/// AttributeDefinitions array" (`CreateTable$KeySchema`).
///
/// The SCHEMA the table would be created on is settled first — every element paired with
/// the definition it keys on, the type that definition states, the two key roles distinct
/// and the elements in the order their roles require — and only then the declared list's
/// own defects: a name it defines twice and a definition no schema of the table uses. So a
/// request that gets both wrong is told about the key schema, which is what the table could
/// not be built from, rather than about the declaration it draws its types from.
///
/// [`DeclaredTable::clamped`] has already bounded every list this walks.
pub fn validated_key_schema(
    declared: &DeclaredTable<'_>,
) -> Result<Vec<KeySchemaElement>, crate::state::RequestError> {
    let key_schema = declared.key_schema.to_vec();
    if key_schema.is_empty() {
        return Err(crate::state::RequestError::Validation(
            "KeySchema is required and must declare a HASH key attribute".to_string(),
        ));
    }
    let definitions = declared.attribute_definitions.to_vec();
    if key_schema.len() > crate::state::MAX_TABLE_KEY_ELEMENTS {
        // The LIST itself is what broke a bound here — a primary key may carry one
        // partition key and at most one sort key, so a longer list is outside the length
        // the member admits — which is the class of defect the request validator reports:
        // the lowerCamel member path, the submitted list echoed, and the length
        // requirement, inside the envelope that counts the clauses
        // ([`crate::state::invalid_member`]). The checks below are about what the
        // ELEMENTS say, and state their own sentences.
        return Err(crate::state::invalid_member(
            TABLE_KEY_SCHEMA_MEMBER_PATH,
            Some(&rendered_key_schema(&key_schema)),
            &crate::state::max_length_requirement(crate::state::MAX_TABLE_KEY_ELEMENTS),
        ));
    }
    // The key attributes of every requested index, collected ONCE: the loop below asks
    // whether each definition is used, and a per-definition scan of every index's key
    // schema would be the product of two request-chosen counts. Both index kinds declare
    // their key attributes in the same array, so both are collected here, and so does
    // every vector index the request declares: a vector index consumes the attribute its
    // `VectorAttribute` names and each attribute its `SearchSchema` names, whose types
    // this array is what declares.
    let index_key_attributes: ::std::collections::HashSet<&str> = declared
        .global_secondary_indexes
        .iter()
        .flat_map(|index| index.key_schema.iter())
        .chain(
            declared
                .local_secondary_indexes
                .iter()
                .flat_map(|index| index.key_schema.iter()),
        )
        .map(|element| element.attribute_name.as_str())
        .chain(
            declared
                .vector_indexes
                .iter()
                .flat_map(vector_index_attributes),
        )
        .collect();
    for element in &key_schema {
        let name = element.attribute_name.as_str();
        let Some(definition) = definitions
            .iter()
            .find(|definition| definition.attribute_name == name)
        else {
            // A key element the request declares no definition for has no attribute to key
            // on, and WHICH sentence states that follows from the COUNT the request
            // declared against the number of elements this schema has
            // ([`undefined_key_refusal`]) — the table's primary key is a key schema like
            // any other here, and earns the same two sentences a SECONDARY INDEX's key
            // schema does. Whether the declaration carries anything else does not enter
            // it: a request that also defines an attribute no schema uses breaks two
            // rules, and this is the one it is told about, because a key with nothing
            // declared for it is what the primary key itself cannot be built from.
            return Err(undefined_key_refusal(&key_schema, &definitions));
        };
        if !matches!(definition.attribute_type.as_str(), "S" | "N" | "B") {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid AttributeDefinition: {name} must have AttributeType S, N or B, got {}",
                definition.attribute_type
            )));
        }
    }
    // Every element now resolves to a definition, so what is left to settle is that they
    // do not all address the SAME attribute. Settled AFTER the definitions, as it is for a
    // secondary index's key schema ([`validated_index_key_schema`]), so a schema with both
    // defects is refused for the key nothing declares.
    //
    // WHICH sentence a repeat earns follows from the COUNT the request declared: the
    // number of `AttributeDefinitions` entries it carries, against the number of elements
    // this schema has. A request that declares fewer definitions than there are key
    // elements cannot have one per element, so it is told the element left without a
    // definition ([`KEY_WITHOUT_DEFINITION_MESSAGE`]). A request that declared at least as
    // many is
    // told what is actually wrong with the schema instead: the table's primary key is the
    // one schema with a check of the two key ROLES, so it names them. The count is over
    // the whole declared list, which is the member the rule is about and the one every
    // schema of the table draws its definitions from.
    let duplicated = if definitions.len() >= key_schema.len() {
        DUPLICATE_KEY_ATTRIBUTE_MESSAGE
    } else {
        KEY_WITHOUT_DEFINITION_MESSAGE
    };
    check_distinct_key_attributes(&key_schema, duplicated)?;
    // A table's primary key is "one KeySchemaElement (for the partition key)" and, when
    // composite, "another KeySchemaElement for the sort key": position 1 holds the only
    // HASH element and position 2, when present, the only RANGE one.
    //
    // AFTER the elements have been paired with their definitions: each element is resolved
    // to the attribute it keys on before the ROLE that element plays is read, so a schema
    // naming an attribute the request declares no definition for is refused for the missing
    // definition whatever its key types say ([`undefined_key_refusal`]) — a key
    // with nothing declared for it has no attribute to key on at all, which is the earlier
    // defect of the two.
    validated_key_type_order(None, &key_schema, crate::state::MAX_TABLE_PARTITION_KEYS)?;
    // The key schema the table is created ON is settled above; what is left are the defects
    // of the DECLARED list itself, which is a different member and is read only once the
    // schema drawing on it holds together. Two entries defining the same attribute state two
    // types for one attribute of the item ([`check_distinct_definitions`]), and an entry no
    // schema of the table uses is declared for nothing (below) — so a request that gets both
    // its key schema and its declaration wrong is told about the SCHEMA, which is what the
    // table could not be built from.
    check_distinct_definitions(&definitions)?;
    for definition in &definitions {
        // "Some AttributeDefinitions are not used in any KeySchema": every defined
        // attribute must be consumed by a schema of the table — its own key, the key of
        // one of its secondary indexes, or the vector attribute or search schema of one
        // of its vector indexes.
        let used_by_table = key_schema
            .iter()
            .any(|element| element.attribute_name == definition.attribute_name);
        let used_by_index = index_key_attributes.contains(definition.attribute_name.as_str());
        if !used_by_table && !used_by_index {
            return Err(crate::state::RequestError::Validation(format!(
                "Some AttributeDefinitions are not used in any KeySchema: {}",
                definition.attribute_name
            )));
        }
    }
    Ok(key_schema)
}

/// Every attribute of the table ONE requested vector index consumes: the one its
/// `VectorAttribute` names, and each one its `SearchSchema` names.
///
/// A `HASH` search-schema element "partitions the vector index for independent scaling"
/// and an `INLINE_FILTER` one is "an attribute projected into the vector index for
/// filtering at the storage layer during search"
/// (`SearchSchemaElement$SearchSchemaElementType`) — either way the index reads that
/// attribute of the table's items, so the attribute is consumed and its
/// `AttributeDefinitions` entry is used.
fn vector_index_attributes(index: &VectorIndex) -> impl Iterator<Item = &str> {
    ::std::iter::once(index.vector_attribute.attribute_name.as_str()).chain(
        index
            .search_schema
            .iter()
            .flatten()
            .map(|element| element.attribute_name.as_str()),
    )
}

/// The global secondary indexes to store with the table.
///
/// Each one is refused unless its name is unique on the table, its key schema names
/// attributes `AttributeDefinitions` declares with a scalar type, its `Projection` is
/// one the model's `ProjectionType` enum names, and its throughput matches the table's
/// billing mode — "You must use either OnDemandThroughput or ProvisionedThroughput
/// based on your table's capacity mode" (`GlobalSecondaryIndex$ProvisionedThroughput`).
/// An index created with the table is reported `CREATING` and becomes `ACTIVE` on the
/// same clock-owed transition as the table.
pub(crate) fn validated_indexes(
    declared: &DeclaredTable<'_>,
    billing_mode: &str,
    region: &str,
    table: &str,
    now: ::std::time::SystemTime,
) -> Result<Vec<crate::state::GlobalSecondaryIndex>, crate::state::RequestError> {
    let requested = declared.global_secondary_indexes.to_vec();
    let definitions = declared.attribute_definitions.to_vec();
    let mut indexes: Vec<crate::state::GlobalSecondaryIndex> = Vec::new();
    for index in &requested {
        if indexes.iter().any(|stored| stored.name == index.index_name) {
            return Err(crate::state::duplicate_index_name(&index.index_name));
        }
        validated_index_key_schema(
            &index.index_name,
            &index.key_schema,
            &definitions,
            &IndexKeyShape::GLOBAL,
        )?;
        validated_projection(&index.projection)?;
        let throughput = validated_index_throughput(
            &index.index_name,
            billing_mode,
            index.provisioned_throughput.clone(),
        )?;
        // "Represents the warm throughput value (in read units per second and write
        // units per second) for the specified secondary index. If you use this
        // parameter, you must specify ReadUnitsPerSecond, WriteUnitsPerSecond, or both"
        // (`GlobalSecondaryIndex$WarmThroughput`): the member is read by the same rule
        // the table's own is, so an index the request names no warm throughput for keeps
        // warm the capacity it is provisioned for.
        let warm_throughput = crate::state::resolved_warm_throughput(
            index.warm_throughput.as_ref(),
            &crate::state::WarmThroughputSettings::tracking(throughput.as_ref(), now),
            now,
        )?;
        indexes.push(crate::state::GlobalSecondaryIndex {
            arn: crate::state::index_arn(region, table, &index.index_name),
            name: index.index_name.clone(),
            key_schema: index.key_schema.clone(),
            projection: index.projection.clone(),
            provisioned_throughput: throughput,
            transient_status: crate::state::IndexStatus::Creating,
            active_at: now + crate::state::STATUS_TRANSITION,
            throughput_history: crate::state::ThroughputHistory::default(),
            warm_throughput,
            reported_counters: crate::state::MeteredCounters::new(now),
            // Off on a new index, for the same reason it is off on a new table.
            contributor_insights: crate::state::ContributorInsights::default(),
            // Defined WITH the table, so there is no table data to read and the member
            // "does not appear in the DescribeTable output" (the `Backfilling` doc).
            backfill: crate::state::IndexBackfill::WithTable,
        });
    }
    Ok(indexes)
}

/// The local secondary indexes to store with the table.
///
/// A local secondary index is "an index that has the same partition key as the table,
/// but a different sort key" (the `LocalSecondaryIndex` doc and the Developer Guide), so
/// each one is refused unless its `HASH` key is the table's own partition key. Beyond
/// that it is held to the same rules as a global index: a name unique "among all other
/// indexes on this table" (`LocalSecondaryIndex$IndexName`), key attributes declared in
/// `AttributeDefinitions` with a scalar type, and a `Projection` the model's
/// `ProjectionType` enum names. A local index carries no throughput of its own and no
/// status: it exists from the moment the table does.
///
/// [`clamped_lists`] has already bounded every list this walks.
fn validated_local_indexes(
    declared: &DeclaredTable<'_>,
    table_key_schema: &[KeySchemaElement],
    global_secondary_indexes: &[crate::state::GlobalSecondaryIndex],
    region: &str,
    table: &str,
    now: ::std::time::SystemTime,
) -> Result<Vec<crate::state::LocalSecondaryIndex>, crate::state::RequestError> {
    let requested = declared.local_secondary_indexes.to_vec();
    let definitions = declared.attribute_definitions.to_vec();
    let partition_key = table_key_schema
        .iter()
        .find(|element| element.key_type == "HASH")
        .map_or("", |element| element.attribute_name.as_str());
    let mut indexes: Vec<crate::state::LocalSecondaryIndex> = Vec::new();
    for index in &requested {
        if indexes.iter().any(|stored| stored.name == index.index_name)
            || global_secondary_indexes
                .iter()
                .any(|stored| stored.name == index.index_name)
        {
            return Err(crate::state::duplicate_index_name(&index.index_name));
        }
        validated_index_key_schema(
            &index.index_name,
            &index.key_schema,
            &definitions,
            &IndexKeyShape::LOCAL,
        )?;
        validated_projection(&index.projection)?;
        let hash_key = index
            .key_schema
            .iter()
            .find(|element| element.key_type == "HASH")
            .map_or("", |element| element.attribute_name.as_str());
        if hash_key != partition_key {
            return Err(crate::state::RequestError::Validation(
                crate::state::index_leading_hash_key_message(
                    &index.index_name,
                    hash_key,
                    partition_key,
                ),
            ));
        }
        indexes.push(crate::state::LocalSecondaryIndex {
            arn: crate::state::index_arn(region, table, &index.index_name),
            name: index.index_name.clone(),
            key_schema: index.key_schema.clone(),
            projection: index.projection.clone(),
            reported_counters: crate::state::MeteredCounters::new(now),
        });
    }
    Ok(indexes)
}

/// The vector indexes to store with the table.
///
/// Each one is refused unless its name is free on the table ("Must be unique only for
/// this table" — `GlobalSecondaryIndex$IndexName`, which holds for every index a table
/// carries) and its `Projection` is one the model's `ProjectionType` enum names. Its
/// `DistanceFunction`, its `SearchSchema` element types and its `Dimensions` are
/// modelled as an enum, an enum and a `@range` minimum, so the request validator has
/// already refused every value outside them before a request reaches this handler.
/// A vector index created with the table is reported `CREATING` and becomes `ACTIVE` on
/// the same clock-owed transition as the table.
///
/// A vector index exists only on an ON-DEMAND table, whichever member declared it
/// ([`crate::state::check_vector_index_capacity_mode`]), so the table's capacity mode is
/// settled before any of them is built.
///
/// The attributes its `SearchSchema` names are the table's own attributes, declared in
/// `AttributeDefinitions` like any other indexed attribute — which is what
/// [`validated_key_schema`] counts them as used by, and which this refuses an index for
/// naming an attribute the request declares no definition for, as an index key schema is
/// refused for the same thing ([`validated_index_key_schema`]): a search schema
/// partitions and filters by that attribute's VALUE, so its type has to be declared. A
/// definition is not REQUIRED for the `VectorAttribute` — no schema is built over the
/// vector itself — but one the request does declare for it counts as used all the same.
pub(crate) fn validated_vector_indexes(
    declared: &DeclaredTable<'_>,
    billing_mode: &str,
    global_secondary_indexes: &[crate::state::GlobalSecondaryIndex],
    local_secondary_indexes: &[crate::state::LocalSecondaryIndex],
    region: &str,
    table: &str,
    now: ::std::time::SystemTime,
) -> Result<Vec<crate::state::VectorIndex>, crate::state::RequestError> {
    let requested = declared.vector_indexes.to_vec();
    crate::state::check_vector_index_capacity_mode(billing_mode, requested.len())?;
    let definitions = declared.attribute_definitions.to_vec();
    let mut indexes: Vec<crate::state::VectorIndex> = Vec::new();
    for index in &requested {
        let taken = indexes.iter().any(|stored| stored.name == index.index_name)
            || global_secondary_indexes
                .iter()
                .any(|stored| stored.name == index.index_name)
            || local_secondary_indexes
                .iter()
                .any(|stored| stored.name == index.index_name);
        if taken {
            return Err(crate::state::duplicate_index_name(&index.index_name));
        }
        indexes.push(
            DeclaredVectorIndex {
                index_name: &index.index_name,
                vector_attribute: &index.vector_attribute,
                search_schema: index.search_schema.as_deref(),
                projection: &index.projection,
                dimensions: index.dimensions,
                distance_function: &index.distance_function,
            }
            .validated(&definitions, region, table, crate::state::IndexBackfill::WithTable, now)?,
        );
    }
    // The dimensions are a property of the vectors the ATTRIBUTE holds, so every index
    // over one has to agree about them ([`crate::state::check_vector_dimensions_agree`]);
    // asked of the whole list, since a pair is what disagrees.
    crate::state::check_vector_dimensions_agree(&indexes)?;
    Ok(indexes)
}

/// One vector index as a REQUEST declares it, whichever member it arrived in.
///
/// `CreateTable$VectorIndexes` and the `Create` action of `UpdateTable$VectorIndexUpdates`
/// carry the same six members and describe the same resource, so the rules a declaration is
/// held to — and the stored index built from it — are stated ONCE, here, and both operations
/// borrow their own shape into this one before applying them.
pub(crate) struct DeclaredVectorIndex<'d> {
    pub(crate) index_name: &'d str,
    pub(crate) vector_attribute: &'d VectorAttributeDefinition,
    pub(crate) search_schema: Option<&'d [SearchSchemaElement]>,
    pub(crate) projection: &'d Projection,
    pub(crate) dimensions: i64,
    pub(crate) distance_function: &'d str,
}

impl DeclaredVectorIndex<'_> {
    /// The index this declaration STORES, or the refusal it earns.
    ///
    /// Two rules, both of the declaration alone: its `Projection` has to hold together
    /// ([`validated_projection`]), and every attribute its `SearchSchema` names has to be
    /// declared in `definitions` — the search schema partitions and filters by that
    /// attribute's VALUE, so its type has to be declared, exactly as an index key's is. A
    /// definition is not REQUIRED for the `VectorAttribute`: no schema is built over the
    /// vector itself.
    ///
    /// The stored index starts `CREATING` and becomes `ACTIVE` when the clock makes the
    /// transient span due, and it carries the ARN this service mints for an index of
    /// `table` in `region`. What it has to BACKFILL is the caller's to state
    /// ([`crate::state::IndexBackfill`]): an index declared with the table has no table
    /// data to read, while one added to a table that already holds items does.
    pub(crate) fn validated(
        &self,
        definitions: &[AttributeDefinition],
        region: &str,
        table: &str,
        backfill: crate::state::IndexBackfill,
        now: ::std::time::SystemTime,
    ) -> Result<crate::state::VectorIndex, crate::state::RequestError> {
        validated_projection(self.projection)?;
        check_vector_dimensions(self.dimensions)?;
        // "HASH - A partition key that partitions the vector index for independent
        // scaling" (`SearchSchemaElement$SearchSchemaElementType`): ONE partition key
        // partitions the index, so a schema declaring the role twice declares two
        // partitionings of one index and has exceeded the count that role admits — the
        // violation a key schema's second `HASH` element is, refused with the sentence
        // this service already states for it
        // ([`key_schema_exceeds_key_kind_message`]). The role every further element may
        // take is the `INLINE_FILTER` one, of which a schema may declare as many as it
        // carries elements.
        let partition_keys = self
            .search_schema
            .unwrap_or_default()
            .iter()
            .filter(|element| {
                element.search_schema_element_type == crate::state::SEARCH_SCHEMA_PARTITION_KEY
            })
            .count();
        if partition_keys > crate::state::MAX_VECTOR_SEARCH_SCHEMA_PARTITION_KEYS {
            return Err(crate::state::RequestError::Validation(
                key_schema_exceeds_key_kind_message(crate::state::SEARCH_SCHEMA_PARTITION_KEY),
            ));
        }
        for element in self.search_schema.unwrap_or_default() {
            let name = element.attribute_name.as_str();
            if !definitions
                .iter()
                .any(|definition| definition.attribute_name == name)
            {
                return Err(crate::state::RequestError::Validation(
                    crate::state::SEARCH_SCHEMA_ATTRIBUTE_UNDECLARED_MESSAGE.to_string(),
                ));
            }
        }
        Ok(crate::state::VectorIndex {
            arn: crate::state::index_arn(region, table, self.index_name),
            name: self.index_name.to_string(),
            vector_attribute: self.vector_attribute.clone(),
            search_schema: self.search_schema.unwrap_or_default().to_vec(),
            projection: self.projection.clone(),
            dimensions: self.dimensions,
            distance_function: self.distance_function.to_string(),
            transient_status: crate::state::IndexStatus::Creating,
            // An index is built when it has read what it was given to read
            // ([`crate::state::IndexBackfill::complete_at`]): one declared with the table
            // settles with the table, and one added to a table that already holds items
            // keeps building after the table's own update has settled.
            active_at: backfill.settled_at(now + crate::state::STATUS_TRANSITION),
            // An index's resources are allocated for the span the table's own update takes,
            // and only then does the build read what it was given to read
            // ([`crate::state::VectorIndex::in_resource_allocation`]).
            allocated_at: now + crate::state::STATUS_TRANSITION,
            // Nobody has asked for this index to be removed, so the clock owes it no
            // removal ([`crate::state::VectorIndex::begin_deletion`]).
            deleting_at: None,
            reported_counters: crate::state::MeteredCounters::new(now),
            backfill,
        })
    }
}

/// The shape ONE KIND of secondary index's key schema may take: how many partition keys
/// lead it, how many sort keys may follow, and whether one of those sort keys is
/// REQUIRED.
///
/// The two kinds of secondary index key on different things, so one of them admits a key
/// schema the other does not — which is why the counts are a property of the KIND rather
/// than of "an index" ([`IndexKeyShape::GLOBAL`] and [`IndexKeyShape::LOCAL`] state each
/// kind's, with the doc sentence it comes from).
pub(crate) struct IndexKeyShape {
    /// The most `HASH` elements the schema may lead with.
    partition_keys: usize,
    /// The most `RANGE` elements that may follow them.
    sort_keys: usize,
    /// Whether the schema is incomplete without one of those sort keys.
    sort_key_required: bool,
}

impl IndexKeyShape {
    /// A GLOBAL secondary index: "Each global secondary index supports up to 4 partition
    /// keys and up to 4 sort keys" (`CreateTable$GlobalSecondaryIndexes`). A global index
    /// keys on attributes of its own choosing, so one over a partition key alone is a
    /// complete index and its sort key is optional.
    pub(crate) const GLOBAL: Self = Self {
        partition_keys: crate::state::MAX_INDEX_PARTITION_KEYS,
        sort_keys: crate::state::MAX_INDEX_SORT_KEYS,
        sort_key_required: false,
    };

    /// A LOCAL secondary index: "an index that has the same partition key as the table,
    /// but a different sort key" (the `LocalSecondaryIndex` doc), whose "key schema must
    /// begin with the same partition key as the table"
    /// (`CreateTable$LocalSecondaryIndexes`).
    ///
    /// So it keys on the table's ONE partition key ([`crate::state::MAX_TABLE_PARTITION_KEYS`])
    /// and on the one sort key of its own ([`crate::state::MAX_TABLE_SORT_KEYS`]) that makes
    /// it a different index from the table: that sort key is what the index IS, so a local
    /// index without one is not a local index at all. The several partition keys a global
    /// index may carry are documented for that kind alone.
    pub(crate) const LOCAL: Self = Self {
        partition_keys: crate::state::MAX_TABLE_PARTITION_KEYS,
        sort_keys: crate::state::MAX_TABLE_SORT_KEYS,
        sort_key_required: true,
    };
}

/// How many elements of `key_schema` claim `key_type`.
fn count_of_key_type(key_schema: &[KeySchemaElement], key_type: &str) -> usize {
    key_schema
        .iter()
        .filter(|element| element.key_type == key_type)
        .count()
}

/// AWS's fixed text for a key schema carrying more keys of one KIND than it admits: the
/// sentence names the kind whose count was exceeded and nothing else — not the index, not
/// the maximum, not the count that was sent — because the fact is about that kind's limit,
/// which is the same limit for every index of every table.
///
/// A vector index's SEARCH SCHEMA is the schema that index is partitioned and filtered by
/// — "the search schema that defines partition key and inline filter attributes"
/// (`VectorIndex$SearchSchema`), with "HASH - A partition key that partitions the vector
/// index" as the role a key schema's `HASH` plays — so a search schema declaring more than
/// the one partitioning element its index admits
/// ([`crate::state::MAX_VECTOR_SEARCH_SCHEMA_PARTITION_KEYS`]) has exceeded that same
/// count, and earns this same sentence over the same role. One rule, one sentence, and no
/// text invented for the vector surface: the wording here is the one this service already
/// states for a key schema past that count.
fn key_schema_exceeds_key_kind_message(key_type: &str) -> String {
    format!(
        "{}: The KeySchema exceeds the maximum allowed number of {key_type} key attributes",
        crate::state::INVALID_PARAMETER_CLAUSE
    )
}

/// One index's key schema: at least one `HASH` element, within the key counts its KIND
/// admits ([`IndexKeyShape`]), with every attribute declared in `AttributeDefinitions` as
/// a scalar type.
///
/// An index key is read COUNT first and POSITION second, for the kind of index that admits
/// several keys of a role: a schema with more partition keys or more sort keys than that
/// kind admits is refused by the count, and one within both counts is then validated by
/// position like a table's — the leading positions hold the partition keys and the sort
/// keys follow — so an element out of place is named by its ordinal.
pub(crate) fn validated_index_key_schema(
    index_name: &str,
    key_schema: &[KeySchemaElement],
    definitions: &[AttributeDefinition],
    shape: &IndexKeyShape,
) -> Result<(), crate::state::RequestError> {
    if key_schema.is_empty() {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid KeySchema for index {index_name}: an index key must declare a HASH key \
             attribute"
        )));
    }
    // HOW MANY elements claim each role, before WHICH position claims which — for the kind
    // of index that admits SEVERAL keys of a role. Such a schema with more of a role than
    // its kind admits has broken that role's COUNT rather than put one element out of
    // place: with several partition keys allowed no single position is the one at fault, so
    // AWS states the count's own fixed sentence
    // ([`key_schema_exceeds_key_kind_message`]) instead of naming an element.
    //
    // A kind that admits ONE key of each role has no such count to exceed: its second
    // partition key is an element in the wrong ROLE for its position, which is how the
    // TABLE's own primary key — one partition key and at most one sort key — is refused
    // too, by its ordinal ([`validated_key_type_order`]).
    let range_keys = count_of_key_type(key_schema, "RANGE");
    if shape.partition_keys > 1 && count_of_key_type(key_schema, "HASH") > shape.partition_keys {
        return Err(crate::state::RequestError::Validation(
            key_schema_exceeds_key_kind_message("HASH"),
        ));
    }
    if shape.sort_keys > 1 && range_keys > shape.sort_keys {
        return Err(crate::state::RequestError::Validation(
            key_schema_exceeds_key_kind_message("RANGE"),
        ));
    }
    validated_key_type_order(Some(index_name), key_schema, shape.partition_keys)?;
    if range_keys > shape.sort_keys {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid KeySchema for index {index_name}: an index key may declare at most {} RANGE \
             attribute(s), got {range_keys}",
            shape.sort_keys
        )));
    }
    // A kind of index whose sort key is what distinguishes it needs one: the schema is
    // incomplete rather than out of order, so AWS states the fact about the schema and
    // names the index it belongs to.
    if shape.sort_key_required && range_keys == 0 {
        return Err(crate::state::RequestError::Validation(format!(
            "One or more parameter values were invalid: Index KeySchema does not have a range key \
             for index: {index_name}"
        )));
    }
    for element in key_schema {
        let name = element.attribute_name.as_str();
        let Some(definition) = definitions
            .iter()
            .find(|definition| definition.attribute_name == name)
        else {
            // The same two sentences a TABLE's own key schema earns, chosen the same way
            // ([`undefined_key_refusal`]): a request that declared at least as many
            // definitions as this schema has elements is told both lists — the keys the
            // index is built on beside the attribute names the request defined — and one
            // that declared fewer is told the element left with no definition.
            return Err(undefined_key_refusal(key_schema, definitions));
        };
        if !matches!(definition.attribute_type.as_str(), "S" | "N" | "B") {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid AttributeDefinition: {name} must have AttributeType S, N or B, got {}",
                definition.attribute_type
            )));
        }
    }
    // A secondary index has no two-role check of its own: the attributes its key is
    // resolved against are the ones its OWN elements name, so a repeat leaves it with
    // fewer definitions than elements however many the request declared, and that is the
    // sentence it earns.
    check_distinct_key_attributes(key_schema, KEY_WITHOUT_DEFINITION_MESSAGE)?;
    Ok(())
}

/// One index's projection: `ProjectionType` must be a value the model's enum names,
/// and `NonKeyAttributes` and `INCLUDE` require each other — "INCLUDE - Only the
/// specified table attributes are projected into the index. The list of projected
/// attributes is in NonKeyAttributes" and "This limit only applies when you specify the
/// ProjectionType of INCLUDE" (`Projection$ProjectionType` /
/// `Projection$NonKeyAttributes`).
///
/// A projection that states NO type states no value of that enum, so it describes an index
/// the service cannot build and the whole declaration is refused
/// ([`UNKNOWN_PROJECTION_TYPE_MESSAGE`]) — there is no type the member falls back to.
///
/// So the member pair is checked BOTH ways: a projection that names non-key attributes
/// under another type projects something no type projects, and an `INCLUDE` projection
/// that names none states which attributes are projected nowhere. Either way the index
/// cannot be built as asked for, so the request is refused before any of it is stored.
///
/// Every sentence here is about the PAIR of members and names no index: the projection
/// contradicts itself the same way wherever it was declared, which is why this takes the
/// projection alone.
pub(crate) fn validated_projection(
    projection: &Projection,
) -> Result<(), crate::state::RequestError> {
    // A projection that states no type states nothing the enum names, so there is no
    // projection to build: AWS reports the value it could not place, and the value a
    // request left out — or sent as JSON `null` — reads as `null`
    // ([`UNKNOWN_PROJECTION_TYPE_VALUE`]).
    let projection_type = projection
        .projection_type
        .as_deref()
        .unwrap_or(UNKNOWN_PROJECTION_TYPE_VALUE);
    if !PROJECTION_TYPE_VALUES.contains(&projection_type) {
        return Err(crate::state::RequestError::Validation(format!(
            "{UNKNOWN_PROJECTION_TYPE_MESSAGE}{projection_type}"
        )));
    }
    let non_key = projection
        .non_key_attributes
        .as_ref()
        .is_some_and(|attributes| !attributes.is_empty());
    if non_key && projection_type != "INCLUDE" {
        return Err(crate::state::RequestError::Validation(
            non_key_attributes_outside_include_message(projection_type),
        ));
    }
    if !non_key && projection_type == "INCLUDE" {
        return Err(crate::state::RequestError::Validation(
            INCLUDE_WITHOUT_NON_KEY_ATTRIBUTES_MESSAGE.to_string(),
        ));
    }
    Ok(())
}

/// AWS's fixed text for a projection whose `ProjectionType` is not one of the enum's
/// values, with the value the request carried appended after it.
///
/// `Projection$ProjectionType` targets the `ProjectionType` enum, whose value set is
/// [`PROJECTION_TYPE_VALUES`] (ALL, KEYS_ONLY, INCLUDE); a projection that names none of
/// them describes an index the service cannot build, so no table is created for it.
pub(crate) const UNKNOWN_PROJECTION_TYPE_MESSAGE: &str =
    "One or more parameter values were invalid: Unknown ProjectionType: ";

/// How that refusal reports a `ProjectionType` the request did not state: an absent member
/// and a JSON `null` are one and the same value to a reader of the request, and `null` is
/// what AWS names it.
pub(crate) const UNKNOWN_PROJECTION_TYPE_VALUE: &str = "null";

/// AWS's fixed text for an `INCLUDE` projection that names no `NonKeyAttributes`: the
/// whole sentence is fixed, naming the two members rather than the index — the pair is
/// what contradicts itself, and it reads the same for every index of every table.
pub(crate) const INCLUDE_WITHOUT_NON_KEY_ATTRIBUTES_MESSAGE: &str =
    "One or more parameter values were invalid: ProjectionType is INCLUDE, but NonKeyAttributes \
     is not specified";

/// AWS's text for the OTHER half of that pair: a projection that names `NonKeyAttributes`
/// under a type which projects no such list.
///
/// The same sentence as [`INCLUDE_WITHOUT_NON_KEY_ATTRIBUTES_MESSAGE`] read the other way
/// round — the two members, and which of the two the projection stated — with the
/// projection type the request carried as its one variable part, so each value of the enum
/// but `INCLUDE` states its own refusal. Nothing of the index is named: the member pair is
/// what contradicts itself, and it does so the same way for every index of every table.
pub(crate) fn non_key_attributes_outside_include_message(projection_type: &str) -> String {
    format!(
        "One or more parameter values were invalid: ProjectionType is {projection_type}, but \
         NonKeyAttributes is specified"
    )
}

/// The most dimensions one vector may carry: a vector index holds vectors of up to 4096
/// dimensions ("Service, Account, and Table Quotas" in the Amazon DynamoDB Developer
/// Guide, the vector-search entry), so an index asking for more than that could never be
/// built. The model bounds the member below ([`VectorIndex$Dimensions`] is a
/// `PositiveLongObject` with a `@range` minimum of 1 and no maximum), so the ceiling is
/// this service's to state.
pub(crate) const MAX_VECTOR_DIMENSIONS: i64 = 4096;

/// The fewest dimensions one vector may carry: the model bounds
/// [`VectorIndex$Dimensions`] with a `@range` minimum of 1, so an index of no dimensions
/// holds no vector at all.
pub(crate) const MIN_VECTOR_DIMENSIONS: i64 = 1;

/// Hold one vector index's `Dimensions` to that range. AWS states it as a
/// parameter-value sentence naming the quantity and the inclusive range it has to fall
/// in, and nothing of the index or of the value supplied: the quota is the same for every
/// index of every table.
pub(crate) fn check_vector_dimensions(dimensions: i64) -> Result<(), crate::state::RequestError> {
    if !(MIN_VECTOR_DIMENSIONS..=MAX_VECTOR_DIMENSIONS).contains(&dimensions) {
        return Err(crate::state::RequestError::Validation(format!(
            "One or more parameter values were invalid: Number of dimensions must be between \
             {MIN_VECTOR_DIMENSIONS} and {MAX_VECTOR_DIMENSIONS} inclusive."
        )));
    }
    Ok(())
}

/// AWS's fixed text for a `PAY_PER_REQUEST` table that also states a
/// `ProvisionedThroughput`: "If you set BillingMode as PAY_PER_REQUEST, you cannot
/// specify this property" (`CreateTable$ProvisionedThroughput`). The sentence names the
/// MEMBER the request may not carry and the billing mode that rules it out, and nothing
/// of either capacity dimension or of the table.
pub(crate) const THROUGHPUT_WITH_PAY_PER_REQUEST_MESSAGE: &str =
    "One or more parameter values were invalid: ProvisionedThroughput cannot be specified when \
     BillingMode is PAY_PER_REQUEST";

/// AWS's fixed text for a table CREATED on-demand that also states a
/// `ProvisionedThroughput`: the sentence names the two CAPACITY members the block carries
/// rather than the block itself, since those are what a `PAY_PER_REQUEST` table has no
/// setting for, and nothing of the table. The index-level refusal states the same two
/// members ([`validated_index_throughput`]).
pub(crate) const CAPACITY_WITH_PAY_PER_REQUEST_MESSAGE: &str =
    "One or more parameter values were invalid: Neither ReadCapacityUnits nor WriteCapacityUnits \
     can be specified when BillingMode is PAY_PER_REQUEST";

/// AWS's fixed text for a `PROVISIONED` table that states no `ProvisionedThroughput`:
/// "If you set BillingMode as PROVISIONED, you must specify this property"
/// (`CreateTable$ProvisionedThroughput`).
///
/// The sentence names the two CAPACITY members the block carries rather than the block
/// itself, exactly as the on-demand half of the same rule does
/// ([`CAPACITY_WITH_PAY_PER_REQUEST_MESSAGE`]): those are the members a `PROVISIONED` table
/// has no setting for unless the request states them.
pub(crate) const THROUGHPUT_WITHOUT_PROVISIONED_MESSAGE: &str =
    "One or more parameter values were invalid: ReadCapacityUnits and WriteCapacityUnits must \
     both be specified when BillingMode is PROVISIONED";

/// AWS's fixed text for a key schema the request declared fewer attribute definitions
/// than it has elements for: a schema that names one attribute in two of its elements,
/// which leaves one of them with no definition of its own
/// ([`check_distinct_key_attributes`]), and a schema naming an attribute nothing declares
/// where the request declared too few definitions to have one per element
/// ([`undefined_key_refusal`]). The sentence interpolates nothing. A schema whose request
/// declared at least as many definitions as it has elements is refused over the two lists
/// instead ([`undefined_schema_keys`]).
pub(crate) const KEY_WITHOUT_DEFINITION_MESSAGE: &str =
    "Invalid KeySchema: Some index key attribute have no definition";

/// AWS's fixed text for a key schema whose partition keys do not all precede its sort
/// keys: the whole sentence is fixed, stating the ORDER the elements have to be in and
/// naming neither an element nor the schema it belongs to.
pub(crate) const HASH_AFTER_RANGE_MESSAGE: &str =
    "One or more parameter values were invalid: All HASH key attributes must precede RANGE key \
     attributes in the KeySchema";

/// The refusal one key schema earns for an element `AttributeDefinitions` does not
/// declare, in the wording the COUNT the request declared selects.
///
/// A request that declares FEWER `AttributeDefinitions` entries than the schema at fault
/// has elements cannot have one per element whatever the names say, so the fact stated is
/// the element left with no definition at all, in a sentence that interpolates nothing
/// ([`KEY_WITHOUT_DEFINITION_MESSAGE`]). A request that declared at least as many has
/// stated enough definitions for the schema and got the NAMES wrong, so it is told what
/// each of the two lists holds and has to reconcile them ([`undefined_schema_keys`]).
///
/// This is the one comparison that settles every key-schema sentence of a declaration —
/// the same count that decides which sentence a REPEATED key attribute earns
/// ([`check_distinct_key_attributes`]) — and it holds for each schema the declaration
/// carries: the table's own primary key and every secondary index's key, which draw their
/// definitions from the one `AttributeDefinitions` list the request declared.
pub(crate) fn undefined_key_refusal(
    key_schema: &[KeySchemaElement],
    definitions: &[AttributeDefinition],
) -> crate::state::RequestError {
    if definitions.len() < key_schema.len() {
        return crate::state::RequestError::Validation(KEY_WITHOUT_DEFINITION_MESSAGE.to_string());
    }
    undefined_schema_keys(key_schema, definitions)
}

/// The refusal for KEY attributes `AttributeDefinitions` does not declare: AWS's
/// parameter-value template over the WHOLE key schema the request declared and the
/// attribute names it defined.
///
/// The keys are the whole key schema of the index at fault — AWS reports the keys the
/// schema is built on rather than only the ones with no definition, which is what tells
/// the caller which of the two lists to extend — and the definitions are the ones the
/// request declared. Neither list is in the order the request stated it
/// ([`hash_table_order`]). A TABLE's own primary key is a key schema like any other and is
/// refused with this same sentence; which requests reach it is [`undefined_key_refusal`]'s
/// count, and the sentences a schema earns instead are
/// [`KEY_WITHOUT_DEFINITION_MESSAGE`] and [`DUPLICATE_KEY_ATTRIBUTE_MESSAGE`].
pub(crate) fn undefined_schema_keys(
    key_schema: &[KeySchemaElement],
    definitions: &[AttributeDefinition],
) -> crate::state::RequestError {
    let keys: Vec<&str> = key_schema
        .iter()
        .map(|element| element.attribute_name.as_str())
        .collect();
    let defined: Vec<&str> = definitions
        .iter()
        .map(|definition| definition.attribute_name.as_str())
        .collect();
    crate::state::RequestError::Validation(format!(
        "One or more parameter values were invalid: Some index key attributes are not defined \
         in AttributeDefinitions. Keys: [{}], AttributeDefinitions: [{}]",
        hash_table_order(&keys).join(", "),
        hash_table_order(&defined).join(", ")
    ))
}

/// The order DynamoDB renders a list of attribute NAMES in, inside the refusal above.
///
/// Neither list follows the request: a create whose definitions were declared in one
/// order has them reported in another, and the same holds for a key schema's own
/// elements, so each list is rendered out of a name-keyed hash table rather than out of
/// the request. Which name lands where is decided by the NAME alone, so the same names
/// declared in any order are reported the same way.
///
/// The table has a power-of-two count of slots — the smallest that holds the names at a
/// 3/4 load factor — and a name's slot is its 32-bit polynomial hash (each UTF-16 code
/// unit added to 31 times the running value) folded with its own high half, taken modulo
/// that count. Names that share a slot keep the order they were declared in, and a name
/// declared twice occupies one slot, as a name-keyed table holds one entry per name.
///
/// The slot count GROWS with the list rather than being fixed: a five-name list declared
/// in one order is reported in an order no fixed count of sixteen slots produces, while
/// the growth rule above reproduces that list and every shorter recorded one. The
/// recorded lists are what the rule was settled against ([`undefined_schema_keys`]'s
/// suite), and the permutation is computed from the names a request carries, never from a
/// recorded list.
fn hash_table_order<'a>(names: &[&'a str]) -> Vec<&'a str> {
    let mut ordered: Vec<&str> = Vec::with_capacity(names.len());
    for name in names {
        if !ordered.contains(name) {
            ordered.push(name);
        }
    }
    let mut slots: usize = 2;
    while ordered.len() * 4 > slots * 3 {
        slots *= 2;
    }
    // A stable sort is what keeps two names of one slot in the order they arrived in, and
    // the cached key hashes each name once rather than once per comparison.
    ordered.sort_by_cached_key(|name| name_slot(name, slots));
    ordered
}

/// Which of `slots` slots `name` occupies in the table [`hash_table_order`] renders.
fn name_slot(name: &str, slots: usize) -> usize {
    let mut hash: i32 = 0;
    for unit in name.encode_utf16() {
        hash = hash.wrapping_mul(31).wrapping_add(i32::from(unit));
    }
    let hash = hash as u32;
    ((hash ^ (hash >> 16)) as usize) & (slots - 1)
}

/// One index's provisioned throughput, held to the table's billing mode: a
/// `PROVISIONED` table's index must carry one (with both dimensions at least 1), and a
/// `PAY_PER_REQUEST` table's index must not.
pub(crate) fn validated_index_throughput(
    index_name: &str,
    billing_mode: &str,
    throughput: Option<ProvisionedThroughput>,
) -> Result<Option<ProvisionedThroughput>, crate::state::RequestError> {
    match (billing_mode, throughput) {
        ("PAY_PER_REQUEST", None) => Ok(None),
        ("PAY_PER_REQUEST", Some(_)) => Err(crate::state::RequestError::Validation(format!(
            "One or more parameter values were invalid: Neither ReadCapacityUnits nor \
             WriteCapacityUnits can be specified when BillingMode is PAY_PER_REQUEST for \
             index: {index_name}"
        ))),
        (_, Some(throughput)) => {
            if throughput.read_capacity_units < 1 || throughput.write_capacity_units < 1 {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid ProvisionedThroughput for index {index_name}: ReadCapacityUnits and \
                     WriteCapacityUnits must be at least 1, got {} and {}",
                    throughput.read_capacity_units, throughput.write_capacity_units
                )));
            }
            Ok(Some(throughput))
        }
        (_, None) => Err(crate::state::RequestError::Validation(
            crate::state::index_capacity_required_message(index_name),
        )),
    }
}

/// The billing mode and the provisioned throughput to store: "If you set BillingMode
/// as PROVISIONED, you must specify this property. If you set BillingMode as
/// PAY_PER_REQUEST, you cannot specify this property"
/// (`CreateTable$ProvisionedThroughput`). `BillingMode` defaults to `PROVISIONED`.
///
/// Stated once for every operation that CREATES a table from a declaration of one — the
/// members are the same wherever they are carried (`CreateTable`'s own, and
/// `ImportTable$TableCreationParameters`), so the rule and its two sentences are too.
pub fn validated_declared_throughput(
    billing_mode: Option<&str>,
    table_throughput_mode: Option<&str>,
    provisioned_throughput: Option<&ProvisionedThroughput>,
) -> Result<(String, Option<ProvisionedThroughput>), crate::state::RequestError> {
    let billing_mode = crate::state::requested_throughput_mode(billing_mode, table_throughput_mode)
        .unwrap_or("PROVISIONED")
        .to_string();
    // Each mode member was held to the enum's value set before this handler ran, so the
    // two modes below are the whole of what a request can resolve to.
    let on_demand = billing_mode == "PAY_PER_REQUEST";
    match (on_demand, provisioned_throughput.cloned()) {
        (true, None) => Ok((billing_mode, None)),
        (true, Some(_)) => Err(crate::state::RequestError::Validation(
            CAPACITY_WITH_PAY_PER_REQUEST_MESSAGE.to_string(),
        )),
        (false, Some(throughput)) => {
            if throughput.read_capacity_units < 1 || throughput.write_capacity_units < 1 {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid ProvisionedThroughput: ReadCapacityUnits and WriteCapacityUnits \
                     must be at least 1, got {} and {}",
                    throughput.read_capacity_units, throughput.write_capacity_units
                )));
            }
            Ok((billing_mode, Some(throughput)))
        }
        (false, None) => Err(crate::state::RequestError::Validation(
            THROUGHPUT_WITHOUT_PROVISIONED_MESSAGE.to_string(),
        )),
    }
}
