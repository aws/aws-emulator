impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> TagResource<Eng> {
    /// The write itself: authorize, validate the tags and store them on the pool.
    async fn tag(
        &self,
        input: TagResourceInput,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<TagResourceOutput, TagResourceError> {
        // Authorization comes first, before the pool the `ResourceArn` names is looked up:
        // this operation is served only to a caller whose identity-based IAM policies allow
        // its own action on the resource the request names.
        if let Some(denied) = crate::state::authorization::denied(
            &*self.engine,
            ctx,
            <Self as smithy_server_runtime::Operation>::NAME,
            Some(&input.resource_arn),
        ) {
            return Err(denied);
        }
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalErrorException(
                InternalErrorException {
                    message: Some("the identity-pool store is unavailable".to_string()),
                },
            )
            .into());
        };

        // `ARNString` constrains only the length (20..2048), so the ARN's own form is this
        // service's rule — the same rule `ListTagsForResource` reads a `ResourceArn` by: a
        // `ResourceArn` that is not an identity-pool ARN of this service names no resource
        // at all, which is a bad input parameter rather than a missing resource. The ARN is
        // read before any resource is looked up, so the refusal is the one fixed sentence
        // that layer states ([`crate::state::ARN_VALIDATION_FAILED_MESSAGE`]).
        let Some(identity_pool_id) = crate::state::identity_pool_id_from_arn(&input.resource_arn)
        else {
            return Err(invalid_parameter(
                crate::state::ARN_VALIDATION_FAILED_MESSAGE.to_string(),
            ));
        };

        // The tags themselves are checked before the pool is looked up, and everything is
        // checked before anything is written: a refused call leaves the pool's tag set
        // exactly as it was.
        //
        // Iterated in key order so which entry a multi-entry map is refused for does not
        // depend on the iteration order of the request's map.
        let mut requested: Vec<(&String, &String)> = input.tags.iter().collect();
        requested.sort_by_key(|(tag_key, _)| *tag_key);

        // The MODELLED bounds on the map's own key and value shapes. The protocol's
        // boundary walk checks the map's VALUES against `TagValueType` before this handler
        // runs, but not its KEYS, so a key outside `TagKeysType`'s bound reaches here: a
        // constraint the model states is a protocol-level refusal — HTTP 400
        // `ValidationException` with a message built from the request — which is what
        // `Scaffolded::validation` answers. Both are checked here so the rule holds for
        // every entry of the map whichever path refuses it.
        let violations = constraint_violations(&requested);
        if !violations.is_empty() {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::validation_errors_detected(violations.len(), &violations),
            ));
        }

        // The CHARACTERS a tag is spelled with, which the model bounds nothing about: AWS
        // publishes one character set for a tag key and a tag value alike, and an entry
        // outside it is a bad input parameter rather than a constraint the model states.
        // The rule is the shared one every operation of this service that writes a pool's
        // tags reads.
        let entries: Vec<(&str, &str)> = requested
            .iter()
            .map(|(tag_key, tag_value)| (tag_key.as_str(), tag_value.as_str()))
            .collect();
        if let Some(message) =
            crate::state::pool_configuration::tag_charset_refusal(&entries)
        {
            return Err(invalid_parameter(message.to_string()));
        }

        for (tag_key, _) in &requested {
            if crate::state::is_reserved_tag_key(tag_key) {
                return Err(invalid_parameter(
                    crate::state::SYSTEM_TAG_MUTATION_MESSAGE.to_string(),
                ));
            }
        }

        let mut store = state.lock();
        let Some(record) = store.identity_pools.get_mut(identity_pool_id) else {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(format!("IdentityPool '{identity_pool_id}' not found.")),
                },
            )
            .into());
        };

        // The tag set the pool would end up with: what it holds, plus the keys this call
        // carries, with the call's value winning for a key that is already there. The
        // ceiling is on the RESULT, so re-assigning keys a pool already holds never takes
        // it past the limit however many tags the call carries.
        let held = record.identity_pool_tags.clone().unwrap_or_default();
        let mut assigned = held.clone();
        for (tag_key, tag_value) in requested {
            assigned.insert(tag_key.clone(), tag_value.clone());
        }
        if assigned.len() > crate::state::MAX_TAGS_PER_IDENTITY_POOL {
            return Err(invalid_parameter(
                crate::state::too_many_user_tags_message(),
            ));
        }

        // A call that leaves the pool holding the set it already held changed nothing, so it
        // leaves the record untouched — including the instant it was last modified. That
        // covers a call carrying no key at all and one re-assigning the value a key already
        // has, and it is the same rule `UntagResource` moves the instant by: the instant
        // moves when the stored tag set really changes.
        if assigned != held {
            record.identity_pool_tags = Some(assigned);
            record.last_modified_date = ::std::time::SystemTime::now();
        }
        Ok(TagResourceOutput {})
    }
}

/// Every modelled-constraint violation in the request's `Tags`, in key order, each phrased
/// the way a constraint refusal names the member and the constraint it failed.
///
/// The map's KEY and VALUE shapes carry the bounds ([`crate::state::TAG_KEY_LENGTH`] and
/// [`crate::state::TAG_VALUE_LENGTH`], which every operation of this service reading a tag
/// shares), so a violation is in one entry of the map rather than in the member as a whole,
/// and the entry is named in the member path.
fn constraint_violations(requested: &[(&String, &String)]) -> Vec<String> {
    let mut violations = Vec::new();
    for (tag_key, tag_value) in requested {
        if !crate::state::length_is_within(tag_key, &crate::state::TAG_KEY_LENGTH) {
            violations.push(format!(
                "Value '{tag_key}' at 'tags' failed to satisfy constraint: Map keys must have \
                 length greater than or equal to {} and less than or equal to {}",
                crate::state::TAG_KEY_LENGTH.start(),
                crate::state::TAG_KEY_LENGTH.end()
            ));
        }
        if !crate::state::length_is_within(tag_value, &crate::state::TAG_VALUE_LENGTH) {
            violations.push(format!(
                "Value '{tag_value}' at 'tags.{tag_key}' failed to satisfy constraint: Member \
                 must have length less than or equal to {}",
                crate::state::TAG_VALUE_LENGTH.end()
            ));
        }
    }
    violations
}

