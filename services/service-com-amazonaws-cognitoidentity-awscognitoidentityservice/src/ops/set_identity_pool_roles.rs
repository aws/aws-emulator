/// The `Roles` map as it will be stored, or the refusal for the first entry the map may not
/// carry.
///
/// Two refusals, and they are different CLASSES. A KEY outside the constraints `RoleType`
/// declares breaks a constraint the MODEL states, which is a protocol-level refusal — HTTP
/// 400 `ValidationException` naming the member, the map it was handed and what a key of that
/// map has to satisfy ([`crate::state::map_key_constraint_refusal`]) — and reaches a handler
/// at all only because the validating walk ahead of it treats a map's key as a path segment
/// rather than as a constrained leaf. A VALUE satisfies every constraint the model states
/// (`ARNString` bounds only the length), so what is asked of it is not its form but whether
/// Amazon Cognito may be passed it: a value that names no role of this account is refused
/// `NotAuthorizedException` ([`not_authorized`]).
fn validated_roles(
    roles: &::std::collections::HashMap<String, String>,
) -> Result<::std::collections::BTreeMap<String, String>, SetIdentityPoolRolesError> {
    // Ordered, so which entry a multi-entry map is refused for, and the order a refusal
    // states the map in, do not depend on the iteration order of the request's map.
    let submitted: ::std::collections::BTreeMap<String, String> = roles
        .iter()
        .map(|(role_type, role_arn)| (role_type.clone(), role_arn.clone()))
        .collect();
    for (role_type, role_arn) in &submitted {
        if !ROLE_TYPES.contains(&role_type.as_str()) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::map_key_constraint_refusal(
                    ROLES_MEMBER_PATH,
                    &submitted,
                    &ROLE_TYPE_LENGTH,
                    Some(&::service_common::validation::unanchored(ROLE_TYPE_PATTERN)),
                ),
            ));
        }
        if !crate::state::names_an_assumable_role(role_arn) {
            return Err(not_authorized());
        }
    }
    // Every key and value was admitted, so the map as submitted is the map as stored.
    Ok(submitted)
}

/// The `RoleMappings` map as it will be stored, or the modelled refusal for the first
/// mapping that is not complete for its `Type`.
fn validated_role_mappings(
    role_mappings: &::std::collections::HashMap<String, RoleMapping>,
) -> Result<::std::collections::BTreeMap<String, RoleMapping>, SetIdentityPoolRolesError> {
    let mut validated = ::std::collections::BTreeMap::new();
    let mut entries: Vec<(&String, &RoleMapping)> = role_mappings.iter().collect();
    entries.sort_by_key(|(provider, _)| *provider);
    for (provider, mapping) in entries {
        if !ROLE_MAPPING_TYPE_VALUES.contains(&mapping.r#type.as_str()) {
            return Err(invalid_parameter(format!(
                "RoleMappings['{provider}'].Type '{}' is not valid: the type must be one of {}.",
                mapping.r#type,
                ROLE_MAPPING_TYPE_VALUES.join(", ")
            )));
        }
        // `RoleMapping$AmbiguousRoleResolution`, from the model: "If you specify Token or
        // Rules as the Type, AmbiguousRoleResolution is required." `RoleMappingType` is
        // exactly those two values, so it is required for every mapping, and the refusal is
        // the sentence AWS words that condition with over the `Type` that requires it.
        match mapping.ambiguous_role_resolution.as_deref() {
            None => {
                return Err(invalid_parameter(ambiguous_role_resolution_required(
                    &mapping.r#type,
                )));
            }
            Some(resolution) if !AMBIGUOUS_ROLE_RESOLUTION_TYPE_VALUES.contains(&resolution) => {
                return Err(invalid_parameter(format!(
                    "RoleMappings['{provider}'].AmbiguousRoleResolution '{resolution}' is not \
                     valid: it must be one of {}.",
                    AMBIGUOUS_ROLE_RESOLUTION_TYPE_VALUES.join(", ")
                )));
            }
            Some(_) => {}
        }
        // `RoleMapping$RulesConfiguration`, from the model: "If you specify Rules as the
        // role mapping type, RulesConfiguration is required." The refusal is the fixed
        // sentence AWS words that condition with, naming neither the provider the mapping is
        // keyed by nor the member it is missing twice over.
        if mapping.r#type == RULES_ROLE_MAPPING_TYPE && mapping.rules_configuration.is_none() {
            return Err(invalid_parameter(
                RULES_CONFIGURATION_REQUIRED_MESSAGE.to_string(),
            ));
        }
        if let Some(configuration) = &mapping.rules_configuration {
            if configuration.rules.len() > crate::state::MAX_RULES_PER_IDENTITY_PROVIDER {
                return Err(invalid_parameter(format!(
                    "RoleMappings['{provider}'].RulesConfiguration.Rules carries {} rules: at \
                     most {} rules can be specified per identity provider.",
                    configuration.rules.len(),
                    crate::state::MAX_RULES_PER_IDENTITY_PROVIDER
                )));
            }
            // A role a RULE resolves to is as much a role this pool would be passed as one
            // of its two plain roles, so the same question is asked of it.
            if configuration
                .rules
                .iter()
                .any(|rule| !crate::state::names_an_assumable_role(&rule.role_arn))
            {
                return Err(not_authorized());
            }
        }
        validated.insert(provider.clone(), mapping.clone());
    }
    Ok(validated)
}

