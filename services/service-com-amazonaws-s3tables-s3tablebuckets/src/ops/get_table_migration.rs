/// Where the migration's reports go: the bucket every report is written to, and
/// one overview per report carrying the prefix it is written under.
///
/// A report's `key`, its checksum and its finding counts are "returned after the
/// migration writes the report", and this emulator holds no source objects to
/// report on, so no report object exists and those members are left out rather
/// than filled with values nothing computed. The prefix IS reported, because it
/// is the configuration the migration was started with and this store holds it.
fn reported_output(stored: &crate::state::MigrationReports) -> MigrationOutputOverview {
    let overview = |prefix: Option<String>| ReportOverview {
        prefix,
        key: None,
        checksum_crc64_nvme: None,
        invalid_findings: None,
    };
    MigrationOutputOverview {
        bucket: stored.bucket.clone(),
        table_compatibility_report: overview(stored.table_compatibility_prefix.clone()),
        object_compatibility_report: overview(stored.object_compatibility_prefix.clone()),
        object_migration_report: overview(stored.object_migration_prefix.clone()),
    }
}

