/// The maintenance settings and migration policies the migration applies to the
/// destination table, with every member the request left out settled at the
/// model's own default for it — so what is persisted is one whole configuration
/// and a read of it answers the same values whichever members the request
/// carried.
///
/// `Err` carries the sentence the request is refused with: the compaction
/// strategy, whose only accepted value is the one a migration compacts the
/// destination table under ("The only valid value is `binpack`",
/// `MigrationCompactionSettings$strategy`), and the two policy members, which the
/// model targets at enums — so a value outside either set is refused at the
/// boundary and reaching here with an unknown one would mean the model changed
/// under us.
fn requested_data_migration(
    settings: Option<&DataMigrationSettings>,
) -> Result<crate::state::DataMigration, String> {
    let mut stored = crate::state::DataMigration::default();
    let Some(settings) = settings else {
        return Ok(stored);
    };
    if let Some(maintenance) = settings.maintenance_settings.as_ref() {
        if let Some(compaction) = maintenance.iceberg_compaction.as_ref() {
            // The model bounds the size at `@range(64, 512)`, so the boundary has
            // already refused one outside the window a migration writes towards.
            stored.target_file_size_mb = compaction.target_file_size_mb;
            let strategy = crate::state::IcebergCompactionStrategy::from_wire(&compaction.strategy)
                .filter(|strategy| *strategy == crate::state::MIGRATION_COMPACTION_STRATEGY)
                .ok_or_else(|| crate::state::INVALID_COMPACTION_STRATEGY_MESSAGE.to_string())?;
            stored.compaction_strategy = strategy;
        }
        if let Some(snapshots) = maintenance.iceberg_snapshot_management.as_ref() {
            stored.min_snapshots_to_keep = snapshots.min_snapshots_to_keep;
            stored.max_snapshot_age_hours = snapshots.max_snapshot_age_hours;
        }
    }
    if let Some(policies) = settings.migration_policies.as_ref() {
        stored.unmatched_source_fields = crate::state::UnmatchedSourceFieldsPolicy::from_wire(
            &policies.unmatched_source_fields_policy,
        )
        .ok_or_else(|| crate::state::INVALID_INPUT_MESSAGE.to_string())?;
        stored.incompatible_values = crate::state::IncompatibleValuesPolicy::from_wire(
            &policies.incompatible_values_policy,
        )
        .ok_or_else(|| crate::state::INVALID_INPUT_MESSAGE.to_string())?;
    }
    Ok(stored)
}

