/// The state the migration moves into for `requested`, or the sentence the
/// request is refused with because the migration's CURRENT state is not one
/// `requested` moves out of.
///
/// The two rules `UpdateTableMigration` states, read off the migration's own
/// state: `queued` "continue[s] a migration in the pendingReview state", and
/// `cancelled` cancels "a migration in the new, planning, pendingReview, queued
/// or migrating state" — which moves it to `cancelling`, because a cancelled
/// migration "finishes the work in progress, and then ends in the cancelled
/// state".
fn moves_to(
    requested: crate::state::MigrationRequestedState,
    current: crate::state::MigrationState,
) -> Result<crate::state::MigrationState, &'static str> {
    match requested {
        crate::state::MigrationRequestedState::Queued => {
            if current == crate::state::MigrationState::PendingReview {
                Ok(crate::state::MigrationState::Queued)
            } else {
                Err(crate::state::MIGRATION_NOT_PENDING_REVIEW_MESSAGE)
            }
        }
        crate::state::MigrationRequestedState::Cancelled => {
            if current.is_cancellable() {
                Ok(crate::state::MigrationState::Cancelling)
            } else {
                Err(crate::state::MIGRATION_ALREADY_ENDED_MESSAGE)
            }
        }
    }
}

