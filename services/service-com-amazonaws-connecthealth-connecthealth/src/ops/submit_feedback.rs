        // request was signed for, so a domain of another Region is not found here.
        let region = crate::state::region_of(ctx);
        let now = ::std::time::SystemTime::now();

        let mut store = state.lock();
        // The one preamble every handler shares, before anything is resolved or written:
        // everything the CLOCK already made due.
        store.materialise_due(now);

        let not_found = |message: String| -> Self::Error {
            SubmitFeedbackErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                message: Some(message),
                ..Default::default()
            })
            .into()
        };
        if store.live_domain(&region, &input.domain_id).is_none() {
            return Err(not_found(
                crate::service::error_detail::domain_not_found_message(&input.domain_id),
            ));
        }
        // A subscription the request names has to be one of THIS domain's, resolved through
        // the same liveness rule its own reader uses.
        if let Some(subscription_id) = input.subscription_id.as_deref() {
            if store
                .live_subscription(&region, &input.domain_id, subscription_id)
                .is_none()
            {
                return Err(not_found(
                    crate::service::error_detail::subscription_not_found_message(
                        &input.domain_id,
                        subscription_id,
                    ),
                ));
            }
        }

        // A token this domain has already recorded a submission under is a REPEAT: the
        // request is ignored and still accepted, which is what this operation's own
        // documentation says of the member.
        let repeat = input.client_token.as_deref().is_some_and(|token| {
            store
                .live_domain(&region, &input.domain_id)
                .is_some_and(|domain| {
                    domain
                        .feedback
                        .values()
                        .any(|held| held.client_token.as_deref() == Some(token))
                })
        });
        if repeat {
            return Ok(SubmitFeedbackOutput {});
        }

        // Bound the store BEFORE minting, so a refused submission advances nothing. This
        // operation models no quota failure, so the refusal goes out as the modelled
        // client-input error, naming the count it enforced.
