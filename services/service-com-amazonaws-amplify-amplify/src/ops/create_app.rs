impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateApp<Eng>
{
    type Input = CreateAppInput;
    type Output = CreateAppOutput;
    type Error = CreateAppError;

    const NAME: &'static str = "CreateApp";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_APP_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_APP_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            CreateAppErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the Amplify emulator has no state store attached".to_string()),
            })
        })?;

        let region = crate::state::request_region(ctx.parts());
        // One instant for both stamps: an app Amplify has only just created has not
        // been updated since, so `createTime` and `updateTime` are equal.
        let created = crate::state::now();

        let mut store = state.lock();

        // The quota is enforced BEFORE anything is minted or stored, so a refused
        // create leaves the store exactly as it was and the number of records one
        // caller can accumulate is bounded.
        if store.apps.len() >= MAX_APPS {
            return Err(CreateAppErrorModeled::LimitExceededException(LimitExceededException {
                message: Some(format!(
                    "Number of apps exceeds the limit of {MAX_APPS} for this account and Region"
                )),
            })
            .into());
        }

        // The rewrite and redirect rules are walked for every request the app's hosting
        // edge serves, so the list one app may carry is bounded the same way — before
        // anything is stored.
        let supplied_rules = input.custom_rules.as_ref().map_or(0, Vec::len);
        if supplied_rules > crate::state::MAX_CUSTOM_RULES_PER_APP {
            return Err(CreateAppErrorModeled::LimitExceededException(LimitExceededException {
                message: Some(crate::state::custom_rules_limit_message(
                    &input.name,
                    supplied_rules,
                )),
            })
            .into());
        }

        // Three members of the request are INGESTED rather than stored as sent, each by
        // the one reader of its member in this crate:
        //
        // * the basic-authorization credentials for this app's branches, of which only a
        //   verifier is kept — the record reports the reference every reader is answered
        //   with, never the credentials the request sent (`BasicAuthCredentials` is
        //   `@sensitive`; see `crate::state::basic_auth`);
        // * the same `@sensitive` member inside the auto-branch-creation configuration;
        // * the custom-header document, which is a DOCUMENT: the rules it declares are
        //   parsed here, once, and the record reports them re-serialized as JSON (see
        //   `crate::state::custom_headers`).
        //
        // The document is read — and a document declaring more rules than one app may
        // carry refused — BEFORE anything is minted or stored, so a refused create leaves
        // the store exactly as it was, exactly like the rewrite-rule bound above.
        let (reported_headers, header_rules) =
            match crate::state::ingest_custom_headers(input.custom_headers) {
                crate::state::IngestedCustomHeaders::TooManyRules(supplied) => {
                    return Err(CreateAppErrorModeled::LimitExceededException(
                        LimitExceededException {
                            message: Some(crate::state::custom_header_rules_limit_message(
                                &input.name,
                                supplied,
                            )),
                        },
                    )
                    .into())
                }
                crate::state::IngestedCustomHeaders::Declared { document, rules } => {
                    (document, rules)
                }
                // The record always carries the member: an app created without a document
                // carries the empty one, which declares no rule.
                crate::state::IngestedCustomHeaders::Unsupplied => (String::new(), Vec::new()),
            };
        let mut kept_credentials = None;
        let reported_credentials =
            crate::state::ingest_basic_auth(&mut kept_credentials, input.basic_auth_credentials);
        let mut auto_branch_creation_config = input.auto_branch_creation_config;
        crate::state::ingest_auto_branch_basic_auth(&mut auto_branch_creation_config);

        let app_id = store.mint_app_id();

        let app = App {
            app_arn: ::emulator_server::emulator_arn("amplify", &region, &format!("apps/{app_id}")),
            // `defaultDomain` is the domain the app's hosting is published under — a
            // client composes `https://<branch displayName>.<defaultDomain>/` from it —
            // and it is a property of the APP: the minted app id under Amplify's hosting
            // zone, resolved once here and reported unchanged by every later read
            // (`crate::state::hosting_address`). The member is @required and never empty.
            default_domain: crate::state::amplify_zone_default_domain(&app_id),
            app_id,
            name: input.name,
            // `tags` is echoed exactly as the request set it: the create response
            // carries the member only when the request carried it, and a later read
            // reports the app's tag map (see `AppProjection::reported`).
            tags: input.tags,
            // The @required members below have no value in a request that omits
            // them. The record holds the empty value of the member's type, which is
            // what `AppProjection` reports as JSON `null`.
            description: input.description.unwrap_or_default(),
            repository: input.repository.unwrap_or_default(),
            platform: input.platform.unwrap_or_else(|| DEFAULT_PLATFORM.to_string()),
            create_time: created,
            update_time: created,
            compute_role_arn: input.compute_role_arn,
            iam_service_role_arn: input.iam_service_role_arn,
            environment_variables: input.environment_variables.unwrap_or_default(),
            enable_branch_auto_build: input.enable_branch_auto_build.unwrap_or(false),
            // Every feature flag below is OFF on an app created without it, and an
            // app Amplify created has a definite answer for each: the flag carries
            // `false`, never nothing at all.
            enable_branch_auto_deletion: Some(input.enable_branch_auto_deletion.unwrap_or(false)),
            enable_basic_auth: input.enable_basic_auth.unwrap_or(false),
            basic_auth_credentials: reported_credentials,
            // The redirect/rewrite rules and the custom header document are
            // collections the app always has: empty until a request supplies one.
            custom_rules: Some(input.custom_rules.unwrap_or_default()),
            // A production branch is a property of a DEPLOYED branch, and a new app
            // has no branches at all.
            production_branch: None,
            build_spec: input.build_spec,
            custom_headers: Some(reported_headers),
            enable_auto_branch_creation: Some(input.enable_auto_branch_creation.unwrap_or(false)),
            auto_branch_creation_patterns: input.auto_branch_creation_patterns,
            auto_branch_creation_config,
            // `repositoryCloneMethod` is documented "for internal use": Amplify sets
            // it from the credential kind it used to reach the repository, and this
            // emulator reaches no repository.
            repository_clone_method: None,
            // An app always has a cache configuration; an app created without one
            // gets the type the model calls the default setting.
            cache_config: Some(input.cache_config.unwrap_or_else(|| CacheConfig {
                r#type: DEFAULT_CACHE_CONFIG_TYPE.to_string(),
            })),
            // Set when Amplify creates a webhook in the connected Git repository,
            // which creating an app does not do.
            webhook_create_time: None,
            waf_configuration: None,
            // An app always has a job configuration: the build instance size its
            // jobs run on, which defaults to the size the model documents.
            job_config: Some(input.job_config.unwrap_or_else(|| JobConfig {
                build_compute_type: DEFAULT_BUILD_COMPUTE_TYPE.to_string(),
            })),
        };

        // `accessToken` / `oauthToken` are deliberately NOT persisted: both members
        // document "The token is not stored.", and neither appears on `App`.
        store.apps.insert(
            app.app_id.clone(),
            crate::state::AmplifyApp::created(app.clone(), kept_credentials, header_rules),
        );

        Ok(CreateAppOutput {
            app: AppProjection::written(app),
        })
    }
}

