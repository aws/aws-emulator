/// The queue `arn` names, projected onto `QueueDescription` — the ONE reading of a stored
/// queue the three operations that answer a description share
/// (`crate::ops::create_queue`, `crate::ops::update_queue`, this one), so a create, an update
/// and a read never disagree about one queue.
///
/// The stream's trim horizon travels with it, because the starting position a read reports is
/// the effective one ([`crate::state::Queue::reported_starting_position`]).
pub(crate) fn described_queue(
    store: &crate::state::ComAmazonawsKinesisKinesis20131202State,
    now: ::std::time::SystemTime,
    region: &str,
    arn: &str,
) -> Option<QueueDescription> {
    let queue = store.queue_by_arn(now, region, arn)?;
    let trim_horizon = store
        .stream_by_arn(now, region, &queue.stream_arn)
        .map(|stream| stream.trim_horizon(now));
    Some(queue.to_description(now, trim_horizon))
}

