/// The `MaxReceiveCount` the queue's dead-letter handling runs with, or the refusal the
/// configuration earns.
///
/// "Dead-letter handling is enabled by default, with a MaxReceiveCount of 6. To use a
/// different value, or to turn dead-letter handling off, specify DeadLetterConfiguration"
/// (`CreateQueue`), and "if you specify it with a TargetType of BUILT_IN, you must also
/// specify MaxReceiveCount" (`QueueAttributes$DeadLetterConfiguration`) — so a queue carrying
/// no configuration at all, and one that carries `BUILT_IN` with a count, both run with a
/// count, and only `NONE` runs without one.
///
/// ONE rule for the create that first states it and the update that re-states it alike
/// (`crate::ops::update_queue`).
pub(crate) fn resolved_max_receive_count(
    configuration: Option<&DeadLetterConfiguration>,
) -> Result<Option<i32>, String> {
    match configuration {
        None => Ok(Some(crate::state::DEFAULT_MAX_RECEIVE_COUNT)),
        Some(configuration) if configuration.target_type == crate::state::TARGET_TYPE_NONE => {
            Ok(None)
        }
        Some(configuration) => match configuration.max_receive_count {
            Some(count) => Ok(Some(count)),
            None => Err(crate::state::MAX_RECEIVE_COUNT_REQUIRED_MESSAGE.to_string()),
        },
    }
}

/// Insert the queue the request names, or answer the modelled refusal that stands in the way.
///
/// The whole read-and-write lives here so the caller holds the store's lock for exactly this
/// long, which is what serialises two overlapping creates of one name: exactly one of them
/// inserts a record and the other is told the name is taken.
///
/// The order the refusals are taken in: what the request says on its own first, then the name
/// and the room this store has, then what the request says ABOUT the stored stream. So a
/// create that is wrong in two ways is refused for the request's own fault before the store's,
/// which keeps a refusal the same whatever the store happens to hold. AWS documents no
/// precedence between them.
fn create_queue(
    store: &mut crate::state::ComAmazonawsKinesisKinesis20131202State,
    region: &str,
    now: ::std::time::SystemTime,
    input: &CreateQueueInput,
) -> Result<QueueDescription, CreateQueueError> {
    let configuration = stream_configuration(input)?;
    let max_receive_count = resolved_max_receive_count(
        input
            .queue_attributes
            .as_ref()
            .and_then(|attributes| attributes.dead_letter_configuration.as_ref()),
    )
    .map_err(validation)?;
    // A key in the namespace AWS keeps for itself is no caller's to write
    // ([`crate::state::reserved_tag_keys`]), so a create carrying one stores no queue, and a
    // tag set past the documented ceiling is refused rather than stored short.
    if let Some(tags) = input.tags.as_ref() {
        if crate::state::names_reserved_tag_key(tags.keys().map(String::as_str)) {
            return Err(invalid_argument(
                crate::state::RESERVED_TAG_KEYS_MESSAGE.to_string(),
            ));
        }
        if tags.len() > crate::state::MAX_QUEUE_TAGS {
            return Err(invalid_argument(crate::state::tag_ceiling_exceeded_message(
                tags.len(),
            )));
        }
    }

    // A queue a delete has already carried off frees its name once that removal falls due, so
    // the store is pruned before the name and the room are counted.
    store.drop_removed_queues(now);
    if store.queue_in(now, region, &input.queue_name).is_some() {
        return Err(resource_in_use(crate::state::queue_already_exists_message(
            &input.queue_name,
        )));
    }
    let held_in_region = store.queues_held_in(now, region);
    let held = store.queues_held(now);
    if held_in_region >= crate::state::MAX_QUEUES_PER_REGION
        || held >= crate::state::MAX_QUEUES_TOTAL
    {
        return Err(limit_exceeded(crate::state::queue_ceiling_exceeded_message(
            held_in_region,
            held,
        )));
    }

    // The stream half of the create, read from the STORED stream rather than from the request:
    // a queue delivers from one stream of this account and region, so a `StreamARN` naming
    // none names no queue this service could create.
    let stream_arn = configuration.stream_arn.as_str();
    let stream = store
        .stream_by_arn(now, region, stream_arn)
        .ok_or_else(|| not_found(crate::state::stream_not_found_message(stream_arn)))?;
    if stream.stream_mode != crate::state::STREAM_MODE_ON_DEMAND {
        return Err(validation(crate::state::stream_not_on_demand_message(
            &stream.name,
            &stream.stream_mode,
        )));
    }
    let status = stream.status(now);
    if status != crate::state::STREAM_ACTIVE {
        return Err(resource_in_use(crate::state::stream_not_active_message(
            &stream.name,
            status,
        )));
    }
    // "A queue counts as a registered consumer on the stream and shares the stream's
    // registered consumer limit with enhanced fan-out consumers" (`CreateQueue`), so the two
    // kinds are counted against ONE ceiling.
    let stream_name = stream.name.clone();
    let stream_created_at = stream.created_at;
    let registered = usize::try_from(stream.consumer_count()).unwrap_or_default()
        + store.queues_on(now, stream_arn);
    if registered >= crate::state::MAX_CONSUMERS_PER_STREAM {
        return Err(limit_exceeded(
            crate::state::consumer_ceiling_exceeded_message(&stream_name, registered),
        ));
    }
    let trim_horizon = store
        .stream_by_arn(now, region, stream_arn)
        .map(|stream| stream.trim_horizon(now));

    let position = configuration.starting_position.as_ref();
    let queue = crate::state::Queue {
        name: input.queue_name.clone(),
        region: region.to_string(),
        arn: crate::state::queue_arn(region, &input.queue_name, now),
        created_at: now,
        // CREATING is not terminal: the queue is owed ACTIVE, and the instant that is due is
        // stored rather than slept on.
        active_at: now + crate::state::QUEUE_ACTIVATION_DELAY,
        // No configuration change has been accepted for a queue this call has just minted, and
        // no delete, so the only transition it is owed is the one to `ACTIVE` above.
        updating_until: None,
        deleted_at: None,
        stream_arn: stream_arn.to_string(),
        stream_created_at,
        // "Use StartingPosition to set the position in the stream where delivery begins. The
        // default is LATEST" (`CreateQueue`).
        starting_position_type: position.map_or_else(
            || crate::state::QUEUE_STARTING_POSITION_LATEST.to_string(),
            |position| position.r#type.clone(),
        ),
        starting_position_at: position
            .and_then(|position| position.timestamp)
            // CHECKED, and already refused above for a timestamp that names no instant: the
            // addend is a value the caller chose, so it never reaches the panicking add.
            .and_then(crate::state::requested_instant),
        visibility_timeout_seconds: input
            .queue_attributes
            .as_ref()
            .and_then(|attributes| attributes.visibility_timeout_seconds)
            .unwrap_or(crate::state::DEFAULT_VISIBILITY_TIMEOUT_SECONDS),
        max_receive_count,
        tags: input.tags.clone().unwrap_or_default(),
        // A queue this call has just minted has drawn no record from the stream yet, so it
        // tracks none and its cursor stands at the position delivery begins at.
        cursor: ::std::collections::BTreeMap::new(),
        tracked: Vec::new(),
    };

    let description = queue.to_description(now, trim_horizon);
    store.queues.insert(
        crate::state::RegionalName::new(region, &input.queue_name),
        queue,
    );
    Ok(description)
}

