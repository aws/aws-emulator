/// Whether `queue` passes the `StreamFilter` the request carried: "Use StreamFilter to list
/// only the queues on a particular data stream" (`ListQueues`), so a request carrying none
/// lists every queue of the region and one carrying entries lists the queues on any stream it
/// names — the same rule, and the same reading of a pinned creation instant, that filters a
/// channel listing by its source stream.
fn passes_stream_filter(
    queue: &crate::state::Queue,
    filter: Option<&[QueueStreamFilter]>,
) -> bool {
    let Some(filters) = filter.filter(|filters| !filters.is_empty()) else {
        return true;
    };
    filters
        .iter()
        .any(|stream| queue.delivers_from(&stream.stream_arn, stream.stream_creation_timestamp))
}

