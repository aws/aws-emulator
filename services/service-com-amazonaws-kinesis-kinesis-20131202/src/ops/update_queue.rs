/// Apply the attributes the request names to the queue it names, or answer the modelled
/// refusal that stands in the way.
///
/// The whole read-and-write lives here so the caller holds the store's lock for exactly this
/// long — which is what serialises two overlapping updates of one queue: the first is applied
/// and the second finds the queue `UPDATING` and is told it is not available.
fn update_queue(
    store: &mut crate::state::ComAmazonawsKinesisKinesis20131202State,
    region: &str,
    now: ::std::time::SystemTime,
    input: &UpdateQueueInput,
) -> Result<QueueDescription, UpdateQueueError> {
    // What the request says ON ITS OWN is judged first, before the store is read at all, so an
    // update that is wrong in two ways is refused for its own fault whatever this account
    // holds.
    let attributes = &input.queue_attributes;
    let requested_max_receive_count = match attributes.dead_letter_configuration.as_ref() {
        None => None,
        Some(configuration) => Some(
            crate::ops::create_queue::resolved_max_receive_count(Some(configuration))
                .map_err(validation)?,
        ),
    };

    let identifier = input.queue_arn.as_str();
    let queue = store
        .queue_by_arn_mut(now, region, identifier)
        .ok_or_else(|| not_found(crate::state::queue_not_found_message(identifier)))?;
    // An update is a change to the queue's configuration, so the queue has to be ready for one:
    // a queue still being created, one whose earlier change is still due, and one a delete has
    // carried off are each "not available for this operation".
    let status = queue.status(now);
    if status != crate::state::QUEUE_ACTIVE {
        let refusal = crate::state::queue_not_active_message(&queue.name, status);
        return Err(resource_in_use(refusal));
    }

    // Each attribute the request names is written; one it omits is left as it was.
    if let Some(seconds) = attributes.visibility_timeout_seconds {
        queue.visibility_timeout_seconds = seconds;
    }
    if let Some(max_receive_count) = requested_max_receive_count {
        queue.max_receive_count = max_receive_count;
    }
    // UPDATING is not terminal: the queue is owed ACTIVE, and the instant that is due is stored
    // rather than slept on.
    queue.updating_until = Some(now + crate::state::QUEUE_UPDATE_DELAY);

    let stream_arn = queue.stream_arn.clone();
    let trim_horizon = store
        .stream_by_arn(now, region, &stream_arn)
        .map(|stream| stream.trim_horizon(now));
    let queue = store
        .queue_by_arn(now, region, identifier)
        .ok_or_else(|| not_found(crate::state::queue_not_found_message(identifier)))?;
    Ok(queue.to_description(now, trim_horizon))
}

