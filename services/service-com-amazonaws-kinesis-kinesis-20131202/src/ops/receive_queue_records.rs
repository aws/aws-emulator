fn one_look(
    store: &mut crate::state::ComAmazonawsKinesisKinesis20131202State,
    region: &str,
    now: ::std::time::SystemTime,
    input: &ReceiveQueueRecordsInput,
    limit: usize,
) -> Result<Vec<QueueRecord>, ReceiveQueueRecordsError> {
    match store.receive_from_queue(
        now,
        region,
        &input.queue_arn,
        crate::state::QueueReceive {
            path: crate::state::QueueRecordPath::Queue,
            limit,
            visibility_timeout_seconds: input.visibility_timeout_seconds,
            // The per-queue growth bound, stated where the growth is driven: a receive draws
            // records from the stream into the queue's delivery-tracking set, and that set
            // holds at most this many at once, so repeated receives cannot grow one queue
            // without bound. A queue at the ceiling draws again once the records it holds are
            // acknowledged.
            tracked_ceiling: crate::state::MAX_TRACKED_RECORDS_PER_QUEUE,
        },
    ) {
        Ok(records) => Ok(records),
        Err(crate::state::QueueReceiveFailure::NotFound) => Err(not_found(
            crate::state::queue_not_found_message(&input.queue_arn),
        )),
        Err(crate::state::QueueReceiveFailure::NotDelivering { .. }) => Ok(Vec::new()),
    }
}

