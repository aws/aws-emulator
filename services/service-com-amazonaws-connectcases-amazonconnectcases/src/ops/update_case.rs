impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateCase<Eng>
{
    type Input = UpdateCaseInput;
    type Output = UpdateCaseOutput;
    type Error = UpdateCaseError;

    const NAME: &'static str = "UpdateCase";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CASE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CASE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateCaseErrorModeled::InternalServerException(
                crate::state::state_unavailable(),
            )
            .into());
        };
        let principal = crate::state::caller_principal_arn(ctx);
        let now = ::std::time::SystemTime::now();

        // Pure input validation, done BEFORE the store lock is taken so no
        // caller-sized work happens while every other request is blocked. The
        // list is held to `MAX_CASE_FIELD_IDS` here as well as at the boundary,
        // so the scans below are bounded by this code, and they are linear.
        if let Some(message) = crate::state::list_too_long(
            "fields",
            input.fields.len(),
            crate::state::MAX_CASE_FIELD_IDS,
        ) {
            return Err(
                UpdateCaseErrorModeled::ValidationException(ValidationException { message }).into(),
            );
        }
        let duplicates = crate::state::duplicate_ids(input.fields.iter().map(|f| f.id.as_str()));
        if !duplicates.is_empty() {
            return Err(UpdateCaseErrorModeled::ValidationException(ValidationException {
                message: format!(
                    "fields carries more than one value for field ids: {}",
                    crate::state::name_ids(&duplicates)
                ),
            })
            .into());
        }

        let mut store = state.lock();

        let domain = store
            .domain_mut(&input.domain_id)
            .map_err(UpdateCaseErrorModeled::ResourceNotFoundException)?;

        // Resolve every reference the body carries, and check every value
        // against its field's own declared type, before writing any of it, so a
        // rejected update leaves the case exactly as it was.
        let unknown = domain.unrecorded_field_ids(input.fields.iter().map(|f| f.id.as_str()));
        // A DELETED field is a tombstone, not an absence: "Calling UpdateCase
        // with a deleted field ID throws a ValidationException if the case does
        // not already contain a value for the deleted field. Otherwise it
        // succeeds, allowing you to update or remove (using emptyValue: {}) the
        // field's value from the case"
        // (`smithy_query(query="doc",shape="DeleteField")`) — so the refusal
        // depends on the CASE, and is made once the case is resolved below.
        let deleted = domain.deleted_field_ids(input.fields.iter().map(|f| f.id.as_str()));
        let mismatched =
            domain.mismatched_field_values(input.fields.iter().map(|f| (f.id.as_str(), &f.value)));
        let Some(case) = domain.cases.get_mut(&input.case_id) else {
            return Err(UpdateCaseErrorModeled::ResourceNotFoundException(
                crate::state::not_found_worded(
                    crate::state::ResourceKind::Case,
                    &input.case_id,
                    crate::state::NotFoundWording::AddressedCase,
                ),
            )
            .into());
        };
        if !unknown.is_empty() {
            return Err(UpdateCaseErrorModeled::ValidationException(
                crate::state::unknown_fields(&unknown),
            )
            .into());
        }
        let deleted_without_a_value: Vec<String> = deleted
            .into_iter()
            .filter(|id| !case.field_values.contains_key(id))
            .collect();
        if !deleted_without_a_value.is_empty() {
            return Err(UpdateCaseErrorModeled::ValidationException(
                crate::state::deleted_fields(&deleted_without_a_value),
            )
            .into());
        }
        if !mismatched.is_empty() {
            return Err(UpdateCaseErrorModeled::ValidationException(ValidationException {
                message: format!("fields: {}", crate::state::name_ids(&mismatched)),
            })
            .into());
        }

        // The edit this call makes, as the case's audit history records it:
        // every field value it writes, each against the value the case held for
        // that field before this call. Taken BEFORE the merge below, which is
        // what makes the previous value readable at all.
        let edited_fields = crate::state::audit_event_fields(
            Some(&case.field_values),
            input.fields.iter().map(|field| (field.id.as_str(), &field.value)),
        );

        // A MERGE, not a replace: a supplied id overwrites the value stored for it
        // and every other stored value is left alone.
        for field in input.fields {
            case.field_values.insert(field.id, field.value);
        }
        let performed_by = input.performed_by;
        if let Some(user) = performed_by.clone() {
            case.performed_by = Some(user);
        }
        case.last_modified_time = now;

        // An audit entry reports the field values an edit wrote, and an update
        // that names none wrote nothing to report.
        if !edited_fields.is_empty() {
            case.record_audit_event(
                crate::state::AUDIT_EVENT_CASE_UPDATED,
                // An edit of the case itself, about no related item.
                None,
                now,
                principal,
                performed_by,
                edited_fields,
            );
        }

        Ok(UpdateCaseOutput {})
    }
}
