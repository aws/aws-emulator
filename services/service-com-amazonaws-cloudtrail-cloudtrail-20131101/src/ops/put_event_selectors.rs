/// request naming neither configures nothing, so it is a contradiction too.
fn read_configuration(
    event_selectors: Option<Vec<EventSelector>>,
    advanced_event_selectors: Option<Vec<AdvancedEventSelector>>,
) -> Result<crate::state::EventSelectorConfig, String> {
    match (event_selectors, advanced_event_selectors) {
        // The recorded refusal for a request carrying both members, which states the
        // documented rule itself ("You can use either AdvancedEventSelectors or
        // EventSelectors, but not both").
        (Some(_), Some(_)) => Err(
            "You can select events by using either EventSelectors or \
             AdvancedEventSelectors, but not both."
                .to_string(),
        ),
        (None, None) => Err(
            "A PutEventSelectors request must carry either EventSelectors or \
             AdvancedEventSelectors"
                .to_string(),
        ),
        (Some(selectors), None) => Ok(crate::state::EventSelectorConfig::Basic(
            normalize_event_selectors(selectors)?,
        )),
        (None, Some(selectors)) => {
            validate_advanced_event_selectors(&selectors)?;
            Ok(crate::state::EventSelectorConfig::Advanced(selectors))
        }
    }
}

/// Check a basic selector set against the documented limits and fill in each member's
/// documented default, so what is stored is what every later read reports.
///
/// Two rules are enforced over the set: the UPPER bounds on the selector and
/// data-resource counts, and that no selector would log NOTHING (see
/// [`selector_logs_nothing`]). An EMPTY list of selectors is a configuration in its own
/// right — nothing is logged — and is kept as given: the recorded behaviour this emulator
/// is measured against distinguishes an empty list from an absent member and preserves it
/// (corpus check `cloudtrail.event-selectors-empty-list-vs-absent-field-preserved`), so
/// the "1 to 5" phrasing in `InvalidEventSelectorsException`'s doc is read as the remedy
/// for too MANY selectors rather than as a floor.
fn normalize_event_selectors(selectors: Vec<EventSelector>) -> Result<Vec<EventSelector>, String> {
    // Each count refusal states the REMEDY for the bound it broke, naming that
    // bound — the wording the model's own `InvalidEventSelectorsException` doc
    // gives under "You can:", and the wording the recorded refusal of a request
    // past the selector bound carries.
    if selectors.len() > crate::state::EVENT_SELECTORS_PER_TRAIL_LIMIT {
        return Err(format!(
            "Specify a valid number of selectors (1 to {}) for your trail",
            crate::state::EVENT_SELECTORS_PER_TRAIL_LIMIT
        ));
    }

    let data_resources: usize = selectors
        .iter()
        .map(|selector| selector.data_resources.as_ref().map_or(0, Vec::len))
        .sum();
    if data_resources > crate::state::DATA_RESOURCES_PER_TRAIL_LIMIT {
        return Err(format!(
            "Specify a valid number of data resources (1 to {}) for an event selector",
            crate::state::DATA_RESOURCES_PER_TRAIL_LIMIT
        ));
    }

    // A selector that excludes management events and names no data resource selects
    // NOTHING, so the trail it is applied to would log nothing at all. That combination
    // is refused rather than installed — the model's own `InvalidEventSelectorsException`
    // doc names exactly this case as one of its own ("the combination of event selectors
    // or advanced event selectors and data resources is not valid") — and the refusal
    // leaves whatever the trail had configured before untouched, because nothing is
    // stored until every selector has been read.
    if selectors.iter().any(selector_logs_nothing) {
        return Err(NOTHING_LOGGED_MESSAGE.to_string());
    }

    selectors
        .into_iter()
        .map(|selector| {
            // `ReadWriteType` is a modelled enum, so a value outside it is already
            // refused before this handler runs — as `InvalidEventSelectorsException`,
            // which is what the model's own doc for that error calls it ("Specify a
            // valid value for a parameter. For example, specifying the ReadWriteType
            // parameter with a value of read-only is not valid"); see
            // `EmulatedService::override_refusal`.
            for resource in selector.data_resources.iter().flatten() {
                // "You can specify the following basic event selector resource
                // types"; anything else needs advanced event selectors. The refusal
                // is the service's one wording for a value outside the set its
                // parameter admits (`crate::state::value_not_valid_message`): the
                // parameter's API path and the value as the request sent it.
                let resource_type = resource.r#type.as_deref().unwrap_or_default();
                if !crate::state::BASIC_DATA_RESOURCE_TYPES.contains(&resource_type) {
                    return Err(crate::state::value_not_valid_message(
                        DATA_RESOURCE_TYPE_MEMBER,
                        resource_type,
                    ));
                }
            }
            for source in selector.exclude_management_event_sources.iter().flatten() {
                if !crate::state::EXCLUDABLE_MANAGEMENT_EVENT_SOURCES.contains(&source.as_str()) {
                    return Err(crate::state::value_not_valid_message(
                        EXCLUDE_MANAGEMENT_EVENT_SOURCES_MEMBER,
                        source,
                    ));
                }
            }
            Ok(EventSelector {
                // The documented defaults of a member the request leaves out, so a
                // stored selector is complete and reads of it agree.
                read_write_type: Some(selector.read_write_type.unwrap_or_else(|| {
                    crate::state::DEFAULT_READ_WRITE_TYPE.to_string()
                })),
                include_management_events: Some(
                    selector
                        .include_management_events
                        .unwrap_or(crate::state::DEFAULT_INCLUDE_MANAGEMENT_EVENTS),
                ),
                data_resources: Some(selector.data_resources.unwrap_or_default()),
                exclude_management_event_sources: Some(
                    selector.exclude_management_event_sources.unwrap_or_default(),
                ),
            })
        })
        .collect()
}

