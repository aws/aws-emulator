fn restore_in_progress_message(name: &str) -> String {
    format!("The request is already in progress for the domain {name}")
}

/// The message the `InvalidInput` refusal carries when the account still holds the
/// registration the request asks to restore.
///
/// Restoration applies to a registration the account no longer holds: the operation
/// "[r]estores a domain that has expired, or was deleted, before it becomes available for
/// others to register". A name this account holds right now has nothing to restore, which
/// is a problem with the REQUEST and so is stated in the envelope this service words those
/// in ([`crate::state::request_problem`]), naming the domain and the condition.
