/// A FIXED-SIZE digest of the parameters one create call states, for the
/// `@idempotencyToken` comparison: a replay carrying the same token but different parameters
/// is `IncompatibleParameterError`, and a digest is what makes remembering one token cost a
/// bounded amount of memory however large the request was.
///
/// Every member that decides what the policy IS takes part; the token itself does not,
/// because it is the key the digest is remembered under.
fn snapmirror_policy_parameter_fingerprint(
    input: &CreateSnapmirrorPolicyInput,
    tags: &BTreeMap<String, String>,
) -> String {
    let rendered = format!(
        "{:?}|{:?}|{}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}",
        input.file_system_id,
        input.storage_virtual_machine_id,
        input.name,
        input.snapshot_copy_mode,
        input
            .retention_rules
            .as_ref()
            .map(|rules| format!("{rules:?}")),
        input.transfer_schedule,
        input.network_compression_enabled,
        input.throttle_in_kbps,
        tags,
    );
    ::hex::encode(<::sha2::Sha256 as ::sha2::Digest>::digest(
        rendered.as_bytes(),
    ))
}
