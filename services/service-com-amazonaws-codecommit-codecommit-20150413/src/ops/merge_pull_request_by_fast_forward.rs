//! @op MergePullRequestByFastForward
//!
//! Implemented: merges the pull request's source reference into its destination
//! reference with the FAST-FORWARD strategy — the one merge that writes no commit.
//! A fast-forward is nothing but an advance of the destination reference, so the
//! only question it asks is how the two tips are related by ancestry
//! ([`crate::state::merge::fast_forward`], the one reading of that relation this
//! crate has, shared with `MergeBranchesByFastForward` and `GetMergeOptions`): the
//! merge is admitted exactly where the destination tip IS the merge base of the two,
//! and the destination branch is then left at the SOURCE tip, which is the merge
//! (two references holding the same tip advance by nothing and are still admitted).
//! Nothing about which paths either side changed enters into it, which is why this
//! operation models no conflict members.
//!
//! A destination tip that is NOT the merge base holds commits the source does not —
//! the source already merged, or the two histories diverged — and no move of the
//! destination reference can honour both sides, so the merge is refused with the
//! modelled `ManualMergeRequiredException` and nothing is written; so are a pull
//! request that
//! was closed without ever being merged, one whose approval rules still state
//! conditions its approvals do not meet
//! ([`crate::state::PullRequestRecord::approval_rules_satisfied`]), and one whose
//! source or destination reference the repository no longer holds — the modelled
//! `ReferenceDoesNotExistException`, which is the error the model gives THIS merge
//! and not its squash and three-way siblings, because a fast-forward has nothing but
//! those references to work with.
//!
//! A pull request this operation ALREADY merged ([`crate::state::PullRequestRecord::
//! is_merged`]) is not one it attempts again: the merge happened, so the call is the
//! idempotent re-read of it and the stored pull request is answered unchanged — the
//! same merge commit, the same `mergedBy`, the destination reference left where the
//! merge put it.
//!
//! The merge is between the tips the two references hold NOW rather than the tips
//! the pull request was opened at — `sourceCommitId` is the value to pass "if you
//! want an exception thrown if the current commit ID of the tip of the source branch
//! does not match this commit ID", so the current tip is what is merged — and the
//! stored target then records what was merged, who merged it, the commit the merge
//! left on the destination branch and the strategy, with the pull request CLOSED:
//! "If the merge is successful, it closes the pull request." A later
//! `GetPullRequest` therefore reports the merge rather than a prediction of it.
//!
//! The ancestry walk runs under one per-request budget and off the async worker,
//! exactly as every other merge question in this crate does, because it holds the
//! store guard for its whole span.
