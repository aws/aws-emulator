//! @op Converse
//! Serves one conversational turn: it validates the turn sequence and each
//! turn's own content, counts the input tokens with the tokenizer in
//! [`crate::state`] (the same one `CountTokens` uses) and refuses an input past
//! the model's context window ([`crate::state::context_window`]), answers with
//! an assistant message derived from the supplied conversation, and records the
//! call in the inference log.
//!
//! No language model runs in this emulator, so the assistant message says so
//! (see [`crate::state::emulated_completion_text`]); the turn semantics, the
//! token accounting, the stop reason and the metrics are all computed from the
//! request that was actually served.
//!
//! The supplied `inferenceConfig` bounds that message: it is composed to fit
//! `maxTokens` and it HALTS where the first configured `stopSequences` entry
//! completes (see [`crate::state::halt_at_stop_sequence`]), so a configured stop
//! sequence is the last thing the turn serves, nothing follows it, and the turn
//! reports `stop_sequence` as what stopped it.
//!
//! A mandatory `toolConfig.toolChoice` (`any` or `tool`) obliges the turn to
//! request a tool instead of generating text: the assistant message is then one
//! `toolUse` block whose `toolUseId` is minted here, whose `input` is the
//! argument object the requested tool's own `inputSchema` describes (see
//! [`crate::state::tool_input_arguments`]), and the turn stops on `tool_use`. A
//! later turn's `toolResult` has to address an id this service issued, which is
//! why the conversation's tool results are validated against the tool requests
//! it carries.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `Converse::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! ## Reaching this service's state
//!
//! The engine is held on `self` (constructor-injected), NOT passed per request — so
//! engine access is guaranteed by the time any request runs. Reach the store through
//! [`crate::state::service_state`] and read and write it through the guard it hands back:
//!
//! ```ignore
//!     let state = crate::state::service_state(&*self.engine)
//!         .ok_or(/* a modelled server error */)?;
//!     state.lock().your_field = /* ... */;
//! ```
//!
//! `ctx` ([`smithy_server_runtime::OperationContext`]) carries request metadata only —
//! headers, URI, method, and anything middleware placed in `ctx.parts().extensions`.
//! The engine is NOT reached through `ctx`.
//!
//! @generated by the emulator core scaffold op-stub generator.
