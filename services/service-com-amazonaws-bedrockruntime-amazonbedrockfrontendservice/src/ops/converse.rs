impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for Converse<Eng>
{
    type Input = ConverseInput;
    type Output = ConverseOutput;
    type Error = ConverseError;

    const NAME: &'static str = "Converse";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONVERSE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONVERSE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let started = ::std::time::Instant::now();
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ConverseErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the Bedrock Runtime emulator has no state store".to_string()),
                },
            )
            .into());
        };

        // The model has to be one this emulator recognises, and one the Converse
        // API serves: "Supported models and model features" lists base models
        // that only `InvokeModel` serves. An identifier the service cannot
        // interpret is a 400; one naming a model or resource that is not
        // available here is a 404 (see
        // `crate::state::resolve_model_for_inference`).
        let model = {
            let guard = state.lock();
            match guard.resolve_model_for_inference(&input.model_id) {
                Ok(entry) => entry.clone(),
                Err(crate::state::ModelRejection::Invalid(message)) => {
                    return Err(validation(message))
                }
                Err(crate::state::ModelRejection::NotFound(message)) => {
                    return Err(ConverseErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: Some(message),
                        },
                    )
                    .into())
                }
            }
        };
        if !model.supports_converse {
            return Err(validation(format!(
                "The model {} does not support the Converse API.",
                model.model_id
            )));
        }

        // A conversation needs a turn to answer; the ORDER its roles appear in
        // is not a precondition — the rule `ConverseStream` states too, so both
        // read it from `crate::state`.
        let messages =
            crate::state::validate_conversation(input.messages.as_ref()).map_err(validation)?;
        // Every tool result in that conversation has to address a tool request
        // the conversation carries, by the id that request was issued under.
        crate::state::validate_tool_results(messages).map_err(validation)?;

        // The input-size stage: a model reads a bounded prompt, so a request
        // whose counted input tokens are past the resolved model's context
        // window is refused rather than served against a shortened prompt (see
        // `crate::state::context_window`). The Converse API reports it as the
        // model-side error it is.
        let submitted_tokens = crate::state::converse_input_tokens(
            input.system.as_ref(),
            input.messages.as_ref(),
            input.tool_config.as_ref(),
        );
        if crate::state::context_window::exceeds_context_window(&model, submitted_tokens) {
            return Err(validation(crate::state::context_window::model_errors_message(
                crate::state::context_window::INPUT_TOKENS_EXCEEDED_MESSAGE,
            )));
        }

        // The tool stage: a mandatory `toolChoice` obliges the turn to request a
        // tool, and a choice left to the model is decided from the conversation
        // (`crate::state::tool_use_turn`) — under an id minted here.
        let tool_use = state
            .lock()
            .tool_use_for_turn(
                input.tool_config.as_ref(),
                input.messages.as_ref(),
                crate::state::now_millis(),
            )
            .map_err(validation)?;

        // The prompt-cache stage both Converse operations share: a `cachePoint`
        // marker delimits a cacheable prefix, which this call writes to the
        // cache or reads back from it, and which is then no longer charged as
        // ordinary input tokens.
        let cache = crate::state::serve_prompt_cache(
            &state,
            &model.model_id,
            input.system.as_ref(),
            input.messages.as_ref(),
            input.tool_config.as_ref(),
        );

        let turn = crate::state::converse_turn(
            &model,
            input.system.as_ref(),
            input.messages.as_ref(),
            input.tool_config.as_ref(),
            crate::state::TurnInference::of(input.inference_config.as_ref()),
            tool_use,
            cache,
        );
        // The guardrail stage: the account-enforced guardrail is applied to this
        // request whether or not it asked for a guardrail, and a turn it blocked
        // carries the guardrail's blocked messaging and ends on
        // `guardrail_intervened`.
        let turn = crate::state::enforced_guardrail::guard_converse_turn(
            &*self.engine,
            &model,
            input.system.as_ref(),
            input.messages.as_ref(),
            turn,
        );
        // The guardrail the REQUEST named, evaluated by the very stage
        // `ApplyGuardrail` evaluates the same policies with, so the two surfaces
        // cannot disagree about what this guardrail does to this text. A request
        // naming a guardrail revision this account does not hold, or one whose
        // guardrail needs grounding material it carries none of, names no guardrail
        // this turn can be guarded by.
        let guardrail = crate::state::guardrail_evaluation::converse_guardrail(
            &*self.engine,
            input
                .guardrail_config
                .as_ref()
                .and_then(|config| config.guardrail_identifier.as_deref()),
            input
                .guardrail_config
                .as_ref()
                .and_then(|config| config.guardrail_version.as_deref()),
            input
                .guardrail_config
                .as_ref()
                .map_or("", |config| config.trace.as_str()),
            input.system.as_ref(),
            input.messages.as_ref(),
        )
        .map_err(validation)?;
        // The policies are synchronous, CPU-bound work over caller-supplied text, so
        // they run off the async worker and under the one budget every surface that
        // runs these recognizers waits for.
        let (turn, guardrail_trace) = match guardrail {
            None => (turn, None),
            Some(guardrail) => {
                match ::tokio::time::timeout(
                    crate::state::guardrail_checks::EVALUATION_TIME_BUDGET,
                    ::tokio::task::spawn_blocking(move || {
                        crate::state::guardrail_evaluation::guard_turn(guardrail, turn)
                    }),
                )
                .await
                {
                    Ok(Ok(guarded)) => guarded,
                    // The guardrail did not answer, so there is no turn to serve: a
                    // turn served unguarded would be one this request asked to be
                    // guarded.
                    Ok(Err(error)) => {
                        return Err(ConverseErrorModeled::InternalServerException(
                            InternalServerException {
                                message: Some(format!(
                                    "the guardrail evaluation did not complete: {error}"
                                )),
                            },
                        )
                        .into())
                    }
                    Err(_) => {
                        return Err(ConverseErrorModeled::InternalServerException(
                            InternalServerException {
                                message: Some(format!(
                                    "the guardrail evaluation did not complete within {} seconds",
                                    crate::state::guardrail_checks::EVALUATION_TIME_BUDGET
                                        .as_secs()
                                )),
                            },
                        )
                        .into())
                    }
                }
            }
        };

        let logged = crate::state::InvocationLogEntry {
            model_id: model.model_id.clone(),
            kind: crate::state::InvokeKind::Converse,
            input_tokens: turn.input_tokens,
            output_tokens: turn.output_tokens,
            at_millis: crate::state::now_millis(),
        };
        state.lock().log_invocation(logged.clone());
        // The duration this call reports inline, measured over serving the turn.
        let latency_ms = crate::state::latency_ms(started.elapsed());
        // The token volume and the latency this call reports inline are also its
        // contribution to the `AWS/Bedrock` series dimensioned on the invoked
        // model, beside the one successful request it is, published with no state
        // guard of this service held.
        crate::state::invocation_metrics::publish_served_invocation(
            &*self.engine,
            &logged,
            latency_ms,
        );

        Ok(ConverseOutput {
            output: ConverseOutput2::Message(Message {
                role: "assistant".to_string(),
                content: turn.content(),
            }),
            stop_reason: turn.stop_reason().to_string(),
            usage: turn.usage(),
            metrics: ConverseMetrics { latency_ms },
            additional_model_response_fields: None,
            // The guardrail's own assessments, reported only where the request asked
            // for the trace.
            trace: guardrail_trace.map(|guardrail| ConverseTrace {
                guardrail: Some(guardrail),
                prompt_router: None,
            }),
            performance_config: input.performance_config.clone(),
            service_tier: input.service_tier.clone(),
        })
    }
}
