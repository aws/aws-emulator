//! @op CreateReplicator
//! Mints an MSK Replicator from the submitted configuration and registers it in
//! [`crate::state::ComAmazonawsKafkaKafkaState`]. A replicator name is unique
//! within an account and region, so a second create under a name already taken is
//! a `ConflictException`; a replication flow whose source and target resolve to
//! one Kafka cluster is a `BadRequestException`, since the two cluster aliases are
//! what distinguish the ends of a flow.
//!
//! The clusters a replicator names are not resolved while the request is ADMITTED:
//! `CreateReplicator` is asynchronous, so AWS accepts the request and reports the
//! replicator `CREATING` whether or not the Kafka clusters it points at exist. They
//! are resolved while the replicator is PROVISIONED
//! ([`crate::state::ComAmazonawsKafkaKafkaState::replicator_provisioning_failure`]),
//! and a setup naming an Amazon MSK cluster that does not exist converges to
//! `FAILED` carrying the modelled `StateInfo` instead of ever replicating.
//!
//! The SUBNETS each `KafkaClusters` entry names
//! (`KafkaClusterClientVpcConfig$SubnetIds`) are a different matter: the
//! replicator's own client interfaces are created in them, one per Availability
//! Zone, so a list that does not span the two or three Availability Zones a client
//! VPC configuration spans ([`crate::state::MIN_CLIENT_VPC_SUBNETS`]) is refused
//! from the request alone, before anything is resolved — as is a `KafkaClusters`
//! list that does not name the one source and the one target a replicator
//! replicates between ([`crate::state::KAFKA_CLUSTERS_PER_REPLICATOR`]). The
//! subnets themselves are EC2's resources rather than this service's, so what the
//! admitted list names is resolved against the account's EC2 inventory
//! ([`crate::state::network::placement_subnet_refusal`]) before any ARN is minted —
//! a subnet the account does not have is a `BadRequestException` and no replicator
//! record is written. Those interfaces are only ever created for a setup whose
//! clusters resolve, so that gate runs only when the clusters did — and it runs
//! LAST among this handler's refusals, after every decision taken from the request
//! and from this service's own registry, the name conflict included, so a create
//! MSK refuses on its own terms is never answered out of what another service
