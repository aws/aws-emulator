                    DeleteChannelErrorModeled::NotFoundException(NotFoundException {
                        invalid_parameter: Some("ChannelArn".to_string()),
                        message: Some(crate::state::RESOURCE_NOT_FOUND_MESSAGE.to_string()),
                    })
                    .into()
