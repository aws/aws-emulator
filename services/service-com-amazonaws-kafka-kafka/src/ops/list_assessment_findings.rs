/// Marker that prefixes this listing's page-token plaintext, so a token minted for
/// some other list cannot be mistaken for one of these. The assessment the token
/// was minted for is part of the plaintext, so one assessment's page cannot resume
/// another's findings.
const NEXT_TOKEN_PREFIX: &str = "kafka:assessment-findings:";

/// Separates the assessment ARN a token was minted for from the number of findings
/// the page had already reported. Neither an MSK ARN nor a decimal number can
/// contain it, so the plaintext splits back into exactly two fields.
const NEXT_TOKEN_SEPARATOR: char = '#';

/// The largest page this listing serves: "Default 100, maximum 500"
/// (`ListAssessmentFindingsRequest$MaxResults`), which is the range the model's
/// `__integerMin1Max500` states too.
const MAX_FINDINGS_RESULTS: i32 = 500;

/// The page size a request that names none asks for, from the same sentence.
const DEFAULT_FINDINGS_RESULTS: i32 = 100;

/// Encode how far into one assessment's findings a page got, through the crate's
/// one page-token codec ([`crate::state::encode_page_token`]).
fn encode_next_token(assessment_arn: &str, reported: usize) -> String {
    crate::state::encode_page_token(
        NEXT_TOKEN_PREFIX,
        &format!("{assessment_arn}{NEXT_TOKEN_SEPARATOR}{reported}"),
    )
}

/// How many findings a token resumes after, or `None` when the token is not one
/// this operation minted FOR THIS ASSESSMENT.
fn decode_next_token(token: &str, assessment_arn: &str) -> Option<usize> {
    let plaintext = crate::state::decode_page_token(NEXT_TOKEN_PREFIX, token)?;
    let (arn, reported) = plaintext.split_once(NEXT_TOKEN_SEPARATOR)?;
    if arn != assessment_arn {
        return None;
    }
    reported.parse::<usize>().ok()
}

