        if let Some(reason) = crate::state::tag_write_violation(
            &std::collections::BTreeMap::new(),
            input
                .tags
                .iter()
                .flatten()
                .map(|(key, value)| (key.as_str(), value.as_str())),
        ) {
            return Err(bad_request("tags", reason));
        }

