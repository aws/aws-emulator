        // protocol there as that cluster's brokers ([`crate::state::broker_plane`]), so
        // a client that takes any pair of a bootstrap string verbatim reaches a broker of
        // the cluster over the method that pair's port names. A method whose
        // socket could not be opened is reported as a server fault rather than announced
        // as an address nothing serves.
        type Method = state::broker_plane::AccessPath;
