impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    /// `TagResourceResponse` declares no member, and this surface answers such a success
    /// `204 No Content` — the status the recorded tagging responses carry, where the
    /// model leaves the code defaulted to 200. The BODY that goes with it is framed
    /// service-wide (`crate::service`).
    const SUCCESS_STATUS: u16 = ::service_common::no_content_responses::NO_CONTENT_STATUS;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the greengrassv2 state store is unavailable".to_string(),
                    retry_after_seconds: 1,
                },
            )
            .into());
        };

        let requested = st::tags_in(Some(&input.tags));
        let mut store = state.lock();
        // Tags belong to the resource, so they are written onto the ONE copy that
        // resource holds and that its own reader and the tag listing report. An ARN
        // that names no resource this service holds is refused with the tagging route's
        // own not-found class, and nothing is written.
        let Some(stored) = store.resource_tags_mut(&input.resource_arn) else {
            return Err(TagResourceError::NotFound(st::TaggingNotFound::new()));
        };

        // A tag whose key the resource already carries UPDATES that tag's value rather
        // than adding a second entry, so the resulting size is what the stored keys the
        // request does not name add to the keys it does.
        let resulting = requested.len()
            + stored
                .keys()
                .filter(|key| !requested.contains_key(*key))
                .count();
        if resulting > st::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::ValidationException(ValidationException {
                message: format!(
                    "A resource may carry at most {} tags; this request would leave \
                     {resulting}.",
                    st::MAX_TAGS_PER_RESOURCE
                ),
                reason: Some("FIELD_VALIDATION_FAILED".to_string()),
                fields: Some(vec![ValidationExceptionField {
                    name: "tags".to_string(),
                    message: format!(
                        "at most {} tags may be stored on one resource.",
                        st::MAX_TAGS_PER_RESOURCE
                    ),
                }]),
            })
            .into());
        }
        for (key, value) in requested {
            stored.insert(key, value);
        }
        let written = stored.len();
        drop(store);

        // Audit record for a state-changing call: who asked, what changed, and how it
        // ended. The presented access-key id is an identifier, never a secret.
        ::tracing::info!(
            target: "audit",
            operation = Self::NAME,
            outcome = "tagged",
            principal = %::engine::extract_akid(&ctx.parts().headers),
            resource = %input.resource_arn,
            tags = written,
            "wrote a resource's tags"
        );

        Ok(TagResourceOutput {})
    }
}
