impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CancelDeployment<Eng>
{
    type Input = CancelDeploymentInput;
    type Output = CancelDeploymentOutput;
    type Error = CancelDeploymentError;

    const NAME: &'static str = "CancelDeployment";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_DEPLOYMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_DEPLOYMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        // IAM decides first, before the deployment record is touched: a caller whose
        // identity-based policies do not allow this action on the deployment the request
        // names is refused 403, nothing is cancelled, and it learns nothing about whether
        // that deployment exists (`st::authorization`).
        let region = st::request_region(ctx.parts());
        st::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &st::deployment_arn(&region, &input.deployment_id),
        )
        .map_err(CancelDeploymentErrorModeled::AccessDeniedException)?;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(CancelDeploymentErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the greengrassv2 state store is unavailable".to_string(),
                    retry_after_seconds: 1,
                },
            )
            .into());
        };

        // The cancel is a WRITE on the one deployment record the deployment surface
        // reads, so an id nothing created is refused before anything changes, and the
        // status a later `GetDeployment` reports is the one stored here.
        let mut store = state.lock();
        let Some(entry) = store.deployments.get_mut(&input.deployment_id) else {
            return Err(CancelDeploymentErrorModeled::ResourceNotFoundException(
                st::deployment_not_found(&input.deployment_id),
            )
            .into());
        };
        // Cancelling what is already cancelled changes nothing and is not a failure:
        // the operation asks for a terminal status, which the deployment already has.
        let iot_job_id = entry.iot_job_id.clone();
        let previous = ::std::mem::replace(
            &mut entry.deployment_status,
            st::DEPLOYMENT_STATUS_CANCELED.to_string(),
        );
        drop(store);

        // "Cancels a deployment. This operation cancels the deployment for devices that
        // haven't yet received it" — which is what cancelling the IoT job that applies
        // it does, so the job this deployment reported is moved to the terminal
        // `CANCELED` status in the plane that owns jobs, where a client reads it. A
        // deployment whose job is no longer there (deleted through the jobs plane) is
        // cancelled on its own.
        if let Some(iot_jobs) = st::iot_job_store(&*self.engine) {
            let now = ::service_common::iot_job_executions::now_epoch_seconds();
            if let Some(job) = iot_jobs.lock().job_mut(&iot_job_id) {
                job.set_status(::service_common::iot_jobs::JOB_STATUS_CANCELED, now);
            }
        }

        // Audit record for a state-changing call: who asked, what changed, and how it
        // ended. The presented access-key id is an identifier, never a secret.
        ::tracing::info!(
            target: "audit",
            operation = Self::NAME,
            outcome = "canceled",
            principal = %::engine::extract_akid(&ctx.parts().headers),
            resource = %input.deployment_id,
            previous_status = %previous,
            "cancelled a deployment"
        );

        Ok(CancelDeploymentOutput {
            message: Some(CANCEL_ACCEPTED_MESSAGE.to_string()),
        })
    }
}

