impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeComponent<Eng>
{
    type Input = DescribeComponentInput;
    type Output = DescribeComponentOutput;
    type Error = DescribeComponentError;

    const NAME: &'static str = "DescribeComponent";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_COMPONENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_COMPONENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        // IAM decides first, before the catalog is read: a caller whose identity-based
        // policies do not allow this action on the component version the request names is
        // refused 403 and learns nothing about whether that version exists
        // (`st::authorization`). The resource is the ARN the request itself carried.
        st::authorization::authorize(&*self.engine, ctx, Self::NAME, &input.arn)
            .map_err(DescribeComponentErrorModeled::AccessDeniedException)?;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(DescribeComponentErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the greengrassv2 state store is unavailable".to_string(),
                    retry_after_seconds: 1,
                },
            )
            .into());
        };

        let now = ::std::time::SystemTime::now();
        let store = state.lock();

        let Some(entry) = store.component_version(&input.arn) else {
            // Greengrass words this operation's absent-version answer as the component
            // it could not find in the account the request is authorized for, so the
            // name and the version come out of the ARN the caller submitted and the
            // account out of this emulator's own.
            let (name, version) = st::parse_component_version_arn(&input.arn)
                .unwrap_or_else(|| (input.arn.clone(), String::new()));
            return Err(DescribeComponentErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: format!(
                        "Component ({name}:{version}) does not exist in account {}.",
                        st::account_id()
                    ),
                    resource_id: input.arn.clone(),
                    resource_type: "COMPONENT_VERSION".to_string(),
                },
            )
            .into());
        };

        Ok(DescribeComponentOutput {
            arn: Some(entry.arn.clone()),
            component_name: Some(entry.component_name.clone()),
            component_version: Some(entry.component_version.clone()),
            creation_timestamp: Some(st::to_datetime(entry.creation_timestamp)),
            publisher: entry.publisher.clone(),
            description: entry.description.clone(),
            // The REQUESTED -> DEPLOYABLE move the clock owes is DERIVED from the
            // stored due instant: this read writes nothing.
            status: Some(entry.status_at(now)),
            platforms: (!entry.platforms.is_empty()).then(|| entry.platforms.clone()),
            tags: st::tags_out(&entry.tags),
        })
    }
}
