    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_COMPONENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_COMPONENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        // IAM decides first, before the catalog is read: a caller whose identity-based
        // policies do not allow this action on the component version the request names is
        // refused 403 and learns nothing about whether that version exists
        // (`st::authorization`). The resource is the ARN the request itself carried.
        st::authorization::authorize(&*self.engine, ctx, Self::NAME, &input.arn)
            .map_err(GetComponentErrorModeled::AccessDeniedException)?;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(GetComponentErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the greengrassv2 state store is unavailable".to_string(),
                    retry_after_seconds: 1,
                },
            )
            .into());
        };

        // `recipeOutputFormat` is optional; JSON is the format Greengrass returns
        // when the caller names none.
        let requested_raw = input.recipe_output_format.as_deref().unwrap_or("JSON");
        let Some(requested) = st::RecipeFormat::from_wire(requested_raw) else {
            return Err(GetComponentErrorModeled::ValidationException(ValidationException {
                message: format!(
                    "recipeOutputFormat must be one of JSON, YAML; got {requested_raw}."
                ),
                reason: Some("FIELD_VALIDATION_FAILED".to_string()),
                fields: Some(vec![ValidationExceptionField {
                    name: "recipeOutputFormat".to_string(),
                    message: format!("{requested_raw} is not a RecipeOutputFormat value."),
                }]),
            })
            .into());
        };

        let store = state.lock();
        let Some(entry) = store.component_version(&input.arn) else {
            // A recipe fetch names the visibility scope it searched beside the
            // component it did not find: a component-version ARN carrying this
            // account names a component this account published, which is the private
            // scope.
            let (name, version) = st::parse_component_version_arn(&input.arn)
                .unwrap_or_else(|| (input.arn.clone(), String::new()));
            return Err(GetComponentErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: format!(
                        "{} component ({name}:{version}) under account {} does not exist",
                        st::SCOPE_PRIVATE,
                        st::account_id()
                    ),
                    resource_id: input.arn.clone(),
                    resource_type: "COMPONENT_VERSION".to_string(),
                },
            )
            .into());
        };
        // Copy out and release the shared lock BEFORE re-rendering: rendering is
        // work proportional to the document, and it must not be done inside the
        // critical section every other request waits on.
        let stored_recipe = entry.recipe.clone();
        let stored_format = entry.recipe_format;
        let tags = st::tags_out(&entry.tags);
        drop(store);

        let Some(recipe) = st::render_recipe(&stored_recipe, stored_format, requested) else {
            return Err(GetComponentErrorModeled::InternalServerException(
                InternalServerException {
                    message: format!(
                        "The stored recipe for {} could not be rendered as {requested_raw}.",
                        input.arn
                    ),
                    retry_after_seconds: 1,
                },
            )
            .into());
        };

        Ok(GetComponentOutput {
            recipe_output_format: requested.as_wire().to_string(),
            recipe,
            tags,
        })
    }
