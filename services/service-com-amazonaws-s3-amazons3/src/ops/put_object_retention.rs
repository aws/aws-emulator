        let version_id = input.version_id.as_deref();

        // The ADDRESS is resolved first, so a request naming a bucket, a key or a version
        // this emulator does not hold answers that — the way the service orders the
        // refusals — rather than reporting whatever is wrong with a retention no object
        // version could have carried.
        let Some(bucket) = store.bucket(&input.bucket) else {
            return Err(PutObjectRetentionErrorModeled::NoSuchBucket(NoSuchBucket {}).into());
        };
        // A retention is one half of S3 Object Lock, which a bucket has only once an Object
        // Lock configuration is on it: the configuration's rule "will be applied by default
        // to every new object placed in the specified bucket"
        // (`PutObjectLockConfiguration`'s own documentation), and a bucket carrying none
        // locks nothing. Placing a retention there is a request S3 cannot carry out as
        // given, which is what `InvalidRequest` reports — the refusal `PutObjectLegalHold`
        // answers the same cause with.
        if !bucket.object_lock_enabled() {
            return Err(crate::scaffolded::Scaffolded::unmodeled(
                crate::state::INVALID_REQUEST_CODE,
                crate::state::INVALID_REQUEST_STATUS,
                crate::state::OBJECT_LOCK_CONFIGURATION_MISSING_MESSAGE,
            ));
        }
        // A delete marker has no object behind it to carry a retention: 405, the status S3
        // answers an object-level call on a marker with, as `HeadObject` already answers it
        // for the same cause — naming the marker in the refusal's two headers (see
        // `crate::service::wire`'s delete-marker note).
        if let Some(marker) =
            version_id.and_then(|named| bucket.delete_marker_version(&input.key, named))
        {
            return Err(crate::scaffolded::Scaffolded::delete_marker_method_not_allowed(
                RETENTION_WRITE_METHOD,
                marker,
            ));
        }
        let Some(object) = bucket.addressed_object(&input.key, version_id) else {
            return Err(no_such_object(version_id));
        };
