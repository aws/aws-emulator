//! The two endpoint members an Aurora DB CLUSTER publishes when a CloudFormation stack is what
//! deployed it, read back through Amazon RDS's own `DescribeDBClusters`.
//!
//! The rule under test: a DB cluster's endpoint members are HOSTS and nothing else — the
//! port is reported only in the Integer member `Port` and the zone only in `HostedZoneId`
//! (`smithy_query(query="shape", shape="DBCluster")`) — so a consumer that composes a target
//! from the pair (a DSN or JDBC URL builder, a driver, a production-readiness audit) needs the
//! port NOT glued onto the host, or it composes a target carrying the port twice. For a cluster
//! whose engine wire this emulator SERVES, both members carry the ADDRESS this emulator answers
//! that cluster's data plane at, because an address a service hands a client is one the client
//! resolves and then dials and the only hosts that reach this process are its own; a cluster it
//! serves no plane for keeps the names the CLUSTER mints from its own identifier under the
//! published AWS suffix, there being no local plane for it to lead a client to.
//!
//! Both hold whatever the cluster's membership is and whoever created it.
//!
//! Beside the representation, the same deployment pins the rule that makes it reach a client:
//! every endpoint value a stack publishes for the cluster is the value Amazon RDS published for
//! it, so a template output and that service's own read cannot drift.
//!
//! Three crates have to agree for this to hold — CloudFormation deploys the estate, Secrets
//! Manager holds the master credentials the declaration resolves, and Amazon RDS owns the
//! cluster and mints its endpoints — so the suite lives here rather than in any one of them.
//!
//! The rows span what the rule generalises over: the engine (Aurora PostgreSQL, Aurora MySQL),
//! the cluster's MEMBERSHIP (none at all — the Serverless v2 cluster nobody declared an
//! instance in, which has no reader instance any name could be read off — and one member), how
//! the cluster is placed (the stack's own VPC, subnets and DB subnet group, or the default
//! network), and where the identifier the cluster is held under comes from (declared in the
//! template, or generated by CloudFormation).

use std::collections::BTreeMap;
use std::sync::Arc;
use std::time::Duration;

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::query_wire::{
    blocks_of, element, elements, form_encode, opt_element, outputs_of, physical_ids_of,
};

/// The Region every request here is signed for, and so the Region the estate lives in.
const REGION: &str = "us-west-2";

/// The master user the declared clusters are created with: the username the stack's secret
/// holds, and the JSON key its generated password is put under.
const MASTER_USER: &str = "dbadmin";
const PASSWORD_KEY: &str = "password";

/// The instance class a declared member of an Aurora cluster is offered with.
const MEMBER_CLASS: &str = "db.r5.large";

/// The logical id of the cluster every row declares, and of the secret its credentials come
/// from.
const CLUSTER: &str = "Cluster";
const SECRET: &str = "DbSecret";

/// The status a deployed stack settles in.
const CREATE_COMPLETE: &str = "CREATE_COMPLETE";

/// The `DBCluster$Status` a cluster that is serving reports.
const AVAILABLE: &str = "available";

/// How long one poll waits before the next, and how many are made: the transitions waited for
/// here are owed on Amazon RDS's and CloudFormation's own clocks, so the suite waits for the
/// CONDITION rather than for a span, with a budget far longer than the spans themselves so a
/// loaded host does not decide the outcome.
const POLL: Duration = Duration::from_millis(50);
/// See [`POLL`].
const POLLS: usize = 2_400;

/// The emulator as it is ASSEMBLED, on one engine: the CloudFormation provisioner's own calls
/// are dispatched back into this same router, so the cluster it creates is the one these reads
/// resolve.
fn build_router() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = aws_emulator_router::build_router(engine);
    // The signature is never checked here, as in every other suite of this crate; the
    // credential scope is what routes a request.
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` header whose credential scope names `service`, which is what routes
/// the request and what each handler reads its Region from.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20260101/{REGION}/{service}/\
         aws4_request, SignedHeaders=host, Signature=0000"
    )
}

/// One awsQuery call of `service`, answered with the HTTP status and the XML body.
async fn query(
    router: &MultiServiceRouter,
    service: &str,
    version: &str,
    action: &str,
    members: &[(&str, &str)],
) -> (u16, String) {
    let mut body = format!("Action={action}&Version={version}");
    for (key, value) in members {
        body.push('&');
        body.push_str(&form_encode(key));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{service}.{REGION}.amazonaws.com"))
        .header("content-type", "application/x-www-form-urlencoded")
        .header("authorization", authorization(service))
        .body(Bytes::from(body))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    (
        response.status().as_u16(),
        String::from_utf8_lossy(response.body()).to_string(),
    )
}

/// One CloudFormation call over its awsQuery wire.
async fn cloudformation(
    router: &MultiServiceRouter,
    action: &str,
    members: &[(&str, &str)],
) -> (u16, String) {
    query(router, "cloudformation", "2010-05-15", action, members).await
}

/// One Amazon RDS call over its awsQuery wire.
async fn rds(
    router: &MultiServiceRouter,
    action: &str,
    members: &[(&str, &str)],
) -> (u16, String) {
    query(router, "rds", "2014-10-31", action, members).await
}

/// One cluster of the table.
struct Row {
    case: &'static str,
    /// The stack the row deploys, and the prefix its resources are named under.
    stack: &'static str,
    engine: &'static str,
    /// The `DBClusterIdentifier` the declaration names, or `""` where the template names none
    /// and CloudFormation generates one.
    identifier: &'static str,
    /// Whether the stack declares its own VPC, subnets and DB subnet group and places the
    /// cluster in them.
    own_network: bool,
    /// Whether the cluster is declared as an Aurora Serverless v2 cluster with deletion
    /// protection on.
    serverless: bool,
    /// How many member DB instances the stack declares in the cluster.
    members: usize,
}

const ROWS: &[Row] = &[
    Row {
        // The shape a reader endpoint has to be minted for whatever happens: an Aurora
        // Serverless v2 cluster with no DB instance declared in it, in the stack's own subnet
        // group, with its master credentials in a Secrets Manager secret.
        case: "an Aurora PostgreSQL Serverless v2 cluster in the stack's own subnet group",
        stack: "xsvc-aur-endpoints-serverless",
        engine: "aurora-postgresql",
        identifier: "xsvc-aur-endpoints-serverless-cluster",
        own_network: true,
        serverless: true,
        members: 0,
    },
    Row {
        // The same rule on the other served Aurora engine, with a member instance in the
        // cluster: the names are the CLUSTER's either way.
        case: "an Aurora MySQL cluster with one declared member instance",
        stack: "xsvc-aur-endpoints-member",
        engine: "aurora-mysql",
        identifier: "xsvc-aur-endpoints-member-cluster",
        own_network: false,
        serverless: false,
        members: 1,
    },
    Row {
        // And the identifier the names derive from need not be one the template wrote: a
        // declaration that names the cluster nowhere takes the identifier CloudFormation
        // generated, and the minted names follow THAT.
        case: "a cluster whose identifier CloudFormation generated",
        stack: "xsvc-aur-endpoints-generated",
        engine: "aurora-postgresql",
        identifier: "",
        own_network: false,
        serverless: false,
        members: 0,
    },
];

/// The template one row deploys: the secret its master credentials are resolved from, the
/// cluster itself, the network it sits in where the row declares one, the member instances it
/// declares, and the three endpoint values the type publishes.
fn template(row: &Row) -> String {
    let stack = row.stack;
    let mut cluster = json!({
        "Engine": row.engine,
        "MasterUsername": {
            "Fn::Sub": format!("{{{{resolve:secretsmanager:${{{SECRET}}}:SecretString:username}}}}"),
        },
        "MasterUserPassword": {
            "Fn::Sub": format!(
                "{{{{resolve:secretsmanager:${{{SECRET}}}:SecretString:{PASSWORD_KEY}}}}}"
            ),
        },
    });
    if !row.identifier.is_empty() {
        cluster["DBClusterIdentifier"] = Value::String(row.identifier.to_string());
    }
    if row.serverless {
        cluster["EngineMode"] = Value::String("provisioned".to_string());
        cluster["DeletionProtection"] = Value::Bool(true);
        cluster["ServerlessV2ScalingConfiguration"] =
            json!({ "MinCapacity": 0.5, "MaxCapacity": 1 });
    }
    let mut resources = serde_json::Map::new();
    resources.insert(
        SECRET.to_string(),
        json!({
            "Type": "AWS::SecretsManager::Secret",
            "Properties": {
                "Name": format!("{stack}-credentials"),
                "GenerateSecretString": {
                    "SecretStringTemplate": json!({ "username": MASTER_USER }).to_string(),
                    "GenerateStringKey": PASSWORD_KEY,
                    "PasswordLength": 20,
                    "ExcludePunctuation": true,
                },
            },
        }),
    );
    if row.own_network {
        resources.insert(
            "Vpc".to_string(),
            json!({
                "Type": "AWS::EC2::VPC",
                "Properties": { "CidrBlock": "10.9.0.0/16" },
            }),
        );
        for (logical, block, zone) in [("SubA", "10.9.1.0/24", 0), ("SubB", "10.9.2.0/24", 1)] {
            resources.insert(
                logical.to_string(),
                json!({
                    "Type": "AWS::EC2::Subnet",
                    "Properties": {
                        "VpcId": { "Ref": "Vpc" },
                        "CidrBlock": block,
                        "AvailabilityZone": { "Fn::Select": [zone, { "Fn::GetAZs": "" }] },
                    },
                }),
            );
        }
        resources.insert(
            "SubnetGroup".to_string(),
            json!({
                "Type": "AWS::RDS::DBSubnetGroup",
                "Properties": {
                    "DBSubnetGroupDescription": "the stack's own subnets",
                    "SubnetIds": [{ "Ref": "SubA" }, { "Ref": "SubB" }],
                },
            }),
        );
        cluster["DBSubnetGroupName"] = json!({ "Ref": "SubnetGroup" });
    }
    resources.insert(
        CLUSTER.to_string(),
        json!({ "Type": "AWS::RDS::DBCluster", "Properties": cluster }),
    );
    for member in 0..row.members {
        resources.insert(
            format!("Member{member}"),
            json!({
                "Type": "AWS::RDS::DBInstance",
                "Properties": {
                    "DBInstanceIdentifier": format!("{stack}-m{member}"),
                    "Engine": row.engine,
                    "DBInstanceClass": MEMBER_CLASS,
                    "DBClusterIdentifier": { "Ref": CLUSTER },
                },
            }),
        );
    }
    json!({
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": "an Aurora DB cluster whose published endpoints the stack reports",
        "Resources": Value::Object(resources),
        "Outputs": {
            "EndpointAddress": { "Value": { "Fn::GetAtt": [CLUSTER, "Endpoint.Address"] } },
            "EndpointPort": { "Value": { "Fn::GetAtt": [CLUSTER, "Endpoint.Port"] } },
            "ReaderAddress": { "Value": { "Fn::GetAtt": [CLUSTER, "ReadEndpoint.Address"] } },
        },
    })
    .to_string()
}

/// Deploy `body` as the stack `stack` and answer the status it settled in with the stack's own
/// answer. The CONDITION is polled for — the deployment is finished when it is no longer in
/// progress — never a span.
async fn deploy(router: &MultiServiceRouter, case: &str, stack: &str, body: &str) -> String {
    let (status, answered) = cloudformation(
        router,
        "CreateStack",
        &[("StackName", stack), ("TemplateBody", body)],
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case:?}: CreateStack {stack:?} must answer 200, got {status} with {answered}"
    );
    let mut last = stack_state(router, case, stack).await;
    for _ in 0..POLLS {
        if !last.0.ends_with("_IN_PROGRESS") {
            break;
        }
        tokio::time::sleep(POLL).await;
        last = stack_state(router, case, stack).await;
    }
    let (settled, described) = last;
    assert_eq!(
        settled, CREATE_COMPLETE,
        "case {case:?}: expected the stack to settle in {CREATE_COMPLETE}, got {settled:?} with \
         the resources' own reasons {:?}",
        failure_reasons(router, stack).await
    );
    described
}

/// The `StackStatus` the stack reports now, with the answer it was read from.
async fn stack_state(router: &MultiServiceRouter, case: &str, stack: &str) -> (String, String) {
    let (status, body) = cloudformation(router, "DescribeStacks", &[("StackName", stack)]).await;
    assert_eq!(
        status, 200,
        "case {case:?}: DescribeStacks {stack:?} must answer 200, got {status} with {body}"
    );
    (opt_element(&body, "StackStatus").unwrap_or_default(), body)
}

/// Every `ResourceStatusReason` the stack has recorded, so a deployment that did not settle
/// where the case says reports WHY.
async fn failure_reasons(router: &MultiServiceRouter, stack: &str) -> Vec<String> {
    let (_, events) = cloudformation(router, "DescribeStackEvents", &[("StackName", stack)]).await;
    elements(&events, "ResourceStatusReason")
}

/// The physical id the stack holds the cluster under — the identifier Amazon RDS stored it as,
/// which is what its endpoint names are minted from.
async fn cluster_identifier(router: &MultiServiceRouter, case: &str, stack: &str) -> String {
    let (status, body) =
        cloudformation(router, "DescribeStackResources", &[("StackName", stack)]).await;
    assert_eq!(
        status, 200,
        "case {case:?}: DescribeStackResources must answer 200, got {status} with {body}"
    );
    let ids: BTreeMap<String, String> = physical_ids_of(&body);
    ids.get(CLUSTER)
        .cloned()
        .unwrap_or_else(|| panic!("case {case:?}: expected the cluster's physical id in {body}"))
}

/// RULE: each endpoint member of a cluster whose data plane this emulator SERVES carries the
/// ADDRESS that plane is answered at — a bare host of this emulator's own, never an address
/// with a port glued on and never a name in a zone AWS serves — so both members carry that one
/// address and a client composes its target from it and the cluster's one `Port`.
fn assert_published_pair(case: &str, port: u16, writer: &str, reader: &str) {
    for (member, value) in [("Endpoint", writer), ("ReaderEndpoint", reader)] {
        // A HOST and nothing else: no port and no authority — the port is the cluster's one
        // `Port` member, so a client composes the target itself.
        assert!(
            !value.ends_with(&format!(":{port}")) && !value.contains(':'),
            "case {case:?}: <{member}> carries no port of its own, got {value:?}"
        );
        // An address of the interface the core bound this emulator's listeners on, which is the
        // only host a client of the emulator reaches that plane at. A name in a zone AWS serves
        // would send the client out of the emulated environment.
        let address = value.trim_matches(['[', ']']).parse::<std::net::IpAddr>();
        assert!(
            address.is_ok_and(|address| address.is_loopback()),
            "case {case:?}: <{member}> must publish the address this emulator answers the \
             cluster's data plane at, got {value:?}"
        );
    }
    assert_eq!(
        writer, reader,
        "case {case:?}: both members in front of one served data plane name the address it is \
         answered at, got {writer:?} and {reader:?}"
    );
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_stack_deployed_aurora_cluster_publishes_the_address_of_its_plane() {
    for row in ROWS {
        let case = row.case;
        let router = build_router();
        let described = deploy(&router, case, row.stack, &template(row)).await;
        let identifier = cluster_identifier(&router, case, row.stack).await;
        if !row.identifier.is_empty() {
            assert_eq!(
                identifier, row.identifier,
                "case {case:?}: expected the stack to hold the cluster under the declared \
                 identifier, got {identifier:?}"
            );
        }

        // Amazon RDS's OWN read of the cluster: the service that mints the endpoints is where a
        // client reads them, so this is the answer the rule holds for.
        let (status, body) = rds(
            &router,
            "DescribeDBClusters",
            &[("DBClusterIdentifier", &identifier)],
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: expected Amazon RDS to resolve {identifier:?}, got {status} with \
             {body}"
        );
        let reported = element(&body, "Status");
        assert_eq!(
            reported, AVAILABLE,
            "case {case:?}: expected the deployed cluster to be {AVAILABLE}, got {reported:?} in \
             {body}"
        );

        // The port is the pair's, reported as an Integer member of its own, and the zone the
        // names live in is reported beside them.
        let published_port = element(&body, "Port");
        let port: u16 = published_port.parse().unwrap_or_else(|_| {
            panic!("case {case:?}: expected the port the engine listens on, got {published_port:?}")
        });
        assert!(
            port != 0,
            "case {case:?}: expected the port the engine listens on, got {port}"
        );
        let zone = element(&body, "HostedZoneId");
        assert!(
            zone.starts_with('Z') && zone.len() > 1,
            "case {case:?}: expected the hosted zone the endpoints live in, got {zone:?}"
        );

        let writer = element(&body, "Endpoint");
        let reader = element(&body, "ReaderEndpoint");
        assert_published_pair(case, port, &writer, &reader);
        // The membership the row declared, which the rule holds ACROSS: the reader member is the
        // cluster's own whether or not there is an instance in it.
        let members = blocks_of(&body, "DBClusterMember").len();
        assert_eq!(
            members, row.members,
            "case {case:?}: expected {} member(s) in the cluster, got {members} in {body}",
            row.members
        );

        // And what the stack publishes for the cluster is what that service published: a client
        // reading an output dials the same pair as a client reading the cluster.
        let outputs = outputs_of(&described);
        for (key, expected) in [
            ("EndpointAddress", &writer),
            ("EndpointPort", &published_port),
            ("ReaderAddress", &reader),
        ] {
            assert_eq!(
                outputs.get(key),
                Some(expected),
                "case {case:?}: expected the stack to publish the {key} Amazon RDS published \
                 ({expected:?}), got {outputs:?}"
            );
        }
    }
}
