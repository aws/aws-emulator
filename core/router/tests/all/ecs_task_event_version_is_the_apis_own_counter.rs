//! The `version` an `ECS Task State Change` envelope carries is the SAME counter the Amazon ECS
//! API reports for that task.
//!
//! The RULE under test: **a task carries one version counter that is incremented by every change
//! of it that is published, so the `detail.version` of the envelopes a rule matching `source`
//! `aws.ecs` / `detail-type` `ECS Task State Change` delivers for one task rise strictly in the
//! chronological order of the envelopes' `time`, the last envelope delivered for a task that has
//! settled reports the status that task settled in, and `DescribeTasks` then reports for the same
//! task exactly that envelope's `version`, `lastStatus` and `desiredStatus` — whatever moved the
//! task (the clock materialising its start, its program ending, or a caller asking for its
//! stop).**
//!
//! Sources: `smithy_query(query="operation", operation="RunTask,DescribeTasks,StopTask")` for the
//! task projection an event's `detail` is read off (`taskArn`, `clusterArn`, `lastStatus`,
//! `desiredStatus`, `version`) and `smithy_query(query="shape", shape="Task")` for `Task$version`,
//! whose own documentation states that "Every time a task experiences a change that starts a
//! CloudWatch event, the version counter is incremented" and that "you can compare the version of
//! a task reported by the Amazon ECS API actions with the version reported in CloudWatch Events
//! for the task (inside the `detail` object)" — which is the agreement this suite asserts.
//!
//! This suite lives here because the path is cross-service: Amazon ECS publishes through the
//! in-process callback, EventBridge routes the envelope by its CONTENT, and Amazon SQS holds what
//! arrived — so what is asserted is what each of the three services persisted, and nothing reads
//! the publisher's own queue.
//!
//! The rows differ along what the rule generalises over: WHAT moved the task to its terminal
//! status (its own program ending, and a caller's `StopTask`, which takes the task through one
//! more published status on the way), the launch type and network mode it was placed with (a
//! Fargate task allocated its own elastic network interface against a task sharing its host's
//! networking, and so which statuses it passes through), and how many tasks ONE call placed,
//! since each placed task carries a counter of its own.
//!
//! Each row is driven by a test of its OWN, so the rows' waits overlap instead of adding up, and
//! every wait below looks again for the CONDITION it is waiting on until a generous deadline
//! passes, so a loaded machine polls more often instead of failing.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// The Region every request below is signed for, and so the Region of every ARN minted for them.
const REGION: &str = "us-west-2";

/// The account every emulator ARN carries, which a container-instance registration's identity
/// document has to name.
const ACCOUNT: &str = engine::EMULATOR_ACCOUNT_ID;

/// The `source` and `detail-type` Amazon ECS publishes a task's state changes under, spelled out
/// here rather than imported from the service crate, so a wrong constant in the implementation
/// cannot make this suite pass.
const EVENT_SOURCE: &str = "aws.ecs";
const TASK_STATE_CHANGE: &str = "ECS Task State Change";

/// The two statuses this suite waits for a task to be published in. Source:
/// `smithy_query(query="operation", operation="DescribeTasks")` for `Task$lastStatus`.
const RUNNING: &str = "RUNNING";
const STOPPED: &str = "STOPPED";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon Web
/// Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the target
/// queue's own resource policy admits ("for Amazon SQS queues, EventBridge relies on
/// resource-based policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The `X-Amz-Target` prefix of the Amazon ECS model, whose `sigv4Name` is `ecs`; it speaks
/// awsJson1.1.
const ECS_TARGET_PREFIX: &str = "AmazonEC2ContainerServiceV20141113";

/// The cluster every task below runs in.
const CLUSTER: &str = "taskversions";

/// The container instance the EC2 row's task is placed on: "The EC2 launch type runs your tasks
/// on Amazon EC2 instances registered to your cluster."
const CAPACITY_INSTANCE: &str = "i-0c0ffee0c0ffee0c2";

/// The network a Fargate row's task is placed in. The ids are fixed, because the requests and the
/// records have to name the same ones, so they are written into the account's Amazon EC2 records
/// rather than minted ([`crate::ec2_network`]).
const VPC: &str = "vpc-0ec50000000000003";
const SUBNET: &str = "subnet-0ec50000000000003";

/// The security group a Fargate placement names beside its subnet. Nothing resolves it — what a
/// row is about is the run, not the group — so one value does.
const SECURITY_GROUP: &str = "sg-0ec50000000000003";

/// The image every container names. The VPC the tasks are placed in has a route to it
/// ([`crate::ec2_network::register_internet_route`]) and the Fargate placements take a public
/// address, so the fetch is reachable.
const IMAGE: &str = "public.ecr.aws/amazonlinux/amazonlinux:2023";

/// How often a poll re-reads the target queue.
const POLL_INTERVAL: Duration = Duration::from_millis(50);

/// How long a poll keeps trying before it gives up. Generous: a task crosses its launch steps,
/// its start, the work it was placed to do and then its stop, and each poll stops the instant its
/// own condition holds — so the budget costs nothing when the envelopes arrive and a loaded
/// machine only polls more often.
const POLL_BUDGET: Duration = Duration::from_secs(60);

/// Amazon ECS, EventBridge and Amazon SQS over ONE shared engine — the three services a published
/// task event travels through, mounted the way the production router mounts them — with the
/// network the Fargate rows place into in the account's Amazon EC2 records.
fn emulator() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    crate::ec2_network::register_network(&engine, VPC, &[SUBNET], &format!("{REGION}a"));
    crate::ec2_network::register_internet_route(&engine, VPC);
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(
        service_com_amazonaws_ecs_amazonec2containerservicev20141113::EmulatedService::new(
            Arc::clone(&engine),
        ),
    );
    router.register_service(
        service_com_amazonaws_eventbridge_awsevents::EmulatedService::new(Arc::clone(&engine)),
    );
    router.register_service(service_com_amazonaws_sqs_amazonsqs::EmulatedService::new(
        engine,
    ));
    router
}

/// A SigV4 `Authorization` whose credential scope names `signing_name`, which is what routes the
/// request. The signature is never checked: the router above runs with request authentication
/// off.
fn authorization(signing_name: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{signing_name}\
         /aws4_request, SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call, answered with its HTTP status and parsed body.
async fn json_call(
    router: &MultiServiceRouter,
    signing_name: &str,
    target: &str,
    json_version: &str,
    body: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header(
            "content-type",
            format!("application/x-amz-json-{json_version}"),
        )
        .header("x-amz-target", target)
        .header("authorization", authorization(signing_name))
        .body(Bytes::from(body.to_string()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let payload = response.into_body();
    let parsed: Value = if payload.is_empty() {
        json!({})
    } else {
        serde_json::from_slice(&payload)
            .unwrap_or_else(|_| json!({ "unparsed": String::from_utf8_lossy(&payload) }))
    };
    (status, parsed)
}

/// One Amazon ECS call that must succeed, answered with its body.
async fn ecs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("{ECS_TARGET_PREFIX}.{operation}");
    let (status, parsed) = json_call(router, "ecs", &target, "1.1", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from ECS {operation}, got {status} with {parsed}"
    );
    parsed
}

